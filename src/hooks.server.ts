/**
 * `<html lang>` берётся ИЗ АДРЕСА — семь строк, о которых говорил `researches/26` §5.2.
 *
 * 🔴 ЗАЧЕМ. Фаза 5 эпика `ideas/30` впервые выпускает английские страницы (`/en/dimension/…`),
 * и до этой правки они отдавались роботу с `<html lang="ru">`: английский текст, объявленный
 * русским. Замер `researches/26` §1.2 говорил, что английского в отдаваемом HTML нет ни знака —
 * теперь он есть, и объявить его надо честно, иначе половина работы фазы пропадает.
 *
 * Хук выполняется НА ПРЕРЕНДЕРЕ (сайт статический, `adapter-static`), то есть значение
 * запекается в файл. Именно этот файл читает поисковик.
 *
 * ⚠️ ГРАНИЦА, которую нельзя переступить этой правкой. Инлайн-скрипт `app.html` до сих пор
 * переписывает `lang` из памяти браузера на КАЖДОЙ странице — у ЧЕЛОВЕКА на языковом адресе это
 * по-прежнему ломается (человек с `ru` в памяти откроет `/en/…` и первым кадром получит русский).
 * Лечение — общий модуль языка, где на публичных адресах источник истины АДРЕС, и это работа
 * `plans/24` фазы 6. Здесь чинится только то, что видит РОБОТ, и это названо честно, а не выдано
 * за решение задачи целиком.
 */
import type { Handle } from '@sveltejs/kit';
import { langFromPath } from '$lib/content/langs';

/**
 * Умолчание — русский: экраны за стеной входа языковых адресов не имеют и не получат
 * (`plans/39`, шаг 2). Публичные страницы свой язык называют адресом.
 */
const DEFAULT_LANG = 'ru';

export const handle: Handle = async ({ event, resolve }) => {
  // 🔴 Правило «какой язык задаёт адрес» живёт в ОДНОМ месте (`$lib/content/langs`) и
  // покрыто тестами с мутациями. Здесь была его вторая копия — «взять первый сегмент», — и
  // копии разошлись бы молча, причём в ту сторону, где сборка зелёная, а человек видит не тот
  // язык. Тот же модуль читают ограничитель маршрута и клиентский модуль языка.
  const lang = langFromPath(event.url.pathname) ?? DEFAULT_LANG;

  return resolve(event, {
    transformPageChunk: ({ html }) => html.replace('%ndim.lang%', lang),
  });
};
