/**
 * Ограничитель языкового сегмента адреса: `/ru/…`, `/en/…` — и ничего больше.
 *
 * Схема адресов решена владельцем (интервью №010, Р5 = В): **ни один язык не сидит на голом
 * корне**, у каждого свой префикс, а корень распознаёт язык человека и перенаправляет.
 * Подтверждено им же 2026-08-03: «на каждый язык будет своя / — ru/, en/, и другие новые языки
 * так же встанут в будущем».
 *
 * 🔴 Почему ограничитель, а не голый `[lang]`. Без него `/что-угодно/dimension/x` считался бы
 * валидным маршрутом. Сайт статический, и вживую туда никто не попадёт, — но ошибка в
 * `entries()` молча породила бы страницы на несуществующем языке, и заметили бы это по карте
 * сайта, а не по падению.
 *
 * ⚠️ Список языков живёт ЗДЕСЬ и в `$lib/content/langs.ts` — они обязаны совпадать. Третий язык
 * добавляется в оба места; каркас на это и рассчитан («в будущем добавим ещё языков» — владелец).
 */
import { LANGS } from '$lib/content/langs.ts';

export function match(value: string): boolean {
  return (LANGS as readonly string[]).includes(value);
}
