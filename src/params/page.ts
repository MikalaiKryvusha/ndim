/**
 * Ограничитель номера страницы хаба: `/ru/catalog/movie/2` … `/ru/catalog/movie/47`.
 *
 * 🔴 **Единица сюда не попадает, и это не придирка.** Первая страница хаба живёт на адресе без
 * номера (`/ru/catalog/movie`); если бы `…/1` тоже отвечал, у одного содержания стало бы два
 * адреса — дубль, который поисковик обязан склеивать сам. Дешевле его не создавать.
 *
 * Ведущие нули отсекаются по той же причине: `…/007` — это третий адрес той же страницы.
 */
export function match(value: string): boolean {
  return /^[1-9]\d*$/.test(value) && Number(value) >= 2;
}
