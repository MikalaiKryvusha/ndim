/**
 * Ограничитель сегмента вида в адресе хаба: `/ru/catalog/movie`, `/en/catalog/video-game` — и
 * ничего больше (`plans/48` шаг 3).
 *
 * Список ключей один на проект (`$lib/content/dim-kind.ts`), и здесь он именно СПРАШИВАЕТСЯ, а
 * не переписывается: вторая копия семи строк разошлась бы с первой при первом же пополнении
 * каталога новым видом.
 *
 * 🔴 Зачем ограничитель, если сайт статический и вживую на `/ru/catalog/чепуха` никто не попадёт.
 * Затем же, зачем он у языка: ошибка в `entries()` молча породила бы страницы несуществующего
 * вида, и заметили бы это по карте сайта, а не по падению сборки.
 */
import { isKindKey } from '$lib/content/dim-kind';

export function match(value: string): boolean {
  return isKindKey(value);
}
