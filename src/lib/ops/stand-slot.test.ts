/**
 * СТРАЖ СЛОТОВ ТЕСТОВОГО ПАРКА — адрес стенда выводится из каталога и ни с кем не пересекается.
 *
 * 🔴 ПОЧЕМУ ЭТОТ ТЕСТ ЖИВЁТ СРЕДИ ЮНИТОВ ПРОДУКТА, А СТЕРЕЖЁТ `tools/`. Ровно по тому же
 * доводу, что и сосед `stand-cleanup.test.ts`: командный манифест делает зелёные юниты условием
 * ЛЮБОЙ передачи работы, то есть `npm test` — единственный прогон, который случается перед
 * каждой сдачей у каждой роли. Проверка, живущая только в `--selftest`, прогоняется тем, кто о
 * ней помнит; проверка в `npm test` прогоняется всеми.
 *
 * ЧТО СТЕРЕЖЁТСЯ, кроме арифметики портов:
 *   · **список проверок не разъехался** — `--selftest` модуля и этот файл обязаны гонять ОДИН
 *     список (`checks()`), иначе «зелено» начнёт означать разное в разных прогонах;
 *   · **слот 0 остался сегодняшним стендом** — парк добавляет адреса, а не переселяет главную
 *     копию: любая правда о слоте 0 обязана совпасть с `STAND_PORTS`;
 *   · **потолок владельца — механика, а не строка в документе** (три стенда разом).
 *
 * Мутации, которые этот файл обязан ронять (прогнаны, числа — в `plans/69` шаг 2):
 *   M1 · `slotOf` возвращает 0 для любой роли → падают «слот каждой из шести ролей» и «слоты
 *        не пересекаются»;
 *   M3 · снят потолок в `capacityVerdict` → падает «четвёртый стенд получает отказ».
 */
import assert from 'node:assert/strict';
import { test } from 'node:test';

import {
  ROLES,
  SLOTS,
  MAX_CONCURRENT_STANDS,
  checks,
  portsFor,
  slotConfigName,
  slotOf,
} from '../../../tools/lib/stand-slot.mjs';
import { STAND_PORTS } from '../../../tools/lib/stand-cleanup.mjs';

/**
 * Один список доказательств на два потребителя. Каждая проверка модуля приезжает сюда
 * отдельным юнитом с СОБСТВЕННЫМ именем — падение называет, что именно сломано, а не «список
 * проверок дал false».
 */
for (const [name, fn] of checks()) {
  test(`слот: ${name}`, () => {
    assert.equal(fn(), true, `проверка модуля слота провалена: ${name}`);
  });
}

test('слотов ровно столько, сколько ролей — адрес есть у каждой', () => {
  assert.equal(SLOTS.length, ROLES.length);
  assert.deepEqual([...SLOTS], ROLES.map((_, i) => i));
});

/**
 * Сверка ПОЛНЫМ РАВЕНСТВОМ, а не «содержит»: она и есть то, что заставит будущую сессию прийти
 * сюда и объясниться, вместо того чтобы переселить слот 0 молча. Слот 0 — это главная копия и
 * дверь выката; его переезд сломал бы всё, что сегодня зелено.
 */
test('слот 0 — сегодняшний стенд: порты равны единственному списку баз', () => {
  assert.deepEqual({ ...portsFor(0) }, { ...STAND_PORTS });
  assert.equal(slotConfigName(0), 'firebase.json');
});

test('потолок одновременных стендов назван числом и равен замеру', () => {
  assert.equal(MAX_CONCURRENT_STANDS, 3);
});

/**
 * Мой собственный слот — тот, ради которого эта работа и делается. Проверка держит связку
 * «имя каталога → адрес» на конкретном живом примере, а не только на общей формуле.
 */
test('dev-2 живёт на слоте 4 и на своих портах', () => {
  assert.equal(slotOf('ndim_dev2').slot, 4);
  assert.deepEqual({ ...portsFor(4) }, {
    preview: 4213,
    dev: 5213,
    firestore: 8221,
    auth: 9139,
    storage: 9239,
  });
});
