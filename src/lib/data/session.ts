/**
 * Единственный вопрос лендинга к Firebase: есть ли у человека живая сессия (bugs/08.1).
 *
 * Вошедший человек лендинг не разглядывает — его дом внутри продукта, и корень (`/`)
 * обязан вести его туда. Гость — тоже «внутри»: у него живая сессия и несохранённый труд.
 *
 * Динамический импорт Firebase — канон лендинга (см. `data/funnel.ts`, EXP-0028): SDK не
 * имеет права попадать в его главный бандл (Lighthouse 100). `currentUser` сразу после
 * загрузки страницы ещё null (восстановление сессии асинхронное) — поэтому ждём первого
 * события `onAuthStateChanged`, а не читаем поле наугад.
 *
 * Никогда не бросает: не смогли спросить — считаем, что сессии нет, и показываем лендинг.
 */
export async function hasSession(): Promise<boolean> {
  try {
    const [{ devAuth }, { onAuthStateChanged }] = await Promise.all([
      import('../firebase.ts'),
      import('firebase/auth'),
    ]);
    return await new Promise<boolean>((resolve) => {
      const unsubscribe = onAuthStateChanged(devAuth(), (user) => {
        unsubscribe();
        // Маркер обновлять не нужно: `devAuth()` поднял постоянного слушателя, который
        // уже привёл его в согласие с этим же событием (bugs/40).
        resolve(user !== null);
      });
    });
  } catch {
    return false;
  }
}

/**
 * Маркер сессии — признак, который читается СИНХРОННО, до первого кадра (bugs/40).
 *
 * Зачем он вообще нужен, если правду знает Firebase: правда живёт в IndexedDB, а её
 * нельзя прочитать синхронно. К моменту первого кадра ответа от SDK не существует в
 * принципе — а решение «показывать ли загрузочный щит вместо лендинга» нужно принять
 * именно тогда, иначе лендинг успевает мелькнуть (замер: 4–5 кадров, `tools/measure-bug40.mjs`).
 *
 * Поэтому маркер — не источник истины, а ЭВРИСТИКА «в прошлый раз здесь был вошедший».
 * Цена обеих ошибок посчитана и обе безопасны:
 *   · маркер есть, сессии нет (вышел в другой вкладке, сессия истекла) → человек видит щит
 *     лишний миг, затем {@link endBoot} показывает лендинг;
 *   · маркера нет, сессия есть → поведение ровно такое, как было до bugs/40.
 * Обновляет его РОВНО ОДНА точка — постоянный слушатель `onAuthStateChanged`, поднятый в
 * `firebase.devAuth()` при рождении Auth. Расставлять вызовы по местам входа и выхода —
 * проверенная ошибка: путей входа много (Google · ссылка из письма · гость · апгрейд гостя ·
 * `signInDev` на стенде), и первая же версия пропустила стендовую ветку.
 *
 * Значение маркера ничего не значит и ничего не раскрывает: это флаг, а не личные данные.
 */
export const SESSION_MARK = 'ndim-session';

export function rememberSession(inside: boolean): void {
  try {
    if (inside) localStorage.setItem(SESSION_MARK, '1');
    else localStorage.removeItem(SESSION_MARK);
  } catch {
    // Приватный режим или запрет хранилища — просто не запоминаем. Продукт работает,
    // человек лишь теряет щит и видит прежнее поведение.
  }
}

/**
 * Опустить загрузочный щит (bugs/40).
 *
 * Зовётся, когда решение ПРИНЯТО и под щитом уже нужное содержимое — канон 1.x: там
 * `closeFullScreenLoading()` стоял после `openPage(...)`, и человек не видел ни одного
 * промежуточного состояния (`researches/12` → «Boot-экран: механика целиком»).
 *
 * Для вошедшего щит не опускается вовсе: его уводит редирект, и щит держится до самого
 * ухода со страницы — иначе лендинг мелькнул бы напоследок.
 */
export function endBoot(): void {
  document.documentElement.removeAttribute('data-booting');
}
