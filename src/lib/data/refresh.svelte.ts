/**
 * Принудительное обновление данных по требованию человека (интервью №006).
 *
 * ── ЗАЧЕМ ЭТО СУЩЕСТВУЕТ ───────────────────────────────────────────────────────────────────
 * Решением владельца (интервью №005, В4) топ связей и статистика Пространства застыли на ВЕСЬ
 * сеанс: *«ТОП обновляется очень редко. Нет смысла его обновлять»*. Цена решения названа там же
 * и принята осознанно — оценил измерение, топ перечитался сразу, но сервер к этому моменту мог
 * ещё не досчитать (цикл 60 с + тихий период 120 с), и прочитанное замрёт до конца сеанса.
 * Ровно ради этого случая владелец назвал pull-to-refresh — это его единственное лекарство.
 *
 * ── ЧТО РЕШИЛ ВЛАДЕЛЕЦ (интервью №006, все четыре развилки закрыты 2026-07-29) ──────────────
 * Макет — **V1 «Как в системе»**: чистый жест с круглым индикатором под шапкой, ноль новых
 * элементов на экранах, а путь БЕЗ жеста — строка `↻ Обновить данные · 12 минут назад` в «Меню».
 *
 *   В1=А — жест живёт на всех четырёх главных экранах (Связи, Пространство, Профиль, Измерения):
 *          после В4 они все отдают данные из памяти, значит «хочу свежее» возникает на всех.
 *   В2=А — у браузера отбирается ТОЛЬКО обновление, пружинящий отскок остаётся (`contain`).
 *   В3=А — где жест отобрать нельзя (Safari младше 16), он просто не включается.
 *   В4=А — текст строки в «Меню»: «Обновить данные», справа — «12 минут назад».
 *
 * ── ПОЧЕМУ СТРОКА В «МЕНЮ» ОБЯЗАТЕЛЬНА, А НЕ УКРАШЕНИЕ ─────────────────────────────────────
 * **WCAG 2.2 SC 2.5.7 «Dragging Movements» (AA).** Пока обновление тянет браузер, критерий не
 * применяется — это поведение user agent. Но как только жест забрали МЫ, у него обязан быть
 * равноценный путь без перетаскивания. Плюс на десктопе тянуть нечем вовсе. Разбор с
 * первоисточниками — `researches/18`.
 */

import { invalidateRefreshable } from './cache.ts';

/**
 * Когда данные последний раз читались из базы по требованию человека.
 * `null` — в этом сеансе ещё не обновляли: строка в «Меню» тогда молчит про время, а не врёт.
 */
let refreshedAt = $state<number | null>(null);

/** Идёт ли обновление прямо сейчас — чтобы два жеста подряд не завели два круга чтений. */
let running = $state(false);

/**
 * Отметить ПЕРВОЕ за сеанс чтение данных из базы.
 *
 * Без этого строка в «Меню» до первого жеста молчала бы о времени — а данные-то уже прочитаны,
 * и человеку важно именно то, насколько они старые. Заход в приложение и есть их свежесть
 * (решение владельца, интервью №005, В4: *«Пользователь зайдёт в приложение — получит свежие
 * данные»*), поэтому момент захода — честный ответ на вопрос «когда обновлено».
 *
 * Ставится ТОЛЬКО если отметки ещё нет: последующие заходы на экраны берут данные из памяти и
 * временем обновления не являются — иначе строка молодела бы от одной навигации.
 */
export function noteFirstLoad(): void {
  refreshedAt ??= Date.now();
}

/** Идёт ли обновление прямо сейчас. */
export function refreshing(): boolean {
  return running;
}

/*
 * ── ЧТО ИМЕННО ГАСИТ ОБНОВЛЕНИЕ ────────────────────────────────────────────────────────────
 * Ключи названы в интервью №006 («что будет сделано после ответов», п. 3): `relations:*`,
 * `space`, `ratings:*`, `profile`. Гасим, а не переписываем: чинить кэш руками — известный
 * источник рассинхрона (`researches/17` §2.4). Перечитает тот экран, который открыт, — этим
 * занят {@link refreshNow}.
 *
 * Сам список ключей живёт в `data/cache.ts` → {@link invalidateRefreshable}, и не ради красоты:
 * этот модуль написан на рунах, юнит-тестом он не запускается, а после В1=Б жест остался
 * ЕДИНСТВЕННЫМ входом в механизм — и жест стражами не эмулируется. Судья назвал это дырой в
 * проверяемости (`bugs/78`). В чистом TS список ключей стережёт `cache.test.ts`.
 *
 * Что там гасится, кроме данных: **память вида экранов** (`plans/08`). Человек попросил свежее,
 * ленты пересобираются (а очередь «Все» ещё и случайна) — запомненные 900px указали бы в НИКУДА:
 * тот же номер пикселя в другом списке это другое место. Обновил — значит начал сверху.
 */

/**
 * Обновить данные по требованию человека: погасить кэш и перечитать текущий экран.
 *
 * @param reload как перечитать открытый экран. Экран передаёт СВОЙ загрузчик — тот самый,
 *               которым он грузится в `onMount`; иначе пришлось бы держать здесь знание обо
 *               всех экранах сразу, а это ровно та связанность, которой кэш и избегает.
 *
 * Отметка времени ставится ПОСЛЕ успешного чтения, а не до: «обновлено 12 минут назад» обязано
 * означать, что данные действительно пришли. Упало чтение — отметка остаётся прежней и не врёт.
 */
export async function refreshNow(reload: () => Promise<void>): Promise<void> {
  if (running) return;
  running = true;
  try {
    invalidateRefreshable();
    await reload();
    refreshedAt = Date.now();
  } finally {
    running = false;
  }
}

/**
 * Умеет ли этот браузер отдать нам жест (развилка В3).
 *
 * Свой pull-to-refresh не *добавляется*, а **отбирается** у браузера через `overscroll-behavior`
 * — а он в WebKit появился только в **Safari 16.0** (MDN до сих пор: *«Limited availability…
 * not Baseline»*). Где отобрать нельзя, жест не включается вовсе: строка в «Меню» работает
 * везде, и без возможности обновиться не остаётся никто. Самодельную физику прокрутки не
 * городим — это ровно тот класс самоделок, от которого уходит 2.0 (`GOAL.md`).
 */
export function gestureSupported(): boolean {
  return typeof CSS !== 'undefined' && CSS.supports('overscroll-behavior-y', 'contain');
}
