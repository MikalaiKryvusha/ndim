/**
 * Тесты витрины лендинга «С нами уже N человек» (`bugs/07`, `bugs/81`, `plans/05` хвост).
 *
 * ⚠️ ЗАЧЕМ ЭТИ ТЕСТЫ СУЩЕСТВУЮТ. `bugs/07` назывался «Лендинг врёт: „С нами уже 2 184 человека“
 * зашито в код» и закрывался ссылкой на честность `GOAL.md`. Хвост того бага (`plans/05`, п. 2)
 * требовал «тест-запрет литерала», и он так и не был написан — полтора месяца в плане стояла
 * задача, которую никто не сделал.
 *
 * Теперь запрет исполняемый, и он строже, чем «нет такой строки в коде»: число на лендинге
 * ОБЯЗАНО быть произведением снимка боевой метрики на множитель витрины. Выдуманное число этому
 * равенству не удовлетворяет — значит подмена литералом роняет тест, откуда бы её ни принесли.
 *
 * Граница: сам факт попадания числа в пререндеренный HTML проверяется браузером
 * (`tools/verify-bug81.mjs`, 28 проверок) — юнит-тест до HTML не достаёт и не притворяется.
 *
 * Запуск: npm test
 */

import { test, describe } from 'node:test';
import assert from 'node:assert/strict';

import { PUBLIC_PEOPLE_SNAPSHOT } from '../content/landing-metric.ts';
import { landingPeople, landingPeopleTakenAt } from './metrics.ts';

describe('витрина лендинга', () => {
  test('ЗАПРЕТ ЛИТЕРАЛА: число выводится из снимка боевой метрики, а не придумано', () => {
    /*
     * Множитель — решение владельца (интервью №007, В2=Б: «смотри старый ндим, там я вообще
     * вычислял от реальности»). Здесь он не переписывается, а ВЫВОДИТСЯ из результата, поэтому
     * тест не сломается от смены множителя владельцем — он сломается от подмены числа литералом.
     */
    const shown = landingPeople();
    const factor = shown / PUBLIC_PEOPLE_SNAPSHOT.people;

    assert.ok(Number.isInteger(shown), `на витрине должно быть целое число, получено ${shown}`);
    assert.ok(
      Number.isInteger(factor) && factor >= 1,
      `витрина обязана быть КРАТНА снимку (${PUBLIC_PEOPLE_SNAPSHOT.people}); ` +
        `получено ${shown}, отношение ${factor} — похоже на выдуманное число`,
    );
  });

  test('снимок берётся инструментом, а не пишется руками: людей целое число, дата — день ISO', () => {
    // Оба поля генерирует `tools/snapshot-landing-metric.mjs` из боевого `space/public_metrics`.
    // Правка руками — это ровно `bugs/07`, и запрет стоит в шапке сгенерированного файла.
    assert.ok(
      Number.isInteger(PUBLIC_PEOPLE_SNAPSHOT.people) && PUBLIC_PEOPLE_SNAPSHOT.people > 0,
      `people должно быть целым больше нуля, получено ${PUBLIC_PEOPLE_SNAPSHOT.people}`,
    );
    assert.match(
      landingPeopleTakenAt(),
      /^\d{4}-\d{2}-\d{2}$/,
      'дата снимка обязана быть днём в ISO — по ней видно возраст числа на витрине',
    );
  });

  test('исторический выдуманный литерал 2 184 не имеет отношения к витрине', () => {
    /*
     * Именно это число было зашито в код (`bugs/07`) при 331 живом человеке. Проверка стоит
     * ЯВНО, чтобы возврат к «красивой цифре» упёрся в тест с историей в тексте, а не прошёл как
     * безобидная правка. Заодно это единственное место, где число 2184 вообще упоминается.
     */
    assert.notEqual(landingPeople(), 2184);
    assert.notEqual(PUBLIC_PEOPLE_SNAPSHOT.people, 2184);
  });
});
