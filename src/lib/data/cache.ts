/**
 * Кэш данных экранов на сессию (`ideas/18`).
 *
 * Слово владельца (2026-07-27): «всякий раз, когда открываешь Профиль, Связи, Измерения,
 * Пространство — выглядит так, словно страница с нуля загружает данные, даже если эту страницу
 * в текущей сессии открывали… это точно нужно где-то локально кешировать в рамках сессии, а не
 * перезагружать при каждой навигации». Замер до кода подтвердил дословно: повторный круг по пяти
 * экранам стоил **29 обращений к базе и 5 карточек «Загрузка»** — ровно столько же, сколько
 * первый (`tools/measure-ideas18.mjs`).
 *
 * ── МОДЕЛЬ ─────────────────────────────────────────────────────────────────────────────────
 * Взята у индустрии, а не придумана: **stale-while-revalidate**, стандартизованный RFC 5861, в
 * той форме, в какой его реализуют TanStack Query и SWR. Разбор с первоисточниками —
 * `researches/17`. Из него сюда пришли три вещи:
 *
 *   1. **Свежесть и наличие в памяти — РАЗНЫЕ оси.** Данные могут лежать в кэше и считаться
 *      несвежими; это нормальное состояние, а не авария. Смешение этих осей — главная ошибка
 *      самодельных кэшей.
 *   2. **Показать мгновенно, освежить тихо.** {@link peek} отдаёт лежащее в памяти СИНХРОННО —
 *      экран рисует первый кадр с данными и не показывает лоадер вовсе; {@link cached} тем
 *      временем решает, нужен ли поход в базу. Тот же приём уже работает у лиц
 *      (`avatar.ts` → `cachedAvatarUrl`, bugs/57) — это его обобщение, а не новый механизм.
 *   3. **Инвалидация — пометкой, а не починкой.** Своя запись помечает ключи устаревшими;
 *      перечитает их тот экран, который откроют. Кэш никто не «чинит» руками.
 *
 * ── ЧЕГО ЗДЕСЬ СОЗНАТЕЛЬНО НЕТ ─────────────────────────────────────────────────────────────
 * **Нет `gcTime`** (выброса неиспользуемого по таймеру), хотя в библиотеках он есть. Он нужен
 * там, где пространство ключей неограниченно (ключ на каждый набор параметров запроса) — у нас
 * ключей фиксированный десяток на человека, и растут они не от использования. Заводить таймер
 * уборки ради шести записей — сложность без причины (`PHILOSOPHY.md`). Опасение владельца
 * («чтобы приложение не упало из-за разрастания») закрыто другим: {@link forgetAll} и потолок
 * ключей, а не сборщик мусора.
 *
 * **Нет библиотеки.** `@tanstack/svelte-query` решала бы ту же задачу, но у нас шесть функций
 * загрузки, а не шестьдесят: берём модель, а не пакет (Оккам).
 *
 * ── ПРИВАТНОСТЬ ────────────────────────────────────────────────────────────────────────────
 * ⚠️ Кэш ПЕРСОНАЛЬНЫЙ. За экраном может смениться человек (вышел один, вошёл другой), и в
 * памяти вкладки при этом остались бы чужие данные. Поэтому у кэша есть **хозяин**
 * ({@link own}): смена uid очищает всё содержимое, а {@link forgetAll} обязателен при выходе
 * из аккаунта. Это не перестраховка — без этого кэш сессии становится дырой приватности.
 */

/** Запись кэша: значение и момент, когда оно получено из базы. */
interface Entry {
  readonly value: unknown;
  readonly at: number;
}

/**
 * Контракт свежести — как долго данные считаются свежими (сети не будет вовсе).
 * Выведен из `ideas/14`, где такой же контракт уже принят для сервера синхронизации,
 * и закрыт решением владельца — интервью №005, В4 (2026-07-28).
 */
export const FRESH = {
  /**
   * Данные, которые меняю Я САМ, — и меняю в этой же вкладке. Значит кэш обновляется по факту
   * моей записи и соврать не может: перечитывать их «на всякий случай» — чистые деньги на ветер
   * (канон `AGENT_GUIDE` → «Модель данных»).
   */
  mine: Number.POSITIVE_INFINITY,
  /**
   * ЦИФРЫ, которые производит сервер синхронизации: мой топ связей и статистика Пространства.
   * Тоже вся сессия — слово владельца (интервью №005, В4): *«ТОП обновляется очень редко. Нет
   * смысла его обновлять. Пользователь зайдёт в приложение — получит свежие данные. Этого
   * хватит»*. Свежесть даёт ВХОД в приложение (новая вкладка = пустой кэш), а не секундомер.
   *
   * Совпадение значения с {@link FRESH.mine} — не дубль: это разные контракты с разными
   * хозяевами правды, и живут они порознь. Своя запись гасит топ немедленно
   * (`profile.ts` → `afterMyRatingChanged`); принудительное обновление по требованию человека —
   * отдельный жест (pull-to-refresh, назван владельцем там же и ждёт своих макетов).
   *
   * ⚠️ Следствие, которое надо знать: оценил → топ перечитается сразу, но сервер к этому моменту
   * мог ещё не досчитать (цикл 60 с + тихий период 120 с), и прочитанное замрёт до конца сессии.
   * Это ровно тот случай, ради которого владелец назвал pull-to-refresh.
   */
  server: Number.POSITIVE_INFINITY,
  /**
   * СЕРДЦЕБИЕНИЕ сервера синхронизации (`space/server`) — единственное, что осталось минутным,
   * и намеренно.
   *
   * Из него ВЫВОДИТСЯ лампочка «Работает / Не отвечает», причём относительно «сейчас»
   * (`model/stats.ts` → `syncServerState`, терпимость — 3 цикла). Заморозь пульс на сессию — и
   * живой сервер через три минуты показался бы человеку умершим. Состояние обязано выводиться из
   * наблюдения, а не из памяти, поэтому цифры Пространства и его пульс живут РАЗНЫМИ записями
   * кэша: цифры — сессия, пульс — минута и один дешёвый документ.
   */
  pulse: 60_000,
} as const;

/**
 * Ключи кэша — все в одном месте, потому что по НАЧАЛУ ключа работает инвалидация.
 *
 * Родство выражено префиксом сознательно: `invalidate('relations')` гасит и сам топ, и его
 * сводку в профиле — одна моя оценка делает несвежим и то, и другое.
 */
export const KEYS = {
  profile: 'profile',
  ratings: 'ratings',
  /** Собранный экран «Измерений». Под префиксом `ratings`: моя оценка делает его несвежим. */
  dimsScreen: 'ratings:screen',
  /** Докуда человек долистал ленту «Все» — чтобы возврат не начинал её с пустоты. */
  dimsShown: 'ratings:shown',
  relations: 'relations',
  relationsSummary: 'relations:summary',
  space: 'space',
  syncServer: 'space:server',
} as const;

const store = new Map<string, Entry>();
/** Незавершённые чтения: два экрана, спросившие одно и то же разом, дают ОДИН запрос. */
const inflight = new Map<string, Promise<unknown>>();
/** Чьи данные сейчас в памяти. `null` — кэш пуст либо хозяин ещё не объявлен. */
let owner: string | null = null;

/**
 * Объявляет хозяина кэша. Сменился человек — прежнее содержимое уничтожается ЦЕЛИКОМ.
 * Зовётся слоями данных перед первым чтением за человека.
 */
export function own(uid: string): void {
  if (owner === uid) return;
  store.clear();
  inflight.clear();
  owner = uid;
}

/** Чей кэш лежит в памяти. Нужен экранам, чтобы не подглядывать в чужое. */
export function cacheOwner(): string | null {
  return owner;
}

/**
 * Что лежит в памяти ПРЯМО СЕЙЧАС — синхронно, без обещаний.
 *
 * Это и есть «показать мгновенно»: экран берёт отсюда значение для ПЕРВОГО кадра и потому не
 * рисует карточку «Загрузка». `undefined` — данных нет, лоадер уместен и честен.
 *
 * Свежесть здесь НЕ проверяется намеренно: показать устаревшее и тихо освежить — это и есть
 * stale-while-revalidate. Границу «устаревшее показывать нельзя» держит {@link cached}.
 */
export function peek<T>(key: string): T | undefined {
  return store.get(key)?.value as T | undefined;
}

/**
 * Отдать из кэша, если свежо; иначе прочитать из базы и запомнить.
 *
 * @param key     ключ записи (`profile`, `relations`, …) — фиксированный, не собирается из данных
 * @param freshMs сколько данные считаются свежими; {@link FRESH.mine} — всю сессию
 * @param load    как прочитать из базы, если свежего нет
 */
export async function cached<T>(key: string, freshMs: number, load: () => Promise<T>): Promise<T> {
  const entry = store.get(key);
  if (entry !== undefined && Date.now() - entry.at < freshMs) return entry.value as T;

  // Дедупликация: пока чтение в пути, все остальные ждут ЕГО, а не заводят своё.
  const running = inflight.get(key);
  if (running !== undefined) return running as Promise<T>;

  const request = load()
    .then((value) => {
      store.set(key, { value, at: Date.now() });
      return value;
    })
    .finally(() => inflight.delete(key));

  inflight.set(key, request);
  return request;
}

/**
 * Положить значение в кэш напрямую, без похода в базу.
 *
 * Нужно для того, что базой не читается, но обязано пережить навигацию, — например, докуда
 * человек долистал ленту. У библиотек этот примитив тоже есть (`setQueryData` в TanStack Query),
 * и он же — единственный законный способ ПИСАТЬ в кэш: всё остальное только читает.
 */
export function remember<T>(key: string, value: T): void {
  store.set(key, { value, at: Date.now() });
}

/**
 * Помечает записи устаревшими — по точному ключу или по его началу (`'dims:'`).
 *
 * Мы именно УДАЛЯЕМ запись, а не переписываем её значение: чинить кэш руками — известный
 * источник рассинхрона, индустрия рекомендует пометить и перечитать (`researches/17` §2.4).
 * Тот экран, который откроют следующим, прочитает свежее сам.
 */
export function invalidate(prefix: string): void {
  for (const key of store.keys()) {
    if (key === prefix || key.startsWith(prefix)) store.delete(key);
  }
}

/**
 * Забыть ВСЁ и хозяина заодно. Обязательно при выходе из аккаунта: иначе данные ушедшего
 * человека останутся в памяти вкладки, куда через минуту войдёт другой.
 */
export function forgetAll(): void {
  store.clear();
  inflight.clear();
  owner = null;
}

/** Сколько записей в памяти — для стражей и отладки, продукту не нужно. */
export function cacheSize(): number {
  return store.size;
}
