/**
 * Порядок двух чтений в окне ожидания пересчёта (`bugs/161`, `data/relations.ts`).
 *
 * ЧТО ЗДЕСЬ СТЕРЕЖЁТСЯ И ПОЧЕМУ ЭТО НЕЛЬЗЯ ПРОВЕРИТЬ ИНАЧЕ. Дефект — гонка: подтверждение
 * «сервер учёл мою оценку» (`dirty === false`) могло прийти к топу, прочитанному РАНЬШЕ, чем
 * сервер этот топ закоммитил. Живьём такая раскладка воспроизводится «иногда» — а канон прямо
 * говорит, что баг, который виден иногда, сперва исследовательская задача
 * (`BUG_FIXING_FRAMEWORK.md` → «Сделай воспроизведение детерминированным»). Здесь она сделана
 * детерминированной: заглушки чтений записывают СОБСТВЕННЫЙ порядок вызовов и разрешений, и
 * тест судит порядок, а не удачу.
 *
 * ⚠️ Проверять надо именно ПОРЯДОК, а не результат. Тест «в кэше свежий топ» был бы зелёным и
 * на сломанном коде — в благополучной раскладке гонки, то есть почти всегда.
 *
 * Запуск: npm test
 */
import assert from 'node:assert/strict';
import { test } from 'node:test';

import { readTopAndPoint } from './relations.ts';

/**
 * Пара заглушек с общим журналом. Каждое чтение отмечает МОМЕНТ ВЫЗОВА и МОМЕНТ РАЗРЕШЕНИЯ —
 * без второго нельзя отличить «точка прочитана первой» от «точка просто вызвана первой», а
 * различие тут и есть весь баг.
 */
function readers({ topDelay = 0, pointDelay = 0 } = {}) {
  const log: string[] = [];
  const wait = (ms: number) => new Promise((resolve) => setTimeout(resolve, ms));

  return {
    log,
    readTop: async () => {
      log.push('топ: вызван');
      await wait(topDelay);
      log.push('топ: прочитан');
      return 'ТОП';
    },
    readPoint: async () => {
      log.push('точка: вызвана');
      await wait(pointDelay);
      log.push('точка: прочитана');
      return 'ТОЧКА';
    },
  };
}

test('в окне ожидания топ НЕ читается, пока не прочитана точка', async () => {
  // Топ отвечает мгновенно, точка — медленно: на параллельном чтении топ успел бы прочитаться
  // ПЕРВЫМ, то есть застать документ, который сервер ещё не закоммитил. Это и есть дефект.
  const { log, readTop, readPoint } = readers({ topDelay: 0, pointDelay: 30 });

  const [top, point] = await readTopAndPoint(true, readTop, readPoint);

  assert.deepEqual(log, [
    'точка: вызвана',
    'точка: прочитана',
    'топ: вызван',
    'топ: прочитан',
  ]);
  assert.equal(top, 'ТОП', 'порядок в ответе остаётся [топ, точка] — вызывающие его не меняли');
  assert.equal(point, 'ТОЧКА');
});

test('подтверждение окна не может относиться к топу, снятому раньше коммита', async () => {
  // Формулировка критерия 1 `bugs/161` как проверка: между «точка прочитана» и «топ вызван»
  // не должно быть НИЧЕГО — только так `dirty === false` доказывает, что коммит топа позади.
  const { log, readTop, readPoint } = readers({ topDelay: 5, pointDelay: 5 });

  await readTopAndPoint(true, readTop, readPoint);

  const pointRead = log.indexOf('точка: прочитана');
  const topCalled = log.indexOf('топ: вызван');
  assert.ok(pointRead >= 0 && topCalled >= 0, 'оба чтения обязаны состояться');
  assert.ok(
    topCalled > pointRead,
    `топ вызван до того, как точка прочитана — окно может закрыться на устаревшем топе: ${log.join(' → ')}`,
  );
});

test('ВНЕ окна пара читается ПАРАЛЛЕЛЬНО — задержка экрана не выросла', async () => {
  // Противовес: без него «починку» можно было бы сделать, сделав последовательным ВСЁ, и
  // тест остался бы зелёным ценой лишнего круга на каждом заходе.
  const { log, readTop, readPoint } = readers({ topDelay: 20, pointDelay: 20 });

  const [top, point] = await readTopAndPoint(false, readTop, readPoint);

  assert.deepEqual(
    log.slice(0, 2),
    ['топ: вызван', 'точка: вызвана'],
    'вне окна оба чтения обязаны стартовать до того, как разрешится любое из них',
  );
  assert.equal(top, 'ТОП');
  assert.equal(point, 'ТОЧКА');
});

test('число чтений не выросло ни в окне, ни вне его (контракт экономии №005 В4)', async () => {
  // Канон владельца «экономить запросы к базе»: починка порядка не имеет права стоить
  // ни одного лишнего чтения. Считаем вызовы, а не рассуждаем о них.
  for (const waiting of [true, false]) {
    let tops = 0;
    let points = 0;
    await readTopAndPoint(
      waiting,
      async () => {
        tops += 1;
        return null;
      },
      async () => {
        points += 1;
        return null;
      },
    );
    assert.equal(tops, 1, `окно=${waiting}: топ читается ровно один раз`);
    assert.equal(points, 1, `окно=${waiting}: точка читается ровно один раз`);
  }
});

test('отказ чтения точки не роняет пару — окно просто остаётся открытым', async () => {
  // Так это и устроено на месте вызова: `.catch(() => null)`. Проверка держит инвариант
  // «не прочиталась точка — экран всё равно живёт», чтобы порядок не породил новую хрупкость.
  const [top, point] = await readTopAndPoint(
    true,
    async () => 'ТОП',
    async () => null,
  );

  assert.equal(top, 'ТОП');
  assert.equal(point, null);
});
