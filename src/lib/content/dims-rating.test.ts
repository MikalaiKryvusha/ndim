/**
 * СТРАЖ ПРАВИЛА ОЦЕНОК — строки 1 и 2 таблицы стражей `plans/36`, шаг 5.
 *
 * Мутации, которые эти тесты обязаны ронять (и роняют — проверено):
 *   · «звёзды при `rates` = 0» — подставить измерение с нулём и ждать звёзд;
 *   · «счётчик при `rates` < 3» — подставить `rates` = 2.
 *
 * Проверяется не только функция, но и ВЕСЬ боевой срез: правило существует ради каталога, а не
 * ради красивого юнита. Числа 1873 / 3238 / **526** сняты по бою (третье исправлено 2026-08-03:
 * стояло 892 — ошибка счёта, разошедшаяся по семи документам; см. врезку в `dims-rating.ts`).
 */
import assert from 'node:assert/strict';
import { test } from 'node:test';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';

import { ratingView, starRow, STARS_FROM, RATER_COUNT_FROM } from './dims-rating.ts';
import slice from './dims-slice.json' with { type: 'json' };

/**
 * 🔴 НИ ОДИН ЭКРАН НЕ ДЕРЖИТ СВОЮ КОПИЮ ПРАВИЛА.
 *
 * Копия здесь уже была и уже разошлась: экран «Измерения» показывал «(N оценок)» с ПЕРВОГО
 * голоса, а публичная страница каталога — с ТРЁХ. То есть человек видел на одной и той же
 * карточке разные числа внутри приложения и из поиска, тогда как владелец решил ровно обратное:
 * «одно правило внутри и снаружи» (интервью №022). Поймано 2026-08-03, вылечено `ratingView`.
 *
 * Проверка грепом, а не типами: разойтись копии могут только текстом.
 */
test('правило показа оценок не скопировано ни в один компонент', () => {
  const walk = (dir: string): string[] =>
    readdirSync(dir).flatMap((name) => {
      const full = join(dir, name);
      return statSync(full).isDirectory() ? walk(full) : [full];
    });

  const strays: string[] = [];
  for (const file of walk('src').filter((f) => f.endsWith('.svelte'))) {
    const code = readFileSync(file, 'utf8')
      .replace(/<!--[\s\S]*?-->/g, ' ')
      .replace(/\/\*[\s\S]*?\*\//g, ' ');
    // Сравнение `rates` с порогом мимо общей функции — и есть копия правила.
    if (/\brates\s*[<>=]=?\s*\d/.test(code) || /\d\s*[<>]=?\s*[\w.]*\brates\b/.test(code)) {
      strays.push(file);
    }
  }
  assert.deepEqual(strays, [], 'порог сравнивается мимо `ratingView` — правило снова раздвоилось');
});

test('нет голосов — нет звёзд (две трети каталога)', () => {
  const v = ratingView(0);
  assert.equal(v.showStars, false, 'ноль означает «не оценивали», а не «оценили на ноль»');
  assert.equal(v.showRaterCount, false);
});

test('ОДИН голос — показываем и звёзды, и счётчик', () => {
  // 🔄 Решение владельца 2026-08-03 ОТМЕНЯЕТ интервью №022 В3: «открываем показ оценок при
  // любом числе оценивших везде по приложению». Прежний порог (от трёх) прятал не личность,
  // а лишь впечатление от числа — разбор в `bugs/113`.
  assert.deepEqual(ratingView(1), { showStars: true, showRaterCount: true });
});

test('два голоса — так же', () => {
  assert.deepEqual(ratingView(2), { showStars: true, showRaterCount: true });
});

test('три голоса — показываем и звёзды, и счётчик', () => {
  assert.deepEqual(ratingView(3), { showStars: true, showRaterCount: true });
});

test('пороги именно такие, какие выбрал владелец', () => {
  assert.equal(STARS_FROM, 1, 'интервью №022 В1 = А');
  assert.equal(RATER_COUNT_FROM, 1, 'решение владельца 2026-08-03, отменяет интервью №022 В3');
});

test('счётчик НИКОГДА не показывается без звёзд', () => {
  // Инвариант формы: «оценили: 5» без самой оценки — бессмысленная строка на публичной странице.
  for (let n = -3; n <= 30; n += 1) {
    const v = ratingView(n);
    if (v.showRaterCount) assert.equal(v.showStars, true, `сломалось на rates=${n}`);
  }
});

test('битое значение ведёт себя как «оценок нет», а не как «показать звёзды»', () => {
  // Каталог — ВНЕШНИЕ данные: типы у нас, а числа приезжают из Firestore.
  // 🔴 `Infinity` здесь не украшение, а ЕДИНСТВЕННЫЙ случай, который отличает защиту от её
  // отсутствия: `NaN >= 1` и `-1 >= 1` ложны и без неё, а `Infinity >= 1` — истинно, и битое
  // поле показало бы звёзды. Первая редакция теста писала `Infinity * 0` (это NaN) и мутацию
  // «защиту убрали» НЕ ловила.
  for (const bad of [NaN, -1, -0.5, Infinity, -Infinity]) {
    assert.equal(ratingView(bad as number).showStars, false, `сломалось на ${bad}`);
    assert.equal(ratingView(bad as number).showRaterCount, false, `сломалось на ${bad}`);
  }
  assert.equal(ratingView(0.9).showStars, false, 'дробное меньше единицы — это ещё ноль голосов');
  assert.equal(ratingView(0.9).showRaterCount, false, 'и счётчика у него тоже нет');
});

test('на РЕАЛЬНОМ срезе каталога правило не даёт ни одной неправды', () => {
  const dims = slice as readonly { rates: number; rating: number; title: { ru: string } }[];
  let zero = 0;
  for (const d of dims) {
    const v = ratingView(d.rates);
    if (d.rates === 0) {
      zero += 1;
      assert.equal(v.showStars, false, `«${d.title.ru}» без голосов, а звёзды показаны`);
      assert.equal(d.rating, 0, 'у измерения без голосов средняя обязана быть нулём');
    }
    /*
     * ⚠️ ЗДЕСЬ БЫЛО ЛОЖНОЕ ДОПУЩЕНИЕ `d.rating > 0` — «оценили, значит средняя не ноль».
     * Шкала продукта 0…10, и НОЛЬ — законная оценка: измерению, которому все поставили 0,
     * честно полагается средняя 0 при ненулевом `rates`. В бою таких два. Пока их не было в
     * срезе, допущение молчало; при следующем обновлении среза оно уронило бы тест на
     * исправных данных. Тот же промах я уже поймал в `tools/verify-prod-dim-ratings.mjs`.
     */
    if (v.showStars) {
      assert.ok(d.rating >= 0 && d.rating <= 10, `«${d.title.ru}»: средняя вне шкалы — ${d.rating}`);
    }
    if (v.showRaterCount) assert.ok(d.rates >= 1);
  }
  assert.ok(zero > 0, 'в срезе обязаны быть измерения без голосов — иначе тест ничего не проверил');
});

/*
 * ── РЯД ЗВЁЗД — ПРАВИЛО ВЛАДЕЛЬЦА (интервью №044, В3) ────────────────────────────────────────
 *
 * 🔄 ЭТОТ БЛОК ЗАМЕНИЛ ТЕСТЫ `ratingState`, и замена названа вслух, потому что удалять зелёные
 * тесты без объяснения — это подгонка. Прежние тесты стерегли ТРИ СОСТОЯНИЯ ТЕКСТА двери:
 * «нет голосов» · «есть оценка» · «все поставили ноль», где третье получало отдельный
 * объясняющий абзац. Владелец отменил не тесты, а сам замысел: «*ничего никому объяснять не
 * нужно про ноль звёзд - это просто частный случай пространства*». Объяснения не стало —
 * стеречь стало нечего, и состояние осталось только в ОТРИСОВКЕ. Её и стерегут тесты ниже.
 *
 * Мутации, которые они обязаны ронять:
 *   · «десять позиций» — вернуть ряд из десяти с пустыми хвостами (число звёзд перестаёт
 *     совпадать с округлённой оценкой);
 *   · «ноль рисуется как всё» — вернуть `{ gold: 0, grey: 0 }` при нулевой средней;
 *   · «положительная округляется в ноль» — снять нижнюю границу 1.
 */

test('от единицы и выше — только ЗОЛОТЫЕ звёзды, числом округлённой оценки', () => {
  assert.deepEqual(starRow(1), { gold: 1, grey: 0 });
  assert.deepEqual(starRow(8), { gold: 8, grey: 0 });
  assert.deepEqual(starRow(10), { gold: 10, grey: 0 });
  // «дальше по мере роста оценки растёт количество» — ряд обязан быть неубывающим.
  let prev = 0;
  for (let r = 1; r <= 10; r += 0.1) {
    const gold = starRow(r).gold;
    assert.ok(gold >= prev, `ряд пошёл вспять на ${r.toFixed(1)}: ${gold} после ${prev}`);
    prev = gold;
  }
});

test('дробная средняя округляется, а не обрезается', () => {
  assert.equal(starRow(7.5).gold, 8, '7,5 — это восемь звёзд, а не семь');
  assert.equal(starRow(8.4).gold, 8);
  assert.equal(starRow(8.6).gold, 9);
});

test('🔴 ВЕСЬ поддиапазон ниже единицы — ОДНА ТЯЖЁЛАЯ СЕРАЯ звезда, золотых нет', () => {
  /*
   * Уточнение владельца по кадрам (№044 В3): «*оценка между нулём и единицей - это рисуем первую
   * звезду серым тяжёлым цветом, только от 1 и выше - первая звезда заливается золотом*».
   *
   * 🔄 ЭТОТ ТЕСТ ЗАМЕНИЛ ПРЕЖНИЙ «положительная оценка НИКОГДА не рисуется как ноль», и замена
   * названа вслух: тот тест стерёг МОЙ вывод из его первой фразы (ниже 0,5 — одна ЗОЛОТАЯ), а
   * уточнение прочло ту же границу иначе и прямо. Отменил вывод владелец, а не удобство.
   */
  for (const r of [0, 0.1, 0.33, 0.5, 0.9, 0.999]) {
    assert.deepEqual(starRow(r), { gold: 0, grey: 1 }, `сломалось на средней ${r}`);
  }
});

test('🔑 фикстура 0 < r < 1: кадр нуля ЕСТЬ кадр всего поддиапазона', () => {
  /*
   * В каталоге объектов с такой средней сегодня НОЛЬ (замер по `dims-build.json`: 1877
   * оценённых, ни одного в интервале). Снять их кадром на стенде нечем — поэтому равенство
   * доказывается здесь: отрисовщик получает ОДИН И ТОТ ЖЕ ряд, значит и пиксели у них одни.
   * Тест — замена несуществующей съёмке, и он честнее её: съёмка показала бы один случай,
   * а это утверждение накрывает весь интервал.
   */
  const zero = starRow(0);
  for (const r of [0.01, 0.33, 0.5, 0.75, 0.99]) {
    assert.deepEqual(starRow(r), zero, `средняя ${r} рисуется НЕ так же, как ноль`);
  }
});

test('граница ровно на единице — золото начинается С НЕЁ', () => {
  assert.deepEqual(starRow(0.999), { gold: 0, grey: 1 }, 'чуть ниже единицы — ещё серая');
  assert.deepEqual(starRow(1), { gold: 1, grey: 0 }, 'ровно единица — уже золотая');
  assert.deepEqual(starRow(1.4), { gold: 1, grey: 0 }, 'округление вниз не роняет обратно в серую');
});

test('ряд никогда не выходит за шкалу 0…10 и не падает на битом значении', () => {
  for (const bad of [NaN, undefined, null, 'нет']) {
    assert.deepEqual(starRow(bad as number), { gold: 0, grey: 1 }, `сломалось на ${String(bad)}`);
  }
  assert.deepEqual(starRow(-3), { gold: 0, grey: 1 }, 'отрицательная ведёт себя как ноль');
  assert.deepEqual(starRow(0.5), { gold: 0, grey: 1 }, 'половина балла — ещё не золото');
  assert.equal(starRow(42).gold, 10, 'выше десяти звёзд не бывает');
});

test('звёзд всегда хотя бы одна — там, где ряд вообще рисуется', () => {
  for (const r of [0, 0.2, 1, 5, 9.9, 10]) {
    const row = starRow(r);
    assert.ok(row.gold + row.grey >= 1, `пустой ряд на средней ${r}`);
    assert.ok(row.gold === 0 || row.grey === 0, `золотые и серые вместе на средней ${r}`);
  }
});

test('на РЕАЛЬНОМ срезе каталога ряд согласован с правилом показа оценок', () => {
  const dims = slice as readonly { rates: number; rating: number; title: { ru: string } }[];
  let drawn = 0;
  for (const d of dims) {
    if (!ratingView(d.rates).showStars) continue; // ряд не рисуется вовсе
    drawn += 1;
    const row = starRow(d.rating);
    assert.ok(row.gold + row.grey >= 1, `«${d.title.ru}»: оценка есть, а рисовать нечего`);
    if (d.rating >= 1) assert.equal(row.grey, 0, `«${d.title.ru}»: серая звезда при оценке от единицы`);
    if (d.rating < 1) assert.equal(row.gold, 0, `«${d.title.ru}»: золото ниже единицы`);
  }
  assert.ok(drawn > 0, 'в срезе обязаны быть оценённые — иначе тест ничего не проверил');
});

test('🔴 битая средняя НЕ рисует звезду там, где голосов нет вовсе (вердикт QA)', () => {
  /*
   * Замечание QA, и оно точное: серая звезда «ноль» безопасна ровно потому, что до неё
   * спрашивают ПОРОГ ГОЛОСОВ. Если этот порядок когда-нибудь сломается, неоценённый объект
   * с мусором в поле средней покажет человеку серую звезду — то есть чужую оценку там, где
   * оценки нет вовсе. Это враньё, а не косметика, и стеречь его надо отдельно.
   *
   * Договор шаблона дословно: ряд считается ТОЛЬКО внутри ветки `showStars`. Здесь проверяется
   * первая половина договора — что при нуле голосов эта ветка закрыта при любом значении
   * средней. Вторую половину (что шаблон действительно так и написан) доказывает страж по
   * СОБРАННОМУ HTML: «звёзд НЕТ там, где нет голосов» в `verify-dimension-pages.mjs`.
   */
  for (const rating of [NaN, -1, 0, 7.5, 10, null, undefined]) {
    assert.equal(
      ratingView(0).showStars,
      false,
      `голосов нет — ряд не рисуется, что бы ни лежало в средней (${String(rating)})`,
    );
  }
  // А там, где голоса ЕСТЬ, битая средняя обязана дать серую звезду, а не пустое место:
  // пустой ряд читался бы как «оценки нет», и это была бы та же неправда с другой стороны.
  assert.deepEqual(starRow(NaN as unknown as number), { gold: 0, grey: 1 });
});
