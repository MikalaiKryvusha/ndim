/**
 * ИМЕНА — средняя часть описания, и ЕДИНСТВЕННОЕ, чем отличаются ступени лестницы (§5).
 *
 * Голова и хвост стоят на всех трёх ступенях: режется иллюстрация, а не смысл.
 *
 * ⚠️ Ступень 3 отдаёт вместо имён НОМЕР СТРАНИЦЫ, и это не украшение: без него две страницы
 * одного вида, докатившиеся до третьей ступени, дали бы побайтно одинаковое описание — тот самый
 * дубль, ради которого шаг затеян. Номер возвращает странице отличие от соседних, ушедшее вместе
 * с именами. У вида из ОДНОЙ страницы номера нет — там и соседей нет, отличать не от кого.
 */
const namesPart = (lang: Lang, facts: HubPageFacts, want: number): string => {
  const n = facts.names.map((s) => q(s, lang));
  const en = lang === 'en';
  if (want >= 2 && n.length >= 2) return en ? `: ${n[0]}, ${n[1]} and more` : `: ${n[0]}, ${n[1]} и другие`;
  if (want >= 1 && n.length >= 1) return en ? `: ${n[0]} and more` : `: ${n[0]} и другие`;
  return facts.pages > 1 ? `, ${CATALOG_COPY[lang].pageOf(facts.page, facts.pages)}` : '';
};

