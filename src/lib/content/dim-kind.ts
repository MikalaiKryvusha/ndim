/**
 * КАНОНИЧЕСКИЙ ВИД ОБЪЕКТА КАТАЛОГА — одно место на весь проект (`plans/48`, фаза 2 эпика 40).
 *
 * Поле `type` документа `dims/{dimId}` — это то, чем объект является: фильм, видеоигра, роман.
 * По нему строятся хабы каталога, и именно поэтому оно перестало быть просто подписью: **из
 * значения этого поля рождается АДРЕС**, а адрес обязан быть один на смысл.
 *
 * ── ПОЧЕМУ НОРМАЛИЗАЦИЯ, А НЕ ПРОПОЛКА ДАННЫХ ────────────────────────────────────────────────
 * Метаплан ставил условием сначала прополоть поле в бою (`plans/30`). Замер шага 0 `plans/48`
 * (5111 записей, только чтение) показал, что условие снимается дешевле:
 *
 *   | Класс грязи | Записей | Что именно |
 *   |---|---|---|
 *   | невидимый `U+200B` | **44** | `"TV Series​"` 41 · `"TV Show​"` 3 · `"Телесериал​"` 1 |
 *   | регистр | 46 | `"фильм"`/`"movie"` по 21, `"роман"`, `"novel"`, `"видеоигра"`, `"video game"` |
 *   | год вместо вида | 4 | `"1998"`, `"1993"` ×2, `"1994"` |
 *   | язык не в своём поле | 5 | `"Movie"` в русском ×3, `"Фильм"`/`"Роман"` в английском |
 *   | пустая строка | 1 | `type.en === ""` |
 *
 * 🔴 Без нормализации хабов было бы ДВА на один смысл: «TV Series» (329) и «TV Series​» (41) —
 * визуально неразличимых, с разными адресами, делящих между собой вес. Один невидимый знак
 * стоил бы фазе её собственной цели.
 *
 * Нормализация на ЧТЕНИИ решает это по построению, а прополка данных остаётся гигиеной: она
 * нужна, но больше никого не задерживает и идёт со словом владельца (правка данных в бою).
 * ⚠️ Цена, названная сознательно: до прополки внутренний экран `/dims` читает Firestore напрямую
 * и увидит сырое значение с `U+200B`. Это не регрессия — это граница модуля.
 *
 * ── ЧЕГО ЭТОТ МОДУЛЬ НЕ ДЕЛАЕТ ───────────────────────────────────────────────────────────────
 * ⛔ **Не сливает виды по смыслу.** «Повесть» не становится «Романом», «Мультфильм» — «Фильмом».
 *    Это изменило бы то, ЧЕМ объект является, то есть было бы правкой данных под видом чтения.
 *    Такие записи получают `null` и в хабы не попадают (их 31 из 5111 — таблица ниже).
 * ⛔ Не переводит и не сочиняет подписи из данных: подписи хабов — тексты лица продукта, они
 *    живут здесь явным словарём и проходят вычитку владельца вместе с макетами (`plans/48` шаг 2).
 */

import type { Lang } from './langs';

/**
 * Виды, у которых есть хаб. Порог — **≥20 карточек** (ворота фазы 2: хаб меньшего размера сам
 * становится тонкой страницей и работает против site-wide профиля, `researches/34` §4.3).
 *
 * Числа — замер шага 0 `plans/48` по полному каталогу 2026-08-14; семь видов покрывают
 * **5086 из 5111 (99,5 %)**, значений вида, неизвестных словарю, — **ноль**. Пересчитать, а не
 * поверить:
 * ```
 * node -e "const a=require('./src/lib/content/dims-build.json');const n=s=>String(s||'').replace(/[​-‍﻿]/g,'').trim().toLowerCase();const m={};for(const x of a){const k=n(x.type&&x.type.en)||n(x.type&&x.type.ru);m[k]=(m[k]||0)+1}console.log(Object.entries(m).sort((p,q)=>q[1]-p[1]))"
 * ```
 */
export const KIND_KEYS = [
  'movie', // 2774
  'video-game', // 1221
  'tv-series', // 370
  'novel', // 231
  'practice', // 228
  'music-artist', // 198
  'book', // 64
] as const;

export type KindKey = (typeof KIND_KEYS)[number];

/**
 * Написания, которые каталог реально содержит, → ключ вида.
 *
 * Ключи словаря уже нормализованы (без невидимых знаков, в нижнем регистре) — сравнение идёт
 * с результатом `normalizeRaw`, а не с сырой строкой.
 *
 * 🔑 Оба языка в одном словаре сознательно: в каталоге есть записи, где русское значение стоит в
 * английском поле и наоборот (5 штук). Разделённые словари объявили бы их неизвестными и выбросили
 * бы объект из хаба — при том что вид у него известен совершенно точно.
 */
const KEY_BY_RAW = new Map<string, KindKey>([
  ['movie', 'movie'],
  ['фильм', 'movie'],
  ['video game', 'video-game'],
  ['видеоигра', 'video-game'],
  ['tv series', 'tv-series'],
  ['телесериал', 'tv-series'],
  ['novel', 'novel'],
  ['роман', 'novel'],
  ['practice', 'practice'],
  ['практика', 'practice'],
  ['music artist', 'music-artist'],
  ['музыкальный исполнитель', 'music-artist'],
  ['book', 'book'],
  ['книга', 'book'],
]);

/**
 * Виды БЕЗ хаба — 25 записей из 5111. Перечислены поимённо, чтобы «неизвестный вид» и «известный
 * вид, которому не хватило карточек» не сливались в одну кучу: первое — сигнал о новых данных,
 * второе — осознанное решение порога.
 *
 * TV Show 11 (из них 3 с `U+200B`) · Novella 5 · Animated Movie 3 · Internet Show 3 ·
 * Lecture 2 · Graphic Novel 1.
 *
 * 🔑 Записи с годом или пустотой в ОДНОМ поле (5 штук) в этот список не попадают — их спасает
 * второе поле: у «Six Days Seven Nights» русский вид «1998», зато английский «Movie», и объект
 * совершенно точно фильм. Порядок опроса полей в `kindKeyOf` существует ради них.
 */
const KNOWN_WITHOUT_HUB = new Set<string>([
  'tv show',
  'телешоу',
  'novella',
  'повесть',
  'animated movie',
  'мультфильм',
  'internet show',
  'интернет-шоу',
  'lecture',
  'лекция',
  'graphic novel',
  'графический роман',
]);

/** Невидимые знаки, найденные в поле замером: нулевой ширины и BOM. */
const INVISIBLE = /[​-‍﻿]/g;

/**
 * Сырое значение → сравнимая форма: без невидимых знаков, без краевых пробелов, в нижнем
 * регистре, с одиночными пробелами внутри.
 *
 * Идемпотентна по построению — повторное применение ничего не меняет (инвариант проверяется
 * тестом: нормализация, которая «дочищает» на втором проходе, означает, что первый проход
 * оставил мусор, и рано или поздно даст два адреса на один смысл).
 */
export function normalizeRaw(raw: string | undefined | null): string {
  return String(raw ?? '')
    .replace(INVISIBLE, '')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}

/** Значение-год (`"1998"`) — это не вид, а данные, попавшие не в своё поле. */
const isYearLike = (v: string) => /^\d{4}$/.test(v);

/**
 * Ключ хаба для объекта каталога, либо `null` — «хаба у этого вида нет».
 *
 * Порядок опроса полей: сначала своё языковое, потом второе. Ровно так спасаются те пять записей,
 * где языки перепутаны местами: если в английском поле стоит «Фильм», вид объекта от этого не
 * перестал быть фильмом.
 */
export function kindKeyOf(type: { ru?: string; en?: string } | undefined): KindKey | null {
  const en = normalizeRaw(type?.en);
  const ru = normalizeRaw(type?.ru);
  for (const raw of [en, ru]) {
    if (!raw || isYearLike(raw)) continue;
    const key = KEY_BY_RAW.get(raw);
    if (key) return key;
  }
  return null;
}

/**
 * Вид известен, но хаба у него нет (не хватило карточек по порогу) — в отличие от вида, которого
 * мы не видели вовсе. Разница нужна приборам: рост числа НЕИЗВЕСТНЫХ значит, что каталог
 * пополнился новым видом и словарь пора расширить.
 */
export function isKnownWithoutHub(type: { ru?: string; en?: string } | undefined): boolean {
  const en = normalizeRaw(type?.en);
  const ru = normalizeRaw(type?.ru);
  return KNOWN_WITHOUT_HUB.has(en) || KNOWN_WITHOUT_HUB.has(ru);
}

/**
 * Подписи видов — ТЕКСТ ЛИЦА ПРОДУКТА, а не производная от данных.
 *
 * Единственное число — для карточки объекта («Фильм»), множественное — для заголовка хаба
 * («Фильмы»). Русские формы взяты из самого каталога, то есть из языка, которым владелец уже
 * описал 5111 объектов; английские — из его же английских значений.
 */
const LABELS: Record<
  KindKey,
  { one: Record<Lang, string>; many: Record<Lang, string>; manyLower: Record<Lang, string> }
> = {
  movie: {
    one: { ru: 'Фильм', en: 'Movie' },
    many: { ru: 'Фильмы', en: 'Movies' },
    manyLower: { ru: 'фильмы', en: 'movies' },
  },
  'video-game': {
    one: { ru: 'Видеоигра', en: 'Video game' },
    many: { ru: 'Видеоигры', en: 'Video games' },
    manyLower: { ru: 'видеоигры', en: 'video games' },
  },
  'tv-series': {
    one: { ru: 'Телесериал', en: 'TV series' },
    many: { ru: 'Телесериалы', en: 'TV series' },
    // 🔴 ВОТ РАДИ ЭТОЙ СТРОКИ ФОРМА ЖИВЁТ ТАБЛИЦЕЙ: `toLowerCase()` дал бы «tv series».
    manyLower: { ru: 'телесериалы', en: 'TV series' },
  },
  novel: {
    one: { ru: 'Роман', en: 'Novel' },
    many: { ru: 'Романы', en: 'Novels' },
    manyLower: { ru: 'романы', en: 'novels' },
  },
  practice: {
    one: { ru: 'Практика', en: 'Practice' },
    many: { ru: 'Практики', en: 'Practices' },
    manyLower: { ru: 'практики', en: 'practices' },
  },
  'music-artist': {
    one: { ru: 'Музыкальный исполнитель', en: 'Music artist' },
    many: { ru: 'Музыкальные исполнители', en: 'Music artists' },
    manyLower: { ru: 'музыкальные исполнители', en: 'music artists' },
  },
  book: {
    one: { ru: 'Книга', en: 'Book' },
    many: { ru: 'Книги', en: 'Books' },
    manyLower: { ru: 'книги', en: 'books' },
  },
};

/** Подпись вида в единственном числе — для карточки объекта. */
export const kindLabel = (key: KindKey, lang: Lang): string => LABELS[key].one[lang];

/** Заголовок хаба — множественное число. */
export const kindTitle = (key: KindKey, lang: Lang): string => LABELS[key].many[lang];

/**
 * Вид СТРОЧНОЙ буквы — для середины предложения («Эти фильмы пока ждут первой оценки»).
 *
 * 🔴 Форма взята ТАБЛИЦЕЙ, а не `toLowerCase()` от заголовка, и это требование принятых
 * владельцем текстов (`design/hub-texts-approved.md` §7 п.4). Разделяющий случай — `tv-series`:
 * «TV series» начинается с АББРЕВИАТУРЫ, и механическое понижение регистра дало бы «tv series»
 * на публичной странице. Один вид из семи ломает правило — значит правила нет, есть таблица.
 */
export const kindTitleLower = (key: KindKey, lang: Lang): string => LABELS[key].manyLower[lang];

/** Проверка «это наш ключ вида» — для ограничителя параметра маршрута и стражей. */
export const isKindKey = (v: unknown): v is KindKey =>
  (KIND_KEYS as readonly string[]).includes(v as string);
