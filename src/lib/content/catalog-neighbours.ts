/**
 * СОСЕДИ ПО КАТАЛОГУ — блок «Похожие по каталогу» на карточке (`plans/48` шаг 4).
 *
 * Разрешён владельцем ЯВНО и с названной границей (интервью №025, В7 = А): соседство **по
 * КЛАССИФИКАЦИИ** — тот же вид, пересечение тегов, тот же автор, тот же период. Соседство по
 * математике похожести — «до лучших времён» (`plans/37`).
 *
 * 🔴 ЧЕГО ЗДЕСЬ НЕТ И ЧТО НЕЛЬЗЯ «ДОЧИНИТЬ»:
 *   · ни одного числа похожести и ни одной подписи, намекающей на силу связи. Инвариант владельца
 *     покрывает и ПОРЯДОК близости, поэтому отобранные соседи показываются в нейтральном порядке
 *     (по слагу), а не по убыванию оценки соседства: список, выстроенный по силе, сам является
 *     раскрытым порядком близости;
 *   · формулировка «Рядом в Пространстве» ЗАПРЕЩЕНА (метаплан `plans/40`, ⛔-таблица) — «Рядом в
 *     Пространстве» это про людей и про математику, а здесь классификация;
 *   · ни одного человека и ни одной чужой оценки — публичная поверхность (интервью №022).
 *
 * ── ПОЧЕМУ ВЕС ТЕГА ЗАВИСИТ ОТ ЕГО РЕДКОСТИ ─────────────────────────────────────────────────
 * Замер каталога 2026-08-14: теги есть у **5108 объектов из 5111**, в среднем восемь. Но четыре
 * самых частых — `movie` 3155 · `кино` 3136 · `фильм` 3129 · `film` 3091 — это САМ ВИД, и внутри
 * хаба «Фильмы» они общие у всех. Считать пересечение штуками значило бы объявить каждый фильм
 * соседом каждого.
 *
 * Поэтому вес общего тега — **обратная частота** (IDF, `ln(N / df)`): редкий общий тег говорит
 * много, всеобщий — почти ничего. Приём стандартный (поиск и рекомендации по содержанию), а не
 * изобретённый здесь: `PHILOSOPHY.md` → «best practice вместо велосипеда».
 *
 * 🔑 И побочная выгода, ради которой стоит держать теги как есть: они в каталоге ДВУЯЗЫЧНЫ
 * (`movie` и `кино` лежат рядом у одного объекта), поэтому пересечение считается одинаково для
 * русской и английской страницы. Набор соседей у пары `/ru/…` и `/en/…` выходит ОДИН — иначе
 * `hreflang` снова утверждал бы, что переводами являются страницы с разным содержанием.
 */

import type { CatalogItem } from './catalog-hub.ts';

/** Сколько соседей показывает карточка. План: 6–8; берём верхнюю границу. */
export const NEIGHBOURS = 8;

/** Ссылка на соседа — ровно то, что рисуется, и ни полем больше. */
export interface NeighbourLink {
  readonly slug: string;
  readonly title: string;
  /** Год; пусто, если неизвестен. Автор и оценка сюда НЕ едут — см. врезку о весе ниже. */
  readonly year: string;
}

/**
 * Вклад совпадения автора. Держится соизмеримым с одним редким тегом: автор — сильный сигнал
 * («ещё у этого режиссёра»), но не такой, чтобы одним собой набивать все восемь мест.
 */
const AUTHOR_WEIGHT = 2;
/** Вклад совпадения десятилетия — слабый: период это фон, а не родство. */
const DECADE_WEIGHT = 0.3;

const decadeOf = (year: string) => (/^\d{4}$/.test(year) ? year.slice(0, 3) : '');

/**
 * Обратная частота тега по ВСЕМУ каталогу: `ln(N / df)`.
 *
 * По каталогу, а не по хабу, сознательно: «драма» одинаково распространённая и среди фильмов, и
 * среди сериалов, и общая шкала не даёт весам скакать от размера хаба.
 */
export function tagWeights(items: readonly { tags: readonly string[] }[]): Map<string, number> {
  const df = new Map<string, number>();
  for (const d of items) for (const t of new Set(d.tags)) df.set(t, (df.get(t) ?? 0) + 1);
  const n = Math.max(1, items.length);
  const w = new Map<string, number>();
  for (const [t, f] of df) {
    // 🔴 Тег, который есть у четверти каталога, весит РОВНО НОЛЬ, а не «мало». Замер 2026-08-14
    // называет их поимённо: `movie` 3155 · `кино` 3136 · `фильм` 3129 · `film` 3091 · `драма` 1363
    // · `drama` 1283. Первые четыре — это САМ ВИД, и внутри хаба «Фильмы» они общие у всех: с
    // ненулевым весом они складывались в одинаковую прибавку каждому, равенства разводил слаг, и
    // «Матрица» получала в соседи «10 причин моей ненависти» — первое по алфавиту. Проверено
    // прогоном до этой строки.
    w.set(t, f > n / 4 ? 0 : Math.log(n / f));
  }
  return w;
}

/** Объект каталога с тегами — то, что нужно этому модулю сверх `CatalogItem`. */
export type NeighbourItem = CatalogItem & { readonly tags: readonly string[] };

/**
 * Соседи одного объекта внутри его пула (пул — это его хаб либо хвост).
 *
 * Отбор детерминирован полностью: сначала по убыванию оценки соседства, равенства разводит слаг.
 * Возвращается уже НЕЙТРАЛЬНЫЙ порядок — по слагу (см. врезку об инварианте наверху файла).
 *
 * Объект без единого общего признака соседей не получает: пустой блок честнее восьми случайных
 * ссылок «просто того же вида».
 */
export function neighboursOf(
  target: NeighbourItem,
  pool: readonly NeighbourItem[],
  weights: Map<string, number>,
  limit = NEIGHBOURS,
): NeighbourItem[] {
  const tags = new Set(target.tags);
  const author = target.author.ru && target.author.ru !== '-' ? target.author.ru : '';
  const decade = decadeOf(target.year);

  /*
   * 🔴 ДЕСЯТИЛЕТИЕ УСИЛИВАЕТ ПРИЗНАК, НО САМО ПРИЗНАКОМ НЕ ЯВЛЯЕТСЯ — и это не вкус, а разбор
   * поймавшего меня прогона. Пока совпадение десятилетия давало право попасть в соседи, у
   * «Матрицы» (жанровых тегов нет, только вид) в один и тот же вес 0,3 попадали ВСЕ фильмы
   * девяностых — сотни штук, — равенство разводил слаг, и в блок вставали «10 причин моей
   * ненависти» и «Бронкская история»: первые по алфавиту. Ровно та же болезнь, что с тегами вида,
   * только через другое поле.
   *
   * Поэтому право быть соседом даёт ТОЛЬКО содержательный признак — общий значащий тег или тот же
   * автор; десятилетие лишь поднимает того, кто уже прошёл.
   */
  const scored: { d: NeighbourItem; score: number }[] = [];
  for (const d of pool) {
    if (d.slug === target.slug) continue;
    let base = 0;
    for (const t of new Set(d.tags)) if (tags.has(t)) base += weights.get(t) ?? 0;
    if (author && d.author.ru === author) base += AUTHOR_WEIGHT;
    if (base <= 0) continue;
    scored.push({ d, score: base + (decade && decadeOf(d.year) === decade ? DECADE_WEIGHT : 0) });
  }

  scored.sort((a, b) => b.score - a.score || (a.d.slug < b.d.slug ? -1 : a.d.slug > b.d.slug ? 1 : 0));
  const picked = scored.slice(0, limit).map((s) => s.d);

  /*
   * ЗАПАСНОЙ ПУТЬ — БЛИЖАЙШИЕ ПО ГОДУ ВНУТРИ ТОГО ЖЕ ВИДА.
   *
   * Нужен не «на всякий случай», а по замеру: жанровых тегов нет у **184 фильмов из 2774** (7 %)
   * и у 12 сериалов — у «Матрицы» и «Побега из Шоушенка» в каталоге стоят только четыре тега вида.
   * Без запасного пути их карточки остались бы вовсе без соседей, то есть ровно с одной входящей
   * ссылкой — а критерий фазы обещает ≥3 у КАЖДОЙ карточки.
   *
   * Год и вид — это классификация, а не похожесть: «фильм тех же лет» человек проверяет глазами
   * по карточке. Отбор детерминирован: сначала меньшая разница лет, равенства разводит слаг.
   */
  if (picked.length < limit) {
    const taken = new Set([target.slug, ...picked.map((d) => d.slug)]);
    const year = Number(target.year);
    const rest = pool
      .filter((d) => !taken.has(d.slug))
      .map((d) => ({ d, gap: Number.isFinite(year) && /^\d{4}$/.test(d.year) ? Math.abs(Number(d.year) - year) : 9999 }))
      .sort((a, b) => a.gap - b.gap || (a.d.slug < b.d.slug ? -1 : a.d.slug > b.d.slug ? 1 : 0))
      .slice(0, limit - picked.length)
      .map((s) => s.d);
    picked.push(...rest);
  }

  return picked.sort((a, b) => (a.slug < b.slug ? -1 : a.slug > b.slug ? 1 : 0));
}

/**
 * ВОЗВРАТ ПОТЕРЯННЫХ — проход по всему графу соседства, а не по одной карточке.
 *
 * 🔴 Зачем он вообще нужен, числом. Отбор соседей несимметричен: A может считать B своим соседом,
 * а B выбрать восьмерых других. Замер 2026-08-14 по боевому каталогу: **764 объекта из 5111 не
 * выбраны соседом НИ РАЗУ** — их страницы остались бы с двумя входящими ссылками (языковой
 * двойник и хаб), а критерий 2 фазы обещает **≥3 у каждой карточки**. Обещание, взятое «в
 * среднем», не выполнено ни для кого конкретно.
 *
 * Правило возврата — детерминированное и щадящее: потерянный объект дописывается в список СВОЕГО
 * соседа, и выбирается тот, у кого список сейчас КОРОЧЕ (равенства разводит слаг). Так возвращённые
 * расходятся по каталогу, а не сваливаются на один популярный объект.
 *
 * ⚠️ Названная цена, ЗАМЕРЕННАЯ, а не оценённая: после прохода списки длиной 8 у 4461 карточки ·
 * 9 у 560 · 10 у 66 · 11 у 24. План писал «6–8», и это осознанное отступление от буквы ради его
 * же критерия: 6–8 было указанием размера, а «≥3 входящих у каждой» — воротами фазы. Жёсткий
 * потолок здесь не ставится сознательно: он вернул бы часть объектов обратно в потерянные, то
 * есть купил бы ровную цифру ценой самого смысла прохода.
 */
export function returnLostNeighbours(
  index: Map<string, NeighbourItem[]>,
  items: readonly NeighbourItem[],
): number {
  const inbound = new Map<string, number>();
  for (const slug of index.keys()) inbound.set(slug, 0);
  for (const list of index.values()) {
    for (const n of list) inbound.set(n.slug, (inbound.get(n.slug) ?? 0) + 1);
  }

  /*
   * 🔴 Справочник объектов берётся из САМОГО КАТАЛОГА, а не из списков соседей. Первая редакция
   * собирала его обходом списков — и не находила ровно тех, ради кого проход написан: потерянный
   * объект по определению не лежит ни в одном списке. Проход отработал бы вхолостую и молча.
   */
  const bySlug = new Map<string, NeighbourItem>(items.map((d) => [d.slug, d]));

  const lost = [...inbound.entries()]
    .filter(([, n]) => n === 0)
    .map(([slug]) => slug)
    .sort();

  let returned = 0;
  for (const slug of lost) {
    const own = index.get(slug) ?? [];
    if (!own.length) continue; // соседей нет вовсе — вернуть некуда, и это честнее подделки
    const host = [...own].sort((a, b) => {
      const la = index.get(a.slug)?.length ?? 0;
      const lb = index.get(b.slug)?.length ?? 0;
      return la - lb || (a.slug < b.slug ? -1 : 1);
    })[0];
    const list = index.get(host.slug);
    const self = bySlug.get(slug);
    if (!list || !self || list.some((n) => n.slug === slug)) continue;
    list.push(self);
    list.sort((a, b) => (a.slug < b.slug ? -1 : a.slug > b.slug ? 1 : 0));
    returned += 1;
  }
  return returned;
}
