/**
 * ЯЗЫКИ ПУБЛИЧНЫХ АДРЕСОВ — одно место на весь проект.
 *
 * Решение владельца (интервью №010, Р5 = В, подтверждено 2026-08-03): у каждого языка свой
 * префикс — `/ru/…`, `/en/…`, — ни один не сидит на голом корне, корень перенаправляет.
 * `x-default` указывает на **английский** (отдельная строка того же ответа).
 *
 * ⚠️ ГРАНИЦА ЭТОГО МОДУЛЯ, чтобы его не приняли за общий модуль языка. Здесь только то, что
 * нужно ПУБЛИЧНЫМ АДРЕСАМ: список языков и подписи. Общий модуль языка приложения (память
 * браузера, мост «адрес → память», умолчание для человека с пустой памятью) — работа `plans/24`
 * фазы 6, и он ещё не написан. Когда он появится, ЭТОТ модуль в него вливается, а не живёт рядом.
 * Сегодня язык читается из памяти браузера в 12 местах — трогать их эта фаза не имеет права.
 */

/** Языки, у которых есть публичные адреса. Третий добавляется сюда и в `src/params/lang.ts`. */
export const LANGS = ['ru', 'en'] as const;

export type Lang = (typeof LANGS)[number];

/**
 * Куда указывает `x-default` — на английский.
 * Прямая строка ответа владельца (интервью №010, Р5): «`x-default` указывает на английский».
 */
export const X_DEFAULT: Lang = 'en';

/** Значение атрибута `lang` документа. */
export const HTML_LANG: Record<Lang, string> = { ru: 'ru', en: 'en' };

/** Как язык называется на себе самом — для переключателя и для подписи ссылки. */
export const LANG_LABEL: Record<Lang, string> = { ru: 'Русский', en: 'English' };

/** Проверка «это один из наших языков». Одна на проект — список языков тоже один. */
export const isLang = (v: unknown): v is Lang => (LANGS as readonly string[]).includes(v as string);

/**
 * Язык из АДРЕСА, если адрес его задаёт: `/ru/…`, `/en/…`. Иначе `null`.
 *
 * 🔴 ПОЧЕМУ ЗДЕСЬ, А НЕ В МОДУЛЕ СОСТОЯНИЯ. Это правило нужно трём разным местам: серверному
 * хуку (`<html lang>`), ограничителю параметра маршрута и модулю языка на клиенте. Три копии
 * «взять первый сегмент» разошлись бы молча — и разошлись бы в ту сторону, где сборка зелёная,
 * а человек видит не тот язык. Здесь же оно ТЕСТИРУЕТСЯ: модуль состояния написан на рунах и
 * под `node --test` не исполняется в принципе.
 *
 * Сегмент обязан быть РОВНО кодом языка. Иначе адрес `/russian-literature/…` или измерение со
 * слагом, начинающимся на `ru`, увели бы язык страницы.
 */
export function langFromPath(pathname: string): Lang | null {
  const first = pathname.split('/')[1] ?? '';
  return isLang(first) ? first : null;
}

/**
 * Умолчание для человека, о котором мы не знаем ничего, — решение владельца
 * (интервью №024, В1 = **А**): «спросить браузер: просит русский — даём русский, иначе
 * английский».
 *
 * Так «EN основной» (интервью №009, В8) исполняется для всего мира и одновременно не
 * подсовывает чужой язык русскоязычному человеку — а таких сегодня все 331.
 *
 * ⚠️ Цена, названная владельцу до ответа: поведение зависит от настроек, которых мы не видим.
 * В стражах язык фиксируется явно, а не берётся с машины, где идёт прогон.
 */
export function langFromBrowser(): Lang {
  if (typeof navigator === 'undefined') return 'ru';
  const asked = [navigator.language, ...(navigator.languages ?? [])];
  return asked.some((l) => typeof l === 'string' && l.toLowerCase().startsWith('ru')) ? 'ru' : 'en';
}

/** Достаёт нужную половину двуязычного поля каталога, с запасным вариантом. */
export function pick(field: { ru: string; en: string } | undefined, lang: Lang): string {
  if (!field) return '';
  // Запасной вариант ОБЯЗАТЕЛЕН: в каталоге есть записи, где заполнен только один язык.
  // Пустая страница хуже страницы на «не том» языке — она вообще ни о чём.
  return (lang === 'en' ? field.en || field.ru : field.ru || field.en) ?? '';
}
