/**
 * АДРЕС ПУБЛИЧНОЙ СТРАНИЦЫ ИЗМЕРЕНИЯ — фаза 5 эпика `ideas/30` (`plans/36`, шаг 1).
 *
 * Идентификаторы измерений в каталоге — случайные строки (`00S8ckKACl6WhEdc9n3V`), и адрес
 * `/dimension/00S8ckKACl6WhEdc9n3V` бесполезен и человеку, и поиску. Google прямо просит
 * «use readable words rather than long ID numbers in your URLs» (developers.google.com →
 * URL structure) и приводит длинный идентификатор примером «не рекомендуется».
 *
 * Схема: **читаемые слова + хвост идентификатора** (`battlefield-3-ucvge98o`). Хвост решает две
 * беды разом, которых голый слаг из названия не решает:
 *   · одноимённые произведения разных лет не сталкиваются;
 *   · правка названия в админ-панели (`plans/30`) не осиротит уже проиндексированный адрес молча.
 * Так устроены адреса Stack Overflow и Medium.
 *
 * 🔴 ФУНКЦИЯ ОБЯЗАНА БЫТЬ ДЕТЕРМИНИРОВАННОЙ: один и тот же документ даёт один и тот же адрес
 * всегда и на любой машине. Иначе адреса «поедут» между сборками — тот же класс беды, что
 * мигающие адреса, которых мы избежали в интервью №021. Инвариант накрыт `dim-slug.test.ts`.
 *
 * Живёт в `src/lib/`, а не в инструменте, ровно поэтому: тестируемое место. Инструмент
 * `tools/fetch-dims-slice.mjs` импортирует эту функцию, а не держит свою копию.
 */

/**
 * Транслитерация кириллицы. Таблица — практический стандарт рунета (BGN/PCGN в мягкой форме,
 * та же, что у Яндекса в ЧПУ): читаемость важнее обратимости, адрес человек читает, а не парсит.
 * Твёрдый и мягкий знаки исчезают — в латинице им нет читаемого соответствия.
 */
const RU: Readonly<Record<string, string>> = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ё: 'e', ж: 'zh', з: 'z', и: 'i', й: 'y',
  к: 'k', л: 'l', м: 'm', н: 'n', о: 'o', п: 'p', р: 'r', с: 's', т: 't', у: 'u', ф: 'f',
  х: 'h', ц: 'ts', ч: 'ch', ш: 'sh', щ: 'sch', ъ: '', ы: 'y', ь: '', э: 'e', ю: 'yu', я: 'ya',
};

/** Длина хвоста идентификатора. 8 знаков из алфавита Firestore — этого хватает с запасом. */
export const TAIL_LENGTH = 8;

/** Предел читаемой части адреса. Длинные названия обрезаются, хвост остаётся всегда. */
const WORDS_LIMIT = 60;

/**
 * Слаг адреса измерения: `«Battlefield 3» + ucvGE98o…` → `battlefield-3-ucvge98o`.
 *
 * @param title  название измерения (английское, если есть, иначе русское — так зовёт инструмент)
 * @param id     идентификатор документа `dims/{dimId}`; его хвост делает адрес уникальным
 */
export function slugify(title: string | null | undefined, id: string): string {
  const words = String(title ?? '')
    .toLowerCase()
    .split('')
    .map((ch) => RU[ch] ?? ch)
    .join('')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, WORDS_LIMIT)
    // Обрезка по длине могла оставить дефис на конце — тогда адрес получит двойной разделитель.
    .replace(/-+$/g, '');
  const tail = String(id).slice(0, TAIL_LENGTH).toLowerCase();
  return words ? `${words}-${tail}` : tail;
}
