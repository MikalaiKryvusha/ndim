/**
 * НАБОР ДВИЖКА СЕМЕЙСТВА ТЕСТ — фаза 5 эпика 40 (`plans/42`, шаг 3, такт Б).
 *
 * Набор строится НА СБОРКЕ из каталога (`dims-source.ts`), а не читается из Firestore в
 * рантайме: человек из поиска не платит ни одним запросом к базе, пока не поставил первую
 * оценку (канон владельца «экономить запросы» + Lighthouse публичных страниц). Обёртки делят
 * ОДИН набор — прямое следствие решения «один движок, жанры — обёртки» (интервью №026, В2 = Г);
 * различается только ДЛИНА (`TEST_TARGET`), и её числа обязаны совпадать с обещанием текстов
 * страниц («12 вещей · ~3 минуты», «7 вещей» — `test-copy.ts`).
 *
 * Почему по популярности (`rates` ↓): у самых оценённых объектов наибольшая вероятность, что
 *   · человек их знает (меньше «не знаю эту вещь»),
 *   · у пары будет пересечение — общий результат такта В судится ТОЛЬКО по совпавшим объектам.
 *
 * Порядок ДЕТЕРМИНИРОВАН (rates ↓, id ↑): пререндер и гидратация обязаны показать одну и ту же
 * первую карточку, а оба человека пары — одну и ту же очередь. Случайность здесь была бы
 * дефектом, а не фичей.
 */

// ⚠️ Модуль ЧИСТЫЙ — `dims-source.ts` сюда не импортируется сознательно: тот живёт на
// `import.meta.glob` (примитив Vite), и его импорт закрыл бы этим тестам дорогу под голым
// `node --test`. Привязка к каталогу (`DIMS`) — в загрузчике страницы, где Vite и так есть.
import type { DimPage } from './dims-source.ts';
import type { TestSlug } from './test-copy.ts';
import type { Lang } from './langs.ts';
import { kindKeyOf, kindLabel, normalizeRaw } from './dim-kind.ts';

/** Длина набора каждой обёртки — числа уже обещаны текстами страниц (`test-copy.ts`). */
export const TEST_TARGET: Record<TestSlug, number> = {
  compatibility: 12,
  personality: 12,
  love: 7,
};

/**
 * Запас очереди сверх длины набора — на «не знаю эту вещь — дальше».
 * Пропуски не пишутся никуда: запас живёт только в длине очереди.
 */
export const QUEUE_RESERVE = 24;

/** Одна карточка очереди: всё, что нужно движку, и ничего лишнего в HTML пререндера. */
export interface TestSetEntry {
  readonly id: string;
  readonly kind: { ru: string; en: string };
  readonly name: { ru: string; en: string };
  /** Год издания; «-» каталога означает «неизвестен» — тогда пусто (правило `ideas/26` п.2). */
  readonly year: string;
  /** Сколько людей оценили — для факта «оценили ещё N» (показ только при ≥ 3, №021 В1). */
  readonly rates: number;
}

/**
 * Порог факта «оценили ещё N» на карточке теста.
 *
 * ⚠️ НЕ `RATER_COUNT_FROM` из `dims-rating.ts` — сознательно: там правило показа ЗВЁЗД
 * каталога (владелец открыл при любом N, 2026-08-03), здесь — агрегат-факт публичной
 * поверхности, а «ни одна публичная страница не показывает агрегат меньше чем из N оценок» —
 * инвариант эпика (№021 В1; `plans/42` такт Б называет порог 3 явно).
 */
export const RATED_FACT_FROM = 3;

/**
 * Строит очередь движка: популярнейшие объекты каталога, детерминированно.
 *
 * Фильтр: у объекта есть имя на ОБОИХ языках и вид — карточка без имени или вида была бы
 * пустым вопросом. Сортировка: rates ↓, при равенстве id ↑ (стабильно между сборками).
 */
export function buildTestQueue(dims: readonly DimPage[], length: number): TestSetEntry[] {
  return dims
    .filter((d) => d.title.ru.trim() !== '' && d.title.en.trim() !== '' && d.type.ru.trim() !== '')
    .sort((a, b) => (b.rates - a.rates) || (a.id < b.id ? -1 : a.id > b.id ? 1 : 0))
    .slice(0, length)
    .map((d) => ({
      id: d.id,
      kind: d.type,
      name: d.title,
      year: d.year === '-' ? '' : d.year,
      rates: d.rates,
    }));
}

/** Длина очереди обёртки: набор + запас под пропуски. Каталог подставляет загрузчик страницы. */
export function queueLengthFor(slug: TestSlug): number {
  return TEST_TARGET[slug] + QUEUE_RESERVE;
}

/**
 * Подпись вида для ЛИЦА продукта — каноническая, а не сырое значение каталога.
 *
 * В поле `type` живёт грязь, замеренная шагом 0 `plans/48`: регистр вразнобой («фильм» и
 * «Фильм»), невидимые `U+200B`, год вместо вида, язык не в своём поле. На карточке вопроса это
 * незаметно — там подпись рисуется КАПИТЕЛЬЮ стилем. В строке панели она пойдёт как обычный
 * текст, и «· фильм, 2001» рядом с «· Роман, 1997» читалось бы как небрежность продукта.
 *
 * Неизвестному словарю виду (25 записей из 5111 — «Повесть», «Мультфильм», «Телешоу») подпись
 * всё равно нужна: возвращаем очищенное значение с большой буквы. Выдумывать ему вид нельзя —
 * это была бы правка данных под видом показа (граница `dim-kind.ts`).
 */
export function kindLabelFor(type: { ru: string; en: string }, lang: Lang): string {
  const key = kindKeyOf(type);
  if (key !== null) return kindLabel(key, lang);
  const raw = normalizeRaw(type[lang]) || normalizeRaw(lang === 'ru' ? type.en : type.ru);
  if (raw === '' || /^\d{4}$/.test(raw)) return '';
  return raw.charAt(0).toUpperCase() + raw.slice(1);
}

/**
 * ПОЛНАЯ ПОДПИСЬ ОБЪЕКТА В СТРОКЕ: «имя · Вид, год» (`bugs/126`, интервью №032 В1 = В).
 *
 * ═══ ЗАЧЕМ ═══
 * В каталоге **148 имён носят по два-три разных измерения** (роман и фильм, оригинал и
 * ремейк) — 307 записей. Набор теста строится по популярности, а самые оценённые объекты
 * каталога как раз одноимённые («Гарри Поттер», «Мастер и Маргарита»), поэтому дубль попадает
 * в ПЕРВЫЕ карточки. Без различителя человек видел две одинаковые строки с разными оценками и
 * не мог понять, где какая.
 *
 * ═══ ПОЧЕМУ ВСЕГДА, А НЕ ТОЛЬКО ПРИ СТОЛКНОВЕНИИ ═══
 * Слово владельца (№032, В1 = В): вид и год у КАЖДОЙ строки. Подпись «по столкновению» была бы
 * дешевле, но давала бы строку, меняющую вид от того, что человек оценил ДО неё, — и в
 * результате пары, который читает второй, столкновения вообще могло не быть у него.
 *
 * Год необязателен: у практик («Секс», «Катание на лыжах») его нет, и пустых скобок не будет.
 * Вид тоже может отсутствовать — тогда остаётся голое имя, а не висящий разделитель.
 */
export function rowLabel(
  entry: { name: string; kind: string; year: string },
): string {
  const tail = [entry.kind, entry.year].filter((part) => part.trim() !== '').join(', ');
  return tail === '' ? entry.name : `${entry.name} · ${tail}`;
}
