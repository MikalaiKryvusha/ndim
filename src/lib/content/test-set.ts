/**
 * КЛЮЧ СЕРИИ по русскому названию — «одна вещь от серии» (№098 В2, пример владельца: «Гарри Поттер»,
 * «Пираты Карибского моря»). Голова названия до «:», «,», « и », « — », «(» и без номера части в
 * конце: «Гарри Поттер и Тайная комната» → «гарри поттер» · «Пираты Карибского моря: На краю света»
 * → «пираты карибского моря» · «Брат 2» → «брат» · «Терминатор 2: Судный день» → «терминатор».
 * Роман и фильм одной истории носят одно название и получают один ключ.
 * ⚠️ Граница: серии с РАЗНЫМИ головами названий («Операция „Ы“…» и «Кавказская пленница…» — обе
 * про Шурика) ключ не видит. В пуле таких пар нет — это проверено чтением списка, а не ключом.
 */
export function seriesKey(title: string): string {
  const head = title.toLowerCase().replaceAll('ё', 'е').split(/:|,| и | — |\(/u)[0] ?? '';
  return head.replace(/\s+\d+\s*$/u, '').trim();
}

/** Запись каталога годна в карточку теста: имя на ОБОИХ языках и вид. */
const cardable = (d: DimPage): boolean =>
  d.title.ru.trim() !== '' && d.title.en.trim() !== '' && d.type.ru.trim() !== '';

/**
 * ПРАВИЛО ПУЛА — чистая функция над каталогом: самые оценённые (голоса ↓, NDSR ↓, id ↑), с NDSR не
 * ниже порога, без сенситивных, без вещей «только для своих» (`isLocalOnly`, №100 В2), по одной вещи
 * от серии, `size` штук. Ей сверяется `TEST_POOL`.
 */
export function derivePool(
  dims: readonly DimPage[],
  sensitiveIds: readonly string[],
  size: number = POOL_SIZE,
  minRating: number = POOL_MIN_RATING,
  /** Только эти вещи идут в пул (легенды, №101 В1); `null` — без этого признака (синтетика юнитов). */
  legends: readonly string[] | null = LEGEND_IDS,
): string[] {
  const seen = new Set<string>();
  const pool: string[] = [];
  const ranked = dims
    .filter(cardable)
    .sort((a, b) => (b.rates - a.rates) || (b.rating - a.rating) || (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  for (const d of ranked) {
    if (pool.length >= size) break;
    if (legends !== null && !legends.includes(d.id)) continue;
    if (d.rating < minRating || isSensitive(d, sensitiveIds) || isLocalOnly(d)) continue;
    const key = seriesKey(d.title.ru);
    if (seen.has(key)) continue;
    seen.add(key);
    pool.push(d.id);
  }
  return pool;
}

