/**
 * СТРАЖ КЛАССА «МОЛЧАЛИВЫЙ ПРОПУСК ЖИВОГО КАТАЛОГА» (`bugs/163`).
 *
 * 🔴 Зачем он есть. Полный каталог (`src/lib/content/dims-build.json`, 17 МБ) лежит ВНЕ git —
 * это решение верное и не пересматривается. Но у тестов, которым он нужен, есть два способа
 * исчезнуть, и оба выглядят как успех:
 *
 * | Форма | Что печатает без артефакта | Чем опасна |
 * |---|---|---|
 * | `if (full) { test(…) }` | ничего: прогон просто короче | `node --test` не сообщает о том, чего ему не объявили |
 * | `test(…, () => { if (!full) return; … })` | **`pass`** | активно врёт: проверка объявлена, засчитана и не выполнена |
 *
 * Цена уплачена в командном режиме: у ролей команды пять рабочих копий, артефакт есть не у всех,
 * и числа прогонов расходились МОЛЧА — 325 против 329 за один вечер. Объяснять расхождение
 * приходилось человеку каждый раз, вместо того чтобы его объявлял прогон.
 *
 * 🔑 Почему СТРАЖ, а не запись в журнале. Порядок лечения в каноне жёсткий (`AGENT_GUIDE.md` →
 * «Журнал опыта»): убрать ловушку → страж, который краснеет сам → и лишь потом урок. Правило
 * «объявляй пропуск вслух» невозможно убрать конфигом: следующий тест живого каталога напишет
 * другая сессия в другой рабочей копии, где артефакт ЕСТЬ, — и она не увидит своей ошибки
 * ни разу. Увидит этот страж.
 *
 * ⚠️ Он судит ИСХОДНИК, а не поведение, и это осознанно: поведение «теста нет» ненаблюдаемо по
 * построению — наблюдать нечего. Разрешённая форма ровно одна: `{ skip: <причина> }`, родная для
 * `node --test`, — тест объявлен всегда, а разница видна строкой `skipped` и причиной.
 *
 * 🟡 Что НЕ считается нарушением: честное вырождение с ПЕЧАТЬЮ причины (`dim-kind.test.ts`
 * говорит вслух, что проверил запасной срез, и проверяет его по-настоящему). Молчание — вот
 * признак дефекта, а не сама ветка «артефакта нет».
 *
 * [TESTED: 2026-08-22 · мутация — вернул `if (full) {` в catalog-hub.test.ts, страж покраснел
 * адресно и назвал файл; вернул `if (!full) return` — покраснел вторым правилом]
 */
import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import assert from 'node:assert/strict';
import { test } from 'node:test';

const КОРЕНЬ = 'src';
const АРТЕФАКТ = 'dims-build.json';

/** Все файлы тестов проекта — обходом дерева, а не списком: список устарел бы в день нового файла. */
function файлыТестов(каталог: string): string[] {
  return readdirSync(каталог, { withFileTypes: true }).flatMap((вход) => {
    const путь = join(каталог, вход.name);
    if (вход.isDirectory()) return файлыТестов(путь);
    return вход.name.endsWith('.test.ts') ? [путь] : [];
  });
}

/**
 * 🔴 СТРАЖ ОБЯЗАН СУДИТЬ КОД, А НЕ ПРОЗУ — иначе он краснеет на объяснении самого себя.
 *
 * Первая редакция этого файла судила сырой текст и немедленно дала ТРИ ложных срабатывания:
 * назвала нарушителем разбор дефекта в комментарии `catalog-hub.test.ts`, файл, который артефакт
 * лишь упоминает (`dims-rating.test.ts`), и СЕБЯ САМУ — таблицу форм в собственной шапке.
 * Класс известен и оплачен дважды: `EXP-0163` (страж судит прозу) и `EXP-0081` (фильтр находит
 * сам себя). Поэтому комментарии снимаются ДО разбора.
 *
 * ⚠️ Честная граница снятия: `//` внутри строкового литерала (адрес `https://…`) обрежет хвост
 * строки. Для нашей задачи это безопасно — нарушение всегда занимает строку целиком, — но если
 * страж однажды начнёт судить что-то внутри строк, снятие придётся делать разбором, а не
 * заменой.
 */
const безКомментариев = (текст: string): string =>
  текст.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');

/**
 * ЗАВИСИМЫЙ ФАЙЛ — ТОТ, ЧТО НАЗЫВАЕТ АРТЕФАКТ В КОДЕ, а не в комментарии. Снятие комментариев
 * уже отделило упоминание от зависимости: `dims-rating.test.ts` ссылается на замер по каталогу
 * прозой и в код его не берёт, поэтому в список не попадает сам собой.
 *
 * ⛔ Форму загрузки НЕ сужаем. Первая редакция искала `new URL('./dims-build.json'` — и
 * промахнулась мимо `dim-kind.test.ts`, который берёт тот же файл обычной строкой пути. Это
 * ровно та ошибка, за которую канон ругает короткие подстроки в стражах, только наизнанку:
 * узкий образец оставляет настоящего зависимого без охраны.
 */
const самСтраж = join('src', 'lib', 'content', 'dims-build-skip.test.ts');
const всеФайлы = файлыТестов(КОРЕНЬ);
const код = new Map(всеФайлы.map((п) => [п, безКомментариев(readFileSync(п, 'utf8'))]));
const зависимые = всеФайлы.filter(
  // Сам страж исключён поимённо: он называет артефакт в коде по долгу службы, а пропускать ему
  // нечего. Исключение узкое и объявленное — молчаливого «кроме себя» здесь нет.
  (п) => п !== самСтраж && (код.get(п) ?? '').includes(АРТЕФАКТ),
);

/*
 * 🔑 КОНТРОЛЬ ПРИБОРА — ПЕРВЫМ (`EXP-0082`, `EXP-0070`). «Нарушений 0» и «наблюдений 0»
 * печатаются одинаково: страж, которому нечего судить, зелен бессодержательно. Поэтому сначала
 * доказывается, что судить БЫЛО ЧТО.
 */
test('контроль прибора: файлы тестов найдены и среди них есть зависимые от живого каталога', () => {
  assert.ok(всеФайлы.length >= 15, `файлов тестов найдено ${всеФайлы.length} — обход дерева сломан`);
  assert.ok(
    зависимые.length >= 3,
    `файлов, зависящих от ${АРТЕФАКТ}, найдено ${зависимые.length} — их было три, страж судит пустоту`,
  );
  console.log(
    `[страж bugs/163] осмотрено файлов тестов: ${всеФайлы.length}, из них зависят от каталога: ${зависимые.length}`,
  );
});

test('🔴 тест живого каталога не прячется в `if (full)` — иначе он просто не объявится', () => {
  const нарушители = зависимые.filter((п) =>
    /^\s*if \(full\) \{\s*$/m.test(код.get(п) ?? ''),
  );
  assert.deepEqual(
    нарушители,
    [],
    'обёртка `if (full) { test(…) }` не объявляет тест вовсе — объяви его всегда и дай `{ skip: <причина> }`',
  );
});

test('🔴 тест живого каталога не выходит вхолостую — иначе он печатается как ПРОЙДЕННЫЙ', () => {
  const нарушители = зависимые.filter((п) => /if \(!full\)\s+return/.test(код.get(п) ?? ''));
  assert.deepEqual(
    нарушители,
    [],
    '`if (!full) return` засчитывает непроверенное как проверенное — замени на `{ skip: <причина> }`',
  );
});

test('причина пропуска НАЗЫВАЕТ артефакт и способ его получить — иначе она бесполезна', () => {
  for (const путь of зависимые) {
    const текст = код.get(путь) ?? '';
    if (!текст.includes('skip:')) continue; // файл может честно вырождаться с печатью (dim-kind)
    // Порядок объявления свободен: причина живёт константой ВЫШЕ тестов, поэтому ищем обе части
    // по всему коду файла, а не в окне после `skip:` — окно ловило бы только один способ писать.
    assert.ok(
      текст.includes(АРТЕФАКТ) && текст.includes('npm run build'),
      `${путь}: причина пропуска обязана назвать ${АРТЕФАКТ} и «npm run build» — человек должен знать, чем починить`,
    );
  }
});
