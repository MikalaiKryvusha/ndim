/**
 * ЧТО ПОКАЗЫВАЕТ публичная страница измерения — тип общий для загрузчика и разметки.
 *
 * 🔴 ПОЧЕМУ ОТДЕЛЬНЫМ ФАЙЛОМ, А НЕ В `+page.ts`. Загрузчик страницы обязан быть СЕРВЕРНЫМ
 * (`+page.server.ts`): универсальный `load` исполняется и в браузере, поэтому Vite вшивает всё,
 * что он импортирует, в клиентский бандл — и каталог на 17 МБ уехал бы к каждому посетителю
 * (замерено: чанк узла вырос до **16,86 МБ**, `EXP-0136`). А разметке нужен ТИП, и импортировать
 * его из серверного модуля она не может. Отсюда третий файл, где живёт только контракт.
 *
 * 🔴 ЗДЕСЬ ТОЛЬКО ТО, ЧТО СТРАНИЦА РИСУЕТ, — и это не педантизм, а замеренный вес.
 *
 * Первая редакция возвращала ещё и весь объект каталога `dim` целиком. В нём оба языка:
 * русское название и английское, русское описание И английское, вид, автор, теги — и всё это
 * РЯДОМ с уже разобранными из него полями. Описание лежало в ответе трижды: `dim.description.ru`,
 * `dim.description.en` и выбранное `description`.
 *
 * Цена, замеренная по бою: `__data.json` весил **4 871 байт** на страницу × 10 222 страницы =
 * **41 МБ мёртвого веса** в каждом релизе. Мёртвого потому, что страница объявлена `csr = false`
 * и клиентских переходов на ней нет — эти файлы никто не запрашивает.
 *
 * ⚠️ Совсем убрать `__data.json` нельзя: встроенного выключателя у SvelteKit нет (он пишет их
 * всегда, когда есть серверный `load`), а удаление своим шагом сборки сломало бы будущий
 * клиентский переход СЮДА с любого экрана приложения — клиентский маршрутизатор о `csr = false`
 * целевой страницы не знает и всё равно пойдёт за данными. Поэтому лечим ВЕС, а не факт.
 */
import type { RatingView } from './dims-rating.ts';
import type { Lang } from './langs.ts';

export interface DimView extends RatingView {
  readonly lang: Lang;
  /** Нужен для ссылки на этот же объект на другом языке. */
  readonly slug: string;
  readonly title: string;
  readonly description: string;
  /** Вид произведения. Пусто — элемент не показывается. */
  readonly kind: string;
  /** Автор. Пусто — элемент не показывается. */
  readonly author: string;
  /** Оригинальное название, если оно отличается от заголовка. Иначе пусто. */
  /**
   * Название на ДРУГОМ языке, а не «в оригинале» (`bugs/116`).
   *
   * 🔴 Поле называлось `original`, и имя лгало вслед за подписью: на английской странице
   * «Матрицы» стояло «Original title: Матрица». Языка оригинала мы не знаем ни у одного из
   * 5111 объектов и следить за ним не будем (слово владельца). Имя поля исправлено ВМЕСТЕ с
   * подписью — иначе следующая сессия прочитала бы `original` и вернула бы прежний текст.
   */
  readonly otherTitle: string;
  /** Год; `-` в каталоге означает «неизвестен» — тогда пусто и элемент не показывается. */
  readonly year: string;
  readonly tags: readonly string[];
  /** Средняя оценка, 0…10. Показывать её или нет — решает `showStars`. */
  readonly rating: number;
  /** Сколько человек оценили. Показывать это число или нет — решает `showRaterCount`. */
  readonly rates: number;
  /** Строка для выдачи: обрезана по слову, без хвоста-огрызка. */
  readonly meta: string;
  readonly canonical: string;
  /** Двусторонний `hreflang`: у Google односторонняя разметка игнорируется ЦЕЛИКОМ. */
  readonly alternates: readonly { hreflang: string; href: string }[];
  /**
   * Структурированная разметка объекта — УЖЕ СЕРИАЛИЗОВАННАЯ строка (`plans/48` шаг 5).
   *
   * Строкой, а не объектом, по той же причине, по какой здесь нет самого `dim`: страница всё
   * равно сериализует её в `<script type="application/ld+json">`, а объект в ответе загрузчика
   * стоил бы ещё одной копии названия, описания и автора в каждом `__data.json` (см. врезку о
   * 41 МБ выше).
   */
  readonly jsonLd: string;
}
