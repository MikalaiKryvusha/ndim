/** Поле каталога, заполненное прочерком, означает «неизвестно», а не «так и называется». */
const known = (v: string) => (v && v !== '-' ? v : '');

/** Объект получил хотя бы один голос — по тому же порогу, что и правило показа звёзд. */
const isRated = (d: CatalogItem) => (Number.isFinite(d.rates) ? Math.floor(d.rates) : 0) >= 1;

/**
 * ОПОРА КАТАЛОГА для взвешивания оценки — два числа, оба ПОСЧИТАННЫЕ, ни одного придуманного.
 *
 * `c` — средняя оценка по объектам, у которых есть хотя бы один голос (замер 2026-08-14:
 * **8,2405** по 1877 объектам).
 * `m` — вес опоры: сколько голосов должно быть у объекта, чтобы его собственная средняя начала
 * перевешивать общекаталожную. Берётся как **90-й процентиль числа голосов** среди оценённых
 * (сегодня — **4**): девять объектов из десяти имеют четыре голоса или меньше, и порог означает
 * «пока ты не в верхней десятой доле по числу голосов, твоя единоличная десятка не считается
 * приговором».
 *
 * 🔑 Почему процентиль, а не константа: Пространство очень тихое (самый оценённый объект каталога
 * набрал 14 голосов), и зашитая четвёрка через год стала бы неправдой молча. Процентиль растёт
 * вместе с данными сам. Число печатается в лог сборки и закреплено тестом — молча оно не поедет.
 */
export interface CatalogPrior {
  /** Вес опоры в голосах. */
  readonly m: number;
  /** Средняя оценка по оценённым объектам каталога. */
  readonly c: number;
}

/**
 * ЦЕНА ПОЛНОГО НАСЫЩЕНИЯ В БАЛЛАХ — **1,0** (интервью №036, В2 = B).
 *
 * Столько максимум может добавить к позиции само по себе КОЛИЧЕСТВО голосов, независимо от того,
 * какая у объекта оценка. Слова владельца, которыми выбрано число: «*оценка важнее… Рейтинг
 * важнее*».
 *
 * 🔴 Я предлагал считать эту величину из данных — СКО оценок каталога, 1,6161 — и владелец
 * отклонил: при 1,62 количество голосов способно перекрыть больше полутора баллов разницы в
 * оценке, то есть популярность начинает спорить с качеством. При 1,0 голоса решают исход только
 * между близкими по оценке объектами, а заметно лучшая оценка остаётся сильнее. Число теперь
 * ЕГО, а не выводимое: менять его — только его словом.
 */
export const VOTE_BONUS = 1;

/**
 * ОПОРА ПОЛНОГО ВЕСА — сколько голосов даёт вес ровно 1 (интервью №036, В2).
 *
 * 🔴 ВЕРНУЛСЯ ЛОГАРИФМ, И ЭТО НЕ ОТКАТ, А ВЫВОД ИЗ ЗАМЕРА. Путь решения за один день, записан
 * целиком, чтобы следующая сессия не «починила» его обратно:
 *   1. чистый логарифм с опорой 200 — из фразы владельца «*между 200 и 205 разница уже почти
 *      неразличима*»;
 *   2. в интервью он ответил «*Логарифм должен быстро насыщаться. После 20 оценок людей — это уже
 *      довольно весомая оценка*» → опора 20;
 *   3. он попросил НАРИСОВАТЬ график («*я понимаю математику не цифрами, а когда вижу характер
 *      графика визуально*»), посмотрел и сказал: «*характер кривизны как у зелёной, но насыщение
 *      переместить на 200 голосов*»;
 *   4. затем: «*сильнее перегиб поднять, прижать на точке 20 ближе вверх к 1*» и «*прижми выше,
 *      но не целься в 200, а насыщение — где получится*» → я перевёл кривую на ЭКСПОНЕНТУ
 *      (`1 − exp(−v/τ)`), у которой крутизна отделена от точки плато;
 *   5. посмотрев на неё, владелец забраковал саму СЕМЬЮ: «*почти нет разницы на высоких числах,
 *      слишком быстро оно насытилось*».
 *
 * 🔑 Он прав по существу, и вот почему: у экспоненты плато ЖЁСТКОЕ — за ним объекты с 50 и с 500
 * голосами становятся неразличимы. У логарифма плато не наступает никогда: каждое УДВОЕНИЕ числа
 * голосов добавляет одинаковую прибавку, поэтому 100 и 200 различаются ровно так же ощутимо, как
 * 5 и 10. Это и есть свойство, которого владелец просил.
 *
 * ⚠️ И развилка, которую снять нельзя никакой формулой — это арифметика, а не выбор семьи:
 * **если на 20 голосах вес уже 0,99, то на всё, что выше, остаётся 0,01.** «Прижать к единице на
 * 20» и «сохранить разницу на 200» несовместимы. Опора и есть та ручка, которой владелец решает,
 * куда отдать запас; при `1000` вес на 20 равен 0,44, зато 50 → 0,57, 100 → 0,67, 200 → 0,77.
 */
export const VOTE_KNEE = 1000;

/**
 * ВЕС ЧИСЛА ГОЛОСОВ — 0…1: круто растёт от нуля, замедляется, но разница НЕ исчезает и на
 * больших числах.
 *
 * Указания владельца, которые формула выполняет одновременно:
 *   · «*вес убывает логарифмически по мере роста количество голосов*» — прибавка на каждое
 *     удвоение одинакова;
 *   · «*малое количество голосов — низкий вес*» — один голос даёт 0,10;
 *   · «*большое количество голосов — высокий вес на позицию*»;
 *   · «*между 5 и 10 голосов — большая разница в весе*» — 0,26 против 0,35, шаг 0,09;
 *   · «*между 200 и 205 голосов разница в весе голосов уже почти неразличима*» — шаг 0,004;
 *   · «*почти нет разницы на высоких числах*» ЛЕЧИТСЯ: 50 → 0,57, 100 → 0,67, 200 → 0,77.
 *
 * Верхний зажим оставлен на случай каталога, переросшего опору: вес — коэффициент, и выше единицы
 * он не поднимается никогда.
 */
export const voteWeight = (rates: number): number => {
  const v = Number.isFinite(rates) ? Math.max(0, Math.floor(rates)) : 0;
  return v <= 0 ? 0 : Math.min(1, Math.log(1 + v) / Math.log(1 + VOTE_KNEE));
};

/** 90-й процентиль по возрастающему ряду; ряд обязан быть непустым. */
const p90 = (sorted: readonly number[]) => sorted[Math.floor((sorted.length - 1) * 0.9)];

export function catalogPrior(items: readonly CatalogItem[]): CatalogPrior {
  const rated = items.filter(isRated);
  if (!rated.length) return { m: 1, c: 0 };
  const votes = rated.map((d) => Math.floor(d.rates)).sort((a, b) => a - b);
  return {
    m: Math.max(1, p90(votes)),
    c: rated.reduce((s, d) => s + d.rating, 0) / rated.length,
  };
}

/**
 * ВЗВЕШЕННАЯ ОЦЕНКА — величина, по которой хаб СОРТИРУЕТ. Показывается по-прежнему настоящая
 * средняя: `weighted` наружу не выходит ни числом, ни подписью.
 *
 * Складывается из ДВУХ слагаемых, и у каждого своя работа:
 *
 *   1. **притяжение к средней каталога** — `(v·R + m·C) / (v + m)`. Объект с малым числом
 *      голосов притянут к общей средней, с большим — стоит на своей. Было и остаётся.
 *   2. 🆕 **ВЕС ЧИСЛА ГОЛОСОВ** — `VOTE_BONUS · voteWeight(v)` (интервью №036, В2 = B).
 *
 * 🔴 ПОЧЕМУ ОДНОГО ПРИТЯЖЕНИЯ ОКАЗАЛОСЬ МАЛО — замер, из которого выросло решение владельца.
 * Притяжение умеет только СНИЖАТЬ доверие к одинокой оценке, но не умеет НАГРАЖДАТЬ за массовость.
 * Боевые числа 2026-08-16: «Дом Дракона» с ОДНИМ голосом 10,0 давал 8,592, а «Гарри Поттер» —
 * 8,4 при **14 голосах, максимуме всего каталога** — только 8,365, и стоял **534-м из 981**.
 * Выше него было 533 фильма, из них **245 (46 %) держались на одном голосе**. Показать такое
 * место на карточке значило бы подорвать NDSR числом, посчитанным нами же.
 * После правки: «Гарри Поттер» — **92-е**, одинокая десятка его больше не обгоняет.
 *
 * ⚠️ Цена решения, названная прямо: величина перестала лежать в 0…10 — при полном насыщении
 * бонус добавляет до `sd` баллов сверх. Наружу она по-прежнему НЕ выходит (на карточке и в хабе
 * стоит настоящая средняя), поэтому шкала продукта не задета; но всякий, кто соберётся ПОКАЗАТЬ
 * `weighted`, обязан помнить, что это уже не оценка по шкале, а рейтинговый балл.
 */
export const weighted = (d: CatalogItem, prior: CatalogPrior): number => {
  const v = Math.max(0, Math.floor(d.rates));
  const pulled = (v * d.rating + prior.m * prior.c) / (v + prior.m);
  return pulled + VOTE_BONUS * voteWeight(v);
};

/**
 * ПОРЯДОК КАРТОЧЕК В ХАБЕ — **интервью №030, В2 = Д** (ответ владельца 2026-08-14, страницей
 * вычитки): «по оценке, но С УЧЁТОМ ЧИСЛА ГОЛОСОВ».
 *
 *   1. оценённые идут ПЕРЕД неоценёнными;
 *   2. внутри оценённых — по убыванию ВЗВЕШЕННОЙ оценки, затем по убыванию числа голосов;
 *   3. всё остальное и все равенства — по слагу.
 *
 * 🔴 **Взвешенная участвует ТОЛЬКО в сортировке.** На карточке стоит настоящая средняя и
 * настоящее число голосов — это условие, на котором владелец выбрал Д. Показать взвешенную
 * величину под именем `NDim Space Rating` было бы подменой бренда, а не улучшением порядка.
 *
 * ⚠️ **Честная граница, замеренная ПОСЛЕ ответа и названная владельцу:** взвешивание опускает
 * «десятку от четверых» ниже «9,6 от восьмерых», но НЕ переворачивает пару «10,0 × 7» против
 * «9,3 × 11» — семь единодушных десяток и правда сильнее одиннадцати голосов со средней 9,3 при
 * общей средней каталога 8,24. Пример, которым я иллюстрировал вариант Д в интервью, боевыми
 * числами не воспроизводится; поправка записана там же.
 *
 * 🔴 **ПОРЯДОК ОБЯЗАН БЫТЬ НЕЗАВИСИМ ОТ ЯЗЫКА, и поэтому равенства разводит СЛАГ, а не название.**
 * `/ru/catalog/movie/5` и `/en/catalog/movie/5` объявлены друг другу переводами через `hreflang`.
 * Сортировка по названию дала бы на этих двух адресах РАЗНЫЕ наборы объектов — то есть разметка
 * утверждала бы неправду на каждой странице каждого хаба. Слаг у объекта один на оба языка.
 *
 * 🔴 **Цена, названная в интервью и принятая сознательно:** оценён 981 фильм из 2774, значит
 * примерно с 17-й страницы пойдут сорок страниц «ещё без голосов»; и карточка переезжает между
 * страницами, когда объект получает новый голос (переезд случается на выкате, а не в бою:
 * сайт статический).
 */
export const makeComparator =
  (prior: CatalogPrior) =>
  (a: CatalogItem, b: CatalogItem): number => {
    const ra = isRated(a);
    const rb = isRated(b);
    if (ra !== rb) return ra ? -1 : 1;
    if (ra) {
      const wa = weighted(a, prior);
      const wb = weighted(b, prior);
      if (wb !== wa) return wb - wa;
      if (b.rates !== a.rates) return b.rates - a.rates;
    }
    return a.slug < b.slug ? -1 : a.slug > b.slug ? 1 : 0;
  };

/** Сколько страниц у списка из `n` объектов. Пустой список — всё равно одна страница. */
export const pageCount = (n: number): number => Math.max(1, Math.ceil(n / PER_PAGE));

/**
 * МЕСТО ОБЪЕКТА В СВОЁМ ВИДЕ — «12-е место среди 981 оценённого фильма» (`plans/56` шаг 2).
 *
 * Знаменатель — число ОЦЕНЁННЫХ, а не всех объектов вида, и это не деталь оформления.
 * Неоценённых в каталоге 63 %, и место среди них не существует: они разведены по слагу, то есть
 * по алфавиту адреса. «3106-е место среди фильмов» было бы числом из шума — выдуманным фактом
 * в чистом виде, а выдуманный факт хуже отсутствующего.
 */
export interface HubPlace {
  /** Место среди оценённых объектов вида, от 1. */
  readonly rank: number;
  /** Сколько оценённых объектов в этом виде всего. */
  readonly of: number;
}

/**
 * Места всех ОЦЕНЁННЫХ объектов уже отсортированного списка вида.
 *
 * 🔑 Место считается по отфильтрованному ряду, а НЕ по индексу в общем списке, хотя сегодня они
 * совпадают (`makeComparator` ставит оценённых первыми). Совпадение — свойство сортировки, и
 * опираться на него значило бы завести немую связь: правка порядка сдвинула бы номера на
 * карточках, не уронив ни одного теста. Фильтр верен при любом порядке.
 *
 * 🔴 Это половина пары «истина ↔ зеркало»: то же число человек видит номером строки на странице
 * хаба (`CatalogHub.svelte` → `firstRank + i`). Расхождение означает, что две публичные
 * поверхности говорят об одном объекте разное, — стережётся тестом ниже и стражем хабов.
 */
export function placesIn<T extends CatalogItem>(sortedList: readonly T[]): Map<string, HubPlace> {
  const rated = sortedList.filter(isRated);
  const places = new Map<string, HubPlace>();
  rated.forEach((d, i) => places.set(d.slug, { rank: i + 1, of: rated.length }));
  return places;
}

/**
 * Раскладка каталога по хабам: семь известных видов + хвост.
 *
 * Хвост — это НЕ мусор и не ошибка данных: 25 объектов шести видов, которым не хватило карточек
 * до порога хаба (TV Show 11 · Novella 5 · Animated Movie 3 · Internet Show 3 · Lecture 2 ·
 * Graphic Novel 1). Смысловое слияние («Повесть → Роман») запрещено — это правка данных под
 * видом чтения (`dim-kind.ts`). Поэтому хвост живёт СПИСКОМ на индексной странице каталога:
 * иначе 25 объектов × 2 языка остались бы недостижимыми от корня, а вся фаза существует ровно
 * ради того, чтобы недостижимых не было ни одной.
 */
export function groupByKind<T extends CatalogItem>(
  items: readonly T[],
): { hubs: Map<KindKey, T[]>; tail: T[]; prior: CatalogPrior } {
  // 🔑 Опора считается по ВСЕМУ каталогу, а не по каждому хабу отдельно. Иначе «Книги» (оценено
  // 9 из 64) получили бы собственную среднюю по девяти объектам — опору из шума, и порядок в
  // маленьком хабе гулял бы от одного нового голоса.
  const prior = catalogPrior(items);
  const compare = makeComparator(prior);
  const hubs = new Map<KindKey, T[]>(KIND_KEYS.map((k) => [k, [] as T[]]));
  const tail: T[] = [];
  for (const item of items) {
    const key = kindKeyOf(item.type);
    if (key) hubs.get(key)!.push(item);
    else tail.push(item);
  }
  for (const list of hubs.values()) list.sort(compare);
  tail.sort(compare);
  return { hubs, tail, prior };
}

/** Сводки всех семи хабов в каноническом порядке `KIND_KEYS`. */
export function summarize<T extends CatalogItem>(hubs: Map<KindKey, T[]>): HubSummary[] {
  return KIND_KEYS.map((key) => {
    const list = hubs.get(key) ?? [];
    return { key, count: list.length, rated: list.filter(isRated).length, pages: pageCount(list.length) };
  });
}

/**
 * Срез одной страницы хаба. Номер страницы — от 1; за пределами списка возвращается пусто, и
 * решение «это 404» принимает загрузчик, а не этот модуль.
 */
export const slicePage = <T>(list: readonly T[], page: number): T[] =>
  list.slice((page - 1) * PER_PAGE, page * PER_PAGE);

/**
 * АДРЕСА ХАБОВ — одно место на проект: их считают и загрузчики, и разметка, и карта сайта, и
 * стражи. Три копии «склеить путь» разошлись бы молча, а расхождение здесь означает битую
 * ссылку на каждой странице каталога.
 *
 * 🔴 Первая страница живёт на `/{lang}/catalog/{kind}`, а НЕ на `…/1`. Два адреса с одним
 * содержанием — это дубль, который поисковик обязан склеивать сам; лучше его не создавать.
 */
export const catalogPath = (lang: Lang): string => `/${lang}/catalog`;

export const hubPath = (lang: Lang, kind: KindKey, page = 1): string =>
  page <= 1 ? `/${lang}/catalog/${kind}` : `/${lang}/catalog/${kind}/${page}`;

export const dimensionPath = (lang: Lang, slug: string): string => `/${lang}/dimension/${slug}`;

/** Объект каталога → карточка на нужном языке. */
export const toCard = (item: CatalogItem, lang: Lang): CatalogCard => ({
  slug: item.slug,
  title: pick(item.title, lang),
  year: known(item.year),
  author: known(pick(item.author, lang)),
  rating: item.rating,
  rates: item.rates,
});
