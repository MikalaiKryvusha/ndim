/**
 * ХАБ КАТАЛОГА — группировка, порядок и разбивка на страницы (`plans/48`, фаза 2 эпика 40, шаг 3).
 *
 * Форма страницы выбрана владельцем: **V3 «Рейтинг»** (интервью №030, В1 = В) — ранжированный
 * список, «топ по версии NDim Space»: номер места · название · год и автор · звёзды · оценка ·
 * «оценено N людьми».
 *
 * ── ЗАЧЕМ ХАБЫ ВООБЩЕ СУЩЕСТВУЮТ — одно число ────────────────────────────────────────────────
 * Все **10 222** страницы каталога сегодня недостижимы от корня сайта: пары «ru ↔ en» замкнуты
 * друг на друга, и от лендинга к ним не ведёт ни один путь. Робот знает адреса только из карты
 * сайта — и не приходит: Google взял 994, а 9 237 висят в «обнаружена, не проиндексирована»
 * (`researches/34` §14). Хаб — это путь к карточке и вес для неё.
 *
 * ── ПОЧЕМУ ЭТОТ ФАЙЛ ЧИСТЫЙ, А ДАННЫЕ ЖИВУТ В `catalog-source.ts` ─────────────────────────────
 * Здесь нет ни одного импорта каталога, и это не стиль, а условие проверяемости: `dims-source.ts`
 * держит `import.meta.glob`, который существует ТОЛЬКО внутри Vite, — модуль, зовущий его, под
 * `node --test` не исполняется в принципе. Разделение даёт правилу порядка юнит-тест с мутациями
 * (`catalog-hub.test.ts`), а не «проверим глазами на собранном сайте».
 *
 * Тип входа объявлен СТРУКТУРНО (`CatalogItem`), а не импортом `DimPage`: так этот модуль не
 * знает о существовании файла каталога вовсе.
 */

/*
 * Расширение `.ts` в импортах здесь ОБЯЗАТЕЛЬНО, и это не стиль. Модуль исполняется двумя
 * разными загрузчиками: Vite (сборка сайта) и голым Node внутри `node --test`. Второй ESM-имена
 * без расширения не достраивает — без `.ts` юнит-тест падает `ERR_MODULE_NOT_FOUND`, то есть
 * правило порядка осталось бы вообще без проверки.
 */
import { KIND_KEYS, kindKeyOf, type KindKey } from './dim-kind.ts';
import { pick, type Lang } from './langs.ts';

/**
 * Сколько карточек на странице хаба.
 *
 * 60 — из плана фазы (`plans/48` шаг 3). Число даёт: Movie 47 страниц · Video game 21 ·
 * TV Series 7 · Novel 4 · Practice 4 · Music Artist 4 · Book 2 = **89 страниц на язык**.
 * Меньше — страниц становится больше, и каждая тоньше; больше — страница тяжелеет, а
 * перечисление всех номеров (см. ниже) перестаёт помещаться на экран телефона.
 */
export const PER_PAGE = 60;

/**
 * Минимальный набор полей объекта каталога, нужный хабу.
 *
 * Структурный тип, а не импорт: `DimPage` подходит сюда по форме, и модуль остаётся
 * исполнимым без Vite. Лишние поля (`id`, `description`, `tags`) хабу не нужны и сюда не едут —
 * они и есть тот вес, который однажды уже уехал в клиентский бандл (`EXP-0136`).
 */
export interface CatalogItem {
  readonly slug: string;
  readonly title: { ru: string; en: string };
  readonly author: { ru: string; en: string };
  readonly type: { ru: string; en: string };
  readonly year: string;
  /** Сколько людей оценили. Правило показа — `dims-rating.ts`, одно на весь проект. */
  readonly rates: number;
  /** Средняя оценка 0…10. Ноль означает «не оценивали», а НЕ «оценили на ноль». */
  readonly rating: number;
}

/** Одна карточка списка — ровно то, что рисует страница, и ни полем больше. */
export interface CatalogCard {
  readonly slug: string;
  readonly title: string;
  /** Год; `-` в каталоге означает «неизвестен» — тогда пусто и элемент не показывается. */
  readonly year: string;
  /** Автор; тот же прочерк-неизвестность. */
  readonly author: string;
  readonly rating: number;
  readonly rates: number;
}

/** Сводка одного хаба для индексной страницы каталога и для полосы соседей. */
export interface HubSummary {
  readonly key: KindKey;
  /** Сколько объектов этого вида в каталоге. */
  readonly count: number;
  /** Сколько из них получили хотя бы один голос. */
  readonly rated: number;
  /** Сколько страниц по `PER_PAGE`. */
  readonly pages: number;
}

/** Поле каталога, заполненное прочерком, означает «неизвестно», а не «так и называется». */
const known = (v: string) => (v && v !== '-' ? v : '');

/** Объект получил хотя бы один голос — по тому же порогу, что и правило показа звёзд. */
const isRated = (d: CatalogItem) => (Number.isFinite(d.rates) ? Math.floor(d.rates) : 0) >= 1;

/**
 * ПОРЯДОК КАРТОЧЕК В ХАБЕ.
 *
 * 🟡 **PENDING: интервью №030, В2 ещё не отвечен** (варианты: А по алфавиту · Б сначала лучшие ·
 * В сначала оценённые, внутри по алфавиту). Пока ответа нет, порядок выбран агентом и назван
 * вслух — вот он и вот почему:
 *
 *   1. оценённые идут ПЕРЕД неоценёнными;
 *   2. внутри оценённых — по убыванию оценки, затем по убыванию числа голосов;
 *   3. всё остальное и все равенства — по слагу.
 *
 * **Почему так, а не по алфавиту.** V3 «Рейтинг» — это номера мест: страница объявлена «топом по
 * версии NDim Space». Под алфавитным порядком номер места перестаёт что-либо значить, то есть
 * форма, которую владелец выбрал, разъезжается со своим содержанием. Правило (1) при этом
 * общее у ответов Б и В — при обоих оценённые занимают первые 17 страниц хаба «Фильмы», —
 * поэтому смена ответа переставит карточки ВНУТРИ головы списка, а не перекроит весь хаб.
 *
 * 🔴 **Цена, названная в интервью и принятая сознательно:** оценён 981 фильм из 2774, значит
 * примерно с 17-й страницы пойдут сорок страниц «ещё без голосов»; и карточка переезжает между
 * страницами, когда объект получает новый голос (переезд случается на выкате, а не в бою:
 * сайт статический).
 *
 * 🔴 **ПОРЯДОК ОБЯЗАН БЫТЬ НЕЗАВИСИМ ОТ ЯЗЫКА, и поэтому равенства разводит СЛАГ, а не название.**
 * `/ru/catalog/movie/5` и `/en/catalog/movie/5` объявлены друг другу переводами через `hreflang`.
 * Сортировка по названию дала бы на этих двух адресах РАЗНЫЕ наборы объектов — то есть разметка
 * утверждала бы неправду на каждой странице каждого хаба. Слаг у объекта один на оба языка.
 */
export function compareForHub(a: CatalogItem, b: CatalogItem): number {
  const ra = isRated(a);
  const rb = isRated(b);
  if (ra !== rb) return ra ? -1 : 1;
  if (ra) {
    if (b.rating !== a.rating) return b.rating - a.rating;
    if (b.rates !== a.rates) return b.rates - a.rates;
  }
  return a.slug < b.slug ? -1 : a.slug > b.slug ? 1 : 0;
}

/** Сколько страниц у списка из `n` объектов. Пустой список — всё равно одна страница. */
export const pageCount = (n: number): number => Math.max(1, Math.ceil(n / PER_PAGE));

/**
 * Раскладка каталога по хабам: семь известных видов + хвост.
 *
 * Хвост — это НЕ мусор и не ошибка данных: 25 объектов шести видов, которым не хватило карточек
 * до порога хаба (TV Show 11 · Novella 5 · Animated Movie 3 · Internet Show 3 · Lecture 2 ·
 * Graphic Novel 1). Смысловое слияние («Повесть → Роман») запрещено — это правка данных под
 * видом чтения (`dim-kind.ts`). Поэтому хвост живёт СПИСКОМ на индексной странице каталога:
 * иначе 25 объектов × 2 языка остались бы недостижимыми от корня, а вся фаза существует ровно
 * ради того, чтобы недостижимых не было ни одной.
 */
export function groupByKind<T extends CatalogItem>(
  items: readonly T[],
): { hubs: Map<KindKey, T[]>; tail: T[] } {
  const hubs = new Map<KindKey, T[]>(KIND_KEYS.map((k) => [k, [] as T[]]));
  const tail: T[] = [];
  for (const item of items) {
    const key = kindKeyOf(item.type);
    if (key) hubs.get(key)!.push(item);
    else tail.push(item);
  }
  for (const list of hubs.values()) list.sort(compareForHub);
  tail.sort(compareForHub);
  return { hubs, tail };
}

/** Сводки всех семи хабов в каноническом порядке `KIND_KEYS`. */
export function summarize<T extends CatalogItem>(hubs: Map<KindKey, T[]>): HubSummary[] {
  return KIND_KEYS.map((key) => {
    const list = hubs.get(key) ?? [];
    return { key, count: list.length, rated: list.filter(isRated).length, pages: pageCount(list.length) };
  });
}

/**
 * Срез одной страницы хаба. Номер страницы — от 1; за пределами списка возвращается пусто, и
 * решение «это 404» принимает загрузчик, а не этот модуль.
 */
export const slicePage = <T>(list: readonly T[], page: number): T[] =>
  list.slice((page - 1) * PER_PAGE, page * PER_PAGE);

/**
 * АДРЕСА ХАБОВ — одно место на проект: их считают и загрузчики, и разметка, и карта сайта, и
 * стражи. Три копии «склеить путь» разошлись бы молча, а расхождение здесь означает битую
 * ссылку на каждой странице каталога.
 *
 * 🔴 Первая страница живёт на `/{lang}/catalog/{kind}`, а НЕ на `…/1`. Два адреса с одним
 * содержанием — это дубль, который поисковик обязан склеивать сам; лучше его не создавать.
 */
export const catalogPath = (lang: Lang): string => `/${lang}/catalog`;

export const hubPath = (lang: Lang, kind: KindKey, page = 1): string =>
  page <= 1 ? `/${lang}/catalog/${kind}` : `/${lang}/catalog/${kind}/${page}`;

export const dimensionPath = (lang: Lang, slug: string): string => `/${lang}/dimension/${slug}`;

/** Объект каталога → карточка на нужном языке. */
export const toCard = (item: CatalogItem, lang: Lang): CatalogCard => ({
  slug: item.slug,
  title: pick(item.title, lang),
  year: known(item.year),
  author: known(pick(item.author, lang)),
  rating: item.rating,
  rates: item.rates,
});
