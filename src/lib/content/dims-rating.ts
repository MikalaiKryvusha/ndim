/** Порог, ниже которого звёзд нет вовсе. */
export const STARS_FROM = 1;

/**
 * Порог показа числа проголосовавших.
 *
 * Равен `STARS_FROM` сознательно: есть звёзды — есть и честное число тех, кто их поставил.
 * Константа оставлена отдельной, а не слита с первой, чтобы порог можно было вернуть одной
 * строкой, не разыскивая места сравнения (их больше не будет — правило одно на весь проект).
 */
export const RATER_COUNT_FROM = 1;

export interface RatingView {
  /** Показывать звёзды и число средней оценки. */
  readonly showStars: boolean;
  /** Показывать «оценили: N». Никогда не бывает true при `showStars === false`. */
  readonly showRaterCount: boolean;
}

/**
 * @param rates сколько человек оценили объект (поле `rates` документа `dims/{dimId}`)
 */
export function ratingView(rates: number): RatingView {
  // Отрицательное и дробное сюда приезжать не должно, но каталог — внешние данные, а не наши
  // типы: битое значение обязано вести себя как «оценок нет», а не как «показать звёзды».
  const n = Number.isFinite(rates) ? Math.floor(rates) : 0;
  return {
    showStars: n >= STARS_FROM,
    showRaterCount: n >= RATER_COUNT_FROM,
  };
}

/**
 * ТРИ СОСТОЯНИЯ ВЕЛИЧИНЫ NDSR (`plans/56` шаг 1) — и ни одно не притворяется другим.
 *
 * Шкала продукта 0…10, и НОЛЬ на ней — законная оценка. Отсюда состояний три, а не два:
 *
 * | Состояние | Когда | Что человек видит |
 * |---|---|---|
 * | `none` | голосов нет | честная строка «Ещё без голосов», звёзд нет |
 * | `rated` | голоса есть, средняя больше нуля | звёзды, NDSR полным именем, счётчик |
 * | `all-zero` | голоса есть, средняя РОВНО ноль | то же, плюс дверь называет причину нуля |
 *
 * 🔴 ЗАЧЕМ ТРЕТЬЕ. Прежде дверь знала два состояния, и на `all-zero` она говорила текст «есть
 * оценка» — то есть страница показывала «0,0» и десять пустых звёзд, ничем не объясняя, оценили
 * объект нулём или не оценивали вовсе. Читается это как поломка, а не как факт (`plans/56`,
 * таблица шага 0). В бою таких объектов два: `quadrobics-bdyaergq` и
 * `serious-sam-vr-the-last-hope-otgjmpyx` (замер по `dims-build.json`, 5121 запись).
 *
 * 🔑 ПОЧЕМУ ЭТО НЕ ВТОРАЯ КОПИЯ ПРАВИЛА. Порог голосов здесь НЕ сравнивается: состояние `none`
 * берётся у `ratingView` — того же решения, что рисует звёзды. Своё сравнение `rates` с числом
 * ловит `dims-rating.test.ts` грепом по всему `src`, и ловит справедливо.
 *
 * ⚠️ Средняя РОВНО ноль означает, что нули поставили ВСЕ оценившие: шкала неотрицательна, и
 * ненулевой голос увёл бы среднюю выше нуля. Именно поэтому текст двери вправе назвать это
 * фактом, а не догадкой. Битая средняя (NaN, отрицательная) сюда приезжать не должна, но
 * каталог — внешние данные: она ведёт себя как ноль, и текст остаётся верным по форме.
 */
export type RatingState = 'none' | 'rated' | 'all-zero';

/**
 * @param rates сколько человек оценили объект
 * @param rating средняя оценка объекта, 0…10
 */
export function ratingState(rates: number, rating: number): RatingState {
  if (!ratingView(rates).showStars) return 'none';
  const average = Number.isFinite(rating) ? rating : 0;
  return average > 0 ? 'rated' : 'all-zero';
}
