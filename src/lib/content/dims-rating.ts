/** Порог, ниже которого звёзд нет вовсе. */
export const STARS_FROM = 1;

/**
 * Порог показа числа проголосовавших.
 *
 * Равен `STARS_FROM` сознательно: есть звёзды — есть и честное число тех, кто их поставил.
 * Константа оставлена отдельной, а не слита с первой, чтобы порог можно было вернуть одной
 * строкой, не разыскивая места сравнения (их больше не будет — правило одно на весь проект).
 */
export const RATER_COUNT_FROM = 1;

export interface RatingView {
  /** Показывать звёзды и число средней оценки. */
  readonly showStars: boolean;
  /** Показывать «оценили: N». Никогда не бывает true при `showStars === false`. */
  readonly showRaterCount: boolean;
}

/**
 * @param rates сколько человек оценили объект (поле `rates` документа `dims/{dimId}`)
 */
export function ratingView(rates: number): RatingView {
  // Отрицательное и дробное сюда приезжать не должно, но каталог — внешние данные, а не наши
  // типы: битое значение обязано вести себя как «оценок нет», а не как «показать звёзды».
  const n = Number.isFinite(rates) ? Math.floor(rates) : 0;
  return {
    showStars: n >= STARS_FROM,
    showRaterCount: n >= RATER_COUNT_FROM,
  };
}

/**
 * СКОЛЬКО ЗВЁЗД РИСОВАТЬ — правило владельца, интервью №044, В3 (2026-08-22).
 *
 * Дословно: «*должна рисоваться одна серая звезда, как в шкале оценок. Если оценка выше нуля,
 * единица - то одна золотая звезда, и дальше по мере роста оценки растёт количество отображаемых
 * золотых звезд. Ничего никому объяснять не нужно про ноль звёзд - это просто частный случай
 * пространства*».
 *
 * | Оценка | Что рисуется |
 * |---|---|
 * | больше нуля | ТОЛЬКО золотые звёзды, числом округлённой оценки; пустых позиций нет вовсе |
 * | ровно ноль при живых голосах | ОДНА серая звезда — как в шкале ввода, где ноль тоже серый |
 *
 * 🔴 ЧТО ЭТО ОТМЕНИЛО. Прежде рисовался ряд из ДЕСЯТИ позиций, где незаработанные звёзды стояли
 * пустыми, а объект с нулевой средней показывал десять пустых звёзд и «0,0» — картинку
 * неоценённого. Агент предлагал лечить это ТЕКСТОМ («все поставили ноль…»); владелец текст
 * отклонил и дал правило отрисовки: «ничего никому объяснять не нужно».
 *
 * 🔑 ПОЧЕМУ СЕРАЯ ЗВЕЗДА — НЕ ИЗОБРЕТЕНИЕ. Ровно это уже показывает шкала ВВОДА оценок:
 * поставленный ноль рисуется закрашенной звездой цвета `--faint` с комментарием в коде
 * «*Ноль — это осознанная оценка «ноль», а не «золото». Он серый*» (`src/routes/dims/+page.svelte`).
 * Владелец сослался на неё словами «как в шкале оценок» — карточка перестаёт спорить с продуктом.
 *
 * ⚠️ НИЖНЯЯ ГРАНИЦА `1` У ПОЛОЖИТЕЛЬНОЙ ОЦЕНКИ — не украшение, а его же правило. Средняя 0,3
 * (голоса 0, 0, 1) округляется в ноль, и без границы положительная оценка нарисовалась бы как
 * «ноль золотых», то есть притворилась бы нулевой. Сегодня таких объектов в каталоге НОЛЬ
 * (замер по `dims-build.json`, 1877 оценённых), но шкала допускает их завтра.
 *
 * ⛔ Функция НЕ решает, показывать ли оценку вообще: это работа `ratingView`. Зовут её только
 * там, где `showStars` уже сказал «да».
 *
 * @param rating средняя оценка объекта, 0…10
 */
export function starRow(rating: number): { readonly gold: number; readonly grey: number } {
  const average = Number.isFinite(rating) ? rating : 0;
  // Отрицательная средняя невозможна на шкале 0…10, но каталог — внешние данные: она обязана
  // вести себя как ноль, а не рисовать ряд «в минус».
  if (average <= 0) return { gold: 0, grey: 1 };
  return { gold: Math.min(10, Math.max(1, Math.round(average))), grey: 0 };
}
