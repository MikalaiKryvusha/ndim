/** Порог, ниже которого звёзд нет вовсе. */
export const STARS_FROM = 1;

/**
 * Порог показа числа проголосовавших.
 *
 * Равен `STARS_FROM` сознательно: есть звёзды — есть и честное число тех, кто их поставил.
 * Константа оставлена отдельной, а не слита с первой, чтобы порог можно было вернуть одной
 * строкой, не разыскивая места сравнения (их больше не будет — правило одно на весь проект).
 */
export const RATER_COUNT_FROM = 1;

export interface RatingView {
  /** Показывать звёзды и число средней оценки. */
  readonly showStars: boolean;
  /** Показывать «оценили: N». Никогда не бывает true при `showStars === false`. */
  readonly showRaterCount: boolean;
}

/**
 * @param rates сколько человек оценили объект (поле `rates` документа `dims/{dimId}`)
 */
export function ratingView(rates: number): RatingView {
  // Отрицательное и дробное сюда приезжать не должно, но каталог — внешние данные, а не наши
  // типы: битое значение обязано вести себя как «оценок нет», а не как «показать звёзды».
  const n = Number.isFinite(rates) ? Math.floor(rates) : 0;
  return {
    showStars: n >= STARS_FROM,
    showRaterCount: n >= RATER_COUNT_FROM,
  };
}

/**
 * СКОЛЬКО ЗВЁЗД РИСОВАТЬ — правило владельца (интервью №044, В3 и его уточнение по кадрам).
 *
 * Первое слово: «*должна рисоваться одна серая звезда, как в шкале оценок. Если оценка выше нуля,
 * единица - то одна золотая звезда, и дальше по мере роста оценки растёт количество отображаемых
 * золотых звезд. Ничего никому объяснять не нужно про ноль звёзд - это просто частный случай
 * пространства*».
 *
 * 🔄 Уточнение ПО КАДРАМ (он посмотрел пару «до/после»): «*да, но первую звезду можете тёмно
 * серой нарисовать. То есть, оценка между нулём и единицей - это рисуем первую звезду серым
 * тяжёлым цветом, только от 1 и выше - первая звезда заливается золотом*».
 *
 * | Оценка | Что рисуется |
 * |---|---|
 * | меньше единицы (включая РОВНО ноль) | ОДНА тяжёлая серая звезда |
 * | от единицы и выше | ТОЛЬКО золотые, числом округлённой оценки; пустых позиций нет вовсе |
 *
 * 🔴 ПОЧЕМУ РОВНО НОЛЬ ПОПАДАЕТ В ПЕРВУЮ СТРОКУ, хотя буквально сказано «между нулём и единицей».
 * Во-первых, «но» произнесено, ГЛЯДЯ НА КАДР НУЛЯ, — правился именно тот кадр. Во-вторых, в его
 * фразе ровно ДВЕ ветки: «ниже единицы» и «от 1 и выше»; вынеси ноль из первой — и у него не
 * останется ветки вовсе, чего он не говорил. Одна градация проще двух и не требует второго серого.
 *
 * ⛔ ОТМЕНЕНА МОЯ «ЗАЩИТА НА ВЫРОСТ». В прошлой редакции положительная оценка ниже 0,5 получала
 * ОДНУ ЗОЛОТУЮ звезду — я вывел это из его первой фразы «оценка выше нуля → золотая». Уточнение
 * читает ту же границу иначе и прямо: золото начинается С ЕДИНИЦЫ. Его слово отменяет мой вывод,
 * и возвращать `Math.max(1, …)` нельзя — это будет откат решения владельца, а не улучшение.
 *
 * 🔑 ГРАДАЦИЯ ОДНА, И ЭТО ЕЁ ГЛАВНОЕ СВОЙСТВО: `starRow(0)` и `starRow(0,33)` возвращают ОДНО И
 * ТО ЖЕ. Значит кадр нуля есть одновременно кадр всего поддиапазона — отдельная съёмка «0,33»
 * ничего нового не покажет, и это проверяется юнитом, а не верится на слово.
 *
 * ⛔ Функция НЕ решает, показывать ли оценку вообще: это работа `ratingView`. Зовут её только
 * там, где `showStars` уже сказал «да».
 *
 * @param rating средняя оценка объекта, 0…10
 */
export function starRow(rating: number): { readonly gold: number; readonly grey: number } {
  const average = Number.isFinite(rating) ? rating : 0;
  // Ниже единицы золота нет вовсе — ни при нуле, ни при 0,9. Отрицательная средняя невозможна на
  // шкале 0…10, но каталог — внешние данные: она попадает сюда же, а не рисует ряд «в минус».
  if (average < 1) return { gold: 0, grey: 1 };
  return { gold: Math.min(10, Math.round(average)), grey: 0 };
}
