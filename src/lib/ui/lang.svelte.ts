import { langFromPath, langFromBrowser, isLang, type Lang } from '$lib/content/langs';

export type { Lang };

/** Ключ хранилища — тот же, что читает инлайн-скрипт `app.html`. Не переименовывать: у людей уже сохранён выбор. */
const STORAGE_KEY = 'ndim-lang';

function readInitial(): Lang {
  // 🔴 Порядок ОБЯЗАТЕЛЕН и не переставляется: адрес → память → браузер.
  if (typeof location !== 'undefined') {
    const fromPath = langFromPath(location.pathname);
    if (fromPath) return fromPath;
  }
  if (typeof localStorage !== 'undefined') {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (isLang(saved)) return saved;
    } catch {
      // Приватный режим может запретить чтение — падаем на язык браузера.
    }
  }
  // В пререндере ни `location`, ни `navigator` нет: там честный русский, как и в разметке,
  // которую пререндер порождает. Клиент поправит значение первым же кадром.
  return typeof navigator === 'undefined' ? 'ru' : langFromBrowser();
}

let current = $state<Lang>(readInitial());

/** Текущий язык. Читается в разметке — компонент перерисуется при смене. */
export function lang(): Lang {
  return current;
}

/** Сменить язык: состояние + документ + сохранение выбора. */
export function setLang(next: Lang): void {
  current = next;
  if (typeof document === 'undefined') return;
  document.documentElement.setAttribute('lang', next);
  try {
    localStorage.setItem(STORAGE_KEY, next);
  } catch {
    // Приватный режим может запретить запись — язык всё равно применится на эту сессию.
  }
}

/**
 * МОСТ «АДРЕС → ПАМЯТЬ». Вызывается публичной страницей: язык её адреса становится и языком
 * приложения, куда человек пойдёт дальше.
 *
 * 🔴 Именно здесь адрес побеждает память, а не наоборот. Без этой строки человек, пришедший
 * из поиска на `/en/…`, нажал бы «Войти» и получил русское приложение.
 */
export function adoptLangFromPath(pathname: string): void {
  const fromPath = langFromPath(pathname);
  if (fromPath) setLang(fromPath);
}
