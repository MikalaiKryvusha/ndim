/**
 * Канон движения продукта (bugs/05): спокойные переходы, планка — лендинг.
 *
 * Четыре длительности на всё приложение — чтобы движение всех экранов было одной семьёй:
 *   fast    — микрореакции: выпадающие меню, строка отсчёта, мелкие исчезновения;
 *   base    — появление и уход контента, раскрытия, тосты;
 *   slow    — перестроение списков (FLIP);
 *   gesture — уезд объекта ЗА КРАЙ экрана: самое длинное движение продукта.
 *
 * Почему `gesture` длиннее `slow` вдвое (интервью №007, В9, слово владельца: «нужно замедлить
 * анимацию улетания с экрана сохраняемого измерения, сейчас слишком быстро, не понятно, что
 * происходит»): длительность движения обязана расти вместе с расстоянием, иначе крупный жест
 * читается как мигание. Так это и описано в Material Design (Motion → Duration: чем больше
 * элемент и путь, тем длиннее переход) и в HIG. Карточка «Измерений» уезжает на 480px — путь в
 * разы длиннее любого другого движения продукта, а хронометраж у неё был общий со списком.
 *
 * Используй ВМЕСТЕ со встроенными переходами Svelte (`transition:fade/slide/fly`,
 * `animate:flip`) — не изобретай хронометраж на setTimeout.
 *
 * Уважение к prefers-reduced-motion: человеку, попросившему систему не анимировать,
 * все длительности обнуляются — интерфейс работает мгновенно (так делает и лендинг).
 *
 * ⚠️ У этих чисел есть CSS-зеркало — токены `--motion-fast/base/slow/gesture` в
 * `src/routes/+layout.svelte`. Оно существует потому, что часть переходов умеет только
 * браузер (раскрывашка `<details>`, bugs/56), а импортировать TS в CSS невозможно.
 * Меняешь хронометраж — меняй в ОБОИХ местах.
 */
const reduced =
  typeof window !== 'undefined' &&
  typeof window.matchMedia === 'function' &&
  window.matchMedia('(prefers-reduced-motion: reduce)').matches;

export const MOTION = {
  fast: reduced ? 0 : 140,
  base: reduced ? 0 : 240,
  slow: reduced ? 0 : 320,
  gesture: reduced ? 0 : 1200,
} as const;
