/**
 * Высота прибитой шапки — ОДИН замер на весь продукт.
 *
 * Заведён при переносе шапки во всю ширину (`ideas/17`, макет V3-А, утверждён владельцем
 * 2026-07-27): от высоты шапки теперь зависят ДВА элемента оболочки —
 *   · прилипающая панель «Измерений», которая должна стоять ПОД шапкой (bugs/51, bugs/52);
 *   · боковой рельс, который начинается под шапкой и обязан оставаться прибитым (bugs/49).
 * Второй независимый замер того же самого неизбежно разошёлся бы с первым, поэтому шапка
 * САМА публикует свою высоту: число — для JS, CSS-переменная `--bar-h` — для вёрстки.
 *
 * Число именно МЕРИТСЯ, а не зашивается: живой замер 2026-07-27 даёт 61px на 390 и 55px на 1440 —
 * любая константа врала бы на одной из ширин (урок bugs/51). Числа в прежнем комментарии («57 и 52»)
 * успели устареть: квадратные кнопки 34×34 (bugs/63) и полноширинная шапка изменили высоту —
 * ещё одна причина мерить, а не помнить. `ResizeObserver` держит значение верным и при повороте
 * экрана, и при смене языка (английская строка короче русской).
 *
 * [TESTED: 2026-07-27 · живой Chrome, tools/verify-header-v3a.mjs: рельс и панель «Измерений»
 * стоят ровно под шапкой на 390/1024/1440 в обеих темах; замер совпал с фактической высотой]
 */

/**
 * Запасное значение для JS: до первого замера и в пререндере, где DOM ещё нет.
 *
 * ⚠️ Это НЕ то же самое, что запасное значение для ВЁРСТКИ. У вёрстки оно живёт переменной
 * `--bar-h-fallback` (`routes/+layout.svelte`) и меняется по брейкпойнту 1024px — 61px на узких,
 * 55px от 1024px, ровно как меряется живая шапка (`bugs/67`). Одним числом эти два случая не
 * закрыть: CSS обязан знать значение ДО всякого JS, а здесь значение нужно тому, кто и так
 * работает только после гидратации (порог автопрятания панели «Измерений»).
 *
 * Взято 61 — узкая ширина, как дефолт `--bar-h-fallback`: так два запасных значения хотя бы не
 * противоречат друг другу. Точное придёт замером через кадр.
 */
const FALLBACK = 61;

let height = $state(FALLBACK);

/** Текущая высота шапки в пикселях. Читается в разметке — потребитель перерисуется сам. */
export function barHeight(): number {
  return height;
}

/**
 * Взять шапку под наблюдение. Вызывает САМА шапка, передавая свой элемент, — поэтому здесь нет
 * ни `querySelector`, ни зависимости от класса разметки. Прежний замер жил в «Измерениях» и искал
 * `.bar` по всему документу: при переименовании класса он молча оставался с дефолтом, а панель
 * поиска уезжала ЗА шапку (ровно дефект bugs/51, только тихий).
 *
 * Возвращает функцию отписки — для `$effect`.
 */
export function observeBar(bar: HTMLElement): () => void {
  const measure = () => {
    const exact = bar.getBoundingClientRect().height;
    // JS-потребителям (порог автопрятания панели «Измерений») удобно целое число.
    height = Math.round(exact);
    // А вёрстке нужна ТОЧНАЯ высота: рельс липнет к нижнему краю шапки, и округление
    // до пикселя вверх оставляло бы под шапкой полупиксельную щель, сквозь которую
    // видно едущий контент.
    document.documentElement.style.setProperty('--bar-h', `${exact}px`);
  };

  measure();
  const observer = new ResizeObserver(measure);
  observer.observe(bar);
  return () => observer.disconnect();
}
