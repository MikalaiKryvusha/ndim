import type { Lang } from './format.ts';

/**
 * Персонаж демо с уже посчитанной похожестью.
 *
 * `similarity === null` — законное состояние, а не ошибка: ядро возвращает `null`, когда общих
 * измерений нет вовсе (инвариант `|K| = 0` → связи не существует), и такой персонаж не может
 * быть «самой сильной связью» ни при каком раскладе.
 */
export interface RankedPeer {
  readonly id: string;
  readonly name: string;
  readonly similarity: number | null;
}

/** Точка лица на карте пространства — вход для выбора угла поп-апа. */
export interface FacePoint {
  readonly x: number;
  readonly y: number;
}

/**
 * Кого называет поп-ап — самого похожего из посчитанных.
 *
 * Берётся МАКСИМУМ, а не первый элемент: порядок в списке — забота вызывающего, и полагаться
 * на него значило бы завести вторую истину о том, кто ближе всех. Персонажи без связи
 * пропускаются; когда считать не из чего — честный `null`, и поп-апа не будет вовсе.
 */
export function strongestPeer(peers: readonly RankedPeer[]): RankedPeer | null {
  let best: RankedPeer | null = null;
  for (const peer of peers) {
    if (peer.similarity === null) continue;
    if (best === null || peer.similarity > (best.similarity ?? -1)) best = peer;
  }
  return best;
}

/**
 * Ширина бара в процентах ширины дорожки.
 *
 * Зажимается в 0…100 по той же причине, по какой зажимается всё, что едет в CSS: величина
 * приходит из расчёта, а не из литерала, и отрицательная ширина молча ломала бы вёрстку.
 * `null` (связи нет) — это пустой бар, а не отсутствующий: строка персонажа остаётся на месте.
 */
export function barWidth(similarity: number | null): number {
  if (similarity === null || Number.isNaN(similarity)) return 0;
  return Math.min(100, Math.max(0, similarity));
}

/**
 * В КАКОМ ВЕРХНЕМ УГЛУ КАРТЫ СТОИТ ПОП-АП — вычисляется, а не назначается.
 *
 * 🔴 Урок Ш3 `plans/65`, оплаченный до показа владельцу: в макете поп-ап накрыл кружок Алисы.
 * Лицо человека, закрытое подсказкой, — дефект вида, и от угла карты он не застрахован:
 * узлы ходят по всему радиусу вслед за оценками, поэтому «поставим слева» — это назначение,
 * которое однажды окажется неправдой.
 *
 * Правило: из двух верхних углов выбирается тот, чей якорь ДАЛЬШЕ от ближайшего лица.
 * Ничья уходит влево — направление чтения, и выбор обязан быть детерминированным
 * (`AGENT_GUIDE.md` → «Стиль кода»: канонический порядок у всего, что сравнивается).
 */
export function popupCorner(faces: readonly FacePoint[], viewWidth: number): 'left' | 'right' {
  const anchorY = 30;
  const left = { x: viewWidth * 0.2, y: anchorY };
  const right = { x: viewWidth * 0.8, y: anchorY };

  const nearest = (anchor: FacePoint) =>
    faces.reduce(
      (min, face) => Math.min(min, Math.hypot(face.x - anchor.x, face.y - anchor.y)),
      Number.POSITIVE_INFINITY,
    );

  return nearest(right) > nearest(left) ? 'right' : 'left';
}

/**
 * ВТОРАЯ ПОЛОВИНА ФРАЗЫ МОСТИКА — по факту, а не по сценарию (находка Н3 `plans/67`).
 *
 * 🔴 Макет а4 обещал «вот Ваши настоящие связи» безусловно и добавлял предложение про то, что
 * Алиса, Макс и Настя останутся рядом. Второго в продукте НЕТ: синтетических персонажей в базе
 * не существует (это работа `plans/22`), и писать о них — значит описывать несуществующее
 * поведение. Первое же показывало бы на пустоту: демо-измерения вымышлены, перенести оценки
 * из демо в гостевой профиль не во что, и свежий гость приходит с НУЛЁМ измерений.
 *
 * Поэтому фраза достраивается по списку: есть карточки — «вот», нет — «здесь будут».
 *
 * ⚠️ Ветка пустого списка — НОВАЯ строка, она стоит на вычитке у владельца (через Менеджера) и
 * до его ответа каноном НЕ является. Признак `draft` несёт это в разметку плашкой, а не в
 * память следующей сессии.
 */
export function bridgeLine(
  lang: Lang,
  hasCards: boolean,
): { lead: string; tail: string; draft: boolean } {
  const lead = { ru: 'Это была демонстрация', en: 'That was a demonstration' }[lang];
  return hasCards
    ? {
        lead,
        tail: { ru: ' — вот Ваши настоящие связи.', en: ' — here are your real relations.' }[lang],
        draft: false,
      }
    : {
        lead,
        tail: {
          ru: ' — здесь будут Ваши настоящие связи.',
          en: ' — your real relations will be here.',
        }[lang],
        draft: true,
      };
}

/**
 * ОТМЕТКА «ЧЕЛОВЕК ПРИШЁЛ МОСТОМ» — на вкладку, а не на человека.
 *
 * Мост высаживает в `/profile` (первый экран продукта), а карточка-мостик живёт на «Связях»:
 * между ними человек делает свой шаг, и экрану нужно знать, откуда он. `sessionStorage`
 * подходит по сроку жизни ровно: отметка умирает вместе с вкладкой, ничего не переживает
 * закрытие браузера и никуда не уезжает.
 *
 * ⚠️ Не путать с запретом `sessionStorage` в памяти ВИДА экрана (`view-memory.ts`, решение
 * владельца №008 В11=А): там запрет о том, что перезагрузка обязана обнулять память экрана.
 * Здесь другой предмет и другой срок.
 *
 * Обе функции молчат при отказе хранилища (приватный режим, отключённые куки): мостик — это
 * подсказка, а не опора, и падать из-за неё продукт не имеет права.
 */
const BRIDGE_KEY = 'ndim-bridge-crossed';

export function markBridgeCrossed(): void {
  try {
    sessionStorage.setItem(BRIDGE_KEY, '1');
  } catch {
    /* хранилище недоступно — мостик просто не покажется */
  }
}

export function bridgeCrossed(): boolean {
  try {
    return sessionStorage.getItem(BRIDGE_KEY) === '1';
  } catch {
    return false;
  }
}
