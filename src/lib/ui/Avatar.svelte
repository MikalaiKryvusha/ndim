    flex: none;
    display: flex;
    align-items: center;
    justify-content: center;
    font-weight: 700;
    color: var(--primary);
    /* буква масштабируется вместе с кружком — один компонент на разные размеры */
    font-size: calc(var(--size) * 0.37);
  }
  img.ava {
    /* лицо не должно растягиваться: кадрируем по кругу */
    object-fit: cover;
  }

  /*
   * Фото-кнопка: внешне тот же кружок, но с намёком «можно развернуть».
   *
   * 🖱 КУРСОР — УКАЗАТЕЛЬНЫЙ ПАЛЕЦ, А НЕ ЛУПА (слово владельца 2026-08-18): «*при наведении
   * курсора на аватар человека — курсор должен принимать форму не лупы, а указательного пальца,
   * как при наведении на ссылку*». То же и у открытого фото ниже: «*аналогично при открытом
   * фото — не лупа, а указательный палец*».
   *
   * Довод сходится с разметкой: это `<button>`, а не картинка с зумом. Палец — общий язык
   * нажимаемого во всём продукте, и лупа выбивалась из него одна.
   */
  .peek {
    background: none;
    border: 0;
    padding: 0;
    flex: none;
    display: block;
    border-radius: 50%;
    cursor: pointer;
  }
  .peek .ava {
    display: block;
  }

  /* Полноэкранный просмотр. position: fixed выводит слой из любой раскладки. */
  .lightbox {
    position: fixed;
    /* `inset: 0` — намеренно, и это ПРОВЕРЕНО: расширять слой до `100vw` ради полосы
       `scrollbar-gutter` бесполезно, оверфлоу фиксированного слоя обрезается краем области
       прокрутки (bugs/65, кадры `tools/probe-bug65-edge.mjs`). Полосу закрывает не слой,
       а покраска ХОЛСТА в скрипте выше. */
    inset: 0;
    z-index: 80;
    width: 100%;
    border: 0;
    padding: 20px;
    /* 🔗 Чернила и доля — зеркало констант BACKDROP_INK / BACKDROP_ALPHA в скрипте (bugs/65):
       ими красится холст в полосе жёлоба, и оттенки обязаны совпадать. */
    background: rgba(3, 8, 16, 0.88);
    display: flex;
    align-items: center;
    justify-content: center;
    /* 🖱 Палец, а не лупа — вторая половина того же слова владельца 2026-08-18 (`bugs/151`):
       «*аналогично при открытом фото — не лупа, а указательный палец*». Слой сам является
       кнопкой «закрыть», и палец говорит об этом ровно то же, что и везде в продукте. */
    cursor: pointer;
  }
  .lightbox img {
    max-width: min(92vw, 720px);
    max-height: 86vh;
    border-radius: 14px;
    object-fit: contain;
    box-shadow: 0 30px 90px rgba(0, 0, 0, 0.55);
  }
</style>
