<script lang="ts" module>
  /** Счётчик экземпляров: каждому кружку — свой id слоя истории (см. `lightboxId` ниже). */
  let instances = 0;
</script>

<script lang="ts">
  /**
   * Лицо человека: фотография, если она есть, иначе — первая буква имени.
   *
   * Один компонент на все экраны, потому что фото — это не украшение профиля, а то, ради чего
   * на «Связи» вообще смотрят: там ищут ЧЕЛОВЕКА. Раньше и профиль, и связи рисовали кружок с
   * буквой каждый по-своему, а фотографии из 1.x не показывали вовсе (см. `data/avatar.ts`).
   *
   * За картинкой ходим ТОЛЬКО когда флаг `has` говорит, что она есть. Иначе список связей на
   * 250 человек устроил бы 250 заведомо пустых запросов в Storage.
   *
   * Тап по фотографии открывает её ВО ВЕСЬ ЭКРАН (bugs/14): лайтбокс-оверлей, закрывается
   * тапом в любом месте, Esc — и системной кнопкой «Назад» (близнец bugs/76, см. ниже).
   * Кружок с буквой не интерактивен — разворачивать нечего.
   */
  import { pushState } from '$app/navigation';
  import { page } from '$app/state';
  import { fade } from 'svelte/transition';
  import { avatarUrl, cachedAvatarUrl } from '$lib/data/avatar';
  import Brand from '$lib/ui/Brand.svelte';
  import { MOTION } from '$lib/ui/motion';
  import type { Uid } from '$lib/model/schema';

  /*
   * `nameless` — у человека НЕТ имени ни на одном языке, и `name` здесь несёт запасное слово
   * экрана («Без имени»), а не имя. Признак приходит снаружи намеренно: сам компонент отличить
   * «Без имени» от настоящего имени на «Б» не может, а гадать по тексту — это ровно тот класс
   * ошибок, из которого вырос `bugs/150`.
   */
  let {
    uid,
    name,
    has = false,
    size = 54,
    peek = true,
    nameless = false,
  }: {
    uid: Uid;
    name: string;
    has?: boolean;
    size?: number;
    peek?: boolean;
    nameless?: boolean;
  } = $props();
  /*
   * `peek: false` — лицо БЕЗ собственной кнопки лайтбокса (`bugs/104`): в свёрнутой карточке
   * связи весь верх, включая площадь фото, работает на раскрытие (решение владельца
   * 2026-07-31 — дом действий над фото не здесь), и тап по лицу уходит родителю. Портрет
   * крупно открывается из РАСКРЫТОЙ карточки, где `peek` снова true.
   */

  /**
   * Канон 1.x — карточка появляется СРАЗУ с лицом (bugs/57): экран предзагружает лица до
   * отрисовки (`preloadAvatars`), поэтому первый рендер берёт готовый blob-URL из кэша
   * СИНХРОННО. Буква — только пока фото реально нет: не успело за потолок предзагрузки
   * (доедет фоном и встанет одним кадром — blob локален) или его нет вовсе.
   *
   * Захват НАЧАЛЬНОГО значения пропсов тут намеренный (нужен именно первый кадр);
   * реактивный путь — $effect ниже, он же обслуживает смену uid/has.
   */
  // svelte-ignore state_referenced_locally
  let src = $state<string | null>(has ? cachedAvatarUrl(uid) : null);

  /*
   * «НАЗАД» ЗАКРЫВАЕТ ЛАЙТБОКС (интервью №007, В12б; слово владельца: «навигация должна быть
   * честной, фиксим»). Близнец `bugs/76`: полноэкранный слой без записи в истории уводит
   * человека ИЗ ПРИЛОЖЕНИЯ вместо того, чтобы закрыться.
   *
   * Приём — тот же штатный `pushState` + `page.state`, что и у окна «Как меня видят»
   * (`profile/+page.svelte:76`), а не свой перехват `popstate`: адрес не меняется, слой
   * остаётся слоем, историю обслуживает настоящий роутер.
   *
   * Ключ в состоянии — id ЭТОГО кружка, а не «открыт/закрыт»: на «Связях» лиц много, и от
   * общего признака развернулись бы все сразу. Счётчик модуля даёт каждому экземпляру свой
   * id; на uid опираться нельзя — одно лицо бывает на странице дважды (свой аватар в
   * «Профиле» и он же внутри окна «Как меня видят»).
   *
   * Точка закрытия ОДНА — `history.back()`; тап и Escape зовут её же, поэтому состояние не
   * может разъехаться с историей.
   */
  const lightboxId = `ava-${(instances += 1)}`;
  const open = $derived(page.state.photo === lightboxId);

  /**
   * Цвет ХОЛСТА под развёрнутым фото (bugs/65) — та же подложка, что у слоя, но СКОМПОНОВАННАЯ
   * с фоном темы: в полосе жёлоба содержимого нет, и подложка ложилась бы на голый холст,
   * давая в тёмной теме другой оттенок, чем вокруг снимка.
   *
   * 🔗 Пара «истина ↔ зеркало»: чернила и доля обязаны совпадать с правилом `.lightbox` ниже.
   * Разъехавшись, они заменят светлую щель щелью ДРУГОГО ОТТЕНКА — дефект тише прежнего и
   * оттого хуже. Совпадение стережёт `tools/verify-batch4.mjs`: он считает подложку, лежащую
   * на фоне темы, и требует от холста ровно этот цвет (доказано мутацией — доля 88 → 70).
   */
  const BACKDROP_INK = 'rgb(3, 8, 16)';
  const BACKDROP_ALPHA = 88;
  const LIGHTBOX_BACKDROP = `color-mix(in srgb, ${BACKDROP_INK} ${BACKDROP_ALPHA}%, var(--bg))`;

  /**
   * Портал: выносит лайтбокс в document.body (bugs/36). Внутри карточки ему жить нельзя:
   * у карточек есть transform (hover «Связей»), а трансформированный предок делает
   * position: fixed относительным СЕБЯ — фото открывалось «в карточке», обрезалось,
   * и соседние карточки рисовались поверх (z-index заперт в их stacking context).
   */
  function portal(node: HTMLElement) {
    document.body.appendChild(node);
    return { destroy: () => node.remove() };
  }

  /*
   * Пока фото развёрнуто — страница под ним не прокручивается (bugs/36, полировка), а ХОЛСТ
   * страницы красится в цвет подложки (bugs/65).
   *
   * 🔴 Второе — не украшение, и путь к нему стоил опровергнутой гипотезы. `scrollbar-gutter:
   * stable` (bugs/59) держит справа полосу ~15px; под скролл-локом полосы прокрутки в ней уже
   * нет, и человек видел там СВЕТЛЫЙ фон страницы рядом с тёмной подложкой фото. Очевидное
   * лечение — растянуть слой на всё окно (`width: 100vw`) — ПРОВЕРЕНО ПИКСЕЛЯМИ И НЕ РАБОТАЕТ:
   * габарит слоя честно становится 1440 при окне 1440, но оверфлоу фиксированного слоя
   * обрезается краем области прокрутки, и полоса остаётся прежней (`tools/probe-bug65-edge.mjs`,
   * кадры `-1-defekt` и `-2-vylecheno` неотличимы).
   *
   * В этой полосе видно не слой, а ХОЛСТ — фон, распространяемый от корневого элемента.
   * Поэтому красим его, и щель исчезает (кадр `-2-vylecheno` против `-1-defekt`; третий кадр
   * `-3-kontrol` — контроль прибора, EXP-0082). Гуттер при этом остаётся
   * зарезервированным: раскладка не едет вбок, то есть bugs/59 не тревожим вовсе — в отличие
   * от гипотезы 2 документа бага, которая предлагала гуттер на время отпускать.
   */
  $effect(() => {
    if (!open) return;
    const root = document.documentElement;
    const prevOverflow = document.body.style.overflow;
    const prevBg = root.style.backgroundColor;
    document.body.style.overflow = 'hidden';
    root.style.backgroundColor = LIGHTBOX_BACKDROP;
    return () => {
      document.body.style.overflow = prevOverflow;
      root.style.backgroundColor = prevBg;
    };
  });

  function openPhoto(): void {
    pushState('', { photo: lightboxId });
  }

  function closePhoto(): void {
    if (open) history.back();
  }

  $effect(() => {
    if (!has) {
      src = null;
      return;
    }
    let cancelled = false;
    void avatarUrl(uid).then((url) => {
      if (!cancelled) src = url;
    });
    return () => {
      cancelled = true;
    };
  });
</script>

<svelte:window
  onkeydown={(event) => {
    if (open && event.key === 'Escape') closePhoto();
  }}
/>

{#if src && !peek}
  <!-- Без кнопки: тап по лицу принадлежит родителю (свёрнутая карточка связи, bugs/104).
       alt пуст: лицо стоит ВНУТРИ кнопки, у которой имя уже есть текстом, — иначе экранный
       диктор читал бы имя дважды. -->
  <img class="ava" {src} alt="" style="--size:{size}px" />
{:else if src}
  <button type="button" class="peek" style="--size:{size}px" title={name} onclick={openPhoto}>
    <img class="ava" {src} alt={name} style="--size:{size}px" />
  </button>
  {#if open}
    <!-- Лайтбокс — сам кнопка «закрыть»: тап в любом месте сворачивает фото (bugs/14). -->
    <button
      type="button"
      class="lightbox"
      aria-label={name}
      use:portal
      transition:fade={{ duration: MOTION.base }}
      onclick={closePhoto}
    >
      <img {src} alt={name} />
    </button>
  {/if}
{:else if nameless}
  <!--
    ЧЕЛОВЕК БЕЗ ИМЕНИ — ФИРМЕННЫЙ ЗНАК, А НЕ БУКВА (решение владельца 2026-08-18, `bugs/150`:
    «*„Без имени“ и кружок с буквой «Б». Как ДОЛЖЕН выглядеть человек без имени — рисуй наше
    фирменное N*»).

    🔑 Повод, названный им же: буква «Б» — первая буква ЗАПАСНОГО СЛОВА, а не имени. Она читается
    как имя на «Б» и потому врёт. Знак не врёт: он говорит «человек Пространства, имя не указано».
    Замер боя 2026-08-18: таких людей 206 из 331 — то есть это не редкий случай, а обычный вид
    карточки.

    Знак берётся у `Brand.svelte` со снятой плашкой: кружок уже несёт свою подложку. Доля 0.62 —
    чтобы поля вокруг знака совпадали с полями вокруг буквы у именованных соседей.
    `aria-label` при этом остаётся ТЕКСТОМ («Без имени»): экранный диктор не читает картинок.
  -->
  <span class="ava" style="--size:{size}px" role="img" aria-label={name}>
    <Brand size={Math.round(size * 0.62)} plate={false} />
  </span>
{:else}
  <span class="ava" style="--size:{size}px">{name.slice(0, 1)}</span>
{/if}

<style>
