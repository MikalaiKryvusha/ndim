<script lang="ts">
  /**
   * КАРТОЧКА-МОСТИК НА «СВЯЗЯХ» — пояснение тому, кто только что пришёл из демо
   * (Ш6 `plans/67`, основа А4 «Мостик демонстрации», композиция владельца — синтез №043 В1).
   *
   * ЗАЧЕМ ОНА ЕСТЬ. Человек играл со звёздами, видел Алису, Макса и Настю на карте — и его
   * внесло внутрь продукта. Без единого слова он вправе решить, что три персонажа и есть его
   * связи. Карточка честно называет игру игрой и говорит, что здесь начинается настоящее.
   *
   * 🔴 ЧТО ОНА НЕ ГОВОРИТ И ПОЧЕМУ (находка Н3 `plans/67`). Макет а4 добавлял второе
   * предложение — «Алиса, Макс и Настя останутся рядом, пока не появится первая настоящая;
   * убрать их можно крестиком». Синтетических персонажей в базе НЕТ (это работа `plans/22`),
   * поэтому предложение описывало бы несуществующее поведение. Его здесь нет вовсе.
   *
   * ⚠️ Ветка пустого списка — НОВАЯ строка, она стоит на вычитке у владельца (через Менеджера)
   * и до его ответа каноном НЕ является. Пометка живёт атрибутом `data-draft`, а НЕ словами на
   * экране: «текст на вычитку» — наш внутренний жаргон, и человеку на лице продукта его видеть
   * нельзя (`AGENT_GUIDE.md` → «Словарь продукта»). Плашка из макета — пометка для вычитки,
   * а не часть продукта.
   *
   * Показывается только пришедшему МОСТОМ: отметку кладёт демо лендинга, живёт она во вкладке
   * (`$lib/ui/handhold`). Человек, открывший «Связи» своим ходом, ничего этого не видит.
   */
  import { onMount } from 'svelte';
  import { slide } from 'svelte/transition';
  import { bridgeCrossed, bridgeLine } from '$lib/ui/handhold';
  import { lang as currentLang } from '$lib/ui/lang.svelte';
  import { MOTION } from '$lib/ui/motion';

  let { ready, hasCards }: { ready: boolean; hasCards: boolean } = $props();

  const lang = $derived(currentLang());

  /*
   * Отметка читается в `onMount`, а не при разборе модуля: `sessionStorage` на сборке не
   * существует, и пререндер обязан пройти молча. В пререндеренном HTML карточки нет вовсе —
   * это правильно, она принадлежит одному живому переходу, а не странице.
   */
  let crossed = $state(false);
  onMount(() => {
    crossed = bridgeCrossed();
  });

  /*
   * Фраза достраивается ПО ФАКТУ наличия карточек, а не по сценарию. Ждём `ready`: до ответа
   * экрана список пуст по незнанию, а не по правде, и текст сменился бы у человека на глазах —
   * ровно то «на горячую», которое владелец запретил (`ideas/21` п. 10).
   */
  const line = $derived(bridgeLine(lang, hasCards));
</script>

{#if crossed && ready}
  <div class="bridge" data-draft={line.draft} transition:slide={{ duration: MOTION.base }}>
    <p><b>{line.lead}</b>{line.tail}</p>
  </div>
{/if}

