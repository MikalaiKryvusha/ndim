/**
 * Идёт ПРОГРАММНОЕ восстановление прокрутки.
 *
 * Обработчики прокрутки не умеют отличать руку человека от нашего же `scrollTo` — и на
 * «Измерениях» это уводило панель «Все / Мой NDim ID» (`bugs/75`, п. 2 волны). Владелец описал
 * точно: «словно разные глубины скрола на этих суб страницах вынуждают панель скрыться (она
 * думает, что страницу листали)». В 1.x той же болезни не было, потому что владелец ЗАСТАВЛЯЛ
 * панель показаться сразу после восстановления позиции (`showTopStickyToolbar()` стоял в трёх
 * местах: `app.js:1157-1161`, `:1478`, `:1235`).
 *
 * Признак живёт ЗДЕСЬ, а не в экране, именно потому, что теперь программная прокрутка бывает на
 * любом экране: иначе дефект панели рождался бы заново на каждом новом экране с прибитой
 * шапкой (прямое предупреждение `plans/08`, шаг 6).
 */
let restoring = false;
/** Поколение попытки: вторая навигация обязана останавливать цикл первой. */
let generation = 0;

/** Идёт ли программное восстановление прокрутки прямо сейчас. */
export function restoringScroll(): boolean {
  return restoring;
}

/** Сколько ждём, пока документ наберёт прежнюю высоту. Канон `bugs/64`. */
const DEADLINE_MS = 1200;
/** Допуск попадания: ближе этого считаем, что сели ровно. */
const TOLERANCE_PX = 2;

/**
 * Вернуть прокрутку на запомненное место.
 *
 * Одного `scrollTo` мало: документ может ещё не набрать прежнюю высоту (лента дорисовывается),
 * и браузер ПРИЖИМАЕТ прокрутку к текущему концу — человек оказывается не там, где был. Поймано
 * QA-прогоном `bugs/64`: просили 7658px, получали 7191px. Поэтому повторяем по кадрам, пока не
 * сядем ровно или пока не выйдет время.
 *
 * `instant` обязателен: плавный переход здесь и был бы тем самым «съездом», от которого мы ушли
 * (`+layout.svelte` → `scroll-behavior: auto`).
 *
 * И уважаем человека: тронул прокрутку сам — немедленно отступаем. Бороться с рукой
 * пользователя недопустимо.
 */
export function restoreScroll(
  target: number,
  hooks?: { onStart?: (() => void) | undefined; onEnd?: (() => void) | undefined },
): void {
  const mine = ++generation;
  restoring = true;
  hooks?.onStart?.();

  if (target <= 0) {
    window.scrollTo({ top: 0, behavior: 'instant' });
    // Ранний путь тоже обязан снять признак — иначе обработчики прокрутки замрут навсегда.
    requestAnimationFrame(() => {
      if (mine === generation) restoring = false;
    });
    return;
  }

  const until = performance.now() + DEADLINE_MS;
  let cancelled = false;
  const giveUp = (): void => {
    cancelled = true;
  };
  const events = ['wheel', 'touchstart', 'keydown', 'pointerdown'] as const;
  for (const type of events) window.addEventListener(type, giveUp, { once: true, passive: true });

  const stop = (): void => {
    for (const type of events) window.removeEventListener(type, giveUp);
    hooks?.onEnd?.();
    /*
     * Признак снимаем СЛЕДУЮЩИМ кадром: событие `scroll` от последнего `scrollTo` прилетает
     * уже после `stop()`, и снятие в тот же момент вернуло бы дефект панели в миниатюре.
     */
    requestAnimationFrame(() => {
      if (mine === generation) restoring = false;
    });
  };

  const step = (): void => {
    if (mine !== generation) return; // нас сменила новая навигация — тихо уходим
    if (cancelled) return stop();
    window.scrollTo({ top: target, behavior: 'instant' });
    if (Math.abs(window.scrollY - target) <= TOLERANCE_PX || performance.now() > until) {
      return stop();
    }
    requestAnimationFrame(step);
  };

  // Первый прыжок — СИНХРОННО, в том же кадре: так человек не видит кадра «экран сверху».
  step();
}
