/**
 * ПАМЯТЬ ВИДА ЭКРАНОВ — `plans/08` (волна `ideas/21`, п. 9; ответ владельца В11=А).
 *
 * Слово владельца дословно:
 *   «при навигации, страницы открываются вверху, не сохраняются позиции скрола по каждой из
 *    страниц. Должны сохраняться. Страницы должны открываться в том состоянии, в каком их
 *    оставили при навигации С ЭТИХ страниц.»
 *
 * ── ЧТО ЭТОТ МОДУЛЬ И ЧТО НЕ ОН ────────────────────────────────────────────────────────────
 * Это ТОНКИЙ слой поверх штатных крючков SvelteKit (`beforeNavigate` / `afterNavigate`), а не
 * свой роутер. Всё, что платформа умеет сама (записи истории, back/forward), остаётся у неё; мы
 * добавляем ровно одно, чего у неё нет: память, привязанную к ПУТИ маршрута, а не к записи
 * истории. Требование владельца именно про путь: тап по нав-панели — это history PUSH, новая
 * запись, и снимок старой записи к ней не относится.
 *
 * ⚠️ Самодельный перехват `popstate`, свои индексы истории, свои гонки с восстановлением
 * прокрутки роутера — запрещены (`plans/08` → «Чего НЕ делать»): это быстро превращается в
 * самодельный роутер поверх штатного.
 *
 * ── РАЗВЕДКА ПЛАТФОРМЫ, СНЯТАЯ НА СТЕНДЕ 2026-07-30 (шаг 2 плана) ──────────────────────────
 * Три факта, добытые наблюдением, — на них построен этот модуль:
 *
 *   1. PUSH-переход по нав-панели ставит прокрутку в **0** (как и записано в `+layout.svelte`).
 *   2. Системная «Назад» в нашем приложении даёт **тоже 0**, а не прежнюю позицию. Платформа
 *      честно пытается восстановить её, но данные экрана приезжают асинхронно: в момент
 *      восстановления в ленте было 12 карточек вместо 44, и позиция прижималась к короткому
 *      документу. То есть **на платформенное восстановление опираться нельзя** — и записанный
 *      в репозитории диагноз «при возврате назад восстанавливает прежнюю» верен лишь для
 *      документа, который уже набрал высоту.
 *   3. Штатный `snapshot` SvelteKit хранит снимки в **`sessionStorage`** (`sveltekit:snapshot`,
 *      увидено там же) — то есть ПЕРЕЖИВАЕТ перезагрузку страницы. Это прямо противоречит
 *      ответу владельца В11=А («память живёт в живой вкладке, перезагрузка обнуляет»), поэтому
 *      штатный `snapshot` здесь не используется вовсе.
 *
 * ── ГДЕ ЖИВЁТ ПАМЯТЬ (ответ В11=А) ─────────────────────────────────────────────────────────
 * В кэше сессии (`$lib/data/cache`), под префиксом `view:`. Это не «складываем что попало в
 * кэш данных»: у {@link remember} ровно такое назначение и записано в его документации —
 * «то, что базой не читается, но обязано пережить навигацию». Выгода тройная и бесплатная:
 *
 *   · перезагрузка страницы обнуляет память вместе с кэшем — ровно ответ В11=А;
 *   · смена человека (`own(uid)`) уносит её ЦЕЛИКОМ — чужую позицию показать невозможно;
 *   · выход из аккаунта (`forgetAll`) — то же.
 *
 * Заводить второе хранилище рядом значило бы заводить второй жизненный цикл и вторую дыру
 * приватности (`PHILOSOPHY.md`: Оккам).
 */

import { afterNavigate, beforeNavigate } from '$app/navigation';
import { tick } from 'svelte';
import { peek, remember } from '../data/cache.ts';

/** Снимок вида одного экрана. */
interface ViewSnapshot {
  /** Позиция прокрутки окна на момент уходa. */
  readonly scroll: number;
  /** Всё остальное, что экран считает своим видом (вкладка, докуда раскрыта лента). */
  readonly view: unknown;
}

/** Ключ памяти — ПУТЬ маршрута. Префикс `view:` роднит записи для инвалидации одной строкой. */
function viewKey(path: string): string {
  return `view:${path}`;
}

export interface ViewMemorySpec<T> {
  /** Путь маршрута этого экрана (`/dims`, `/relations`, …) — он же ключ памяти. */
  readonly path: string;
  /**
   * Есть ли у экрана ТО ЖЕ содержимое, что при уходе (данные взяты из кэша, а не перечитаны).
   *
   * Зачем это здесь: вернуть человека на 900px ДРУГОГО списка хуже, чем открыть экран сверху.
   * Лента «Все» собирается в случайном порядке, и после пересборки та же позиция указывает в
   * никуда. Значение снимается экраном синхронно при инициализации (`peek…() !== undefined`).
   */
  readonly warm: boolean;
  /** Что экран считает своим видом. Вызывается ПЕРЕД уходом с маршрута. */
  readonly capture?: () => T;
  /**
   * Вернуть вид. Может быть асинхронным: «докуда долистано» приходится добирать, и прокрутке
   * нужна прежняя ВЫСОТА документа, иначе браузер прижмёт её к текущему концу (bugs/64).
   */
  readonly restore?: (view: T) => void | Promise<void>;
  /** Экран хочет что-то сделать в начале программной прокрутки (показать панель — канон 1.x). */
  readonly onScrollStart?: () => void;
  /** …и в конце. */
  readonly onScrollEnd?: () => void;
}

/**
 * Подключает экран к памяти вида. Зовётся ОДИН раз при инициализации компонента страницы —
 * штатные `beforeNavigate`/`afterNavigate` требуют именно этого.
 *
 * Экран объявляет только СВОИ поля: знание о конкретных экранах в этот модуль не утекает.
 */
export function useViewMemory<T>(spec: ViewMemorySpec<T>): void {
  const key = viewKey(spec.path);

  beforeNavigate((nav) => {
    // Уходим ли мы вообще с нашего маршрута. `to === null` — закрытие вкладки или переход
    // наружу: снимок всё равно снимаем, он умрёт вместе со страницей и никому не помешает.
    if (nav.from?.url.pathname !== spec.path) return;
    if (nav.to !== null && nav.to.url.pathname === spec.path) return; // остаёмся на месте
    remember<ViewSnapshot>(key, {
      scroll: Math.round(window.scrollY),
      view: spec.capture?.(),
    });
  });

  afterNavigate((nav) => {
    if (nav.to?.url.pathname !== spec.path) return;
    /*
     * Пришли ли мы С ДРУГОГО экрана. Три случая, когда восстанавливать НЕЛЬЗЯ:
     *   · `from === null` — первый заход в приложение (тогда и памяти нет);
     *   · тот же путь — это либо якорь внутри страницы, либо ЗАКРЫТИЕ слоя системной
     *     «Назад» (неглубокое маршрутирование `bugs/76`: окно «Как меня видят», лайтбокс
     *     фото, панель глав). Там снимок наш СТАРЫЙ, и возврат к нему увёз бы человека
     *     с места, где он стоит.
     */
    if (nav.from === null || nav.from.url.pathname === spec.path) return;
    if (nav.to.url.hash !== '') return; // ссылка с якорем: место выбирает якорь, не мы

    const snapshot = peek<ViewSnapshot>(key);
    if (snapshot === undefined) return;
    // Содержимое другое — позиция от него не имеет смысла (см. `warm`).
    if (!spec.warm) return;

    void apply(snapshot, spec);
  });
}

/**
 * Вернуть снимок: сначала прокрутка, ПОТОМ добор содержимого — и прокрутка доводится по кадрам.
 *
 * Порядок именно такой, и он не противоречит правилу «сначала высота, потом позиция»:
 * {@link restoreScroll} повторяет попытку по кадрам ровно потому, что документ набирает высоту
 * не сразу. Зато первый прыжок происходит СИНХРОННО, в том же кадре, что и навигация, — и
 * человек не видит кадра «экран сверху». На тёплом экране (лента восстановлена из кэша,
 * `ideas/18`) высота уже есть, и первый же прыжок садится ровно.
 */
async function apply<T>(snapshot: ViewSnapshot, spec: ViewMemorySpec<T>): Promise<void> {
  restoreScroll(snapshot.scroll, { onStart: spec.onScrollStart, onEnd: spec.onScrollEnd });
  if (spec.restore !== undefined && snapshot.view !== undefined) {
    await spec.restore(snapshot.view as T);
  }
  await tick();
}

