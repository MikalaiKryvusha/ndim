/**
 * Заменить адрес текущей записи истории, СОХРАНИВ состояние, которое в ней держит роутер.
 *
 * @param url путь с параметрами и якорем — то, что должно остаться в адресной строке.
 */
export function replaceUrl(url: string): void {
  if (typeof history === 'undefined') return;
  // `history.state` — то, что положил туда SvelteKit. Передаём его обратно, а не `null`.
  history.replaceState(history.state, '', url);
}
