<style>
  /* Мобильная раскладка не меняется: до 1024px рельса нет, работает BottomNav. */
  .rail {
    display: none;
  }

  @media (min-width: 1024px) {
    .rail {
      display: flex;
      flex-direction: column;
      gap: 3px;
      /* В сетке экрана рельс занимает первую колонку от ВТОРОЙ строки и до низа:
         первую строку целиком забрала полноширинная шапка (V3-А). */
      grid-row: 2 / -1;
      grid-column: 1;
      padding: 16px 12px;
      background: var(--panel);
      border-right: 1px solid var(--edge);
      /* Рельс прибит (bugs/49, слово владельца КАПСОМ: «ДОЛЖНО БЫТЬ ЗАФИКСИРОВАНО»):
         колонка сетки тянется на всю высоту ДОКУМЕНТА, поэтому без sticky кнопки
         уезжали за верхний край при скролле. align-self: start сжимает сам рельс до
         высоты вьюпорта — иначе sticky нечему липнуть; на низком окне пункты
         скроллятся внутри рельса.

         Отсчёт от ИЗМЕРЕННОЙ высоты шапки (--bar-h, публикует сама шапка): она стоит
         над рельсом и прибита к нулю, поэтому рельс липнет к её нижнему краю. Зашитая
         константа врала бы при смене языка и на другой ширине (урок bugs/51), а
         height: 100dvh без вычитания вытолкнул бы последний пункт «Меню» за низ
         вьюпорта — буквальная регрессия bugs/49. */
      position: sticky;
      /* ⚠️ Запасные 56px — ЗНАЮЩИЙ компромисс, а не небрежность. Не меняй, не прочитав bugs/67.
         Пока шапка не опубликовала `--bar-h` (это происходит при гидратации, окно ~3 кадра),
         CSS берёт это значение, и оно НЕИЗБЕЖНО расходится с настоящей высотой (55px на 1440).
         Обе стороны компромисса измерены:
           · 56 (завышено) → `sticky` прижимает рельс вниз, расхождение 1px при нулевой прокрутке;
           · 0  (занижено) → в том же окне при ПРОКРУТКЕ рельс липнет к нулю и заезжает ПОД шапку
             (замер 2026-07-29: `Expected: 55, Received: 0`) — регрессия bugs/49.
         1px невидим человеку, заезд под шапку — виден. Поэтому здесь остаётся завышенное
         значение, а настоящее лечение — убрать асинхронную публикацию, а не крутить константу. */
      top: var(--bar-h, 56px);
      align-self: start;
      height: calc(100vh - var(--bar-h, 56px));
      height: calc(100dvh - var(--bar-h, 56px));
      overflow-y: auto;
    }
    .rail > a {
      display: flex;
      align-items: center;
      gap: 11px;
      padding: 10px 12px;
      border-radius: 10px;
      font-size: 14px;
      text-decoration: none;
      color: var(--dim);
      transition: background 0.15s, color 0.15s;
    }
    .rail > a:hover {
      background: var(--edge-soft);
      color: var(--text);
    }
    .rail > a.on {
      background: color-mix(in srgb, var(--primary) 12%, transparent);
      color: var(--primary);
      font-weight: 650;
    }
    .ico {
      /* Ширина фиксирована, чтобы подписи пунктов стояли по одной вертикали
         независимо от того, шире или уже конкретная иконка. */
      width: 22px;
      display: flex;
      justify-content: center;
      line-height: 1;
    }
  }
</style>
