/**
 * ЧИСТАЯ ЧАСТЬ ОСТРОВА ДВЕРИ — то, что готовит его текст к вставке в страницу (`plans/75` Ш1).
 *
 * 🔴 ПОЧЕМУ ОТДЕЛЬНЫМ ФАЙЛОМ, А НЕ В СЕРВЕРНОМ ЗАГРУЗЧИКЕ — тот же довод, что у `dim-view.ts`,
 * и он про ВЕС, а не про красоту.
 *
 * Текст острова одинаков на всех 10 222 страницах. Верни его загрузчик — и он лёг бы в каждый
 * `__data.json` отдельной копией: это ровно тот класс, который уже стоил проекту 41 МБ мёртвого
 * веса в релизе. Поэтому исходник острова приходит в разметку СТАТИЧЕСКИМ импортом (`?raw`), то
 * есть лежит в сборке ОДИН раз, а загрузчик отдаёт только короткий адрес движка.
 *
 * Функции здесь чистые и без единого обращения к диску — их достаёт `node --test`, и они
 * работают в разметке, которую собирает клиентская половина Vite.
 */

/**
 * Метка конца заголовка-документации острова.
 *
 * Заголовок нужен следующей сессии и не нужен человеку: он уехал бы в каждую из 10 222 страниц.
 * Режем ПО МЕТКЕ, а не «убираем комментарии»: разбор комментариев ошибается на строках вроде
 * `'//'` внутри кавычек, а срез по метке не ошибается никогда.
 */
export const ISLAND_MARK = '/* ОСТРОВ */';

/** Убирает заголовок-документацию: в страницу уезжает только исполняемая часть. */
export function stripIslandDoc(source: string): string {
  const at = source.indexOf(ISLAND_MARK);
  return (at === -1 ? source : source.slice(at + ISLAND_MARK.length)).trim();
}

/**
 * Убирает комментарии из тела острова.
 *
 * 🔴 ЗАЧЕМ ЭТО ВООБЩЕ НУЖНО — ЗАМЕР, А НЕ ВКУС. Остров уезжает в КАЖДУЮ из 10 222 страниц.
 * С комментариями он весил 5 607 байт: это +57 МБ в сборке и +5,5 КБ в каждой странице, которую
 * читает человек с телефона. План называл потолок «~1–2 КБ», и он назван не зря. Комментарии
 * при этом нужны — следующей сессии, а не браузеру, — поэтому они живут в исходнике и режутся
 * на пути в страницу.
 *
 * ⚠️ ДОПУЩЕНИЕ, НА КОТОРОМ ДЕРЖИТСЯ ЭТОТ РАЗБОРЩИК, И ОНО ОХРАНЯЕТСЯ: в острове нет
 * РЕГУЛЯРНЫХ ВЫРАЖЕНИЙ. Разбор кавычек надёжен, разбор литерала регулярки — нет («/» после
 * скобки может быть и делением, и началом регулярки, и различить их без разбора грамматики
 * нельзя). Допущение проверяет `island-core.test.ts` отдельным тестом: появится регулярка —
 * тест покраснеет раньше, чем сборка отдаст людям испорченный скрипт. Он же доказывает, что
 * результат остаётся ИСПОЛНИМЫМ кодом, а не похожим на код текстом.
 */
export function stripComments(code: string): string {
  let out = '';
  let quote = '';
  for (let i = 0; i < code.length; i++) {
    const c = code[i];
    const next = code[i + 1];
    if (quote !== '') {
      out += c;
      if (c === '\\') {
        out += code[i + 1] ?? '';
        i++;
      } else if (c === quote) quote = '';
      continue;
    }
    if (c === '"' || c === "'" || c === '`') {
      quote = c;
      out += c;
      continue;
    }
    if (c === '/' && next === '*') {
      const end = code.indexOf('*/', i + 2);
      i = end === -1 ? code.length : end + 1;
      continue;
    }
    if (c === '/' && next === '/') {
      const end = code.indexOf('\n', i);
      i = end === -1 ? code.length : end - 1;
      continue;
    }
    out += c;
  }
  // Пустые строки, оставшиеся от вырезанных комментариев, — тот же мёртвый вес.
  return out
    .split('\n')
    .filter((line) => line.trim() !== '')
    .join('\n');
}

/**
 * Тело инлайн-скрипта двери, готовое к вставке.
 *
 * ⛔ Проверка на закрывающий тег — не паранойя, а тот же класс, что экранирование `<` в JSON-LD
 * соседнего загрузчика: строка едет ВНУТРЬ тега, и одна такая последовательность закрыла бы его
 * раньше времени, вывалив остаток кода в разметку всех страниц каталога. Сборка обязана упасть
 * здесь, а не отдать людям рваную страницу.
 */
export function doorIslandScript(source: string): string {
  const code = stripComments(stripIslandDoc(source));
  if (code === '') throw new Error('[дверь карточки] остров пуст — метка съела весь файл');
  if (/<\/script/i.test(code)) {
    throw new Error('[дверь карточки] в острове есть закрывающий тег script — он порвёт страницу');
  }
  return code;
}

