/**
 * «ДВИЖОК ДВЕРИ» — единственное, что грузит карточка каталога по первому касанию
 * (`plans/75` Ш1, пункт 2 разведки).
 *
 * Это НЕ новый движок. Оценка с карточки пишется тем же кодом, что и на страницах Теста, — он в
 * бою с 2026-08-14 и доказан там: `saveTestRating` рождает гостя при отсутствии сессии, заводит
 * ему Пространство и пишет НАСТОЯЩУЮ оценку тем же `saveRating`, что экран «Измерения».
 * Переизобретать его запрещено разведкой плана.
 *
 * Файл существует ради двух вещей:
 *   · он вход второй сборки (`vite.door.config.ts`), и его поверхность — ровно то, что нужно
 *     двери. Экспортировать `test-engine.ts` целиком нельзя: половина модуля — работа с парами
 *     теста, она утащила бы в чанк лишний код;
 *   · здесь, а не в инлайн-скрипте, живёт счётчик касания двери: модульный `$lib/data/funnel`
 *     ванильному острову недоступен, а Firebase в момент касания грузится и так.
 */

/*
 * ⚠️ ПУТИ ЗДЕСЬ ОТНОСИТЕЛЬНЫЕ, И ЭТО НЕ СТИЛЬ. Алиас `$lib` — собственность SvelteKit, а этот
 * файл собирает ВТОРОЙ конфиг Vite, который о нём не знает: сборка падает с «Rolldown failed to
 * resolve import». Поймано сборкой в тот же час, когда алиас сюда попал.
 */
import type { Lang } from '../content/langs.ts';
import { saveTestRating } from '../data/test-engine.ts';

/**
 * Касание звезды на карточке: считаем шаг воронки и пишем оценку.
 *
 * 🔴 ДВА ДЕЙСТВИЯ НЕЗАВИСИМЫ, И ЭТО КОНТРАКТ, А НЕ УДОБСТВО (dev-2, фаза 1 `plans/74`).
 * `track` возвращает обещание, никогда не бросает и не заставляет себя ждать; сцепить его с
 * записью оценки значило бы поставить оценку человека в зависимость от счётчика. Отсюда `void`:
 * счётчик уходит своей дорогой, а дверь ждёт ТОЛЬКО обещание записи.
 * Дедупликация за визит — внутри `track`: второе касание той же вкладки молчит.
 *
 * ⛔ Шага «открыл карточку» здесь нет и не будет: он тащил бы Firebase на каждый просмотр
 * SEO-поверхности ради числа, которое отдаёт Search Console (разведка `plans/75`, п. 7).
 */
export async function rateFromDoor(lang: Lang, dimId: string, value: number): Promise<string> {
  /*
   * ✅ ВКЛЮЧЕНО 2026-08-28 по сигналу Менеджера: фаза 1 `plans/74` (dev-2) влита в `main`, и
   * `FunnelStep` знает `door_click`. До мержа строка стояла закомментированной — дописать шаг
   * самому значило бы тронуть чужую зону, а привести тип к нужному было бы фродом.
   *
   * 🔴 СЧЁТЧИК СТОИТ ПОСЛЕ ЗАПИСИ ОЦЕНКИ, И ЭТО НЕ ВКУСОВЩИНА — ЭТО ЗАМЕР.
   *
   * Первая редакция звала `track('door_click')` ПЕРВОЙ строкой, до `saveTestRating`, — ровно
   * как читается контракт «считать в момент касания». Прибор двери показал ноль прироста, и
   * управляемый опыт назвал причину:
   *   · касание БЕЗ сессии (гость рождается этим же касанием): door_click 2 → 2 — потерян;
   *   · касание ПРИ живой сессии (состояние входа не меняется): door_click 2 → 3 — сосчитан.
   * Запись счётчика уходит в полёт ДО входа, а вход тут же меняет состояние авторизации —
   * Firestore рвёт канал записи (`ERR_ABORTED`), и незавершённая запись пропадает молча.
   *
   * ⚠️ Цена ошибки, если бы её не поймали: терялся бы счёт ровно того человека, ради которого
   * дверь и построена, — НЕЗНАКОМЦА ИЗ ПОИСКА, у которого сессии нет. Считались бы только
   * касания вернувшихся, и воронка врала бы владельцу в самую важную свою сторону.
   *
   * Контракт при этом соблюдён: счётчик НЕ в цепочке сохранения — он в `finally`, то есть
   * оценка его не ждёт, а он уходит `void`-ом и не может её задержать или уронить. `finally`,
   * а не «после успеха»: касание засчитывается и тогда, когда запись оценки не удалась.
   */
  try {
    return await saveTestRating(lang, dimId, value);
  } finally {
    const { track } = await import('../data/funnel.ts');
    void track('door_click');
  }
}
