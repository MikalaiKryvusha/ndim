/**
 * СТРАЖ ОСТРОВА ДВЕРИ — `plans/75` Ш3 (юнитная половина; живой клик судит прибор стенда).
 *
 * Что здесь судится и почему именно это:
 *   1. в страницу уезжает ИСПОЛНИМЫЙ код, а не похожий на код текст — вырезание комментариев
 *      делает свой разборщик, и «выглядит правильно» здесь не мера;
 *   2. допущение разборщика (в острове нет регулярных выражений) ОХРАНЯЕТСЯ, а не записано в
 *      комментарии: правило, которое держится чтением, — третий сорт лечения (`AGENT_GUIDE`);
 *   3. вес шипящего в страницу скрипта не растёт молча. У сборки обязан быть страж ВЕСА —
 *      урок `EXP-0136`: функциональные проверки этот класс не видят по построению;
 *   4. в скрипте нет закрывающего тега script — иначе он порвал бы 10 222 страницы;
 *   5. остров действительно делает то, ради чего заведён: ждёт запись перед переходом и
 *      возвращает запасную дверь, если сам упал.
 */
import assert from 'node:assert/strict';
import { test } from 'node:test';
import { readFileSync } from 'node:fs';

import { DOOR_JS_MARK, doorIslandScript, stripComments, stripIslandDoc } from './island-core.ts';

const SOURCE = readFileSync('src/lib/door/island.js', 'utf8');
const SHIPPED = doorIslandScript(SOURCE);

/**
 * Потолок веса острова В СТРАНИЦЕ. Число названо планом («инлайн-скрипт ~1–2 КБ») и умножается
 * на 10 222 страницы, поэтому оно и есть предмет охраны, а не пожелание. Запас над сегодняшним
 * размером оставлен небольшим намеренно: страж, который не может покраснеть, ничего не стережёт.
 */
const ISLAND_CEILING = 2600;

test('в страницу уезжает исполнимый код, а не похожий на код текст', () => {
  // Разбор — единственная честная проверка вырезания: испорченный синтаксис виден только тому,
  // кто попробует этот текст выполнить. `new Function` разбирает, но НЕ запускает.
  assert.doesNotThrow(() => new Function(SHIPPED), 'вырезание комментариев сломало синтаксис');
});

test('допущение разборщика охраняется: в острове нет регулярных выражений', () => {
  /*
   * Разбор кавычек надёжен, разбор литерала регулярки — нет: «/» после скобки может быть и
   * делением, и началом регулярки. Пока регулярок в острове нет, разборщик прав по построению;
   * появится первая — красным станет ЭТОТ тест, а не страница у людей.
   */
  const withoutComments = stripComments(stripIslandDoc(SOURCE));
  const suspicious = withoutComments.match(/[=(,:[]\s*\/(?![/*])/g) ?? [];
  assert.deepEqual(
    suspicious,
    [],
    'в острове появилось регулярное выражение — вырезание комментариев больше не доказано, ' +
      'либо убери регулярку, либо научи stripComments её разбирать',
  );
});

test('вес острова в странице не растёт молча', () => {
  const bytes = Buffer.byteLength(SHIPPED, 'utf8');
  assert.ok(
    bytes <= ISLAND_CEILING,
    `остров весит ${bytes} байт при потолке ${ISLAND_CEILING}; он уезжает в 10 222 страницы, ` +
      'то есть каждый лишний килобайт стоит 10 МБ сборки и лишнего трафика человеку',
  );
});

test('комментарии вырезаны, а строки продукта целы', () => {
  assert.doesNotMatch(SHIPPED, /ВАНИЛЬНЫЙ ОСТРОВ/, 'заголовок-документация уехал в страницу');
  assert.doesNotMatch(SHIPPED, /\/\*/, 'блочный комментарий уехал в страницу');
  // А вот это — работа острова, и она обязана пережить вырезание целиком.
  for (const token of [
    '[data-door]',
    '[data-star]',
    '[data-door-panel]',
    '[data-door-enter]',
    'data-engine',
    'rateFromDoor',
    'door-js',
  ]) {
    assert.ok(SHIPPED.includes(token), `вырезание съело «${token}» — остров перестал работать`);
  }
});

test('в острове нет закрывающего тега script — он порвал бы страницу', () => {
  assert.doesNotMatch(SHIPPED, /<\/script/i);
  /*
   * И сама проверка обязана уметь краснеть, иначе она украшение.
   *
   * ⚠️ Первый контрольный случай здесь был БЕССИЛЕН: `"<" + "/script>"` не содержит опасной
   * последовательности НИ ОДНИМ куском, поэтому проверка честно молчала, а тест объявлял её
   * сломанной. Это третий вопрос лестницы к зелёному прогону в чистом виде — «мог ли материал
   * дать проверке упасть»; лечится материалом, а не проверкой. Собираем строку из частей,
   * чтобы опасная последовательность жила в ЗНАЧЕНИИ, а не в тексте этого файла.
   */
  const danger = '/* ОСТРОВ */ var a = "x<' + '/script>y";';
  assert.throws(() => doorIslandScript(danger), /закрывающий тег script/);
});

test('кнопка ждёт запись, а упавший остров возвращает запасную дверь', () => {
  /*
   * Две строки, ради которых остров вообще устроен именно так, судятся текстом: живой клик
   * проверяет прибор стенда, но он требует эмуляторов и замка — а этот класс ошибок («кто-то
   * убрал ожидание») дешевле ловить здесь и на каждом прогоне.
   */
  assert.match(SHIPPED, /preventDefault/, 'переход больше не ждёт запись — оценка потеряется');
  assert.match(SHIPPED, /Promise\.race/, 'исчез потолок ожидания — дверь может не открыться');
  assert.match(
    SHIPPED,
    /classList\.remove\('door-js'\)/,
    'упавший остров больше не возвращает запасную дверь — страница осталась бы без выхода',
  );
});

test('микроскрипт головы ставит признак живого JS до первой отрисовки', () => {
  assert.equal(DOOR_JS_MARK, "document.documentElement.classList.add('door-js')");
  assert.doesNotThrow(() => new Function(DOOR_JS_MARK));
});

test('вырезание не трогает то, что стоит внутри кавычек', () => {
  const code = "/* ОСТРОВ */ var a = 'http://x'; // хвост\nvar b = '/*'; var c = \"//\";";
  const out = stripComments(stripIslandDoc(code));
  assert.match(out, /'http:\/\/x'/, 'адрес внутри кавычек принят за комментарий');
  assert.match(out, /'\/\*'/, 'звёздочка внутри кавычек принята за начало комментария');
  assert.match(out, /"\/\/"/, 'две косые внутри кавычек приняты за комментарий');
  assert.doesNotMatch(out, /хвост/, 'строчный комментарий не вырезан');
});
