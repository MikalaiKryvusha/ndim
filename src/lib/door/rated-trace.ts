/**
 * СЛЕД «ЧЕЛОВЕК ТОЛЬКО ЧТО ОЦЕНИЛ ЭТОТ ОБЪЕКТ» — от двери карточки к первому экрану внутри.
 *
 * ── ЗАЧЕМ ОН ВООБЩЕ НУЖЕН (три находки разведки `plans/82` Ш0, каждая закрывает обходной путь) ──
 *
 * 1. **У оценки НЕТ метки времени** — ни в базе, ни в памяти: документ оценки по схеме это
 *    `{ value }` и только (`schema.ts`), а `saveRating` перезаписывает его целиком. Значит
 *    «только что» из данных не выводится НИКАК, и признак обязан прийти следом.
 * 2. **Профиль не знает названий вовсе.** Из карты `ratings` экран использует ровно одну
 *    величину — её размер; каталог профиль не читает НАМЕРЕННО («это 5111 документов на каждое
 *    открытие»), а индекс каталога весит 565 911 байт. Значит название и год едут СЛЕДОМ.
 * 3. **Дверь сегодня следа не оставляет** и уходит по одной константе `/profile?guest=1` на все
 *    10 222 страницы — без идентификатора объекта. След заводится здесь впервые.
 *
 * ── СРОК ЖИЗНИ ──
 * `sessionStorage`: след умирает вместе с вкладкой, ничего не переживает закрытие браузера и
 * никуда не уезжает. Образец и обоснование — `markBridgeCrossed` в `src/lib/ui/handhold.ts`.
 * ⚠️ Не путать с запретом `sessionStorage` в памяти ВИДА экрана (решение владельца №008 В11 = А):
 * там запрет о том, что перезагрузка обязана обнулять память экрана. Здесь другой предмет.
 *
 * ── ДВА ПРАВИЛА, БЕЗ КОТОРЫХ ПРОДУКТ СОВРЁТ ──
 * · **Сверять с `ratings`.** Дверь молчит при неудачной записи и уходит в профиль по
 *   восьмисекундному потолку — то есть след может быть, а оценки в базе нет. Показать блок,
 *   не сверившись, значит утверждать человеку его же оценку, которой нет.
 * · **Гасить после первого показа.** Иначе «Вы оценили» провисит всю вкладку и через час будет
 *   утверждать то же самое.
 *
 * ── ПОЧЕМУ КЛЮЧ ЕДЕТ В ОСТРОВ АТРИБУТОМ ──
 * Остров двери — обычный скрипт без `import`, он физически не может позвать этот модуль. Копия
 * строки ключа в острове была бы ПАРОЙ, которая разъедется молча. Поэтому ключ отдаётся острову
 * `data`-атрибутом из разметки: истина остаётся здесь одна.
 */

/** Ключ следа. Единственное место, где он написан. */
export const RATED_TRACE_KEY = 'ndim-rated-just-now';

/** Что дверь рассказывает первому экрану о жесте человека. */
export type RatedTrace = {
  /** Идентификатор измерения — по нему блок сверяется с оценками человека. */
  id: string;
  /** Название объекта целиком: закон «названия не обрезаются» (слово владельца 2026-08-14). */
  title: string;
  /** Год. Пустая строка, когда года у объекта нет, — поле тогда не показывается. */
  year: string;
  /** Вид объекта человеческими словами: «Фильм», «Роман», «Видеоигра». */
  kind: string;
  /** Отметка человека, 0…10. Ноль — ЗАКОННАЯ оценка, а не «не оценивал». */
  value: number;
};

/**
 * Разбирает след из строки хранилища. Чистая функция: её и судят юниты.
 *
 * Молчит на любом мусоре — след это подсказка, а не опора, и падать из-за него первый экран
 * человека не имеет права.
 */
export function parseRatedTrace(raw: string | null): RatedTrace | null {
  if (!raw) return null;
  let данные: unknown;
  try {
    данные = JSON.parse(raw);
  } catch {
    return null;
  }
  if (typeof данные !== 'object' || данные === null) return null;
  const т = данные as Record<string, unknown>;
  const id = typeof т.id === 'string' ? т.id : '';
  const title = typeof т.title === 'string' ? т.title : '';
  const value = typeof т.value === 'number' ? т.value : NaN;
  // Без идентификатора сверить не с чем, без названия показывать нечего, без отметки нечего
  // утверждать. Отметка 0…10 включительно: ноль — осознанная оценка человека.
  if (id === '' || title === '' || !Number.isFinite(value) || value < 0 || value > 10) return null;
  return {
    id,
    title,
    year: typeof т.year === 'string' ? т.year : '',
    kind: typeof т.kind === 'string' ? т.kind : '',
    value,
  };
}

/** Читает след вкладки. Хранилище недоступно (приватный режим) — следа просто нет. */
export function readRatedTrace(): RatedTrace | null {
  try {
    return parseRatedTrace(sessionStorage.getItem(RATED_TRACE_KEY));
  } catch {
    return null;
  }
}

/**
 * Гасит след. Зовётся СРАЗУ после того, как первый экран его прочитал: блок про «только что»,
 * и второй показ той же вкладке был бы неправдой.
 */
export function clearRatedTrace(): void {
  try {
    sessionStorage.removeItem(RATED_TRACE_KEY);
  } catch {
    /* хранилище недоступно — гасить нечего */
  }
}

/**
 * ГОТОВЫЙ СЛЕД ДЛЯ ПРЕРЕНДЕРА — собирается ЗДЕСЬ, а не в острове двери.
 *
 * 🔴 Форма выбрана ЦЕНОЙ. Первая редакция читала четыре `data`-атрибута и собирала JSON прямо
 * в острове: плюс 526 байт кода × 10 222 страницы = 5,4 МБ сборки и лишнего трафика людям.
 * Страж веса острова (`island-core.test.ts`) её завернул, и правильно сделал.
 * Теперь всю сборку делает пререндер — здесь, один раз на страницу, — а острову остаётся
 * подставить отметку человека вместо `%v`: два чтения атрибута и одна замена.
 *
 * ⚠️ Результат — НЕ валидный JSON до подстановки, и это намеренно: `%v` — наш плейсхолдер,
 * единственный его потребитель — остров двери. `parseRatedTrace` увидит уже подставленное.
 */
export function ratedTraceTemplate(dim: {
  id: string;
  title: string;
  year?: string | number | null;
  kind?: string | null;
}): string {
  const тело = JSON.stringify({
    id: dim.id,
    title: dim.title,
    year: dim.year === null || dim.year === undefined ? '' : String(dim.year),
    kind: dim.kind ?? '',
  });
  // Отметка приписывается последним полем: остров меняет ровно `%v` и ничего больше.
  return тело.slice(0, -1) + ',"value":%v}';
}
