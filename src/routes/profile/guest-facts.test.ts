/**
 * СТРАЖ СРОКА ЖИЗНИ ГОСТЯ НА ЛИЦЕ ПРОДУКТА — приёмка `bugs/201`.
 *
 * Дефект, ради которого страж существует: карточка гостя обещала «30 дней», а сервер
 * синхронизации стирал гостя через семь. Число стояло в тексте ЛИТЕРАЛОМ, поэтому греп по
 * имени константы его не видел, и правка срока (`plans/63`, слово владельца №010 Р3) прошла
 * мимо — экран истёкшей сессии починили, а карточку нет. Класс назван в аудите (`bugs/156`):
 * «копия класса пережила чистку класса».
 *
 * ⚠️ ПОЧЕМУ ПРОВЕРКА ЧИТАЕТ ИСХОДНИК, А НЕ РЕНДЕР. Тексты живут в объекте внутри
 * `+page.svelte`, и вытащить их отсюда без сборки Svelte нечем. Прецедент этого проекта —
 * `dims-rating.test.ts`: разойтись копии могут только ТЕКСТОМ, поэтому текстом их и судят.
 * Граница честная: страж судит ИСТОЧНИК строки, а не пиксель. Пиксель судит кадр карточки
 * гостя на стенде — он назван в приёмке `bugs/201` и заменой этому стражу не является.
 *
 * Чем страж обязан краснеть (проверено мутациями, числа — в отчёте задачи):
 *   1. вернуть литерал: `в течение 30 дней` вместо `${GUEST_TTL_DAYS}` → падение;
 *   2. любое НОВОЕ число дней литералом в текстах гостя → падение;
 *   3. сменить `GUEST_TTL_DAYS` → ожидаемая строка едет за константой, оба экрана обязаны
 *      сказать новый срок; экран, отставший от константы, роняет проверку.
 */
import assert from 'node:assert/strict';
import { test } from 'node:test';
import { readFileSync } from 'node:fs';

import { GUEST_TTL_DAYS } from '../../lib/model/schema.ts';

const FILE = 'src/routes/profile/+page.svelte';

/**
 * Исходник без комментариев: разборы дефектов законно называют старое число словами
 * («здесь стояло 30 дней»), и судить их наравне с живым текстом значило бы запретить
 * объяснять собственные баги.
 */
const code = readFileSync(FILE, 'utf8')
  .replace(/<!--[\s\S]*?-->/g, ' ')
  .replace(/\/\*[\s\S]*?\*\//g, ' ');

/** Строки-тексты, показывающие человеку срок жизни гостя. Обе половины, оба экрана. */
const LIFETIME_LINES = [
  /*
   * 🔄 ОБРАЗЦЫ ОБНОВЛЕНЫ 2026-09-09 ПОД ТЕКСТ ВЛАДЕЛЬЦА (интервью №080 В1 = Г). Прежние искали
   * фразу «Если Вы не вернётесь в течение …, мы удалим», и когда она была заменена как ЛОЖНАЯ,
   * страж честно покраснел словами «строка не найдена — текст переписан, страж ослеп». Это его
   * работа: молчаливый зелёный на исчезнувшей строке был бы дырой, а не удобством.
   */
  { where: 'карточка гостя · fact3 · ru', find: /Гостевой аккаунт живёт ([^ ]+) дней от дня создания/ },
  { where: 'карточка гостя · fact3 · en', find: /A guest account lives (.+?) days from the day/ },
  { where: 'экран истёкшей сессии · lede · ru', find: /Гостевой профиль живёт (.+?) с момента создания/ },
  { where: 'экран истёкшей сессии · lede · en', find: /A guest profile lives for (.+?) from creation/ },
];

test('срок жизни гостя на всех экранах берётся из GUEST_TTL_DAYS, а не литералом', () => {
  for (const line of LIFETIME_LINES) {
    const hit = code.match(line.find);
    assert.ok(hit, `${line.where}: строка не найдена — текст переписан, страж ослеп, поправь его`);
    assert.match(
      hit[1],
      /\$\{GUEST_TTL_DAYS\}/,
      `${line.where}: срок стоит литералом «${hit[1]}» — он разойдётся с константой молча, как в bugs/201`,
    );
  }
});

test('смена константы уводит за собой ОБА экрана — рендер срока сходится с GUEST_TTL_DAYS', () => {
  // Подставляем настоящее значение константы ровно так, как это сделает Svelte, и читаем то,
  // что увидит человек. Ожидание выводится ИЗ константы, поэтому мутация константы двигает и
  // ожидание, и обе стороны обязаны за ним поспеть.
  for (const line of LIFETIME_LINES) {
    const rendered = code.match(line.find)![1].replaceAll('${GUEST_TTL_DAYS}', String(GUEST_TTL_DAYS));
    assert.match(
      rendered,
      new RegExp(`\\b${GUEST_TTL_DAYS}\\b`),
      `${line.where}: человек видит «${rendered}», а гость живёт ${GUEST_TTL_DAYS} дней`,
    );
  }
});

test('в текстах гостя не осталось ни одного числа дней литералом', () => {
  /*
   * Греп по ФОРМЕ, а не по имени константы, — это и есть лечение класса `bugs/156`. Ищем
   * «<цифры> дн…/days» в самих текстах; интерполяция под этот признак не подпадает по
   * построению, потому что цифр в ней нет.
   *
   * Окно сужено до блоков `guest:` и `expired:`: витрина «Пространства» законно считает
   * «Новых за последние 30 дней» — это окно статистики, а не срок жизни гостя, и путать их
   * нельзя.
   */
  const region = code.slice(code.indexOf('expired: {'), code.indexOf('leaveTitle:'));
  assert.ok(region.length > 200, 'область текстов гостя не найдена — поправь границы стража');

  const literals = [...region.matchAll(/(\d+)\s*(дней|дня|дн\.|days)\b/g)].map((m) => m[0]);
  assert.deepEqual(
    literals,
    [],
    `срок жизни гостя стоит числом: ${literals.join(' · ')} — он обязан приходить из GUEST_TTL_DAYS`,
  );
});

/*
 * 🔴 СТРАЖ ОТМЕНЁННОГО ПРАВИЛА — приёмка `bugs/227`.
 *
 * Дефект, ради которого страж существует: карточка гостя утверждала «Вас никто не видит: в
 * Пространстве Вы невидимы». Правило «гость невидим» (№004 В3 = А) владелец ОТМЕНИЛ ответом
 * №009 В5 от 2026-08-01, а строка прожила на лице продукта ещё месяц — при зелёных воротах,
 * потому что текст и код были СОГЛАСНЫ между собой и расходились только с решением владельца.
 * Убрать строку велел он сам (№069 В2 = А, 2026-08-30), подтвердил повторно 2026-09-09:
 * «*это фрод. Тысячу раз обсуждали*».
 *
 * Почему страж, а не запись в журнале: запись — третий сорт лечения (`AGENT_GUIDE.md` →
 * «Журнал опыта»), и по этому самому тексту она уже не сработала — правку написали в ветке,
 * ветку не влили, а эстафета объявила дело сделанным. Красная проверка не забывается.
 *
 * ⚠️ ОКНО — тексты гостя целиком, включая комментарии: разбор дефекта законно цитирует
 * убранную строку, поэтому судится не файл, а живой РЕНДЕР — список `guest-facts` и
 * объявление самих текстов без комментариев.
 */
test('отменённое правило «гость невидим» на лицо продукта не возвращается', () => {
  /*
   * ОКНО — блок текстов `guest:` целиком. Оно выбрано не для удобства: снаружи блока живёт
   * `account.doneNote` («Вас по-прежнему не видит никто»), и он говорит о ДРУГОМ предмете —
   * об умолчании видимости у ВОШЕДШЕГО человека («скрыть», решение владельца 2026-07-10),
   * а не об отменённом правиле для гостя. Запрет по всему файлу смешал бы два факта и
   * заставил бы будущую сессию «чинить» правдивую строку. Судьба `doneNote` — вопрос
   * владельцу, а не догадка стража.
   */
  const guestBlock = code.slice(code.indexOf('guest: {'), code.indexOf('account: {'));
  assert.ok(guestBlock.length > 500, 'блок текстов гостя не найден — поправь границы стража');

  /*
   * 🔴 ОБРАЗЦЫ СУДЯТ СМЫСЛ, А НЕ ФРАЗУ. Первая редакция искала «никто не видит» — и вторая
   * мутация («Пока Вы гость, Вас **не видит никто**») прошла НЕЗАМЕЧЕННОЙ: русский порядок
   * слов свободен, а образец был отпечатком одной формулировки. Это третий вопрос лестницы
   * зелёного прогона (`AGENT_GUIDE.md`): проверка обязана МОЧЬ покраснеть на этом материале.
   * Поэтому оба слова ищутся в любом порядке, в окне одного предложения.
   */
  const BANNED = [
    { ru: /никто[^.!?]{0,40}не\s+вид|не\s+вид[^.!?]{0,40}никто/i, en: /nobody sees you|no one sees you/i, what: 'Вас никто не видит' },
    { ru: /невидим/i, en: /you are invisible/i, what: 'Вы невидимы' },
  ];
  for (const line of BANNED) {
    for (const half of ['ru', 'en'] as const) {
      assert.doesNotMatch(
        guestBlock,
        line[half],
        `отменённое правило вернулось на экран («${line.what}», ${half}): решение владельца №069 В2 = А, разбор — bugs/227`,
      );
    }
  }
});

test('список фактов гостя показывает РОВНО два пункта — сохранность и срок', () => {
  /*
   * Пара к проверке выше: она запрещает ТЕКСТ, эта — сторожит СОСТАВ. Без неё третий пункт
   * можно вернуть под любой другой формулировкой о видимости, и запрет по словам промолчит.
   * Число «два» — решение владельца, а не вкус: строка о видимости убрана совсем.
   */
  const source = readFileSync(FILE, 'utf8');
  const list = source.match(/<ul class="guest-facts">([\s\S]*?)<\/ul>/);
  assert.ok(list, 'список фактов гостя не найден — вёрстка переписана, поправь стража');
  const items = [...list[1].matchAll(/<li>/g)].length;
  assert.equal(items, 2, `в списке фактов гостя пунктов: ${items}, а решением владельца их два`);
});
