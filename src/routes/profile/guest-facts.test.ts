/**
 * СТРАЖ СРОКА ЖИЗНИ ГОСТЯ НА ЛИЦЕ ПРОДУКТА — приёмка `bugs/201`.
 *
 * Дефект, ради которого страж существует: карточка гостя обещала «30 дней», а сервер
 * синхронизации стирал гостя через семь. Число стояло в тексте ЛИТЕРАЛОМ, поэтому греп по
 * имени константы его не видел, и правка срока (`plans/63`, слово владельца №010 Р3) прошла
 * мимо — экран истёкшей сессии починили, а карточку нет. Класс назван в аудите (`bugs/156`):
 * «копия класса пережила чистку класса».
 *
 * ⚠️ ПОЧЕМУ ПРОВЕРКА ЧИТАЕТ ИСХОДНИК, А НЕ РЕНДЕР. Тексты живут в объекте внутри
 * `+page.svelte`, и вытащить их отсюда без сборки Svelte нечем. Прецедент этого проекта —
 * `dims-rating.test.ts`: разойтись копии могут только ТЕКСТОМ, поэтому текстом их и судят.
 * Граница честная: страж судит ИСТОЧНИК строки, а не пиксель. Пиксель судит кадр карточки
 * гостя на стенде — он назван в приёмке `bugs/201` и заменой этому стражу не является.
 *
 * Чем страж обязан краснеть (проверено мутациями, числа — в отчёте задачи):
 *   1. вернуть литерал: `в течение 30 дней` вместо `${GUEST_TTL_DAYS}` → падение;
 *   2. любое НОВОЕ число дней литералом в текстах гостя → падение;
 *   3. сменить `GUEST_TTL_DAYS` → ожидаемая строка едет за константой, оба экрана обязаны
 *      сказать новый срок; экран, отставший от константы, роняет проверку.
 */
import assert from 'node:assert/strict';
import { test } from 'node:test';
import { readFileSync } from 'node:fs';

import { GUEST_TTL_DAYS } from '../../lib/model/schema.ts';

const FILE = 'src/routes/profile/+page.svelte';

/**
 * Исходник без комментариев: разборы дефектов законно называют старое число словами
 * («здесь стояло 30 дней»), и судить их наравне с живым текстом значило бы запретить
 * объяснять собственные баги.
 */
const code = readFileSync(FILE, 'utf8')
  .replace(/<!--[\s\S]*?-->/g, ' ')
  .replace(/\/\*[\s\S]*?\*\//g, ' ');

/** Строки-тексты, показывающие человеку срок жизни гостя. Обе половины, оба экрана. */
const LIFETIME_LINES = [
  { where: 'карточка гостя · fact3 · ru', find: /Если Вы не вернётесь в течение ([^,]+), мы удалим/ },
  { where: 'карточка гостя · fact3 · en', find: /If you do not come back within (.+?), we erase/ },
  { where: 'экран истёкшей сессии · lede · ru', find: /Гостевой профиль живёт (.+?) с момента создания/ },
  { where: 'экран истёкшей сессии · lede · en', find: /A guest profile lives for (.+?) from creation/ },
];

test('срок жизни гостя на всех экранах берётся из GUEST_TTL_DAYS, а не литералом', () => {
  for (const line of LIFETIME_LINES) {
    const hit = code.match(line.find);
    assert.ok(hit, `${line.where}: строка не найдена — текст переписан, страж ослеп, поправь его`);
    assert.match(
      hit[1],
      /\$\{GUEST_TTL_DAYS\}/,
      `${line.where}: срок стоит литералом «${hit[1]}» — он разойдётся с константой молча, как в bugs/201`,
    );
  }
});

test('смена константы уводит за собой ОБА экрана — рендер срока сходится с GUEST_TTL_DAYS', () => {
  // Подставляем настоящее значение константы ровно так, как это сделает Svelte, и читаем то,
  // что увидит человек. Ожидание выводится ИЗ константы, поэтому мутация константы двигает и
  // ожидание, и обе стороны обязаны за ним поспеть.
  for (const line of LIFETIME_LINES) {
    const rendered = code.match(line.find)![1].replaceAll('${GUEST_TTL_DAYS}', String(GUEST_TTL_DAYS));
    assert.match(
      rendered,
      new RegExp(`\\b${GUEST_TTL_DAYS}\\b`),
      `${line.where}: человек видит «${rendered}», а гость живёт ${GUEST_TTL_DAYS} дней`,
    );
  }
});

test('в текстах гостя не осталось ни одного числа дней литералом', () => {
  /*
   * Греп по ФОРМЕ, а не по имени константы, — это и есть лечение класса `bugs/156`. Ищем
   * «<цифры> дн…/days» в самих текстах; интерполяция под этот признак не подпадает по
   * построению, потому что цифр в ней нет.
   *
   * Окно сужено до блоков `guest:` и `expired:`: витрина «Пространства» законно считает
   * «Новых за последние 30 дней» — это окно статистики, а не срок жизни гостя, и путать их
   * нельзя.
   */
  const region = code.slice(code.indexOf('expired: {'), code.indexOf('leaveTitle:'));
  assert.ok(region.length > 200, 'область текстов гостя не найдена — поправь границы стража');

  const literals = [...region.matchAll(/(\d+)\s*(дней|дня|дн\.|days)\b/g)].map((m) => m[0]);
  assert.deepEqual(
    literals,
    [],
    `срок жизни гостя стоит числом: ${literals.join(' · ')} — он обязан приходить из GUEST_TTL_DAYS`,
  );
});
