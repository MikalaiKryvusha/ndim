  async function signIn(method: 'google' | 'email') {
    signupError = '';

    if (method === 'google') {
      signupStep = 'linking';
      const result = await continueWithGoogle();
      if (!result.ok) {
        signupError = t.account.errors[result.reason][lang];
        signupStep = 'facts';
        return;
