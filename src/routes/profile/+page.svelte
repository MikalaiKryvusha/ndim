  /**
   * Возврат по почтовой ссылке. Показывает карточку в состоянии «подтверждаем»,
   * привязывает почту к текущей (гостевой) сессии и чистит адрес: коды из ссылки
   * одноразовые, при перезагрузке страницы они дали бы ложную ошибку.
   */
  async function finishEmailLink(): Promise<string | null> {
    guest = true;
    guestCard = true;
    signupStep = 'linking';

    const session = await waitForSession();

    /*
     * ПУТЬ ВЫБИРАЕТ НАМЕРЕНИЕ, А НЕ СЕССИЯ (bugs/84, интервью №007 В4).
     *
     * Человек нажал «У меня уже есть аккаунт» — значит он идёт ДОМОЙ, а не превращает гостя
     * в аккаунт. Гостевую сессию отпускаем здесь, до `completeLoginLink`: тогда та уходит в
     * ветку `signInWithEmailLink`, и почта, которая «уже связана с другим профилем», это
     * просто его собственная почта.
     *
     * Выход делаем именно `signOutUser()`, а не голым `signOut`: он же чистит кэш экранов и
     * скачанные лица. Без этого в памяти вкладки остались бы данные гостя, а войти в неё
     * собирается другой человек — прямая дыра приватности (`cache.ts` → «ПРИВАТНОСТЬ»).
     *
     * Труд гостя при этом отпускается осознанно: слить два профиля нельзя, чьи-то оценки
     * пришлось бы выбросить. Именно поэтому дверь спрашивает подтверждение ДО письма.
     */
    /*
     * 🔴 `released` — не украшение, а память о том, что `session` УЖЕ МЁРТВА.
     *
     * `session` объявлена `const` и хранит снимок ДО выхода. Ветки отказа ниже возвращали
     * `session.uid` не глядя — то есть UID сессии, которую эта же функция строкой выше и
     * отпустила. Дальше `loadScreen()` шёл читать данные от имени никого, правила отвечали
     * отказом, и человек с протухшей ссылкой видел «Не удалось загрузить данные» вместо
     * честного «ссылка устарела, запросите новую». Дефект ложного диагноза: настоящая
     * причина (ссылка) подменялась выдуманной (база).
     *
     * Поймано состязательной проверкой 01.08.2026, живьём не воспроизводилось.
     */
    const intent = pendingIntent();
    const released = intent === 'signin' && session?.isAnonymous === true;
    if (released) await signOutUser();

    const result = await completeLoginLink();
    replaceUrl('/profile');

    if (result.ok) {
      guest = false; // сессия больше не гостевая: пилюля гостя и запреты уходят
      if (result.created) {
        // Аккаунт родился только что (апгрейд гостя или первый вход новичка) —
        // единственный случай, когда поздравление уместно.
        signupStep = 'done';
        void track('account_created'); // четвёртый шаг воронки — путь пройден
      } else {
        // Обычный вход существующего человека (331 из 1.x входят именно так):
        // поздравлять его с «регистрацией» не с чем — сразу его профиль (bugs/08.2).
        // Воронку тоже не трогаем: вход — не создание аккаунта.
        guestCard = false;
        signupStep = 'facts';
      }
      return result.uid;
    }

    /*
     * ОТКАЗ «ПОЧТА УЖЕ ЗАНЯТА» — ЭТО НЕ ОШИБКА, А ОБНАРУЖЕННЫЙ ФАКТ (bugs/84, половина «б»).
     *
     * Раньше он дописывался КРАСНОЙ СТРОКОЙ внутрь карточки под заголовком «Сейчас Вы гость —
     * Ваши результаты не сохранены», и владелец видел один экран, который не решил, что он
     * такое: «не понимает разницы между гостем и попыткой использовать чужой email».
     *
     * Теперь карточка переходит в ОТДЕЛЬНОЕ состояние `mine?` с развилкой: «это мой аккаунт —
     * войти в него» или «указать другую почту». Двух состояний в одной карточке больше нет.
     */
    if (result.reason === 'already-in-use') {
      signupStep = 'mine?';
      // При отпущенной сессии этот отказ не рождается (без гостя идёт `signInWithEmailLink`,
      // а он про «занято» не знает) — но возвращать мёртвый UID нельзя и здесь.
      if (session && !released) return session.uid;
      if (released) return null;
      const uid = await signInGuest();
      await ensureSpaceExists(uid, lang);
      return uid;
    }

    signupError = t.account.errors[result.reason][lang];
    signupStep = 'choose';
    // Ссылка не сработала, но человек всё ещё в своей гостевой сессии — показываем
    // ему его же профиль, а не выкидываем на пустой экран.
    if (session && !released) return session.uid;
    /*
     * Сессию отпустили, а ссылка не сработала. Заводить взамен НОВОГО гостя нельзя: человек
     * шёл ВХОДИТЬ в существующий аккаунт, и пустая анонимная сессия снова соврала бы ему о
     * том, кто он. `null` уводит экран в `signedout`, где уже стоят и форма почты, и красная
     * строка `signupError` — то есть честная причина и возможность запросить письмо заново.
     */
    if (released) return null;
    const uid = await signInGuest();
    await ensureSpaceExists(uid, lang);
    return uid;
  }

