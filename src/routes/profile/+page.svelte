  onMount(async () => {
    try {
      let uid: string | null;
      // Человек вернулся по ссылке из письма. Если он был гостем — почта привязывается
      // к его же сессии (UID и труд сохраняются). Если сессии нет — это вход человека,
      // который у нас уже есть: 331 человек из 1.x входит именно так, и вход по ссылке
      // ЗАОДНО подтверждает им почту.
      if (isLoginLink()) {
        uid = await finishEmailLink();
        // Вход не состоялся, а гостевую сессию под него уже отпустили: показываем экран
        // входа с причиной, а не идём читать базу от имени никого (см. `released` ниже).
        if (uid === null) {
          stand = 'signedout';
          return;
        }
      } else if (new URLSearchParams(location.search).has('guest')) {
        /*
         * Дверь «Продолжить гостем» УВАЖАЕТ живую сессию (bugs/95). Раньше ветка звала
         * signInAnonymously ПЕРВОЙ, и у вошедшего человека (F5 сразу после апгрейда,
         * закладка /profile?guest=1) Firebase заводил НОВОГО анонима, молча выбрасывая
         * настоящий аккаунт из сессии. Порядок — как у стендовой двери `?as=guest`:
         * сначала смотрим, кто за экраном.
         */
        const session = await waitForSession();
        if (session !== null && !session.isAnonymous) {
          uid = session.uid; // живой аккаунт: параметр гостя игнорируется, это обычный заход
          guest = false;
        } else {
          // Анонимная сессия переиспользуется (труд гостя не теряется); новый гость
          // заводится только когда сессии нет вовсе — и только он шаг воронки.
          uid = session?.uid ?? (await signInGuest());
          await ensureSpaceExists(uid, lang);
          guest = true;
          guestCard = localStorage.getItem(GUEST_CARD_KEY) !== 'later';
          if (session === null) void track('guest_start'); // третий шаг воронки (plans/03 этап 4)
        }
        // Параметр одноразовый: F5 и закладка не должны нести его дальше (тот же приём,
        // что очистка адреса в finishEmailLink). Остальные параметры (?db=, двери стенда)
        // не трогаем — вырезается только guest.
        const url = new URL(location.href);
        url.searchParams.delete('guest');
        replaceUrl(url.pathname + url.search + url.hash);
      } else {
        // Стенд входит сам; в бою — только существующая сессия. Её нет — предлагаем войти,
        // а не заводим человеку анонимную сессию за его спиной.
        uid = await currentSession();
        if (uid === null) {
          stand = 'signedout';
          return;
        }
        guest = isGuestSession();
        guestCard = guest && localStorage.getItem(GUEST_CARD_KEY) !== 'later';
      }
      await loadScreen(uid);
    } catch (error) {
      /*
       * У ГОСТЯ ДОКУМЕНТА МОЖЕТ НЕ БЫТЬ, И ЭТО НОРМА (bugs/87; обработка переехала сюда
       * из «Меню» вместе с виджетом «Аккаунт», ideas/19). В бою гость всегда с документом
       * (?guest=1 заводит его сразу) — это стендовая дверь ?as=guest; но «Выйти» обязан
       * быть доступен гостю и здесь, иначе реплей замка bugs/84.
       */
      if (isGuestSession() && error instanceof ProfileMissingError) {
        /*
         * За одним симптомом — ДВА состояния, и путать их нельзя (plans/63 шаг 5):
         * свежий гость без документа — норма; ИСТЁКШИЙ гость — его документы унесла
         * уборка (7 дней от рождения, №010 Р3), и пустой продукт без объяснения — это
         * дефект класса bugs/84, только злее: человек вошёл в пустоту.
         */
        if (isExpiredGuestSession()) {
          stand = 'expired';
          return;
        }
        guest = true;
        acctEmail = currentEmail();
        stand = 'ready';
        return;
      }
      standError = technicalDetail(error);
      stand = 'down';
    }
  });

