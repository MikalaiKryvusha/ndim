<script lang="ts">
  /**
   * ЯЗЫКОВОЙ СЕГМЕНТ ПУБЛИЧНОГО САЙТА — здесь живёт МОСТ «адрес → память» (`plans/39` шаг 1–2).
   *
   * 🔴 Публичный адрес не просто читается — он ЗАПИСЫВАЕТ язык в память браузера. За стеной
   * входа языковых адресов нет (`/profile`, `/dims`, … под `noindex`), поэтому без моста
   * человек, пришедший из поиска на `/ru/…`, провалился бы внутрь приложения на языке своей
   * старой памяти (или английского браузера). Одно место на ВСЕ публичные страницы — чтобы
   * каждая не помнила об этом сама.
   *
   * ⚠️ На страницах каталога (`[lang=lang]/dimension/[slug]`, `csr = false`) этот код не
   * исполняется вовсе — у них нет клиентского JS по построению, и дверь в продукт там ведёт
   * на корень-распознаватель, который смотрит память и браузер. Мост работает там, где есть
   * гидратация: лендинг, документы, страница удаления.
   *
   * `$effect`, а не `onMount`: при КЛИЕНТСКОМ переходе `/ru/…` → `/en/…` (переключатель языка)
   * страница не перемонтируется — а память обязана пойти за адресом и в этом случае тоже.
   */
  import { page } from '$app/state';
  import { adoptLangFromPath } from '$lib/ui/lang.svelte';

  let { children } = $props();

  $effect(() => {
    adoptLangFromPath(page.url.pathname);
  });
</script>

{@render children()}
