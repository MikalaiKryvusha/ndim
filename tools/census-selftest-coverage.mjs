/**
 * Снятие комментариев. 🔴 Несущая деталь, а не гигиена: без неё прибор, лишь УПОМИНАЮЩИЙ
 * `--selftest` в прозе, считался бы носителем. Таких в дереве трое.
 */
export function безКомментариев(текст) {
  return текст.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/.*$/gm, '$1');
}

/**
 * Несёт ли прибор самотест — по ДИСПЕТЧЕРИЗАЦИИ, а не по наличию строки.
 *
 * 🔴 ТРЕТЬЕ УТОЧНЕНИЕ ПРИЗНАКА, И ОНО ОПЛАЧЕНО ЛОЖНЫМ КРАСНЫМ НА ЧУЖОЙ РАБОТЕ.
 * Первая редакция считала носителем всякий прибор, чей исполняемый текст СОДЕРЖИТ `--selftest`.
 * После мержа порции dev-1 страж покраснел «ДОЛГ ВЫРОС: selftest-pair.mjs» — а это его
 * ПОМОЩНИК, который сам самотеста не имеет и лишь ПЕРЕДАЁТ флаг чужим приборам:
 *   `spawnSync(process.execPath, [путь, '--selftest', ...argv])`.
 * Строка есть, самотеста нет. Страж потребовал бы пару к файлу, которому она не нужна, — то есть
 * отправил бы человека делать лишнюю работу за мой дефект.
 * 🔑 Класс мой собственный, дневной: признак судил ФОРМУ (есть ли подстрока), а вопрос был о
 * СУЩЕСТВЕ (разбирает ли прибор этот флаг). Замер по корпусу: содержат строку 34, диспетчеризуют
 * 32; двое лишних — `guards.mjs` и `selftest-pair.mjs`, оба флаг только передают.
 *
 * Признак: флаг стоит ЕДИНСТВЕННЫМ доводом вызова — `argv.includes('--selftest')`,
 * `flag('--selftest')`. В массиве доводов запуска (`[путь, '--selftest', ...argv]`) он так не
 * стоит, и передача больше не читается как владение.
 */
const ДИСПЕТЧЕР = /[\w.]+\(\s*['"]--selftest['"]\s*\)/;

export function несётСамотест(текст) {
  return ДИСПЕТЧЕР.test(безКомментариев(текст));
}

function файлыКаталога(корень, подкаталоги) {
  const итог = [];
  for (const к of подкаталоги) {
    const путь = join(корень, к);
    for (const f of readdirSync(путь)) {
      const п = join(путь, f);
      if (statSync(п).isFile()) итог.push(п);
    }
  }
  return итог;
}

function обходГлубже(корень, итог = []) {
  for (const f of readdirSync(корень)) {
    const п = join(корень, f);
    if (statSync(п).isDirectory()) {
      if (f !== 'node_modules') обходГлубже(п, итог);
    } else итог.push(п);
  }
  return итог;
}

/** Перепись. Чистая функция от КОРНЯ дерева — поэтому её зовут на поддельных деревьях. */
export function перепись(корень) {
  const вTools = файлыКаталога(корень, ['tools', join('tools', 'lib')]).filter((п) => п.endsWith('.mjs'));
  const приборы = вTools.filter((п) => !п.endsWith('.test.mjs'));

  const парные = new Set();
  for (const п of вTools.filter((x) => x.endsWith('.test.mjs'))) парные.add(basename(п).replace(/\.test\.mjs$/, ''));
  for (const п of обходГлубже(join(корень, 'src')).filter((x) => x.endsWith('.test.ts'))) {
    парные.add(basename(п).replace(/\.test\.ts$/, ''));
  }

  const носители = приборы.filter((п) => несётСамотест(readFileSync(п, 'utf8')));
  const безПары = (п) => !парные.has(basename(п).replace(/\.mjs$/, ''));
  // ⚠️ не `.map(basename)`: map отдаёт вторым доводом ИНДЕКС, а basename берёт его за suffix.
  const группаА = носители.filter(безПары).map((п) => basename(п)).sort();

  /*
   * ГРУППА Б — приборы, СТОЯЩИЕ В ВОРОТАХ и не имеющие парного теста.
   * 🔴 Заведена по находке dev-1 (смена 14), и она закрывает СЛЕПУЮ ЗОНУ группы А. Признак
   * «несёт --selftest и не имеет пары» пропускает прибор, у которого самотеста нет ВОВСЕ:
   * он не попадает в список по первому условию, а защищён не лучше прочих — хуже, потому что
   * у него нет даже самотеста, который можно позвать. Таких в воротах двое:
   * `verify-sync-server-name` и `qa-journeys-lint`. Проверено моей рукой, не на слово.
   * 🔑 Класс ровно тот, против которого храповик и написан: СПИСОК МОЛЧИТ О ТОМ, ЧЕГО В НЁМ НЕТ.
   */
  const вВоротах = составВорот(корень);
  const группаБ = вВоротах.filter(безПары).map((п) => basename(п)).sort();
  const долг = [...new Set([...группаА, ...группаБ])].sort();
  return { носителей: носители.length, вВоротах: вВоротах.length, группаА, группаБ, долг };
}

/**
 * Состав ворот — пути приборов из `GUARDS` в `tools/guards.mjs`.
 * ⚠️ Первая запись состава — `--test tools/*.test.mjs`, то есть САМ ПРОГОН ЮНИТОВ, а не прибор;
 * ворота печатают её наравне со стражами, отчего «стражей 15» читается как «приборов 15».
 * Приборов 14. Отличаем по расширению `.mjs` в первом доводе (находка dev-1, проверена мной).
 */
export function составВорот(корень) {
  const текст = readFileSync(join(корень, 'tools', 'guards.mjs'), 'utf8');
  return [...текст.matchAll(/argv:\s*\[([^\]]*)\]/g)]
    .map((m) => m[1].replace(/['"\s]/g, '').split(',')[0])
    .filter((п) => п.endsWith('.mjs'))
    .map((п) => join(корень, п));
}

/** Приговор храповика: вырос — красный; протух — тоже красный, лечение другое. */
export function судХраповика(долг, храповик = ХРАПОВИК) {
  const сейчас = new Set(долг);
  const было = new Set(храповик);
  const появились = [...сейчас].filter((и) => !было.has(и)).sort();
  const ушли = [...было].filter((и) => !сейчас.has(и)).sort();
  return { появились, ушли, чисто: появились.length === 0 && ушли.length === 0 };
}

function печать(итог) {
  console.log(
    `Приборов с самотестом: ${итог.носителей} · приборов в воротах: ${итог.вВоротах} · ` +
      `ДОЛГ (без парного теста): ${итог.долг.length} — группа А (несут самотест) ${итог.группаА.length} · ` +
      `группа Б (стоят в воротах) ${итог.группаБ.length}`,
  );
  console.log(
    '⚠️ «Имеет пару» — ФОРМА, не доказательство исполнения: замером покрытия 2026-08-30 самотест ' +
      'реально исполняется у 8 из 31, и шесть приборов имеют пару, которая его НЕ зовёт (шапка).',
  );

  if (НЕДОКАЗАНО.length) {
    console.log(
      `⚠️ Пара есть, КРАСНЕТЬ НЕ ДОКАЗАНО (${НЕДОКАЗАНО.length}): ${НЕДОКАЗАНО.join(', ')} — ` +
        'их пара судит запуск и добычу материала, а не умение покраснеть на настоящем нарушении.',
    );
  }

  const { появились, ушли, чисто } = судХраповика(итог.долг);
  if (чисто) {
    console.log(`\n✅ Долг совпал с храповиком (${ХРАПОВИК.length}). Новых приборов без пары нет.`);
    return 0;
  }
  console.log('');
  if (появились.length) {
    console.log('🔴 ДОЛГ ВЫРОС — у этих приборов проверку не исполняет никто:');
    /*
     * ⚠️ Причина печатается ПОИМЁННО, а не общей строкой. Первая редакция писала всем
     * «несут --selftest, и звать его некому» — и на приборе группы Б это была НЕПРАВДА:
     * самотеста он не несёт вовсе, тем и опасен. Собственный вывод соврал о предмете ровно
     * тем классом, против которого стоит вся порция. Поймано мутацией М3.
     */
    for (const и of появились) {
      const вА = итог.группаА.includes(и);
      const вБ = итог.группаБ.includes(и);
      const причина = вА && вБ ? 'несёт --selftest и стоит в воротах — пары нет'
        : вА ? 'несёт --selftest, и звать его некому'
        : 'стоит в воротах и не имеет ни пары, ни самотеста';
      console.log(`     ${и.padEnd(34)} ${причина}`);
    }
    console.log('   Лечение: завести парный тест, ЗОВУЩИЙ проверку (импортом или дочерним');
    console.log('   процессом), а не дописывать имя в ХРАПОВИК — он существует, чтобы долг не рос.');
  }
  if (ушли.length) {
    console.log('🔴 ХРАПОВИК ПРОТУХ — эти имена в нём есть, а в долге их больше нет:');
    for (const и of ушли) console.log(`     ${и}`);
    console.log('   Лечение: убрать их из ХРАПОВИК тем же коммитом, которым заведена пара.');
  }
  return 1;
}

export function selftest() {
  let провалов = 0;
  const скажи = (ок, что, деталь) => {
    if (!ок) провалов += 1;
    console.log(`${ок ? '✅' : '🔴'} ${что}${деталь ? ` · ${деталь}` : ''}`);
  };

  скажи(несётСамотест("if (argv.includes('--selftest')) run();"), 'носитель опознан по исполняемому тексту');
  скажи(
    !несётСамотест('/* Запуск: node t.mjs --selftest */\nmain();'),
    '🔴 упоминание в ПРОЗЕ носителем не считается',
    'в дереве таких трое — они бы раздули знаменатель',
  );
  скажи(!несётСамотест('// самотест: --selftest\nmain();'), 'упоминание в строчном комментарии тоже не считается');
  скажи(судХраповика(['a']).чисто === false, 'храповик судит против своего списка, а не против пустоты');
  скажи(судХраповика(['a'], ['a']).чисто, 'храповик: долг совпал — чисто');
  скажи(судХраповика(['a', 'b'], ['a']).появились.join() === 'b', 'храповик краснеет на выросшем долге');
  скажи(судХраповика(['a'], ['a', 'b']).ушли.join() === 'b', 'храповик краснеет на протухшем списке');

  console.log(провалов ? `\n🔴 САМОТЕСТ КРАСНЫЙ: провалов ${провалов}` : '\n✅ САМОТЕСТ ЧИСТ');
  return провалов ? 1 : 0;
}

