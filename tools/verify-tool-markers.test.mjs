/**
 * ПАРНЫЙ ЮНИТ ПЕРЕПИСИ ПРИБОРОВ (`tools/verify-tool-markers.mjs`) — эскалация QA смены 14.
 *
 * 🔴 ЗАЧЕМ ПАРА ПРИБОРУ, У КОТОРОГО САМОТЕСТ УЖЕ ЕСТЬ. Самотест не способен поймать собственный
 * незапуск: сломай стражу предохранитель наоборот — и `--selftest` промолчит, напечатав ноль
 * символов, а прогон отчитается успехом. Прибор стоит в воротах `npm run guards`, и его самотест
 * до сегодня не звал НИКТО и НИКОГДА: он стерёг ровно до первой правки, после которой молча
 * перестал бы стеречь.
 *
 * 🔴 ПРИЁМКА ЗДЕСЬ — ВЫЗОВ, А НЕ СОСЕДСТВО. Замер покрытия V8 (Дизайнер, смена 14) нашёл ШЕСТЬ
 * приборов, у которых парный файл ЕСТЬ, а самотест всё равно не исполняется: файл живёт рядом и
 * проверяет своё. Наличие пары — форма, вызов — существо, и между ними шесть живых расхождений в
 * нашем же дереве. Поэтому ниже стоит настоящий вызов и требование ОТВЕТА с числом случаев.
 *
 * ⚠️ ВЫЗОВ ИДЁТ ДОЧЕРНИМ ПРОЦЕССОМ, а не импортом экспортированной функции. Прибор свой самотест
 * НЕ ЭКСПОРТИРУЕТ (как и остальные пять воротных этой порции), и заводить экспорт значило бы
 * править шесть воротных приборов ради формы пары. Дочерний процесс к тому же единственный
 * безопасный способ: сломанный предохранитель зовёт `process.exit()`, и он убил бы САМ ПРОГОН
 * НАБОРА — вердикт читался бы как «тесты не запускались» вместо «предохранитель снят»
 * (`EXP-0188` п.3).
 *
 * Прогон: node --test tools/verify-tool-markers.test.mjs · npm run test:tools
 */
import test from 'node:test';
import assert from 'node:assert/strict';

import { спроситьСамотест, разобратьОтвет, спроситьИмпорт } from './lib/selftest-pair.mjs';

const ПРИБОР = 'verify-tool-markers';
/** Образец ИТОГОВОЙ строки этого прибора — со своей группой-числом. */
const ИТОГ = /САМОТЕСТ ЧИСТ: случаев (\d+)/;

test('🔴 ЗАПУЩЕН: самотест ОТВЕТИЛ, случаев больше нуля, код 0', () => {
  const r = спроситьСамотест(ПРИБОР);
  // Пустой ответ — это не «нечего сказать», это «предохранитель отключил стража».
  assert.notEqual(r.stdout.trim(), '', 'самотест не ответил вовсе');
  const { число } = разобратьОтвет(r.stdout, ИТОГ);
  assert.notEqual(число, null, 'итоговая строка самотеста не найдена — форма вывода сменилась');
  // Ноль случаев печатается тем же зелёным, что и пятьдесят два: «чисто» на пустом наборе
  // неотличимо от здоровья (`TESTING_FRAMEWORK.md` правило 10, вопрос 3).
  assert.ok(число > 0, `самотест выполнил ${число} случаев — зелёное на нуле наблюдений`);
  assert.equal(r.status, 0);
});

test('🔴 ПОДКЛЮЧЁН: импорт прибора не исполняет обход и не убивает чужой процесс', () => {
  const r = спроситьИмпорт(ПРИБОР);
  assert.ok(r.жив, 'импорт убил чужой процесс — предохранителя нет или он сломан');
  assert.equal(r.лишнее, '', `импорт исполнил работу: «${r.лишнее}»`);
  assert.equal(r.status, 0);
});
