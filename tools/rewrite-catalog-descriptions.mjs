/**
 * Маркеры справочного стиля по языкам. Английские — сито §10; русские — сито заказа владельца
 * 2026-08-16 («и русские текста нужно будет править»).
 *
 * ⚠️ ЗДЕСЬ ОНИ РАБОТАЮТ УЖЕ НЕ СИТОМ, А ЗАПРЕТОМ: прибор не даёт записать правку, в которой
 * маркер уцелел. Это разные роли одного списка, и путать их нельзя — в грепе маркер лишь
 * повод посмотреть, здесь он признак того, что правка своей работы не сделала.
 */
const MARKERS_BY_LANG = {
  en: [/voiced by/i, /premiered on/i, /totaling \d+ episodes/i, /consists of \d+ seasons/i,
    /aired on .{0,80}? from .+? to /i],
  ru: [/премьера состоялась/i, /В главных ролях/i, /[СC]ъёмки проходили/i, /роль исполн(ил|ила|или)/i,
    /транслировал(ся|ась|ись)/i, /состоит из \d+ сезон/i],
};

/**
 * 🆕 ЗАМЕЧАНИЯ — ВТОРОЙ ВЫХОД `checkEdit` (общий канал ворот, 2026-08-22).
 *
 * У ворот было одно слово — ОТКАЗ, — и `proseNotes` («*the score was composed by*» и прочее
 * артефактное подлежащее) не звал НИКТО: функция была написана, объявлена решением Менеджера
 * «предъявлять, а не отказывать» — и не подключена ни к одному прогону. Класс `EXP-0194`.
 *
 * Совместимость держится формой возврата: `checkEdit` по-прежнему отдаёт МАССИВ проблем, и все
 * прежние вызовы (`gate-rewrites.mjs`, самотест, рабочий режим) работают без правки. Замечания
 * висят на нём вторым полем — `problems.замечания`. Так канал стал общим, не сломав ни одного
 * потребителя; отдельная функция-близнец разъехалась бы с этой на первом же новом признаке.
 */
export function checkEdit(edit) {
  const problems = [];
  const замечания = [];
  problems.замечания = замечания;
  const lang = edit.lang ?? 'en';
  if (!edit.slug) problems.push('нет slug');
  if (!MARKERS_BY_LANG[lang]) problems.push(`неизвестный язык «${lang}»`);
  if (!edit.before) problems.push('нет before');
  if (!edit.after) problems.push('нет after');
  if (edit.before && edit.after && edit.before === edit.after) problems.push('after равен before');

  if (edit.before && edit.after && MARKERS_BY_LANG[lang]) {
    const numbers = (s) => (s.match(/\b\d{1,4}(?:,\d{3})*\b/g) ?? []).map((n) => n.replace(/,/g, ''));
    const lost = numbers(edit.before).filter((n) => !numbers(edit.after).includes(n));
    if (lost.length) problems.push(`потеряны числа: ${[...new Set(lost)].join(', ')}`);

    /*
     * 🔴 МАРКЕР ЗАПРЕЩЁН В ТОМ, ЧТО Я НАПИСАЛ, а в остальном тексте он лишь повод посмотреть.
     *
     * Первая редакция проверяла ВЕСЬ текст — и заблокировала две законные правки: описания
     * содержали «В главных ролях» в другом предложении, которого правка не касалась. Для русских
     * маркеров это неизбежно: они обычные фразы, а не улики сами по себе.
     *
     * Ценность прежней проверки при этом настоящая (она поймала «voiced by», уцелевшее внутри
     * моей же замены) — поэтому она не снята, а сужена до фрагмента правки.
     */
    const где = edit.replace !== undefined
      ? [edit.replace].flat().join(' ')
      : edit.after;
    const left = MARKERS_BY_LANG[lang].filter((re) => re.test(где));
    if (left.length) problems.push(`маркер остался в самой правке: ${left.length}`);

    /*
     * 🔴 СЛЕДЫ РЕЗА — П4 `plans/70`, критерий К4, урок `EXP-0177`.
     *
     * Повод дословно: ворота мастерской печатали «✅ ЧИСТО» на ПОРВАННОМ тексте — «…для крупных
     * постановок. ; продюсерами выступили…» и дважды висящая кавычка. Прибор мерил объём,
     * строение, заимствование и зачин, а пунктуацию не мерил НИКТО, и молчание об этом читалось
     * как «текст цел». Класс шире мастерской: **всякий раз, когда механизм режет или склеивает
     * человеческий текст, к нему в тот же заход пишется мера артефактов реза.** Писарь режет и
     * склеивает по определению — он подставляет `replace` вместо `find`.
     *
     * 🔑 СУДИМ ПРИРОСТ, А НЕ НАЛИЧИЕ, и это не смягчение, а точность. Две крайности негодны:
     *   · проверять только фрагмент правки (как маркеры выше) — СЛЕПО к главному: артефакт
     *     рождается на ШВЕ, между хвостом уцелевшего предложения и головой замены, то есть
     *     ровно там, куда фрагмент не смотрит;
     *   · проверять весь `after` на наличие — ЛОЖНЫЕ ТРЕВОГИ: в чужом, не тронутом правкой
     *     предложении двойной пробел мог лежать до нас, и писарь запирал бы законные правки за
     *     грязь, которой не делал. Тот же капкан уже сработал на маркерах и там же описан.
     * Прирост свободен от обеих бед: шов виден, чужая грязь не считается нашей.
     *
     * ⚠️ И СЧИТАЕМ ШТУКИ, А НЕ ФАКТ НАЛИЧИЯ. `punctuationArtifacts` отвечает «есть или нет» по
     * каждому образцу, и на таком ответе уцелевший в тексте двойной пробел ЗАМАСКИРОВАЛ БЫ
     * второй, внесённый нами: было «есть» — стало «есть», прироста нет. Поэтому образцы
     * пересчитываются глобальной копией, а имена берутся оттуда же — замечание обязано
     * читаться словами, без раскодирования регулярного выражения.
     */
    const считать = (текст) => {
      const счёт = new Map();
      for (const [образец, имя] of ARTIFACT_PATTERNS) {
        const все = String(текст).match(new RegExp(образец.source, `${образец.flags}g`));
        счёт.set(имя, все ? все.length : 0);
      }
      return счёт;
    };
    const было = считать(edit.before);
    const стало = считать(edit.after);
    const следы = [...стало]
      .filter(([имя, n]) => n > (было.get(имя) ?? 0))
      .map(([имя]) => имя);
    if (следы.length) problems.push(`следы правки: ${следы.join(', ')}`);

    /*
     * 🆕 ВОРОТА ПРОЗЫ — АНГЛИЙСКАЯ СТОРОНА (П5 `plans/70`, `tools/lib/prose-gates.mjs`).
     *
     * ⚠️ СТОИТ РЯДОМ С П4 НАМЕРЕННО, И ОБЛАСТИ У НИХ РАЗНЫЕ. Следы реза судятся по ПРИРОСТУ во
     * всём тексте (артефакт рождается на шве), ворота прозы — по ФРАГМЕНТУ правки (оборот в
     * соседнем предложении правка не трогала). Свести их к одной области нельзя: у каждого
     * класса своя область по построению, и обе границы разобраны здесь же.
     *
     * Два класс-запрета владельца, у которых до 2026-08-22 не было ни строки кода:
     * расщеплённое сказуемое («Production was carried out by …») и конструкция отнесения
     * («By genre the film belongs to …»). Разделяющие признаки назначены ЗАМЕРОМ по корпусам
     * из git — 0 ложных срабатываний на 389 живых текстах владельца против 11 находок на
     * карточках, которые он вернул. Разбор и таблица — в шапке модуля.
     *
     * 🔑 СУДИТСЯ ФРАГМЕНТ ПРАВКИ, А НЕ ВЕСЬ ТЕКСТ — по тому же доводу, что у маркеров выше:
     * оборот в соседнем предложении правка не трогала, и заворачивать честную работу за чужой
     * грех нельзя. Цена этого решения названа прямо: условная половина ворот отнесения
     * (голое `belongs to` при тавтологии) во фрагменте не видит текста РАНЬШЕ себя и потому
     * не срабатывает. Безусловные обороты ловятся и здесь. Недобор проверки дешевле ложного
     * отказа: ложный отказ запрещает писать так, как пишет владелец.
     *
     * ⛔ Русскую правку английский список не судит — модуль сам возвращает пустое на `lang ≠ en`.
     */
    problems.push(...proseProblems(где, lang));
    замечания.push(...proseNotes(где, lang));

    /*
     * 🔴🔴 ВТОРАЯ ЦЕЛЬ ПРАВКИ — НЕ УХУДШИТЬ ПРОПОРЦИЮ (`bugs/180`, заказ владельца).
     *
     * До этой строки у правки была ОДНА цель: сбить дословный ряд с Википедией. Первое
     * предложение энциклопедической статьи почти всегда про производство — поэтому правка брала
     * мету и переписывала мету, а иногда ДОПИСЫВАЛА её, и «зелёный прогон» это скрывал. Слово
     * владельца, названное им классом: «*Куда важнее то, что происходит в сюжете, чем то, как
     * объект культуры создавался*»; содержание — сюжет, герои, проблематика.
     *
     * 🔑 ПРАВИЛО СТИЛЯ НЕ ПЕРЕПИСЫВАЕТСЯ ЗДЕСЬ, А БЕРЁТСЯ ПРИБОРОМ МАСТЕРСКОЙ. Канон один —
     * `candidates/README.md`, — и конвейер правок обязан читать ЕГО, а не свою редакцию. Поэтому
     * подключается `metaDelta` из общего `lib/meta-share.mjs`, тем же способом, каким сюда уже
     * подключены `ARTIFACT_PATTERNS` и `proseProblems`. Второй копии правил не заводится:
     * вторая правда расходится молча.
     *
     * 🔑 СУДИТСЯ ПРИРОСТ, А НЕ НАЛИЧИЕ — и здесь это особенно важно. Правка, УНАСЛЕДОВАВШАЯ
     * плохую пропорцию, в ней не виновата: запирать её значило бы остановить снятие
     * заимствования, а откат к тексту Википедии запрещён стоячим правилом. Виновата правка,
     * которая пропорцию УХУДШИЛА.
     *
     * ⚠️ ЗАПИРАЕТСЯ ТОЛЬКО РОСТ В ШТУКАХ, и это назначено ЗАМЕРОМ 364 живых правок из журналов,
     * а не осторожностью: доля меты выросла у 23 правок, но у 20 из них выросло и ЧИСЛО
     * предложений о производстве — правка дописала производство, двусмысленности нет. У
     * оставшихся трёх число меты не менялось, а сжался ЗНАМЕНАТЕЛЬ: два предложения содержания
     * слились в одно. Содержание при этом не убыло, и отказ был бы ложным. Такой случай
     * предъявляется числом в журнале (доля ДО → ПОСЛЕ у каждой правки), а не запирается.
     */
    const пропорция = metaDelta(edit.before, edit.after, lang, splitSentences);
    if (пропорция.метаВыросла) {
      problems.push(
        `правка добавила производства: предложений о создании ${пропорция.до.мета} → ${пропорция.после.мета}`
          + ` (доля ${пропорция.до.доля}% → ${пропорция.после.доля}%)`,
      );
    }

    /*
     * 🔴🔴 ВТОРАЯ ПОЛОВИНА ВТОРОЙ ЦЕЛИ — ЖАНР НЕ УЕЗЖАЕТ ВГЛУБЬ РАДИ ПРОИЗВОДСТВА (`bugs/188`).
     *
     * 🔑 СУДИТСЯ ПАРА ПРИЗНАКОВ, А НЕ ОДИН, и это назначено ЗАМЕРОМ по 364 живым правкам из
     * журналов, а не осторожностью. Перекрёстная таблица «исход сдвига × что встало впереди»:
     *
     *   исход \ зачин ПОСЛЕ   производство   жанр   иное   всего
     *   ровно                            1    225      0     226
     *   ухудшение                       61     12      0      73
     *   улучшение                        0     14      0      14
     *   жанр пропал                      5      0      3       8
     *
     * Одно лишь «ухудшение» заперло бы 73 правки, включая 12, где жанр уехал вглубь, но остался
     * ВПЕРЕДИ производства, — а это не та беда, про которую говорил владелец. Пара «ухудшение И
     * производство вперёд» даёт 61 из 364 (16,8 %), и все прочитанные глазами — настоящий дефект,
     * начиная с канонического `insomnia-5ul3dkfi` из шапки `bugs/180`: «The 2002 American
     * psychological thriller directed by…» → «Hillary Seitz wrote the screenplay and…», 4 → 13.
     *
     * 🔑 СУДИТСЯ СДВИГ, А НЕ АБСОЛЮТНОЕ ЧИСЛО — форма та же, что у доли меты, и по той же причине:
     * порога на глубине нет и это РЕШЕНИЕ (шапка `lib/genre-depth.mjs` объявляет прибор
     * предъявляющим, а не судящим). Правка, УНАСЛЕДОВАВШАЯ глубокий жанр, не виновата: в таблице
     * это строка «ровно · производство · 1» — она проходит, потому что ухудшения не внесла.
     *
     * ⚠️ РАЗРЯД «ЖАНР ПРОПАЛ» — ЗАМЕЧАНИЕ, А НЕ ОТКАЗ, и это тоже замер, а не мягкость. Их восемь,
     * и разряд неоднороден: у трёх впереди встало СОДЕРЖАНИЕ (жанр просто не назван — другая беда,
     * лечится дописыванием слова, а не переносом), а словарь видов и жанров конечен и составные
     * через дефис пропускает: `taken-23hrkovo` пишет «this French action-thriller», жанр НАЗВАН, а
     * `^thriller` на «action-thriller» не совпадает. Отказ здесь был бы ложным. Числами этот разряд
     * с «ухудшением» не сравнивается — так велит и шапка модуля, и `bugs/188`.
     */
    const жанрДо = genreDepth(edit.before, lang, splitSentences);
    const жанрПосле = genreDepth(edit.after, lang, splitSentences);
    const сдвиг = depthShift(жанрДо, жанрПосле);
    const зачинПосле = openingClass(жанрПосле.первое, lang).класс;
    if (сдвиг.исход === 'ухудшение' && зачинПосле === 'производство') {
      problems.push(
        `правка увела жанр вглубь ради производства: глубина ${жанрДо.глубина} → ${жанрПосле.глубина}`
          + ` (+${сдвиг.сдвиг}), впереди теперь производство`,
      );
    }
  }
  return problems;
}

/**
 * ЗАМЕЧАНИЯ — то, что предъявляется человеку, но дверь не запирает.
 *
 * Отдельно от `checkEdit` по тому же закону, по какому отдельно живёт `пропорцияПравки`: дверь
 * СУДИТ, а замечание ПРЕДЪЯВЛЯЕТ. Разряд «жанр пропал» назначен замечанием замером (разбор — в
 * `checkEdit` выше), и без этой функции он был бы не виден нигде: молчаливый пропуск и есть
 * дефект, за который платил `bugs/188`.
 */
export function noteEdit(edit) {
  const notes = [];
  const lang = edit.lang ?? 'en';
  if (!edit.before || !edit.after || !MARKERS_BY_LANG[lang]) return notes;
  const до = genreDepth(edit.before, lang, splitSentences);
  const после = genreDepth(edit.after, lang, splitSentences);
  const сдвиг = depthShift(до, после);
  if (сдвиг.исход === 'жанр пропал') {
    notes.push(`после правки жанр в первом предложении не назван (было слово ${до.глубина}) —`
      + ' проверьте: либо допишите вид одним словом, не трогая порядок, либо это составное слово,'
      + ' которого нет в словаре');
  }
  return notes;
}

/**
 * ПРОПОРЦИЯ ПРАВКИ ЧИСЛОМ — для журнала. Отдельно от `checkEdit`, потому что журнал ПРЕДЪЯВЛЯЕТ,
 * а дверь СУДИТ: сжатый знаменатель дверь не запирает, но в журнале он обязан быть виден.
 */
export function пропорцияПравки(edit) {
  const lang = edit.lang ?? 'en';
  if (!edit.before || !edit.after) return null;
  return metaDelta(edit.before, edit.after, lang, splitSentences);
}

/** Журнал для вычитки владельцем — страницей, а не списком идентификаторов. */
export function journalText(edits, { applied, skipped }) {
  const lines = [
    '# Журнал правок описаний каталога',
    '',
    '> **Кто правил:** агент, по `AUTHOR_STYLOMETRY.md` · **Разрешение:** интервью №025, В6 = А',
    '> (правки текстов пишет агент, владелец вычитывает ПОСТФАКТУМ одной страницей).',
    `> **Шаг:** \`plans/56\` шаг 3 · **Прибор:** \`tools/rewrite-catalog-descriptions.mjs\``,
    '',
    'Правило правки: **менялся СТИЛЬ, а не факты.** Ни один год, ни одно число, ни одно имя из',
    'исходного текста не удалены — это проверяет сам прибор и отказывается писать иначе.',
    '',
    `Правок в этой партии: **${edits.length}** · записано: **${applied}** · пропущено: **${skipped}**`,
    '',
    '---',
    '',
  ];
  for (const e of edits) {
    lines.push(`## \`${e.slug}\``);
    lines.push('');
    if (e.why) lines.push(`*${e.why}*`, '');

    /*
     * 🔴 ПРОПОРЦИЯ ЧИСЛОМ, У КАЖДОЙ ПРАВКИ — ради этого журнал и существует после `bugs/180`.
     * Владелец отказался вычитывать 360 правок глазами и потребовал урегулировать это правилами.
     * Правило без числа в журнале осталось бы обещанием: проверить 360 правок можно только
     * СЧЁТОМ. Дверь запирает лишь рост в штуках, поэтому сжатый знаменатель обязан быть виден
     * здесь — иначе он не виден нигде.
     */
    const п = пропорцияПравки(e);
    if (п) {
      const знак = п.метаВыросла ? '🔴 ХУЖЕ' : п.доляВыросла ? '⚠️ знаменатель сжался' : п.после.доля < п.до.доля ? '✅ лучше' : '= ровно';
      lines.push(
        `*Доля производства: **${п.до.доля}% → ${п.после.доля}%** ${знак}`
          + ` (предложений о создании ${п.до.мета} → ${п.после.мета}, всего ${п.до.всего} → ${п.после.всего}).*`,
        '',
      );
    }

    lines.push('**Было:**', '', `> ${e.before.replace(/\n+/g, ' ')}`, '');
    lines.push('**Стало:**', '', `> ${e.after.replace(/\n+/g, ' ')}`, '');
  }
  return lines.join('\n');
}

