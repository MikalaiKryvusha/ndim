/**
 * ЮНИТЫ ЗАМЕРА ИМЁН ПРОТИВ РЕЕСТРА (`tools/lib/name-registry.mjs`, кусок 2 постановки Менеджера).
 *
 * 🔴 ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ, КОГДА У ПРИБОРА ЕСТЬ `--selftest`. Самотест зовут руками, а
 * `npm run test:tools` гоняет `tools/*.test.mjs` — то есть в ВОРОТАХ стоит только этот файл.
 * Урок `EXP-0194` дословно: «страж, не стоящий ни в одних воротах, не защищает — он ЖДЁТ, пока
 * о нём вспомнят». Самотест остаётся: он печатает разбор случаев глазами при работе над
 * прибором; юниты — то, что краснеет само.
 *
 * ⚠️ ОБРАЗЦЫ РУССКИЕ ТАМ, ГДЕ ПРОВЕРКА РУССКАЯ (канон «самотест языка X — на образцах X»,
 * `researches/47` §8): английский образец не ловит класс `\b` рядом с кириллицей вовсе.
 *
 * Прогон: node --test tools/name-registry.test.mjs   ·   npm run test:tools
 */
import test from 'node:test';
import assert from 'node:assert/strict';

import {
  entityLabels, registryState, registrySilence, nameFindings, nameNotes, nameMatches, normalizeName,
  NAME_PROPS, SILENCE_REASONS,
} from './lib/name-registry.mjs';

/** Живой человек реестра: русская метка есть только в заголовке статьи, и та инвертирована. */
const УИЛЛ = { labels: { mul: { value: 'Will Gluck' } }, sitelinks: { ruwiki: { title: 'Глак, Уилл' } } };
const МОНИКА = { labels: { ru: { value: 'Моника Барбаро' }, en: { value: 'Monica Barbaro' } } };

const снк = (qid) => ({ mainsnak: { snaktype: 'value', datavalue: { value: { id: qid } } } });

/** Состояние-образец: режиссёр и состав известны, сценарист отсутствует как свойство. */
const состояние = (lang = 'ru') => registryState(
  { claims: { P57: [снк('Q9')], P161: [снк('Q8')] } },
  { Q9: УИЛЛ, Q8: МОНИКА },
  lang,
);

test('цепочка имени: русской метки нет, а имя есть — берётся из mul и из заголовка статьи', () => {
  const имена = entityLabels({ labels: { mul: { value: 'Nintendo' } }, sitelinks: { ruwiki: { title: 'Nintendo' } } }, 'ru');
  assert.ok(имена.includes('Nintendo'));
});

test('инверсия заголовка русской Википедии развёрнута: «Глак, Уилл» → «Уилл Глак»', () => {
  assert.ok(entityLabels(УИЛЛ, 'ru').includes('Уилл Глак'));
});

test('скобочное уточнение снимается: «Инклинги (Splatoon)» → «Инклинги»', () => {
  assert.ok(entityLabels({ labels: { ru: { value: 'Инклинги (Splatoon)' } } }, 'ru').includes('Инклинги'));
});

test('русская флексия не мешает сверке', () => {
  assert.ok(nameMatches('Дэвидом Робертом Митчеллом', 'Дэвид Роберт Митчелл'));
  assert.ok(nameMatches('Элаем Ротом', 'Элай Рот'), 'короткое имя: порог считается от КОРОТКОГО слова');
  assert.ok(nameMatches('Ли Гарлингтон', 'Ли Гарлингтон'), 'двухбуквенное имя сходится само с собой');
});

test('диакритика снимается, инициал сходится с полным именем', () => {
  assert.ok(nameMatches('Hildur Gudnadottir', 'Hildur Guðnadóttir'));
  assert.ok(nameMatches('George Pan Cosmatos', 'George P. Cosmatos'));
});

test('разные имена НЕ сходятся — иначе прибор молчал бы обо всём', () => {
  assert.ok(!nameMatches('Купер Томлинсон', 'Дэвид Роберт Митчелл'));
  assert.ok(!nameMatches('Иван Петров', 'Игорь Петров'), 'общее начало в одну букву — не совпадение');
  assert.ok(!nameMatches('Робин Гуд', 'Роберт Гуд'), 'три общие буквы при пороге 3,5 — не совпадение');
  assert.equal(normalizeName('Керри-Энн Мосс'), 'керри энн мосс');
});

test('ТРИ ВИДА МОЛЧАНИЯ РЕЕСТРА различаются — это ядро постановки', () => {
  assert.equal(registryState({ claims: {} }, {}, 'ru').P178.вид, 'нет-свойства');
  assert.equal(
    registryState({ claims: { P178: [{ mainsnak: { snaktype: 'somevalue' } }] } }, {}, 'ru').P178.вид,
    'без-значения',
  );
  assert.equal(
    registryState({ claims: { P58: [снк('Q1')] } }, { Q1: { labels: { en: { value: 'John Doe' } } } }, 'ru').P58.вид,
    'без-метки',
  );
});

test('молчание предъявляется ОТДЕЛЬНЫМ списком, а не смешивается с расхождением', () => {
  const сост = registryState({ claims: { P58: [снк('Q1')] } }, { Q1: { labels: { en: { value: 'John Doe' } } } }, 'ru');
  const молчит = registrySilence(сост);
  assert.ok(молчит.some((x) => x.свойство === 'P58' && x.вид === 'без-метки'));
  assert.ok(NAME_PROPS.every((p) => Boolean(сост[p])), 'состояние заведено на каждое именное свойство');
});

test('окно 40: имя рядом с маркером проверяется, подтверждённое молчит', () => {
  const r = nameFindings('Снял картину Уилл Глак. Играют Моника Барбаро и Каллум Тёрнер.', 'ru', состояние());
  assert.equal(r.находки.length, 1);
  assert.equal(r.находки[0].имя, 'Каллум Тёрнер');
  assert.equal(r.находки[0].роль, 'состав');
  assert.equal(r.находки[0].вердикт, 'расхождение', 'состав реестр даёт — значит расхождение, не молчание');
});

test('ЦЕПОЧКА ПЕРЕЧИСЛЕНИЯ: четвёртое имя ЗА окном всё равно проверяется', () => {
  /* 🔴 Этот случай стережёт ИМЕННО цепочку, и заведён он мутацией: первая редакция теста ставила
   * третье имя в 18 знаках от маркера, то есть внутри окна 40, — снятие цепочки её НЕ роняло, и
   * признак стоял без охраны. Здесь «Лоренс Фишберн» отстоит от «Играют» на 49 знаков: поймать
   * его может только продолжение перечисления. Мутация «продолжение = false» роняет этот тест
   * и ровно на этом ожидании — контроль попадания ПО СМЫСЛУ (`EXP-0193`). */
  const текст = 'Играют Моника Барбаро, Кэрри-Энн Мосс, Хьюго Уивинг и Лоренс Фишберн.';
  assert.ok(текст.indexOf('Лоренс') - 'Играют'.length > 40, 'образец обязан выходить за окно');
  const r = nameFindings(текст, 'ru', состояние());
  assert.ok(r.находки.some((f) => f.имя === 'Лоренс Фишберн'), 'четвёртое имя перечисления проверено');
});

test('реестр молчит по роли → вердикт «молчание», и вид молчания НАЗВАН', () => {
  const r = nameFindings('Сценарий написал Флоран Бернар.', 'ru', состояние());
  assert.equal(r.находки.length, 1);
  assert.equal(r.находки[0].вердикт, 'молчание');
  assert.equal(r.находки[0].вид, 'нет-свойства');
  assert.match(nameNotes('Сценарий написал Флоран Бернар.', 'ru', состояние())[0], /молчит/u);
});

test('ГРАНИЦА: имя за окном и вне перечисления не судится — фильмография не попадает', () => {
  /* Живая строка корпуса (карточка «Невеста», английская сторона): между маркером `directing`
   * и названием прежней работы стоит придаточное, то есть больше 40 знаков и не соединитель. */
  const r = nameFindings(
    'For Maggie Gyllenhaal, who came to directing from acting, this is a second feature after The Lost Daughter.',
    'en', состояние('en'));
  assert.ok(!r.находки.some((f) => f.имя === 'The Lost Daughter'));
});

test('ОСТАТОК ПЕРЕБОРА ЗАКРЕПЛЁН, чтобы никто не счёл прибор точным', () => {
  /* Название прежней работы, стоящее БЛИЗКО к маркеру, прибор предъявляет — и это не дефект,
   * а честная цена окна: отличить название фильма от имени человека он не умеет. Строка стоит
   * тестом ровно затем, чтобы граница была видна, а не открывалась заново на живой партии. */
  const r = nameFindings('Сценарий написал тот же автор, что и Парк Юрского Периода.', 'ru', состояние());
  assert.equal(r.находки.length, 1);
  assert.equal(r.находки[0].имя, 'Парк Юрского Периода');
});

test('ГРАНИЦА: имя героини вне ролевого места не судится вовсе', () => {
  const r = nameFindings('Дениз Платт мечтает написать роман; её муж Грег потерял место.', 'ru', состояние());
  assert.equal(r.находки.length, 0);
  assert.equal(r.внеРоли, 1);
});

test('ГРАНИЦА СЛОВА: маркер не ловится ВНУТРИ чужого слова — ни слева, ни справа', () => {
  /* 🔴 Живое ложное срабатывание замера: `cast` внутри `castle` притянуло «Castle Grayskull»
   * к роли «состав». Левая граница его не ловит — нужна ПРАВАЯ. Мутация «снять границы»
   * роняет ровно этот тест. */
  const справа = nameFindings('The castle belongs to Prince Adam and stands empty.', 'en', состояние('en'));
  assert.equal(справа.находки.length, 0, '`cast` внутри `castle` роль назначать не имеет права');
  const слева = nameFindings('The result was indirect harm to Prince Adam.', 'en', состояние('en'));
  assert.equal(слева.находки.length, 0, '`direct` внутри `indirect` роль назначать не имеет права');
  const русский = nameFindings('Внешний авторитет Джона Смита тут ни при чём.', 'ru', состояние());
  assert.equal(русский.находки.length, 0, '«автор» внутри «авторитет» роль назначать не имеет права');
  /* И обратная половина: настоящие формы маркера обязаны ЛОВИТЬСЯ, иначе граница съела проверку. */
  const живой = nameFindings('The film was directed by Prince Adam.', 'en', состояние('en'));
  assert.equal(живой.находки.length, 1, '`direct` обязан ловить `directed` — основа открыта справа');
});

test('ОДОБРЕННАЯ ВЛАДЕЛЬЦЕМ строка «Кобры» остаётся чистой', () => {
  /* Живая строка одобренной карточки Q637290: двухбуквенное имя «Ли» внутри перечисления. */
  const сост = registryState(
    { claims: { P161: [снк('Q1'), снк('Q2')] } },
    { Q1: { labels: { ru: { value: 'Бригитта Нильсен' } } }, Q2: { labels: { ru: { value: 'Ли Гарлингтон' } } } },
    'ru');
  const r = nameFindings('Вместе со Сталлоне играют Бригитта Нильсен и Ли Гарлингтон.', 'ru', сост);
  assert.equal(r.находки.length, 0);
});

test('вид молчания читается словами, а не кодом', () => {
  assert.equal(SILENCE_REASONS['нет-свойства'], 'свойства нет вовсе');
  assert.equal(SILENCE_REASONS['без-метки'], 'значение есть, имени на этом языке нет');
});
