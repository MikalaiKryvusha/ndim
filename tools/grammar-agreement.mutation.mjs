/**
 * ДОКАЗАТЕЛЬСТВО МУТАЦИЕЙ для прибора согласования — `tools/lib/grammar-agreement.mjs`.
 *
 * Зачем отдельный файл, а не абзац в отчёте. `AGENT_GUIDE.md` → «Зелёные тесты сами по себе
 * ничего не доказывают»: прежде чем поверить набору, СЛОМАЙ код намеренно и убедись, что он
 * падает. Утверждение «мутацией доказано» без перевыводимой команды — это унаследованное число,
 * каких проект уже держит одно. Здесь команда есть, и её может повторить кто угодно.
 *
 * 🔴 ЧТО ЭТОТ ФАЙЛ ОТВЕЧАЕТ ПО «ЛЕСТНИЦЕ ТРЁХ ВОПРОСОВ К ЗЕЛЁНОМУ ПРОГОНУ»:
 *   · вопрос 1 «проверка ВООБЩЕ исполнилась?» — мутация «отцепить саму проверку согласования»;
 *   · вопрос 2 «признак ВЕРЕН?» — мутации по Н3, границе предложения и лексикону;
 *   · вопрос 3 «мог ли МАТЕРИАЛ дать проверке упасть?» — три предохранителя ниже, из которых
 *     главный: МУТАНТ ОБЯЗАН ОТЛИЧАТЬСЯ ОТ ИСХОДНИКА НЕ ТОЛЬКО БАЙТОМ, НО И ПОВЕДЕНИЕМ.
 *
 * ⚠️ ЦЕНА, ОПЛАЧЕННАЯ ПРИ НАПИСАНИИ ЭТОГО ФАЙЛА, названа вслух, потому что класс живучий.
 * Первая редакция первой мутации была `const согласовано = true && …` — и дала НОЛЬ падений.
 * Подстановка легла в файл, набор прогнался, всё выглядело проведённым: `true && X` тождественно
 * `X`, мутанту было НЕ НА ЧЕМ покраснеть. Ровно тот случай, который `AGENT_GUIDE.md` называет
 * четвёртым слоем «не способен упасть» — сам мутант. Отсюда предохранитель 2 ниже.
 * Вторая цена: подстановка «убрать границу предложения» не находилась в файле, потому что в
 * исходнике стоял НЕВИДИМЫЙ неразрывный пробел. Отсюда предохранитель 1 — «подстановка не
 * нашлась» это ПРОВАЛ доказательства, а не пропуск строки.
 *
 * Три предохранителя, и каждый роняет прогон:
 *   1. подстановка обязана НАЙТИСЬ в файле;
 *   2. мутант обязан ОТЛИЧАТЬСЯ от исходника;
 *   3. эталон обязан быть зелёным ДО мутаций и восстановиться ПОСЛЕ них.
 *
 * Запуск:  node tools/grammar-agreement.mutation.mjs
 * Код выхода 0 — все мутации уронили набор. Ненулевой — хотя бы одна проехала.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { pathToFileURL } from 'node:url';

const ФАЙЛ = 'tools/lib/grammar-agreement.mjs';
const НАБОР = 'tools/grammar-agreement.test.mjs';

/**
 * Каждая мутация ломает ОДНО решение конструкции. Ни одна не является «случайной порчей
 * символа»: все пять — это отмена признака, который разведка вывела замером.
 */
const МУТАЦИИ = [
  {
    имя: 'отцепить саму проверку согласования',
    ломает: 'вопрос 1 лестницы: исполняется ли проверка вообще',
    было: 'if (согласовано) continue;',
    стало: 'if (true) continue;',
  },
  {
    имя: 'убрать правило Н3 (причастие УПРАВЛЯЕТ, а не согласуется)',
    ломает: 'шесть ложных на текстах владельца — «снятый режиссёром»',
    было: 'if (причастиеУправляет(разбор, сущ.падежи))',
    стало: 'if (false)',
  },
  {
    имя: 'убрать границу предложения',
    ломает: 'пара перешагивает точку — «обыкновенной. Картина»',
    было: '.test(промежуток)) continue;',
    стало: '.test(промежуток) && false) continue;',
  },
  {
    имя: 'соврать в лексиконе: режиссёр → женский род',
    ломает: 'объявленный род существительного — ядро правила Н1',
    было: "{ лемма: 'режиссёр', род: 'м'",
    стало: "{ лемма: 'режиссёр', род: 'ж'",
  },
  {
    имя: 'сломать границу слова: \\p{L} → ASCII \\w',
    ломает: 'AGENT_GUIDE: «\\b и \\w определены через ASCII, флаг u этого НЕ чинит»',
    было: 'const БУКВА = String.raw`\\p{L}`;',
    стало: 'const БУКВА = String.raw`\\w`;',
  },
];

function прогон() {
  let вывод;
  try {
    вывод = execFileSync('node', ['--test', НАБОР], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
  } catch (ошибка) {
    вывод = (ошибка.stdout ?? '') + (ошибка.stderr ?? '');
  }
  return {
    падений: (вывод.match(/^✖/gmu) ?? []).length,
    зелёных: (вывод.match(/^✔/gmu) ?? []).length,
  };
}

function main() {
  const эталон = readFileSync(ФАЙЛ, 'utf8');
  const базовый = прогон();
  console.log(`ЭТАЛОН: зелёных ${базовый.зелёных} · падений ${базовый.падений}`);

  // Предохранитель 3, первая половина: на красном эталоне мутации ничего не доказывают.
  if (базовый.падений !== 0) {
    console.error('🔴 эталон уже красный — доказательство мутацией невозможно');
    process.exit(1);
  }

  let всеУпали = true;
  for (const м of МУТАЦИИ) {
    // Предохранитель 1: подстановка обязана найтись.
    if (!эталон.includes(м.было)) {
      console.error(`🔴 ПОДСТАНОВКА НЕ НАШЛАСЬ — «${м.имя}». Это провал доказательства, а не пропуск.`);
      всеУпали = false;
      continue;
    }
    const мутант = эталон.replace(м.было, м.стало);
    // Предохранитель 2: мутанту должно быть НА ЧЕМ покраснеть.
    if (мутант === эталон) {
      console.error(`🔴 МУТАНТ ТОЖДЕСТВЕН ИСХОДНИКУ — «${м.имя}». Подстановка легла, поведение не изменилось.`);
      всеУпали = false;
      continue;
    }

    writeFileSync(ФАЙЛ, мутант);
    const результат = прогон();
    writeFileSync(ФАЙЛ, эталон);

    if (результат.падений === 0) {
      console.log(`  🔴 «${м.имя}» — НАБОР ПРОЕХАЛ. Проверка не способна упасть на этой поломке.`);
      всеУпали = false;
    } else {
      console.log(`  ✅ «${м.имя}» — набор упал, падений ${результат.падений}  (ломает: ${м.ломает})`);
    }
  }

  // Предохранитель 3, вторая половина: файл обязан вернуться в исходное состояние.
  const после = прогон();
  console.log(`ВОССТАНОВЛЕНО: зелёных ${после.зелёных} · падений ${после.падений}`);
  if (после.падений !== 0 || после.зелёных !== базовый.зелёных) {
    console.error('🔴 файл НЕ восстановлен — верни его из git прежде, чем продолжать');
    process.exit(1);
  }

  process.exit(всеУпали ? 0 : 1);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) main();
