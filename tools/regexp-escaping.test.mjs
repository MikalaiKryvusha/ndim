/**
 * СТРАЖ ЭКРАНИРОВАНИЯ В ОБРАЗЦАХ: шаблонная строка СЪЕДАЕТ `\s`, `\d`, `\w`, `\p{…}`.
 *
 * 🔴 ПОВОД — ЖИВОЙ, ОПЛАЧЕН 2026-08-22 ПРИ ЗАМЕРЕ ИМЁН ПРОТИВ РЕЕСТРА. Образец собирался так:
 *
 *     new RegExp(`${СЛОВО}(?:\s+(?:${СЛОВО}|де|of|the))*`, 'gu')
 *
 * В ШАБЛОННОЙ строке `\s` — не escape-последовательность, и JavaScript отдаёт голую букву `s`.
 * В регулярку уезжает `(?:s+…)`, то есть «одна или больше букв s» вместо пробела. И вот чем
 * этот класс опаснее опечатки: **регулярка КОМПИЛИРУЕТСЯ и что-то находит**. Прогон выглядит
 * исправным, печатает правдоподобные числа — и они неверны. Первое число того замера, «42 %
 * ложных срабатываний», было снято сломанным образцом и отброшено целиком.
 *
 * Родня по классу — `\b` и `\w` рядом с кириллицей (`researches/47` §8, стережёт
 * `verify-cyrillic-word-boundary.mjs`): там образец молча НЕ срабатывает, здесь молча срабатывает
 * НЕ НА ТО. Общее одно: **сломанный образец не падает, а врёт.**
 *
 * ЛЕЧЕНИЕ — `String.raw` либо удвоенная косая. Оба варианта страж принимает.
 *
 * 🔑 ПОЧЕМУ ЭТО ТЕСТ, А НЕ ОТДЕЛЬНЫЙ ПРИБОР `verify-*`. Урок `EXP-0194`: «страж, не стоящий ни в
 * одних воротах, не защищает — он ЖДЁТ, пока о нём вспомнят». Приборы `verify-*` в этом проекте
 * не зовёт ни один npm-скрипт, а `npm run test:tools` гоняет `tools/*.test.mjs` на каждой сдаче.
 * Поэтому страж живёт файлом теста: у него есть прогон, который его зовёт, и назван он в том же
 * коммите, что и сам страж.
 *
 * ⚠️ ЧЕСТНЫЕ ГРАНИЦЫ, названные, а не спрятанные:
 *   · страж читает ТЕКСТ файла построчно и не разбирает JavaScript. Образец, размазанный по
 *     нескольким строкам, он не увидит — та же граница, что у соседа по классу;
 *   · он смотрит только на аргументы `new RegExp(...)`. Шаблонная строка, из которой регулярка
 *     собирается через переменную двумя шагами, ему не видна;
 *   · литералы `/…/` его не касаются вовсе: там экранирование работает как положено.
 *
 * Прогон: node --test tools/regexp-escaping.test.mjs   ·   npm run test:tools
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const КОРЕНЬ = join(dirname(fileURLToPath(import.meta.url)), '..');
const ОБХОД = ['tools', 'src', 'sync-server'];
const ПРОПУСК = new Set(['node_modules', '.svelte-kit', 'build', 'test-results', 'fixtures']);

/**
 * ОПАСНАЯ СТРОКА: в аргументе `new RegExp(` стоит шаблонная строка (обратные кавычки), внутри
 * которой есть ОДИНОЧНАЯ косая перед буквой класса. Удвоенная косая законна — она и даёт `\s`.
 */
export function опасныеСтроки(текст) {
  const найдено = [];
  const строки = String(текст).split(/\r?\n/u);
  for (let i = 0; i < строки.length; i += 1) {
    const s = строки[i];
    /* Комментарий — не код. Здесь и в соседних шапках образцы разбираются НАРОЧНО, и страж,
     * ловящий разбор собственного класса, был бы вечно красным (и первым делом поймал бы себя). */
    if (/^\s*(?:\*|\/\/|\/\*)/u.test(s)) continue;
    if (!s.includes('new RegExp(')) continue;
    if (s.includes('String.raw')) continue;              // сырой литерал — лечение на месте
    const хвост = s.slice(s.indexOf('new RegExp('));
    const шаблон = хвост.match(/`[^`]*`/u);              // шаблонная строка в аргументах
    if (!шаблон) continue;
    /* Одиночная косая перед буквой класса: `(?<!\\)` отсекает уже удвоенную. */
    const беда = шаблон[0].match(/(?<!\\)\\[sdwbSDWBpP]/u);
    if (беда) найдено.push({ строка: i + 1, что: беда[0], текст: s.trim() });
  }
  return найдено;
}

function файлы(каталог) {
  const из = [];
  let записи;
  try { записи = readdirSync(каталог); } catch { return из; }
  for (const имя of записи) {
    if (ПРОПУСК.has(имя)) continue;
    const путь = join(каталог, имя);
    if (statSync(путь).isDirectory()) из.push(...файлы(путь));
    else if (/\.(mjs|js|ts|svelte)$/u.test(имя)) из.push(путь);
  }
  return из;
}

test('образец, собранный в шаблонной строке, не теряет экранирование', () => {
  const нарушения = [];
  for (const каталог of ОБХОД) {
    for (const путь of файлы(join(КОРЕНЬ, каталог))) {
      for (const н of опасныеСтроки(readFileSync(путь, 'utf8'))) {
        нарушения.push(`${путь.slice(КОРЕНЬ.length + 1)}:${н.строка} — «${н.что}» в шаблонной строке`);
      }
    }
  }
  assert.deepEqual(нарушения, [],
    'в шаблонной строке `\\s` — это буква s. Собирай образец String.raw либо удваивай косую');
});

// ── САМОТЕСТ САМОГО СТРАЖА: он обязан краснеть по делу и молчать на здоровом ────────────────

test('страж ловит подделку и молчит на здоровом коде', () => {
  /*
   * Образцы собираются ПОСИМВОЛЬНО, через код обратной косой. Иначе они зависели бы от того,
   * как экранирован сам этот файл, — а именно эту зависимость страж и ловит. Заодно страж не
   * ловит собственный самотест за руку.
   */
  const косая = String.fromCharCode(92);
  const беда = 'const RE = new RegExp(`${A}(?:' + косая + 's+(?:${A}|of))*`, "gu");';
  assert.equal(опасныеСтроки(беда).length, 1, 'одиночная косая в шаблонной строке — нарушение');
  assert.equal(опасныеСтроки(беда)[0].что, косая + 's');

  const лечение1 = 'const RE = new RegExp(A + String.raw`(?:' + косая + 's+)*`, "gu");';
  assert.equal(опасныеСтроки(лечение1).length, 0, 'String.raw — законное лечение');

  const лечение2 = 'const RE = new RegExp(`${A}(?:' + косая + косая + 's+)*`, "gu");';
  assert.equal(опасныеСтроки(лечение2).length, 0, 'удвоенная косая — тоже законное лечение');

  const литерал = 'const RE = /(?:' + косая + 's+)*/gu;';
  assert.equal(опасныеСтроки(литерал).length, 0, 'литерал регулярки страж не трогает');

  assert.equal(опасныеСтроки('const s = `просто ' + косая + 'sтекст`;').length, 0,
    'шаблонная строка вне new RegExp страж не трогает');
});
