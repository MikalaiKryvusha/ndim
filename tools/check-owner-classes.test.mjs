// Самотест прибора классов владельца.
// 🔴 РУССКАЯ ПРОВЕРКА ИДЁТ НА РУССКОМ ОБРАЗЦЕ (канон AGENT_GUIDE.md): каждый признак
// проверяется его же дословным словом — тем текстом, за который он вернул карточку, —
// и КОНТРОЛЕМ: законной строкой, на которой признак обязан молчать.

import test from 'node:test';
import assert from 'node:assert/strict';
import { scanCard, extractDates, RULES } from './check-owner-classes.mjs';

const СЕГОДНЯ = '2026-08-22';

/** Карточка-заготовка: даты в прошлом, чтобы класс 1 не шумел на чужих проверках. */
function карточка(ru, en = 'The film opened in cinemas on 7 May 2026.') {
  return { wikidata: 'Q1', title: { ru: 'Образец', en: 'Sample' }, description: { ru: `${ru} Картина вышла в прокат 7 мая 2026 года.`, en } };
}

const классы = (находки) => находки.map((s) => +s.match(/класс (\d)/)[1]);

test('предохранитель: подключение модуля не разобрало argv и не уронило процесс', () => {
  assert.ok(Array.isArray(RULES) && RULES.length === 7);
});

test('даты разбираются на обоих языках и приводятся к ISO', () => {
  assert.deepEqual(extractDates('вышла 7 мая 2026 года'), ['2026-05-07']);
  assert.deepEqual(extractDates('opened on 25 December 2025'), ['2025-12-25']);
  assert.deepEqual(extractDates('дат тут нет'), []);
});

test('класс 1: дата в БУДУЩЕМ ловится — это фильтр отбора, а не правка текста', () => {
  const н = scanCard({ description: { ru: 'Картина выйдет в прокат 14 декабря 2026 года.', en: 'It opens on 14 December 2026.' } }, СЕГОДНЯ);
  assert.ok(классы(н).includes(1), н.join('\n'));
});

test('🔴 мера класса 1 — САМАЯ РАННЯЯ дата, а не любая: вышедшее и допечатанное позже чисто', () => {
  const н = scanCard({ description: { ru: 'Игра вышла 19 июля 2022 года. Последнее издание выйдет в свет 28 мая 2027 года.', en: 'The game came out on 19 July 2022.' } }, СЕГОДНЯ);
  assert.deepEqual(н, [], 'объект ВЫШЕЛ; поздняя дата издания снятия с вычитки не требует');
});

test('🔴 контроль класса 1: вышедший объект молчит', () => {
  const н = scanCard(карточка('Действие происходит на Этернии.'), СЕГОДНЯ);
  assert.deepEqual(н, []);
});

test('класс 1: описание без единой даты честно объявляется непроверяемым', () => {
  const н = scanCard({ description: { ru: 'Сюжет о коте.', en: 'A story about a cat.' } }, СЕГОДНЯ);
  assert.ok(классы(н).includes(1));
});

test('класс 3: «Зато» и «Однако» в начале предложения ловятся', () => {
  assert.ok(классы(scanCard(карточка('Герой молчит. Зато мир говорит за него.'), СЕГОДНЯ)).includes(3));
  assert.ok(классы(scanCard(карточка('Герой молчит. Однако мир говорит.'), СЕГОДНЯ)).includes(3));
});

test('🔴 контроль класса 3: ЕГО СОБСТВЕННАЯ правка проходит — «не X, а Y» он оставил', () => {
  const н = scanCard(карточка('Картина смотрит не на зал заседаний, а на человека рядом с подсудимыми.'), СЕГОДНЯ);
  assert.deepEqual(н, [], 'его же образец обязан быть чистым');
});

test('класс 4: «первый полный метр» ловится — запрет термина', () => {
  assert.ok(классы(scanCard(карточка('Для Сафди это первый полный метр, снятый без брата.'), СЕГОДНЯ)).includes(4));
});

test('🔴 контроль класса 4: «полнометражная картина» и «хронометраж» чисты', () => {
  assert.deepEqual(scanCard(карточка('Полнометражная картина выросла из короткометражки. Хронометраж — 109 минут.'), СЕГОДНЯ), []);
});

test('класс 5: «Первые даты выхода» и «Даты выхода —» ловятся', () => {
  assert.ok(классы(scanCard(карточка('Первые даты выхода — 7 и 8 мая 2026 года.'), СЕГОДНЯ)).includes(5));
  assert.ok(классы(scanCard(карточка('Сюжет прост. Даты выхода — 22 и 23 января 2026 года.'), СЕГОДНЯ)).includes(5));
});

test('класс 5 английский: «The release dates are» ловится', () => {
  const н = scanCard(карточка('Сюжет прост.', 'The release dates are 22 and 23 January 2026.'), СЕГОДНЯ);
  assert.ok(классы(н).includes(5), н.join('\n'));
});

test('🔴 контроль класса 5: дата, поданная событием, чиста — это его собственная форма', () => {
  assert.deepEqual(scanCard(карточка('Картина представлена на фестивале 3 сентября 2025 года.'), СЕГОДНЯ), []);
});

test('класс 6: «Действие развёрнуто» и «Действие отнесено» ловятся', () => {
  assert.ok(классы(scanCard(карточка('Действие развёрнуто на планете Этерния.'), СЕГОДНЯ)).includes(6));
  assert.ok(классы(scanCard(карточка('Действие отнесено в Долину Санта-Клара.'), СЕГОДНЯ)).includes(6));
});

test('🔴 контроль класса 6: «Действие разворачивается» — его же правка — чисто', () => {
  assert.deepEqual(scanCard(карточка('Действие разворачивается на планете Этерния.'), СЕГОДНЯ), []);
});

test('класс 7: «поставила его», «производство осуществлено», «Литературной основой послужил»', () => {
  assert.ok(классы(scanCard(карточка('Фильм ужасов: поставила его Мэгги Джилленхол.'), СЕГОДНЯ)).includes(7));
  assert.ok(классы(scanCard(карточка('Производство осуществлено компанией Amblin.'), СЕГОДНЯ)).includes(7));
  assert.ok(классы(scanCard(карточка('Литературной основой послужил роман Леони Свонн.'), СЕГОДНЯ)).includes(7));
});

test('🔴 контроль класса 7: короткая форма «поставлен» чиста', () => {
  assert.deepEqual(scanCard(карточка('Фильм ужасов, поставлен Мэгги Джилленхол.'), СЕГОДНЯ), []);
});

test('класс 8: «тунисской режиссёром» — его собственный пример — ловится', () => {
  const н = scanCard(карточка('Драма, снятая тунисской режиссёром Каутер Бен Хания.'), СЕГОДНЯ);
  assert.ok(классы(н).includes(8), н.join('\n'));
});

test('🔴 контроль класса 8: «тунисским режиссёром» чисто, и «своей продюсерской работе» тоже', () => {
  assert.deepEqual(scanCard(карточка('Драма, снятая тунисским режиссёром Каутер Бен Хания.'), СЕГОДНЯ), []);
  assert.deepEqual(scanCard(карточка('В своей продюсерской работе он пошёл дальше.'), СЕГОДНЯ), [],
    'основа «продюсер\\p{L}*» объявила бы дефектом законное словосочетание');
});

test('класс 9: «музыка электронная» — его собственный пример — ловится', () => {
  const н = scanCard(карточка('Облик города плотный, музыка электронная.'), СЕГОДНЯ);
  assert.ok(классы(н).includes(9), н.join('\n'));
});

test('🔴 контроль класса 9: ЕГО формулировка полной фразой чиста', () => {
  assert.deepEqual(scanCard(карточка('Музыкальный ряд игры выполнен в электронном стиле.'), СЕГОДНЯ), []);
});

test('🔴 граница слова рядом с кириллицей: признак срабатывает и в середине текста', () => {
  const н = scanCard(карточка('Картина о войне, и действие развёрнуто в Европе.'), СЕГОДНЯ);
  assert.ok(классы(н).includes(6), 'ASCII-граница \\b здесь молчала бы');
});
