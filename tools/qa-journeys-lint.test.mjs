import test from 'node:test';
import assert from 'node:assert/strict';

import { спроситьПрогон, разобратьОтвет } from './lib/selftest-pair.mjs';

const ПРИБОР = 'qa-journeys-lint';
/** Образец строки, называющей РАЗМЕР КОРПУСА, — со своей группой-числом. */
const КОРПУС = /ИТОГО\s+(\d+)/;

test('🔴 ЗАПУЩЕН: прибор ответил, вышел нулём и ДОСТАЛ материал', () => {
  const r = спроситьПрогон(ПРИБОР);
  assert.notEqual(r.stdout.trim(), '', 'прибор не ответил вовсе — предохранитель или падение');
  const { число } = разобратьОтвет(r.stdout, КОРПУС);
  assert.notEqual(число, null, 'строка с размером корпуса не найдена — форма вывода сменилась');
  // Ноль осмотренного печатается тем же зелёным, что и полторы тысячи.
  assert.ok(число > 0, `осмотрено ${число} — зелёное на непрочитанном корпусе`);
  assert.equal(r.status, 0);
});

