/**
 * ЮНИТЫ ОБЩЕГО КАНАЛА ЗАМЕЧАНИЙ (`tools/lib/gate-notes.mjs`) и его подключения к ВОРОТАМ.
 *
 * 🔴 ГЛАВНОЕ ЗДЕСЬ — НЕ КОРЗИНА, А ПОДКЛЮЧЕНИЕ. Сам по себе канал прост до скуки; ценность его
 * в том, что им пользуются ОБА прибора, а не один. Ровно это и ломается молча: `proseNotes`
 * была написана, объявлена решением Менеджера «предъявлять, а не отказывать» — и не подключена
 * ни к одному прогону целые сутки (`EXP-0194`: «страж, не стоящий ни в одних воротах, не
 * защищает — он ЖДЁТ, пока о нём вспомнят»). Поэтому здесь стоят проверки, которые краснеют
 * при ОТКЛЮЧЕНИИ проверки от канала, а не только при поломке самой корзины.
 *
 * Прогон: node --test tools/gate-notes.test.mjs   ·   npm run test:tools
 */
import test from 'node:test';
import assert from 'node:assert/strict';

import { создатьКорзину, ЗАГОЛОВОК } from './lib/gate-notes.mjs';
import { proseProblems, proseNotes } from './lib/prose-gates.mjs';
import { checkEdit } from './rewrite-catalog-descriptions.mjs';

// ── Корзина ──────────────────────────────────────────────────────────────────────────────────

test('пустая корзина не печатает ни строки — заголовка без содержимого не бывает', () => {
  const к = создатьКорзину();
  assert.ok(к.пусто());
  assert.deepEqual(к.строкиОтчёта(), []);
});

test('замечание несёт ТРИ вещи: кто нашёл, где и что', () => {
  const к = создатьКорзину();
  к.добавить('строчная латиница', 'Обсессия (ru)', 'screenlife');
  const [, шапка, строка] = к.строкиОтчёта();
  assert.match(шапка, new RegExp(ЗАГОЛОВОК.replace(/[()]/gu, '\\$&')));
  assert.match(строка, /Обсессия \(ru\)/u, 'адрес: без него человек находку не найдёт');
  assert.match(строка, /строчная латиница/u, 'имя проверки: без него неясно, кому верить');
  assert.match(строка, /screenlife/u, 'само сообщение');
});

test('пустое сообщение в канал не попадает, а список добавляется целиком', () => {
  const к = создатьКорзину();
  к.добавить('проверка', 'адрес', '');
  assert.ok(к.пусто(), 'пустая строка — не замечание');
  к.добавитьВсе('ворота прозы', 'Кобра (en)', ['первое', 'второе']);
  к.добавитьВсе('ворота прозы', 'Кобра (ru)', []);
  assert.equal(к.список().length, 2, 'пустой список ничего не добавляет');
});

test('корзины разных прогонов не смешиваются', () => {
  const а = создатьКорзину();
  const б = создатьКорзину();
  а.добавить('п', 'а', 'сообщение');
  assert.ok(б.пусто(), 'у каждого прогона своя корзина, а не общий глобальный список');
});

// ── Подключение: то, ради чего канал заведён ─────────────────────────────────────────────────

test('ВОРОТА ПРАВОК отдают замечания вторым выходом, не ломая прежних потребителей', () => {
  /* «the score was composed by» — артефактное подлежащее. Решением Менеджера 2026-08-22 это
   * ЗАМЕЧАНИЕ, а не отказ: тот же оборот стоит в карточке, которую владелец одобрил. */
  const правка = {
    slug: 'x', lang: 'en',
    before: 'The film came out in 2019. Somebody wrote the music.',
    after: 'The film came out in 2019. The score was composed by Hans Zimmer.',
    replace: 'The score was composed by Hans Zimmer.',
  };
  const проблемы = checkEdit(правка);
  assert.ok(Array.isArray(проблемы), 'форма возврата прежняя — МАССИВ проблем');
  assert.equal(проблемы.length, 0, 'артефактное подлежащее отказом НЕ является');
  assert.equal(проблемы.замечания.length, 1, 'но человеку оно предъявляется');
  assert.match(проблемы.замечания[0], /расщеплённое сказуемое/u);
});

test('ВОРОТА ПРАВОК: настоящий класс-запрет остаётся ОТКАЗОМ, а не уезжает в замечания', () => {
  /* Контроль границы: если бы канал «смягчил» и этот оборот, ворота были бы разоружены. */
  const правка = {
    slug: 'x', lang: 'en',
    before: 'The film came out in 2019. Somebody made it.',
    after: 'The film came out in 2019. Production was carried out by Amblin Entertainment.',
    replace: 'Production was carried out by Amblin Entertainment.',
  };
  const проблемы = checkEdit(правка);
  assert.ok(проблемы.some((p) => /расщеплённое сказуемое/u.test(p)), 'производственное подлежащее — ОТКАЗ');
  assert.equal(проблемы.замечания.length, 0);
});

test('ВОРОТА ПРОЗЫ отдают отказы и замечания РАЗНЫМИ списками', () => {
  const надутый = 'Production was carried out by Amblin Entertainment.';
  const мягкий = 'The score was composed by Hans Zimmer.';
  assert.equal(proseProblems(надутый, 'en').length, 1);
  assert.equal(proseNotes(надутый, 'en').length, 0, 'отказ не дублируется замечанием');
  assert.equal(proseProblems(мягкий, 'en').length, 0);
  assert.equal(proseNotes(мягкий, 'en').length, 1);
});

test('русскую сторону английские ворота прозы не судят — ни отказом, ни замечанием', () => {
  const русский = 'Производство осуществлено компанией Amblin Entertainment.';
  assert.deepEqual(proseProblems(русский, 'ru'), []);
  assert.deepEqual(proseNotes(русский, 'ru'), []);
});
