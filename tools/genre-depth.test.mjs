/**
 * САМОТЕСТ ПРИЗНАКА «ГЛУБИНА ЖАНРА».
 *
 * 🔴 Входы РУССКИЕ — правило `AGENT_GUIDE.md` → «САМОТЕСТ РУССКОЙ ПРОВЕРКИ ИДЁТ НА РУССКОМ
 * ОБРАЗЦЕ». Английские случаи добавлены отдельно, они проверяют вторую половину словаря.
 *
 * Половина случаев — КОНТРОЛИ ЛОЖНЫХ СРАБАТЫВАНИЙ, найденные до прогона: слова «Играют»,
 * «Рассказывают», «повествует», «практически» роднятся с жанровыми основами и красились бы
 * первой редакцией словаря.
 *
 * Запуск: `node --test tools/genre-depth.test.mjs` либо `npm run test:tools`.
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { genreDepth, genreDepthOfSentence, depthShift, opensWithProduction, openingClass } from './lib/genre-depth.mjs';

/* Разбивателя своего у признака НЕТ и быть не должно: в бою ему передают тот же
 * `splitSentences`, которым разбивают текст ворота (`tools/lib/prose-gates.mjs`). Второй
 * разбиватель был бы второй правдой — класс, оплаченный этой же сменой. Здесь он подставлен
 * заглушкой ровно затем, чтобы проверить ПРОВОДКУ: что признак берёт первое предложение. */
const разбитьЗаглушкой = (t) => String(t).split(/(?<=[.!?])\s+/).filter(Boolean);

const гл = (s, lang = 'ru') => genreDepthOfSentence(s, lang).глубина;

test('эталон владельца: зачин о «Матрице» даёт глубину 2', () => {
  const s = 'Научно-фантастический боевик братьев Вачовски: они же написали сценарий, продюсировал Джоэл Сильвер.';
  assert.equal(гл(s), 2, 'жанр стоит вторым словом — так пишет сам владелец');
});

test('зачин с вида даёт глубину 1', () => {
  assert.equal(гл('Фильм рассказывает о человеке, который держит слово.'), 1);
});

test('производство впереди жанра уводит глубину вглубь', () => {
  const s = 'Сценарий написала Хиллари Сайц, поставил картину Кристофер Нолан.';
  assert.equal(гл(s), 6, 'жанровое слово «картину» стоит шестым');
});

test('🔴 контроль: «Играют Джейсон Стейтем…» НЕ жанр', () => {
  assert.equal(гл('Играют Джейсон Стейтем и Аннабелль Уоллис.'), null,
    '«Играют» роднится с основой «игра» и красилось первой редакцией словаря');
});

test('🔴 контроль: «Рассказывают её с начала» НЕ жанр', () => {
  assert.equal(гл('Рассказывают её с самого начала, от гибели родителей.'), null);
});

test('🔴 контроль: «повествует о жизни Моисея» НЕ жанр', () => {
  assert.equal(гл('Основан на библейской книге и повествует о жизни Моисея.'), 4,
    '«книге» — вид, и оно стоит четвёртым; «повествует» молчит, хотя роднится с «повесть»');
});

test('🔴 контроль: «практически» НЕ жанр', () => {
  assert.equal(гл('Практически весь замысел держится на одном выборе героя.'), null);
});

test('словоформы вида ловятся: «игре», «игру», «игры»', () => {
  assert.equal(гл('В игре двадцать четыре карты.'), 2);
  assert.equal(гл('Студия выпустила игру летом.'), 3);
});

test('составное слово через дефис считается одним', () => {
  assert.equal(гл('Научно-фантастический хоррор о выживании.'), 2,
    '«научно-фантастический» — одно слово, второе слово «хоррор»');
});

test('жанра нет вовсе — глубина null, а не большое число', () => {
  assert.equal(гл('Съёмки прошли в Хорватии осенью две тысячи двадцать пятого года.'), null);
});

test('английский: образец «Бессонницы» до и после правки', () => {
  assert.equal(гл('The 2002 American psychological thriller directed by Christopher Nolan is a remake.', 'en'), 4,
    'год «2002» считается словом: жанр на четвёртом');
  assert.equal(гл('Hillary Seitz wrote the screenplay and Christopher Nolan directed this 2002 American psychological thriller.', 'en'), 13,
    'та же правка отодвинула жанр с четвёртого слова на тринадцатое');
});

test('🔴 английский контроль: «Warner Brothers» НЕ жанр «war»', () => {
  assert.equal(гл('Warner Brothers published it in May.', 'en'), null,
    '«war» стоит ТОЧНОЙ формой именно поэтому: основа «war» покрасила бы Warner, warm, warrior');
});

test('⚠️ известная граница: видовое слово внутри имени предприятия признак не отличает', () => {
  assert.equal(гл('Warner Brothers Games published it in May.', 'en'), 3,
    '«Games» здесь часть имени, а не вид — прибор этого не видит, и цена направлена в безопасную '
    + 'сторону: текст выглядит лучше, чем он есть. Случай закреплён, а не починен.');
});

test('🔴 английский контроль: «features» и «shown» НЕ виды', () => {
  assert.equal(гл('It features a cast of newcomers and was shown at the festival.', 'en'), null);
});

test('глубина берётся по ПЕРВОМУ предложению, а не по лучшему', () => {
  const t = 'Съёмки шли в Северной Ирландии. Мрачная драма о состарившемся разбойнике.';
  assert.equal(genreDepth(t, 'ru', разбитьЗаглушкой).глубина, null,
    'второе предложение несёт жанр, но признак смотрит только первое');
});

test('сдвиг: ухудшение, улучшение, ровно и два разряда без числа', () => {
  const d = (n) => ({ глубина: n });
  assert.equal(depthShift(d(5), d(13)).исход, 'ухудшение');
  assert.equal(depthShift(d(5), d(13)).сдвиг, 8);
  assert.equal(depthShift(d(13), d(2)).исход, 'улучшение');
  assert.equal(depthShift(d(2), d(2)).исход, 'ровно');
  assert.equal(depthShift(d(2), d(null)).исход, 'жанр пропал');
  assert.equal(depthShift(d(null), d(2)).исход, 'жанр появился');
  assert.equal(depthShift(d(null), d(null)).сдвиг, null, 'разряд без числа не даёт числа');
});

/* ───────── ЗАЧИН ДЕЙСТВИТЕЛЬНЫМ ПРОИЗВОДСТВЕННЫМ ОБОРОТОМ ───────── */

test('русский зачин: «Снял её Ди Джей Карузо» — производство впереди', () => {
  const r = opensWithProduction('Снял её Ди Джей Карузо, а сыграли Аль Пачино и Рене Руссо.', 'ru');
  assert.equal(r.есть, true);
  assert.equal(r.место, 1);
});

test('русский зачин: имя перед глаголом тоже ловится в окне', () => {
  const r = opensWithProduction('Эльдар Рязанов поставил эту картину в 1977 году.', 'ru');
  assert.equal(r.есть, true, '«поставил» стоит третьим словом, за двумя словами имени');
  assert.equal(r.место, 3);
  assert.equal(openingClass('Эльдар Рязанов поставил эту картину в 1977 году.', 'ru').класс, 'производство',
    'производство на третьем слове, жанр («картину») на пятом — производство впереди');
});

test('🔴 контроль: производство ПОСЛЕ жанра зачином не считается', () => {
  const s = 'Мрачная драма о состарившемся разбойнике, которую снял Майкл Сарноски.';
  assert.equal(opensWithProduction(s, 'ru').есть, true, 'глагол в предложении есть');
  assert.equal(openingClass(s, 'ru').класс, 'жанр', 'но он стоит ПОСЛЕ жанра — это норма канона');
});

test('🔴 контроль: сюжетный глагол производственным не считается', () => {
  assert.equal(opensWithProduction('Коул Рид довозит мальчика живым до порта.', 'ru').есть, false);
});

test('английский зачин: «Devin Clark created this…» — производство впереди', () => {
  const r = opensWithProduction('Devin Clark created this American animated sitcom.', 'en');
  assert.equal(r.есть, true);
  assert.equal(r.место, 3);
});

test('🔴 слепое пятно доли меты в одном образце: залог сменили, производство осталось', () => {
  const было = 'The 2002 American psychological thriller directed by Christopher Nolan is a remake.';
  const стало = 'Hillary Seitz wrote the screenplay and Christopher Nolan directed this 2002 American psychological thriller.';
  assert.equal(openingClass(было, 'en').класс, 'жанр',
    'жанр на четвёртом слове, «directed» на шестом — производство ПОСЛЕ жанра, норма');
  assert.equal(openingClass(стало, 'en').класс, 'производство',
    'после правки «wrote» стоит третьим, а жанр уехал на тринадцатое — производство впереди');
});
