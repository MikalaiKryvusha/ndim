/** Версия Node как тройка чисел из строки вида `v23.6.1`. */
export function разобратьВерсию(строка) {
	const m = /^v?(\d+)\.(\d+)\.(\d+)/.exec(String(строка).trim());
	return m ? [Number(m[1]), Number(m[2]), Number(m[3])] : null;
}

/** Достаточна ли версия. Сравнение по старшинству, а не строкой: «v9» строкой больше «v23». */
export function версияГодна(версия, минимум = МИН_NODE) {
	if (!версия) return false;
	for (let i = 0; i < минимум.length; i += 1) {
		const порог = минимум[i] ?? 0;
		const своё = версия[i] ?? 0;
		if (своё > порог) return true;
		if (своё < порог) return false;
	}
	return true;
}

/**
 * Приговор пульсу по коду выхода прибора.
 *
 * 🔑 Здесь названа граница, которую легко пропустить: код 2 («отчёта нет вовсе») — это НЕ «жив» и
 * НЕ «просто стоит». Он значит, что сервер здесь никогда не работал, и для выката это красное.
 */
export function пульсЗелёный(код) {
	return код === 0;
}

/** ── ШАГИ ДВЕРИ ────────────────────────────────────────────────────────────────────────── */

function шаг(название) {
	console.log(`\n══ ${название} ══`);
}

function отказ(причина, лечение = null) {
	console.error(`\n🔴 ДВЕРЬ ОТКАЗАЛА: ${причина}`);
	if (лечение) console.error(`   Лечение: ${лечение}`);
	process.exit(1);
}

const git = (аргументы, каталог = '.') =>
	execFileSync('git', ['-C', каталог, ...аргументы], { encoding: 'utf8' }).trim();

/** Node, установленный в систему, — тот же выбор, что делает конфиг PM2. */
function системныйNode() {
	const кандидаты = [
		resolve(process.env.ProgramFiles ?? 'C:/Program Files', 'nodejs', 'node.exe'),
		resolve(process.env['ProgramFiles(x86)'] ?? 'C:/Program Files (x86)', 'nodejs', 'node.exe'),
	];
	return кандидаты.find((путь) => existsSync(путь)) ?? 'node';
}

function проверитьNode() {
	шаг('1. NODE УСТАНОВЛЕННОЙ СИСТЕМЫ');
	const путь = системныйNode();
	const строка = execFileSync(путь, ['--version'], { encoding: 'utf8' }).trim();
	const версия = разобратьВерсию(строка);
	console.log(`   ${путь} → ${строка}`);
	if (!версияГодна(версия)) {
		отказ(
			`Node ${строка} младше требуемой ${МИН_NODE.join('.')} — сервер импортирует ядро похожести исходником .ts`,
			'обновить Node в системе (не в nvm: PM2 берёт системный)',
		);
	}
	console.log(`   ✅ годится (нужно ≥ ${МИН_NODE.join('.')})`);
}

function проверитьДерево() {
	шаг('2. РАБОЧЕЕ ДЕРЕВО ЧИСТОЕ');
	const грязь = git(['status', '--porcelain']);
	if (грязь) {
		console.error(грязь.split('\n').slice(0, 10).map((s) => `   ${s}`).join('\n'));
		отказ(
			'в рабочем дереве есть незакоммиченные правки — выкатывается КОММИТ, а не содержимое диска',
			'закоммитить или спрятать правки, затем повторить',
		);
	}
	console.log('   ✅ чисто');
}

function проверитьКоммит(коммит) {
	шаг('3. КОММИТ СУЩЕСТВУЕТ И НЕСЁТ КОД СЕРВЕРА');
	let полный;
	try {
		полный = git(['rev-parse', '--verify', `${коммит}^{commit}`]);
	} catch {
		отказ(`коммита «${коммит}» в этом репозитории нет`);
	}
	const короткий = полный.slice(0, 7);
	const естьКод = git(['ls-tree', '--name-only', полный, 'sync-server/']);
	if (!естьКод) отказ(`в коммите ${короткий} нет каталога sync-server/ — выкатывать нечего`);
	console.log(`   ✅ ${короткий} — ${git(['log', '-1', '--format=%s', полный])}`);
	return полный;
}

function проверитьСтендПогашен() {
	шаг('4. СТЕНД ПОГАШЕН');
	// 🔴 Занятые порты дают ЛОЖНЫЙ красный у `test:sync` (капкан STATUS, воспроизведён дважды).
	const занятые = ПОРТЫ_СТЕНДА.filter((порт) => портЗанят(порт));
	if (занятые.length) {
		отказ(
			`порты стенда заняты: ${занятые.join(', ')} — прогон тестов сервера при живых эмуляторах даёт ложный красный`,
			'погасить стенд от КОРНЕВОГО pid (taskkill /PID <корень> /T /F) и дать портам освободиться',
		);
	}
	console.log(`   ✅ порты ${ПОРТЫ_СТЕНДА.join(', ')} свободны`);
}

function портЗанят(порт) {
	try {
		const вывод = execSync(
			`powershell -NoProfile -Command "(Get-NetTCPConnection -LocalPort ${порт} -State Listen -ErrorAction SilentlyContinue | Measure-Object).Count"`,
			{ encoding: 'utf8' },
		).trim();
		return Number(вывод) > 0;
	} catch {
		return false; // Не смогли спросить — не выдумываем «занят»; шаг 8 всё равно судит пульсом.
	}
}

function прогнатьТесты(коммит, к) {
	шаг('6. ТЕСТЫ СЕРВЕРА ПО ВЫКАТЫВАЕМОМУ КОММИТУ');
	// Прогон идёт в ЗАМОРОЖЕННОЙ копии, уже сдвинутой на коммит: проверяется то, что поедет,
	// а не то, что лежит в рабочем дереве. Их расхождение и есть весь смысл двери.
	console.log(`   npm run test:sync (в ${к.копия}, коммит ${коммит.slice(0, 7)})`);
	try {
		execSync('npm run test:sync', { cwd: к.копия, stdio: 'inherit' });
	} catch {
		return false;
	}
	return true;
}

function сдвинутьКопию(коммит, к) {
	шаг('5. ЗАМОРОЖЕННАЯ КОПИЯ СДВИГАЕТСЯ НА КОММИТ');
	git(['checkout', '--detach', коммит], к.копия);
	console.log(`   копия на ${git(['rev-parse', '--short', 'HEAD'], к.копия)}`);
	console.log('   npm install --omit=dev …');
	execSync('npm install --omit=dev', { cwd: resolve(к.копия, 'sync-server'), stdio: 'inherit' });
	console.log('   ✅ зависимости на месте');
}

function перезапустить(к) {
	шаг('7. СЛУЖБА ПЕРЕЗАПУСКАЕТСЯ');
	execSync(`pm2 restart ${к.служба}`, { stdio: 'inherit' });
}

/**
 * Пульс живой службы — ПРИБОРОМ, а не по «процесс поднялся».
 *
 * 🔴 Почему с ожиданием: отчёт в базу пишется тактом 60 с, и сразу после перезапуска прошлый удар
 * ещё свежий — то есть первая же проверка сказала бы «жив» о СТАРОМ отчёте. Ждём НОВЫЙ удар.
 */
function проверитьПульс(контур, { ждатьСекунд = 150 } = {}) {
	шаг('8. ПУЛЬС ЖИВОЙ СЛУЖБЫ (прибором)');
	const дедлайн = Date.now() + ждатьСекунд * 1000;
	for (let попытка = 1; ; попытка += 1) {
		const код = прогнатьПульс(контур);
		if (пульсЗелёный(код)) {
			console.log('   ✅ пульс жив');
			return true;
		}
		if (Date.now() >= дедлайн) {
			console.error(`   🔴 пульс не ожил за ${ждатьСекунд} с (код прибора ${код})`);
			return false;
		}
		console.log(`   попытка ${попытка}: пульса нет, ждём такт…`);
		execSync('powershell -NoProfile -Command "Start-Sleep -Seconds 30"');
	}
}

function прогнатьПульс(контур) {
	try {
		execFileSync(process.execPath, ['tools/read-server-pulse.mjs', '--contour', контур], {
			encoding: 'utf8',
			stdio: 'inherit',
		});
		return 0;
	} catch (ошибка) {
		return ошибка.status ?? 1;
	}
}

function прочитатьРасписку(к) {
	return existsSync(к.расписка) ? JSON.parse(readFileSync(к.расписка, 'utf8')) : null;
}

function выписатьРасписку(коммит, прежний, контур, к) {
	const расписка = {
		deployedAt: new Date().toISOString(),
		commit: коммит,
		commitShort: коммит.slice(0, 7),
		subject: git(['log', '-1', '--format=%s', коммит]),
		previousCommit: прежний,
		service: к.служба,
		worktree: к.копия,
		contour: контур,
		by: 'tools/deploy-sync-server.mjs',
	};
	writeFileSync(к.расписка, `${JSON.stringify(расписка, null, '\t')}\n`);
	console.log(`\n🧾 расписка выписана: ${к.расписка}`);
	return расписка;
}

/** ── САМОТЕСТ ──────────────────────────────────────────────────────────────────────────── */

function самотест() {
	const проверки = [
		['версия разбирается', () => разобратьВерсию('v23.6.1')?.join('.') === '23.6.1'],
		['мусор версией не считается', () => разобратьВерсию('не версия') === null],
		['23.6.0 годится', () => версияГодна([23, 6, 0])],
		['23.5.9 НЕ годится', () => !версияГодна([23, 5, 9])],
		['24.0.0 годится', () => версияГодна([24, 0, 0])],
		// 🔑 Ловушка строкового сравнения: «v9» строкой больше «v23», числами — меньше.
		['9.99.99 НЕ годится', () => !версияГодна([9, 99, 99])],
		['пульс зелёный только на нуле', () => пульсЗелёный(0) && !пульсЗелёный(1) && !пульсЗелёный(2)],
	];
	let провалов = 0;
	for (const [имя, проверка] of проверки) {
		const ок = проверка();
		console.log(`  ${ок ? '✅' : '🔴'} ${имя}`);
		if (!ок) провалов += 1;
	}
	console.log(`\n${провалов ? `🔴 провалов ${провалов}` : `✅ самотест чист: ${проверки.length}/${проверки.length}`}`);
	return провалов ? 1 : 0;
}

/** ── ГЛАВНАЯ ───────────────────────────────────────────────────────────────────────────── */

async function главная() {
	if (есть('--selftest')) return самотест();

	// ⛔ Контур называется ЯВНО и всегда: цена путаницы несимметрична (боевым ключом можно
	// перезаписать топы живых людей), поэтому молчаливого умолчания здесь нет.
	const контур = довод('--contour');
	if (!контур || !КОНТУРЫ[контур]) {
		отказ(
			`контур не назван либо неизвестен («${контур ?? '—'}»)`,
			`--contour prod | --contour stage. Известные: ${Object.keys(КОНТУРЫ).join(', ')}`,
		);
	}
	const к = КОНТУРЫ[контур];
	console.log(`ДВЕРЬ ВЫКАТА СЕРВЕРА СИНХРОНИЗАЦИИ · контур ${контур.toUpperCase()}`);
	console.log(`   копия ${к.копия} · служба ${к.служба}\n`);

	if (есть('--rollback')) {
		const расписка = прочитатьРасписку(к);
		if (!расписка?.previousCommit) {
			отказ('расписки с прежним коммитом нет — откатывать не на что', `посмотреть ${к.расписка}`);
		}
		console.log(`ОТКАТ на ${расписка.previousCommit.slice(0, 7)} (с ${расписка.commitShort})`);
		сдвинутьКопию(расписка.previousCommit, к);
		перезапустить(к);
		if (!проверитьПульс(контур)) отказ('после отката пульс не ожил — служба требует рук');
		выписатьРасписку(расписка.previousCommit, расписка.commit, контур, к);
		console.log('\n✅ ОТКАТ СОСТОЯЛСЯ, пульс жив.');
		return 0;
	}

	const запрошен = довод('--commit');
	if (!запрошен) {
		отказ(
			'не назван коммит',
			'node tools/deploy-sync-server.mjs --contour <контур> --commit <коммит>  (порядок порций — plans/85)',
		);
	}

	if (!existsSync(к.копия)) {
		отказ(
			`замороженной копии нет: ${к.копия}`,
			`git worktree add --detach ${к.копия} <коммит> && npm --prefix ${к.копия}/sync-server install --omit=dev`,
		);
	}

	const прежний = git(['rev-parse', 'HEAD'], к.копия);
	console.log(`   сейчас в контуре: ${прежний.slice(0, 7)}`);

	проверитьNode();
	проверитьДерево();
	const коммит = проверитьКоммит(запрошен);

	if (коммит === прежний) {
		console.log('\n✅ этот коммит уже в контуре — делать нечего.');
		return 0;
	}

	проверитьСтендПогашен();

	if (есть('--dry')) {
		console.log(`\n(--dry: дальше выкатил бы ${коммит.slice(0, 7)} вместо ${прежний.slice(0, 7)}; контур не тронут)`);
		return 0;
	}

	сдвинутьКопию(коммит, к);

	if (!прогнатьТесты(коммит, к)) {
		console.error('\n🔴 тесты сервера по этому коммиту КРАСНЫЕ — откатываю копию, служба не тронута.');
		сдвинутьКопию(прежний, к);
		отказ('тесты выкатываемого коммита не прошли', 'починить код и повторить');
	}

	перезапустить(к);

	if (!проверитьПульс(контур)) {
		console.error('\n🔴 ПУЛЬС НЕ ОЖИЛ — АВТОМАТИЧЕСКИЙ ОТКАТ.');
		сдвинутьКопию(прежний, к);
		перезапустить(к);
		if (!проверитьПульс(контур)) {
			отказ('откат выполнен, но пульс не ожил и на прежнем коммите — служба требует рук');
		}
		отказ(`коммит ${коммит.slice(0, 7)} убивает службу; контур возвращён на ${прежний.slice(0, 7)}`);
	}

	выписатьРасписку(коммит, прежний, контур, к);
	console.log(`\n✅ ВЫКАТ СОСТОЯЛСЯ: ${прежний.slice(0, 7)} → ${коммит.slice(0, 7)}, пульс жив.`);
	console.log(`   Откат одной командой: node tools/deploy-sync-server.mjs --contour ${контур} --rollback`);
	return 0;
}

