test('регрессия 2 — причастие УПРАВЛЯЕТ, а не согласуется (правило Н3)', () => {
  // Шесть ложных на текстах живого каталога: страдательное причастие + творительный = деятель.
  const страдательные = проверить('Шутер, разработанный студией Gearbox Software и выпущенный компанией 2K Games.');
  assert.equal(страдательные.подозрения.length, 0);
  assert.ok(страдательные.снятоН3.length >= 2, 'деятель при причастии не распознан');

  // Действительное причастие + винительный = прямое дополнение.
  const действительное = проверить('Компания, продюсировавшая картину, объявила о продолжении.');
  assert.equal(действительное.подозрения.length, 0);
  assert.equal(действительное.снятоН3.length, 1);

  // И признак, на котором это стоит, проверяется напрямую.
  assert.ok(причастиеУправляет(разборПрилагательного('снятый'), ['твор']));
  assert.ok(причастиеУправляет(разборПрилагательного('продюсировавшая'), ['вин']));
  assert.ok(!причастиеУправляет(разборПрилагательного('тунисской'), ['твор']),
    '«тунисской» — не причастие; снимать с него подозрение нельзя');
});

test('регрессия 3 — адъективное окончание не делает слово прилагательным', () => {
  // «кругом», «Положение», «совмещение», «теплее», «которой» ловились одним окончанием.
  for (const слово of ['кругом', 'положение', 'совмещение', 'теплее', 'которой', 'значение']) {
    assert.equal(разборПрилагательного(слово), null, `«${слово}» разобрано как прилагательное`);
  }
  // А настоящие прилагательные и причастия — разбираются.
  for (const слово of ['тунисской', 'норвежского', 'бельгийским', 'снятая', 'разработанный']) {
    assert.notEqual(разборПрилагательного(слово), null, `«${слово}» НЕ разобрано как прилагательное`);
  }
});

test('регрессия 4 — предложная форма судится только после предлога и только при предложном существительном', () => {
  // «…и в этом игра стоит ближе к суровой школе…»: «в этом» — законченная предложная группа,
  // «игра» — подлежащее следующего оборота. Подозрения здесь нет.
  assert.equal(проверить('Бой требует счёта, и в этом игра стоит ближе к японским боевикам.').подозрения.length, 0);
  // Существительное в творительном («делом», «трудом») не должно читаться как предложное
  // прилагательное. Проверяем на паре, где такое слово стоит перед известным существительным.
  assert.equal(проверить('Он занят делом режиссёра.').подозрения.length, 0);
});

test('регрессия 5 — сравнительная степень неизменяема и не согласуется', () => {
  // «…для PlayStation 5, позднее игра вышла на Xbox One…» — форма на «-ее» омонимична
  // среднему роду, а сравнительная степень не согласуется ни с чем.
  const р = проверить('Релиз состоялся для PlayStation 5, позднее игра вышла на Xbox One.');
  assert.equal(р.подозрения.length, 0);
  assert.equal(р.снятоОмонимией.length, 1, 'снятое омонимией обязано быть посчитано, а не пропущено молча');
});

test('множественное число не судится — это законная конструкция при числительном', () => {
  // Розенталь §193: «два высоких дома». Прилагательное во мн. ч., существительное в ед. ч.
  const р = проверить('Игру делали два независимых разработчика.');
  assert.equal(р.подозрения.length, 0);
  assert.equal(р.множественных, 1, 'пропущенное по множественному числу обязано быть посчитано');
});

