test('покрытие печатается и оно ЧЕСТНО НИЗКОЕ — прибор судит малую долю текста', () => {
  const наши = померить(текстыПартий());
  // Это утверждение стоит здесь не ради числа, а ради честности: «прогон зелёный» НЕ значит
  // «в партии нет грамматических ошибок». Прибор судит долю пар, и доля названа.
  assert.ok(наши.пар > 500, 'адъективных пар слишком мало — корпус или разбор сломались');
  assert.ok(наши.известных / наши.пар < 0.5,
    'покрытие внезапно выросло выше половины — это условие пересмотра решения о словаре словоформ,'
    + ' а не повод править тест (разведка §7)');
});
