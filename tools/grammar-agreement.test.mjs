test('корпус: на текстах владельца ноль подозрений, и этот ноль ОСМЫСЛЕН', () => {
  const каталог = померить(срезКаталога());
  assert.equal(каталог.подозрения.length, 0,
    `ложные срабатывания на живом каталоге: ${JSON.stringify(каталог.подозрения.map((п) => п.цитата))}`);

  // 🔴 ПРОВЕРКА ВТОРОГО РОДА (третий вопрос лестницы). Ноль читается двояко — «беды нет» или
  // «прибор слеп». Различает их только показ того, что на ЭТОМ материале прибор способен
  // работать: он разобрал пары, опознал существительные и принял решение молчать ОСМЫСЛЕННО —
  // по правилу Н3, назвав снятое поимённо.
  assert.ok(каталог.известных > 50, `опознано существительных ${каталог.известных} — слишком мало, ноль недоказателен`);
  assert.ok(каталог.снятоН3.length >= 10,
    `снято правилом Н3 ${каталог.снятоН3.length} — ожидалось не меньше 10; ноль подозрений не подтверждён`);
});

test('корпус: в наших партиях названо ровно то, что вернул владелец', () => {
  const наши = померить(текстыПартий());
  assert.equal(наши.подозрения.length, 1,
    `ожидалось одно подозрение, получено: ${JSON.stringify(наши.подозрения.map((п) => п.цитата))}`);
  assert.equal(наши.подозрения[0].адрес, 'Q135038882');
  assert.equal(наши.подозрения[0].цитата, 'тунисской режиссёром');
});

