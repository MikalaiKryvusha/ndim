const ВОЗВРАТ_ВЛАДЕЛЬЦА =
  'Драма 2025 года, снятая тунисской режиссёром Каутер Бен Хания по собственному сценарию.';

test('Н1: «тунисской режиссёром» названо, и названо именно правилом рода', () => {
  const р = проверить(ВОЗВРАТ_ВЛАДЕЛЬЦА);
  assert.equal(р.подозрения.length, 1, 'ожидалось ровно одно подозрение');
  const [п] = р.подозрения;
  assert.equal(п.цитата, 'тунисской режиссёром');
  // 🔑 Ярлык обязан быть Н1 (род), а не абстрактное «форма не согласована»: владелец назвал
  // ошибку именно родом — «Режиссёр - Он Мой, мужской род».
  assert.equal(п.правило, 'Н1');
  assert.match(п.почему, /мужской род/u);
  assert.match(п.почему, /твор/u);
});

