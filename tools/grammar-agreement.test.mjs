// 4. 🔴 МУТАЦИЯ МАТЕРИАЛА — внести ошибку, получить крик; убрать, получить молчание
// ═══════════════════════════════════════════════════════════════════════════════════════════
//
// Требование постановки Менеджера дословно: «внеси заведомо неверное согласование — прибор
// обязан его назвать; убери — обязан замолчать».
//
// 🔑 И ТРЕТИЙ ВОПРОС ЛЕСТНИЦЫ, ради которого этот блок написан так, а не иначе: «мог ли МАТЕРИАЛ
// дать проверке упасть». Мутант обязан ОТЛИЧАТЬСЯ от исходника не только байтом, но и поведением.
// Поэтому каждая мутация ниже сначала ПРЕДЪЯВЛЯЕТ строку, на которой мутант обязан вести себя
// иначе, и утверждает про исходник ноль, а про мутанта — единицу. Совпади они — мутация не
// состоялась, и набор обязан упасть, а не проехать.

const МУТАЦИИ = [
  {
    что: 'род определения при роли: мужской → женский',
    исходник: 'Американский триллер 2001 года, снятый известным режиссёром Ричардом Келли.',
    мутант: 'Американский триллер 2001 года, снятый известной режиссёром Ричардом Келли.',
    ожидаемая: 'известной режиссёром',
    правило: 'Н1',
  },
  {
    что: 'падеж определения: творительный → именительный',
    исходник: 'Работа с бельгийским режиссёром продолжалась год.',
    мутант: 'Работа с бельгийский режиссёром продолжалась год.',
    ожидаемая: 'бельгийский режиссёром',
    правило: 'Н2',
  },
  {
    что: 'род определения при существительном женского рода',
    исходник: 'Съёмки вела независимая студия из Осло.',
    мутант: 'Съёмки вёл независимый студия из Осло.',
    ожидаемая: 'независимый студия',
    правило: 'Н1',
  },
];

for (const м of МУТАЦИИ) {
  test(`мутация — ${м.что}`, () => {
    // Шаг 1. ИСХОДНИК обязан молчать. Иначе мутация ничего не докажет: прибор кричал бы и так.
    const до = проверить(м.исходник);
    assert.equal(до.подозрения.length, 0,
      `исходник уже даёт подозрение — мутация ничего не докажет: ${JSON.stringify(до.подозрения)}`);

    // Шаг 2. МУТАНТ ОБЯЗАН ОТЛИЧАТЬСЯ ОТ ИСХОДНИКА. Подстановка, легшая в строку без изменения
    // поведения, — это «мутант, которому не на чем покраснеть».
    assert.notEqual(м.мутант, м.исходник, 'мутант тождествен исходнику — подстановка не состоялась');

    // Шаг 3. Мутант обязан быть НАЗВАН, и назван поимённо.
    const после = проверить(м.мутант);
    assert.equal(после.подозрения.length, 1,
      `мутант не назван прибором: ${м.мутант}`);
    assert.equal(после.подозрения[0].цитата, м.ожидаемая);
    assert.equal(после.подозрения[0].правило, м.правило);

    // Шаг 4. Убрать мутацию — прибор обязан ЗАМОЛЧАТЬ (симметрия, а не только крик).
    assert.equal(проверить(м.исходник).подозрения.length, 0);
  });
}

test('мутация в ЖИВОЙ карточке партии: прибор ловит её там, где она реально живёт', () => {
  // 🔴 Границы слова здесь — `(?!\p{L})`, а НЕ `\b`. В JavaScript `\b` определён через ASCII, и
  // флаг `u` этого не чинит: на кириллице он даёт неверные границы молча. Первая редакция этого
  // юнита была написана с `\b` и упала — правило `AGENT_GUIDE.md` поймало собственный тест.
  // Карточка выбирается ПО ОБРАЗЦУ МУТАЦИИ, а не по одному слову: карточка, где «режиссёра»
  // стоит без определения («Тема для режиссёра давняя»), подстановку не примет, и юнит упал бы
  // на пустой замене вместо настоящей проверки.
  const ОБРАЗЕЦ = /(\p{L}+?)(ого|его)\s+режиссёра(?!\p{L})/u;
  const карточки = текстыПартий();
  const чистая = карточки.find((к) => к.адрес !== 'Q135038882' && ОБРАЗЕЦ.test(к.текст));
  assert.ok(чистая, 'в партиях не нашлось пары «определение + режиссёра» — фикстура устарела');

  // Исходная карточка молчит…
  assert.equal(проверить(чистая.текст).подозрения.length, 0,
    `выбранная карточка ${чистая.адрес} уже даёт подозрение — возьми другую`);

  // …портим согласование прямо в её тексте…
  const мутант = чистая.текст.replace(ОБРАЗЕЦ, '$1ой режиссёра');
  assert.notEqual(мутант, чистая.текст, 'подстановка не легла в текст карточки');

  // …и прибор обязан её назвать.
  const р = проверить(мутант);
  assert.equal(р.подозрения.length, 1, `мутация в живой карточке ${чистая.адрес} не поймана`);
  assert.equal(р.подозрения[0].правило, 'Н1');
});

