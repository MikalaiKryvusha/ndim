/**
 * СТРАЖ ПРИБОРА РАЗМЕТКИ — доказывает `tools/tag-dims-approval.mjs` НА ЖИВОЙ БАЗЕ стенда.
 *
 * Юниты держат чистое ядро (`tag-dims-approval.test.mjs`), но пишущий прибор ими не доказан:
 * запись в базу, отказ-предохранитель и неприкосновенность публичного поля живут ровно там, где
 * юнита нет. Этот страж гоняет прибор как ЧЁРНЫЙ ЯЩИК — запускает его отдельным процессом и
 * судит по базе, а не по его собственным словам (`TESTING_FRAMEWORK.md`: вердикт снимается с
 * базы, а не с экрана).
 *
 * Что доказывается, по порядку:
 *   1. ОТКАЗ: служебное значение в публичном `tags` останавливает прибор (код 3), и он не пишет;
 *   2. СУХОЙ ПРОГОН: разбор напечатан числами, сумма сошлась, запись вне свода названа отдельно,
 *      в базе после него — НИ ОДНОГО `techTags`;
 *   3. МУТАЦИЯ: подменённый порог роняет проверку разбора, и прибор ОТКАЗЫВАЕТСЯ писать (код 1);
 *   4. ЗАПИСЬ: классы легли в `techTags` ровно те, что известны человеку заранее; запись вне
 *      свода осталась БЕЗ тега; поле `tags` побайтово то же, что до прогона;
 *   5. ПОВТОР: второй `--apply` не пишет ничего (квота записей не тратится на известное).
 *
 * Запуск (эмулятор поднимается на время прогона и гасится сам):
 *   firebase emulators:exec --only firestore,auth,storage --project demo-ndim-dev
 *     "node tools/seed-dev.mjs && node tools/verify-tag-dims-approval.mjs"
 */
import { spawnSync } from 'node:child_process';
import { initializeApp } from 'firebase-admin/app';
import { getFirestore } from 'firebase-admin/firestore';

const ФИКСТУРА = 'tools/fixtures/wiki-overlap-stand';
const ПРИБОР = 'tools/tag-dims-approval.mjs';

/**
 * ОЖИДАНИЕ, ИЗВЕСТНОЕ ЧЕЛОВЕКУ, — а не вычисленное тем же прибором.
 *
 * Список набран руками по фикстуре (`tools/fixtures/wiki-overlap-stand/README.md`). Спрашивать
 * класс у самого прибора значило бы проверять его им же: сошлось бы всегда, включая случай, когда
 * разбор сломан.
 */
const ЖДЁМ = {
  cats: 'needs-rewrite',
  travel: 'needs-rewrite',
  'star-wars-1977': 'needs-rewrite',
  silence: 'unchecked',
  math: 'unchecked',
  'taxi-driver-1976': 'migrated',
  'rocky-4-1985': 'migrated',
  'alchemist-1988': 'migrated',
  theatre: 'migrated',
  running: 'migrated',
  'spider-man-2002': 'migrated',
  yoga: 'migrated',
};
/** Запись, которой в своде НЕТ: класс ей присваивать запрещено. */
const ВНЕ_СВОДА = 'early-rising';

process.env.FIRESTORE_EMULATOR_HOST ??= '127.0.0.1:8181';
initializeApp({ projectId: process.env.GCLOUD_PROJECT ?? 'demo-ndim-dev' });
const db = getFirestore();

let провалов = 0;
const шаг = (ok, текст) => {
  if (!ok) провалов += 1;
  console.log(`  ${ok ? '✅' : '❌'} ${текст}`);
};

/** Запуск прибора отдельным процессом: страж судит по коду выхода и выводу, как человек. */
function прибор(...args) {
  const r = spawnSync(process.execPath, [ПРИБОР, '--contour', 'stand', '--svod-dir', ФИКСТУРА, ...args], {
    encoding: 'utf8',
    env: process.env,
  });
  return { код: r.status, вывод: `${r.stdout ?? ''}${r.stderr ?? ''}` };
}

/** Снимок каталога: `tags` и `techTags` каждой записи. Им же доказывается неприкосновенность. */
async function снимок() {
  const snap = await db.collection('dims').get();
  const out = {};
  for (const doc of snap.docs) {
    if (doc.id === 'dims_list') continue;
    const d = doc.data() ?? {};
    out[doc.id] = { tags: [...(d.tags ?? [])], techTags: d.techTags ? [...d.techTags] : undefined };
  }
  return out;
}

console.log('\n═══ СТРАЖ ПРИБОРА РАЗМЕТКИ (plans/58 шаг 1) — стенд ═══');

const до = await снимок();
console.log(`Каталог стенда: ${Object.keys(до).length} записей · фикстура-свод: ${ФИКСТУРА}`);

// ── 1. ОТКАЗ-ПРЕДОХРАНИТЕЛЬ ────────────────────────────────────────────────────────────────
console.log('\n1. Служебное значение в ПУБЛИЧНОМ поле tags — прибор обязан отказаться');
const жертва = 'cats';
await db.collection('dims').doc(жертва).update({ tags: [...(до[жертва].tags ?? []), 'needs-rewrite'] });
const отказ = прибор();
шаг(отказ.код === 3, `код выхода ${отказ.код} (ждём 3)`);
шаг(/ОТКАЗ/.test(отказ.вывод) && отказ.вывод.includes(жертва), 'отказ назван и виновная запись указана');
const послеОтказа = await снимок();
шаг(
  Object.values(послеОтказа).every((d) => d.techTags === undefined),
  'ни одной записи не размечено — отказ случился ДО записи',
);
await db.collection('dims').doc(жертва).update({ tags: до[жертва].tags });

// ── 2. СУХОЙ ПРОГОН ────────────────────────────────────────────────────────────────────────
console.log('\n2. Сухой прогон: разбор числами, сумма сошлась, ничего не записано');
const сухой = прибор();
шаг(сухой.код === 0, `код выхода ${сухой.код} (ждём 0)`);
for (const [класс, сколько] of Object.entries(
  Object.values(ЖДЁМ).reduce((a, c) => ({ ...a, [c]: (a[c] ?? 0) + 1 }), {}),
)) {
  шаг(new RegExp(`${класс}\\s+${сколько}\\b`).test(сухой.вывод), `${класс}: ${сколько}`);
}
шаг(/① сумма разбора сошлась/.test(сухой.вывод), '① сумма разбора сошлась с числом записей каталога');
шаг(/② вывод и ярлыки свода согласны/.test(сухой.вывод), '② вывод согласен с ярлыками свода');
/*
 * Записей вне свода на стенде БОЛЬШЕ одной: сид добавляет 36 проб `probe-NN`
 * (`tools/seed-dev.mjs:217`) сверх тринадцати именованных. Это и есть модель боевой правды —
 * каталог вырос после того, как свод сняли, — поэтому число берётся из каталога, а не зашивается.
 */
const внеСвода = Object.keys(до).length - Object.keys(ЖДЁМ).length;
шаг(
  new RegExp(`ЗАПИСЕЙ НЕТ В СВОДЕ: ${внеСвода}\\b`).test(сухой.вывод),
  `записи вне свода сосчитаны: ${внеСвода} из ${Object.keys(до).length}`,
);
шаг(
  new RegExp(`^\\s+${ВНЕ_СВОДА}\\s`, 'm').test(сухой.вывод),
  `каждая названа по идентификатору — проверено на ${ВНЕ_СВОДА}`,
);
const послеСухого = await снимок();
шаг(
  Object.values(послеСухого).every((d) => d.techTags === undefined),
  'после сухого прогона в базе НИ ОДНОГО techTags',
);

// ── 3. МУТАЦИЯ ─────────────────────────────────────────────────────────────────────────────
console.log('\n3. МУТАЦИЯ: порог подменён так, что копии считаются чистыми');
const мутант = прибор('--run-threshold', '30', '--apply');
шаг(мутант.код === 1, `код выхода ${мутант.код} (ждём 1 — отказ записи)`);
шаг(/РАЗОШЛИСЬ/.test(мутант.вывод), 'проверка ② покраснела: вывод и ярлыки свода разошлись');
шаг(
  /needs-rewrite\s+1\s+\(по ярлыкам свода 3\)/.test(мутант.вывод),
  'числа разбора сдвинулись: копия в 28 слов объявлена чистой, needs-rewrite 3 → 1',
);
шаг(/ОТКАЗ ЗАПИСИ/.test(мутант.вывод), 'прибор отказался писать по красным числам');
const послеМутации = await снимок();
шаг(
  Object.values(послеМутации).every((d) => d.techTags === undefined),
  'мутантный прогон не записал НИЧЕГО',
);

// ── 4. ЗАПИСЬ ──────────────────────────────────────────────────────────────────────────────
console.log('\n4. Запись: классы легли в techTags, публичное поле не тронуто');
const запись = прибор('--apply', '--backup');
шаг(запись.код === 0, `код выхода ${запись.код} (ждём 0)`);
шаг(/💾 Снимок каталога ДО записи/.test(запись.вывод), 'снимок каталога положен в .private/ ДО записи');
const после = await снимок();
let классовВерно = 0;
for (const [id, класс] of Object.entries(ЖДЁМ)) {
  const got = после[id]?.techTags ?? [];
  if (got.length === 1 && got[0] === класс) классовВерно += 1;
  else шаг(false, `${id}: ждём [${класс}], в базе [${got.join(', ')}]`);
}
шаг(классовВерно === Object.keys(ЖДЁМ).length, `классы совпали у ${классовВерно}/${Object.keys(ЖДЁМ).length} записей`);
шаг(после[ВНЕ_СВОДА]?.techTags === undefined, `${ВНЕ_СВОДА} остался БЕЗ тега — класс ему не придуман`);
const тегиЦелы = Object.keys(до).every(
  (id) => JSON.stringify(до[id].tags) === JSON.stringify(после[id]?.tags),
);
шаг(тегиЦелы, 'публичное поле tags побайтово то же, что до прогона — ни у одной записи');

// ── 5. ПОВТОР ──────────────────────────────────────────────────────────────────────────────
console.log('\n5. Повторный прогон: квота записей не тратится на известное');
const повтор = прибор('--apply');
шаг(повтор.код === 0, `код выхода ${повтор.код} (ждём 0)`);
шаг(/К записи: 0\b/.test(повтор.вывод), 'к записи 0 — прибор идемпотентен');

console.log(провалов ? `\n❌ СТРАЖ КРАСНЫЙ: провалов ${провалов}` : '\n✅ СТРАЖ ЗЕЛЁНЫЙ: все проверки пройдены');
process.exit(провалов ? 1 : 0);
