/**
 * ГРЕП RU-КАТАЛОГА ПО МАРКЕРАМ СПРАВОЧНОГО СТИЛЯ — заказ владельца 2026-08-16, дословно:
 * «*тогда и русские текста нужно будет править, они тоже из википедии могли писаться*».
 *
 * 🔴 ПОЧЕМУ ОТДЕЛЬНЫЙ ПРИБОР, А НЕ ФЛАГ У АНГЛИЙСКОГО. У них разные маркеры, разный выход и свой
 * контрольный случай у каждого. Английское сито проверено полем в тот же день (из 14 сверенных
 * текстов у шести нашёлся дословный ряд), русское — своей сверкой, ниже.
 *
 * 🔑 ЧЕГО ЭТОТ СПИСОК НЕ ДОКАЗЫВАЕТ — то же, что и у английского, и это не формальность:
 * **маркер ≠ заимствование.** «Премьера состоялась» — обычная русская фраза о премьере, а не
 * улика. Список отвечает на вопрос «что проверять глазами», а не «что переписать».
 *
 * ✅ КОНТРОЛЬНЫЙ СЛУЧАЙ НАЙДЕН ЗАМЕРОМ В ТОТ ЖЕ ДЕНЬ — `two-for-the-money-1myjyafy` («Деньги на
 * двоих»). Наше описание открывалось строкой «американский спортивный драматический фильм 2005
 * года режиссёра Ди Джея Карузо с Аль Пачино, Мэттью Макконахи и Рене Руссо в главных ролях», а
 * ru.wikipedia — «американский спортивно-драматический кинофильм 2005 года режиссёра Ди Джея
 * Карузо с Аль Пачино, Мэттью Макконахи, Рене Руссо и Карли Поуп в главных ролях»: ряд около
 * 20 слов.
 *
 * 🔑 Почему это важнее одной правки: §10 проверил 10 русских текстов и объявил их чистыми — то
 * есть выборка из десяти дала НОЛЬ там, где заимствование есть. «Проверено выборкой» никогда не
 * значит «в каталоге этого нет».
 *
 * ⛔ Прежде чем править ПО МАРКЕРУ, прочти шапку `plans/56` шаг 3: маркер ловит примерно половину
 * настоящих случаев, а сам дословный ряд обычно ВЫХОДИТ ЗА ПРЕДЕЛЫ предложения с маркером.
 *
 * Запуск:  node tools/grep-ru-boilerplate.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';

const SRC = 'src/lib/content/dims-build.json';
const OUT = 'researches/34_ru_boilerplate_candidates.md';

/**
 * Маркеры выбраны НЕ по вкусу, а по замеру частоты на самом каталоге: в список вошли обороты,
 * которыми русская Википедия открывает раздел о производстве и премьере. Число рядом с каждым —
 * сколько записей его несут на момент заведения прибора (2026-08-16).
 */
const MARKERS = [
  { имя: 'премьера состоялась', re: /премьера состоялась/i },
  { имя: 'В главных ролях', re: /В главных ролях/i },
  { имя: 'Съёмки проходили', re: /[СC]ъёмки проходили/i },
  { имя: 'озвучил / озвучивает', re: /озвуч(ил|ила|ивает|ивают)/i },
  { имя: 'роль исполнил', re: /роль исполн(ил|ила|или)/i },
  { имя: 'транслировался', re: /транслировал(ся|ась|ись)/i },
  { имя: 'вышел в прокат', re: /вышел[а]? в (широкий )?прокат/i },
  { имя: 'мировая премьера', re: /мировая премьера/i },
  { имя: 'состоит из N сезонов', re: /состоит из \d+ сезон/i },
];

const dims = JSON.parse(readFileSync(SRC, 'utf8'));
const sentencesOf = (text) => text.split(/(?<=[.!?])\s+/);

const found = [];
for (const d of dims) {
  const ru = d.description?.ru ?? '';
  if (!ru) continue;
  const hits = [];
  for (const s of sentencesOf(ru)) {
    const markers = MARKERS.filter((m) => m.re.test(s)).map((m) => m.имя);
    if (markers.length) hits.push({ предложение: s.trim(), маркеры: markers });
  }
  if (hits.length) found.push({ slug: d.slug, title: d.title?.ru ?? d.slug, type: d.type?.ru ?? '—', hits });
}
found.sort((a, b) => (a.slug < b.slug ? -1 : 1));

/**
 * Контроль прибора: известный положительный случай обязан найтись, иначе греп ослеп и его числам
 * верить нельзя. ⚠️ Когда фаза ВЫЛЕЧИТ этот текст, проверка упадёт — и это не поломка, а сигнал
 * перевесить контроль на другой живой случай (ровно так уже случилось с английским прибором).
 */
const CONTROL_SLUG = 'two-for-the-money-1myjyafy';
if (!found.some((f) => f.slug === CONTROL_SLUG)) {
  console.error(
    `ОШИБКА СКРИПТА: контрольный случай ${CONTROL_SLUG} («Деньги на двоих», подтверждён сверкой с ` +
      'ru.wikipedia 2026-08-16) в список не попал — греп слеп, его числам верить нельзя.',
  );
  process.exit(1);
}

const byMarker = {};
for (const f of found) for (const h of f.hits) for (const m of h.маркеры) byMarker[m] = (byMarker[m] ?? 0) + 1;

const lines = [
  '# Кандидаты RU-каталога со справочным стилем (маркеры Википедии)',
  '',
  `> **Создан:** 2026-08-16 скриптом \`tools/grep-ru-boilerplate.mjs\` · **Заказ владельца:**`,
  '> «тогда и русские текста нужно будет править, они тоже из википедии могли писаться» ·',
  '> **Родитель:** `plans/56` шаг 3 · **Статус:** список снят; **правок в данных 0**.',
  '',
  `Проверено записей каталога: **${dims.length}** · записей с маркерами: **${found.length}**.`,
  '',
  '**Частота маркеров** (одно предложение может нести несколько):',
  '',
  ...Object.entries(byMarker).sort((a, b) => b[1] - a[1]).map(([k, v]) => `- \`${k}\` — ${v}`),
  '',
  '🔴 **ЧЕГО ЭТОТ СПИСОК НЕ ДОКАЗЫВАЕТ.** Маркер — это СИТО, а не приговор: «премьера состоялась» —',
  'обычная русская фраза. Английский опыт того же дня показал обе стороны: сито ловит настоящее',
  'заимствование примерно в половине случаев, но заимствование при этом ВЫХОДИТ ЗА ПРЕДЕЛЫ',
  'предложения с маркером — то есть правка «по маркеру» даёт ложное «сделано».',
  '',
  '✅ **СИТО ПРОВЕРЕНО ПОЛЕМ.** Контрольный случай — `two-for-the-money-1myjyafy` («Деньги на двоих»):',
  'сверка с ru.wikipedia 2026-08-16 дала ряд около 20 слов почти дословно. Это же и опровергает',
  'прежний вывод §10 `researches/34` («10 русских текстов чисты»): выборка из десяти дала НОЛЬ там,',
  'где заимствование есть. «Проверено выборкой» никогда не значит «в каталоге этого нет».',
  '',
  '**Порог, которым судим** (тот же, что у английской половины): дословный ряд от 10 слов, не',
  'являющийся именем собственным или неизбежным обозначением.',
  '',
  '---',
  '',
];
for (const f of found) {
  lines.push(`## \`${f.slug}\` · ${f.type} · ${f.title}`, '');
  for (const h of f.hits) lines.push(`- [${h.маркеры.join(', ')}] «${h.предложение}»`);
  lines.push('');
}

writeFileSync(OUT, lines.join('\n'), 'utf8');
console.log(`Записей с маркерами: ${found.length} из ${dims.length}`);
console.log(`Частота: ${JSON.stringify(byMarker, null, 0)}`);
console.log(`Записано: ${OUT}`);
console.log(`Контроль ${CONTROL_SLUG}: в списке — прибор не ослеп.`);
