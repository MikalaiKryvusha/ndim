/**
 * ЮНИТЫ СБОРЩИКА РАЗВЁРТКИ (`tools/build-flow-map.mjs`).
 *
 * 🔴 ГЛАВНОЕ ЗДЕСЬ — НЕ РАЗМЕТКА, А ТРИ ОБЕЩАНИЯ ЛИСТА, каждое из которых легко потерять молча:
 *   1) **самодостаточность** — в собранном файле НЕТ ни одной внешней ссылки. Стоит кому-то
 *      подключить шрифт или скрипт с CDN, и лист перестанет открываться без интернета, а владелец
 *      узнает об этом в самолёте, а не здесь (замер проекта: все 43 макета в `design/` — нулевые
 *      по внешним ссылкам, и развёртка вошла в этот же класс сознательно);
 *   2) **отказ на кривом манифесте** — связь в несуществующий экран обязана ронять сборку, а не
 *      рисовать стрелку в пустоту;
 *   3) **пара «истина ↔ зеркало»** — HTML собирается ИЗ манифеста, поэтому правка манифеста обязана
 *      быть видна в HTML. Если зеркало перестало зависеть от истины, пара мертва (`EXP-0274`).
 * Плюс обязательный по канону проекта вызов `--selftest` дочерним процессом: прибор, чью
 * самопроверку никто не зовёт, стережёт до первой правки (`census-selftest-coverage.mjs`).
 *
 * Прогон: node --test tools/build-flow-map.test.mjs   ·   npm run test:tools
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

import { стыковка, проверить } from './build-flow-map.mjs';

const СБОРЩИК = 'tools/build-flow-map.mjs';
const ЛИСТ = 'design/flow-map.html';

test('САМОТЕСТ сборщика зовётся отсюда и обязан быть зелёным', () => {
  const r = spawnSync(process.execPath, [join(process.cwd(), СБОРЩИК), '--selftest'], { encoding: 'utf8' });
  const вывод = (r.stdout ?? '') + (r.stderr ?? '');
  assert.equal(r.status, 0, `самотест упал:\n${вывод}`);
  assert.match(вывод, /самопроверка сборщика развёртки пройдена/u);
});

test('манифест с битой связью РОНЯЕТ проверку — стрелок в пустоту не бывает', () => {
  const беды = проверить({ 'экраны': [{ id: 'a', x: 0, y: 0 }], 'связи': [{ 'от': 'a', 'к': 'призрак' }] });
  assert.equal(беды.length, 1);
  assert.match(беды[0], /призрак/u, 'отказ обязан НАЗВАТЬ несуществующий экран, а не просто сказать «ошибка»');
});

test('здоровый манифест молчит — страж без ложных тревог', () => {
  assert.deepEqual(
    проверить({ 'экраны': [{ id: 'a', x: 0, y: 0 }, { id: 'b', x: 600, y: 0 }], 'связи': [{ 'от': 'a', 'к': 'b' }] }),
    [],
  );
});

test('стыковка выводит линию из БОРТА карточки, а не из её середины', () => {
  const г = стыковка({ x: 0, y: 0 }, { x: 900, y: 0 });
  assert.equal(г.x1, 390, 'по горизонтали выходим из правого борта');
  assert.ok(г.y1 > 0 && г.y1 < 964, 'по вертикали — из середины борта');
  const в = стыковка({ x: 0, y: 0 }, { x: 0, y: 1400 });
  assert.equal(в.x1, 195, 'по вертикали выходим из середины нижнего борта');
  assert.equal(в.y1, 964, 'нижний борт = высота снимка плюс шапка карточки');
});

test('СОБРАННЫЙ ЛИСТ самодостаточен: ни одной внешней ссылки', { skip: !existsSync(ЛИСТ) }, () => {
  const html = readFileSync(ЛИСТ, 'utf8');
  const внешние = html.match(/(?:src|href)="(?!data:|#)[^"]*"/gu) ?? [];
  assert.deepEqual(внешние, [], `лист тянет наружу: ${внешние.join(' · ')}`);
  assert.match(html, /src="data:image\/png;base64,/u, 'снимки обязаны быть вшиты, а не приложены файлами');
});

test('ПАРА ЖИВА: каждый экран манифеста виден в собранном листе', { skip: !existsSync(ЛИСТ) }, () => {
  const м = JSON.parse(readFileSync('design/flow-map/flow-map.json', 'utf8'));
  const html = readFileSync(ЛИСТ, 'utf8');
  for (const э of м['экраны']) {
    assert.ok(html.includes(`data-id="${э.id}"`), `экрана «${э.id}» нет в листе — зеркало отстало от истины`);
    assert.ok(html.includes(э['имя']), `имя «${э['имя']}» не доехало до листа`);
  }
  // Размер листа тоже приезжает из манифеста: если перестанет — раскладка будет врать.
  assert.ok(html.includes(`width:${м['лист']['ширина']}px`), 'ширина листа в HTML разошлась с манифестом');
});
