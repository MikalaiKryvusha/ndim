/**
 * ЮНИТЫ СБОРЩИКА РАЗВЁРТКИ (`tools/build-flow-map.mjs`).
 *
 * 🔴 ГЛАВНОЕ ЗДЕСЬ — НЕ РАЗМЕТКА, А ТРИ ОБЕЩАНИЯ ЛИСТА, каждое из которых легко потерять молча:
 *   1) **самодостаточность** — в собранном файле НЕТ ни одной внешней ссылки. Стоит кому-то
 *      подключить шрифт или скрипт с CDN, и лист перестанет открываться без интернета, а владелец
 *      узнает об этом в самолёте, а не здесь (замер проекта: все 43 макета в `design/` — нулевые
 *      по внешним ссылкам, и развёртка вошла в этот же класс сознательно);
 *   2) **отказ на кривом манифесте** — связь в несуществующий экран обязана ронять сборку, а не
 *      рисовать стрелку в пустоту;
 *   3) **пара «истина ↔ зеркало»** — HTML собирается ИЗ манифеста, поэтому правка манифеста обязана
 *      быть видна в HTML. Если зеркало перестало зависеть от истины, пара мертва (`EXP-0274`).
 * Плюс обязательный по канону проекта вызов `--selftest` дочерним процессом: прибор, чью
 * самопроверку никто не зовёт, стережёт до первой правки (`census-selftest-coverage.mjs`).
 *
 * Прогон: node --test tools/build-flow-map.test.mjs   ·   npm run test:tools
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

import { стыковка, проверить, полосы, разместитьПодписи, указатели, КАРТА_В } from './build-flow-map.mjs';

test('🔑 на ЖИВОМ манифесте ни одна труба не проходит сквозь карточку и ни один указатель не стоит под ней', { skip: !existsSync('design/flow-map/flow-map.json') }, () => {
  // Класс пойман владельцем дважды за день («нет стрелочек в начале» — они были под карточкой;
  // трубы между рядами шли сквозь экраны промежуточных рядов). Проверяется чистой геометрией,
  // без браузера: отрезки труб (кроме концов, входящих в борт) и центры указателей против
  // прямоугольников всех карточек манифеста.
  const m = JSON.parse(readFileSync(join(process.cwd(), 'design/flow-map/flow-map.json'), 'utf8'));
  const поId = Object.fromEntries(m['экраны'].map((э) => [э.id, э]));
  const карточки = m['экраны'].map((э) => ({ id: э.id, x: э.x, y: э.y, w: 390, h: КАРТА_В }));
  const внутри = (x, y) => карточки.find((c) => x > c.x + 1 && x < c.x + c.w - 1 && y > c.y + 1 && y < c.y + c.h - 1);
  const беды = [];
  for (const т of полосы(m['связи'], поId)) {
    const имя = `${т.с['от']} → ${т.с['к']}`;
    for (let k = 0; k < т.точки.length - 1; k++) {
      const [x0, y0] = т.точки[k], [x1, y1] = т.точки[k + 1];
      const l = Math.hypot(x1 - x0, y1 - y0);
      // концы трубы входят в борт — первые и последние 24 единицы законно касаются карточки
      for (let s = k === 0 ? 24 : 0; s <= l - (k === т.точки.length - 2 ? 24 : 0); s += 8) {
        const c = внутри(x0 + ((x1 - x0) / l) * s, y0 + ((y1 - y0) / l) * s);
        if (c) { беды.push(`труба ${имя} проходит сквозь «${c.id}»`); break; }
      }
    }
    for (const у of указатели(т.точки)) {
      const c = внутри(у.x, у.y);
      if (c) беды.push(`указатель трубы ${имя} стоит под «${c.id}»`);
    }
  }
  assert.deepEqual(беды, []);
});

test('🔑 подпись сама уходит от чужой трубы и от соседней подписи (слово владельца: «инструмент должен сам разруливать»)', () => {
  // Три карточки в ряд: a → c длинной трубой (обход снизу) и b → c короткой. Наивная середина
  // длинного отрезка обхода лежит ровно там, где проходит вертикаль второй трубы.
  const экраны = [
    { id: 'a', x: 0, y: 0 }, { id: 'b', x: 900, y: 0 }, { id: 'c', x: 1800, y: 0 },
  ];
  const поId = Object.fromEntries(экраны.map((э) => [э.id, э]));
  const связи = [
    { 'от': 'a', 'к': 'c', 'подпись': 'длинная дорога вокруг' },
    { 'от': 'b', 'к': 'c', 'подпись': 'короткая' },
    { 'от': 'a', 'к': 'b', 'подпись': 'соседняя' },
  ];
  const трассы = полосы(связи, поId);
  const места = разместитьПодписи(трассы, экраны);
  assert.equal(места.size, 3, 'каждая подпись обязана получить место');

  const прям = ([x1, y1], [x2, y2], поле = 5) => ({ x: Math.min(x1, x2) - поле, y: Math.min(y1, y2) - поле, w: Math.abs(x2 - x1) + поле * 2, h: Math.abs(y2 - y1) + поле * 2 });
  const бьёт = (r, q) => !(q.x > r.x + r.w || q.x + q.w < r.x || q.y > r.y + r.h || q.y + q.h < r.y);
  const боксы = [];
  for (const т of трассы) {
    const м = места.get(т.i);
    // подпись не лежит ни на одной ЧУЖОЙ трубе
    for (const д of трассы) {
      if (д.i === т.i) continue;
      for (let k = 0; k < д.точки.length - 1; k++) {
        assert.ok(!бьёт(прям(д.точки[k], д.точки[k + 1]), м.box), `«${т.с['подпись']}» легла на трубу «${д.с['подпись']}»`);
      }
    }
    // и не на карточке
    for (const э of экраны) assert.ok(!бьёт({ x: э.x, y: э.y, w: 390, h: КАРТА_В }, м.box), `«${т.с['подпись']}» легла на карточку ${э.id}`);
    for (const z of боксы) assert.ok(!бьёт(z, м.box), `«${т.с['подпись']}» легла на другую подпись`);
    боксы.push(м.box);
  }
});

const СБОРЩИК = 'tools/build-flow-map.mjs';
const ЛИСТ = 'design/flow-map.html';

test('САМОТЕСТ сборщика зовётся отсюда и обязан быть зелёным', () => {
  const r = spawnSync(process.execPath, [join(process.cwd(), СБОРЩИК), '--selftest'], { encoding: 'utf8' });
  const вывод = (r.stdout ?? '') + (r.stderr ?? '');
  assert.equal(r.status, 0, `самотест упал:\n${вывод}`);
  assert.match(вывод, /самопроверка сборщика развёртки пройдена/u);
});

test('манифест с битой связью РОНЯЕТ проверку — стрелок в пустоту не бывает', () => {
  const беды = проверить({ 'экраны': [{ id: 'a', x: 0, y: 0 }], 'связи': [{ 'от': 'a', 'к': 'призрак' }] });
  assert.equal(беды.length, 1);
  assert.match(беды[0], /призрак/u, 'отказ обязан НАЗВАТЬ несуществующий экран, а не просто сказать «ошибка»');
});

test('здоровый манифест молчит — страж без ложных тревог', () => {
  assert.deepEqual(
    проверить({ 'экраны': [{ id: 'a', x: 0, y: 0 }, { id: 'b', x: 600, y: 0 }], 'связи': [{ 'от': 'a', 'к': 'b' }] }),
    [],
  );
});

test('стыковка выводит линию из БОРТА карточки, а не из её середины', () => {
  const г = стыковка({ x: 0, y: 0 }, { x: 900, y: 0 });
  assert.equal(г.x1, 390, 'по горизонтали выходим из правого борта');
  assert.ok(г.y1 > 0 && г.y1 < КАРТА_В, 'по вертикали — из середины борта');
  const в = стыковка({ x: 0, y: 0 }, { x: 0, y: 1400 });
  assert.equal(в.x1, 195, 'по вертикали выходим из середины нижнего борта');
  // Нижний борт — ВМЕСТЕ с заметкой (2026-09-05): геометрия без заметки прятала стартовые
  // треугольники под карточку, владелец увидел трубы «без стрелочек в начале».
  assert.equal(в.y1, КАРТА_В, 'нижний борт = шапка + снимок + заметка, одна константа на разметку и геометрию');
});

test('СОБРАННЫЙ ЛИСТ самодостаточен: ни одной внешней ссылки', { skip: !existsSync(ЛИСТ) }, () => {
  const html = readFileSync(ЛИСТ, 'utf8');
  const внешние = html.match(/(?:src|href)="(?!data:|#)[^"]*"/gu) ?? [];
  assert.deepEqual(внешние, [], `лист тянет наружу: ${внешние.join(' · ')}`);
  assert.match(html, /src="data:image\/png;base64,/u, 'снимки обязаны быть вшиты, а не приложены файлами');
});

test('ПАРА ЖИВА: каждый экран манифеста виден в собранном листе', { skip: !existsSync(ЛИСТ) }, () => {
  const м = JSON.parse(readFileSync('design/flow-map/flow-map.json', 'utf8'));
  const html = readFileSync(ЛИСТ, 'utf8');
  for (const э of м['экраны']) {
    assert.ok(html.includes(`data-id="${э.id}"`), `экрана «${э.id}» нет в листе — зеркало отстало от истины`);
    assert.ok(html.includes(э['имя']), `имя «${э['имя']}» не доехало до листа`);
  }
  // Размер листа тоже приезжает из манифеста: если перестанет — раскладка будет врать.
  assert.ok(html.includes(`width:${м['лист']['ширина']}px`), 'ширина листа в HTML разошлась с манифестом');
});
