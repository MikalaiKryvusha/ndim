#!/usr/bin/env node
/**
 * СОГЛАСОВАНИЕ ВОКРУГ ИМЕНИ «МЕНЕДЖЕР ИЗМЕРЕНИЙ» — напарник `verify-dims-manager-name.mjs`.
 *
 * ═══ ЗАЧЕМ ОТДЕЛЬНЫЙ ПРИБОР ═══
 *
 * Страж имени следит, чтобы слова «комната» не было. Он НЕ следит за тем, во что превращается
 * фраза после замены, — а «комната» женского рода, «Менеджер измерений» мужского, и согласование
 * едет по всему предложению. Менеджер команды попробовал заменить слепо по падежам и откатил;
 * его собственная порча, дословно: «Менеджер измерений построенА» · «первАЯ Менеджер измерений» ·
 * «остальные МенеджерА измерений въезжают» · «ОтдельнОЙ Менеджера измерений не будет».
 * 🔑 То есть слепая замена производит ровно тот дефект, за который владелец ругает нас в карточках
 * (класс 8 его критических замечаний: «*Прилагательное к существительному режиссёр. Режиссёр — Он
 * Мой, мужской род*»). Страж имени зелёный и на испорченном тексте — значит нужен второй.
 *
 * ═══ 🔴 ПОЧЕМУ НЕ ВЗЯТ ОБЩИЙ ПРИБОР СОГЛАСОВАНИЯ dev-2 ═══
 *
 * Взят и ЗАМЕРЕН первым делом — `tools/lib/grammar-agreement.mjs` (ветка `ndim_dev2`). На этом
 * материале он СЛЕП, и это показано числами, а не предположено:
 *   · все ПЯТЬ примеров порчи выше дают у него **0 подозрений**;
 *   · покрытие на переименованных строках — **0 известных пар из 28**.
 * Причина честная и не в его качестве: его лексикон собран под описания карточек, слова
 * «менеджер» и «измерений» в нём нет, а вне лексикона прибор молчит — о чём его собственная
 * шапка предупреждает прямо («ноль подозрений при нулевом покрытии — это слепота, а не чистота»).
 * Расширять чужой лексикон из этой ветки нельзя: территория dev-2.
 *
 * Поэтому здесь узкая проверка ровно на одно имя — и она СПОСОБНА покраснеть на этом материале,
 * что доказано самотестом на всех пяти живых примерах порчи.
 *
 * ═══ ЧТО ИЩЕТСЯ ═══
 *
 * Женский или множественный род, приклеившийся к мужскому имени, — с ОБЕИХ сторон:
 *   ⛔ слева:  «эта Менеджер измерений» · «первая Менеджер измерений» · «Отдельной Менеджера»
 *   ⛔ справа: «Менеджер измерений построена» · «Менеджер измерений открыта»
 *   ⛔ само имя в чужой форме: «МенеджерА измерений въезжают» (мн. ч. от мужского — «менеджерЫ»)
 *
 * ⚠️ ЧЕСТНАЯ ГРАНИЦА: список определителей и причастий закрытый и короткий. Прибор ловит частые
 * следы слепой замены, а не всю грамматику русского языка — за ней идти к прибору dev-2, когда
 * его лексикон дорастёт. Пропуск здесь дешевле ложной тревоги: вечно красный страж приучает себя
 * игнорировать (та же граница объявлена у соседей).
 *
 * Запуск:
 *   node tools/verify-dims-manager-agreement.mjs [путь ...]
 *   node tools/verify-dims-manager-agreement.mjs --selftest
 */
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

/** Имя в любой падежной форме — левая опора для обеих проверок. */
const ИМЯ = '[Мм]енеджер(?:а|у|ом|е|ы|ов|ам|ами|ах)?\\s+измерени(?:й|я|ю|ем|и|ями|ях)';

/** Определители женского рода единственного числа — то, что осталось от «комнаты». */
const ЖЕНСКИЕ_СЛЕВА = 'эта|Эта|та|Та|одна|Одна|перва[яю]|Перва[яю]|втора[яю]|Втора[яю]|нова[яю]|Нова[яю]'
  + '|этой|Этой|той|Той|одной|Одной|первой|Первой|отдельной|Отдельной|отдельна[яю]|Отдельна[яю]'
  + '|прежн[яю]я|Прежн[яю]я|сама|Сама|всю|Всю|эту|Эту|ту|Ту|нашей|Нашей|наша|Наша|наду|каждая|Каждая';

/** Краткие причастия и прилагательные женского рода — то, что осталось справа. */
const ЖЕНСКИЕ_СПРАВА = 'построена|открыта|закрыта|сделана|готова|заперта|создана|написана|снята'
  + '|видна|нужна|принята|отдана|занята|полна|пуста|жива|мертва|разобрана|проверена|доработана';

export const ОБРАЗЦЫ = [
  [new RegExp(`(?:${ЖЕНСКИЕ_СЛЕВА})\\s+${ИМЯ}`, 'u'),
    'женский определитель перед мужским именем'],
  [new RegExp(`${ИМЯ}\\s+(?:${ЖЕНСКИЕ_СПРАВА})(?![а-яё])`, 'u'),
    'краткое причастие женского рода после мужского имени'],
  /*
   * «МенеджерА измерений въезжают» — множественное сказуемое при единственном имени.
   * ⚠️ Флаг `i` здесь ОБЯЗАТЕЛЕН и поставлен не для красоты: живая порча пишется «МенеджерА» —
   * с ПРОПИСНОЙ «А», потому что слепая замена приклеивает окончание к слову, набранному с
   * большой буквы. Первая редакция образца искала только строчную и этот случай пропускала;
   * поймано собственным самотестом.
   */
  [new RegExp('менеджера\\s+измерений\\s+(?:въезжают|стоят|открыты|построены|живут|едут)', 'iu'),
    'множественное сказуемое при единственном имени'],
];

/** Проверка одной строки. Экспорт — ради самотеста и чужих ворот. */
export function подозрения(строка) {
  return ОБРАЗЦЫ.filter(([re]) => re.test(строка)).map(([, имя]) => имя);
}

const ПРОПУСК = /(^|[\\/])(node_modules|\.git|\.svelte-kit|build|dist|test-results)([\\/]|$)/;
const РАСШИРЕНИЯ = /\.(md|ts|js|mjs|svelte|json|rules)$/;

function обойти(путь, собрано = []) {
  if (ПРОПУСК.test(путь)) return собрано;
  const с = statSync(путь);
  if (с.isDirectory()) {
    for (const и of readdirSync(путь)) обойти(join(путь, и), собрано);
  } else if (РАСШИРЕНИЯ.test(путь)) собрано.push(путь);
  return собрано;
}

const runAsScript = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;

if (runAsScript && process.argv.includes('--selftest')) {
  /*
   * 🔴 ВСЕ ПЯТЬ ПОЛОЖИТЕЛЬНЫХ ОБРАЗЦОВ — ЖИВАЯ ПОРЧА, снятая с отката Менеджера, а не выдуманная.
   * Отрицательные стоят ПАРОЙ к ним и порознь бессмысленны: без них зелёным был бы и прибор,
   * который краснеет на всём подряд.
   */
  const случаи = [
    ['Менеджер измерений построена ради одного', 1],
    ['первая Менеджер измерений панели', 1],
    ['остальные МенеджерА измерений въезжают', 1],
    ['Отдельной Менеджера измерений не будет', 1],
    ['эта Менеджер измерений открыта', 2],
    // ✅ Исправные формы — обязаны молчать.
    ['Менеджер измерений построен ради одного', 0],
    ['первый экран панели — Менеджер измерений', 0],
    ['этот Менеджер измерений открыт', 0],
    ['До этого Менеджера измерений завести измерение было нельзя', 0],
    ['только `admin` видит Менеджер измерений', 0],
    // ✅ Чужое слово «комната» здесь не судится — на то есть страж имени.
    ['эта комната построена', 0],
  ];
  let плохо = 0;
  случаи.forEach(([с, ждали], i) => {
    const было = подозрения(с).length;
    const ок = было === ждали;
    if (!ок) плохо += 1;
    console.log(`  ${ок ? '✅' : '❌'} случай ${i + 1}: ${было}, ожидалось ${ждали} — «${с}»`);
  });
  console.log(плохо ? `\n❌ самотест провален: ${плохо}` : `\n✅ самотест пройден: ${случаи.length} случаев`);
  process.exit(плохо ? 1 : 0);
}

if (runAsScript) {
  const цели = process.argv.slice(2).filter((a) => !a.startsWith('--'));
  const файлы = (цели.length ? цели : ['.']).flatMap((п) => обойти(п));
  let нарушений = 0;
  for (const ф of файлы) {
    const строки = readFileSync(ф, 'utf8').split(/\r?\n/);
    строки.forEach((с, i) => {
      for (const имя of подозрения(с)) {
        нарушений += 1;
        console.log(`❌ ${ф}:${i + 1}\n   ${с.trim().slice(0, 110)}\n   ${имя}`);
      }
    });
  }
  console.log(`\nпросмотрено файлов: ${файлы.length}`);
  console.log(нарушений
    ? `❌ СОГЛАСОВАНИЕ СЛОМАНО В ${нарушений} МЕСТАХ — «Менеджер измерений» мужского рода.`
    : '✅ согласование вокруг имени «Менеджер измерений» цело.');
  process.exit(нарушений ? 1 : 0);
}
