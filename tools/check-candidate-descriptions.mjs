/** Текст статьи по ТОЧНОМУ заголовку. `redirects` — перенаправления ведут к настоящей странице. */
async function страницаПоЗаголовку(lang, заголовок) {
  const page = await api(lang, {
    action: 'query', prop: 'extracts', explaintext: '1', redirects: '1', titles: заголовок,
  });
  const первая = Object.values(page?.query?.pages ?? {})[0];
  if (!первая || первая.missing !== undefined || !первая.extract) return null;
  return { title: первая.title ?? заголовок, text: первая.extract };
}

/**
 * Текст статьи об объекте или `null` («статьи нет» либо «спросить не удалось»).
 * Вся логика порядка — в `статьяОбъекта` выше; здесь только настоящие запросы к сети.
 */
async function articleText(lang, c) {
  return статьяОбъекта(lang, c, {
    реестр: (l, qid) => заголовокИзРеестра(l, qid, api).catch(() => null),
    страница: (l, заголовок) => страницаПоЗаголовку(l, заголовок).catch(() => null),
    поиск: async (l, карточка) => {
      const kind = карточка.type?.[l] ?? '';
      const year = карточка.year && карточка.year !== '-' ? карточка.year : '';
      const запрос = `${карточка.title?.[l] ?? ''} ${kind} ${year}`.trim();
      const search = await api(l, { action: 'query', list: 'search', srsearch: запрос, srlimit: '1' })
        .catch(() => null);
      return search?.query?.search?.[0]?.title ?? null;
    },
  });
}

