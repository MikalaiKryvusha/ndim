/** Один запрос к API с кэшем на диск. Ключ — ПОЛНЫЙ хеш адреса (`EXP`: обрезанный
 *  ключ однажды свалил все статьи в один файл и дал «97 чистых» на копиях).
 *  `lang` — код языкового раздела Википедии либо `wikidata` для самого реестра. */
async function api(lang, params) {
  // `wikidata` — не язык, а отдельный хост: тождество объекта живёт там, а не в языковом разделе.
  const host = lang === 'wikidata' ? 'https://www.wikidata.org' : `https://${lang}.wikipedia.org`;
  const url = `${host}/w/api.php?${new URLSearchParams({ ...params, format: 'json' })}`;
  const key = join(CACHE, `${lang}-${createHash('sha256').update(url).digest('hex')}.json`);
  if (existsSync(key)) return JSON.parse(readFileSync(key, 'utf8'));
  await sleep(DELAY_MS);
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  const data = await res.json();
  writeFileSync(key, JSON.stringify(data), 'utf8');
  return data;
}

