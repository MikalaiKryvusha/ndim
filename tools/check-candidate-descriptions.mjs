/**
 * Вердикт по непроверенному — отдельной функцией, потому что лечение у него своё:
 * не «перепиши описание», а «объясни, почему у партии нет статей, либо подними границу».
 */
export function unverifiedFaults(unverified, всего, доля = UNVERIFIED_SHARE, допуск = UNVERIFIED_TOLERANCE) {
  if (!Number.isFinite(всего) || всего <= 0) return [];
  if (unverified <= допуск) return [];
  const часть = unverified / всего;
  if (часть <= доля) return [];
  const пц = (x) => `${(x * 100).toFixed(1).replace('.', ',')} %`;
  return [
    `НЕПРОВЕРЕННОГО ${unverified} из ${всего} половин — ${пц(часть)} при объявленной границе ${пц(доля)}. ` +
      'Гарантия «ворота проверили заимствования» истинна при нуле непроверенного; на такой доле ' +
      'прибор проверил меньше, чем пропустил. Законная единица границу не трогает — значит дело ' +
      'в партии: назови, почему статей нет, либо подними границу осознанной правкой',
  ];
}

/**
 * Зачин, повторяющий название карточки, — ОТКАЗ (разбор в шапке). Кавычки всех начертаний
 * снимаются: «Обсессия» и "Obsession" — то же нарушение, что и голое Nuremberg.
 */
export function opensWithTitle(title, text) {
  const norm = (x) => String(x ?? '')
    .replace(/[«»"'“”„]/gu, '')
    .replace(/\s+/gu, ' ')
    .trim()
    .toLowerCase();
  const имя = norm(title);
  const тело = norm(text);
  if (имя.length < 2 || !тело) return false;
  return тело.startsWith(имя);
}

