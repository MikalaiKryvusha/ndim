/**
 * Зачин, повторяющий название карточки, — ОТКАЗ (разбор в шапке). Кавычки всех начертаний
 * снимаются: «Обсессия» и "Obsession" — то же нарушение, что и голое Nuremberg.
 */
export function opensWithTitle(title, text) {
  const norm = (x) => String(x ?? '')
    .replace(/[«»"'“”„]/gu, '')
    .replace(/\s+/gu, ' ')
    .trim()
    .toLowerCase();
  const имя = norm(title);
  const тело = norm(text);
  if (имя.length < 2 || !тело) return false;
  return тело.startsWith(имя);
}

/**
 * Обороты внешнего авторитета — ОТКАЗ (разбор в шапке). Список узкий намеренно: он ловит приписку
 * к ИСТОЧНИКУ НАШИХ СВЕДЕНИЙ, а не отсылку внутри сюжета.
 */
export const AUTHORITY_PATTERNS = [
  /реестр\w*/giu,
  /по разметке/giu,
  /зафиксирован\w*/giu,
  /по данным\b/giu,
  /как сообщает/giu,
  /\bregistry\b/giu,
  /\brecorded as\b/giu,
  /\bis recorded\b/giu,
  /\bas recorded\b/giu,
];

/** Возвращает найденные обороты внешнего авторитета — пустой массив означает «чисто». */
export function externalAuthority(text) {
  const t = String(text ?? '');
  const найдено = [];
  for (const p of AUTHORITY_PATTERNS) {
    const m = t.match(p);
    if (m) найдено.push(...m);
  }
  return найдено;
}

/**
 * Следы машинной правки: висящая пунктуация, склейки, двойные пробелы. Каждый образец назван
 * словами, чтобы замечание читалось без раскодирования регулярного выражения.
 */
export const ARTIFACT_PATTERNS = [
  [/\.\s*;/u, 'точка перед точкой с запятой'],
  [/\s[»"]\.\s*$/u, 'висящая кавычка в конце'],
  [/\.\s+\./u, 'две точки через пробел'],
  [/\s+,/u, 'пробел перед запятой'],
  [/,\s*\./u, 'запятая перед точкой'],
  [/\(\s*\)/u, 'пустые скобки'],
  [/—\s*—/u, 'двойное тире'],
  [/\S {2,}\S/u, 'двойной пробел'],
  [/[;,]\s*$/u, 'текст обрывается на запятой или точке с запятой'],
];

/** Возвращает названия найденных следов правки — пустой массив означает «чисто». */
export function punctuationArtifacts(text) {
  const t = String(text ?? '');
  return ARTIFACT_PATTERNS.filter(([p]) => p.test(t)).map(([, имя]) => имя);
}

