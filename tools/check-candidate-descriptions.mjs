/**
 * НАБОР ТЕКСТОВЫХ ПРОВЕРОК ОДНОЙ ЯЗЫКОВОЙ ПОЛОВИНЫ — всё, что решается БЕЗ статьи Википедии.
 *
 * 🔴 ВЫНЕСЕНО РАДИ ПРОВЕРЯЕМОСТИ ПОДКЛЮЧЕНИЯ, а не ради красоты. Пока набор жил телом цикла,
 * ОТКЛЮЧИТЬ от ворот любую проверку можно было молча: юниты трогали функции по одной, а тело
 * цикла не трогал никто, и ни один тест бы не покраснел. Ровно так `proseProblems` сутки не
 * стоял в воротах мастерской, а `proseNotes` не звал вообще никто (`EXP-0194`).
 *
 * Возвращает ДВА списка, и это весь смысл общего канала:
 *   · `отказы` — то, что останавливает работу. Признак с нулём ложных на живом корпусе;
 *   · `замечания` — то, что ПРЕДЪЯВЛЯЕТСЯ человеку и на чём прибор не настаивает. Признак,
 *     краснеющий хотя бы на одном тексте, который владелец написал или одобрил.
 * Границу между ними держит `tools/lib/gate-notes.mjs`, там же разбор, почему их не одна.
 *
 * ⛔ Заимствование сюда НЕ входит: ему нужна статья, то есть сеть, а сеть в чистую функцию не
 * ставится. Оно остаётся в рабочем цикле рядом с `articleText`.
 */
export function проверитьТекст(text, lang, c) {
  const отказы = [];
  const замечания = [];
  const t = String(text ?? '');

  const chars = t.length;
  const sentences = sentenceCount(t);
  if (chars < MIN_CHARS) отказы.push(`${chars} знаков — короче ${MIN_CHARS}`);
  if (chars > MAX_CHARS) отказы.push(`${chars} знаков — длиннее ${MAX_CHARS}`);
  if (sentences < MIN_SENTENCES || sentences > MAX_SENTENCES) {
    отказы.push(`${sentences} предложений — вне ${MIN_SENTENCES}…${MAX_SENTENCES}`);
  }

  /* Зачин: название уже стоит в шапке карточки, повтор владелец запретил правилом КЛАССА. */
  if (opensWithTitle(c?.title?.[lang], t)) {
    отказы.push(`описание начинается с названия — «${t.slice(0, 45)}…»`);
  }

  /* Внешний авторитет: «NDim самодостаточен… Мы констатируем факт сами» — слово владельца. */
  const authority = externalAuthority(t);
  if (authority.length > 0) {
    отказы.push(`внешний авторитет — ${authority.length} шт.: ${[...new Set(authority)].join(', ')}`);
  }

  /* Следы машинной правки: три порванных места пережили зелёный прогон, потому что их не мерили. */
  const artifacts = punctuationArtifacts(t);
  if (artifacts.length > 0) отказы.push(`след машинной правки — ${artifacts.join(', ')}`);

  /* Смешение алфавитов внутри слова — отказ; одиночная строчная латиница — замечание. */
  const смешение = mixedScriptWords(t, lang);
  if (смешение.length > 0) отказы.push(`слово из двух алфавитов — ${смешение.join(', ')}`);
  const свои = [c?.title?.en, c?.author?.en].filter(Boolean).join(' ');
  const латиница = standaloneLatinPhrases(t, lang, свои);
  if (латиница.length > 0) замечания.push({ проверка: 'строчная латиница', текст: латиница.join(', ') });

  /*
   * ВОРОТА ПРОЗЫ. До 2026-08-22 `tools/lib/prose-gates.mjs` стоял в воротах ТОЛЬКО одной
   * стороной: `proseProblems` звал писарь правок каталога, а ворота МАСТЕРСКОЙ — никто, хотя
   * оба класс-запрета владельца («расщеплённое сказуемое», «конструкция отнесения») писались
   * ровно про карточки кандидатов.
   * 📐 Что это поймало бы на УЖЕ ПРИНЯТЫХ партиях 1–4 (замер 2026-08-22, 50 карточек):
   * отказов **0**, замечаний **1** — «The score was composed by» в «Дне разоблачения», и та
   * карточка ОДОБРЕНА владельцем, потому это и замечание. Принятая работа непойманных дефектов
   * прозы не несёт, и подключение ничего задним числом не переворачивает.
   * ⛔ Русскую сторону модуль не судит и не притворяется, что судит (`lang !== 'en'` — пусто).
   */
  отказы.push(...proseProblems(t, lang));
  for (const з of proseNotes(t, lang)) замечания.push({ проверка: 'ворота прозы', текст: з });

  /*
   * ВОРОТА ПРОЗЫ, РУССКАЯ СТОРОНА — классы владельца 3 · 4 · 5 · 6 · 7 · 9 (2026-08-22).
   * Повод: владелец вернул 12 карточек и заказал 60 новых «с учётом моих критических
   * комментариев только». Граница отказа и замечания проведена ЗАМЕРОМ по его собственным
   * текстам, а не силой его слова, — разбор и числа в шапке `lib/owner-classes-ru.mjs`.
   * 📐 Что это даёт на УЖЕ СДАННЫХ партиях 1–4 (50 карточек): числа перевыводит
   * `node tools/measure-owner-classes.mjs`, и в шапке модуля они разложены по классам.
   * Ложных отказов — 0 на всех классах, объявленных отказом.
   */
  отказы.push(...ownerClassProblems(t, lang));
  /* Вид объекта (`type.ru`) и дата выхода из реестра едут в замечания: класс 11б спрашивает,
   * зовёт ли текст объект СВОИМ словом (вид берётся ИЗ ДАННЫХ карточки, а не угадывается), а
   * класс 16 называет недостающую дату, раз прибор её в этот же прогон уже узнал. */
  for (const з of ownerClassNotes(t, lang, c?.type?.ru, c?.__датаВыхода ?? null)) {
    замечания.push({ проверка: 'классы владельца', текст: з });
  }

  /* Класс 2 — МЕРА, а не приговор: порог тут может назначить только владелец. Она едет
   * отдельным полем и печатается отдельным блоком, чтобы не притворяться находкой. */
  return { отказы, замечания, chars, sentences, сложность: мераСложности(t, lang) };
}

