/**
 * ПАСПОРТ ПРИБОРА СОГЛАСОВАНИЯ И СТРОКА КАНОНА О НЁМ (`bugs/208`).
 *
 * Две вещи. (1) `паспорт()` производит числа из источников, а не переписывает их: лемм и
 * словоформ — из лексикона, мутаций — из файла набора, корпуса — из файлов. (2) Пара
 * «истина ↔ зеркало»: истина — паспорт, зеркало — строка реестра инструментов в `AGENT_GUIDE.md`.
 * Строка обязана ЦИТИРОВАТЬ команду и не нести набранных рукой чисел прибора — ровно тех форм,
 * которые в поле устарели («N лемм», «N словоформ», «N мутациями», «на N текстах», «N пар»).
 * «Сломанный случай» документа: вернуть в строку «228 словоформ» → второй тест красный.
 *
 * Прогон: node --test tools/grammar-passport.test.mjs   (или `npm run test:tools`)
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { паспорт } from './measure-grammar-agreement.mjs';
import { ЛЕКСИКОН, ФОРМЫ } from './lib/grammar-agreement.mjs';

test('паспорт: числа сняты с источников, единицы названы', () => {
	const п = паспорт({ today: new Date(2026, 8, 12) });
	assert.equal(п.снято, '2026-09-12');
	assert.equal(п.лемм, ЛЕКСИКОН.length);
	assert.equal(п.словоформ, ФОРМЫ.size);
	const вФайле = (readFileSync('tools/grammar-agreement.mutation.mjs', 'utf8').match(/^\s*имя:/gmu) ?? []).length;
	assert.equal(п.мутаций, вФайле);
	assert.ok(п.мутаций >= 7, 'контроль прибора: в наборе не меньше семи мутаций (замер bugs/208)');
	for (const к of Object.values(п.корпуса)) {
		assert.ok(к.текстов > 0, `корпус ${к.имя} пуст — паспорт ничего не измерил`);
		assert.ok(к.Н3.карточек <= к.Н3.пар, 'пар не меньше, чем карточек: единица названа верно');
	}
	assert.ok(п.корпуса.N.файлов >= 10, 'контроль прибора: партий кандидатов не меньше десяти');
});

test('🔴 строка канона о приборе цитирует команду и не несёт набранных рукой чисел прибора', () => {
	const строка = readFileSync('AGENT_GUIDE.md', 'utf8')
		.split('\n')
		.find((l) => l.startsWith('| `node tools/measure-grammar-agreement.mjs`'));
	assert.ok(строка, 'строка реестра о приборе согласования не найдена');
	assert.match(строка, /--passport/u, 'строка обязана называть команду паспорта');
	const набранныеРукой = [
		/\d+\s*лемм/u, /\d+\s*словоформ/u, /\d+\s*мутаци/u, /на\s+\d+\s+текст/u, /\d+\s+пар(?![\p{L}])/u,
	];
	for (const форма of набранныеРукой) {
		assert.doesNotMatch(строка, форма, `в строке канона стоит набранное рукой число прибора: ${форма}`);
	}
});
