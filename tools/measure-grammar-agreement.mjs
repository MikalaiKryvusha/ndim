import { readFileSync, readdirSync } from 'node:fs';
import { existsSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

import { проверить, пунктуацияПояснения, ЛЕКСИКОН, ФОРМЫ } from './lib/grammar-agreement.mjs';

/** Русские описания всех партий кандидатов. */
export function текстыПартий(каталог = 'candidates/batches') {
  const тексты = [];
  for (const файл of readdirSync(каталог).filter((f) => f.endsWith('.json')).sort()) {
    const разбор = JSON.parse(readFileSync(`${каталог}/${файл}`, 'utf8'));
    for (const карточка of разбор.candidates ?? []) {
      const ru = карточка.description?.ru;
      if (ru) тексты.push({ адрес: карточка.wikidata ?? файл, текст: ru });
    }
  }
  return тексты;
}

/** Срез живого каталога — тексты, которые лежат у владельца перед глазами. */
export function срезКаталога(путь = 'src/lib/content/dims-slice.json') {
  const разбор = JSON.parse(readFileSync(путь, 'utf8'));
  const записи = Array.isArray(разбор) ? разбор : Object.values(разбор)[0];
  return записи
    .filter((з) => з.description?.ru)
    .map((з) => ({ адрес: з.slug ?? з.id, текст: з.description.ru }));
}

/** Строки каталога из разведки о справочном стиле. */
export function строкиКаталога(путь = 'researches/34_ru_boilerplate_candidates.md') {
  return readFileSync(путь, 'utf8')
    .split('\n')
    .filter((строка) => /[а-яё]{4}/iu.test(строка) && строка.length > 60)
    .map((строка, i) => ({ адрес: `строка ${i + 1}`, текст: строка }));
}

/** Складывает результаты по корпусу. */
export function померить(тексты) {
  const итог = { подозрения: [], снятоН3: [], снятоОмонимией: [], н9: [], оборотов: 0, пар: 0, известных: 0, неизвестных: 0, множественных: 0 };
  for (const { адрес, текст } of тексты) {
    const п9 = пунктуацияПояснения(текст);
    итог.н9.push(...п9.подозрения.map((п) => ({ ...п, адрес })));
    итог.оборотов += п9.оборотов;
    const р = проверить(текст);
    итог.подозрения.push(...р.подозрения.map((п) => ({ ...п, адрес })));
    итог.снятоН3.push(...р.снятоН3.map((с) => ({ ...с, адрес })));
    итог.снятоОмонимией.push(...р.снятоОмонимией.map((с) => ({ ...с, адрес })));
    итог.пар += р.пар;
    итог.известных += р.известных;
    итог.неизвестных += р.неизвестных;
    итог.множественных += р.множественных;
  }
  return итог;
}

function процент(часть, целое) {
  return целое === 0 ? '—' : `${((часть / целое) * 100).toFixed(0)} %`;
}

function печатьКорпуса(имя, тексты, показатьПары) {
  const р = померить(тексты);
  const судимых = р.известных - р.множественных;

  console.log(`\n══════ ${имя} ══════`);
  console.log(`  текстов ${тексты.length} · адъективных пар ${р.пар}`);
  console.log(`  ПОКРЫТИЕ: существительное известно лексикону — ${р.известных} (${процент(р.известных, р.пар)})`
    + ` · вне лексикона ${р.неизвестных} · множественное число не судится ${р.множественных}`
    + ` · СУДИМЫХ ПАР ${судимых}`);

  // 🔴 Отчёт ПО ПРАВИЛАМ, а не одним числом (Н8).
  const поПравилам = new Map();
  for (const п of р.подозрения) поПравилам.set(п.правило, (поПравилам.get(п.правило) ?? 0) + 1);
  for (const правило of ['Н1', 'Н2', 'Н1+Н2']) {
    console.log(`  правило ${правило}: подозрений ${поПравилам.get(правило) ?? 0}`);
  }
  console.log(`  правило Н3 (причастие УПРАВЛЯЕТ — НЕ нарушение): снято ${р.снятоН3.length}`);
  console.log(`  снято омонимией (различить нечем — молчим): ${р.снятоОмонимией.length}`);
  // 🔴 Н9 отчитывается ОТДЕЛЬНОЙ строкой и с названной точностью: приложение от однородного
  // ряда отличается смыслом, и машина здесь предъявляет заведомо с запасом.
  console.log(`  правило Н9 (пунктуация пояснения): подозрений ${р.н9.length} из ${р.оборотов} оборотов`
    + ' · ⚠️ точность ~41 % по ручной сверке (12 настоящих из 29) — читать глазами обязательно');

  for (const п of р.подозрения) {
    console.log(`    ⚠ [${п.правило}] ${п.адрес} — «${п.цитата}»`);
    console.log(`       ${п.почему}`);
  }
  for (const п of р.н9) console.log(`    ⚠ [Н9] ${п.адрес} — «${п.цитата}» — пояснение? владелец требует тире с двух сторон`);
  if (показатьПары) {
    for (const с of р.снятоН3) console.log(`    ○ [Н3] ${с.адрес} — «${с.цитата}» — причастие управляет, не согласуется`);
    for (const с of р.снятоОмонимией) console.log(`    ○ [омонимия: ${с.вид}] ${с.адрес} — «${с.цитата}»`);
  }

  // 🔴 Второе условие пересмотра решения о словаре словоформ (разведка §7), названное числом.
  if (р.снятоОмонимией.length > р.подозрения.length && р.снятоОмонимией.length > 0) {
    console.log(`  🔴 ОМОНИМИЯ СЪЕДАЕТ БОЛЬШЕ, ЧЕМ ПРИБОР НАХОДИТ: снято ${р.снятоОмонимией.length}`
      + ` против ${р.подозрения.length} подозрений.`);
    console.log('     Условие пересмотра из разведки §7 выполнено — считать цену словаря словоформ заново.');
  }

  // Условие пересмотра решения о морфологическом словаре — названо числом, а не «когда-нибудь».
  if (р.пар > 0 && р.неизвестных / р.пар > 0.5) {
    console.log(`  🔴 ЛЕКСИКОН ПЕРЕСТАЛ ПОКРЫВАТЬ МАТЕРИАЛ: вне лексикона ${процент(р.неизвестных, р.пар)} пар.`);
    console.log('     Условие пересмотра из разведки §7 выполнено — считать цену словаря словоформ заново.');
  }
  return р;
}

function main(аргументы) {
  const показатьПары = аргументы.includes('--show-pairs');
  const входы = аргументы.filter((а) => !а.startsWith('--'));

  console.log('ПРИБОР СОГЛАСОВАНИЯ ОПРЕДЕЛЕНИЯ — правила Н1/Н2 · предъявляет, а не судит');
  console.log(`лексикон: ${ЛЕКСИКОН.length} лемм · ${ФОРМЫ.size} словоформ единственного числа`);

  if (входы.length > 0) {
    const тексты = входы.map((вход) => existsSync(вход)
      ? { адрес: вход, текст: readFileSync(вход, 'utf8') }
      : { адрес: '<аргумент>', текст: вход });
    печатьКорпуса('вход из аргументов', тексты, показатьПары);
    return;
  }

  печатьКорпуса('N — наши партии кандидатов', текстыПартий(), показатьПары);
  печатьКорпуса('K — срез живого каталога', срезКаталога(), показатьПары);
  печатьКорпуса('R — строки каталога (researches/34)', строкиКаталога(), показатьПары);

  console.log('\n⚠️ Прибор предъявляет, а не судит: код возврата 0 при любом числе подозрений.');
  console.log('   Каждое подозрение читается глазами по цитате. Ноль при нулевом покрытии — слепота.');
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) main(process.argv.slice(2));
