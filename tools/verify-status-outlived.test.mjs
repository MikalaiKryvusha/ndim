/**
 * ТЕСТ СТРАЖА «СТРОКА ПЕРЕЖИЛА СВОЁ ИСПОЛНЕНИЕ» (слой 1, `bugs/177`).
 *
 * 🔴 ПОВОД. Класс прожил восемь известных случаев именно потому, что за правилом «пункт „ждём X“
 * обязан нести проверку» не стояло машины. Машина появилась — значит у неё должен быть свой
 * страж, иначе она разъедется тем же способом.
 *
 * 🔴🔴 ГЛАВНЫЙ СЛУЧАЙ ЗДЕСЬ — НЕ «ЛОЖЬ ПОЙМАНА», А «АККУРАТНО ВЕДОМЫЙ ПЛАН НЕ ПОЙМАН». Проверка
 * «ложь поймана» одна была бы ЗЕЛЁНОЙ и на первой редакции прибора, которая считала работой любой
 * коммит, тронувший файл плана, — и красила `plans/59`, куда всего лишь внесли ОТВЕТ ВЛАДЕЛЬЦА,
 * закрыв развилку. Правка плана есть ПЛАНИРОВАНИЕ, а «не начат» говорит про ИСПОЛНЕНИЕ. Эти два
 * поведения различает только пара случаев, поэтому они стоят рядом и порознь не имеют смысла.
 *
 * Коммиты сюда ВПРЫСКИВАЮТСЯ, а не берутся из git: тест обязан быть детерминированным, а живая
 * история меняется с каждым коммитом и превратила бы набор в лотерею.
 *
 * ⚠️ Прибор ПОДКЛЮЧАЕТСЯ напрямую, и это законно: у него стоит предохранитель «запустили или
 * подключили», накрывающий оба режима, — импорт отдаёт только чистые функции.
 *
 * Прогон: node --test tools/verify-status-outlived.test.mjs   (или `npm run test:tools`)
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';

import { объявленНеначатым, статусИзШапки, работаПо } from './verify-status-outlived.mjs';

/** Впрыснутый ответ «какие файлы тронул коммит» — вместо git. */
const файлыИз = (карта) => (hash) => карта[hash] ?? [];

test('🔴 правка САМОГО плана работой не считается — иначе краснеет аккуратно ведомый план', () => {
  const коммиты = [{ h: 'aaa1111', s: 'docs(plans/59): развилка закрыта владельцем, интервью №039' }];
  const файлы = файлыИз({ aaa1111: ['plans/59_today_widget_new_dims_list.md'] });

  assert.deepEqual(
    работаПо('plans', '59', коммиты, файлы),
    [],
    'коммит, тронувший только сам план, засчитан исполнением',
  );
});

test('исполнение кодом со ссылкой на план — работа', () => {
  const коммиты = [{ h: 'bbb2222', s: 'feat(plans/58 шаг 1): четвёртый тег owner-approved' }];
  const файлы = файлыИз({ bbb2222: ['src/lib/dims.ts', 'plans/58_dim_lifecycle_tags.md'] });

  assert.deepEqual(
    работаПо('plans', '58', коммиты, файлы).map((c) => c.h),
    ['bbb2222'],
    'коммит с кодом и именем плана в заголовке не засчитан работой',
  );
});

test('коммит ЗАВЕДЕНИЯ документа отсекается тем же правилом, а не исключением', () => {
  const коммиты = [{ h: 'ccc3333', s: 'docs(план): plans/59 — виджет «Сегодня» списком' }];
  const файлы = файлыИз({ ccc3333: ['plans/59_today_widget_new_dims_list.md'] });

  assert.deepEqual(работаПо('plans', '59', коммиты, файлы), [], 'заведение документа засчитано работой');
});

test('чужой большой коммит без имени документа плану не приписывается', () => {
  const коммиты = [{ h: 'ddd4444', s: 'feat(эпик 60): ритм сервера синхронизации' }];
  const файлы = файлыИз({ ddd4444: ['sync-server/index.mjs', 'plans/59_today_widget_new_dims_list.md'] });

  assert.deepEqual(
    работаПо('plans', '59', коммиты, файлы),
    [],
    'коммит без имени плана в заголовке приписан плану — так работа размажется по всем подряд',
  );
});

test('соседний номер не съедает документ: 5 против 58', () => {
  const коммиты = [{ h: 'eee5555', s: 'fix(plans/58): тег одной оси больше не стирает тег другой' }];
  const файлы = файлыИз({ eee5555: ['src/lib/dims.ts'] });

  assert.deepEqual(работаПо('plans', '5', коммиты, файлы), [], 'номер 5 поймался на plans/58');
  assert.equal(работаПо('plans', '58', коммиты, файлы).length, 1, 'номер 58 не поймался на своём же коммите');
});

test('признак «не начат» отличает ложь от темпа работы', () => {
  assert.equal(объявленНеначатым('🔲 написан, не начат.'), true);
  assert.equal(объявленНеначатым('🔲 написан, НЕ начат — заперт воротами'), true);
  assert.equal(объявленНеначатым('🔧 шаг 1 НАЧАТ — обвязка легла двумя коммитами'), false, '«НАЧАТ» без «не»');
  assert.equal(объявленНеначатым('в работе, частично закрыт'), false, '«в работе» — темп, а не ложь');
  assert.equal(объявленНеначатым('✅ ПОЧИНЕН в ветке, доказан мутацией'), false);
});

/*
 * 🔴 СЛУЧАЙ ЗАВЕДЁН ПОТОМУ, ЧТО ТЕСТ ВЫШЕ БЫЛ ЗЕЛЁНЫМ ПРИ МЁРТВОМ ПРИЗНАКЕ.
 *
 * Оба его положительных образца несут «🔲 написан» — то есть проходили ВТОРЫМ признаком списка, а
 * первый (`не начат`) не исполнялся в них НИ РАЗУ. Пять дней он совпадал ни с чем: `\b` в
 * JavaScript определена через ASCII, и после кириллической «т» границы не образуется. Зелёный был
 * настоящим — и означал он «проверке не на чем упасть», а не «правило держится».
 * Лечение по лестнице трёх вопросов — перестроить МАТЕРИАЛ: здесь у образцов «🔲 написан» нет, и
 * упасть им есть на чём.
 */
/*
 * 🔴 КОНТРОЛЬНЫЙ СЛУЧАЙ ГРАНИЦЫ СЛОВА — требование QA, вошедшее в вердикт по партии 1.
 *
 * Довод её словами: без такого случая границу через полгода «починят» обратно на `\b` и вернут
 * шесть ложных. Случай пришпиливает ОБЕ стороны границы, потому что односторонний пришпилил бы
 * половину: слева — что «не начат» не приклеивается к предыдущему слову, справа — что за ним не
 * стоит буква. `\b` в JavaScript определена через ASCII и на кириллице молча даёт ноль, поэтому
 * границу держит `(?<!\p{L}) … (?!\p{L})` с флагом `u`.
 */
test('🔴 КОНТРОЛЬ ГРАНИЦЫ СЛОВА: обе стороны, иначе её вернут на \\b через полгода', () => {
  assert.equal(объявленНеначатым('план не начат'), true, 'граница слева не пропускает целое слово');
  assert.equal(объявленНеначатым('не начат.'), true, 'справа точка — граница есть');
  assert.equal(объявленНеначатым('не начат, заперт'), true, 'справа запятая — граница есть');
  assert.equal(объявленНеначатым('не начатый этап'), false, 'справа буква — это ДРУГОЕ слово');
  assert.equal(объявленНеначатым('нененачат'), false, 'слева буква — совпадения быть не должно');
});

test('🔴 признак «не начат» работает В ОДИНОЧКУ, без подпорки «🔲 написан»', () => {
  assert.equal(объявленНеначатым('🔴🔴 ПЕРВЫЙ ПРИОРИТЕТ с 2026-08-17 — не начат.'), true, 'plans/44');
  assert.equal(объявленНеначатым('🔲 не начат — готов к исполнению ·'), true, 'plans/56');
  assert.equal(объявленНеначатым('написан 2026-08-17, НЕ начат.'), true, 'plans/57');
  assert.equal(объявленНеначатым('НЕ НАЧАТ — место освобождено'), true, 'верхний регистр, plans/09');
  assert.equal(объявленНеначатым('не  начат'), true, 'два пробела между словами');
});

/*
 * 🔑 РАЗДЕЛЯЮЩИЙ ПРИЗНАК ЗДЕСЬ ГРАММАТИЧЕСКИЙ, А НЕ ЭВРИСТИЧЕСКИЙ, и эта пара к случаю выше
 * поодиночке бессмысленна: без неё зелёным был бы и грубый признак `не начат[аоы]?`, который даёт
 * ПЯТЬ ложных тревог на живом корпусе. Краткое причастие согласуется с подлежащим: когда «не
 * начат» относится к самому документу («план», «баг» — мужской род), форма всегда мужская. Иное
 * окончание означает, что не начато ЧТО-ТО ВНУТРИ, при живой работе над документом.
 * Все пять строк ниже — ЖИВЫЕ, снятые с корпуса, а не выдуманные.
 */
test('🔑 не начата ЧАСТЬ документа — это темп, а не ложь: судит род краткого причастия', () => {
  assert.equal(объявленНеначатым('🔧 ШАГ 1 (замер) ЗАКРЫТ 2026-08-22. Шаги 2–7 не начаты ·'), false, 'plans/69');
  assert.equal(объявленНеначатым('🔧 метаплан написан 2026-08-15; фазы не начаты ·'), false, 'plans/54');
  assert.equal(объявленНеначатым('🔲 метаплан написан, фаза 1 не начата ·'), false, 'plans/68');
  assert.equal(объявленНеначатым('🔧 В РАБОТЕ — конвейер чинится; переделка правок НЕ начата'), false, 'plans/NEW');
  assert.equal(объявленНеначатым('🔴 ОТКРЫТ. Диагноз полный. Лечение назначено, не начато.'), false, 'bugs/152');
});

/*
 * ПЛАНИРОВАНИЕ ЖИВЁТ НЕ ТОЛЬКО В `plans/` И `bugs/` — находка QA, четыре ложные тревоги из шести.
 * Довод тот же, что у первого теста файла, и здесь он лишь распространяется на семью каталогов:
 * внесение ответа владельца, разведки или идеи в план — это ПЛАНИРОВАНИЕ, а «не начат» говорит
 * про ИСПОЛНЕНИЕ. Каждая строка ниже — живой коммит из замера.
 */
test('🔴 разведка, идея и интервью — планирование, а не исполнение', () => {
  const случаи = [
    ['researches', '2a6176d', 'docs(plans/54): миссия QA', ['researches/38_qa_mission.md'], '54'],
    ['ideas', '03bdda4', 'docs(plans/68): флот стендов', ['ideas/41_test_stand_fleet.md'], '68'],
    ['interviews', '16fd905', 'docs(plans/71): ответы владельца', ['interviews/interview_046.md'], '71'],
  ];
  for (const [имя, h, s, файлы, номер] of случаи) {
    assert.deepEqual(
      работаПо('plans', номер, [{ h, s }], файлыИз({ [h]: файлы })),
      [],
      `коммит, тронувший только ${имя}/, засчитан исполнением`,
    );
  }
});

test('исполнение кодом остаётся работой — пара к случаю выше, иначе он запретил бы всё', () => {
  const коммиты = [{ h: 'fff6666', s: 'feat(plans/54): страж миссии QA' }];
  const файлы = файлыИз({ fff6666: ['researches/38_qa_mission.md', 'tools/qa-guard.mjs'] });

  assert.equal(
    работаПо('plans', '54', коммиты, файлы).length,
    1,
    'коммит с кодом перестал считаться работой из-за соседнего файла разведки',
  );
});

test('значение «Статус:» берётся целиком, даже когда перенесено на вторую строку', () => {
  const шапка = [
    '# План 58 — теги',
    '',
    '> **Создан:** 2026-08-17 ·',
    '> **Статус:** 🔲 написан,',
    '> не начат.',
    '> **Исходящее:** —',
  ].join('\n');

  const значение = статусИзШапки(шапка);
  assert.ok(значение, 'значение поля не найдено');
  assert.equal(объявленНеначатым(значение), true, 'перенос на вторую строку потерял «не начат»');
});

test('соседнее поле шапки в значение статуса не затекает', () => {
  const шапка = ['# План', '', '> **Статус:** ✅ закрыт', '> **Исходящее:** отчёт, работа не начата'].join('\n');

  assert.equal(
    объявленНеначатым(статусИзШапки(шапка)),
    false,
    'в статус затекло соседнее поле — прибор судил бы чужую строку',
  );
});
