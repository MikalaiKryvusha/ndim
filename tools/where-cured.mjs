function selftest() {
  let bad = 0;
  for (const c of СЛУЧАИ) {
    let ok = false;
    try {
      ok = c.run() === true;
    } catch {
      ok = false;
    }
    console.log(`${ok ? '  ✓' : '  ✗'} ${c.name}`);
    if (!ok) bad += 1;
  }
  console.log(bad === 0 ? `\n✅ САМОТЕСТ ЧИСТ: случаев ${СЛУЧАИ.length}.` : `\n❌ САМОТЕСТ КРАСНЫЙ: ${bad} из ${СЛУЧАИ.length}.`);
  process.exit(bad === 0 ? 0 : 1);
}

/* ── РАБОЧИЙ ПРОГОН ───────────────────────────────────────────────────────────── */

function walk(dir) {
  const out = [];
  let names;
  try {
    names = readdirSync(dir);
  } catch {
    return out;
  }
  for (const name of names) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) out.push(...walk(path));
    else if (РАСШИРЕНИЯ.has(extname(name))) out.push(path);
  }
  return out;
}

/**
 * Неслитые ветки: где класс назван у соседей. Лечит случай `close-bug.mjs` наполовину.
 *
 * Разбор ряда идёт по ИЗВЕСТНОЙ приставке ветки, а не образцом `^(.+?):(.+?):`: имя ветки
 * бывает с двоеточием и дефисами, а нежадный образец на таком имени молча съехал бы на
 * половину строки — и промах выглядел бы как путь.
 *
 * Возвращает `{ branch, path, lineno, text, line }`; отсев уже лежащего у меня — снаружи,
 * чистой функцией `rowIsNew`, чтобы его можно было проверить самотестом.
 */
function inBranches(query) {
  let branches = [];
  try {
    branches = execFileSync('git', ['branch', '--format=%(refname:short)'], { encoding: 'utf8' })
      .split(/\r?\n/).map((s) => s.trim()).filter(Boolean);
  } catch {
    return [];
  }
  const here = branches.length ? execFileSync('git', ['rev-parse', '--abbrev-ref', 'HEAD'], { encoding: 'utf8' }).trim() : '';
  const rows = [];
  for (const b of branches) {
    if (b === here) continue;
    try {
      const out = execFileSync('git', ['grep', '-n', '-i', '--', query, b, '--', 'tools', 'src'], { encoding: 'utf8' });
      for (const line of out.split(/\r?\n/).filter(Boolean).slice(0, 4)) {
        const hit = line.startsWith(`${b}:`) ? line.slice(b.length + 1).match(/^([^:]+):(\d+):(.*)$/) : null;
        rows.push({ branch: b, line, path: hit?.[1] ?? '', lineno: hit?.[2] ?? '', text: hit?.[3] ?? '' });
      }
    } catch {
      /* git grep выходит кодом 1, когда не нашёл, — это не ошибка, а ответ */
    }
  }
  return rows;
}

function run(argv) {
  const branches = argv.includes('--branches');
  const query = argv.filter((a) => !a.startsWith('--')).join(' ').trim();
  if (!query) {
    console.error('Запуск: node tools/where-cured.mjs <слова | EXP-NNNN | bugs/NNN> [--branches]');
    process.exit(2);
  }

  const files = [];
  let корпус = 0;
  for (const dir of ГДЕ_ИСКАТЬ) {
    for (const path of walk(dir)) {
      корпус += 1;
      const hits = hitsIn(readFileSync(path, 'utf8'), query);
      if (hits.length) files.push({ path, hits });
    }
  }

  // 🔴 Первой строкой — и это не вежливость: без неё «нашёл» читается как «вылечено».
  console.log('\n⚠️  Прибор находит, где класс НАЗВАН, а не где он доказанно ВЫЛЕЧЕН.');
  console.log('   Лечение проверяй ЧТЕНИЕМ найденного.\n');
  // Корпус назван В САМОЙ строке — доля без знаменателя это слух (класс `EXP-0226`).
  console.log(
    `Запрос: «${query}» · файлов с упоминанием: ${files.length} из ${корпус} ` +
      `(корпус: ${ГДЕ_ИСКАТЬ.join('/ + ')}/ по ${[...РАСШИРЕНИЯ].join(' ')})\n`,
  );
  const ширина = breadthWarning(files.length, корпус);
  if (ширина.length) console.log(`${ширина.join('\n')}\n`);

  if (files.length === 0) {
    console.log('НИГДЕ — и это ответ, а не поломка: у класса нет упоминания в коде.');
    console.log('Значит машинного лечения, скорее всего, нет вовсе, а урок живёт записью — третий сорт.');
  }

  for (const f of rank(files)) {
    const шапка = f.hits.filter((h) => h.inHeader);
    const тело = f.hits.filter((h) => !h.inHeader);
    console.log(`${шапка.length ? '📌 В ШАПКЕ' : '·  в теле '} ${f.path.split(sep).join('/')} — совпадений ${f.hits.length}`);
    for (const h of шапка.slice(0, 2)) console.log(`      :${h.line}  ${h.text.slice(0, 120)}`);
    if (!шапка.length) for (const h of тело.slice(0, 1)) console.log(`      :${h.line}  ${h.text.slice(0, 120)}`);
  }

  if (branches) {
    const все = inBranches(query);
    const читать = (path) => {
      try {
        return readFileSync(path, 'utf8');
      } catch {
        return null; // файла у меня нет — ряд настоящая новость
      }
    };
    const новые = все.filter((r) => rowIsNew(r, читать(r.path)));
    const уже = все.length - новые.length;

    console.log(`\n── НЕСЛИТЫЕ ВЕТКИ: строк ${новые.length} из ${все.length} найденных ──`);
    // 🔑 Отсев НАЗЫВАЕТСЯ числом. Молчаливый фильтр — это свой дефект: человек не может
    //    отличить «у соседей ничего нет» от «прибор мне это не показал».
    if (уже) console.log(`   (${уже} отброшено: те же строки ДОСЛОВНО лежат в твоём дереве — не новость)`);
    for (const line of branchHonesty(новые.length)) console.log(line);
    for (const r of новые) console.log(`   ${r.line.slice(0, 150)}`);
  }
  process.exit(0);
}

