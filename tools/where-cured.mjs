function selftest() {
  let bad = 0;
  for (const c of СЛУЧАИ) {
    let ok = false;
    try {
      ok = c.run() === true;
    } catch {
      ok = false;
    }
    console.log(`${ok ? '  ✓' : '  ✗'} ${c.name}`);
    if (!ok) bad += 1;
  }
  console.log(bad === 0 ? `\n✅ САМОТЕСТ ЧИСТ: случаев ${СЛУЧАИ.length}.` : `\n❌ САМОТЕСТ КРАСНЫЙ: ${bad} из ${СЛУЧАИ.length}.`);
  process.exit(bad === 0 ? 0 : 1);
}

