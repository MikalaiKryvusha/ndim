/**
 * Разбор вывода `for-each-ref`: `{ name, sha }` для строк, которые ДЕЙСТВИТЕЛЬНО ссылки.
 *
 * Требование `objectname` из 40 шестнадцатеричных — не придирка к форме, а тот самый закрытый
 * признак: любая строка-описание (`(no branch)`, `(HEAD detached at …)`, будущая третья форма,
 * о которой я не знаю) его не несёт и отсеивается, откуда бы список ни пришёл.
 */
export function веткиИзВывода(текст) {
  const out = [];
  for (const строка of String(текст ?? '').split(/\r?\n/)) {
    const [name, sha] = строка.split('\t');
    if (!name || !sha) continue;
    if (!/^[0-9a-f]{40}$/u.test(sha.trim())) continue;
    out.push({ name: name.trim(), sha: sha.trim() });
  }
  return out;
}

/**
 * Чужие ветки — те, чья вершина НЕ совпадает с моим HEAD.
 *
 * 🔴 ОТСЕЧКА ПО SHA, А НЕ ПО ИМЕНИ, и это вторая половина того же дефекта. Прежде своя ветка
 * искалась через `git rev-parse --abbrev-ref HEAD`, а в отсоединённом дереве эта команда
 * возвращает буквально `HEAD` — имя, не совпадающее ни с одной веткой. То есть отсечка не
 * срабатывала вовсе. По sha она работает в обоих деревьях одинаково и заодно точнее: ветка,
 * стоящая на моей же вершине, соседом не является, как бы она ни называлась.
 */
export function чужиеВетки(ветки, headSha) {
  const мой = String(headSha ?? '').trim();
  return ветки.filter((b) => !мой || b.sha !== мой);
}

/**
 * Отказ git, о котором законно промолчать: РОВНО код 1 (`git grep` не нашёл — это ответ).
 *
 * Всё прочее — поломка: 128 у неразрешённой ссылки, отсутствие `status` у несостоявшегося
 * запуска. Молчать о них значит выдавать незнание за ответ (`EXP-0165`: «нет записи» —
 * утверждение о ПОИСКЕ, а не о мире).
 */
export function тихийОтказ(err) {
  return err?.status === 1;
}

