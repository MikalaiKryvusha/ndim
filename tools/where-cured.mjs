function walk(dir) {
  const out = [];
  let names;
  try {
    names = readdirSync(dir);
  } catch {
    return out;
  }
  for (const name of names) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) out.push(...walk(path));
    else if (РАСШИРЕНИЯ.has(extname(name))) out.push(path);
  }
  return out;
}

/**
 * Неслитые ветки: где класс назван у соседей. Лечит случай `close-bug.mjs` наполовину.
 *
 * Разбор ряда идёт по ИЗВЕСТНОЙ приставке ветки, а не образцом `^(.+?):(.+?):`: имя ветки
 * бывает с двоеточием и дефисами, а нежадный образец на таком имени молча съехал бы на
 * половину строки — и промах выглядел бы как путь.
 *
 * Возвращает `{ branch, path, lineno, text, line }`; отсев уже лежащего у меня — снаружи,
 * чистой функцией `rowIsNew`, чтобы его можно было проверить самотестом.
 */
