export function breadthWarning(найдено, корпус, доля = ДОЛЯ_ШИРОКОГО) {
  if (!Number.isFinite(корпус) || корпус <= 0) return [];
  const часть = найдено / корпус;
  if (часть <= доля) return [];
  const пц = (x) => `${(x * 100).toFixed(1).replace('.', ',')} %`;
  return [
    `⚠️  ЗАПРОС СВЕРХШИРОК: он попал в ${найдено} файлов из ${корпус} — это ${пц(часть)} корпуса ` +
      `при объявленной границе ${пц(доля)}.`,
    '   ОПАСНОСТЬ НЕ В ДЛИНЕ ВЫВОДА, А В ТОМ, ЧТО ОТВЕТ НИЧЕГО НЕ ВЫДЕЛЯЕТ: запрос, встречающийся',
    '   почти везде, не указывает на лечение класса — он показывает, что слово общеупотребительно.',
    '   Сузь запрос до имени класса (`EXP-NNNN`, `bugs/NNN`, слова из шапки лечения).',
  ];
}

