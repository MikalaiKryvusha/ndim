/**
 * СТРАЖ БРЕНД-ИМЕНИ «СЕРВЕР СИНХРОНИЗАЦИИ».
 *
 * Правило владельца 2026-08-15, дословно: «*записать в историю, что отныне это строгое канон
 * правило на бренд имя — сервер синхронизации. **Любое применение иного термина — запрет, баг,
 * срочное исправление** на сервер синхронизации*». И причина, названная им же: «*никакого
 * «вычислителя» быть не должно — это отсебятина, придуманная ИИ агентом по ошибке при переносе
 * старого NDim Space 1.x в новый 2.0*».
 *
 * 🔑 ПОЧЕМУ СТРАЖ, А НЕ ЗАПИСЬ В КАНОНЕ. Запись там уже была — и разрешала «вычислитель» как
 * «внутреннее имя папки». Ровно эта поблажка позволила отсебятине расползтись на 715 мест в
 * 146 файлах. Правило, которое можно забыть, здесь уже не работало (`AGENT_GUIDE` → «Журнал
 * опыта»: убрать ловушку → страж → и только потом запись).
 *
 * ⚠️ ЧЕГО СТРАЖ НЕ ДЕЛАЕТ: он не запрещает слово «калькулятор» вообще. «Калькулятор любви» —
 * утверждённое имя страницы (интервью №028), а «интернет-калькуляторы» — о чужих сайтах. Страж
 * ловит имя НАШЕГО КОМПОНЕНТА, поэтому смотрит на формы пути и идентификатора плюс русское
 * «вычислитель», которое другого значения в проекте не имеет вовсе.
 *
 * Запуск: node tools/verify-sync-server-name.mjs
 * Выход: 0 — чисто; 1 — найдено запрещённое имя.
 */
import { execSync } from 'node:child_process';
import { readFileSync } from 'node:fs';

/*
 * ⛔ Исключения. Каждое — с причиной; исключение без причины само является нарушением
 * (тот же принцип, что у стража вопросов).
 */
const ALLOW = [
	// Данные каталога: «вычислительница» — профессия героини ФИЛЬМА, английское calculator может
	// стоять в описании любого произведения. Это не про наш компонент.
	{ test: /^src\/lib\/content\/dims-(build|slice)\.json$/, why: 'каталог измерений — данные, не наш текст' },
	{ test: /^researches\/34_demand_/, why: 'выгрузка спроса — чужие данные' },
	// Тексты продукта: «Калькулятор любви» (интервью №028) и фраза о ЧУЖИХ сайтах.
	{ test: /^src\/lib\/content\/test-copy\.ts$/, why: 'утверждённое имя страницы «Калькулятор любви»' },
	// Страж жаргона: слово стоит там как ЗАПРЕЩЁННОЕ и как фикстура, которую он обязан пропускать.
	{ test: /^e2e\/no-jargon\.spec\.ts$/, why: 'сам запрещает это слово — держит его как образец' },
	{ test: /^e2e\/dims\.spec\.ts$/, why: 'проверяет отсутствие жаргона в собранном сайте' },
	// Этот файл: в нём запрещённые имена перечислены по долгу службы.
	{ test: /^tools\/verify-sync-server-name\.mjs$/, why: 'сам страж' },
	// Прошлое не переписывается: хроника, архив канона, дословные ответы владельца.
	{ test: /^PROJECT_HISTORY\.md$/, why: 'append-only хроника прошлого' },
	{ test: /^\.kaif\/backup-/, why: 'архивный слепок канона до KAIF 2.2' },
	{ test: /^interviews\/decisions\//, why: 'ответы владельца дословно' },
	// Документы, где имя старой директории цитируется как ИСТОРИЯ переименования.
	{ test: /^bugs\/13[01]_/, why: 'разбор дефектов, где путь назван как он был' },
];

/** Запрещённые имена НАШЕГО компонента — с человеческим объяснением для отчёта. */
const FORBIDDEN = [
	{ re: /[Вв]ычислител[ья](?![а-яёА-ЯЁ])/g, what: '«вычислитель» — отсебятина ИИ' },
	{ re: /[Вв]ычислителе[мй]?(?![а-яёА-ЯЁ])/g, what: '«вычислитель» в косвенном падеже' },
	{ re: /ndim-calculator/g, what: 'старое имя образа' },
	{ re: /(^|[^-\w])calculator\//g, what: 'старый путь директории' },
	{ re: /`calculator`/g, what: 'старый идентификатор' },
	{ re: /\bCALC_[A-Z_]+/g, what: 'старый префикс переменных окружения' },
	{ re: /\[calc[\s\]]/g, what: 'старый префикс лога' },
	{ re: /\bcalc:image\b|\btest:calc\b/g, what: 'старые имена npm-скриптов' },
];

const files = execSync('git ls-files', { encoding: 'utf8', maxBuffer: 1 << 28 }).split('\n').filter(Boolean);
const allowed = (file) => ALLOW.find((a) => a.test.test(file));

let violations = 0;
let scanned = 0;
const skipped = new Map();

for (const file of files) {
	if (!/\.(mjs|ts|svelte|md|json|yml|html|txt)$|Dockerfile$/.test(file)) continue;
	const skip = allowed(file);
	if (skip) {
		skipped.set(file, skip.why);
		continue;
	}
	let text;
	try {
		text = readFileSync(file, 'utf8');
	} catch {
		continue;
	}
	scanned += 1;
	// ⚠️ Разбиение УЧИТЫВАЕТ CRLF: у проекта `core.autocrlf=true`, и при `split('\n')` каждая
	// строка кончается на `\r`. Якорь `$` тогда не достаёт до текста маркера, и исключение молча
	// не срабатывает — поймано на себе при первом же прогоне.
	const lines = text.split(/\r?\n/);

	/*
	 * МАРКЕР ИСКЛЮЧЕНИЯ — `ИМЯ-ОК: причина`, по образцу стража вопросов.
	 * Он нужен там, где запрещённое имя стоит ПО ДЕЛУ: канон объявляет запрет и обязан назвать
	 * запрещённое слово; разбор дефекта цитирует старый путь; скрипт объясняет, почему считает
	 * по обоим путям. Маркер действует на 15 строк ВПЕРЁД — привязан к месту, а не к файлу,
	 * иначе одна пометка ослепляла бы документ целиком.
	 * 🔑 Маркер БЕЗ причины сам является нарушением: иначе он стал бы способом заткнуть стража.
	 */
	const exempt = (lineNumber) => {
		for (let i = Math.max(0, lineNumber - 16); i < lineNumber; i += 1) {
			const m = lines[i]?.match(/ИМЯ-ОК:\s*(\S.*)?$/);
			if (!m) continue;
			if (m[1] && m[1].replace(/-->|\*\/|\s/g, '').length > 0) return true;
			console.log(`  ❌ ${file}:${i + 1} — маркер ИМЯ-ОК без причины`);
			violations += 1;
		}
		return false;
	};

	for (const { re, what } of FORBIDDEN) {
		for (let n = 0; n < lines.length; n += 1) {
			re.lastIndex = 0;
			const hits = lines[n].match(re);
			if (!hits) continue;
			if (exempt(n + 1)) continue;
			violations += hits.length;
			console.log(`  ❌ ${file}:${n + 1} — ${what} (${hits.length})`);
		}
	}
}

console.log('\n═══ СТРАЖ БРЕНД-ИМЕНИ «СЕРВЕР СИНХРОНИЗАЦИИ» ═══');
console.log(`просмотрено файлов : ${scanned}`);
console.log(`исключений         : ${skipped.size} (каждое с причиной)`);
console.log(`нарушений          : ${violations}`);
if (violations === 0) {
	console.log('\n✅ запрещённых имён компонента не найдено');
} else {
	console.log('\n🔴 Правило владельца: любое применение иного термина — запрет, баг, срочное исправление.');
}
process.exit(violations === 0 ? 0 : 1);
