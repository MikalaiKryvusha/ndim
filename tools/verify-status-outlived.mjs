/**
 * СТРАЖ «СТРОКА ПЕРЕЖИЛА СВОЁ ИСПОЛНЕНИЕ» — слой 1 (`bugs/177`).
 *
 * Что ловит: документ, чья шапка объявляет его НЕНАЧАТЫМ, при том что работа по нему в git уже
 * есть. Один класс, одна мера, один прибор.
 *
 * 🔑 ПОЧЕМУ КЛАСС НЕ САМОИСПРАВЛЯЕТСЯ, и почему без машины он прожил восемь раз. Строка «не
 * начат» врёт в сторону БЕЗДЕЙСТВИЯ: она останавливает работу, которая давно разрешена. Агент,
 * поверивший ей, ничего не ломает — он просто не делает. Симптома не видно вовсе, пока кто-то не
 * сверит строку с миром; живёт она ровно столько, сколько никто не сверяет. Машине это стоит
 * секунды, человеку — не стоит ничего, потому что он не знает, что надо смотреть.
 *
 * ⛔ ЧЕГО ЭТОТ ПРИБОР НЕ ДЕЛАЕТ, И ЭТО ГРАНИЦА, А НЕ НЕДОДЕЛКА:
 *   · не судит «ждём выката», «ждём руки владельца», «назначено на четверг» — у них нет дешёвой
 *     машинной проверки, и это слой 2 (`bugs/177`) со своей механикой маркеров;
 *   · не трогает проверку 4 стража вопросов (`npm run questions`) — та про ИНТЕРВЬЮ, у неё своя
 *     мера и свой файл базовой линии. Смешение двух мер даёт третью, которую никто не понимает;
 *   · не ведёт ручного реестра ожиданий — реестр разъедется ровно так же, как разъехались четыре
 *     строки, из-за которых прибор и написан.
 *
 * Запуск:
 *   node tools/verify-status-outlived.mjs            # красное = ненулевой код
 *   node tools/verify-status-outlived.mjs --quiet    # только итог
 *   node tools/verify-status-outlived.mjs --selftest # проверить сам прибор, без git и файлов
 */
import { readFileSync, readdirSync, existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

const КАТАЛОГИ = ['plans', 'bugs'];

/** Сколько первых строк документа считаются шапкой. Дальше «Статус:» — уже текст, а не поле. */
const ШАПКА_СТРОК = 40;

/** Сколько строк подряд может занимать значение поля «Статус:» (оно переносится). */
const СТАТУС_СТРОК = 3;

/*
 * ПРИЗНАК «НЕ НАЧАТ». Список закрытый и короткий нарочно: каждое выражение здесь обязано означать
 * «работы по этому документу ещё нет». Всё, что означает «работа идёт, но не закончена» («в
 * работе», «частично», «заперт»), сюда не входит — иначе прибор начнёт судить ТЕМП, а не ложь.
 */
const НЕ_НАЧАТ = [/не\s+начат[аоы]?\b/i, /🔲\s*написан/i, /не\s+начина/i];

/** Ссылка на документ в теле коммита: `plans/58`, но НЕ `plans/580` и не `plans/5`. */
const упоминание = (каталог, номер) => new RegExp(`${каталог}[/\\s-]?0*${номер}(?![0-9])`, 'i');

export function объявленНеначатым(статус) {
  return НЕ_НАЧАТ.some((re) => re.test(статус));
}

/**
 * ЗНАЧЕНИЕ ПОЛЯ «Статус:» ИЗ ШАПКИ. Поле переносится на следующую строку, поэтому берётся не
 * строка, а ЗНАЧЕНИЕ: продолжением считается строка, не открывающая новое **Поле:**.
 */
export function статусИзШапки(текст) {
  const строки = String(текст).split(/\r?\n/).slice(0, ШАПКА_СТРОК);
  const i = строки.findIndex((s) => s.includes('**Статус:**'));
  if (i < 0) return null;
  const метка = '**Статус:**';
  const части = [строки[i].slice(строки[i].indexOf(метка) + метка.length)];
  for (let j = i + 1; j < Math.min(строки.length, i + СТАТУС_СТРОК); j += 1) {
    const s = строки[j];
    if (!s.trim() || /\*\*[^*]+:\*\*/.test(s) || /^#{1,6}\s/.test(s)) break;
    части.push(s.replace(/^>\s?/, ''));
  }
  return части.join(' ').trim();
}

/**
 * РАБОТА ПО ДОКУМЕНТУ — и определение здесь ГЛАВНОЕ во всём приборе.
 *
 * Работа = коммит, который (1) НАЗЫВАЕТ документ в заголовке и (2) изменил хоть что-нибудь ВНЕ
 * `plans/` и `bugs/`.
 *
 * 🔴 Оба условия оплачены ложным срабатыванием, а не осторожностью. Первая редакция считала
 * работой ЛЮБОЙ коммит, тронувший файл плана, — и покрасила `plans/59`, у которого исполнение
 * действительно не начиналось: коммит `715d561` (эпик 60) внёс в план ОТВЕТ ВЛАДЕЛЬЦА, закрыв
 * развилку. Правка плана — это ПЛАНИРОВАНИЕ, а «не начат» говорит про ИСПОЛНЕНИЕ; смешивать их
 * значит краснеть на аккуратно ведомом плане. Отсюда условие (2).
 * Условие (1) отсекает обратную беду: план исполняют кодом внутри чужого большого коммита, и без
 * имени в заголовке любой такой коммит приписывался бы всем планам подряд.
 *
 * 🔑 И коммит ЗАВЕДЕНИЯ документа отсекается тем же правилом, а не отдельным случаем: он трогает
 * только сам документ, значит по условию (2) работой не является. Один закон вместо закона и
 * исключения к нему.
 *
 * ⚠️ ЧЕСТНАЯ ГРАНИЦА, ВЫБРАННАЯ СОЗНАТЕЛЬНО: исполнение, закоммиченное БЕЗ имени документа в
 * заголовке, прибор пропустит. Это ПРОПУСК, а не ложь, и он выбран нарочно — вечно красный страж
 * приучает себя игнорировать, и тогда он не стоит ничего (та же граница объявлена у стража
 * вопросов: ложная тревога дороже пропуска).
 */
export function работаПо(каталог, номер, всеКоммиты, файлыКоммита) {
  const re = упоминание(каталог, номер);
  return всеКоммиты
    .filter((c) => re.test(c.s))
    .filter((c) => файлыКоммита(c.h).some((f) => !/^(plans|bugs)\//.test(f)));
}

/** Заголовки всех коммитов по спрошенным ссылкам — один вызов git на весь прогон. */
function всеЗаголовки(ссылки) {
  try {
    return execFileSync('git', ['log', '--format=%h\t%s', ...ссылки], { encoding: 'utf8' })
      .split('\n')
      .filter(Boolean)
      .map((s) => {
        const [h, ...t] = s.split('\t');
        return { h, s: t.join('\t') };
      });
  } catch {
    return [];
  }
}

/** Файлы коммита, с памятью: один и тот же коммит спрашивается несколькими документами. */
function читательФайлов() {
  const память = new Map();
  return (hash) => {
    if (!память.has(hash)) {
      let файлы = [];
      try {
        файлы = execFileSync('git', ['show', '--name-only', '--format=', hash], { encoding: 'utf8' })
          .split('\n')
          .map((s) => s.trim())
          .filter(Boolean);
      } catch {
        файлы = [];
      }
      память.set(hash, файлы);
    }
    return память.get(hash);
  };
}

function собрать(ссылки) {
  const находки = [];
  const всеКоммиты = всеЗаголовки(ссылки);
  const файлыКоммита = читательФайлов();
  let просмотрено = 0;
  let объявились = 0;
  for (const каталог of КАТАЛОГИ) {
    if (!existsSync(каталог)) continue;
    for (const имя of readdirSync(каталог).filter((f) => f.endsWith('.md') && f !== 'README.md')) {
      просмотрено += 1;
      const файл = join(каталог, имя).replace(/\\/g, '/');
      const статус = статусИзШапки(readFileSync(файл, 'utf8'));
      if (!статус || !объявленНеначатым(статус)) continue;
      объявились += 1;
      const номер = (имя.match(/^(\d+)/) ?? [])[1];
      if (!номер) continue;
      const коммиты = работаПо(каталог, номер, всеКоммиты, файлыКоммита);
      if (коммиты.length) находки.push({ файл, статус: статус.replace(/\s+/g, ' ').slice(0, 90), коммиты });
    }
  }
  return { находки, просмотрено, объявились };
}

/** Ссылки, по которым спрашивается работа: своя ветка И `main` — работа может лежать в любой. */
function ссылкиДляОпроса() {
  const есть = (ref) => {
    try {
      execFileSync('git', ['rev-parse', '--verify', '--quiet', ref], { encoding: 'utf8' });
      return true;
    } catch {
      return false;
    }
  };
  return ['HEAD', 'main'].filter(есть);
}

function selftest() {
  const случаи = [
    ['🔲 написан, не начат.', true, 'план, объявленный неначатым'],
    ['🔲 написан, НЕ начат — заперт воротами', true, 'заглавные и хвост после тире'],
    ['🔧 шаг 1 НАЧАТ — обвязка легла двумя коммитами', false, '«НАЧАТ» без «не» не считается'],
    ['✅ ПОЧИНЕН в ветке, доказан мутацией', false, 'закрытый документ'],
    ['🔬 класс доказан замером, лечение спланировано', false, 'работа идёт'],
    ['в работе, частично закрыт', false, '«в работе» — это темп, а не ложь'],
  ];
  let плохо = 0;
  for (const [текст, ждём, зачем] of случаи) {
    const получено = объявленНеначатым(текст);
    if (получено !== ждём) {
      плохо += 1;
      console.log(`  ❌ ${зачем}: ждали ${ждём}, получили ${получено}`);
    } else {
      console.log(`  ✅ ${зачем}`);
    }
  }

  /* Разбор шапки проверяется отдельно: перенос значения на вторую строку — живой случай. */
  const шапка = '# План\n\n> **Создан:** 2026-08-17 ·\n> **Статус:** 🔲 написан,\n> не начат.\n> **Исходящее:** —';
  const значение = статусИзШапки(шапка);
  if (!значение || !объявленНеначатым(значение)) {
    плохо += 1;
    console.log(`  ❌ перенос значения на вторую строку: получено «${значение}»`);
  } else {
    console.log('  ✅ перенос значения на вторую строку');
  }

  /* Соседний номер не должен ловиться: без границы «5» съел бы «58» и прибор врал бы каждый раз. */
  if (упоминание('plans', '5').test('fix(plans/58): тег одной оси')) {
    плохо += 1;
    console.log('  ❌ номер 5 поймался на plans/58');
  } else {
    console.log('  ✅ номер 5 НЕ ловится на plans/58');
  }
  if (!упоминание('plans', '58').test('fix(plans/58): тег одной оси')) {
    плохо += 1;
    console.log('  ❌ номер 58 не поймался на plans/58');
  } else {
    console.log('  ✅ номер 58 ловится на plans/58');
  }
  if (!упоминание('bugs', '177').test('bugs/177: класс доказан')) {
    плохо += 1;
    console.log('  ❌ номер 177 не поймался на bugs/177');
  } else {
    console.log('  ✅ номер 177 ловится на bugs/177');
  }

  console.log(плохо ? `\n❌ самотест провален: ${плохо}` : `\n✅ самотест пройден: ${случаи.length + 4} случаев`);
  return плохо;
}

/*
 * 🔴 ПРЕДОХРАНИТЕЛЬ «ЗАПУСТИЛИ ИЛИ ПОДКЛЮЧИЛИ», И ОН НАКРЫВАЕТ ОБА РЕЖИМА — самотест тоже.
 *
 * Файл экспортирует разбор шапки и признак «не начат», значит его будут ИМПОРТИРОВАТЬ (юниты уже
 * импортируют). Без предохранителя импорт запускал бы обход корпуса и `process.exit` — то есть
 * убивал бы чужой процесс. Класс за двое суток встречался пять раз, включая самотест ворот правок,
 * который печатал зелёный, ни разу не отработав, потому что его дёргал чужой импорт (П3 `plans/70`).
 */
const запущенНапрямую = Boolean(process.argv[1]) && import.meta.url === pathToFileURL(process.argv[1]).href;

const тихо = process.argv.includes('--quiet');

if (!запущенНапрямую) {
  // Подключили как модуль — отдаём только чистые функции и не делаем ничего.
} else if (process.argv.includes('--selftest')) {
  process.exit(selftest() ? 1 : 0);
} else {
  прогнать();
}

function прогнать() {
const ссылки = ссылкиДляОпроса();
const { находки, просмотрено, объявились } = собрать(ссылки);

if (!тихо) {
  console.log(`\n═══ СТРОКА ПЕРЕЖИЛА СВОЁ ИСПОЛНЕНИЕ (слой 1) ═══`);
  console.log(`спрошено по ссылкам: ${ссылки.join(', ')}`);
  console.log(`просмотрено документов: ${просмотрено} · объявили себя неначатыми: ${объявились}\n`);
  for (const н of находки) {
    console.log(`❌ ${н.файл}`);
    console.log(`   шапка говорит: «${н.статус}»`);
    console.log(`   а работа есть — коммитов ${н.коммиты.length}:`);
    for (const c of н.коммиты.slice(0, 6)) console.log(`     ${c.h}  ${c.s.slice(0, 90)}`);
    if (н.коммиты.length > 6) console.log(`     … и ещё ${н.коммиты.length - 6}`);
    console.log('');
  }
}

console.log(
  находки.length
    ? `❌ документов, объявленных неначатыми при живой работе: ${находки.length}`
    : '✅ ни один документ не объявляет себя неначатым при живой работе',
);
process.exit(находки.length ? 1 : 0);
}
