#!/usr/bin/env node
/**
 * СТРАЖ СЛОВАРЯ ПРОДУКТА — механизация правила, которое три недели жило прозой (`bugs/115`).
 *
 * ЧТО ОХРАНЯЕТСЯ. `AGENT_GUIDE.md` → «Словарь продукта» держит колонку «❌ НИКОГДА не пишем», и
 * про главное слово там сказано прямым текстом: «"Ось" — рабочий жаргон разработки; наружу, к
 * человеку, он выходить не должен НИКОГДА». Правило было. Механизма не было — и слово уехало на
 * **10 222 публичные страницы** разом, где его и увидел владелец.
 *
 * 🔴 ПОЧЕМУ СУЩЕСТВУЮЩИЙ СТРАЖ ЭТО ПРОПУСТИЛ. `e2e/no-jargon.spec.ts` стережёт жаргон
 * РАЗРАБОТЧИКА (команды запуска,技нические слова оснастки). Слова словаря ПРОДУКТА не проверял
 * никто. Два разных класса под одним словом «жаргон» — и один из них был без охраны.
 *
 * ЧТО СУДИТСЯ. Видимый текст СОБРАННОГО сайта — ровно то, что читает человек. Не исходники:
 * слово может приехать из данных, из генерируемого `docs.ts`, из чужого компонента.
 *
 * ⚠️ ГРАНИЦА, названная честно. Стерегутся ПУБЛИЧНЫЕ страницы — лицо продукта. Личные экраны
 * (`/profile`, `/dims`, `/relations`, `/space`, `/menu`) под `noindex` в сборке присутствуют, и
 * их видимый текст тоже проверяется: правило словаря действует и внутри приложения. Исключение
 * ровно одно и оно осознанное — см. `ALLOW` ниже.
 *
 * Запуск:  npm run build && node tools/verify-product-vocabulary.mjs
 * Выход:   0 — чисто; 1 — есть нарушения.
 */
import { readFileSync, existsSync, readdirSync, statSync } from 'node:fs';
import { join, sep } from 'node:path';

const BUILD = 'build';

/**
 * Запрещённые слова словаря продукта. Формы перечислены явно, а не выведены стеммером: список
 * короткий, а стеммер добавил бы ложные срабатывания на ровном месте.
 *
 * 🔑 Каждая строка — из колонки «НИКОГДА не пишем» канона. Добавляешь слово в словарь — добавь и
 * сюда, иначе правило снова станет пожеланием.
 */
const BANNED = [
  { re: /(?<!\p{L})(ось|оси|осью|осей|осям|осями|осях)(?!\p{L})/giu, what: 'ось/оси — говорим «измерение»' },
  { re: /(?<!\p{L})(axis|axes)(?!\p{L})/giu, what: 'axis/axes — говорим «dimension»' },
  { re: /(?<!\p{L})(матч|матчи|матчей|мэтч|мэтчи)(?!\p{L})/giu, what: 'матч/мэтч — говорим «связи»' },
  { re: /(?<!\p{L})(вычислител[ья]|калькулятор)(?!\p{L})/giu, what: 'сервер синхронизации — говорим «сервер синхронизации»' },
];

/**
 * Осознанные исключения ПО СТРАНИЦАМ. Пусто — и это правильно: страница целиком в этом списке
 * слепа к стражу навсегда, а завтра в неё допишут настоящий жаргон.
 */
const ALLOW = [];

/**
 * Осознанные исключения ПО ТЕРМИНУ — вырезаются из текста до поиска, как и области данных.
 *
 * 🔴 Правило заведения, и оно жёстче, чем у `ALLOW`: только СЛОВО ВЛАДЕЛЬЦА, только на
 * конкретное сочетание, и причина записана рядом. Страница остаётся под стражем целиком —
 * слепым становится ровно одно утверждённое имя, а не весь экран.
 *
 * 🟡 Найдено 2026-08-14 прогоном фазы 2: страж краснел на ЧЕТЫРЁХ страницах семейства «Тест»,
 * выкаченных днём раньше, и краснел НЕ НА ЖАРГОНЕ. Слово «калькулятор» стоит в словаре в колонке
 * «никогда не пишем» как чужое имя СЕРВЕРА СИНХРОНИЗАЦИИ — а на этих страницах оно означает
 * совсем другое: так называется сама страница, и это название утвердил владелец
 * (интервью №028: «Калькулятор любви» `/{lang}/test/love`). Два разных предмета под одним
 * словом; запрет остаётся у первого.
 */
const ALLOW_TERMS = [
  {
    re: /калькулятор\w*\s+любви/giu,
    why: 'название страницы, утверждённое владельцем (интервью №028); запрет словаря — о сервере синхронизации',
  },
];

let failed = 0;
let passed = 0;
const check = (name, ok, detail = '') => {
  if (ok) passed += 1;
  else failed += 1;
  console.log(`  ${ok ? '✅' : '❌'} ${name}${detail ? ` — ${detail}` : ''}`);
};

if (!existsSync(BUILD)) {
  console.error('❌ нет каталога build/ — сначала `npm run build`');
  process.exit(1);
}

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...walk(full));
    else if (name.endsWith('.html')) out.push(full);
  }
  return out;
}

/**
 * 🔴 СУДИМ ТОЛЬКО НАШУ ОБВЯЗКУ, А НЕ ДАННЫЕ КАТАЛОГА. Это не послабление, а исправление
 * постановки, и оно оплачено ложным срабатыванием первой редакции.
 *
 * Первая редакция сканировала страницу целиком и покраснела на описаниях «FIFA 12» и «Внезапной
 * смерти»: там «матчи» и «матч» — обычные русские слова о футболе и хоккее, а вовсе не запрещённый
 * синоним «связей». Продолжи я в том же духе, страж ловил бы «Ось зла» в названии фильма, ось
 * автомобиля в описании и «Axis» в фильме о войне.
 *
 * **Словарь продукта правит НАШ ТЕКСТ — интерфейс, заголовки, кнопки, объяснения.** Описания
 * объектов культуры пишет владелец, и слова в них принадлежат предметной области, а не нам.
 * Поэтому области ДАННЫХ вырезаются до поиска: описание, карточка-досье (вид, год, автор, теги)
 * и заголовки с названием объекта.
 *
 * 🆕 **С хабами каталога (`plans/48` шаг 3) данных на страницах стало больше, и вырез расширен.**
 * Хаб показывает 60 названий с авторами, индекс каталога — 25 названий хвоста. Проверено по
 * боевому каталогу: под запрет попадает РОВНО ОДНА запись — фильм «American Traitor: The Trial
 * of **Axis** Sally». То есть без этого выреза страж покраснел бы на исправном продукте, и это
 * ровно та ложная тревога, которой он уже болел на «FIFA 12» и «Внезапной смерти».
 * Пересчитать, а не поверить:
 * ```
 * node --input-type=module -e "import {readFileSync} from 'node:fs';
 * const d=JSON.parse(readFileSync('src/lib/content/dims-build.json','utf8'));
 * const re=/(?<!\p{L})(ось|оси|axis|axes|матч|мэтч)(?!\p{L})/giu;
 * console.log(d.filter(x=>re.test([x.title.ru,x.title.en,x.author.ru,x.author.en].join(' '))).length)"
 * ```
 */
const stripData = (html) =>
  html
    .replace(/<div class="desc[\s\S]*?<\/div>/gi, ' ')
    .replace(/<section class="dossier[\s\S]*?<\/section>/gi, ' ')
    .replace(/<h1[\s\S]*?<\/h1>/gi, ' ')
    .replace(/<p class="orig[\s\S]*?<\/p>/gi, ' ')
    // Ранжированный список хаба каталога: 60 настоящих названий и авторов.
    .replace(/<ol class="[^"]*\brank\b[^"]*"[\s\S]*?<\/ol>/gi, ' ')
    // Хвост индексной страницы каталога: 25 настоящих названий.
    .replace(/<section class="[^"]*\btail\b[^"]*"[\s\S]*?<\/section>/gi, ' ');

/** Утверждённые владельцем сочетания вырезаются так же, как данные, — до поиска. */
const stripApproved = (text) => ALLOW_TERMS.reduce((s, a) => s.replace(a.re, ' '), text);

/** Видимый текст НАШЕЙ обвязки: выкидываем данные, скрипты, стили, комментарии и теги. */
const visible = (html) =>
  stripData(html)
    .replace(/<script[\s\S]*?<\/script>/gi, ' ')
    .replace(/<style[\s\S]*?<\/style>/gi, ' ')
    .replace(/<!--[\s\S]*?-->/g, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/\s+/g, ' ');

const all = walk(BUILD);
/*
 * Страницы каталога однотипны по обвязке: их 10 222, и обходить все ради одного и того же блока
 * незачем. Берём равномерную выборку, а ВСЁ остальное — целиком: там каждая страница своя.
 */
const isCatalog = (f) => f.includes(`${sep}dimension${sep}`);
const catalog = all.filter(isCatalog);
const rest = all.filter((f) => !isCatalog(f));
const step = Math.max(1, Math.floor(catalog.length / 80));
const scanned = [...rest, ...catalog.filter((_, i) => i % step === 0)];

console.log('\n— что проверяем —');
check('сайт собран', all.length > 0, `страниц ${all.length}`);
check('страницы вне каталога проверяются ЦЕЛИКОМ', rest.length > 0, `их ${rest.length}`);
console.log(`  ℹ каталог — выборка ${scanned.length - rest.length} из ${catalog.length}`);

// 🔑 КОНТРОЛЬ ПРИБОРА (EXP-0082). Все проверки ниже отрицательные («ничего не нашлось»), а такие
// красятся зелёным от чего угодно — от опечатки в регулярке до пустой выборки. Поэтому сперва
// доказываем, что прибор УМЕЕТ находить: скармливаем ему заведомо запрещённый текст.
console.log('\n— контроль прибора —');
{
  const probe = 'Человек это точка, а объекты вокруг неё — оси. In English these are axes.';
  const found = BANNED.filter((b) => new RegExp(b.re.source, b.re.flags).test(probe)).length;
  check('прибор ловит заведомо запрещённый текст', found >= 2, `сработало правил: ${found}`);

  /*
   * 🔑 ВТОРАЯ ПОЛОВИНА КОНТРОЛЯ — исключение по термину не ослепило стража. Вырез утверждённого
   * сочетания легко написать так, что он съест и настоящее нарушение рядом; тогда весь этот
   * прогон красился бы зелёным именно там, где обязан кричать.
   */
  const banned = 'Связи считает калькулятор, он же сервер синхронизации.';
  const approved = 'Поиграть вдвоём — калькулятор любви.';
  const hits = (s) => BANNED.filter((b) => new RegExp(b.re.source, b.re.flags).test(stripApproved(s))).length;
  check('вырез утверждённого термина НЕ съедает настоящее нарушение', hits(banned) >= 1);
  check('утверждённое название стражем не считается нарушением', hits(approved) === 0);
  check('и то, и другое в одном тексте: нарушение видно', hits(`${approved} ${banned}`) >= 1);
}

console.log('\n— словарь продукта на лице сайта —');
const hits = [];
for (const file of scanned) {
  const text = stripApproved(visible(readFileSync(file, 'utf8')));
  const page = file.slice(BUILD.length + 1);
  if (ALLOW.some((a) => page.startsWith(a))) continue;
  for (const { re, what } of BANNED) {
    const m = text.match(new RegExp(re.source, re.flags));
    if (m) hits.push({ page, what, sample: [...new Set(m.map((x) => x.toLowerCase()))].join(', ') });
  }
}

const pagesHit = new Set(hits.map((h) => h.page));
check('ни одного запрещённого словом слова', hits.length === 0,
  hits.length === 0 ? `проверено страниц ${scanned.length}` : `страниц с нарушениями: ${pagesHit.size}`);

if (hits.length > 0) {
  console.log('\n  Нарушения (до 15):');
  for (const h of hits.slice(0, 15)) console.log(`    · ${h.page} — ${h.what} (нашлось: ${h.sample})`);
  if (hits.length > 15) console.log(`    … и ещё ${hits.length - 15}`);
  console.log('\n  🔑 Правило — `AGENT_GUIDE.md` → «Словарь продукта». Слово из колонки');
  console.log('     «НИКОГДА не пишем» на лице продукта — это дефект, а не стилистика.');
}

console.log(`\n${failed === 0 ? '✅' : '❌'} проверок ${passed + failed} · провалов ${failed}\n`);
process.exit(failed === 0 ? 0 : 1);
