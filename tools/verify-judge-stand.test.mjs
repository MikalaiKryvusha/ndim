/**
 * ЮНИТ КОНТРОЛЯ СТЕНДА СУДЬИ — тот же список случаев, но зовёт его МАШИНА.
 *
 * 🔴 ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ, ЕСЛИ У ПРИБОРА ЕСТЬ `--selftest`. Потому что `--selftest` зовут рукой,
 * а рукой не зовут никогда. Это `EXP-0194` в чистом виде, и прибор, написанный против ложных
 * ответов стенда, обязан не наступить на него сам: `npm run test:tools` — ПЕРВАЯ запись
 * `guards.mjs`, значит отсюда случаи гоняются на каждом прогоне ворот, у всех ролей, без памяти.
 *
 * 🔑 Список случаев ОДИН на оба входа (`СЛУЧАИ_САМОТЕСТА` экспортируется прибором) — две копии
 * были бы парой, которая молча разъедется, а пару лучше убрать, чем сторожить (`AGENT_GUIDE.md`
 * → DRY, «истина ↔ зеркало»).
 *
 * Прогон: node --test tools/verify-judge-stand.test.mjs   ·   npm run test:tools
 */
import test from 'node:test';
import assert from 'node:assert/strict';

import {
  СЛУЧАИ_САМОТЕСТА,
  бедыЗависимостей,
  бедаИстории,
  бедыДерева,
} from './verify-judge-stand.mjs';

test('контроль стенда: каждый случай самотеста проходит', () => {
  assert.ok(СЛУЧАИ_САМОТЕСТА.length >= 11, 'список случаев усох — контроль стенда потерял покрытие');
  const провалы = СЛУЧАИ_САМОТЕСТА.filter(([, проверка]) => проверка() !== true).map(([имя]) => имя);
  assert.deepEqual(провалы, [], 'случай самотеста провален');
});

/*
 * 🔴 КОНТРОЛЬ САМОГО КОНТРОЛЯ. Без него список из одних «молчит» был бы зелёным, а прибор —
 * немым: ровно тот класс ложного зелёного, против которого он и написан. Поэтому проверяется,
 * что у КАЖДОГО из трёх вопросов в списке есть случай, где он КРАСНЕЕТ.
 */
test('🔴 у каждого вопроса есть случай, где он КРАСНЕЕТ — список не может стать немым', () => {
  const краснеет = {
    зависимости: бедыЗависимостей(['posthog-js'], []).length > 0,
    история: бедаИстории(1).length > 0,
    чистота: бедыДерева(['?? чужое.mjs']).length > 0,
  };
  assert.deepEqual(краснеет, { зависимости: true, история: true, чистота: true });
});

test('вопрос «история» краснеет ТОЛЬКО на синтетическом дереве, а не на любом', () => {
  /* Граница не вкусовая, и юнит её стережёт: два коммита уже дают историю по файлам. */
  assert.equal(бедаИстории(2).length, 0, 'два коммита — уже история, краснеть не на чем');
  assert.equal(бедаИстории(1500).length, 0);
  assert.ok(бедаИстории(1).length > 0, 'один коммит — история синтетическая (EXP-0243)');
  assert.ok(бедаИстории(null).length > 0, 'git промолчал — это НЕ «годен», это «судить нельзя»');
});

test('вопрос «зависимости» спрашивает ПОИМЕННО, а не «каталог существует»', () => {
  /* Живой случай Дизайнера: каталог был, `posthog-js` в нём не было, `check` упал ложным красным. */
  const беды = бедыЗависимостей(['vite', 'posthog-js'], ['vite', 'svelte']);
  assert.ok(беды.length > 0, 'отставший node_modules обязан краснеть при существующем каталоге');
  assert.ok(беды[0].includes('posthog-js'), 'беда обязана НАЗВАТЬ недостающее имя, а не число');
  assert.ok(!беды[0].includes('svelte,'), 'лишнее в node_modules бедой не является');
});
