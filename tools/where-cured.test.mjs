/**
 * ЮНИТ ПРИБОРА «ГДЕ ЭТОТ КЛАСС УЖЕ НАЗВАН В КОДЕ» (`tools/where-cured.mjs`).
 *
 * 🔴 ПОЧЕМУ ЮНИТ У ПРИБОРА, У КОТОРОГО ЕСТЬ `--selftest`, И ПОЧЕМУ ИМЕННО ЗДЕСЬ.
 *
 * Замечание З2 вердикта №20 названо было соседней порции: самотест не способен поймать
 * СОБСТВЕННЫЙ НЕЗАПУСК. У переписи приборов риск закрыт снаружи — она стоит в воротах, и её
 * молчание видно по числу стражей. 🔑 **У этого прибора такой защиты нет вовсе:** он объявляет
 * «Ворота: нет» намеренно (прибор отвечает на вопрос, а не судит дерево), а значит его
 * `--selftest` не зовёт НИКТО и НИКОГДА — ни ворота, ни человек в рабочем прогоне.
 *
 * То есть 23 случая самотеста сегодня доказывают ровно себя: сломай признак — и всё останется
 * зелёным, потому что красить нечему. Это `EXP-0194` этажом ниже («проверка вне ворот не
 * защищает»), и лечение у него одно: позвать проверку ОТТУДА, КУДА ЗАГЛЯДЫВАЮТ ВОРОТА. Глоб
 * `tools/*.test.mjs` стоит первой записью `guards.mjs`, поэтому этот файл — и есть тот вызов.
 *
 * ⛔ ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО: дубля всех 23 случаев самотеста. Юнит покрывает признаки,
 * заведённые пост-оконной корзиной (ширина запроса · честность `--branches` · новизна ряда), и
 * ЗОВЁТ самотест целиком дочерним процессом — так его незапуск становится видимым, а его
 * содержание остаётся в одном месте. Две копии одних случаев разъехались бы первой же правкой.
 *
 * 🔴 Прибор спрашивается ТОЛЬКО дочерним процессом. `--selftest` кончается `process.exit`, и
 * импорт с прямым вызовом убил бы ЧУЖОЙ процесс — набор умер бы молча и засчитался пройденным
 * (класс `ideas/43`). Чистые функции при этом импортируются свободно: предохранитель
 * «запущен напрямую» в приборе есть, и его исправность здесь тоже проверяется.
 *
 * Прогон: node --test tools/where-cured.test.mjs   (или `npm run test:tools`)
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

import { breadthWarning, branchHonesty, rowIsNew, hitsIn, ДОЛЯ_ШИРОКОГО } from './where-cured.mjs';

const ЗДЕСЬ = dirname(fileURLToPath(import.meta.url));
const ПРИБОР = join(ЗДЕСЬ, 'where-cured.mjs');
const прогон = (...argv) => spawnSync(process.execPath, [ПРИБОР, ...argv], { encoding: 'utf8' });

/* ── ГЛАВНОЕ: САМОТЕСТ ЗОВУТ СНАРУЖИ И ТРЕБУЮТ ОТВЕТА ─────────────────────────────────── */

test('самотест прибора отвечает, а не просто «не падает»', () => {
  const r = прогон('--selftest');
  assert.equal(r.status, 0, 'самотест обязан выйти нулём');
  assert.match(r.stdout, /САМОТЕСТ ЧИСТ: случаев (\d+)/u);
  const сколько = Number(r.stdout.match(/случаев (\d+)/u)[1]);
  // Пустой набор напечатал бы «случаев 0» и вышел бы нулём — зелёный, не способный покраснеть.
  assert.ok(сколько >= 20, `набор обязан быть непустым, получено ${сколько}`);
});

test('🔑 КОНТРОЛЬ предохранителя: импорт модуля НЕ убивает чужой процесс', () => {
  // Сам факт, что этот файл дожил до этой строки, уже доказывает предохранитель: импорт
  // `where-cured.mjs` наверху не позвал ни `run`, ни `selftest`, иначе набора бы не было.
  assert.equal(typeof breadthWarning, 'function');
  assert.equal(typeof rowIsNew, 'function');
});

/* ── ШИРИНА ЗАПРОСА (замечание З1 вердикта №22) ───────────────────────────────────────── */

test('сверхширокий запрос предупреждает, живой класс — молчит', () => {
  // Числа живые, из таблицы замера в шапке прибора (корпус 434 файла).
  assert.ok(breadthWarning(434, 434).length > 0, '«.» — 100 % корпуса');
  assert.ok(breadthWarning(166, 434).length > 0, '«npm» — 38,2 %, ближайшая опасность');
  assert.equal(breadthWarning(30, 434).length, 0, '«кириллиц» — 6,9 %, живой максимум');
  assert.equal(breadthWarning(5, 434).length, 0, '«EXP-0227» — 1,2 %, самый узкий живой класс');
});

test('🔴 предупреждение называет ОПАСНОСТЬ и ДОЛЮ, а не длину запроса', () => {
  const текст = breadthWarning(434, 434).join(' ');
  assert.match(текст, /корпуса/u, 'опасность меряется долей корпуса');
  assert.match(текст, /НИЧЕГО НЕ ВЫДЕЛЯЕТ/u, 'названо, ЧТО именно сломалось в ответе');
  assert.doesNotMatch(текст, /коротк/u, 'лечение длиной запроса было отвергнуто с доводом');
});

test('граница объявлена числом и «превышает», а не «достигает»', () => {
  assert.equal(ДОЛЯ_ШИРОКОГО, 0.25, 'число названо в модуле, а не спрятано в условии');
  assert.equal(breadthWarning(25, 100).length, 0, 'ровно доля — молчит');
  assert.ok(breadthWarning(26, 100).length > 0, 'выше доли — говорит');
});

test('🔑 КОНТРОЛЬ: пустой корпус не делит на ноль и не выдумывает предупреждение', () => {
  assert.equal(breadthWarning(0, 0).length, 0);
  assert.equal(breadthWarning(5, 0).length, 0);
  assert.equal(breadthWarning(5, NaN).length, 0);
});

/* ── ЧЕСТНОСТЬ `--branches` (замечание З3 вердикта №22) ───────────────────────────────── */

test('🔴 вторая строка честности говорит «ЕЩЁ НЕТ» и называет класс EXP-0227', () => {
  const текст = branchHonesty(3).join(' ');
  assert.match(текст, /ЕЩЁ НЕТ/u);
  assert.match(текст, /EXP-0227/u);
  assert.match(текст, /НЕ ЗАЩИЩЁН/u, 'сказано не про взятие находки, а про сегодняшнюю защиту');
});

test('🔑 КОНТРОЛЬ: над пустотой честность молчит', () => {
  assert.deepEqual(branchHonesty(0), []);
});

/* ── НОВИЗНА РЯДА — признак, без которого честность выше ЛЖЁТ ─────────────────────────── */

test('🔴 ЖИВОЙ ПРОМАХ: дословно лежащая у меня строка — НЕ новость', () => {
  const мой = '/**\n * Запуск: node tools/close-bug.mjs <NNN>\n */\n';
  assert.equal(rowIsNew({ path: 'tools/close-bug.mjs', text: ' * Запуск: node tools/close-bug.mjs' }, мой), false);
});

test('🔑 КОНТРОЛЬ: признак не съедает настоящую находку', () => {
  assert.equal(rowIsNew({ path: 'tools/x.mjs', text: 'новое лечение соседа' }, 'const x = 1;\n'), true,
    'строки в моём файле нет — новость');
  assert.equal(rowIsNew({ path: 'tools/нет.mjs', text: 'что угодно' }, null), true,
    'файла у меня нет вовсе — новость (это случай close-bug ДО мержа)');
  assert.equal(rowIsNew({ path: 'tools/x.mjs', text: '' }, 'const x = 1;\n'), true,
    'разбор ряда не удался — глотать ряд нельзя');
});

test('отступ не считается различием: сверка по обрезанной строке', () => {
  assert.equal(rowIsNew({ path: 'tools/x.mjs', text: '        const cure = 1;' }, '  const cure = 1;\n'), false);
});

/* ── КОНТРОЛЬ САМОГО НАБОРА: признак поиска жив ───────────────────────────────────────── */

test('🔑 КОНТРОЛЬ: пустой запрос не совпадает ни с чем, а живой — совпадает', () => {
  const образец = '/**\n * Класс CRLF объясняется здесь.\n */\n';
  assert.equal(hitsIn(образец, '').length, 0, 'иначе прибор вывалил бы дерево');
  assert.equal(hitsIn(образец, 'crlf').length, 1, 'иначе набор судил бы мёртвый признак');
});
