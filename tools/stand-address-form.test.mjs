/**
 * ЮНИТЫ ФОРМЫ АДРЕСА СТЕНДА — суждение стража, отделённое от дерева.
 *
 * Страж `verify-stand-address-form.mjs` судит живые файлы; здесь судится САМ ПРИЗНАК, на
 * синтетике. Это разделение не церемония: на живом дереве дефектных форм сегодня НОЛЬ, и
 * страж зелен по существу — а зелёный признак, который ни разу не краснел, не доказывает
 * ничего (`TESTING_FRAMEWORK.md`, ворота наблюдения, п. 5). Красным его делает этот файл.
 *
 * 🔴 ДВА СЛУЧАЯ ЗДЕСЬ — ОПЛАЧЕННЫЕ ПРОМАХИ ПЕРВЫХ РЕДАКЦИЙ, а не полнота ради полноты:
 *   · «обратная кавычка с подстановкой — это ЛЕЧЕНИЕ, а не дефект»: первая редакция признака
 *     не различала кавычку и обратную и объявила дефектными четыре прибора, вылеченных тем же
 *     днём. Признак ПОКРАСНЕЛ НА ЛЕЧЕНИИ — самый дорогой род ложного срабатывания, он посылает
 *     ломать починенное;
 *   · «у вылеченной формы есть ИМЯ»: без имени она падала в «не опознано» и читалась как
 *     недоделка. Молчание прибора неотличимо от его вердикта, если у состояния нет имени.
 */
import assert from 'node:assert/strict';
import { test } from 'node:test';

import { формаАдреса, безКомментариев, ДЕФЕКТНЫЕ_ФОРМЫ } from './lib/stand-address-form.mjs';

test('🔴 ПРИСВОЕНИЕ литералом — дефект: перебивает даже верный адрес от emulators:exec', () => {
  for (const строка of [
    "process.env.FIRESTORE_EMULATOR_HOST = '127.0.0.1:8181';",
    'process.env.FIREBASE_AUTH_EMULATOR_HOST = "127.0.0.1:9099";',
    'process.env.FIREBASE_STORAGE_EMULATOR_HOST = `127.0.0.1:9199`;',
  ]) {
    assert.equal(формаАдреса(строка), 'присвоение', `не опознано как дефект: ${строка}`);
  }
  assert.ok(ДЕФЕКТНЫЕ_ФОРМЫ.includes('присвоение'), 'присвоение обязано числиться дефектной формой');
});

test('🔴🔴 ОБРАТНАЯ КАВЫЧКА С ПОДСТАНОВКОЙ — ЭТО ЛЕЧЕНИЕ, А НЕ ДЕФЕКТ', () => {
  // Ровно та строка, на которой первая редакция признака покраснела на четырёх вылеченных
  // приборах. Признак, посылающий ломать починенное, вреднее отсутствующего.
  const лечение = 'process.env.FIRESTORE_EMULATOR_HOST = `127.0.0.1:${ports.firestore}`;';
  assert.equal(формаАдреса(лечение), 'изСлота');
  assert.ok(!ДЕФЕКТНЫЕ_ФОРМЫ.includes('изСлота'));
});

test('ЗАПАСНОЕ значение — не дефект: срабатывает, только когда адреса нет', () => {
  for (const строка of [
    "process.env.FIRESTORE_EMULATOR_HOST ??= '127.0.0.1:8181';",
    "if (!process.env.FIRESTORE_EMULATOR_HOST) { process.env.FIRESTORE_EMULATOR_HOST = '127.0.0.1:8181'; }",
  ]) {
    assert.equal(формаАдреса(строка), 'запасное', `не опознано как запасное: ${строка}`);
    assert.ok(!ДЕФЕКТНЫЕ_ФОРМЫ.includes('запасное'));
  }
});

test('ОТКАЗ без env — форма с именем, и она сильнее присвоения в том же файле', () => {
  const исходник = [
    "if (!process.env.FIRESTORE_EMULATOR_HOST) {",
    "  throw new Error('FIRESTORE_EMULATOR_HOST не задан — запускай через emulators:exec');",
    '}',
  ].join('\n');
  assert.equal(формаАдреса(исходник), 'отказ');
});

test('🔒 ПОРЯДОК: полулечённый файл читается как ЗАПАСНОЙ, а не как вылеченный', () => {
  /*
   * ⚠️ ЭТОТ СЛУЧАЙ Я СНАЧАЛА НАПИСАЛ НАОБОРОТ — «лечение сильнее запасного рядом» — и был
   * неправ. Файл, где одна переменная взята из слота, а другая осталась запасной, НЕСЁТ
   * не-слотовый адрес; назвать его вылеченным значило бы спрятать оставшуюся работу.
   * Правка сделана по существу, а не подогнана под реализацию, и след оставлен здесь.
   */
  const смешанный = [
    'process.env.FIRESTORE_EMULATOR_HOST = `127.0.0.1:${ports.firestore}`;',
    "process.env.FIREBASE_AUTH_EMULATOR_HOST ??= '127.0.0.1:9099';",
  ].join('\n');
  assert.equal(формаАдреса(смешанный), 'запасное');
});

test('🔴🔴 ПРИСВОЕНИЕ, ОГОРОЖЕННОЕ `if (!env)`, — ЗАПАСНОЕ, а не дефект', () => {
  /*
   * Ровно строение `sync-server/index.mjs:243`. Вторая редакция признака судила файл целиком,
   * не различая охрану, и объявила бы дефектным исправный сервер синхронизации. Поймано ЭТИМ
   * юнитом до того, как страж встал в ворота.
   */
  const огорожено = [
    "if (projectId.startsWith('demo-') && !process.env.FIRESTORE_EMULATOR_HOST) {",
    "  process.env.FIRESTORE_EMULATOR_HOST = '127.0.0.1:8181';",
    '}',
  ].join('\n');
  assert.equal(формаАдреса(огорожено), 'запасное');
  assert.ok(!ДЕФЕКТНЫЕ_ФОРМЫ.includes('запасное'));
});

test('🔒 охрана считается ПОВАРИАНТНО: огорожена одна переменная — другая всё равно дефект', () => {
  // Иначе один законный `??=` в файле открывал бы дверь любому присвоению рядом.
  const частично = [
    "process.env.FIRESTORE_EMULATOR_HOST ??= '127.0.0.1:8181';",
    "process.env.FIREBASE_AUTH_EMULATOR_HOST = '127.0.0.1:9099';",
  ].join('\n');
  assert.equal(формаАдреса(частично), 'присвоение');
});

test('🔒 литерал в КОММЕНТАРИИ дефектом не является — иначе страж покраснел бы на разборе', () => {
  const разбор = [
    '/*',
    " * Здесь стояло process.env.FIRESTORE_EMULATOR_HOST = '127.0.0.1:8181'; — это и был дефект.",
    ' */',
    "// и в строчном тоже: process.env.FIRESTORE_EMULATOR_HOST = '127.0.0.1:8181';",
    'const x = 1;',
  ].join('\n');
  assert.equal(формаАдреса(разбор), null, 'объяснение дефекта — не дефект');
});

test('файл без адреса эмулятора формы не имеет, и это НЕ «здоров»', () => {
  assert.equal(формаАдреса('const a = 1;'), null);
  assert.equal(формаАдреса(''), null);
  assert.equal(формаАдреса(null), null);
});

test('безКомментариев снимает три вида прозы и не трогает код', () => {
  const src = ['/* блок */', ' * продолжение блока', '// строчный', 'const код = 1;'].join('\n');
  const очищено = безКомментариев(src);
  assert.match(очищено, /const код = 1;/u);
  assert.ok(!/продолжение блока/u.test(очищено));
  assert.ok(!/строчный/u.test(очищено));
});
