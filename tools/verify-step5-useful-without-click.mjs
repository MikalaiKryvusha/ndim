/**
 * ПРИЁМКА ШАГА 5 `plans/56` — «СТРАНИЦА КАТАЛОГА ПОЛЕЗНА БЕЗ КЛИКА ВНУТРЬ ПРОДУКТА».
 *
 * Вектор фазы дословно: «страница каталога полезна БЕЗ клика внутрь продукта». Это ВПЕЧАТЛЕНИЕ,
 * а план требует «результат числом, а не впечатлением». Поэтому впечатление разложено на
 * измеримые вопросы, и каждый отвечает за свой кусок пользы.
 *
 * 🔴 ЧЕКЛИСТ ОБЪЯВЛЕН ДО ПРОГОНА — иначе он подгонится под увиденное. Десять вопросов, и каждый
 * взят из уже принятого решения, а не придуман здесь:
 *
 *   1. Название видно и НЕ ОБРЕЗАНО — закон владельца 2026-08-14 («названия не обрезаются
 *      троеточием, всегда полностью влазят — это закон»): ни `ellipsis`, ни `line-clamp`,
 *      ни `nowrap`, ни срезанной высоты.
 *   2. Описание есть и содержательно — ради него человек и пришёл из поиска.
 *   3. NDSR ПОДПИСАН ПОЛНЫМ ИМЕНЕМ там, где оценки есть (канон бренд-имени: «наш рейтинг» и
 *      «средняя оценка» как ИМЯ величины запрещены), и честная строка там, где их нет.
 *   4. Блок-дверь на месте — канон-текст владельца, написанный его рукой (интервью №036 В3 = C):
 *      заголовок · одно из двух состояний · кнопка.
 *   5. Место объекта среди оценённых своего вида (шаг 2 плана) — там, где оно есть.
 *   6. ⛔ Ни числа похожести, ни «Рядом в Пространстве» — боевой инвариант продукта.
 *   7. ⛔ ПДн нет: ни почты, ни `uid`, ни `/points/`.
 *   8. Консоль чиста.
 *   9. 🔑 СОДЕРЖАНИЕ ЖИВЁТ БЕЗ JS — страница пришедшего из поиска не должна зависеть от скриптов.
 *      Проверяется по СЫРОМУ HTML собранного файла, а не по отрисованной странице.
 *  10. Горизонтального переполнения нет — на 390 особенно.
 *
 * ⚠️ ЧЕГО ЭТОТ ПРИБОР НЕ ДЕЛАЕТ, чтобы не выглядеть шире, чем он есть. Он НЕ судит, хорош ли
 * ТЕКСТ описания: это вкус и territory владельца (вычитка постфактум, №025 В6 = А). Он судит,
 * что странице ЕСТЬ чем быть полезной и что она ничего не ломает. Вкус смотрит человек —
 * для этого прибор и кладёт кадры.
 *
 * ⚠️ И НЕ ДУБЛИРУЕТ `verify-dimension-pages` (40 проверок по сырому HTML) и `verify-catalog-hubs`
 * (93). Те судят СОБРАННЫЙ ФАЙЛ; этот — ЖИВУЮ страницу в браузере, в обеих темах и на двух
 * ширинах, чего файл показать не может. Оба набора гоняются, вопросы у них разные.
 *
 * Выборка — `tools/pick-step5-sample.mjs` (детерминированная, разные виды × три среза
 * оценённости). Случайность здесь запрещена: приёмка обязана повторяться.
 *
 * Требует поднятый preview по СОБРАННОМУ артефакту. Порт — адрес роли, а не «первый свободный»:
 *   npx vite preview --port <порт своего слота> --strictPort
 * ⚠️ `--strictPort` обязателен: голый `vite preview` при занятом порте молча переезжает на
 * соседний, и кадры снимаются с ЧУЖОГО сервера (`EXP-0091` — осиротевший preview отдаёт СТАРУЮ
 * сборку, и это не видно ни по одному признаку, кроме порта).
 *
 * Запуск: node tools/verify-step5-useful-without-click.mjs [--base http://localhost:<порт>]
 *         адрес берётся из `--base`, иначе из окружения (`PROBE_PREVIEW_BASE`), иначе слот 0
 * Выход:  test-results/step5/ (кадры + report.txt) · код 0 — чисто, 1 — есть провалы.
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { readFileSync, existsSync } from 'node:fs';
import { chromium } from '@playwright/test';
import { standAddresses, addressesLine } from './lib/stand-addresses.mjs';

const arg = (n, d = null) => {
  const i = process.argv.indexOf(n);
  return i > 0 && process.argv[i + 1] ? process.argv[i + 1] : d;
};
/*
 * Адрес preview: флаг сильнее окружения, окружение сильнее умолчания слота 0.
 * Литерал `4203` отсюда убран — он привязывал прибор к МОЕМУ слоту так же, как раньше `4173`
 * привязывал соседей к нулевому. Порт своего слота приходит из окружения (`PROBE_PREVIEW_BASE`),
 * таблица слотов живёт у хозяина парка и здесь не дублируется.
 */
const АДРЕСА = standAddresses();
const BASE = arg('--base', АДРЕСА.preview);
const OUT = 'test-results/step5';
const SAMPLE = 'test-results/step5-sample.json';

const lines = [];
const say = (t = '') => {
  console.log(t);
  lines.push(t);
};

let passed = 0;
let failed = 0;
/** На скольких конфигурациях проверке «название не обрезано» БЫЛО ЧТО судить (см. `строкЗаголовка`). */
let многострочных = 0;
const провалы = [];
function check(page, name, ok, detail = '') {
  if (ok) passed += 1;
  else {
    failed += 1;
    провалы.push(`${page} · ${name}${detail ? ` — ${detail}` : ''}`);
  }
  return ok;
}

if (!existsSync(SAMPLE)) {
  console.error(`❌ нет выборки ${SAMPLE} — сначала: node tools/pick-step5-sample.mjs > ${SAMPLE}`);
  process.exit(1);
}
const sample = JSON.parse(readFileSync(SAMPLE, 'utf8'));

/** Сырой HTML собранного файла — им судится вопрос 9 («содержание живёт без JS»). */
function рвHtml(slug) {
  const f = `build/ru/dimension/${slug}.html`;
  return existsSync(f) ? readFileSync(f, 'utf8') : null;
}

const browser = await chromium.launch();
await mkdir(OUT, { recursive: true });

try {
  say('═══ ПРИЁМКА ШАГА 5: «полезна без клика» ═══');
  say(addressesLine(АДРЕСА));
  say(`адрес прогона: ${BASE} · страниц в выборке: ${sample.length}`);
  say('');

  /*
   * КОНТРОЛЬ ПРИБОРА ПЕРВЫМ (`EXP-0082`): убеждаемся, что мы говорим с ЖИВЫМ preview по нашей
   * сборке, а не с осиротевшим чужим сервером. Признак — страница вообще открылась и несёт
   * разметку карточки. Без этого «всё зелено» означало бы «прибор ни до чего не дошёл».
   */
  {
    const p = await browser.newPage();
    const r = await p.goto(`${BASE}/ru/dimension/${sample[0].slug}`, { waitUntil: 'domcontentloaded' }).catch(() => null);
    const ok = r !== null && r.ok();
    say(`контроль прибора: страница ${sample[0].slug} отвечает — ${ok ? '✅' : '❌'}`);
    if (!ok) {
      say(`❌ preview не отвечает по адресу ${BASE}.`);
      say('   Поднят ли он? `--strictPort` обязателен: без него занятый порт не роняет запуск,');
      say('   vite молча переезжает на соседний, и кадры снимаются с ЧУЖОГО сервера.');
      await p.close();
      process.exit(1);
    }
    await p.close();
  }

  for (const запись of sample) {
    const { slug, вид, срез, rates } = запись;
    say('');
    say(`── ${slug} · ${вид} · ${срез} · голосов ${rates}`);

    // ── Вопрос 9 судится по СЫРОМУ файлу: он о том, что отдаёт сервер, а не что нарисовал JS.
    const raw = рвHtml(slug);
    if (raw === null) {
      check(slug, 'собранный файл существует', false, `build/ru/dimension/${slug}.html`);
      continue;
    }
    const телоБезСкриптов = raw.replace(/<script[\s\S]*?<\/script>/gi, '');
    const видимыйТекст = телоБезСкриптов.replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim();
    check(slug, '9. содержание есть в сыром HTML (без JS)', видимыйТекст.length > 600,
      `${видимыйТекст.length} знаков`);
    check(slug, '9б. страница не просит ни одного JS-модуля', !/_app\/immutable\/[a-z]+\/[\w.-]+\.js/.test(raw));

    for (const theme of ['light', 'dark']) {
      for (const width of [390, 1440]) {
        const ctx = await browser.newContext({ viewport: { width, height: 900 }, locale: 'ru-RU' });
        await ctx.addInitScript((t) => localStorage.setItem('ndim-theme', t), theme);
        const ошибкиКонсоли = [];
        const p = await ctx.newPage();
        p.on('console', (m) => { if (m.type() === 'error') ошибкиКонсоли.push(m.text()); });
        p.on('pageerror', (e) => ошибкиКонсоли.push(String(e)));

        await p.goto(`${BASE}/ru/dimension/${slug}`, { waitUntil: 'load' });
        const метка = `${slug}-${theme}-${width}`;

        // Тема ДЕЙСТВИТЕЛЬНО применена — иначе «обе темы» проверялись бы формально.
        const применена = await p.evaluate(() => document.documentElement.dataset.theme ?? '(нет)');
        check(метка, 'тема применена', применена === theme, `получено «${применена}»`);

        const данные = await p.evaluate(() => {
          const t = document.body.innerText;
          const h1 = document.querySelector('h1');
          const st = h1 ? getComputedStyle(h1) : null;
          return {
            текст: t,
            заголовок: h1 ? h1.innerText.trim() : '',
            обрезка: st
              ? st.textOverflow === 'ellipsis' || st.whiteSpace === 'nowrap' || st.webkitLineClamp !== 'none'
              : false,
            заголовокВысота: h1 ? Math.round(h1.getBoundingClientRect().height) : 0,
            /*
             * 🔴 ДОПУСК — ПОЛСТРОКИ, А НЕ ПИКСЕЛЬ, И ЭТО ПРАВКА ПО СОБСТВЕННОМУ ЛОЖНОМУ КРАСНОМУ.
             *
             * Первая редакция сравнивала `scrollHeight > clientHeight + 1` и покраснела на ВСЕХ
             * СОРОКА конфигурациях разом. Замер показал, чего это стоило: у заголовка
             * `line-height: 37.76px`, браузер округляет `clientHeight` до 38, а `scrollHeight`
             * отдаёт 40 — разница в два пикселя есть арифметика округления дробной строки, и
             * никакой обрезки за ней нет (`text-overflow: clip`, `white-space: normal`,
             * `-webkit-line-clamp: none` — проверено на живой странице).
             *
             * 🔑 Одинаковый провал на ВСЕХ конфигурациях — подпись сломанного прибора, а не
             * продукта: настоящий дефект так ровно не ложится. Настоящая обрезка теряет ЦЕЛУЮ
             * СТРОКУ, поэтому и допуск взят долей строки, а не пикселем.
             */
            заголовокСрезан: (() => {
              if (!h1 || !st) return false;
              const строка = parseFloat(st.lineHeight) || parseFloat(st.fontSize) || 16;
              return h1.scrollHeight > h1.clientHeight + строка / 2;
            })(),
            /*
             * Сколько строк занимает название. Нужно НЕ для вердикта, а для честности зелёного:
             * на ОДНОСТРОЧНОМ названии проверка «не обрезано» бессодержательна — обрезать нечего,
             * и она зелена при любом коде (класс `EXP-0070`). Мутационная проба это поймала:
             * первый опыт ставился на однострочном «Пуаро» и не покраснел даже под настоящим
             * `-webkit-line-clamp: 1`. Итог печатает, на скольких конфигурациях проверке было
             * что судить.
             */
            строкЗаголовка: (() => {
              if (!h1 || !st) return 0;
              const строка = parseFloat(st.lineHeight) || parseFloat(st.fontSize) || 16;
              return Math.max(1, Math.round(h1.clientHeight / строка));
            })(),
            переполнение: document.documentElement.scrollWidth > document.documentElement.clientWidth + 1,
            ширинаОкна: document.documentElement.clientWidth,
            ширинаДока: document.documentElement.scrollWidth,
          };
        });

        check(метка, '1. название видно', данные.заголовок.length > 0, данные.заголовок.slice(0, 40));
        check(метка, '1б. название НЕ обрезано', !данные.обрезка && !данные.заголовокСрезан);
        if (данные.строкЗаголовка > 1) многострочных += 1;
        check(метка, '2. описание содержательно', данные.текст.length > 500, `${данные.текст.length} знаков`);

        // 3 · 4 — канон-имя и блок-дверь владельца.
        check(метка, '3. NDSR подписан полным именем', данные.текст.includes('NDim Space Rating'));
        /*
         * Тексты двери сверяются ДОСЛОВНО с каноном владельца (интервью №036 В3 = C, его рука).
         * Первая редакция искала `/Оцените .* чтобы найти людей/` и краснела всюду: у владельца
         * после «Оцените» стоит ЗАПЯТАЯ, а не пробел, и образец не совпадал ни разу. Свободный
         * образец по канон-тексту — приглашение к такой ошибке; здесь сверяется строка.
         */
        check(метка, '4. заголовок блока-двери — канон владельца',
          данные.текст.includes('NDim Space Rating — уникальная система рейтинга Пространства NDim Space'));
        check(метка, '4а. кнопка двери — канон владельца',
          данные.текст.includes('Оцените, чтобы найти людей, кто думает, как Вы'));
        if (rates === 0) {
          check(метка, '4б. состояние «оценок нет» честное', /Ваша оценка будет первой/i.test(данные.текст));
        } else {
          check(метка, '4б. состояние «оценки есть» честное', /Ваш голос отображается/i.test(данные.текст));
        }

        // 6 · 7 — боевые инварианты. Судим ОТРИСОВАННЫЙ текст: сюда смотрит человек.
        check(метка, '6. нет «Рядом в Пространстве»', !/Рядом в Пространстве/i.test(данные.текст));
        /*
         * ⚠️ `[\p{L}]*` с флагом `u`, а НЕ `\w*` — и это правка по собственному ложному зелёному.
         * Первая редакция писала `/похожест\w*\s*[:—-]?\s*\d/i`. В JavaScript `\w` определён
         * через ASCII, и флаг `u` этого не чинит: после кириллического корня образец не мог
         * совпасть НИ РАЗУ, то есть боевой инвариант «цифр похожести наружу не даём» стерегла
         * проверка, которая была мертва на всех сорока конфигурациях и печатала ✅.
         * Поймал не глаз, а `tools/verify-cyrillic-word-boundary.mjs` — страж ровно этого класса.
         */
        check(метка, '6б. нет чисел похожести', !/похожест[\p{L}]*\s*[:—-]?\s*\d/iu.test(данные.текст));
        check(метка, '7. нет ПДн', !/@[\w.-]+\.\w{2,}|\/points\//.test(данные.текст));

        check(метка, '8. консоль чиста', ошибкиКонсоли.length === 0, ошибкиКонсоли.slice(0, 2).join(' · '));
        check(метка, '10. нет горизонтального переполнения', !данные.переполнение,
          `док ${данные.ширинаДока} против окна ${данные.ширинаОкна}`);

        await p.screenshot({ path: `${OUT}/${метка}.png`, fullPage: false });
        await ctx.close();
      }
    }
  }

  say('');
  say('═══ ИТОГ ═══');
  say(`проверок пройдено: ${passed} · провалов: ${failed}`);
  const всего = sample.length * 4;
  say(
    `из них проверке «название не обрезано» было ЧТО судить на ${многострочных} конфигурациях из ` +
      `${всего}: на однострочном названии обрезать нечего, и её зелёный там ничего не доказывает ` +
      '(класс EXP-0070 — названо, а не замолчано).',
  );
  if (провалы.length) {
    say('');
    say('провалы поимённо:');
    for (const п of провалы) say(`  ❌ ${п}`);
  }
  say('');
  say(`кадров снято: ${sample.length * 4} (10 страниц × 2 темы × 390/1440) — в ${OUT}/`);
  say('⚠️ Кадры обязан посмотреть ЧЕЛОВЕК: прибор судит наличие и целость, вкус — не его дело.');
} finally {
  await browser.close();
  await writeFile(`${OUT}/report.txt`, lines.join('\n'), 'utf8');
  console.log(`\nотчёт: ${OUT}/report.txt`);
}

process.exit(failed ? 1 : 0);
