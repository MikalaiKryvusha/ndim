#!/usr/bin/env node
/**
 * СТРАЖ ЭКРАНА ВХОДА — исполняет критерии приёмки `plans/80` живым браузером, а не чтением кода.
 *
 * ПОВОД — `bugs/19`, слово владельца (волна 09): «Войдите в Пространство — должно быть отдельным
 * экраном… а не показываться внутри приложения». Жалоба ПРОВЕРЯЕМА: оболочка приложения либо
 * есть в разметке экрана, либо её нет. Плюс две правки вида, которые он назвал 2026-09-04:
 * «*кнопку гостя делаем яркой синей, как ещё одна основная*» и «*слово "или" заметнее*» — обе
 * тоже проверяемы вычисленным стилем, а не впечатлением.
 *
 * ⛔ ЧЕГО ПРИБОР НЕ ДЕЛАЕТ. Он не судит, КРАСИВ ли экран, и не заменяет глаз владельца: вкус
 * решает он (`AGENT_GUIDE.md` → «Дизайн»). Прибор стережёт ровно четыре факта, у каждого из
 * которых есть машинный ответ.
 *
 * @guard signin-screen
 * THREAT:         экран входа тихо возвращается внутрь оболочки приложения (табы, рельс, нижняя
 *                 панель) или гостевая дверь снова становится тихой ссылкой третьим планом —
 *                 то есть отменяется решение владельца, и отмена никем не замечается
 * PROVED-AGAINST: мутация каждого из четырёх фактов по очереди (`--selftest`): подсунутая
 *                 разметка с нижней панелью, с прозрачной гостевой кнопкой, с мелким «или» и с
 *                 чужим текстом кнопки — на каждой прибор обязан покраснеть ИМЕННО своим пунктом
 * GAP:            проверяет РАЗМЕТКУ И СТИЛЬ, но не поведение дверей: что Google действительно
 *                 логинит, а гостевая заводит анонимную сессию — предмет других стражей
 *                 (`verify-bug110`, смоук двери выката)
 * ON-REAL-PATH:   NOT YET — прибор рождён вместе с экраном 2026-09-04 и на стенде прогнан; в
 *                 ворота `npm run guards` встанет отдельным шагом, когда экран доедет до боя
 *
 * Запуск:  node tools/verify-signin-screen.mjs [адрес]     по умолчанию http://127.0.0.1:5173
 *          node tools/verify-signin-screen.mjs --selftest  самопроверка на подложных страницах
 * Коды:    0 — все четыре факта на месте; 1 — красный; 2 — стенд не отвечает.
 */

import { chromium } from 'playwright';
import { pathToFileURL } from 'node:url';

/* ── Работа только под ЗАПУСКОМ, не под импортом (класс EXP-0188, ideas/43). Без этого
   `import { судить }` из парного теста поднимал бы браузер и звал `process.exit`, убивая
   прогон после первого же случая — поймано собственным парным тестом в день рождения. ───── */
const ЗАПУЩЕН_НАПРЯМУЮ = Boolean(process.argv[1]) && import.meta.url === pathToFileURL(process.argv[1]).href;

const БАЗА = process.argv.find((a) => a.startsWith('http')) ?? 'http://127.0.0.1:5173';
/** Дверь стенда в состояние «не вошёл»: без неё стенд отдаёт dev-аккаунт (`src/lib/data/profile.ts`). */
const ПУТЬ = '/profile?as=none';

/**
 * Текст гостевой двери — ДОСЛОВНО слово владельца 2026-09-04, с ЕГО ЖЕ переносом от 2026-09-05
 * («*в кнопке входа в анонимный аккаунт нужно сделать принудительный перенос, чтобы "без
 * регистрации" было на новой строке*»). Сравнение побайтовое, перенос — часть строки.
 */
const ТЕКСТ_ГОСТЯ = 'Смотреть Пространство NDim Space гостем\nбез регистрации';

/** Стили, при которых браузер ПОКАЗЫВАЕТ перенос из строки, а не съедает его как пробел. */
const ПОКАЗЫВАЕТ_ПЕРЕНОС = new Set(['pre-line', 'pre-wrap', 'pre', 'break-spaces']);

/** Те же слова БЕЗ переноса — мутация самопроверки «перенос молча выпал». */
const плоскийТекстГостя = ТЕКСТ_ГОСТЯ.replace('\n', ' ');

/**
 * Снять со страницы ровно те факты, по которым судим. Возвращает плоский объект — его же
 * получают подложные страницы самопроверки, поэтому оценщик у боя и у самотеста ОДИН.
 */
export const СНЯТЬ = () => {
  const q = (s) => document.querySelector(s);
  const кнопки = [...document.querySelectorAll('button')];
  // Гостевую дверь берём ПО КРЮЧКУ `data-door="guest"`, а не по тексту: ровно на поиске по
  // тексту уже падал смоук двери выката, когда владелец текст переименовал. Текст остаётся
  // предметом суждения (К4), но НАЙТИ кнопку он больше не мешает.
  const гость = q('[data-door="guest"]') ?? кнопки.find((b) => /гостем/u.test(b.textContent));
  const google = кнопки.find((b) => b.textContent.includes('Google'));
  const sep = q('.signin-screen .sep');
  const cs = (e) => (e ? getComputedStyle(e) : null);
  return {
    экран: Boolean(q('.signin-screen')),
    нижняяПанель: Boolean(q('nav.bottom, .bottomnav, .bnav, [data-nav="bottom"]')),
    рельс: Boolean(q('.siderail, .rail')),
    табы: Boolean(q('.tabs, [role="tablist"]')),
    переключатели: document.querySelectorAll('.signin-screen .ctl button').length,
    текстГостя: гость ? гость.textContent.trim() : null,
    // Перенос живёт в ДВУХ местах сразу: символ в строке и стиль, который его не съедает.
    // Снимаем оба — иначе `white-space: normal` тихо схлопнул бы перенос в пробел, а строка
    // осталась бы «правильной», и прибор промолчал бы на ровно той правке, что владелец просил.
    пробелыГостя: гость ? cs(гость).whiteSpace : null,
    фонГостя: гость ? cs(гость).backgroundColor : null,
    фонGoogle: google ? cs(google).backgroundColor : null,
    илиКегль: sep ? parseFloat(cs(sep).fontSize) : null,
    илиВес: sep ? Number(cs(sep).fontWeight) : null,
    илиЦвет: sep ? cs(sep).color : null,
    цветТекста: cs(q('.signin-screen h1') ?? document.body).color,
  };
};

/** Прозрачный фон в любом его написании — «кнопка не покрашена». */
const прозрачный = (c) => !c || c === 'transparent' || /rgba\([^)]*,\s*0\s*\)$/.test(c);

/**
 * Судить снятые факты. Возвращает массив претензий; пустой массив = чисто.
 * Вынесено отдельно и ЭКСПОРТИРУЕТСЯ, потому что ровно этот оценщик гоняет самопроверка.
 */
export function судить(ф) {
  const беды = [];
  if (!ф.экран) беды.push('К1: экрана входа нет в разметке — селектор .signin-screen не найден');
  if (ф.нижняяПанель) беды.push('К1: на экране входа НИЖНЯЯ ПАНЕЛЬ приложения — ровно то, на что жаловался владелец (bugs/19)');
  if (ф.рельс) беды.push('К1: на экране входа БОКОВОЙ РЕЛЬС приложения (bugs/19)');
  if (ф.табы) беды.push('К1: на экране входа ТАБЫ профиля (bugs/19)');
  if (ф.переключатели < 3) беды.push(`К1: переключателей языка и темы ${ф.переключатели}, ожидалось 3 (RU · EN · тема) — вторая половина bugs/19`);

  // К4 разложен на ТРИ независимые претензии: слова · перенос в строке · стиль, который его
  // показывает. Иначе пропавший перенос красил бы тем же красным, что чужой текст, и следующий
  // читал бы «текст не тот» там, где слова целы.
  const плоско = (t) => (t ?? '').replace(/\s+/gu, ' ').trim();
  if (плоско(ф.текстГостя) !== плоско(ТЕКСТ_ГОСТЯ)) {
    беды.push(`К4: текст гостевой двери не тот. Ожидалось «${плоско(ТЕКСТ_ГОСТЯ)}», получено «${плоско(ф.текстГостя) || '—'}»`);
  } else if (!/гостем\s*\n\s*без регистрации/u.test(ф.текстГостя ?? '')) {
    беды.push('К4: в гостевой двери ПРОПАЛ принудительный перенос — «без регистрации» обязано стоять новой строкой (слово владельца 2026-09-05)');
  } else if (ф.пробелыГостя && !ПОКАЗЫВАЕТ_ПЕРЕНОС.has(ф.пробелыГостя)) {
    беды.push(`К4: перенос в строке есть, но стиль его СЪЕДАЕТ: white-space: ${ф.пробелыГостя} — нужен pre-line (слово владельца 2026-09-05)`);
  }
  if (прозрачный(ф.фонГостя)) беды.push('К2: гостевая дверь ПРОЗРАЧНАЯ — она снова тихая, а владелец велел «яркой синей, как ещё одна основная»');
  else if (ф.фонГостя !== ф.фонGoogle) беды.push(`К2: гостевая дверь ${ф.фонГостя} против основной ${ф.фонGoogle} — веса разошлись`);

  if (!(ф.илиКегль >= 14)) беды.push(`К3: «или» кеглем ${ф.илиКегль ?? '—'}px, ожидалось 14 и больше`);
  if (!(ф.илиВес >= 700)) беды.push(`К3: «или» весом ${ф.илиВес ?? '—'}, ожидалось 700 и больше`);
  if (ф.илиЦвет && ф.цветТекста && ф.илиЦвет !== ф.цветТекста) {
    беды.push(`К3: «или» цветом ${ф.илиЦвет} против основного текста ${ф.цветТекста} — снова приглушено`);
  }
  return беды;
}

// ── самопроверка: каждая мутация обязана краснить ИМЕННО своим пунктом ───────────────────────
if (ЗАПУЩЕН_НАПРЯМУЮ && process.argv.includes('--selftest')) {
  const здоровый = {
    экран: true, нижняяПанель: false, рельс: false, табы: false, переключатели: 3,
    текстГостя: ТЕКСТ_ГОСТЯ, пробелыГостя: 'pre-line',
    фонГостя: 'rgb(20, 103, 214)', фонGoogle: 'rgb(20, 103, 214)',
    илиКегль: 14, илиВес: 700, илиЦвет: 'rgb(27, 26, 23)', цветТекста: 'rgb(27, 26, 23)',
  };
  const случаи = [
    ['чистый экран молчит', здоровый, null],
    ['вернулась нижняя панель', { ...здоровый, нижняяПанель: true }, /НИЖНЯЯ ПАНЕЛЬ/u],
    ['вернулся рельс', { ...здоровый, рельс: true }, /РЕЛЬС/u],
    ['вернулись табы', { ...здоровый, табы: true }, /ТАБЫ/u],
    ['пропал переключатель темы', { ...здоровый, переключатели: 2 }, /переключателей/u],
    ['гостевая снова прозрачная', { ...здоровый, фонГостя: 'rgba(0, 0, 0, 0)' }, /ПРОЗРАЧНАЯ/u],
    ['гостевая другого цвета', { ...здоровый, фонГостя: 'rgb(255, 255, 255)' }, /веса разошлись/u],
    ['«или» измельчало', { ...здоровый, илиКегль: 12 }, /кеглем 12/u],
    ['«или» похудело', { ...здоровый, илиВес: 500 }, /весом 500/u],
    ['«или» приглушили', { ...здоровый, илиЦвет: 'rgb(150, 150, 150)' }, /снова приглушено/u],
    ['текст кнопки подменили', { ...здоровый, текстГостя: 'Осмотреться гостем' }, /не тот/u],
    ['перенос выпал из строки', { ...здоровый, текстГостя: плоскийТекстГостя }, /ПРОПАЛ принудительный перенос/u],
    ['перенос съеден стилем', { ...здоровый, пробелыГостя: 'normal' }, /СЪЕДАЕТ/u],
    ['экран исчез совсем', { ...здоровый, экран: false }, /экрана входа нет/u],
  ];
  let плохо = 0;
  for (const [имя, факты, ждём] of случаи) {
    const беды = судить(факты);
    if (ждём === null) {
      if (беды.length === 0) console.log(`  ✓ ${имя}`);
      else { console.error(`  ✖ ${имя}: ${беды.join(' · ')}`); плохо++; }
    } else if (беды.length === 1 && ждём.test(беды[0])) {
      console.log(`  ✓ ${имя} — краснеет ровно своим пунктом`);
    } else {
      console.error(`  ✖ ${имя}: получено ${беды.length} претензий: ${беды.join(' · ') || '—'}`);
      плохо++;
    }
  }
  if (плохо) { console.error(`\n✖ самопроверка провалена: ${плохо}`); process.exit(1); }
  console.log(`\n✅ самопроверка стража экрана входа пройдена — ${случаи.length} случаев`);
  process.exit(0);
}

// ── боевой прогон ────────────────────────────────────────────────────────────────────────────
if (ЗАПУЩЕН_НАПРЯМУЮ) {
const адрес = БАЗА.replace(/\/$/, '') + ПУТЬ;
const браузер = await chromium.launch();
let код = 0;
try {
  const ctx = await браузер.newContext({ viewport: { width: 390, height: 844 } });
  const page = await ctx.newPage();
  const ошибки = [];
  page.on('pageerror', (e) => ошибки.push(String(e)));
  page.on('console', (m) => { if (m.type() === 'error') ошибки.push(m.text()); });

  try {
    await page.goto(адрес, { waitUntil: 'domcontentloaded', timeout: 30_000 });
    await page.waitForSelector('.signin-screen', { timeout: 25_000 });
  } catch (err) {
    console.error(`✖ экран входа не поднялся на ${адрес}: ${err.message}`);
    console.error('  Стенд запущен? `npm run stand`. Дверь «не вошёл» — это ?as=none.');
    await браузер.close();
    process.exit(2);
  }
  await page.waitForTimeout(600);

  const факты = await page.evaluate(СНЯТЬ);
  const беды = судить(факты);

  if (беды.length) {
    console.error(`✖ экран входа разошёлся с решениями владельца (${адрес}):`);
    for (const b of беды) console.error('  · ' + b);
    код = 1;
  } else {
    console.log(`✅ экран входа в порядке: оболочки нет · переключателей ${факты.переключатели} · ` +
      `гость и Google одного фона ${факты.фонГостя} · «или» ${факты.илиКегль}px/${факты.илиВес} · текст кнопки дословный`);
  }
  if (ошибки.length) {
    console.error(`✖ консоль не чиста: ${ошибки.length}`);
    for (const e of ошибки.slice(0, 5)) console.error('  · ' + e.slice(0, 160));
    код = 1;
  }
} finally {
  await браузер.close();
}
process.exit(код);
}
