function собрать(каталог, накопитель = []) {
  let записи;
  try {
    записи = readdirSync(каталог, { withFileTypes: true });
  } catch {
    return накопитель; // каталога может не быть — это не находка стража
  }
  for (const з of записи) {
    const путь = join(каталог, з.name);
    if (з.isDirectory()) {
      if (з.name === 'node_modules') continue;
      собрать(путь, накопитель);
    } else if (з.name.endsWith('.mjs')) {
      // Косые вперёд ВСЕГДА: путь попадает и в вывод, и в сверку с реестром, а `join` на Windows
      // отдаёт обратные — реестр перестал бы совпадать ровно на той машине, где всё и работает.
      накопитель.push(путь.split('\\').join('/'));
    }
  }
  return накопитель;
}

function суд() {
  const файлы = КАТАЛОГИ.flatMap((к) => собрать(к));
  const красные = [];
  const непрочитанные = [];
  let сЭкспортом = 0;
  let сПредохранителем = 0;

  for (const файл of файлы) {
    let вердикт;
    try {
      вердикт = судить(readFileSync(файл, 'utf8'));
    } catch (беда) {
      // Неразобранный файл — НЕ зелёный: страж о нём ничего не знает и обязан это сказать.
      непрочитанные.push({ файл, почему: беда.message });
      continue;
    }
    if (вердикт.экспорт) сЭкспортом++;
    if (вердикт.предохранитель) сПредохранителем++;
    if (красный(вердикт)) красные.push({ файл, вердикт });
  }

  const реестр = судитьРеестр({
    реестр: РЕЕСТР,
    красные: new Set(красные.map((к) => к.файл)),
    существующие: new Set(файлы),
  });

  return { всего: файлы.length, сЭкспортом, сПредохранителем, красные, непрочитанные, реестр };
}

function печать(итог) {
  // К4 `ideas/43`: страж не вакуумен — он печатает, сколько наблюдений сделал.
  console.log(`осмотрено файлов .mjs: ${итог.всего} (${КАТАЛОГИ.join(', ')})`);
  console.log(`из них с экспортом: ${итог.сЭкспортом} · с предохранителем: ${итог.сПредохранителем}`);

  const { покрытые, непокрытые, протухшие } = итог.реестр;
  console.log(`реестр: исключений и отсрочек ${РЕЕСТР.length}, из них в силе ${покрытые.length}`);
  // Покрытое печатается ПОИМЁННО: молчаливое исключение неотличимо от забытого.
  for (const файл of покрытые) {
    const строка = РЕЕСТР.find((с) => с.файл === файл);
    console.log(`   ⏸️ ${файл} — ${строка.вид}${строка.вид === 'отсрочка' ? ` до: ${строка.до} (с ${строка.с})` : ''}`);
    console.log(`      причина: ${строка.причина}`);
  }

  for (const { файл, почему } of итог.непрочитанные) {
    console.error(`⛔ не разобран: ${файл} — ${почему}`);
  }

  for (const { файл, почему } of протухшие) {
    console.error(`\n🔴 РЕЕСТР ПРОТУХ: ${файл}`);
    console.error(`   ${почему}`);
  }

  const кЛечению = итог.красные.filter((к) => непокрытые.includes(к.файл));
  for (const { файл, вердикт } of кЛечению) {
    console.error(`\n🔴 ${файл}`);
    console.error(вердикт.предохранитель
      ? '   предохранитель в файле ЕСТЬ, но работа стоит СНАРУЖИ него:'
      : '   экспорт есть, предохранителя нет; работа на верхнем уровне:');
    for (const { строка, вид } of вердикт.незакрытая) {
      console.error(`   · строка ${строка} — ${вид}`);
    }
  }

  if (кЛечению.length === 0 && протухшие.length === 0 && итог.непрочитанные.length === 0) {
    console.log(`✅ незакрытой работы нет: ${итог.красные.length} под реестром, остальное чисто`);
    return 0;
  }

  if (кЛечению.length) {
    console.error(`\n❌ приборов с незакрытой работой: ${кЛечению.length}`);
    console.error('   Лечение: `const ЗАПУЩЕН_НАПРЯМУЮ = Boolean(process.argv[1]) && import.meta.url === pathToFileURL(process.argv[1]).href;`');
    console.error('   и вся работа верхнего уровня — внутрь `if (ЗАПУЩЕН_НАПРЯМУЮ) main();`. Образец: tools/team-status.mjs');
  }
  if (протухшие.length) {
    console.error(`\n❌ протухших строк реестра: ${протухшие.length} — снять их в tools/verify-import-safety.mjs`);
  }
  return 1;
}

