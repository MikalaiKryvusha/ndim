function selftest() {
  let провалов = 0;
  for (const [имя, исходник, ждём] of ФИКСТУРЫ) {
    let ok;
    try {
      ok = красный(судить(исходник)) === ждём;
    } catch {
      ok = false;
    }
    console.log(`${ok ? '✅' : '❌'} ${имя}`);
    if (!ok) провалов++;
  }
  console.log(провалов ? `\n❌ провалов: ${провалов}` : `\n✅ самопроверка чиста: ${ФИКСТУРЫ.length}/${ФИКСТУРЫ.length}`);
  return провалов ? 1 : 0;
}

