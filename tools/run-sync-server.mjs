import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { CONTOURS } from './lib/contours.mjs';
import { serviceAccount } from './lib/credentials.mjs';
import { loadEnv } from './lib/env.mjs';

/** Имя переменной ключа для каждого контура — то же соглашение, что в `lib/credentials.mjs`. */
const ПЕРЕМЕННАЯ_КЛЮЧА = { prod: 'NDIM_PROD_SA_B64', stage: 'NDIM_STAGE_SA_B64' };

/** Ключи, которым в окружении сервера синхронизации делать нечего ни при каком контуре. */
const ПОСТОРОННИЕ_КЛЮЧИ = ['NDIM_CONSOLE_SA_B64'];

const довод = (имя, умолчание = null) => {
	const i = process.argv.indexOf(имя);
	return i === -1 ? умолчание : process.argv[i + 1];
};

/**
 * Требуемая версия Node — из `engines.node` самого сервера синхронизации, а не из этого файла.
 * Там она объявлена, там и живёт: вторая копия числа разъехалась бы при первом же поднятии планки.
 */
function требуемыйNode(кореньВхода) {
	try {
		const манифест = JSON.parse(readFileSync(resolve(кореньВхода, 'sync-server', 'package.json'), 'utf8'));
		const выражение = манифест.engines?.node ?? null;
		// Форма в проекте одна — «>=23.6». Разбирать весь язык semver ради неё было бы Оккамом наоборот.
		const найдено = выражение?.match(/(\d+)\.(\d+)(?:\.(\d+))?/);
		return найдено ? { выражение, части: [Number(найдено[1]), Number(найдено[2]), Number(найдено[3] ?? 0)] } : null;
	} catch {
		return null;
	}
}

/** Сравнение «мажор.минор.патч» по числам: строковое сравнение считает 9 больше 23. */
function версияНеНиже(версия, требование) {
	const свои = версия.split('.').map(Number);
	for (let i = 0; i < 3; i += 1) {
		const своё = свои[i] ?? 0;
		const надо = требование.части[i] ?? 0;
		if (своё !== надо) return своё > надо;
	}
	return true;
}

/** Номер сборки и момент кода — из git рабочей копии, откуда взят вход. */
function отметкиКода(каталог) {
	const git = (...доводы) => execFileSync('git', ['-C', каталог, ...доводы], { encoding: 'utf8' }).trim();
	try {
		return {
			build: git('rev-list', '--count', 'HEAD', '--', 'sync-server', 'calculator'),
			builtAt: git('log', '-1', '--format=%cI', 'HEAD'),
			commit: git('rev-parse', '--short', 'HEAD'),
		};
	} catch (ошибка) {
		// Отсутствующее честнее выдуманного (PHILOSOPHY): без git экран покажет версию без скобок.
		console.warn(`[запуск] git недоступен в ${каталог} (${ошибка.message.split('\n')[0]}) — номер сборки не подаётся`);
		return { build: null, builtAt: null, commit: null };
	}
}

async function запустить() {
	const контур = довод('--contour');
	if (!контур || !CONTOURS[контур]) {
		console.error(
			`[запуск] СТОП: контур не назван или неизвестен («${контур ?? ''}»). ` +
				`Ожидались: ${Object.keys(CONTOURS).join(' · ')}.\n` +
				'Умолчания здесь нет намеренно: боевым ключом можно перезаписать топы живых людей.',
		);
		process.exit(2);
	}

	const свой = resolve(dirname(fileURLToPath(import.meta.url)), '..', 'sync-server', 'index.mjs');
	const вход = resolve(довод('--entry', свой));
	const кореньВхода = resolve(dirname(вход), '..');

	// Замороженной копии может не оказаться (перенесли, удалили, не создали на новой машине).
	// Без этой проверки PM2 крутил бы петлю перезапусков с невнятной ошибкой модуля.
	if (!existsSync(вход)) {
		console.error(
			`[запуск] СТОП: входа нет — ${вход}\n` +
				'Боевая копия создаётся замороженной на коммите:\n' +
				'  git worktree add --detach D:/work/ai_sandbox/ndim-server-prod <коммит>\n' +
				'  npm install --omit=dev  (в её sync-server)',
		);
		process.exit(2);
	}

	// 🔴 ВЕРСИЯ NODE — ПРОВЕРЯЕТСЯ, А НЕ ПРЕДПОЛАГАЕТСЯ. `index.mjs` импортирует ядро похожести
	// ИСХОДНИКОМ (`../src/lib/similarity/similarity.ts`): TypeScript исполняет сам Node, сборки
	// нет. Значит слишком старый Node роняет службу на первом же импорте.
	// Замер 2026-09-08: PM2 стоит под nvm и запускал v22.6.0, тогда как `engines` требует ≥ 23.6.
	// Требование берётся из `sync-server/package.json` — там оно и объявлено, второй копии не заводим.
	const требование = требуемыйNode(кореньВхода);
	if (требование && !версияНеНиже(process.versions.node, требование)) {
		console.error(
			`[запуск] СТОП: Node ${process.versions.node}, а сервер синхронизации требует ${требование.выражение}.\n` +
				`Он импортирует TypeScript исходником — старый Node упадёт на первом импорте.\n` +
				`Этот Node: ${process.execPath}\n` +
				'Под PM2 версия задаётся полем `interpreter` в sync-server/ecosystem.config.cjs.',
		);
		process.exit(2);
	}

	loadEnv();

	// Сверка «ключ того контура, за который себя выдаёт» — падает громко и с адресом лечения.
	serviceAccount(контур);

	process.env.NDIM_SA_B64 = process.env[ПЕРЕМЕННАЯ_КЛЮЧА[контур]];

	// 🔴 Чужие ключи — вон из окружения. Смешение контуров запрещено `plans/53`.
	const убрано = [];
	for (const [имя, переменная] of Object.entries(ПЕРЕМЕННАЯ_КЛЮЧА)) {
		if (имя !== контур && process.env[переменная]) {
			delete process.env[переменная];
			убрано.push(переменная);
		}
	}
	for (const переменная of ПОСТОРОННИЕ_КЛЮЧИ) {
		if (process.env[переменная]) {
			delete process.env[переменная];
			убрано.push(переменная);
		}
	}

	const описание = CONTOURS[контур];
	process.env.FIREBASE_PROJECT_ID = описание.project;
	process.env.FIRESTORE_DATABASE_ID = описание.database;

	const отметки = отметкиКода(кореньВхода);
	if (отметки.build) process.env.SYNC_BUILD = отметки.build;
	if (отметки.builtAt) process.env.SYNC_BUILT_AT = отметки.builtAt;

	// Одна строка, отвечающая на вопрос «что сейчас работает» без археологии по логам.
	console.log(
		`[запуск] контур ${описание.title} · проект ${описание.project} · база ${описание.database}\n` +
			`[запуск] код: ${вход}\n` +
			`[запуск] коммит ${отметки.commit ?? 'неизвестен'} · сборка ${отметки.build ?? '—'} · от ${отметки.builtAt ?? '—'}\n` +
			`[запуск] убраны из окружения чужие ключи: ${убрано.length ? убрано.join(', ') : 'нечего убирать'}`,
	);

	// 🔑 ПОЧЕМУ ПОДМЕНЯЕТСЯ `argv[1]`, А НЕ ПОРОЖДАЕТСЯ ДОЧЕРНИЙ ПРОЦЕСС.
	// У `sync-server/index.mjs` СВОЙ входной предохранитель: он сверяет `import.meta.url` с
	// `process.argv[1]` и при импорте считает, что его не запускали, — первый заход поднял прибор
	// молча и без единого такта (замер: сердцебиение не сдвинулось). Запускаемая программа теперь
	// и есть вход, поэтому argv[1] обязан называть его.
	//
	// Дочерний процесс решил бы то же, но ценой второго Node в памяти — на машине, которую
	// владелец вернул в состояние игрового ПК, это не мелочь. И главное: при дочернем запуске
	// окружение с ключом пришлось бы отдавать PM2, а `pm2 save` кладёт окружение в свой файл
	// дампа — то есть боевой ключ лёг бы на диск. Правило владельца 2026-08-15: «никогда ключи в
	// коде и других файлах не храним». Здесь ключ живёт только в памяти процесса.
	process.argv[1] = вход;
	await import(pathToFileURL(вход).href);
}

// ⚠️ ВХОДНОГО ПРЕДОХРАНИТЕЛЯ ЗДЕСЬ НЕТ, И ЭТО НЕ НЕДОСМОТР.
// Файл ничего не экспортирует — защищать нечего, импортировать его незачем. А привычная форма
// предохранителя (`process.argv[1] === import.meta.url`) здесь ВРЕДНА: PM2 в режиме fork
// запускает не сам скрипт, а свою обёртку `ProcessContainerFork.js`, и argv[1] называет ЕЁ.
// Замер 2026-09-08: служба висела «online» три минуты, не написав ни строки и не сделав ни
// одного такта, — предохранитель молча не пускал её работать. Класс тот же, что у `ideas/43`,
// только вывернутый наизнанку.
await запустить();
