#!/usr/bin/env node
/**
 * МЕТКА СБОРКИ — из КАКОГО дерева собран артефакт `build/`.
 *
 * Ворота: нет — это шаг сборки, а не страж. Судит метку `tools/lib/build-freshness.mjs`.
 * Запуск: автоматически из `postbuild` (`npm run build`) · руками: `node tools/stamp-build.mjs`
 *
 * ═══ ЗАЧЕМ, ЕСЛИ У СБОРКИ УЖЕ ЕСТЬ НОМЕР ═══
 *
 * У продукта есть `__APP_BUILD__` — ЧИСЛО КОММИТОВ (`git rev-list --count HEAD`, `vite.config.ts`),
 * и это правильная величина для витрины: монотонная, растущая, не требующая хука. Но она НЕ
 * отвечает на вопрос «из какого дерева собрано»: `git commit --amend` её не меняет, переключение
 * на ветку той же длины — тоже. Два разных дерева дают один номер.
 * ⛔ Поэтому здесь НЕ заводится вторая система версий, и номер отсюда не берётся: метка несёт
 * `sha`, которого у номера нет, и ССЫЛАЕТСЯ на существующий номер, а не дублирует его.
 *
 * ═══ ЧТО ЭТО ЗАКРЫВАЕТ ═══
 *
 * Остаток класса, названный мной при сдаче контроля свежести и НЕ выданный тогда за сделанный:
 * **«свежа ПО ВРЕМЕНИ» ≠ «собрана из ЭТОГО дерева».** Время ловит забытую пересборку; sha ловит
 * переключённую ветку, откат и `amend` — случаи, где время как раз в порядке.
 * Повод у класса живой: 2026-08-30 страж хабов дал ЛОЖНОЕ КРАСНОЕ на позавчерашней сборке, и его
 * строки читались как находки про свежую порцию.
 *
 * ⚠️ **МЕТКА УЕЗЖАЕТ В БОЙ ВМЕСТЕ С АРТЕФАКТОМ И БУДЕТ ПУБЛИЧНА** (`/build-stamp.json`). Названо
 * вслух, а не проведено молча: репозиторий проекта ПУБЛИЧЕН (`github.com/MikalaiKryvusha/ndim`),
 * поэтому `sha` не раскрывает ничего закрытого, а номер сборки и так уже виден в продукте на
 * экране «Меню». Взамен появляется настоящая польза: по боевому адресу становится проверяемым,
 * ЧТО именно выкачено, — сегодня это знание живёт только в чате выката.
 * 🔑 Если владелец решит иначе — метку убирать не из кода, а из состава выката; судья свежести
 * переживёт её отсутствие и честно скажет «метки нет».
 */
import { execSync } from 'node:child_process';
import { writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

/** Имя файла метки — одно на проект; его же знает судья свежести. */
export const ИМЯ_МЕТКИ = 'build-stamp.json';

/**
 * Спросить git. Недоступен (сборка из архива без `.git`) — честный `null`, а не выдуманное
 * значение: выдуманное хуже отсутствующего (`PHILOSOPHY.md` → три двери).
 */
const git = (cmd) => {
  try {
    return execSync(cmd, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
  } catch {
    return null;
  }
};

/** Содержимое метки. Отдельной функцией — её судит юнит, не трогая диск. */
export function метка(now = new Date()) {
  const sha = git('git rev-parse HEAD');
  const статус = git('git status --porcelain');
  return {
    sha,
    /*
     * 🔴 ГРЯЗНОЕ ДЕРЕВО НАЗЫВАЕТСЯ ЧЕСТНО. Сборка из дерева с незакоммиченными правками
     * НЕ ОПИСЫВАЕТСЯ своим `sha`: код, которого нет в коммите, по определению не тот, на который
     * указывает метка. Признак стоит рядом с `sha`, чтобы читатель не принял одно за другое —
     * тот же приём, что у расписки стейджа (`.kaif/stage-receipt.json`).
     */
    dirty: статус === null ? null : статус !== '',
    builtAt: now.toISOString(),
    // Ссылка на существующую величину, а не её копия: сверять эти два числа между собой не надо.
    buildNumber: Number(git('git rev-list --count HEAD')) || 0,
  };
}

function main() {
  const dir = process.argv[2] ?? 'build';
  if (!existsSync(dir)) {
    console.error(`⛔ нет каталога «${dir}» — метку класть некуда; сначала сборка`);
    process.exit(1);
  }
  const m = метка();
  writeFileSync(join(dir, ИМЯ_МЕТКИ), `${JSON.stringify(m, null, 2)}\n`, 'utf8');
  const где = m.sha ? m.sha.slice(0, 7) : '— git недоступен —';
  console.log(`🏷  метка сборки: ${где}${m.dirty ? ' · 🔴 ДЕРЕВО ГРЯЗНОЕ' : ''} · сборка ${m.buildNumber}`);
}

// Предохранитель: прибор работает под ЗАПУСКОМ, а не под импортом — его метку судит юнит,
// и импорт, пишущий в `build/`, испортил бы предмет проверки (`tools/verify-import-safety.mjs`).
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
