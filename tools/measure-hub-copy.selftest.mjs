/**
 * САМОТЕСТ ПРИБОРА `measure-hub-copy.mjs` — доказывает, что он мерит ДЕРЕВО, В КОТОРОМ ЛЕЖИТ.
 *
 * Запуск: node tools/measure-hub-copy.selftest.mjs (либо node tools/measure-hub-copy.mjs --selftest)
 * Ворота: ДА — `npm run test:tools` через обёртку `tools/measure-hub-copy.test.mjs`.
 * Код возврата: 0 — все контроли сошлись · 1 — хотя бы один разошёлся.
 *
 * ═══ ЧТО ИМЕННО ОН СТЕРЕЖЁТ ═══
 *
 * Класс `EXP-0269` — **СТАБИЛЬНОСТЬ КАК ПРИЗНАК СЛЕПОТЫ**. Прибор с зашитым абсолютным путём
 * отвечает ОДИНАКОВО ОТКУДА УГОДНО, и его ответ выглядит тем надёжнее, чем он слепее: признак
 * «числа не меняются между рабочими местами» читается как устойчивость прибора, а означает, что
 * прибор не смотрит на дерево вовсе. Прежняя, скретчпадная редакция этого самого прибора,
 * положенная в поддельное дерево на 7 записей, напечатала оттуда числа НАСТОЯЩЕГО дерева
 * (178 страниц) — без ошибки, без предупреждения, без намёка.
 *
 * ═══ ПОЧЕМУ КОНТРОЛЯ ДВА, А НЕ ОДИН — ЭТО НЕ ПЕДАНТИЗМ ═══
 *
 * Проверка «прибор напечатал правильное число в СВОЁМ дереве» бесполезна: правильный прибор и
 * слепой дают там ОДИНАКОВЫЙ ответ. Различает их только чужое дерево. Поэтому:
 *
 *   · КОНТРОЛЬ 1 (положительный) — настоящий прибор в песочнице А обязан увидеть А;
 *   · КОНТРОЛЬ 2 (отрицательный) — копия, ослеплённая на песочницу Б, обязана увидеть Б,
 *     СТОЯ В А. Это и есть живая мутация: она вшита в самотест, а не прожита руками один раз.
 *
 * ═══ 🔴 ПОЧЕМУ ПЕСОЧНИЦ ДВЕ, А НЕ ОДНА — ЭТО УСЛОВИЕ ВЕРДИКТА №37, И ОНО ПРАВИЛЬНОЕ ═══
 *
 * Первая редакция брала за «чужое дерево» НАСТОЯЩИЙ каталог проекта: ослеплённая копия должна
 * была увидеть 5125 записей `src/lib/content/dims-build.json`. Это стоило самотесту двух вещей
 * сразу, и обе назвал суд:
 *
 *  1. **Он не запускался в чистом клоне.** `dims-build.json` весит 17,5 МБ и лежит в
 *     `.gitignore` — на голом `actions/checkout` самотест падал сырым `ENOENT`. То есть в ворота
 *     он не мог встать в принципе, а `EXP-0269` при этом уже обещал «доказывает каждый прогон».
 *     Обещание без прогонов — ровно `EXP-0194` в собственном доме: проверка, не стоящая ни в
 *     одних воротах, не защищает, а ЖДЁТ, пока о ней вспомнят.
 *  2. **Его различение зависело от числа, которого я не контролирую.** Каталог растёт; в день,
 *     когда в нём стало бы ровно 7 записей, контроль 2 перестал бы различать что-либо. Щель я
 *     объявил сам, и суд подтвердил, что она деградирует в красный, а не в ложный зелёный, —
 *     но жить с ней незачем, когда лечение бесплатно.
 *
 * Обе беды снимает одна правка: **чужим деревом становится ВТОРАЯ ПЕСОЧНИЦА.** Настоящий каталог
 * самотесту не нужен ВООБЩЕ — предмет у него «на какое дерево прибор смотрит», а не «что там
 * лежит». Оба числа теперь мои, различие между ними утверждается В КОДЕ, и весь опыт герметичен:
 * ему хватает `node` и пустого клона.
 *
 * ⚠️ **МУТАЦИЯ ОБЯЗАНА ДОКАЗАТЬ, ЧТО ОНА ПРИМЕНИЛАСЬ** (`EXP-0249`: мутация без проверки
 * применения — это зелёное ни о чём). Ослепление делается заменой строки в исходнике; если
 * строка изменит форму, замена молча не сработает, «мутант» окажется здоровым и контроль 2
 * позеленеет, ничего не проверив. Поэтому подстановка сверяется на факт: текст обязан
 * ИЗМЕНИТЬСЯ, иначе самотест краснеет с прямым объяснением.
 *
 * ⚠️ ГРАНИЦА: самотест судит АДРЕСАЦИЮ прибора и ничего не говорит о верности его арифметики —
 * длины, ступени и лестница проверяются юнитом порции dev-1 на фикстуре, у которой предмет
 * постоянен. Здесь предмет — «на какое дерево прибор смотрит», и только он.
 */

import { execFileSync } from 'node:child_process';
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

/**
 * Записей в песочнице А — там, где ПРИБОР СТОИТ, и в песочнице Б — туда, куда СМОТРИТ
 * ослеплённая копия. Числа обязаны быть разными: на этом стоит всё различение, и потому
 * неравенство ниже проверяется отдельным контролем, а не подразумевается.
 */
const А_ЗАПИСЕЙ = 7;
const Б_ЗАПИСЕЙ = 13;

/** Строка, задающая корень. Её подменяет мутация — и обязана доказать, что подменила. */
const СТРОКА_КОРНЯ = "const КОРЕНЬ = new URL('../', import.meta.url);";

/** Заглушка `catalog-hub.ts`: ровно те четыре имени, которые прибор импортирует, и ничего сверх. */
const ЗАГЛУШКА = `
export interface CatalogItem { slug: string; kind: string; title: { ru: string; en: string }; rates?: number }
export const PER_PAGE = 60;
export const pageCount = (n: number): number => Math.max(1, Math.ceil(n / PER_PAGE));
export const slicePage = <T,>(list: readonly T[], page: number): T[] =>
  list.slice((page - 1) * PER_PAGE, page * PER_PAGE);
export function groupByKind(items: readonly CatalogItem[]) {
  const hubs = new Map<string, CatalogItem[]>();
  for (const d of items) {
    if (!hubs.has(d.kind)) hubs.set(d.kind, []);
    hubs.get(d.kind)!.push(d);
  }
  return { hubs };
}
export function placesIn(list: readonly CatalogItem[]) {
  const m = new Map<string, { place: number }>();
  list.forEach((d, i) => { if ((d.rates ?? 0) > 0) m.set(d.slug, { place: i + 1 }); });
  return m;
}
`;

/** Первая строка вывода прибора — «каталог: N записей …». Сколько записей он УВИДЕЛ. */
function увиденоЗаписей(вывод) {
  const m = /каталог:\s*(\d+)\s+записей/u.exec(вывод);
  if (!m) throw new Error(`прибор не напечатал строку «каталог: N записей». Вывод:\n${вывод}`);
  return Number(m[1]);
}

function прогон(путьКПрибору) {
  return execFileSync(process.execPath, [путьКПрибору], {
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  });
}

/**
 * Замер с УЛОВЛЕННОЙ бедой (замечание З2 вердикта №37). Раньше падение прибора или сорванный
 * разбор вывода летели наружу трассой Node, и красный самотест выглядел как поломка самотеста, а
 * не как найденный дефект. Теперь беда возвращается строкой и печатается тем же 🔴, что и любой
 * другой разошедшийся контроль: в воротах CI читать трассу некому.
 */
function померил(путьКПрибору) {
  try {
    return { ок: true, видел: увиденоЗаписей(прогон(путьКПрибору)) };
  } catch (e) {
    const текст = e?.stderr ? `${e.message}\n${e.stderr}` : e?.message || String(e);
    return { ок: false, беда: текст.split('\n').slice(0, 4).join(' / ') };
  }
}

/** Собрать поддельное дерево: форма настоящего, объём — заданный. */
function поддельноеДерево(гдеБаза, имя, записей) {
  const корень = mkdtempSync(join(гдеБаза, `${имя}-`));
  mkdirSync(join(корень, 'src/lib/content'), { recursive: true });
  mkdirSync(join(корень, 'tools'), { recursive: true });
  writeFileSync(join(корень, 'src/lib/content/catalog-hub.ts'), ЗАГЛУШКА, 'utf8');
  writeFileSync(
    join(корень, 'src/lib/content/dims-build.json'),
    JSON.stringify(
      Array.from({ length: записей }, (_, i) => ({
        slug: `${имя}-${i + 1}`,
        kind: 'movie',
        title: { ru: `Поддельный фильм ${i + 1}`, en: `Fake movie ${i + 1}` },
        rates: 0,
      })),
    ),
    'utf8',
  );
  return корень;
}

export function самотест() {
  const исходник = fileURLToPath(new URL('measure-hub-copy.mjs', import.meta.url));
  const база = mkdtempSync(join(tmpdir(), 'measure-hub-copy-selftest-'));
  let провалов = 0;
  const скажи = (ок, что, деталь) => {
    if (!ок) провалов += 1;
    console.log(`${ок ? '✅' : '🔴'} ${что}${деталь ? ` · ${деталь}` : ''}`);
  };

  try {
    // ── КОНТРОЛЬ 0: сами числа опыта обязаны различаться. Раньше это подразумевалось; теперь
    //    утверждается, потому что равенство превратило бы оба следующих контроля в зелёные ни о чём.
    скажи(
      А_ЗАПИСЕЙ !== Б_ЗАПИСЕЙ,
      'песочницы различимы по объёму материала',
      `А=${А_ЗАПИСЕЙ}, Б=${Б_ЗАПИСЕЙ}`,
    );
    if (А_ЗАПИСЕЙ === Б_ЗАПИСЕЙ) {
      console.log('   ⛔ дальше не идём: при равных объёмах различать нечего');
      return 1;
    }

    const песочницаА = поддельноеДерево(база, 'дерево-А', А_ЗАПИСЕЙ);
    const песочницаБ = поддельноеДерево(база, 'дерево-Б', Б_ЗАПИСЕЙ);

    // ── КОНТРОЛЬ 1 (положительный): настоящий прибор обязан увидеть дерево, В КОТОРОМ СТОИТ.
    const целый = join(песочницаА, 'tools/measure-hub-copy.mjs');
    copyFileSync(исходник, целый);
    const ц = померил(целый);
    скажи(
      ц.ок && ц.видел === А_ЗАПИСЕЙ,
      'корень следует за файлом: прибор в песочнице А видит А',
      ц.ок ? `увидел ${ц.видел}, ждали ${А_ЗАПИСЕЙ}` : `прибор не отработал: ${ц.беда}`,
    );

    // ── МУТАЦИЯ: зашиваем корень в ЧУЖОЕ дерево — ровно та болезнь, что была у скретчпадной
    //    редакции (там это был абсолютный путь в мой worktree). Факт применения доказывается
    //    сравнением текста, а не надеждой на replace.
    const текст = readFileSync(исходник, 'utf8');
    const адресБ = JSON.stringify(pathToFileURL(join(песочницаБ, '/')).href);
    const слепойТекст = текст.replace(СТРОКА_КОРНЯ, `const КОРЕНЬ = new URL(${адресБ});`);
    скажи(
      слепойТекст !== текст,
      'мутация ПРИМЕНИЛАСЬ (строка корня найдена и заменена)',
      слепойТекст === текст ? `строка не найдена: ${СТРОКА_КОРНЯ}` : '',
    );
    if (слепойТекст === текст) {
      console.log('   ⛔ дальше не идём: непримененная мутация дала бы зелёный контроль 2 ни о чём');
      return 1;
    }

    // ── КОНТРОЛЬ 2 (отрицательный, живая мутация): ослеплённая копия обязана увидеть Б, СТОЯ В А.
    //    Если она вдруг увидит А — различать нечего, и весь самотест не значит ничего.
    const слепой = join(песочницаА, 'tools/measure-hub-copy.СЛЕПОЙ.mjs');
    writeFileSync(слепой, слепойТекст, 'utf8');
    const с = померил(слепой);
    скажи(
      с.ок && с.видел === Б_ЗАПИСЕЙ && с.видел !== А_ЗАПИСЕЙ,
      'ослеплённая копия мерит СВОЁ дерево, стоя в чужом — различение работает',
      с.ок ? `увидела ${с.видел}, ждали Б=${Б_ЗАПИСЕЙ}, под ногами А=${А_ЗАПИСЕЙ}` : `копия не отработала: ${с.беда}`,
    );
  } finally {
    rmSync(база, { recursive: true, force: true });
  }

  console.log(
    провалов === 0
      ? '\n✅ САМОТЕСТ ЧИСТ: прибор смотрит на своё дерево, и это доказано чужим (EXP-0269)'
      : `\n🔴 САМОТЕСТ КРАСНЫЙ: провалов ${провалов}`,
  );
  return провалов === 0 ? 0 : 1;
}

// Запускается и сам по себе, и через `--selftest` прибора: два входа, одна работа.
// Предохранитель «работа под запуском, а не под импортом» — импорт из прибора не должен
// исполнять самотест дважды.
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  process.exit(самотест());
}
