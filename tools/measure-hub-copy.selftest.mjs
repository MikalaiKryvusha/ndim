/**
 * САМОТЕСТ ПРИБОРА `measure-hub-copy.mjs` — доказывает, что он мерит ДЕРЕВО, В КОТОРОМ ЛЕЖИТ.
 *
 * Запуск: node tools/measure-hub-copy.selftest.mjs (либо node tools/measure-hub-copy.mjs --selftest)
 * Ворота: нет — самотест зовётся прибором, а прибор в воротах не стоит (причина — в его шапке).
 * Код возврата: 0 — оба контроля сошлись · 1 — хотя бы один разошёлся.
 *
 * ═══ ЧТО ИМЕННО ОН СТЕРЕЖЁТ ═══
 *
 * Класс `EXP-0269` — **СТАБИЛЬНОСТЬ КАК ПРИЗНАК СЛЕПОТЫ**. Прибор с зашитым абсолютным путём
 * отвечает ОДИНАКОВО ОТКУДА УГОДНО, и его ответ выглядит тем надёжнее, чем он слепее: признак
 * «числа не меняются между рабочими местами» читается как устойчивость прибора, а означает, что
 * прибор не смотрит на дерево вовсе. Прежняя, скретчпадная редакция этого самого прибора,
 * положенная в поддельное дерево на 7 записей, напечатала оттуда числа НАСТОЯЩЕГО дерева
 * (178 страниц) — без ошибки, без предупреждения, без намёка.
 *
 * ═══ ПОЧЕМУ КОНТРОЛЯ ДВА, А НЕ ОДИН — ЭТО НЕ ПЕДАНТИЗМ ═══
 *
 * Проверка «прибор напечатал правильное число в СВОЁМ дереве» бесполезна: правильный прибор и
 * слепой дают там ОДИНАКОВЫЙ ответ. Различает их только чужое дерево. Поэтому:
 *
 *   · КОНТРОЛЬ 1 (положительный) — настоящий прибор в поддельном дереве обязан увидеть ПОДДЕЛКУ;
 *   · КОНТРОЛЬ 2 (отрицательный) — ОСЛЕПЛЁННАЯ копия там же обязана увидеть НАСТОЯЩЕЕ дерево.
 *
 * Второй и есть живая мутация, и она вшита В САМОТЕСТ, а не исполнена руками один раз: мутация,
 * прожитая однократно, доказывает прибор на один день, а вшитая — доказывает его каждый прогон.
 *
 * ⚠️ **МУТАЦИЯ ОБЯЗАНА ДОКАЗАТЬ, ЧТО ОНА ПРИМЕНИЛАСЬ** (`EXP-0249`: мутация без проверки
 * применения — это зелёное ни о чём). Ослепление делается заменой строки в исходнике; если
 * строка изменит форму, замена молча не сработает, «мутант» окажется здоровым и контроль 2
 * позеленеет, ничего не проверив. Поэтому подстановка сверяется на факт: текст обязан
 * ИЗМЕНИТЬСЯ, иначе самотест краснеет с прямым объяснением.
 *
 * ⚠️ ГРАНИЦА: самотест судит АДРЕСАЦИЮ прибора и ничего не говорит о верности его арифметики —
 * длины, ступени и лестница проверяются юнитом порции dev-1 на фикстуре, у которой предмет
 * постоянен. Здесь предмет — «на какое дерево прибор смотрит», и только он.
 */

import { execFileSync } from 'node:child_process';
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

/** Записей в поддельном каталоге. Заведомо не равно настоящему — на этом и стоит различение. */
const ПОДДЕЛЬНЫХ = 7;

/** Строка, задающая корень. Её подменяет мутация — и обязана доказать, что подменила. */
const СТРОКА_КОРНЯ = "const КОРЕНЬ = new URL('../', import.meta.url);";

/** Заглушка `catalog-hub.ts`: ровно те четыре имени, которые прибор импортирует, и ничего сверх. */
const ЗАГЛУШКА = `
export interface CatalogItem { slug: string; kind: string; title: { ru: string; en: string }; rates?: number }
export const PER_PAGE = 60;
export const pageCount = (n: number): number => Math.max(1, Math.ceil(n / PER_PAGE));
export const slicePage = <T,>(list: readonly T[], page: number): T[] =>
  list.slice((page - 1) * PER_PAGE, page * PER_PAGE);
export function groupByKind(items: readonly CatalogItem[]) {
  const hubs = new Map<string, CatalogItem[]>();
  for (const d of items) {
    if (!hubs.has(d.kind)) hubs.set(d.kind, []);
    hubs.get(d.kind)!.push(d);
  }
  return { hubs };
}
export function placesIn(list: readonly CatalogItem[]) {
  const m = new Map<string, { place: number }>();
  list.forEach((d, i) => { if ((d.rates ?? 0) > 0) m.set(d.slug, { place: i + 1 }); });
  return m;
}
`;

/** Первая строка вывода прибора — «каталог: N записей …». Сколько записей он УВИДЕЛ. */
function увиденоЗаписей(вывод) {
  const m = /каталог:\s*(\d+)\s+записей/u.exec(вывод);
  if (!m) throw new Error(`прибор не напечатал строку «каталог: N записей». Вывод:\n${вывод}`);
  return Number(m[1]);
}

function прогон(путьКПрибору) {
  return execFileSync(process.execPath, [путьКПрибору], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
}

export function самотест(корень) {
  const исходник = fileURLToPath(new URL('measure-hub-copy.mjs', import.meta.url));
  const настоящихЗаписей = JSON.parse(
    readFileSync(fileURLToPath(new URL('src/lib/content/dims-build.json', корень)), 'utf8'),
  ).length;

  const песочница = mkdtempSync(join(tmpdir(), 'measure-hub-copy-selftest-'));
  let провалов = 0;
  const скажи = (ок, что, деталь) => {
    if (!ок) провалов += 1;
    console.log(`${ок ? '✅' : '🔴'} ${что}${деталь ? ` · ${деталь}` : ''}`);
  };

  try {
    // ── Поддельное дерево: та же форма, что у настоящего, но заведомо другой объём материала.
    mkdirSync(join(песочница, 'src/lib/content'), { recursive: true });
    mkdirSync(join(песочница, 'tools'), { recursive: true });
    writeFileSync(join(песочница, 'src/lib/content/catalog-hub.ts'), ЗАГЛУШКА, 'utf8');
    writeFileSync(
      join(песочница, 'src/lib/content/dims-build.json'),
      JSON.stringify(
        Array.from({ length: ПОДДЕЛЬНЫХ }, (_, i) => ({
          slug: `поддельный-${i + 1}`,
          kind: 'movie',
          title: { ru: `Поддельный фильм ${i + 1}`, en: `Fake movie ${i + 1}` },
          rates: 0,
        })),
      ),
      'utf8',
    );

    // ── КОНТРОЛЬ 1 (положительный): настоящий прибор обязан увидеть ПОДДЕЛКУ.
    const целый = join(песочница, 'tools/measure-hub-copy.mjs');
    copyFileSync(исходник, целый);
    const виделЦелый = увиденоЗаписей(прогон(целый));
    скажи(
      виделЦелый === ПОДДЕЛЬНЫХ,
      'корень следует за файлом: прибор в поддельном дереве видит подделку',
      `увидел ${виделЦелый}, ждали ${ПОДДЕЛЬНЫХ}`,
    );

    // ── МУТАЦИЯ: зашиваем корень в НАСТОЯЩЕЕ дерево — ровно та болезнь, что была у скретчпадной
    //    редакции. Факт применения доказывается сравнением текста, а не надеждой на replace.
    const текст = readFileSync(исходник, 'utf8');
    const слепойТекст = текст.replace(СТРОКА_КОРНЯ, `const КОРЕНЬ = new URL(${JSON.stringify(корень.href)});`);
    скажи(
      слепойТекст !== текст,
      'мутация ПРИМЕНИЛАСЬ (строка корня найдена и заменена)',
      слепойТекст === текст ? `строка не найдена: ${СТРОКА_КОРНЯ}` : '',
    );
    if (слепойТекст === текст) {
      console.log('   ⛔ дальше не идём: непримененная мутация дала бы зелёный контроль 2 ни о чём');
      return 1;
    }

    // ── КОНТРОЛЬ 2 (отрицательный, живая мутация): ослеплённая копия обязана увидеть НАСТОЯЩЕЕ
    //    дерево, стоя в поддельном. Если она вдруг увидит подделку — различать нечего, и весь
    //    самотест не значит ничего.
    const слепой = join(песочница, 'tools/measure-hub-copy.СЛЕПОЙ.mjs');
    writeFileSync(слепой, слепойТекст, 'utf8');
    const виделСлепой = увиденоЗаписей(прогон(слепой));
    скажи(
      виделСлепой === настоящихЗаписей && виделСлепой !== ПОДДЕЛЬНЫХ,
      'ослеплённая копия мерит СВОЁ дерево, стоя в чужом — различение работает',
      `увидела ${виделСлепой}, настоящих ${настоящихЗаписей}, поддельных ${ПОДДЕЛЬНЫХ}`,
    );
  } finally {
    rmSync(песочница, { recursive: true, force: true });
  }

  console.log(
    провалов === 0
      ? '\n✅ САМОТЕСТ ЧИСТ: прибор смотрит на своё дерево, и это доказано чужим (EXP-0269)'
      : `\n🔴 САМОТЕСТ КРАСНЫЙ: провалов ${провалов}`,
  );
  return провалов === 0 ? 0 : 1;
}

// Запускается и сам по себе, и через `--selftest` прибора: два входа, одна работа.
// Предохранитель «работа под запуском, а не под импортом» — импорт из прибора не должен
// исполнять самотест дважды.
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  process.exit(самотест(new URL('../', import.meta.url)));
}
