import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

import { splitTagPairs, tagPairsOf, invisibleCharTags } from './lib/tag-conventions.mjs';

const КОРЕНЬ = join(dirname(fileURLToPath(import.meta.url)), '..');
const ПАРТИИ = join(КОРЕНЬ, 'candidates', 'batches');

/** Все партии из репозитория. Тестовая запись `99_` в корпус не идёт — она нарочно кривая. */
function карточкиПартий() {
  return readdirSync(ПАРТИИ)
    .filter((f) => f.endsWith('.json') && !f.startsWith('99_'))
    .sort()
    .flatMap((f) => JSON.parse(readFileSync(join(ПАРТИИ, f), 'utf8')).candidates ?? []);
}

/**
 * 🔴 ОБЪЯВЛЕННЫЙ ДОПУСК — ЧЕТЫРЕ ИЗВЕСТНЫХ РАСКОЛА ПОИМЁННО (условие 2 вердикта №27).
 *
 * ═══ ПОЧЕМУ ДОПУСК ВООБЩЕ ЕСТЬ ═══
 *
 * Страж написан 22.08 и зелен на партиях 1–4. Расколы легли в партии 05 (22.08) и 06 (23.08) —
 * уже ПОСЛЕ него, пока ветка пять дней лежала невлитой: третья форма `EXP-0227` в чистом виде.
 * Корпус в ветке и в `main` побайтно один (`git diff main <ветка> -- candidates/batches` —
 * пустота), значит без допуска мерж красит `main` в первую же секунду, а красный `main` по
 * канону тушится прежде любой другой работы.
 *
 * Обе прямые дороги закрыты, и это НЕ выбор исполнителя:
 *   · чинить данные — **правка каталога идёт словом владельца** (шаги 1–3 лечения `bugs/178`),
 *     а «ролевая игра» уже подана ему вопросом №061 В4 и ответа ждёт;
 *   · вливать молча — значит внести красное в ствол.
 * Остаётся третья: страж въезжает с ОБЪЯВЛЕННОЙ границей, как `CORPUS_FLOOR` у стража метки.
 *
 * ═══ ПОЧЕМУ ИМЕНА, А НЕ ЧИСЛО (уточнение QA, принято Менеджером) ═══
 *
 * Число («расколов не больше четырёх») глушило бы стража ровно на новом расколе: починили один,
 * появился другой — снова четыре, снова зелено. Имена так не умеют. И у поимённого допуска
 * есть вторая половина, которой у числа нет вовсе: **он краснеет и когда имя из списка ушло из
 * корпуса** — то есть сам просит снять строку, как только владелец ответит. Допуск, умеющий
 * только разрешать, отличается от допуска, умеющего ещё и умирать, ровно этим красным (та же
 * форма, что `ОТСРОЧКА` в переписи приборов и `LIVE_BY_NAME` у стража метки).
 *
 * ⛔ Допуск гасит ровно ЭТИ ЧЕТЫРЕ ИМЕНИ и ничего больше: пятый раскол — красный,
 * а раскол этих же имён с ДРУГИМИ спутниками пройдёт (граница названа честно: сторожится имя
 * русского тега, а не полная строка со счётом — счёт меняется от каждой новой карточки).
 */
const ДОПУСК_РАСКОЛОВ = new Map([
  ['кино', 'правка данных — слово владельца (bugs/178 шаги 1–3); вопрос в очередь вычитки после мержа'],
  ['фильм', 'правка данных — слово владельца (bugs/178 шаги 1–3); вопрос в очередь вычитки после мержа'],
  ['мистика', 'правка данных — слово владельца (bugs/178 шаги 1–3); вопрос в очередь вычитки после мержа'],
  ['ролевая игра', 'подан владельцу интервью №061 В4 — снять строку по его ответу'],
]);

/**
 * Вердикт по расколам против объявленного допуска: обе стороны разом.
 *
 * 🔴 НЕ ЭКСПОРТИРУЕТСЯ, и это не забывчивость. Первая редакция несла `export`, и страж входного
 * предохранителя (`verify-import-safety`, `ideas/43`, класс `EXP-0188`) покраснел на ней в тех
 * же воротах, где я его и увидел: у файла оказались И экспорт, И работа на верхнем уровне —
 * значит чужой `import` молча прогнал бы весь набор в чужом процессе. У теста работа наверху
 * неизбежна, так его зовёт `node --test`; убирается вторая половина пары, экспорт.
 * Ровно то же лечение и ровно тем же доводом стоит в соседе — `tools/regexp-escaping.test.mjs`.
 */
function расколыПротивДопуска(расколы, допуск = ДОПУСК_РАСКОЛОВ) {
  const имена = new Set(расколы.map((р) => р.тег));
  const новые = расколы
    .filter((р) => !допуск.has(р.тег))
    .map((р) => `НОВЫЙ РАСКОЛ «${р.тег}» → ${р.спутники.map(([e, n]) => `${e} ×${n}`).join(' | ')} — в допуске его нет (bugs/178)`);
  const вылеченные = [...допуск.keys()]
    .filter((имя) => !имена.has(имя))
    .map((имя) => `ВЫЛЕЧЕНО «${имя}» — раскола в корпусе больше нет, сними строку из ДОПУСК_РАСКОЛОВ, назвав кто и когда (${допуск.get(имя)})`);
  return [...новые, ...вылеченные];
}

test('КОРПУС ПАРТИЙ: у русского тега ровно одна английская пара', () => {
  const { расколы, записей, безПар } = splitTagPairs(карточкиПартий());
  assert.ok(записей > 0, 'корпус обязан быть непустым, иначе проверка зелена по пустоте');
  assert.equal(безПар, 0, 'запись, у которой русских и английских тегов разное число, паре не поддаётся');
  assert.deepEqual(
    расколыПротивДопуска(расколы),
    [],
    'раскол вне допуска — либо новый (чинить), либо вылеченный (снять строку допуска)',
  );
});

test('🔴 ДОПУСК КРАСНЕЕТ В ОБЕ СТОРОНЫ — иначе он вечное тихое исключение', () => {
  const раскол = (тег) => ({ тег, спутники: [['a', 2], ['b', 1]] });
  const все = [...ДОПУСК_РАСКОЛОВ.keys()].map(раскол);

  // Сторона 1: сегодняшнее состояние корпуса — ровно четыре известных имени, молчание законно.
  assert.deepEqual(расколыПротивДопуска(все), [], 'четыре известных раскола допуск гасит');

  // Сторона 2: ПЯТЫЙ раскол при четырёх в допуске. Число «не больше четырёх» здесь смолчало бы.
  const пятый = расколыПротивДопуска([...все, раскол('аниме')]);
  assert.equal(пятый.length, 1, 'новый раскол обязан краснеть даже при полном допуске');
  assert.match(пятый[0], /НОВЫЙ РАСКОЛ «аниме»/u);

  // Сторона 3: имя из допуска ушло из корпуса — допуск сам просит себя сократить.
  const вылечен = расколыПротивДопуска(все.filter((р) => р.тег !== 'ролевая игра'));
  assert.equal(вылечен.length, 1, 'вылеченный раскол обязан краснеть второй половиной');
  assert.match(вылечен[0], /ВЫЛЕЧЕНО «ролевая игра»/u);
  assert.match(вылечен[0], /№061 В4/u, 'причина строки едет в красный — снимающий узнает, чьего ответа ждали');

  // Контроль обеих сторон разом: и новый, и вылеченный в одном прогоне.
  const оба = расколыПротивДопуска([...безИмени(все, 'ролевая игра'), раскол('аниме')]);
  assert.equal(оба.length, 2, 'две стороны независимы и не глушат друг друга');
});

/** Мелкий помощник случая выше: список без названного имени. */
function безИмени(список, кроме) {
  return список.filter((р) => р.тег !== кроме);
}

test('КОРПУС ПАРТИЙ: в тегах нет невидимых знаков', () => {
  /* 🔴 Находка живого каталога, а не выдуманный случай: там лежат «thriller» и «thriller» с
   * `U+200B` на хвосте — на глаз одно слово, для машины два разных тега, и человек, нажавший
   * тег, второй записи не найдёт. В наших партиях таких нет, и страж держит это состояние. */
  const беды = [];
  for (const c of карточкиПартий()) {
    for (const н of invisibleCharTags(c)) беды.push(`${c.title?.ru}: «${н.тег}» (${н.коды.join(', ')})`);
  }
  assert.deepEqual(беды, []);
});

// ── САМОТЕСТ САМИХ ПРОВЕРОК: они обязаны краснеть по делу и молчать на здоровом ──────────────

test('пара опознаётся по ПОЗИЦИИ и переживает оба способа записи', () => {
  /* Наши партии чередуют теги, каталог владельца пишет их блоками. Правило одно на оба. */
  const чередование = { tags: ['фильм', 'movie', 'кино', 'film', 'триллер', 'thriller'] };
  const блоки = { tags: ['фильм', 'кино', 'триллер', 'movie', 'film', 'thriller'] };
  const ожидание = [['фильм', 'movie'], ['кино', 'film'], ['триллер', 'thriller']];
  assert.deepEqual(tagPairsOf(чередование), ожидание);
  assert.deepEqual(tagPairsOf(блоки), ожидание, 'блочная запись даёт те же пары, что чередование');
});

test('блоки разной длины — ЧЕСТНЫЙ отказ, а не «пар нет»', () => {
  assert.equal(tagPairsOf({ tags: ['фильм', 'movie', 'кино'] }), null);
  assert.equal(tagPairsOf({ tags: [] }), null);
  const r = splitTagPairs([{ tags: ['фильм', 'movie', 'кино'] }]);
  assert.equal(r.безПар, 1, 'такая запись считается отдельно, а не молча попадает в чистые');
  assert.equal(r.записей, 0);
});

test('раскол ловится, и спутники идут по убыванию счёта', () => {
  /* Живой случай `bugs/178` в миниатюре: тот же русский тег с двумя английскими спутниками. */
  const корпус = [
    { tags: ['симулятор', 'simulator'] },
    { tags: ['симулятор', 'simulation'] },
    { tags: ['симулятор', 'simulation'] },
  ];
  const { расколы } = splitTagPairs(корпус);
  assert.equal(расколы.length, 1);
  assert.equal(расколы[0].тег, 'симулятор');
  assert.deepEqual(расколы[0].спутники, [['simulation', 2], ['simulator', 1]],
    'доля и есть то, чем читающий отличит настоящий раскол от шума порядка');
});

test('здоровый корпус расколов не даёт', () => {
  const корпус = [{ tags: ['симулятор', 'simulation'] }, { tags: ['симулятор', 'simulation'] }];
  assert.deepEqual(splitTagPairs(корпус).расколы, []);
});

test('невидимый знак опознаётся и называется КОДОМ, а не «странным символом»', () => {
  const запись = { tags: ['thriller​', 'драма'] };
  const н = invisibleCharTags(запись);
  assert.equal(н.length, 1);
  assert.deepEqual(н[0].коды, ['U+200B'], 'код нужен человеку: на глаз тег выглядит обычным');
  assert.deepEqual(invisibleCharTags({ tags: ['thriller', 'драма'] }), [],
    'здоровый тег не предъявляется');
});
