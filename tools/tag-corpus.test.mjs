import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

import { splitTagPairs, tagPairsOf, invisibleCharTags } from './lib/tag-conventions.mjs';

const КОРЕНЬ = join(dirname(fileURLToPath(import.meta.url)), '..');
const ПАРТИИ = join(КОРЕНЬ, 'candidates', 'batches');

/** Все партии из репозитория. Тестовая запись `99_` в корпус не идёт — она нарочно кривая. */
function карточкиПартий() {
  return readdirSync(ПАРТИИ)
    .filter((f) => f.endsWith('.json') && !f.startsWith('99_'))
    .sort()
    .flatMap((f) => JSON.parse(readFileSync(join(ПАРТИИ, f), 'utf8')).candidates ?? []);
}

test('КОРПУС ПАРТИЙ: у русского тега ровно одна английская пара', () => {
  const { расколы, записей, безПар } = splitTagPairs(карточкиПартий());
  assert.ok(записей > 0, 'корпус обязан быть непустым, иначе проверка зелена по пустоте');
  assert.equal(безПар, 0, 'запись, у которой русских и английских тегов разное число, паре не поддаётся');
  assert.deepEqual(
    расколы.map((р) => `${р.тег} → ${р.спутники.map(([e, n]) => `${e} ×${n}`).join(' | ')}`),
    [],
    'русский тег с двумя английскими спутниками — это раскол каталога (bugs/178)',
  );
});

test('КОРПУС ПАРТИЙ: в тегах нет невидимых знаков', () => {
  /* 🔴 Находка живого каталога, а не выдуманный случай: там лежат «thriller» и «thriller» с
   * `U+200B` на хвосте — на глаз одно слово, для машины два разных тега, и человек, нажавший
   * тег, второй записи не найдёт. В наших партиях таких нет, и страж держит это состояние. */
  const беды = [];
  for (const c of карточкиПартий()) {
    for (const н of invisibleCharTags(c)) беды.push(`${c.title?.ru}: «${н.тег}» (${н.коды.join(', ')})`);
  }
  assert.deepEqual(беды, []);
});

// ── САМОТЕСТ САМИХ ПРОВЕРОК: они обязаны краснеть по делу и молчать на здоровом ──────────────

test('пара опознаётся по ПОЗИЦИИ и переживает оба способа записи', () => {
  /* Наши партии чередуют теги, каталог владельца пишет их блоками. Правило одно на оба. */
  const чередование = { tags: ['фильм', 'movie', 'кино', 'film', 'триллер', 'thriller'] };
  const блоки = { tags: ['фильм', 'кино', 'триллер', 'movie', 'film', 'thriller'] };
  const ожидание = [['фильм', 'movie'], ['кино', 'film'], ['триллер', 'thriller']];
  assert.deepEqual(tagPairsOf(чередование), ожидание);
  assert.deepEqual(tagPairsOf(блоки), ожидание, 'блочная запись даёт те же пары, что чередование');
});

test('блоки разной длины — ЧЕСТНЫЙ отказ, а не «пар нет»', () => {
  assert.equal(tagPairsOf({ tags: ['фильм', 'movie', 'кино'] }), null);
  assert.equal(tagPairsOf({ tags: [] }), null);
  const r = splitTagPairs([{ tags: ['фильм', 'movie', 'кино'] }]);
  assert.equal(r.безПар, 1, 'такая запись считается отдельно, а не молча попадает в чистые');
  assert.equal(r.записей, 0);
});

test('раскол ловится, и спутники идут по убыванию счёта', () => {
  /* Живой случай `bugs/178` в миниатюре: тот же русский тег с двумя английскими спутниками. */
  const корпус = [
    { tags: ['симулятор', 'simulator'] },
    { tags: ['симулятор', 'simulation'] },
    { tags: ['симулятор', 'simulation'] },
  ];
  const { расколы } = splitTagPairs(корпус);
  assert.equal(расколы.length, 1);
  assert.equal(расколы[0].тег, 'симулятор');
  assert.deepEqual(расколы[0].спутники, [['simulation', 2], ['simulator', 1]],
    'доля и есть то, чем читающий отличит настоящий раскол от шума порядка');
});

test('здоровый корпус расколов не даёт', () => {
  const корпус = [{ tags: ['симулятор', 'simulation'] }, { tags: ['симулятор', 'simulation'] }];
  assert.deepEqual(splitTagPairs(корпус).расколы, []);
});

test('невидимый знак опознаётся и называется КОДОМ, а не «странным символом»', () => {
  const запись = { tags: ['thriller​', 'драма'] };
  const н = invisibleCharTags(запись);
  assert.equal(н.length, 1);
  assert.deepEqual(н[0].коды, ['U+200B'], 'код нужен человеку: на глаз тег выглядит обычным');
  assert.deepEqual(invisibleCharTags({ tags: ['thriller', 'драма'] }), [],
    'здоровый тег не предъявляется');
});
