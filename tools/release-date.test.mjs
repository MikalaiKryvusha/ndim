/**
 * ЮНИТЫ КЛАССА 1 ВЛАДЕЛЬЦА — «не вышедший объект не подаётся на вычитку»
 * (`tools/lib/release-date.mjs`).
 *
 * 🔴 ПОЧЕМУ ЗДЕСЬ ТАК МНОГО МУТАЦИЙ, А НЕ ПРОГОН ПО КОРПУСУ. Прогон реестра по всем 50 карточкам
 * партий 1–4 дал НОЛЬ объектов с датой в будущем. Значит на живом материале половина 1а
 * покраснеть НЕ МОЖЕТ — и зелёный её прогон не отличим от зелёного «правило держится»
 * (`AGENT_GUIDE.md` → «Лестница трёх вопросов к зелёному прогону», вопрос 3). Единственное
 * честное доказательство такой проверки — материал, построенный так, чтобы она была ОБЯЗАНА
 * упасть. Каждый случай ниже идёт парой: внеси ошибку — красное; убери — молчит.
 *
 * Прогон: node --test tools/release-date.test.mjs   ·   npm run test:tools
 */
import test from 'node:test';
import assert from 'node:assert/strict';

import {
  периодЗаписи, состояниеВыхода, датыИзРеестра, будущийРегистр, приговорКласса1, СВОЙСТВО_ДАТЫ,
} from './lib/release-date.mjs';

const СЕГОДНЯ = '2026-08-22';
const день = (д) => ({ mainsnak: { datavalue: { value: { time: `+${д}T00:00:00Z`, precision: 11 } } } });
const грубо = (time, precision) => ({ mainsnak: { datavalue: { value: { time, precision } } } });
const реестрОтдаёт = (qid, claims) => async () => ({ entities: { [qid]: claims === null ? { missing: '' } : { claims: claims ? { [СВОЙСТВО_ДАТЫ]: claims } : {} } } });

// ── Период записи: точность реестра — это ПЕРИОД, а не округление ────────────────────────────

test('точность «день» даёт период из одного дня', () => {
  assert.deepEqual(периодЗаписи('+2026-02-27T00:00:00Z', 11), { рано: '2026-02-27', поздно: '2026-02-27' });
});

test('точность «месяц» даёт весь месяц, и конец месяца считается, а не берётся 31-м', () => {
  assert.deepEqual(периодЗаписи('+2025-09-00T00:00:00Z', 10), { рано: '2025-09-01', поздно: '2025-09-30' });
  assert.deepEqual(периодЗаписи('+2024-02-00T00:00:00Z', 10), { рано: '2024-02-01', поздно: '2024-02-29' }, 'високосный февраль');
});

test('точность «год» даёт весь год', () => {
  assert.deepEqual(периодЗаписи('+2027-00-00T00:00:00Z', 9), { рано: '2027-01-01', поздно: '2027-12-31' });
});

test('запись, которую машина толковать не берётся, возвращает null, а не догадку', () => {
  assert.equal(периодЗаписи('-0500-00-00T00:00:00Z', 9), null, 'до нашей эры карточек мастерской не бывает');
  assert.equal(периодЗаписи('+2026-02-27T00:00:00Z', 7), null, 'точность грубее десятилетия');
  assert.equal(периодЗаписи(undefined, 11), null);
});

// ── Состояние выхода: три исхода, и грубая точность — третий, а не округление до второго ─────

test('МУТАЦИЯ 1а: дата в будущем — «не вышел»; сдвинь её в прошлое — «вышел»', () => {
  const будущее = [{ рано: '2026-12-05', поздно: '2026-12-05' }];
  assert.equal(состояниеВыхода(будущее, СЕГОДНЯ).вид, 'не вышел', 'внесли ошибку — прибор обязан её назвать');
  const прошлое = [{ рано: '2026-02-27', поздно: '2026-02-27' }];
  assert.equal(состояниеВыхода(прошлое, СЕГОДНЯ).вид, 'вышел', 'убрали ошибку — прибор обязан замолчать');
});

test('судится по ВСЕМ записям, а не по самой ранней: живой случай Deltarune', () => {
  /* У Deltarune самая ранняя запись по «рано» — грубый +2027-00-00, а рядом точная 2018-10-31.
   * Суд по одной записи объявил бы вышедшую игру невышедшей. */
  const периоды = [
    { рано: '2027-01-01', поздно: '2027-12-31' },
    { рано: '2018-10-31', поздно: '2018-10-31' },
  ];
  const с = состояниеВыхода(периоды, СЕГОДНЯ);
  assert.equal(с.вид, 'вышел');
  assert.equal(с.дата, '2018-10-31', 'называется дата ВЫШЕДШЕЙ записи, а не самая ранняя вообще');
});

test('грубая точность, накрывающая сегодняшний день, — отдельный исход «грубо», а не отказ', () => {
  const годТекущий = [{ рано: '2026-01-01', поздно: '2026-12-31' }];
  assert.equal(состояниеВыхода(годТекущий, СЕГОДНЯ).вид, 'грубо',
    'в августе 2026-го запись «2026 год» не отвечает на вопрос «вышел ли»');
  const годБудущий = [{ рано: '2027-01-01', поздно: '2027-12-31' }];
  assert.equal(состояниеВыхода(годБудущий, СЕГОДНЯ).вид, 'не вышел',
    'а вот весь 2027-й в будущем целиком — тут ответ есть');
});

test('пустой список периодов — «нет даты», а не «вышел»', () => {
  assert.equal(состояниеВыхода([], СЕГОДНЯ).вид, 'нет даты');
  assert.equal(состояниеВыхода(undefined, СЕГОДНЯ).вид, 'нет даты');
});

// ── Разговор с реестром: три ответа, и путать их нельзя ──────────────────────────────────────

test('реестр ответил и даты знает', async () => {
  const о = await датыРеестраПоддельно('Q1', [день('2026-02-27')]);
  assert.equal(о.есть, true);
  assert.deepEqual(о.периоды, [{ рано: '2026-02-27', поздно: '2026-02-27' }]);
});

test('реестр ответил, а P577 у записи НЕТ — это «не знаю», а не «вышел»', async () => {
  const о = await датыРеестраБезСвойства('Q1');
  assert.deepEqual(о, { есть: false });
});

test('реестра спросить не удалось — null, и он НЕ равен «даты нет»', async () => {
  assert.equal(await датыИзРеестра('', async () => ({})), null, 'нет идентификатора');
  assert.equal(await датыИзРеестра('Q1', реестрОтдаёт('Q1', null)), null, 'записи в реестре нет');
});

test('грубая запись доезжает до периода, а нетолкуемая отбрасывается молча', async () => {
  const о = await датыРеестраПоддельно('Q1', [грубо('+2025-09-00T00:00:00Z', 10), грубо('+2026-02-27T00:00:00Z', 7)]);
  assert.deepEqual(о.периоды, [{ рано: '2025-09-01', поздно: '2025-09-30' }]);
});

// ── 1б: старый регистр текста ────────────────────────────────────────────────────────────────

test('МУТАЦИЯ 1б: «выход назначен» ловится; уберёшь оборот — молчит', () => {
  const плохо = 'Выход назначен на 27 февраля 2026 года для Microsoft Windows и PlayStation 5.';
  assert.equal(будущийРегистр(плохо).length > 0, true, 'внесли ошибку — прибор обязан её назвать');
  const хорошо = 'Игра вышла 27 февраля 2026 года для Microsoft Windows и PlayStation 5.';
  assert.deepEqual(будущийРегистр(хорошо), [], 'убрали ошибку — прибор обязан замолчать');
});

test('🔴 ГРАНИЦА СЛОВА ПО-РУССКИ: образец срабатывает на кириллице, а не молчит из-за \\b', () => {
  /* Класс уже оплачен в этом приборе: `/по данным\b/giu` не срабатывал НИ РАЗУ, потому что в
   * JavaScript граница слова определена через ASCII. Проверка стоит здесь, чтобы правка
   * образцов на `\b` роняла тест, а не проезжала молча. */
  assert.equal(будущийРегистр('Премьера назначена на 2026 год.').length, 1);
  assert.equal(будущийРегистр('Прочие сюжетные подробности пока не раскрыты.').length, 1);
});

test('«назначен» не о выходе — сюжет, и он не судится', () => {
  assert.deepEqual(будущийРегистр('Героя назначили начальником участка, и он берётся за дело.'), []);
});

test('английская половина этой проверкой не судится', () => {
  assert.deepEqual(будущийРегистр('The release is scheduled for 27 February 2026.', 'en'), []);
});

// ── Приговор целиком: порядок половин и то, что ни одна не даёт ложного отказа ───────────────

test('1а отказывает по реестру и НЕ спрашивает с текста: у невышедшего «назначен» законно', () => {
  const ответ = { есть: true, периоды: [{ рано: '2026-12-05', поздно: '2026-12-05' }] };
  const п = приговорКласса1(ответ, 'Выход назначен на 5 декабря 2026 года.', СЕГОДНЯ);
  assert.equal(п.отказы.length, 1, 'ровно один отказ — про отбор, а не два про одно и то же');
  assert.match(п.отказы[0], /объект ещё не вышел/u);
});

test('1б отказывает ТОЛЬКО после подтверждения реестром, что объект вышел', () => {
  const ответ = { есть: true, периоды: [{ рано: '2026-02-27', поздно: '2026-02-27' }] };
  const п = приговорКласса1(ответ, 'Выход назначен на 27 февраля 2026 года.', СЕГОДНЯ);
  assert.equal(п.отказы.length, 1);
  assert.match(п.отказы[0], /вышел 2026-02-27, а описание пишет о нём как о будущем/u);
});

test('вышедший объект с живым текстом проходит начисто', () => {
  const ответ = { есть: true, периоды: [{ рано: '2026-02-27', поздно: '2026-02-27' }] };
  const п = приговорКласса1(ответ, 'Игра вышла 27 февраля 2026 года.', СЕГОДНЯ);
  assert.deepEqual(п.отказы, []);
  assert.deepEqual(п.замечания, []);
});

test('незнание реестра — ЗАМЕЧАНИЕ, а не отказ и не зелёный', () => {
  assert.match(приговорКласса1(null, 'текст', СЕГОДНЯ).замечания[0], /реестр не ответил/u);
  assert.match(приговорКласса1({ есть: false }, 'текст', СЕГОДНЯ).замечания[0], /нет в реестре/u);
  assert.deepEqual(приговорКласса1(null, 'Выход назначен на 2026 год.', СЕГОДНЯ).отказы, [],
    'без ответа реестра текст не судится: вдруг объект и правда не вышел');
});

test('грубая точность даёт замечание, а карточку не останавливает', () => {
  const ответ = { есть: true, периоды: [{ рано: '2026-01-01', поздно: '2026-12-31' }] };
  const п = приговорКласса1(ответ, 'Выход назначен на 2026 год.', СЕГОДНЯ);
  assert.deepEqual(п.отказы, [], 'ложный отказ снял бы с вычитки живой объект — это дороже недосчёта');
  assert.match(п.замечания[0], /знает дату грубо/u);
});

// ── Поддельный реестр: помощники, чтобы юниты не ходили в сеть ───────────────────────────────
async function датыРеестраПоддельно(qid, claims) {
  return датыИзРеестра(qid, реестрОтдаёт(qid, claims));
}
async function датыРеестраБезСвойства(qid) {
  return датыИзРеестра(qid, реестрОтдаёт(qid, undefined));
}

test('🔴 состояние «вышел» отличает точную дату реестра от грубой', () => {
  /* Повод живой: у «Отец, мать, сестра, брат» реестр знает ГОД (`+2025-00-00`), а прибор выдал
   * человеку «реестр знает: 2025-01-01» — дату, которой в реестре нет. Поле `точная` и есть
   * лечение: подсказку даёт только запись, у которой начало периода совпало с концом. */
  const точно = состояниеВыхода([{ рано: '2026-02-27', поздно: '2026-02-27' }], СЕГОДНЯ);
  assert.equal(точно.точная, true);
  const грубо = состояниеВыхода([{ рано: '2025-01-01', поздно: '2025-12-31' }], СЕГОДНЯ);
  assert.equal(грубо.вид, 'вышел', 'весь 2025-й в прошлом — объект вышел, это не спорно');
  assert.equal(грубо.точная, false, 'но ДНЯ реестр не знает, и выдавать 1 января нельзя');
});
