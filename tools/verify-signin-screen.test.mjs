/**
 * ЮНИТЫ СТРАЖА ЭКРАНА ВХОДА (`tools/verify-signin-screen.mjs`).
 *
 * 🔴 ГЛАВНОЕ ЗДЕСЬ — ЧТО САМОТЕСТ СТРАЖА КТО-ТО ЗОВЁТ, и что судья прибора судит РЕШЕНИЯ
 * ВЛАДЕЛЬЦА, а не форму разметки. Прибор существует ради трёх его слов:
 *   · `bugs/19` — «должно быть отдельным экраном… а не показываться внутри приложения»;
 *   · 2026-09-04 — «кнопку гостя делаем яркой синей, как ещё одна основная»;
 *   · 2026-09-04 — «слово "или" заметнее».
 * Каждое из них здесь проверяется мутацией: снимаем ровно один факт и требуем, чтобы прибор
 * покраснел ИМЕННО этим пунктом. Прибор, который краснеет «вообще», не отличает возврат
 * оболочки от опечатки, и первый же его красный будет прочитан как шум.
 *
 * Прогон: node --test tools/verify-signin-screen.test.mjs   ·   npm run test:tools
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { join } from 'node:path';

import { судить } from './verify-signin-screen.mjs';

const СТРАЖ = 'tools/verify-signin-screen.mjs';

/** Факты здорового экрана — те же числа, что прибор снял с живого стенда 2026-09-04. */
const ЗДОРОВЫЙ = {
  экран: true,
  нижняяПанель: false,
  рельс: false,
  табы: false,
  переключатели: 3,
  текстГостя: 'Смотреть Пространство NDim Space гостем\nбез регистрации',
  пробелыГостя: 'pre-line',
  фонГостя: 'rgb(20, 103, 214)',
  фонGoogle: 'rgb(20, 103, 214)',
  илиКегль: 14,
  илиВес: 700,
  илиЦвет: 'rgb(27, 26, 23)',
  цветТекста: 'rgb(27, 26, 23)',
};

test('САМОТЕСТ стража зовётся отсюда и обязан быть зелёным', () => {
  const r = spawnSync(process.execPath, [join(process.cwd(), СТРАЖ), '--selftest'], { encoding: 'utf8' });
  const вывод = (r.stdout ?? '') + (r.stderr ?? '');
  assert.equal(r.status, 0, `самотест упал:\n${вывод}`);
  assert.match(вывод, /самопроверка стража экрана входа пройдена — 14 случаев/u);
});

test('здоровый экран молчит — ложных тревог нет', () => {
  assert.deepEqual(судить(ЗДОРОВЫЙ), []);
});

test('bugs/19: возврат ЛЮБОЙ части оболочки приложения краснит, и каждая — своим пунктом', () => {
  for (const [поле, кусок] of [['нижняяПанель', /НИЖНЯЯ ПАНЕЛЬ/u], ['рельс', /РЕЛЬС/u], ['табы', /ТАБЫ/u]]) {
    const беды = судить({ ...ЗДОРОВЫЙ, [поле]: true });
    assert.equal(беды.length, 1, `поле «${поле}» дало ${беды.length} претензий`);
    assert.match(беды[0], кусок);
    assert.match(беды[0], /bugs\/19/u, 'красный обязан назвать ПОВОД — иначе следующий не поймёт, чьё решение защищает');
  }
});

test('слово владельца о гостевой двери: и прозрачность, и чужой цвет — разные претензии', () => {
  const прозрачная = судить({ ...ЗДОРОВЫЙ, фонГостя: 'rgba(0, 0, 0, 0)' });
  assert.equal(прозрачная.length, 1);
  assert.match(прозрачная[0], /ПРОЗРАЧНАЯ/u);
  assert.match(прозрачная[0], /как ещё одна основная/u, 'его слово едет в красный дословно');

  const чужаяКраска = судить({ ...ЗДОРОВЫЙ, фонГостя: 'rgb(255, 255, 255)' });
  assert.equal(чужаяКраска.length, 1);
  assert.match(чужаяКраска[0], /веса разошлись/u);
});

test('слово владельца об «или»: кегль, вес и приглушённость — три независимые претензии', () => {
  assert.match(судить({ ...ЗДОРОВЫЙ, илиКегль: 12 })[0], /кеглем 12/u);
  assert.match(судить({ ...ЗДОРОВЫЙ, илиВес: 500 })[0], /весом 500/u);
  assert.match(судить({ ...ЗДОРОВЫЙ, илиЦвет: 'rgb(150, 150, 150)' })[0], /снова приглушено/u);
  // И контроль: три беды разом не глушат друг друга.
  assert.equal(судить({ ...ЗДОРОВЫЙ, илиКегль: 12, илиВес: 500, илиЦвет: 'rgb(150,150,150)' }).length, 3);
});

test('текст гостевой двери сверяется ПОБАЙТОВО, а не «содержит слово гость»', () => {
  // Прежняя боевая строка — та самая, которую владелец запретил на лендинге решением №009 В3.
  const старая = судить({ ...ЗДОРОВЫЙ, текстГостя: 'Осмотреться гостем' });
  assert.equal(старая.length, 1);
  assert.match(старая[0], /не тот/u);
  // Даже точка в конце — расхождение: строку диктовал владелец.
  const почтиТа = судить({ ...ЗДОРОВЫЙ, текстГостя: ЗДОРОВЫЙ.текстГостя + '.' });
  assert.equal(почтиТа.length, 1, 'лишняя точка обязана краснеть — иначе сверка не побайтовая');
});

test('принудительный перенос: он ЖИВЁТ В ДВУХ МЕСТАХ, и каждое краснеет отдельно', () => {
  // Слово владельца 2026-09-05: «в кнопке входа в анонимный аккаунт нужно сделать принудительный
  // перенос, чтобы "без регистрации" было на новой строке». Слова при этом не менялись — значит
  // претензия «текст не тот» здесь была бы ЛОЖЬЮ: она увела бы следующего искать опечатку.

  // 1 · символ выпал из строки, слова целы
  const безСимвола = судить({ ...ЗДОРОВЫЙ, текстГостя: ЗДОРОВЫЙ.текстГостя.replace('\n', ' ') });
  assert.equal(безСимвола.length, 1, `ожидалась одна претензия, получено: ${безСимвола.join(' · ')}`);
  assert.match(безСимвола[0], /ПРОПАЛ принудительный перенос/u);
  assert.doesNotMatch(безСимвола[0], /текст гостевой двери не тот/u, 'слова целы — врать про текст нельзя');

  // 2 · символ на месте, но стиль схлопнул его в пробел — САМЫЙ тихий способ отменить правку:
  //     строка в коде выглядит правильной, а человек видит одну строку.
  const съеденСтилем = судить({ ...ЗДОРОВЫЙ, пробелыГостя: 'normal' });
  assert.equal(съеденСтилем.length, 1, `ожидалась одна претензия, получено: ${съеденСтилем.join(' · ')}`);
  assert.match(съеденСтилем[0], /СЪЕДАЕТ/u);
  assert.match(съеденСтилем[0], /white-space: normal/u, 'красный обязан назвать виновный стиль');

  // 3 · и контроль: pre-wrap тоже показывает перенос — прибор не придирается к букве pre-line
  assert.deepEqual(судить({ ...ЗДОРОВЫЙ, пробелыГостя: 'pre-wrap' }), []);
});

test('пропавший переключатель темы краснит: это ВТОРАЯ половина bugs/19, её легко потерять', () => {
  const беды = судить({ ...ЗДОРОВЫЙ, переключатели: 2 });
  assert.equal(беды.length, 1);
  assert.match(беды[0], /переключателей языка и темы 2/u);
});
