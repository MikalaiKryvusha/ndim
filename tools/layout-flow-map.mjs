#!/usr/bin/env node
/**
 * РАСКЛАДЧИК РАЗВЁРТКИ — считает координаты экранов в манифесте по ТАБЛИЦЕ РЯДОВ.
 *
 * До 2026-09-05 (вечер) раскладка жила одноразовым скриптом в чате, и истина манифеста
 * (`design/flow-map/flow-map.json`) пересчитывалась руками — первый названный долг дистилляции
 * KUIPS (`design/flow-map/README.md` §6). Этот файл закрывает долг: раскладка стала прибором.
 *
 * ПРАВИЛА — слово владельца 2026-09-05, дословно:
 *   · «Расставлять экраны нужно в ряды слева направо по мере логического развития процесса или
 *     путя (флоу) пользователя. Так же нужно располагать так экраны, чтобы трубопровод был короче»;
 *   · «Выше ниже экрана можно располагать его альтернативные состояния»;
 *   · «Масштабно переходить ниже на новый ряд — если это логически другой процесс».
 * Отсюда: ряд = процесс; внутри ряда колонка = шаг пути; ярус 0 — главная линия, ±1 —
 * альтернативные состояния над и под родителем.
 *
 * ⚠️ ШАГ ЯРУСА ЗАВИСИТ ОТ ВЫСОТЫ КАРТОЧКИ И ГЛУБИНЫ ОБХОДА. Дальние соседи в одном ряду обходят
 * ряд СНИЗУ на `КАРТА_В + 120`; следующий ярус обязан начинаться ниже этой полки, иначе труба
 * пройдёт сквозь карточку яруса +1. Шаг берётся из сборщика, а не пишется числом.
 *
 * Запуск:  node tools/layout-flow-map.mjs          пересчитать координаты в манифесте
 *          node tools/layout-flow-map.mjs --selftest
 * Коды:    0 — манифест переписан; 1 — экран без места или лишнее место.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { КАРТА_В, ШАГ_X } from './build-flow-map.mjs';

const ЗАПУЩЕН_НАПРЯМУЮ = Boolean(process.argv[1]) && import.meta.url === pathToFileURL(process.argv[1]).href;
const MANIFEST = 'design/flow-map/flow-map.json';

// Шаг колонок — константа СБОРЩИКА: зазор между колонками это коридор для труб между рядами,
// и его ширина считается от числа полос, а не от вкуса раскладчика.
export { ШАГ_X };
export const ШАГ_Я = КАРТА_В + 120 + 90;  // карточка + полка обхода + воздух над следующим ярусом
export const ЛЕВО = 380;                  // место под плашку имени ряда
export const ВЕРХ = 260;
export const МЕЖДУ_РЯДАМИ = 260;

/** [id, колонка, ярус] — ярус 0 это главная линия ряда, ±1 — альтернативные состояния. */
export const РЯДЫ = [
  {
    имя: 'Незнакомец из поиска',
    места: [
      ['root', 0, 0], ['landing', 1, 0], ['catalog', 2, 0],
      ['hub-movie', 3, 0], ['hub-game', 3, -1], ['hub-page2', 3, 1],
      ['dimension', 4, 0], ['dimension-practice', 4, 1],
      ['notfound', 5, 1],
    ],
  },
  { имя: 'Стена входа', места: [['signin', 0, 0], ['signin-email', 1, 0], ['signin-sent', 2, 0]] },
  {
    имя: 'Гость',
    места: [
      ['guest-profile', 0, 0], ['guest-leave', 0, 1],
      ['guest-dims', 1, 0], ['guest-relations', 2, 0], ['guest-space', 3, 0], ['guest-menu', 4, 0],
    ],
  },
  {
    имя: 'Приложение',
    места: [
      ['profile', 0, 0], ['profile-seeme', 0, 1],
      ['dims', 1, 0], ['relations', 2, 0], ['space', 3, 0], ['menu', 4, 0], ['account', 5, 0],
    ],
  },
  {
    имя: 'Тесты',
    места: [['tests', 0, 0], ['test-compatibility', 1, 0], ['test-personality', 1, -1], ['test-love', 1, 1]],
  },
  {
    имя: 'Документы',
    места: [
      ['doc-about', 0, 0], ['doc-author', 1, 0], ['doc-support', 2, 0], ['doc-donate', 3, 0],
      ['doc-share', 4, 0], ['doc-manual', 5, 0], ['doc-terms', 6, 0], ['doc-privacy', 7, 0],
      ['doc-disclaimer', 8, 0], ['doc-delete', 9, 0],
    ],
  },
];

/**
 * Разложить экраны манифеста по таблице. Чистая функция: возвращает новый манифест и список бед.
 * Беда — экран манифеста без места ИЛИ место без экрана: оба случая молча дали бы дырку на листе.
 */
export function разложить(манифест, ряды = РЯДЫ) {
  const беды = [];
  const было = Object.fromEntries((манифест['экраны'] ?? []).map((э) => [э.id, э]));
  const размещены = new Set();
  const экраны = [];
  const полосы = [];
  let курсорY = ВЕРХ;
  for (const ряд of ряды) {
    const ярусы = ряд.места.map(([, , я]) => я);
    const мин = Math.min(...ярусы), макс = Math.max(...ярусы);
    const верхРяда = курсорY;
    for (const [id, к, я] of ряд.места) {
      if (!было[id]) { беды.push(`место есть, экрана нет: ${id}`); continue; }
      if (размещены.has(id)) { беды.push(`экран размещён дважды: ${id}`); continue; }
      размещены.add(id);
      экраны.push({ ...было[id], x: ЛЕВО + к * ШАГ_X, y: верхРяда + (я - мин) * ШАГ_Я });
    }
    полосы.push({ имя: ряд.имя, y: верхРяда, высота: (макс - мин + 1) * ШАГ_Я });
    курсорY = верхРяда + (макс - мин + 1) * ШАГ_Я + МЕЖДУ_РЯДАМИ;
  }
  for (const id of Object.keys(было)) if (!размещены.has(id)) беды.push(`экран без места: ${id}`);
  const макс_к = Math.max(...ряды.flatMap((р) => р.места.map(([, к]) => к)));
  return {
    беды,
    манифест: {
      ...манифест,
      экраны,
      полосы,
      лист: { ширина: ЛЕВО + (макс_к + 1) * ШАГ_X + 120, высота: курсорY + 120 },
    },
  };
}

if (ЗАПУЩЕН_НАПРЯМУЮ && process.argv.includes('--selftest')) {
  const м = { экраны: [{ id: 'a' }, { id: 'b' }, { id: 'c' }], связи: [] };
  const здоров = разложить(м, [{ имя: 'р', места: [['a', 0, 0], ['b', 1, 0], ['c', 1, 1]] }]);
  const сирота = разложить(м, [{ имя: 'р', места: [['a', 0, 0], ['b', 1, 0]] }]);
  const призрак = разложить(м, [{ имя: 'р', места: [['a', 0, 0], ['b', 1, 0], ['c', 1, 1], ['z', 2, 0]] }]);
  const ok = (имя, cond) => console.log(`  ${cond ? '✅' : '❌'} ${имя}`);
  ok('здоровая таблица молчит', здоров.беды.length === 0 && здоров.манифест.экраны.length === 3);
  ok('ярус +1 ниже яруса 0 ровно на ШАГ_Я', здоров.манифест.экраны[2].y - здоров.манифест.экраны[1].y === ШАГ_Я);
  ok('ШАГ_Я больше карточки с полкой обхода', ШАГ_Я > КАРТА_В + 120);
  ok('экран без места — беда', сирота.беды.some((b) => /без места: c/u.test(b)));
  ok('место без экрана — беда', призрак.беды.some((b) => /экрана нет: z/u.test(b)));
  const плохо = [здоров.беды.length === 0, сирота.беды.length === 1, призрак.беды.length === 1].filter((x) => !x).length;
  console.log(плохо ? '\n❌ самопроверка раскладчика провалена' : '\n✅ самопроверка раскладчика пройдена');
  process.exit(плохо ? 1 : 0);
}

if (ЗАПУЩЕН_НАПРЯМУЮ) {
  const м = JSON.parse(readFileSync(MANIFEST, 'utf8'));
  const { беды, манифест } = разложить(м);
  if (беды.length) { console.error('✖ раскладка неполна:'); for (const b of беды) console.error('  · ' + b); process.exit(1); }
  writeFileSync(MANIFEST, JSON.stringify(манифест, null, 1) + '\n', 'utf8');
  console.log(`✅ ${MANIFEST}: ${манифест.экраны.length} экранов, ${манифест.полосы.length} рядов, шаг яруса ${ШАГ_Я}, лист ${манифест.лист.ширина}×${манифест.лист.высота}`);
  console.log('   дальше: node tools/build-flow-map.mjs');
}
