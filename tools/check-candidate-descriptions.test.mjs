/**
 * Прогоняет развилку `заголовокИзРеестра` в дочернем процессе на ПОДДЕЛЬНОМ транспорте.
 * Сети здесь нет вовсе: `спросить` — параметр, и юнит подставляет ответы реестра руками.
 * Ответы взяты из ЖИВЫХ записей партии 5, а не выдуманы (проверены curl-ом 2026-08-22).
 */
function развилкаРеестраВДочернем() {
  const импортёр = join(tmpdir(), `ndim-registry-probe-${process.pid}.mjs`);
  const тело = [
    "const m = await import(process.env.NDIM_MODULE);",
    // Живой ответ по Star Fox: ru-ссылка ведёт на статью ОБ ИГРЕ, а не о франшизе.
    "const starFox = () => ({ entities: { Q139683849: { sitelinks: {",
    "  ruwiki: { title: 'Star Fox (игра, 2026)' }, enwiki: { title: 'Star Fox (2026 video game)' } } } } });",
    // Живой ответ по Voicemails for Isabelle: русской ссылки НЕТ, английская есть.
    "const voicemails = () => ({ entities: { Q139665886: { sitelinks: {",
    "  enwiki: { title: 'Voicemails for Isabelle' } } } } });",
    "const пусто = () => ({ entities: { Q1: { missing: '' } } });",
    "const out = {",
    "  есть: await m.заголовокИзРеестра('ru', 'Q139683849', starFox),",
    "  нет:  await m.заголовокИзРеестра('ru', 'Q139665886', voicemails),",
    "  анг:  await m.заголовокИзРеестра('en', 'Q139665886', voicemails),",
    "  безQID: await m.заголовокИзРеестра('ru', null, starFox),",
    "  неответ: await m.заголовокИзРеестра('ru', 'Q1', пусто),",
    "  ключРавен: m.заголовокКлюч('Star Fox (игра, 2026)') === m.заголовокКлюч('Star Fox'),",
    "  ключРазный: m.заголовокКлюч('Робинсон, Ник') === m.заголовокКлюч('Voicemails for Isabelle'),",
    "  ключЁ: m.заголовокКлюч('Всё о Еве') === m.заголовокКлюч('Все о Еве'),",
    "};",
    "console.log('RESULT ' + JSON.stringify(out));",
  ].join('\n');
  writeFileSync(импортёр, тело + '\n', 'utf8');
  try {
    return execFileSync(process.execPath, [импортёр], {
      env: { ...process.env, NDIM_MODULE: МОДУЛЬ }, encoding: 'utf8',
    });
  } finally {
    rmSync(импортёр, { force: true });
  }
}

test('РЕЕСТР РАЗЛИЧАЕТ ТРИ ОТВЕТА: статья есть · статьи нет · спросить не удалось', () => {
  const r = результат(развилкаРеестраВДочернем());

  /* 1. Ссылка есть → сверяем ИМЕННО эту статью. Живой Star Fox: карточка называется «Star Fox»,
   *    а статья об объекте — «Star Fox (игра, 2026)». Прямой заголовок дал бы ФРАНШИЗУ. */
  assert.deepEqual(r.есть, { есть: true, заголовок: 'Star Fox (игра, 2026)' });

  /* 2. Реестр ОТВЕТИЛ, и русской ссылки нет → статьи не существует. Это честное «НЕ ПРОВЕРЕНО»,
   *    и запасной поиск после такого ответа не зовётся: прежде он подсовывал сюда биографию
   *    «Робинсон, Ник» и печатал ✅ ЧИСТО. */
  assert.deepEqual(r.нет, { есть: false });
  assert.deepEqual(r.анг, { есть: true, заголовок: 'Voicemails for Isabelle' },
    'у той же записи английская статья ЕСТЬ — молчание бывает на одном языке, а не на объекте');

  /* 3. `null` — НЕЗНАНИЕ, а не «статьи нет» (`EXP-0165`). Только оно разрешает запасной путь. */
  assert.equal(r.безQID, null, 'нет идентификатора — реестра не спросили');
  assert.equal(r.неответ, null, 'записи в реестре нет — это незнание, а не ответ «статьи нет»');
});

test('сверка заголовка запасного пути: различитель в скобках снимается, чужое НЕ проходит', () => {
  const r = результат(развилкаРеестраВДочернем());
  assert.equal(r.ключРавен, true, '«Star Fox (игра, 2026)» и «Star Fox» — один заголовок');
  assert.equal(r.ключРазный, false, '«Робинсон, Ник» чужому названию не равен — поиск отвергается');
  assert.equal(r.ключЁ, true, '«ё» и «е» не разводят один заголовок на два');
});

/**
 * Прогоняет ПОРЯДОК ступеней (`статьяОбъекта`) на поддельных шагах и возвращает не только исход,
 * но и ЖУРНАЛ вызовов: какая ступень сработала и с каким заголовком. Без журнала мутация
 * «сверили не с той статьёй» невидима — итог у неё тот же самый.
 */
function порядокСтупенейВДочернем() {
  const импортёр = join(tmpdir(), `ndim-order-probe-${process.pid}.mjs`);
  const тело = [
    "const m = await import(process.env.NDIM_MODULE);",
    "const прогон = async (ответРеестра, естьПрямая, попаданиеПоиска, карточка) => {",
    "  const журнал = [];",
    "  const шаги = {",
    "    реестр: async (l, qid) => { журнал.push('реестр:' + qid); return ответРеестра; },",
    "    страница: async (l, t) => { журнал.push('страница:' + t);",
    "      return (t === карточка.title.ru && !естьПрямая) ? null : { title: t, text: 'текст' }; },",
    "    поиск: async () => { журнал.push('поиск'); return попаданиеПоиска; },",
    "  };",
    "  const итог = await m.статьяОбъекта('ru', карточка, шаги);",
    "  return { журнал, статья: итог && итог.title };",
    "};",
    "const starFox = { wikidata: 'Q139683849', title: { ru: 'Star Fox' } };",
    "const voicemails = { wikidata: 'Q139665886', title: { ru: 'Voicemails for Isabelle' } };",
    "const безQID = { title: { ru: 'Сначала дамы' } };",
    "const out = {",
    "  реестрДал: await прогон({ есть: true, заголовок: 'Star Fox (игра, 2026)' }, true, 'Star Fox', starFox),",
    "  реестрСказалНет: await прогон({ есть: false }, true, 'Робинсон, Ник', voicemails),",
    "  реестрМолчитПрямая: await прогон(null, true, null, безQID),",
    "  реестрМолчитПоискЧужой: await прогон(null, false, 'Прикосновение (фильм, 1992)', безQID),",
    "  реестрМолчитПоискСвой: await прогон(null, false, 'Сначала дамы (фильм, 2026)', безQID),",
    "};",
    "console.log('RESULT ' + JSON.stringify(out));",
  ].join('\n');
  writeFileSync(импортёр, тело + '\n', 'utf8');
  try {
    return execFileSync(process.execPath, [импортёр], {
      env: { ...process.env, NDIM_MODULE: МОДУЛЬ }, encoding: 'utf8',
    });
  } finally {
    rmSync(импортёр, { force: true });
  }
}

test('ПОРЯДОК СТУПЕНЕЙ: реестр ответил «есть» → сверяем ЕГО статью, ниже не спускаемся', () => {
  const r = результат(порядокСтупенейВДочернем());
  /* Живой «Star Fox»: карточка зовётся «Star Fox», статья об объекте — «Star Fox (игра, 2026)».
   * Прямой заголовок дал бы франшизу, и итог остался бы «✅ чисто» — виден только заголовок. */
  assert.equal(r.реестрДал.статья, 'Star Fox (игра, 2026)');
  assert.deepEqual(r.реестрДал.журнал, ['реестр:Q139683849', 'страница:Star Fox (игра, 2026)'],
    'после ответа реестра ни прямой заголовок, ни поиск не зовутся');
});

test('ПОРЯДОК СТУПЕНЕЙ: реестр ответил «ссылки нет» → НЕ ПРОВЕРЕНО, и поиск НЕ зовётся', () => {
  const r = результат(порядокСтупенейВДочернем());
  /* Сердце дефекта `bugs/NEW`: здесь запасной поиск возвращал биографию «Робинсон, Ник»,
   * и карточка без русской статьи получала ✅ ЧИСТО. */
  assert.equal(r.реестрСказалНет.статья, null);
  assert.deepEqual(r.реестрСказалНет.журнал, ['реестр:Q139665886'],
    '«ссылки нет» — это ОТВЕТ, а не незнание: ниже спускаться нельзя');
});

test('ПОРЯДОК СТУПЕНЕЙ: реестр не ответил → прямой заголовок, потом поиск СО СВЕРКОЙ', () => {
  const r = результат(порядокСтупенейВДочернем());

  assert.equal(r.реестрМолчитПрямая.статья, 'Сначала дамы', 'незнание разрешает прямой заголовок');
  assert.deepEqual(r.реестрМолчитПрямая.журнал, ['реестр:undefined', 'страница:Сначала дамы']);

  assert.equal(r.реестрМолчитПоискЧужой.статья, null,
    'чужое попадание поиска отвергается сверкой заголовка');
  assert.ok(r.реестрМолчитПоискЧужой.журнал.includes('поиск'), 'поиск при незнании зовётся');

  assert.equal(r.реестрМолчитПоискСвой.статья, 'Сначала дамы (фильм, 2026)',
    'своё попадание принимается: различитель в скобках сверке не мешает');
});

