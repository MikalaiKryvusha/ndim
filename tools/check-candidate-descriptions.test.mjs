/**
 * Гоняет `проверитьТекст` в дочернем процессе на живых образцах и возвращает списки отказов
 * и замечаний по каждому. Сети здесь нет: набор нарочно вынесен так, чтобы проверяться без неё.
 */
function наборПроверокВДочернем() {
  const импортёр = join(tmpdir(), `ndim-checks-probe-${process.pid}.mjs`);
  const длинный = 'Драма о семье, которая переживает переезд и учится заново разговаривать друг с другом. '.repeat(16);
  const тело = [
    "const m = await import(process.env.NDIM_MODULE);",
    `const ХОРОШИЙ = ${JSON.stringify(длинный)};`,
    "const карточка = { title: { ru: 'Обсессия', en: 'Obsession' }, author: { en: 'Curry Barker' } };",
    "const прогон = (t, lang) => { const r = m.проверитьТекст(t, lang, карточка);",
    "  return { отказы: r.отказы, замечания: r.замечания.map((з) => з.проверка + ': ' + з.текст) }; };",
    "const out = {",
    "  здоровый:   прогон(ХОРОШИЙ, 'ru'),",
    "  зачин:      прогон('«Обсессия» — ' + ХОРОШИЙ, 'ru'),",
    "  авторитет:  прогон('Реестр относит картину к драме. ' + ХОРОШИЙ, 'ru'),",
    "  следПравки: прогон(ХОРОШИЙ + ' Далее следуют показы. ; продюсерами выступили.', 'ru'),",
    "  смешение:   прогон('Стиль восходит к традиции japanese-анимации. ' + ХОРОШИЙ, 'ru'),",
    "  латиница:   прогон('Он называет приём screenlife. ' + ХОРОШИЙ, 'ru'),",
    "  коротко:    прогон('Короткое описание.', 'ru'),",
    "  прозаОтказ: прогон('Production was carried out by Amblin Entertainment. ' + ХОРОШИЙ, 'en'),",
    "  прозаЗамеч: прогон('The score was composed by Hans Zimmer. ' + ХОРОШИЙ, 'en'),",
    "};",
    "console.log('RESULT ' + JSON.stringify(out));",
  ].join('\n');
  writeFileSync(импортёр, тело + '\n', 'utf8');
  try {
    return execFileSync(process.execPath, [импортёр], {
      env: { ...process.env, NDIM_MODULE: МОДУЛЬ }, encoding: 'utf8',
    });
  } finally {
    rmSync(импортёр, { force: true });
  }
}

