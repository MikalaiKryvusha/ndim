/** Самопроверка: список экранов не должен молча терять адреса и опознаватели. */
export function судить(экраны) {
  const беды = [];
  const ids = new Set();
  for (const э of экраны) {
    if (!э.id || ids.has(э.id)) беды.push(`повтор или пустой id: ${э.id}`);
    ids.add(э.id);
    if (!э.адрес?.startsWith('/')) беды.push(`${э.id}: адрес не путь — ${э.адрес}`);
    if (!э.ждать) беды.push(`${э.id}: нет опознавателя «ждать» — кадр может оказаться пустым`);
    if (!э.имя) беды.push(`${э.id}: нет имени для подписи на листе`);
  }
  return беды;
}

