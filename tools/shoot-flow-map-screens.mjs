#!/usr/bin/env node
/**
 * СЪЁМЩИК ЭКРАНОВ ДЛЯ РАЗВЁРТКИ — снимает ЖИВОЕ приложение по одному кадру на экран.
 *
 * ПОВОД — слово владельца 2026-09-05: «*Делай скрин вайринг и макеты экраны на разв[ё]ртке.
 * Хочу посмотреть текущую разв[ё]ртку приложения. Делай в русском языке, в мобильной ориентации
 * развертку*». Развёртка до этого дня была ДЕМОНСТРАЦИОННЫМ КУСКОМ из четырёх экранов на старых
 * кадрах (`design/flow-map/flow-map.json`, «демонстрационный кусок»). Он просит текущую и всю.
 *
 * 🔑 ПОЧЕМУ КАДРЫ СНИМАЮТСЯ, А НЕ БЕРУТСЯ ГОТОВЫЕ. Готовые лежат по всему `test-results/` от
 * разных задач, разных дат и разных ширин. Развёртка из таких кадров показала бы не приложение,
 * а историю съёмок: часть экранов свежая, часть — месячной давности, и отличить одно от другого
 * на листе невозможно. Один прогон = один момент времени.
 *
 * ⛔ ЧЕГО НЕ ДЕЛАЕТ. Не судит вид (это глаз владельца) и не проверяет поведение — только снимает.
 *
 * Запуск:  node tools/shoot-flow-map-screens.mjs [--base http://127.0.0.1:5173]
 *          node tools/shoot-flow-map-screens.mjs --selftest
 * Кадры:   test-results/flow-map-screens/<id>.png (390×900, русский, светлая тема)
 * Коды:    0 — все экраны сняты; 1 — хоть один не открылся.
 */

import { chromium } from 'playwright';
import { mkdirSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

const ЗАПУЩЕН_НАПРЯМУЮ = Boolean(process.argv[1]) && import.meta.url === pathToFileURL(process.argv[1]).href;

const OUT = 'test-results/flow-map-screens';
const Ш = 390;
const В = 900;

/**
 * ЧТО СНИМАЕМ. Порядок — это порядок ПУТИ ЧЕЛОВЕКА, а не порядок файлов в `src/routes`:
 * развёртка отвечает на вопрос «куда он попадает и куда может уйти», и лист читается сверху вниз.
 *
 * `ждать` — селектор, по которому видно, что экран ИМЕННО этот, а не общая оболочка. Без него
 * съёмщик поймал бы кадр загрузки и положил бы на лист пустую карточку, которую никто не отличит
 * от настоящего экрана.
 */
export const ЭКРАНЫ = [
  // ── публичное лицо: сюда приходит незнакомец из поиска
  { id: 'root', имя: 'Главная', адрес: '/', ждать: 'main .showcase', группа: 'публичное' },
  { id: 'landing', имя: 'Лендинг', адрес: '/ru', ждать: 'h1', группа: 'публичное' },
  { id: 'catalog', имя: 'Каталог', адрес: '/ru/catalog', ждать: 'h1', группа: 'публичное' },
  { id: 'hub', имя: 'Хаб вида', адрес: '/ru/catalog/movie', ждать: 'h1', группа: 'публичное' },
  { id: 'dimension', имя: 'Карточка объекта', адрес: '/ru/dimension/donnie-darko-1hqyrh7o', ждать: 'h1', группа: 'публичное' },
  { id: 'tests', имя: 'Тесты', адрес: '/ru/tests', ждать: 'h1', группа: 'публичное' },
  { id: 'about', имя: 'О проекте', адрес: '/ru/menu/about', ждать: 'h1', группа: 'публичное' },

  // ── дверь: стена входа
  { id: 'signin', имя: 'Экран входа', адрес: '/profile?as=none', ждать: '.signin-screen', группа: 'дверь' },

  // ── приложение под гостем
  { id: 'guest-profile', имя: 'Профиль — гость', адрес: '/profile?guest=1', ждать: 'main', группа: 'гость', пауза: 6000 },

  // ── приложение под человеком (стендовый dev-пользователь)
  { id: 'profile', имя: 'Профиль', адрес: '/profile', ждать: 'main', группа: 'приложение' },
  { id: 'dims', имя: 'Измерения', адрес: '/dims', ждать: 'main', группа: 'приложение' },
  { id: 'relations', имя: 'Связи', адрес: '/relations', ждать: 'main', группа: 'приложение' },
  { id: 'space', имя: 'Пространство', адрес: '/space', ждать: 'main', группа: 'приложение' },
  { id: 'menu', имя: 'Меню', адрес: '/menu', ждать: 'main', группа: 'приложение' },
  { id: 'account', имя: 'Управление аккаунтом', адрес: '/account', ждать: 'main', группа: 'приложение' },
];

/** Самопроверка: список экранов не должен молча терять адреса и опознаватели. */
export function судить(экраны) {
  const беды = [];
  const ids = new Set();
  for (const э of экраны) {
    if (!э.id || ids.has(э.id)) беды.push(`повтор или пустой id: ${э.id}`);
    ids.add(э.id);
    if (!э.адрес?.startsWith('/')) беды.push(`${э.id}: адрес не путь — ${э.адрес}`);
    if (!э.ждать) беды.push(`${э.id}: нет опознавателя «ждать» — кадр может оказаться пустым`);
    if (!э.имя) беды.push(`${э.id}: нет имени для подписи на листе`);
  }
  return беды;
}

if (ЗАПУЩЕН_НАПРЯМУЮ && process.argv.includes('--selftest')) {
  const беды = судить(ЭКРАНЫ);
  const порча = судить([{ id: 'a', адрес: 'ru', имя: '', ждать: '' }]);
  console.log(беды.length === 0 ? `  ✅ список из ${ЭКРАНЫ.length} экранов здоров` : `  ❌ ${беды.join(' · ')}`);
  console.log(порча.length >= 3 ? '  ✅ порченый экран краснит все три пункта' : `  ❌ порча дала ${порча.length}`);
  process.exit(беды.length === 0 && порча.length >= 3 ? 0 : 1);
}

if (ЗАПУЩЕН_НАПРЯМУЮ) {
  const i = process.argv.indexOf('--base');
  const БАЗА = (i > -1 ? process.argv[i + 1] : 'http://127.0.0.1:5173').replace(/\/$/, '');
  mkdirSync(OUT, { recursive: true });

  const беды = судить(ЭКРАНЫ);
  if (беды.length) { console.error('✖ список экранов болен: ' + беды.join(' · ')); process.exit(1); }

  const браузер = await chromium.launch();
  let провалов = 0;
  console.log(`Развёртка: снимаю ${ЭКРАНЫ.length} экранов с ${БАЗА} · 390×900 · русский · светлая\n`);

  for (const э of ЭКРАНЫ) {
    const ctx = await браузер.newContext({ viewport: { width: Ш, height: В }, deviceScaleFactor: 2, locale: 'ru-RU' });
    // Язык и тема задаются ДО первого кадра: иначе снимок поймает переключение.
    await ctx.addInitScript(() => {
      try { localStorage.setItem('ndim-lang', 'ru'); localStorage.setItem('ndim-theme', 'light'); } catch (e) { /* приватный режим */ }
    });
    const page = await ctx.newPage();
    try {
      const ответ = await page.goto(БАЗА + э.адрес, { waitUntil: 'domcontentloaded', timeout: 40_000 });
      await page.waitForSelector(э.ждать, { timeout: 30_000 });
      // Гостевые и «вошедшие» экраны догружают данные — даём им дорисоваться.
      await page.waitForTimeout(э.пауза ?? 2600);

      /*
       * 🔑 СТРАНИЦА ОШИБКИ — НЕ ЭКРАН. Первый прогон положил на лист кадр «404 Not found» под
       * подписью «Хаб вида»: адрес был `/ru/catalog/movie/1`, а первая страница хаба живёт без
       * номера. Опознаватель `h1` при этом СРАБОТАЛ — заголовок есть и у страницы ошибки.
       * Развёртка с чужим кадром хуже отсутствия кадра: она выглядит как правда.
       */
      const код = ответ?.status() ?? 0;
      const текст = await page.evaluate(() => document.body.innerText.slice(0, 400));
      if (код >= 400 || /\b404\b|Not found|Страница не найдена/iu.test(текст)) {
        throw new Error(`это страница ошибки, а не экран (код ${код})`);
      }

      await page.screenshot({ path: `${OUT}/${э.id}.png` });
      console.log(`  ✅ ${э.имя.padEnd(24)} ${э.адрес}`);
    } catch (err) {
      console.error(`  ❌ ${э.имя.padEnd(24)} ${э.адрес} — ${String(err.message).split('\n')[0]}`);
      провалов++;
    }
    await ctx.close();
  }

  await браузер.close();
  console.log(провалов ? `\n✖ не снято экранов: ${провалов}` : `\n✅ снято ${ЭКРАНЫ.length} экранов → ${OUT}`);
  process.exit(провалов ? 1 : 0);
}
