/**
 * ТЕСТ ИНСТРУМЕНТА СТАТУС-ДОСКИ (`tools/team-status.mjs`) — и прежде всего его предохранителя
 * «запущен или подключён».
 *
 * 🔴 ПОВОД, И ОН ЗАМЕРЕН, А НЕ ПРЕДПОЛОЖЕН. До предохранителя прибор исполнял свой CLI на
 * ЛЮБОЙ импорт: импортирующий не передаёт команду, чейн уходил в подсказку и звал
 * `process.exit(0)`. Замер 2026-08-29 показал, во что это превращалось в воротах:
 *
 *   тест с ЗАВЕДОМО ЛОЖНЫМ утверждением отчитался «✔ tests 1 · pass 1 · fail 0».
 *
 * Файл умирал ДО первого утверждения, а `node --test` засчитывал его пройденным. То есть доску,
 * которую зовут все пять ролей, нельзя было покрыть юнитом ВООБЩЕ — любой её юнит был бы зелёным
 * независимо от того, что в нём написано. Это не «прибор молчит», это фабрика ложнозелёного.
 *
 * 🔴🔴 ПОЧЕМУ ЭТОТ ФАЙЛ НЕ ИМПОРТИРУЕТ `team-status.mjs` — САМОЕ ВАЖНОЕ РЕШЕНИЕ ЗДЕСЬ.
 * Импортируй он прибор строкой `import`, и при возврате дефекта набор снова умер бы молча и
 * снова засчитался бы пройденным — то есть страж исчез бы ровно в тот момент, ради которого
 * заведён. Поэтому о приборе здесь спрашивают ТОЛЬКО дочерние процессы, а импортируется одна
 * чистая `lib/team-stamp.mjs`. Дочерний процесс волен умирать: его смерть — это наблюдение,
 * а не конец набора.
 *
 * 🔑 ЗАЧЕМ ЭТОТ ФАЙЛ, ЕСЛИ У ПРИБОРА ЕСТЬ `--selftest`. Самотест НЕ СПОСОБЕН поймать
 * собственный незапуск: мутация «предохранитель наоборот» (`if (!ЗАПУЩЕН_НАПРЯМУЮ) main()`)
 * оставляет `--selftest` вообще без вывода — доска мертва у всех пяти ролей, а прогон молчит.
 * Ловится это только снаружи и только в воротах (`EXP-0227`: страж вне ворот не защищает — он
 * ЖДЁТ, пока о нём вспомнят). Вердикт мутации, снятый `tools/lib/mutate.mjs`:
 *   · м1 «предохранителя нет»        → самотест: провалов 1 (случай «ПОДКЛЮЧЁН»);
 *   · м2 «предохранитель наоборот»   → самотест: вывод 0 символов ← ловит только этот файл.
 *
 * Прогон: node --test tools/team-status.test.mjs   (или `npm run test:tools`)
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

import { stampNow } from './lib/team-stamp.mjs';

const ЗДЕСЬ = dirname(fileURLToPath(import.meta.url));
const ДОСКА = join(ЗДЕСЬ, 'team-status.mjs');
const ДОСКА_URL = new URL('./team-status.mjs', import.meta.url).href;

/** Прибор дочерним процессом — абсолютным путём, ровно той формой строки, которой его зовут роли. */
const прогон = (...argv) => spawnSync(process.execPath, [ДОСКА, ...argv], { encoding: 'utf8' });

/* ── Метка времени: одна формула на весь проект ───────────────────────────────────────── */

test('метка несёт канонную форму: YYYY-MM-DD HH:MM ±HH:MM', () => {
  assert.match(stampNow(new Date(2026, 7, 29, 12, 7)), /^2026-08-29 12:07 [+-]\d{2}:\d{2}$/);
});

test('однозначные месяц, день, час и минута дополняются нулём', () => {
  // Без padStart метка стала бы «2026-1-2 3:4» — она попадает в документ, который читают люди.
  assert.match(stampNow(new Date(2026, 0, 2, 3, 4)), /^2026-01-02 03:04 [+-]\d{2}:\d{2}$/);
});

test('без аргумента метка берёт «сейчас», а не падает', () => {
  // Умолчание — единственная форма, которой пользуется сам прибор; проверки часто мимо неё.
  assert.match(stampNow(), /^\d{4}-\d{2}-\d{2} \d{2}:\d{2} [+-]\d{2}:\d{2}$/);
});

/* ── Предохранитель: обе половины, и каждая стережёт МОЛЧАЛИВЫЙ отказ ─────────────────── */

test('🔴 ЗАПУЩЕН: --selftest ОТВЕТИЛ и зелен — ловит инверсию предохранителя (м2)', () => {
  const r = прогон('--selftest');
  assert.notEqual(r.stdout.trim(), '', 'самотест не ответил вовсе: предохранитель отключил прибор');
  assert.match(r.stdout, /✅ самопроверка чиста: (\d+)\/\1/);
  assert.equal(r.status, 0);
});

test('🔴 ЗАПУЩЕН: обе половины предохранителя доказаны САМИМ прибором', () => {
  // Не дублируем случаи, а требуем, чтобы они были на месте и зелены: удалить их молча нельзя.
  const { stdout } = прогон('--selftest');
  assert.match(stdout, /^✅ 🔑 ПОДКЛЮЧЁН: /m);
  assert.match(stdout, /^✅ 🔑 ЗАПУЩЕН: /m);
});

test('🔴 ПОДКЛЮЧЁН: импорт не исполняет CLI и НЕ убивает чужой процесс (м1)', () => {
  const r = spawnSync(process.execPath, [
    '--input-type=module',
    '-e', `await import(${JSON.stringify(ДОСКА_URL)}); console.log('ЖИВ-ПОСЛЕ-ИМПОРТА');`,
  ], { encoding: 'utf8' });
  assert.ok(r.stdout.includes('ЖИВ-ПОСЛЕ-ИМПОРТА'), 'импорт убил чужой процесс — предохранителя нет');
  assert.ok(!r.stdout.includes('команды:'), 'импорт исполнил CLI');
  assert.equal(r.status, 0);
});

/* ── Отказ громкий: подсказка приезжает, код возврата различает случаи ────────────────── */

test('без команды — подсказка и код 0: спросили «как пользоваться», это не ошибка', () => {
  const r = прогон();
  assert.match(r.stdout, /^команды: set /);
  assert.equal(r.status, 0);
});

test('неизвестная команда — подсказка и код 1: отказ честный, а не молчаливый', () => {
  // Роль зовёт доску из скриптов; молчаливый код 0 на опечатке означал бы «строка обновлена».
  const r = прогон('sett', '--free');
  assert.match(r.stdout, /^команды: set /);
  assert.equal(r.status, 1);
});
