/**
 * АУДИТ ГОДОВ КАНДИДАТОВ — сверка поля `year` с ДАТОЙ ПЕРВОГО ВЫХОДА В МИР.
 *
 * 🔴 ПОВОД. До 2026-08-23 мастерская жила по правилу «год берётся по первой дате реестра».
 * Правило было ВЫДУМАНО агентами и приписано владельцу. Его слово дословно: «*это неправильное
 * лживое правило, я его НЕ ЗАДАВАЛ… год по ДАТЕ ПЕРВОГО ВЫХОДА В МИР, ни по каким-то там блять
 * реестрам. Когда показано было впервые — тогда и дата выхода*».
 *
 * Разница не косметическая: у реестра премьеры может НЕ БЫТЬ ВОВСЕ. У «Зловещего свиста» самая
 * ранняя дата `P577` — прокатная, март 2026, тогда как мир увидел картину на фестивале 25
 * сентября 2025 года. Правило по реестру дало бы 2026 — на год мимо.
 *
 * ЧЕМ ЭТОТ ПРИБОР МЕРЯЕТ ВЫХОД В МИР. Тремя независимыми свидетелями, и он печатает все три:
 *   1. `year` карточки — то, что мы поставили;
 *   2. самая ранняя дата реестра `P577` — то, что дало бы старое правило;
 *   3. 🔑 ГОД, НАЗВАННЫЙ САМОЙ СТАТЬЁЙ: заголовок английского раздела («Whistle (2025 film)») и
 *      первая фраза лида («is a 2025 … film»). Люди пишут в лиде год ПЕРВОГО показа, а не
 *      прокатной росписи, поэтому этот свидетель ближе всего к правилу владельца.
 *
 * ⛔ ПРИБОР НИЧЕГО НЕ ПРАВИТ. Он печатает расхождения; решение по каждому — за человеком.
 * Автоправка года по лиду была бы тем же классом, что и выдуманное правило: механизм, решающий
 * за владельца там, где источники спорят.
 *
 * 📐 ПЕРВЫЙ ПРОГОН 2026-08-23, все партии 1–6: сверена 91 карточка, расхождений с годом,
 * который называет статья, — 0. То есть выдуманное правило неверных годов в партиях НЕ оставило.
 * Причина, по которой оно так долго держалось, видна здесь же: у 89 карточек из 91 первая дата
 * реестра И ЕСТЬ первый выход в мир, и только у двух они разошлись («Майкл» — реестр 2025 против
 * 2026, «Зловещий свист» — реестр 2026 против 2025). Правило, совпадающее с истиной в 98 %
 * случаев, не проверяет никто.
 * ⚠️ У восьми карточек третий свидетель молчит («статья —»): своей статьи у объекта нет либо
 * заголовок не несёт года. Там год держится письмом, и прибор об этом говорит вслух.
 *
 * Запуск:
 *   node tools/audit-candidate-years.mjs                       # все партии candidates/batches
 *   node tools/audit-candidate-years.mjs candidates/batches/06_*.json
 */
import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const ПАПКА = 'candidates/batches';
const файлы = process.argv.slice(2).filter((a) => !a.startsWith('--'));
const партии = файлы.length
	? файлы
	: readdirSync(ПАПКА)
			.filter((f) => f.endsWith('.json') && !f.startsWith('99'))
			.map((f) => join(ПАПКА, f));

const пауза = (мс) => new Promise((r) => setTimeout(r, мс));

/** Запрос к вики-API с паузой и повтором: сервис отвечает 429 при частом обращении. */
async function api(url) {
	for (let попытка = 0; попытка < 5; попытка += 1) {
		await пауза(1100);
		const res = await fetch(url, { headers: { 'User-Agent': 'NDimSpace-candidates/1.0' } });
		const text = await res.text();
		if (text.startsWith('{')) return JSON.parse(text);
		await пауза(4000 * (попытка + 1));
	}
	throw new Error(`сервис не отдал JSON: ${url}`);
}

/** Самая ранняя дата `P577` с точностью до дня. */
function самаяРанняяДата(entity) {
	const даты = [];
	for (const c of entity.claims?.P577 ?? []) {
		const v = c.mainsnak?.datavalue?.value;
		if (v?.time && v.precision >= 11) даты.push(v.time.slice(1, 11));
	}
	return даты.sort()[0] ?? null;
}

/**
 * Год, названный САМОЙ СТАТЬЁЙ. Два свидетеля подряд: скобка заголовка и лид.
 * Скобка заголовка надёжнее — её ставят именно чтобы развести одноимённые объекты по году.
 */
function годСтатьи(title, lead) {
	const изЗаголовка = title?.match(/\((?:(\d{4})\s+\w+|\w+,\s*(\d{4}))/u);
	if (изЗаголовка) return изЗаголовка[1] ?? изЗаголовка[2];
	const изЛида = lead?.match(/\bis an?\s+(\d{4})\b/iu) ?? lead?.match(/^\S[^.]{0,200}?\b(19|20)(\d{2})\b/u);
	if (изЛида) return изЛида[1]?.length === 4 ? изЛида[1] : `${изЛида[1]}${изЛида[2]}`;
	return null;
}

const строки = [];
for (const файл of партии) {
	const партия = JSON.parse(readFileSync(файл, 'utf8'));
	for (const карточка of партия.candidates ?? []) {
		const qid = карточка.wikidata;
		const d = await api(
			`https://www.wikidata.org/w/api.php?action=wbgetentities&ids=${qid}&format=json&props=claims|sitelinks`,
		);
		const e = d.entities?.[qid];
		if (!e) { строки.push({ файл, qid, имя: карточка.title?.ru, ошибка: 'нет в реестре' }); continue; }
		const реестр = самаяРанняяДата(e);
		const title = e.sitelinks?.enwiki?.title ?? null;
		let lead = null;
		if (title) {
			const t = await api(
				`https://en.wikipedia.org/w/api.php?action=query&prop=extracts&exintro=1&explaintext=1&format=json&titles=${encodeURIComponent(title)}`,
			);
			lead = Object.values(t.query?.pages ?? {})[0]?.extract ?? null;
		}
		console.log('  … ' + (карточка.title && карточка.title.ru));
		строки.push({
			файл,
			qid,
			имя: карточка.title?.ru,
			наш: карточка.year,
			реестр,
			статья: годСтатьи(title, lead),
			заголовок: title,
		});
	}
}

console.log('\n═══ АУДИТ ГОДОВ: поле карточки против ПЕРВОГО ВЫХОДА В МИР ═══');
console.log('  наш = год в карточке · реестр = самая ранняя дата P577 · статья = год, названный статьёй\n');

const спорные = [];
for (const r of строки) {
	if (r.ошибка) { console.log(`  ⚪ ${r.имя} — ${r.ошибка}`); continue; }
	const реестрГод = r.реестр?.slice(0, 4) ?? '—';
	const расхождение = r.статья && r.статья !== r.наш;
	const флаг = расхождение ? '🔴' : '✅';
	if (расхождение) спорные.push(r);
	console.log(`  ${флаг} ${String(r.имя).padEnd(32)} наш ${r.наш} · реестр ${реестрГод} · статья ${r.статья ?? '—'}`);
}

console.log('\n──────────────────────────────────────────────────────────────');
console.log(`  карточек сверено: ${строки.length} · расхождений с годом статьи: ${спорные.length}`);
if (спорные.length) {
	console.log('\n🔴 РАЗБИРАТЬ ПОИМЁННО (прибор не правит — решает человек):');
	for (const r of спорные) {
		console.log(`  · ${r.имя} (${r.qid}) — у нас ${r.наш}, статья «${r.заголовок}» говорит ${r.статья}`);
		console.log(`    ${r.файл}`);
	}
}
console.log(
	'\n⚠️ ЧЕСТНАЯ ГРАНИЦА: год статьи — свидетель, а не приговор. Совпадение всех трёх не доказывает,\n' +
		'   что первый показ найден: если премьеры нет ни в реестре, ни в лиде, прибор её не увидит.',
);
process.exit(спорные.length ? 1 : 0);
