#!/usr/bin/env node
/**
 * СТРАЖ ФОРМЫ АДРЕСА СТЕНДА — приёмка класса `bugs/NEW_pribor_pishet_v_chuzhoy_stend`.
 *
 * Красное: прибор ПРИСВАИВАЕТ адрес эмулятора ЛИТЕРАЛОМ
 * (`process.env.FIRESTORE_EMULATOR_HOST = '127.0.0.1:8181'`). Такая строка перебивает даже
 * ВЕРНЫЙ адрес, поданный `firebase emulators:exec`, — то есть прибор работает с чужим стендом
 * при ЛЮБОМ запуске, и роль, честно взявшая свой слот, всё равно пишет в соседний.
 * Два таких прибора удалили `dev@ndim.space` со стенда 2026-08-30; разбор — в документе бага.
 *
 * 🔴 ПОЧЕМУ ПРИЗНАК ИМЕННО ТАКОЙ, И ПОЧЕМУ НЕ ШИРЕ. Заказан был признак «литерал адреса в
 * пишущем приборе» — он даёт **90 файлов из 254** и стражем быть не может: красный на
 * девяноста научит команду его обходить. Чтение корпуса (16 из 16) показало, что решает не
 * факт литерала, а его ФОРМА; узкая форма «присвоение литералом» даёт на исправном дереве
 * НОЛЬ и при этом ловит оба настоящих дефекта. Разбор четырёх форм — `lib/stand-address-form.mjs`.
 *
 * ⚠️ ЧЕГО СТРАЖ НЕ ЛОВИТ, названо честно:
 *   · ЗАПАСНОЕ значение (`??=`, `if (!env)`) — их сегодня девять, и они опасны только при
 *     запуске РУКОЙ, мимо `emulators:exec`. Это отдельная работа, а не молчание стража;
 *   · адрес, собранный из переменной или пришедший флагом `--base`, — по построению.
 *
 * ⚠️ ФИКСТУРЫ ИСКЛЮЧАЮТСЯ ИМЕННО (`EXP-0215`): в `*.test.mjs` дефектная строка живёт СТРОКОЙ
 * образца, и судить её наравне с живым кодом значило бы запретить проверять самого стража.
 *
 * Ворота: npm run guards
 *
 * Запуск:
 *   node tools/verify-stand-address-form.mjs
 *   node tools/verify-stand-address-form.mjs --list   # напечатать форму каждого файла корпуса
 */

import { readdirSync, readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

import { формаАдреса, ДЕФЕКТНЫЕ_ФОРМЫ } from './lib/stand-address-form.mjs';

const LIST = process.argv.includes('--list');
/** Корпус: приборы и сервер синхронизации — всё, что может ходить в эмулятор. */
const DIRS = ['tools', 'tools/lib', 'sync-server'];

const строки = [];
for (const dir of DIRS) {
  if (!existsSync(dir)) continue;
  for (const file of readdirSync(dir).filter((f) => f.endsWith('.mjs'))) {
    // Фикстуры несут дефектную строку образцом — исключаются именно, с причиной (EXP-0215).
    if (file.endsWith('.test.mjs')) continue;
    const путь = join(dir, file);
    const форма = формаАдреса(readFileSync(путь, 'utf8'));
    if (форма) строки.push({ путь, форма });
  }
}

const дефектные = строки.filter((s) => ДЕФЕКТНЫЕ_ФОРМЫ.includes(s.форма));

console.log('═══ ФОРМА АДРЕСА СТЕНДА В ПРИБОРАХ ═══');
console.log(`  осмотрено файлов, задающих адрес эмулятора: ${строки.length} · охват: ${DIRS.join(', ')}`);

if (LIST) {
  const порядок = ['присвоение', 'запасное', 'изСлота', 'отказ'];
  for (const форма of порядок) {
    const свои = строки.filter((s) => s.форма === форма);
    console.log(`\n  ${форма} — ${свои.length}`);
    for (const s of свои) console.log(`    · ${s.путь}`);
  }
}

/*
 * 🔴 КОНТРОЛЬ ПРИБОРА ИДЁТ ПЕРВЫМ. Пустой корпус — не «нарушений нет», а «мерить нечего»:
 * страж, чей обход развалился, обязан покраснеть, а не покрасить дерево зелёным.
 */
if (строки.length === 0) {
  console.log('\n❌ КОНТРОЛЬ: ни один файл корпуса не задаёт адрес эмулятора — обход развалился.');
  console.log('   Зелёное здесь означало бы слепоту, а не здоровье.');
  process.exit(1);
}

if (дефектные.length === 0) {
  console.log('\n✅ присвоений адреса эмулятора ЛИТЕРАЛОМ нет');
  process.exit(0);
}

console.log(`\n❌ ПРИСВОЕНИЕ адреса эмулятора ЛИТЕРАЛОМ: ${дефектные.length}`);
for (const s of дефектные) {
  const raw = readFileSync(s.путь, 'utf8').split('\n');
  const i = raw.findIndex((l) => /_EMULATOR_HOST\s*=\s*['"`]/.test(l) && !/\$\{/.test(l));
  console.log(`   · ${s.путь}:${i + 1}`);
  if (i >= 0) console.log(`       ${raw[i].trim()}`);
}
console.log('\n   Лечение: адрес — из портов СВОЕГО рабочего места.');
console.log("   const { slot } = slotOf(basename(корень)); const ports = portsFor(slot);");
console.log('   Разбор класса и четыре формы — bugs/NEW_pribor_pishet_v_chuzhoy_stend.md');
process.exit(1);
