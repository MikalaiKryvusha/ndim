import { writeFileSync } from 'node:fs';

/** Боевой проект и его публичный веб-ключ — те же, что в `src/lib/firebase.ts`. */
const PROJECT = 'ndim-space';
const API_KEY = 'AIzaSyCZsGkY0Lw_OJ35QhRumcD5RzNJUFsAsww';
const OUT = 'src/lib/content/landing-metric.ts';

const url =
  `https://firestore.googleapis.com/v1/projects/${PROJECT}/databases/(default)/documents/` +
  `space/public_metrics?key=${API_KEY}`;

const response = await fetch(url);
if (!response.ok) {
  console.error(`❌ боевой space/public_metrics не прочитан: HTTP ${response.status}`);
  console.error('   Файл НЕ тронут — прежний снимок остаётся в силе (это честнее пустой строки).');
  process.exit(1);
}

const body = await response.json();
const people = Number(body?.fields?.people?.integerValue ?? NaN);
if (!Number.isInteger(people) || people <= 0) {
  console.error('❌ в боевом документе нет годного поля people:', JSON.stringify(body?.fields));
  process.exit(1);
}

