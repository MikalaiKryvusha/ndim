/**
 * Видимый штамп момента. НЕ импортируется из `tools/team-status.mjs`, хотя такая же функция
 * `stampNow` живёт там: у доски нет предохранителя прямого запуска, и импорт выполнил бы её
 * CLI вместе с `process.exit`. Настоящее лечение — вынести штамп в `tools/lib/`, но это
 * правка чужого общего прибора; названа Менеджеру, здесь не делается.
 */
export function stampNow(d = new Date()) {
	const p = (n) => String(n).padStart(2, '0');
	const off = -d.getTimezoneOffset();
	const sign = off >= 0 ? '+' : '-';
	const abs = Math.abs(off);
	return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())} ${p(d.getHours())}:${p(d.getMinutes())} ${sign}${p(Math.floor(abs / 60))}:${p(abs % 60)}`;
}

/**
 * Документы по номеру: { open, closed }.
 *
 * Границу номера держит проверка приставки `NNN_`, а НЕ граница слова: обратный слеш в
 * шаблонной строке однажды уже превратился в символ забоя и ослепил правило (`bugs/218`), и
 * тот же класс поймал сам себя на замере, из которого вырос этот прибор. Обратных слешей
 * здесь нет намеренно — приставка сравнением строк неуязвима к этому классу.
 */
export function findDocs(names, n) {
	const prefix = `${n}_`;
	const mine = names.filter((f) => f.startsWith(prefix) && f.endsWith('.md'));
	return {
		open: mine.filter((f) => !f.includes('_DONE_')),
		closed: mine.filter((f) => f.includes('_DONE_')),
	};
}

/** Имя закрытого документа: `NNN_slug.md` → `NNN_DONE_slug.md`. */
export function closedName(open) {
	const i = open.indexOf('_');
	return `${open.slice(0, i)}_DONE_${open.slice(i + 1)}`;
}

/**
 * НЕОТМЕЧЕННЫЕ КРИТЕРИИ ПРИЁМКИ — перечень, а не «да/нет».
 *
 * ПОЧЕМУ ПРИЗНАК УЗКИЙ, А НЕ «ЛЮБОЙ НЕОТМЕЧЕННЫЙ ЧЕКБОКС». Широкая форма опровергнута замером
 * обратной стороны (2026-08-29, дерево `ndim_integrator` на 57ab8db): из 136 ЗАКРЫТЫХ документов
 * она отбила бы ВОСЕМЬ, и шесть из восьми — законно. Чекбоксы там стоят под «План фикса»
 * (32 строки корпуса) и «Что осталось», то есть под МАРШРУТОМ, который в закрытом документе и
 * обязан остаться историей. Отказ по маршруту требовал бы переписывать историю ради галочки —
 * ровно тот класс, против которого прибор и заведён.
 *
 * Поэтому судится ТОЛЬКО раздел приёмки: заголовок, чей текст несёт «приёмк» («Наблюдаемый
 * критерий приёмки фикса» — 19 строк корпуса, «Приёмка» — 8). Случай `bugs/209` и показал, что
 * доказательства, `PENDING:` и имени мало: критерий 2 там не выполнен и назван прямо в документе.
 *
 * ЧЕСТНАЯ ГРАНИЦА ЗАМЕРА. Ложных красных на сегодняшнем корпусе НОЛЬ (0 из 136 закрытых), но
 * контроль обратной стороны ПУСТ, а не зелён: раздела приёмки нет НИ У ОДНОГО закрытого
 * документа — форма молода, все 27 её строк живут в семи открытых (205–209, 216, 217). Признак
 * доказан на своей стороне (7 из 7 открытых с разделом краснеют верно) и НЕ ОПРОВЕРГНУТ на
 * обратной — мерить пока не на чем. Перемерить, когда закроется первый документ с этим разделом.
 *
 * ⚠️ CRLF снимается явно: корпус `bugs/` лежит в CRLF, а в JS точка НЕ матчит возврат каретки
 * (EXP-0047). Первая редакция ЗАМЕРЩИКА этого правила споткнулась ровно здесь: заголовки не
 * находились вовсе, замер дал честный ноль по всему корпусу и чуть не объявил признак пустым.
 */
export function scanCriteria(text) {
	const out = [];
	let all = 0;
	let section = false;
	let head = null;
	let carry = false; // идёт ли перенос НЕотмеченного критерия
	for (const raw of String(text || '').split('\n')) {
		const line = raw.replace(/\r$/, '');
		const h = line.match(/^#{1,6}\s+(.*)$/);
		if (h) {
			head = h[1];
			if (/при[её]мк/i.test(head)) section = true;
			carry = false;
			continue;
		}
		const inCriteria = Boolean(head) && /при[её]мк/i.test(head);
		const b = line.match(/^\s*[-*]\s+\[([ xX])\]\s*(.*)$/);
		if (b) {
			if (inCriteria) all += 1;
			carry = inCriteria && b[1] === ' ';
			if (carry) out.push(b[2].trim());
			continue;
		}
		/*
		 * Перенос строки критерия. Без склейки перечень обрывался на полуслове («…даёт
		 * **красный») — а перечень существует ровно затем, чтобы человек прочитал ТРЕБОВАНИЕ,
		 * а не его начало. Склеиваем только продолжение с отступом; пустая строка кончает пункт.
		 */
		if (carry && /^\s+\S/.test(line)) out[out.length - 1] += ` ${line.trim()}`;
		else if (!line.trim()) carry = false;
	}
	return { section, all, unchecked: out };
}

/** Тонкая обёртка: перечень НЕотмеченных критериев приёмки. */
export function uncheckedCriteria(text) {
	return scanCriteria(text).unchecked;
}

