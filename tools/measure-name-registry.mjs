export const SNAPSHOT = 'candidates/registry-snapshot.json';
const BATCH_DIR = 'candidates/batches';
const API = 'https://www.wikidata.org/w/api.php';
const UA = { 'User-Agent': 'NDimSpace-agent/1.0 (candidate name audit; https://ndimspace.app)' };
/** Куски по 25 и пауза 2,5 с — назначены наблюдением `429`, а не вкусом (разведка §4.1). */
const КУСОК = 25;
const ПАУЗА_МС = 2500;
const ПОПЫТОК = 5;
/** Снимок старше этого — гипотеза, а не факт. То же правило, что у досье окружения. */
export const СРОК_ГОДНОСТИ_ДНЕЙ = 30;

/** Все партии кандидатов из репозитория. Тестовая запись `99_` в замер не идёт. */
export function файлыПартий() {
  if (!existsSync(BATCH_DIR)) return [];
  return readdirSync(BATCH_DIR)
    .filter((f) => f.endsWith('.json') && !f.startsWith('99_'))
    .sort()
    .map((f) => `${BATCH_DIR}/${f}`);
}

/** Читает файл партии в единый вид. Записи без идентификатора реестра сверять не с чем. */
export function прочитатьКарточки(json, откуда = '') {
  const d = JSON.parse(json);
  const arr = Array.isArray(d) ? d : (d.candidates ?? Object.values(d).find(Array.isArray) ?? []);
  return arr.filter((x) => x && x.description).map((x) => ({
    qid: x.wikidata ?? null,
    title: x.title?.ru ?? x.title?.en ?? '?',
    description: x.description,
    agentNote: x.agentNote ?? '',
    свои: [x.title?.ru, x.title?.en, x.author?.ru, x.author?.en].filter(Boolean),
    откуда,
  }));
}

// ═══════════════════════ СНЯТИЕ СНИМКА — единственное место, где есть сеть ═══════════════════

const пауза = (мс) => new Promise((r) => { setTimeout(r, мс); });

async function спросить(ids, props) {
  const собрано = {};
  for (let i = 0; i < ids.length; i += КУСОК) {
    const кусок = ids.slice(i, i + КУСОК);
    let получен = false;
    for (let попытка = 1; попытка <= ПОПЫТОК && !получен; попытка += 1) {
      const url = `${API}?action=wbgetentities&ids=${кусок.join('|')}&props=${props}&format=json`;
      let ответ = null;
      try { ответ = await fetch(url, { headers: UA }); } catch (e) { console.error(`   сеть: ${e.message}`); }
      if (ответ?.ok) { Object.assign(собрано, (await ответ.json()).entities ?? {}); получен = true; break; }
      console.error(`   ${ответ ? `HTTP ${ответ.status}` : 'нет ответа'} · попытка ${попытка}/${ПОПЫТОК}`);
      await пауза(ПАУЗА_МС * попытка);
    }
    await пауза(ПАУЗА_МС);
  }
  return собрано;
}

/**
 * Снимает реестр по всем идентификаторам партий и пишет файл — ЦЕЛИКОМ или никак.
 * В снимке лежит не сырой ответ, а только нужное: состояние каждого именного свойства по обоим
 * языкам. Так снимок читается глазами, не растёт мегабайтами и не тащит в git чужую разметку.
 */
export async function снятьСнимок(карточки) {
  const qids = [...new Set(карточки.map((c) => c.qid).filter(Boolean))];
  console.log(`── снятие: карточек ${карточки.length}, идентификаторов ${qids.length}`);
  const сущности = await спросить(qids, 'claims|labels|sitelinks');
  const нехватка = qids.filter((q) => !сущности[q]);
  if (нехватка.length) {
    console.error(`\n❌ реестр не отдал ${нехватка.length} записей: ${нехватка.slice(0, 8).join(', ')}`);
    console.error('   Снимок НЕ записан: неполный ответ сети — это не молчание реестра (EXP-0165).');
    return null;
  }

  const ссылки = new Set();
  for (const e of Object.values(сущности)) {
    for (const p of NAME_PROPS) {
      for (const s of (e.claims?.[p] ?? [])) {
        if (s?.mainsnak?.snaktype === 'value' && s.mainsnak.datavalue?.value?.id) ссылки.add(s.mainsnak.datavalue.value.id);
      }
    }
  }
  console.log(`── разрешаю ${ссылки.size} ссылок в имена`);
  const referents = await спросить([...ссылки], 'labels|sitelinks');
  const неразрешено = [...ссылки].filter((q) => !referents[q]);
  if (неразрешено.length) {
    console.error(`\n❌ не разрешено ${неразрешено.length} ссылок: ${неразрешено.slice(0, 8).join(', ')}`);
    console.error('   Снимок НЕ записан: недоразрешённая ссылка читалась бы как «имени нет».');
    return null;
  }

  const записи = {};
  for (const qid of qids.sort()) {
    записи[qid] = {
      имя: entityLabels(сущности[qid], 'ru')[0] ?? entityLabels(сущности[qid], 'en')[0] ?? qid,
      ru: свернуть(registryState(сущности[qid], referents, 'ru')),
      en: свернуть(registryState(сущности[qid], referents, 'en')),
    };
  }
  return {
    'ЧТО ЭТО': 'Снимок реестра Wikidata по карточкам мастерской: состояние именных свойств.',
    'КЕМ СНЯТ': 'node tools/measure-name-registry.mjs --refresh',
    'СНЯТ': новаяДата(),
    'УСТАРЕВАНИЕ': `снимок старше ${СРОК_ГОДНОСТИ_ДНЕЙ} дней — ГИПОТЕЗА, а не факт: реестр правят люди`
      + ' каждый день. Перед опорой пересними. Живой случай движения — researches/65_registry_as_name_source.md §5.',
    'ЧЕГО ЗДЕСЬ НЕТ': 'сырого ответа API и текстов Википедии — только имена по ролям и вид молчания.',
    записи,
  };
}

/** Дата снятия. Берётся ОДИН раз и кладётся в шапку — в сравниваемый вывод она не попадает. */
const новаяДата = () => new Date().toISOString().slice(0, 10);

/**
 * Свёртка состояния в снимок. Свойства со видом `нет-свойства` НЕ пишутся вовсе: это умолчание,
 * и `изСнимка` возвращает его само. Иначе снимок наполовину состоял бы из повторяющегося «нет»
 * (243 КБ против 78 КБ на тех же 68 записях), а глазами такой файл не читается.
 * ⚠️ Умолчание безопасно ровно потому, что оно СОВПАДАЕТ с самым безобидным видом молчания:
 * потерянный ключ читается как «реестр роли не знает», то есть карточку не обвиняет.
 */
const свернуть = (состояние) => Object.fromEntries(
  NAME_PROPS
    .filter((p) => состояние[p].вид !== 'нет-свойства')
    .map((p) => [p, { вид: состояние[p].вид, имена: состояние[p].имена }]),
);

/** Разворот снимка обратно в состояние, которое понимает ядро. */
export function изСнимка(снимок, qid, lang) {
  const з = снимок?.записи?.[qid];
  if (!з || !з[lang]) return null;
  return Object.fromEntries(NAME_PROPS.map((p) => [p, з[lang][p] ?? { вид: 'нет-свойства', имена: [] }]));
}

/** Возраст снимка в днях — для строки устаревания. `null`, если даты нет. */
export function возрастСнимка(снимок, сегодня = new Date()) {
  const d = снимок?.СНЯТ;
  if (!d) return null;
  return Math.floor((сегодня - new Date(`${d}T00:00:00Z`)) / 86400000);
}

