/**
 * ЮНИТЫ СЪЁМЩИКА РАЗВЁРТКИ (`tools/shoot-flow-map-screens.mjs`).
 *
 * 🔴 ГЛАВНОЕ ЗДЕСЬ — ДВА СПОСОБА ПОЛОЖИТЬ НА ЛИСТ ЛОЖЬ, оба уже случились в первых прогонах:
 *   1. кадр СТРАНИЦЫ ОШИБКИ под подписью настоящего экрана — адрес был `/ru/catalog/movie/1`,
 *      а первая страница хаба живёт без номера; опознаватель `h1` при этом честно сработал,
 *      потому что заголовок есть и у страницы 404;
 *   2. кадр ЧУЖОГО ЭКРАНА под подписью нужного — `/admin/dims` под не-админом молча уводит на
 *      главную (условие владельца, интервью №015 В1 = Б), и на лист легла главная с подписью
 *      «Админ — измерения».
 * Оба кадра НАСТОЯЩИЕ. Развёртка с настоящим кадром и лживой подписью хуже дырки: дырку видно,
 * а ложь выглядит как правда. Поэтому оба случая закреплены здесь.
 *
 * Прогон: node --test tools/shoot-flow-map-screens.test.mjs   ·   npm run test:tools
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

import { ЭКРАНЫ, судить } from './shoot-flow-map-screens.mjs';

const СЪЁМЩИК = 'tools/shoot-flow-map-screens.mjs';

test('САМОТЕСТ съёмщика зовётся отсюда и обязан быть зелёным', () => {
  const r = spawnSync(process.execPath, [join(process.cwd(), СЪЁМЩИК), '--selftest'], { encoding: 'utf8' });
  const вывод = (r.stdout ?? '') + (r.stderr ?? '');
  assert.equal(r.status, 0, `самотест упал:\n${вывод}`);
  assert.match(вывод, /экранов здоров/u);
});

test('список экранов здоров: без повторов, с адресами и опознавателями', () => {
  assert.deepEqual(судить(ЭКРАНЫ), []);
  assert.ok(ЭКРАНЫ.length >= 30, `экранов ${ЭКРАНЫ.length} — развёртка снова стала куском`);
});

test('порченый экран краснит КАЖДЫМ пунктом, а не одним общим', () => {
  const беды = судить([{ id: 'x', адрес: 'ru', имя: '', ждать: '' }]);
  assert.ok(беды.some((b) => /адрес не путь/u.test(b)));
  assert.ok(беды.some((b) => /опознавател/u.test(b)));
  assert.ok(беды.some((b) => /нет имени/u.test(b)));
});

test('повтор id ловится: два экрана под одним именем файла затёрли бы друг друга', () => {
  const беды = судить([
    { id: 'x', адрес: '/a', имя: 'А', ждать: 'main' },
    { id: 'x', адрес: '/b', имя: 'Б', ждать: 'main' },
  ]);
  assert.ok(беды.some((b) => /повтор/u.test(b)));
});

test('🔑 съёмщик отвергает страницу ошибки и молчаливый увод — оба случая уже случались', () => {
  // Проверки живут внутри боевого цикла (им нужен браузер), поэтому здесь закрепляется САМ ФАКТ
  // их существования: удаление любой из них — тихий возврат лжи на лист.
  const src = readFileSync(join(process.cwd(), СЪЁМЩИК), 'utf8');
  assert.match(src, /это страница ошибки, а не экран/u, 'проверка страницы ошибки снята');
  assert.match(src, /увело на \$\{пришли\}/u, 'проверка «приехали не туда» снята');
  assert.match(src, /ошибкаОК/u, 'нет способа снять страницу 404 НАРОЧНО — а она тоже экран продукта');
});

test('страница 404 стоит на листе как экран продукта, а не как случайность', () => {
  const четыреста = ЭКРАНЫ.find((э) => э.ошибкаОК);
  assert.ok(четыреста, 'экран 404 пропал из развёртки');
  assert.equal(четыреста.id, 'notfound');
});

test('состояния, в которые входят действием, на листе есть', () => {
  // Без них развёртка показывала бы приложение вдвое меньшим, чем оно есть, — ровно то,
  // что владелец и заметил про первую версию листа.
  const сШагами = ЭКРАНЫ.filter((э) => э.шаги?.length);
  assert.ok(сШагами.length >= 3, `состояний с шагами ${сШагами.length}, ожидалось не меньше трёх`);
  for (const э of сШагами) {
    for (const шаг of э.шаги) {
      assert.ok(шаг.клик || шаг.ввод, `${э.id}: шаг ничего не делает`);
    }
  }
});
