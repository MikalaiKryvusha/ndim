/**
 * СТРАЖ КЛАССА «`exit()` ПОСЛЕ `fetch`» — приборы консолей поисковиков завершаются кодом,
 * а не выстрелом. Статический: читает исходники, сети не касается.
 *
 * Прогон: node --test tools/exit-after-fetch.test.mjs   ·   npm run test:tools
 *
 * ── ЗАЧЕМ ЭТОТ СТРАЖ СУЩЕСТВУЕТ ────────────────────────────────────────────────────────────
 * `process.exit()` при живом сетевом сокете роняет процесс на Windows
 * (`Assertion failed: !(handle->flags & UV_HANDLE_CLOSING)`) и отдаёт **код 127 вместо 1**:
 * прибор печатает правильный отказ, а вызывающий, судящий по коду, видит бессмыслицу. Механизм
 * и цена — в шапке `tools/lib/exit-code.mjs`.
 * Судья QA назвал состояние до этого стража точно: два прибора держались «*везением, а не
 * устройством*» (срез суда №4 по «Зрение» Ф2, пункт 3 неотсуженного). Везение теперь заменено
 * устройством: общий хвост `settleExit` плюс эта проверка В ВОРОТАХ `npm run test:tools`,
 * а не рядом с ними.
 *
 * ── 🔴 ГРАНИЦА КОРПУСА, И ОНА ЗАМЕРЕНА, А НЕ ОБЪЯВЛЕНА ─────────────────────────────────────
 * Первая редакция признака звучала шире — «прибор ходит в сеть → `process.exit()` запрещён».
 * Замер по живому корпусу её опроверг. Метод назван, чтобы число можно было перевывести:
 * корпус — `tools/*.mjs` без `*.test.mjs` и `*.mutation.mjs` (**196** файлов на `3fd94fd`),
 * признак сети — прямой `fetch(`/`connectOverCDP` либо импорт сетевой библиотеки консолей,
 * `process.exit(` считается ТОЛЬКО в коде (комментарии и строки сняты). Числа: сетевых — **72**,
 * из них зовут `process.exit()` — **59**. Правило в этой ширине покрасило бы красным
 * исправный корпус чужих ролей — это вопрос 2 «Лестницы трёх вопросов» (`AGENT_GUIDE.md`):
 * ложное срабатывание признака, лечится замером ДО объявления, а не ослаблением правила.
 * Поэтому корпус — ПОИМЁННЫЙ и узкий: приборы, говорящие HTTP с консолями поисковиков. Там
 * класс доказан прогоном (`indexnow-submit`, код 127), в остальных местах он НЕ доказан, и
 * объявлять его там было бы гипотезой, выданной за находку.
 * ⚠️ Браузерные приборы (CDP) сюда НЕ входят намеренно: они закрывают соединение явно
 * (`browser.close()`) до всякого `exit()`, то есть механизм у них другой. Пример —
 * `tools/console-coverage.mjs`.
 *
 * ── ПОЧЕМУ КОРПУС ПОИМЁННЫЙ, А НЕ ВЫВЕДЕННЫЙ ГРЕПОМ ────────────────────────────────────────
 * Урок `EXP-0215`, вторая половина: у стража, который САМ НАБИРАЕТ СЕБЕ КОРПУС, мутация «снять
 * признак» роняет прибор ИЗ корпуса — страж зеленеет, а судить ему стало нечего. Поимённый
 * список мутации не подвластен и сам себе пол: исчезнувшее имя краснеет проверкой 1.
 * Дрейф ловит проверка 3 — новый прибор консолей, не вписанный в список.
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readdirSync, readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const TOOLS = 'tools';

/**
 * Приборы, говорящие HTTP с консолями поисковиков. Список — ПОЛ корпуса: пропавшее имя обязано
 * покраснеть, а не тихо уменьшить число осмотренных.
 */
const HTTP_CONSOLE_TOOLS = [
	'probe-search-console.mjs', // проба доступа Google Search Console
	'console-snapshot.mjs', // снимок ряда Google Search Console
	'yandex-snapshot.mjs', // снимок Яндекс.Вебмастера
	'bing-snapshot.mjs', // снимок Bing Webmaster
	'indexnow-submit.mjs', // подача адресов в IndexNow (здесь класс и пойман прогоном)
	'yandex-recrawl.mjs', // машинная подача переобхода — ПОЙМАН ЭТИМ СТРАЖЕМ в день своего рождения
];

/** Библиотеки, через которые эти приборы ходят в сеть. По ним же ловится дрейф. */
const HTTP_CONSOLE_LIBS = [
	'lib/console-auth.mjs',
	'lib/bing-webmaster.mjs',
	'lib/yandex-webmaster.mjs',
	'lib/indexnow.mjs',
];

/**
 * Имена, законно импортирующие сетевую библиотеку БЕЗ сетевого хвоста, — каждое с причиной.
 * Молчаливого списка исключений здесь нет по решению: он растёт, и через месяц страж судит
 * пустоту (`EXP-0215`).
 */
const NOT_NETWORK = new Map([
	['indexnow-key.mjs', 'генерирует и кладёт файл ключа на диск; в сеть не ходит (0 вызовов fetch)'],
]);

const read = (file) => readFileSync(join(TOOLS, file), 'utf8');
const callsExit = (source) => /process\.exit\s*\(/.test(stripComments(source));

/**
 * Убрать комментарии и строковые литералы: `process.exit()`, упомянутый в объяснении класса,
 * — это ТЕКСТ О дефекте, а не дефект. Без этого страж краснел бы на собственной документации
 * (фикстуры в своём же корпусе — первая половина `EXP-0215`).
 */
function stripComments(source) {
	return source
		.replace(/\/\*[\s\S]*?\*\//g, ' ')
		.replace(/(^|[^:])\/\/[^\n]*/g, '$1 ')
		.replace(/`(?:[^`\\]|\\[\s\S])*`/g, '``')
		.replace(/'(?:[^'\\\n]|\\.)*'/g, "''")
		.replace(/"(?:[^"\\\n]|\\.)*"/g, '""');
}

// ── 1. ПОЛ КОРПУСА ───────────────────────────────────────────────────────────────────────────

test('корпус не пуст и каждое имя списка лежит на диске', () => {
	assert.ok(HTTP_CONSOLE_TOOLS.length >= 6, 'корпус усох — приборы консолей не могли исчезнуть');
	for (const file of HTTP_CONSOLE_TOOLS) {
		assert.ok(
			existsSync(join(TOOLS, file)),
			`${file} назван в корпусе, но его нет на диске — переименован или удалён молча`,
		);
	}
});

// ── 2. САМО ПРАВИЛО ──────────────────────────────────────────────────────────────────────────

test('ни один прибор консолей не зовёт process.exit()', () => {
	const guilty = HTTP_CONSOLE_TOOLS.filter((file) => callsExit(read(file)));
	assert.deepEqual(
		guilty,
		[],
		`process.exit() при живом сокете отдаёт код 127 вместо честного: ${guilty.join(', ')}. ` +
			'Хвост берётся из tools/lib/exit-code.mjs — settleExit(main(...)).',
	);
});

test('каждый прибор консолей завершается общим хвостом settleExit', () => {
	for (const file of HTTP_CONSOLE_TOOLS) {
		const source = read(file);
		assert.match(
			source,
			/import \{ settleExit \} from '\.\/lib\/exit-code\.mjs';/,
			`${file} не импортирует общий хвост`,
		);
		assert.match(
			source,
			/settleExit\(\s*main\(/,
			`${file} не отдаёт свой main() в settleExit — код возврата поедет мимо устройства`,
		);
	}
});

// ── 3. ДРЕЙФ: НОВЫЙ ПРИБОР КОНСОЛЕЙ ОБЯЗАН ВОЙТИ В КОРПУС ────────────────────────────────────

test('новый прибор, ходящий в консоли по HTTP, не проедет мимо списка', () => {
	const named = new Set(HTTP_CONSOLE_TOOLS);
	const strays = [];
	for (const file of readdirSync(TOOLS)) {
		if (!file.endsWith('.mjs')) continue;
		// Проверки и оснастка мутаций живут в том же каталоге и по признакам неотличимы от
		// приборов — они судят материал, а не производят его (`EXP-0215`, первая половина).
		if (file.endsWith('.test.mjs') || file.endsWith('.mutation.mjs')) continue;
		if (named.has(file) || NOT_NETWORK.has(file)) continue;
		const source = read(file);
		if (HTTP_CONSOLE_LIBS.some((lib) => source.includes(lib))) strays.push(file);
	}
	assert.deepEqual(
		strays,
		[],
		`прибор консолей вне корпуса: ${strays.join(', ')} — впиши имя в HTTP_CONSOLE_TOOLS ` +
			'(или в NOT_NETWORK с причиной, если он в сеть не ходит)',
	);
});
