/**
 * ЮНИТЫ СТРАЖА ТЕКСТА ЛИЦА ПРОДУКТА (`tools/guard-product-copy.mjs`).
 *
 * 🔴 ПОВОД — слово владельца 2026-09-05, дословно: «*страж текста не судит макеты — ты
 * понимаешь, какое это вопиющее безответственное распиздяйство? Ты приносишь мне на вычитку
 * макеты, которые написаны не моим языком*».
 *
 * Он назвал одну дыру, нашлись три: зона кончалась на `src/` · форма «можно без …» не ловилась ·
 * и САМ СТРАЖ НЕ СТОЯЛ НИ В КАКИХ ВОРОТАХ, стоя при этом красным на боевой двери. Здесь
 * закрепляются все три, плюс те границы, без которых прибор врёт и его выключают в первый день.
 *
 * Прогон: node --test tools/guard-product-copy.test.mjs   ·   npm run test:tools
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

import { judge, mockupLines, stripInvisible } from './guard-product-copy.mjs';

const СТРАЖ = 'tools/guard-product-copy.mjs';

test('САМОТЕСТ стража зовётся отсюда и обязан быть зелёным', () => {
	const r = spawnSync(process.execPath, [join(process.cwd(), СТРАЖ), '--selftest'], { encoding: 'utf8' });
	const вывод = (r.stdout ?? '') + (r.stderr ?? '');
	assert.equal(r.status, 0, `самотест упал:\n${вывод}`);
	assert.match(вывод, /самотест пройден/u);
});

test('🔑 страж СТОИТ В ВОРОТАХ — снятие его из состава обязано ломать этот тест', () => {
	// Прибор, которого не зовут, — не защита, а мнение файла о себе. Ровно так он и простоял
	// красным на боевой двери: две улики, и никто о них не знал.
	const ворота = readFileSync(join(process.cwd(), 'tools/guards.mjs'), 'utf8');
	assert.match(ворота, /guard-product-copy\.mjs/u, 'страж выпал из состава ворот');
});

test('оправдание «можно без …» ловится, а его собственные слова — нет', () => {
	// Его слово: «Смотреть можно без аккаунта.» — «это ОПРАВДАНИЕ. я миллиард раз говорил тебе
	// не писать такое». Форма разрешает то, чего продукт и не думал требовать.
	assert.ok(judge('Смотреть можно без аккаунта.').some((h) => h.rule === 'З1-разрешение'));
	assert.ok(judge('Регистрация не обязательна').some((h) => h.rule === 'З1-разрешение'));
	assert.ok(judge('ничего не придётся начинать заново').some((h) => h.rule === 'З1-разрешение'));

	// 🔴 ГРАНИЦА: «без регистрации» — ЕГО СОБСТВЕННЫЕ слова на гостевой кнопке (2026-09-04).
	// Прибор, красный на тексте хозяина, выключают в первый день.
	assert.deepEqual(
		judge('Войти в Пространство NDim Space гостем без регистрации').filter((h) => h.rule === 'З1-разрешение'),
		[],
	);
});

test('«напротив» судится как СОЮЗ, а не как предлог места', () => {
	// Ложный красный первой редакции: «установите звёзды напротив измерений» — предлог.
	assert.deepEqual(judge('установите звёзды напротив измерений').filter((h) => h.rule === 'З2-союзы'), []);
	assert.ok(judge('Напротив, оценка останется Вашей').some((h) => h.rule === 'З2-союзы'));
});

test('★ и ☆ — канон шкалы 1.x, а не эмодзи', () => {
	// Первая редакция второй зоны насчитала 1337 «улик», в основном на его собственной шкале.
	assert.deepEqual(judge('★★★★★★★☆☆☆ 7').filter((h) => h.rule === 'эмодзи'), []);
	assert.ok(judge('💾 Всё останется Вашим').some((h) => h.rule === 'эмодзи'));
});

test('в макете судится ПОВЕРХНОСТЬ ПРОДУКТА, а пояснения агента идут отчётом', () => {
	const макет = [
		'<div class="door">',
		'  <p>Смотреть можно без аккаунта.</p>',
		'</div>',
		'<div class="note">Смотреть можно без аккаунта — так написано в макете.</div>',
	].join('\n');
	const строки = mockupLines(макет);
	const внутри = строки.filter((s) => s.onDoor && judge(s.text).length);
	const снаружи = строки.filter((s) => !s.onDoor && judge(s.text).length);
	assert.equal(внутри.length, 1, 'улика внутри двери макета обязана считаться дверью');
	assert.equal(снаружи.length, 1, 'пояснение агента дверью считаться НЕ обязано');
});

test('стили, скрипты и комментарии макета не судятся, а номера строк переживают вырезание', () => {
	const src = '<style>\n.a{можно без аккаунта}\n</style>\n<div class="door"><p>чисто</p></div>';
	const очищено = stripInvisible(src);
	assert.doesNotMatch(очищено, /можно без/u);
	assert.equal(src.split('\n').length, очищено.split('\n').length,
		'номера строк обязаны сохраниться — иначе красный покажет не на ту строку');
});
