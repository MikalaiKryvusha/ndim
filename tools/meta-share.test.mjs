/*
 * ═══ ВТОРАЯ ЦЕЛЬ ПРАВКИ: НЕ УХУДШИТЬ ПРОПОРЦИЮ (`bugs/180`) ═══
 *
 * 🔴 ПОВОД. У правки описания была ОДНА цель — сбить дословный ряд с Википедией, и «зелёный
 * прогон» это скрывал: первое предложение статьи почти всегда про производство, поэтому правка
 * брала мету и переписывала мету, а иногда дописывала её.
 *
 * 🔴🔴 ГЛАВНАЯ ПАРА ЗДЕСЬ — НЕ «УХУДШЕНИЕ ПОЙМАНО», А «СЖАТЫЙ ЗНАМЕНАТЕЛЬ НЕ ЗАПЕРТ». Проверка
 * «ухудшение поймано» одна была бы зелёной и на грубом правиле «доля выросла — отказ», а такое
 * правило заворачивает правку, которая слила два предложения содержания в одно, НЕ ДОБАВИВ ни
 * одного производственного слова. Замер 364 живых правок: доля выросла у 23, из них ЧИСЛО меты
 * выросло у 20; оставшиеся три — сжатый знаменатель. Различает эти поведения только пара, поэтому
 * случаи стоят рядом и порознь не имеют смысла.
 */

/** Описание собирается из предложений, чтобы в случае было видно, ЧТО именно поменялось. */
const описание = (...предложения) => предложения.join(' ');

const СЮЖЕТ_1 = 'Анна бросает привычную жизнь и едет через всю страну на велосипеде.';
const СЮЖЕТ_2 = 'По дороге она встречает случайных попутчиков и обретает уверенность в себе.';
const СЮЖЕТ_3 = 'Финал сводит её с матерью после тринадцати лет молчания.';
const ПРОИЗВОДСТВО = 'Съёмки картины проходили в Магадане, продюсировал ленту Иван Петров.';

test('🔴 правка, ДОПИСАВШАЯ производство, названа ухудшением', () => {
  const было = описание(СЮЖЕТ_1, СЮЖЕТ_2, СЮЖЕТ_3);
  const стало = описание(СЮЖЕТ_1, СЮЖЕТ_2, СЮЖЕТ_3, ПРОИЗВОДСТВО);

  const d = metaDelta(было, стало, 'ru', splitSentences);
  assert.equal(d.метаВыросла, true, 'дописанное производство не опознано');
  assert.equal(d.приростМеты, 1);
});

test('🔴 сжатый ЗНАМЕНАТЕЛЬ ухудшением НЕ считается — производства не прибавилось', () => {
  const было = описание(СЮЖЕТ_1, СЮЖЕТ_2, СЮЖЕТ_3, ПРОИЗВОДСТВО);
  // Два предложения содержания слились в одно: смысл тот же, предложений на одно меньше.
  const стало = описание(
    'Анна бросает привычную жизнь и едет через всю страну на велосипеде, встречая по дороге случайных попутчиков и обретая уверенность в себе.',
    СЮЖЕТ_3,
    ПРОИЗВОДСТВО,
  );

  const d = metaDelta(было, стало, 'ru', splitSentences);
  assert.equal(d.доляВыросла, true, 'доля обязана вырасти — знаменатель сжался');
  assert.equal(d.метаВыросла, false, 'сжатие содержания принято за дописанное производство');
});

test('правка, УБРАВШАЯ производство, ухудшением не считается', () => {
  const было = описание(СЮЖЕТ_1, СЮЖЕТ_2, ПРОИЗВОДСТВО);
  const стало = описание(СЮЖЕТ_1, СЮЖЕТ_2, СЮЖЕТ_3);

  const d = metaDelta(было, стало, 'ru', splitSentences);
  assert.equal(d.метаВыросла, false);
  assert.equal(d.доляВыросла, false);
});

test('🔴 ДВЕРЬ запирает дописанное производство и НЕ запирает сжатый знаменатель', () => {
  const было = описание(СЮЖЕТ_1, СЮЖЕТ_2, СЮЖЕТ_3);
  const дописано = описание(СЮЖЕТ_1, СЮЖЕТ_2, СЮЖЕТ_3, ПРОИЗВОДСТВО);

  const беды = checkEdit({ slug: 'x-1', lang: 'ru', before: было, after: дописано, replace: ПРОИЗВОДСТВО });
  assert.ok(
    беды.some((b) => /добавила производства/.test(b)),
    `дверь пропустила дописанное производство: ${JSON.stringify(беды)}`,
  );

  /*
   * ⚠️ У ЭТОЙ ПОЛОВИНЫ СВОЯ ПАРА «до/после», И ЭТО НЕ НЕБРЕЖНОСТЬ. Сперва я взял здесь ту же
   * `было`, где производства нет вовсе, — и случай был зелёным по НЕВЕРНОЙ причине: доля 0 % → 0 %
   * не может вырасти, значит ни одно правило тут не срабатывало и проверять было нечего. Поймала
   * это мутация М7 (судить по ДОЛЕ вместо ШТУК): её контроль по смыслу не сдвинулся. Чтобы
   * случай стерёг решение, знаменатель обязан сжиматься ПРИ ЖИВОЙ мете: 1 из 4 → 1 из 3.
   */
  const былоСМетой = описание(СЮЖЕТ_1, СЮЖЕТ_2, СЮЖЕТ_3, ПРОИЗВОДСТВО);
  const слито = описание(
    'Анна бросает привычную жизнь и едет через всю страну на велосипеде, встречая по дороге случайных попутчиков.',
    СЮЖЕТ_3,
    ПРОИЗВОДСТВО,
  );
  const беды2 = checkEdit({ slug: 'x-2', lang: 'ru', before: былоСМетой, after: слито, replace: слито });
  assert.equal(
    беды2.filter((b) => /добавила производства/.test(b)).length,
    0,
    `дверь заперла сжатый знаменатель — это ложный отказ: ${JSON.stringify(беды2)}`,
  );
});

test('унаследованная плохая пропорция правку НЕ запирает — судится прирост, а не наличие', () => {
  // Пропорция скверная и ДО, и ПОСЛЕ: правка её не трогала, значит и не виновата.
  const было = описание(ПРОИЗВОДСТВО, 'Картину снимала студия в 2023 году, бюджет составил миллион.', СЮЖЕТ_1);
  const стало = описание(ПРОИЗВОДСТВО, 'Картину снимала студия в 2023 году, бюджет составил миллион.', СЮЖЕТ_2);

  const d = metaDelta(было, стало, 'ru', splitSentences);
  assert.equal(d.метаВыросла, false, 'наследованная мета засчитана как прирост');
  const беды = checkEdit({ slug: 'x-3', lang: 'ru', before: было, after: стало, replace: СЮЖЕТ_2 });
  assert.equal(
    беды.filter((b) => /добавила производства/.test(b)).length,
    0,
    'правка заперта за пропорцию, которую она унаследовала, а не создала',
  );
});
