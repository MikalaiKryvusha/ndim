/**
 * ЮНИТЫ ПРИБОРА ДОЛИ МЕТЫ (`tools/lib/meta-share.mjs`, порция 2 постановки Менеджера).
 *
 * 🔴 ОБРАЗЦЫ ДВУЯЗЫЧНЫЕ ПО КАНОНУ: «самотест проверки языка X идёт на образцах языка X»
 * (`AGENT_GUIDE.md`). Лексиконов здесь два, русский и английский, — значит и случаев два ряда.
 *
 * 🔑 ПАРА «КОБРЫ» БЕРЁТСЯ ИЗ НАСТОЯЩЕГО ФАЙЛА ПАРТИИ, А НЕ НАБИРАЕТСЯ РУКАМИ. Ею Менеджер
 * велел доказать границу класса, и доказательство на переписанной от руки строке доказывало бы
 * работу теста, а не прибора: карточка правится, а копия в тесте — нет.
 *
 * Что стережётся, по слоям:
 *   1. граница класса «приём ≠ мета» — слово владельца 2026-08-22 (`bugs/173`);
 *   2. премьера (выпуск) против премии (приём) — собственный дефект первой редакции;
 *   3. ИЗВЕСТНЫЙ ОСТАТОК перебора — закреплён нарочно, чтобы никто не счёл классификатор точным;
 *   4. допуск в калибровку — по данным, и практика в него не проходит;
 *   5. форма записи — отбор обязан понимать заголовок и строкой, и объектом;
 *   6. прибор ПРЕДЪЯВЛЯЕТ: возвращает сами предложения, а не только число.
 *
 * Прогон: node --test tools/meta-share.test.mjs   ·   npm run test:tools
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

import {
  classifySentence, metaShare, eligibleForCalibration, buildCalibrationCorpus,
  заголовокСтрокой, MATRIX_ROW_SIZE, SHORT_SENTENCE,
} from './lib/meta-share.mjs';
import { splitSentences } from './lib/prose-gates.mjs';
import { прочитатьЗаписи } from './measure-meta-share.mjs';

const ПАРТИЯ_3 = 'candidates/batches/03_2026_films_and_games.json';
const кобра = () => {
  const з = прочитатьЗаписи(readFileSync(ПАРТИЯ_3, 'utf8')).find((x) => x.id === 'Q637290');
  assert.ok(з, 'карточка «Кобра» (Q637290) не найдена — проверять нечем, это отказ проверяющего');
  return з;
};

// ── 1. ГРАНИЦА КЛАССА: ПРИЁМ — НЕ МЕТА (слово владельца, доказано на «Кобре») ───────────────

test('«Кобра» RU: производство — мета, приём сообщества — НЕ мета', () => {
  const r = metaShare(кобра().description.ru, 'ru', splitSentences);
  const мета = r.предложенияМеты.map((x) => x.предложение).join(' | ');
  const приём = r.предложенияПриёма.map((x) => x.предложение).join(' | ');
  assert.match(мета, /Произвели картину Warner Bros\./u, 'предложение о производстве обязано быть метой');
  assert.match(приём, /резкие отзывы критиков/u, 'абзац о приёме обязан уйти в приём, а не в мету');
  assert.doesNotMatch(мета, /резкие отзывы критиков/u, 'приём попал в мету — граница класса сломана');
});

test('«Кобра» EN: то же самое на английской половине карточки', () => {
  const r = metaShare(кобра().description.en, 'en', splitSentences);
  const мета = r.предложенияМеты.map((x) => x.предложение).join(' | ');
  const приём = r.предложенияПриёма.map((x) => x.предложение).join(' | ');
  assert.match(мета, /Warner Bros\. and The Cannon Group produced it/u);
  assert.match(приём, /drew sharp reviews/u);
  assert.doesNotMatch(мета, /drew sharp reviews/u);
});

test('приём побеждает мету в СМЕШАННОМ предложении — и это занижение, а не завышение', () => {
  // Направление ошибки выбрано сознательно: прибор ничего не прячет — приём он тоже печатает.
  const s = 'Картину произвела студия Warner Bros., и она получила премию критиков.';
  assert.equal(classifySentence(s, 'ru').класс, 'приём');
});

// ── 2. ПРЕМЬЕРА (ВЫПУСК) ПРОТИВ ПРЕМИИ (ПРИЁМ) ─────────────────────────────────────────────

test('премьера — выпуск, премия — приём: основу нельзя укоротить до «прем»', () => {
  // ⚠️ Первая редакция комментария утверждала, что подстрока `преми` слепляла оба слова.
  // Проверено — неправда: в «пре**мь**ере» подстроки `преми` нет. Различие настоящее и хрупкое
  // по другой причине: основа короче на одну букву (`прем`) слепляет их сразу, и мутация М3
  // это показывает. Поэтому тест остаётся, а обоснование исправлено.
  assert.equal(classifySentence('Премьера состоялась 2 октября 1986 года в прокате США.', 'ru').класс, 'мета');
  assert.equal(classifySentence('Картина получила премию за лучшую операторскую работу.', 'ru').класс, 'приём');
});

// ── 3. ИЗВЕСТНЫЙ ОСТАТОК ПЕРЕБОРА — закреплён, чтобы его не приняли за точность ─────────────

test('два из трёх ложных срабатываний контракта сняты', () => {
  assert.notEqual(classifySentence('Награду за этот бой он получает вместе с искалеченным коленом.', 'ru').класс, 'мета');
  assert.equal(classifySentence('Остальные Редфеллоу заняты примерно тем же.', 'ru').класс, 'содержание');
});

test('ТРЕТЬЕ ложное срабатывание ЖИВО, и это записано, а не спрятано', () => {
  // «премьера» здесь событие сюжета, а не выпуск. Прибор не краснеет — он предъявляет строку,
  // и человек её отводит. Ровно ради этого остатка Менеджер выбрал «предъявляет, не судит».
  // Тест упадёт, если кто-то решит, что классификатор точен, и снимет эту оговорку.
  assert.equal(classifySentence('После очередной премьеры Годар разносит увиденное.', 'ru').класс, 'мета');
});

// ── 4. ДОПУСК В КАЛИБРОВКУ — ПО ДАННЫМ, А НЕ ПО ТИПУ ───────────────────────────────────────

test('допуск: есть автор И выпуск', () => {
  assert.equal(eligibleForCalibration({ author: { ru: 'Вачовски' }, year: '1999' }), true);
  assert.equal(eligibleForCalibration({ author: 'Вачовски', year: '1999' }), true, 'автор строкой тоже считается');
  assert.equal(eligibleForCalibration({ author: { ru: '-', en: '-' }, year: '-' }), false);
  assert.equal(eligibleForCalibration({ author: { ru: 'Николя Аппер' }, year: '-' }), false, 'нет выпуска — не допущен');
  assert.equal(eligibleForCalibration({ author: { ru: '-' }, year: '1972' }), false, 'нет автора — не допущен');
});

test('практика в корпус калибровки НЕ проходит, и прибор называет причину', () => {
  // Форма записей — настоящая, снята со снимка каталога: незаполненное поле несёт строку `-`.
  const записи = [
    { title: { ru: 'Матрица', en: 'The Matrix' }, author: { ru: 'Вачовски' }, year: '1999' },
    { title: { ru: 'Игра на фортепиано', en: 'Piano playing' }, author: { ru: '-', en: '-' }, year: '-' },
    { title: { ru: 'Матрица: Перезагрузка', en: 'The Matrix Reloaded' }, author: { ru: '-', en: '-' }, year: '-' },
  ];
  const { принятые, отклонённые } = buildCalibrationCorpus(записи);
  assert.equal(принятые.length, 1, 'в калибровку прошло не то, что должно');
  assert.equal(отклонённые.length, 1, 'непригодная запись ряда обязана быть НАЗВАНА, а не отброшена молча');
  assert.match(отклонённые[0].причина, /нет автора или выпуска/u);
  // Практика вне ряда в отбор не попадает вовсе — но и по допуску она бы не прошла.
  assert.equal(eligibleForCalibration(записи[1]), false);
});

test('ряд «Матрицы» — семь записей, и размер выборки объявлен константой', () => {
  const ряд = ['Матрица', 'Матрица: Перезагрузка', 'Матрица: Революция', 'Матрица: Воскрешение',
    'Аниматрица', 'Enter the Matrix', 'The Matrix Online']
    .map((t) => ({ title: { ru: t, en: t }, author: { ru: 'Вачовски' }, year: '1999' }));
  assert.equal(buildCalibrationCorpus(ряд).принятые.length, MATRIX_ROW_SIZE);
});

// ── 5. ФОРМА ЗАПИСИ: отбор понимает заголовок и строкой, и объектом ─────────────────────────

test('отбор не ломается о форму заголовка — пара «истина ↔ зеркало» снята', () => {
  // Первая редакция спрашивала `title.ru` у записи, где `title` уже строка, и дала 0 из 5125.
  assert.equal(заголовокСтрокой({ title: 'Матрица' }), 'Матрица');
  assert.equal(заголовокСтрокой({ title: { ru: 'Матрица', en: 'The Matrix' } }), 'Матрица The Matrix');
  assert.equal(заголовокСтрокой({}), '');
  const строкой = buildCalibrationCorpus([{ title: 'Матрица', author: { ru: 'Вачовски' }, year: '1999' }]);
  assert.equal(строкой.принятые.length, 1, 'запись с заголовком-строкой обязана попасть в корпус');
});

// ── 6. ПРИБОР ПРЕДЪЯВЛЯЕТ, А НЕ ТОЛЬКО СЧИТАЕТ ─────────────────────────────────────────────

test('metaShare возвращает САМИ предложения, а не одно число', () => {
  const r = metaShare(кобра().description.ru, 'ru', splitSentences);
  assert.ok(r.всего > 0);
  assert.equal(r.доля, Math.round((100 * r.мета) / r.всего), 'доля обязана сходиться со счётом');
  assert.equal(r.предложенияМеты.length, r.мета, 'список меты обязан совпадать со счётом меты');
  assert.ok(r.предложенияПриёма.length >= 1, 'предложения приёма тоже предъявляются, а не прячутся');
  for (const п of r.предложенияМеты) assert.ok(п.предложение.trim().length > 0);
});

test('короткому предложению хватает одного производственного слова, длинному нужно два', () => {
  const коротко = 'Продюсировал Джоэл Сильвер.';
  assert.ok(коротко.length < SHORT_SENTENCE);
  assert.equal(classifySentence(коротко, 'ru').класс, 'мета');
  // Длинное с ОДНИМ словом — содержание: одиночное слово в длинной фразе чаще всего сюжет.
  const длинно = 'Герой узнаётся по устойчивому набору признаков, среди которых тёмные очки и старый автомобиль, '
    + 'и весь этот набор держится при нём от начала до конца, ни разу не меняясь по ходу действия сценария.';
  assert.ok(длинно.length >= SHORT_SENTENCE);
  assert.equal(classifySentence(длинно, 'ru').класс, 'содержание');
});

test('пустой текст — ноль, а не деление на ноль', () => {
  const r = metaShare('', 'ru', splitSentences);
  assert.equal(r.всего, 0);
  assert.equal(r.доля, 0);
});

// ── 7. КОРПУСНЫЙ КОНТРОЛЬ — числа партий закреплены, чтобы дрейф был виден ──────────────────

test('наши партии 1–3: доля меты закреплена числом', () => {
  const записи = ['01_2026_films', '02_2026_films_and_games', '03_2026_films_and_games']
    .flatMap((f) => прочитатьЗаписи(readFileSync(`candidates/batches/${f}.json`, 'utf8')));
  assert.equal(записи.length, 30);
  // 🔴 ЧИСЛО EN ПЕРЕЗАКРЕПЛЕНО 28 → 24 (Дизайнер, 2026-08-22). Обоснование правки теста:
  // владелец вернул 12 карточек партий 2 и 3, они переписаны по его девяти классам, и доля
  // меты у переписанных УПАЛА — это цель правки, а не дрейф. Замер до и после на том же
  // приборе: en 27,77 → 24,37 · ru 21,27 → 20,57 (ru округляется в те же 21, число не тронуто).
  // Двум карточкам сюжет добран из сети и вытеснил производственную обвязку: «Закулисье
  // реальности» 30 → 9 % ru, «Властелины Вселенной» 33 → 27 % ru.
  // 🔑 И находка, оплаченная этим красным: его класс 9 («факт брошен обрубком вместо фразы»)
  // ПОДНИМАЕТ долю меты, считаемую по предложениям, — один производственный факт, поданный
  // полной фразой, весит столько же, сколько целое предложение сюжета. Два его правила тянут
  // прибор в разные стороны, и знать это обязан тот, кто будет назначать порог.
  // 🔴 ЧИСЛО RU ПЕРЕЗАКРЕПЛЕНО 21 → 20 (Дизайнер, 2026-08-23, порция 1 починки). Обоснование:
  // владелец вернул 29 карточек и назвал класс 16 — «Ни слова о дате премьеры, об восприятии
  // картины обществом». Приём картины по его же слову 2026-08-22 МЕТОЙ НЕ СЧИТАЕТСЯ, а сюжет,
  // добранный в две карточки взамен производственной обвязки, долю меты снижает. Замер до и
  // после на том же приборе: ru 20,57 → 20,40 · en 24,37 → 23,87 (en округляется в те же 24).
  // 🔴 ЧИСЛО EN ПЕРЕЗАКРЕПЛЕНО 24 → 23 (Дизайнер, 2026-08-23, задача 1 смены 6). Приём картины
  // дописан пяти карточкам по классу 16 владельца; приём его же словом 2026-08-22 метой НЕ
  // считается, поэтому доля меты падает. Замер до и после: en 23,87 → 23,47 · ru 20,40 → 19,97
  // (ru округляется в те же 20, число не тронуто).
  for (const [lang, ожидание] of [['ru', 20], ['en', 23]]) {
    const доли = записи.map((x) => metaShare(x.description[lang], lang, splitSentences).доля);
    const средняя = Math.round(доли.reduce((a, b) => a + b, 0) / доли.length);
    assert.equal(средняя, ожидание, `средняя доля меты ${lang} сдвинулась: было ${ожидание}, стало ${средняя}`);
  }
});
