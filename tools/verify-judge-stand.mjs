/**
 * СТЕНД СУДЬИ ГОДЕН? — контроль дерева, В КОТОРОМ идёт суд, ДО предмета суда.
 *
 * Запуск: node tools/verify-judge-stand.mjs [путь к дереву суда] · самотест: --selftest
 * Ворота: нет — прибор судит ДЕРЕВО СУДА, а не продукт; в воротах продукта ему нечего делать.
 *         Его место — первая команда суда, до первого прогона по предмету.
 * Код возврата: 0 — стенд годен · 1 — стенд негоден, суд начинать нельзя.
 *
 * ═══ 🔴 ЗАЧЕМ ОН СУЩЕСТВУЕТ: ЛЕЧЕНИЕ, КОТОРОЕ БЫЛО ОБЪЯВЛЕНО И НЕ СУЩЕСТВОВАЛО ═══
 *
 * `EXP-0243` (моя же запись, смена 10) несёт строку **«Mechanization: да, и дёшево — контроль
 * стенда ДО суда… Помощник заведён в этот же день и с тех пор ни один слепок не соврал»**.
 * Вердикт №22 говорит то же: «завела себе двухшаговый помощник и контроль».
 *
 * 🔴 **Помощника в дереве НЕТ.** Греп по всему репозиторию находит эти слова ровно в одном
 * месте — в самом `EXPERIENCE.md`. Он жил в рабочем пространстве той сессии и умер вместе с ней,
 * а запись осталась стоять с пометкой «механизировано». То есть урок объявил себя первым сортом
 * (страж), будучи третьим (запись), — и следующая сессия читает его как закрытый долг.
 *
 * 📐 **Доказано повтором, а не рассуждением.** Смена 11, суд мастерской `dev3-shift6`: дерево
 * суда заведено `git worktree add --detach`, `node_modules` в нём не было, первый прогон дал
 * **7 красных при честных 3** — четыре `ERR_MODULE_NOT_FOUND` на `vite` и `@playwright/test`.
 * Ровно тот класс, который `EXP-0243` считает механизированным.
 *
 * 🔑 И вот почему он повторился, — это главное, что здесь написано. Помощник смены 10 умел
 * готовить ОДИН способ сделать дерево суда — слепок (`git archive` + `git init`). Смена 11
 * взяла ДРУГОЙ, столь же законный, — `git worktree add`. Строка «с тех пор ни один слепок не
 * соврал» правдива и бесполезна: это был не слепок.
 * **Лечение, привязанное к СПОСОБУ постройки, обходится сменой способа. Поэтому этот прибор
 * спрашивает готовое дерево о его СОСТОЯНИИ и не знает, чем его сделали.**
 *
 * ═══ ТРИ ВОПРОСА, И КАЖДЫЙ ОПЛАЧЕН ЖИВЫМ ЛОЖНЫМ ОТВЕТОМ ═══
 *
 *   1. **Зависимости на месте?** Ложный КРАСНЫЙ. Смена 11: 4 из 7 (выше). Тот же класс с другой
 *      стороны у Дизайнера: `main` принёс `posthog-js`, отставшие `node_modules` уронили `check`.
 *      Поэтому спрашивается не «есть ли каталог `node_modules`», а «лежит ли в нём КАЖДОЕ имя,
 *      объявленное в `package.json`»: каталог был и у Дизайнера.
 *   2. **История достижима?** Ложный ЗЕЛЁНЫЙ, и он ядовитее (`EXP-0243`). Прибор, спрашивающий
 *      git («сколько коммитов тронуло этот файл»), на дереве с ОДНИМ синтетическим коммитом
 *      честно молчит обо всём корпусе сразу — и молчание читается как «нарушений нет».
 *      Признак не вкусовой: дерево, у которого коммит ровно один, не способно ответить на
 *      вопрос «какие коммиты тронули этот файл» НИ ПРО ОДИН файл.
 *   3. **Дерево чисто?** Ложный КРАСНЫЙ и ложный ЗЕЛЁНЫЙ разом. Смена 11: два моих же файла
 *      замера, лежавших неотслеживаемыми, покрасили `guards` строкой «стражи их НЕ судили».
 *      Числа, снятые в грязной копии, говорят не о предмете суда (правило заявки, манифест).
 *
 * ⛔ ЧЕГО ПРИБОР НЕ ДЕЛАЕТ. Он не судит ВЕРСИИ зависимостей (совпадает ли установленное с
 * `package-lock.json`) — под это нет замера, а `npm ci` отвечает на тот вопрос лучше. Он не
 * запускает ни одного прогона: его дело — сказать, можно ли ВЕРИТЬ прогонам, которые пойдут
 * следом. И он ничего не чинит: лечение называется словами, а исполняет его судья.
 *
 * 🔴 ПУТЬ — АРГУМЕНТОМ, И ЭТО НЕ УДОБСТВО, А ТО ЖЕ САМОЕ ПРАВИЛО. Дерево суда почти всегда стоит
 * на ЧУЖОЙ голове — старой ветке, в которой этого прибора нет и быть не может. Прибор, умеющий
 * судить только дерево, где он сам лежит, повторил бы промах помощника смены 10 в новой форме:
 * лечение, доступное не во всех случаях, обходится первым же случаем не из них. Поэтому судья
 * зовёт его ИЗ СВОЕЙ копии и передаёт путь: `node tools/verify-judge-stand.mjs <дерево суда>`.
 *
 * 🟢 Работы на верхнем уровне нет — файл безопасен для импорта (`ideas/43`, класс `EXP-0188`).
 */
import { readFileSync, existsSync, readdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const КОРЕНЬ = join(dirname(fileURLToPath(import.meta.url)), '..');

/* ── ВОПРОС 1: ЗАВИСИМОСТИ ──────────────────────────────────────────────────────────────────
 * Спрашивается ПОИМЕННО, а не «каталог существует»: отставшая копия несёт каталог со старым
 * составом, и именно она уронила `check` у Дизайнера. Имя, объявленное и не лежащее, —
 * будущий `ERR_MODULE_NOT_FOUND`, то есть будущий ложный красный.
 */
export function бедыЗависимостей(объявлено, лежит) {
  const нет = объявлено.filter((имя) => !лежит.includes(имя));
  if (!нет.length) return [];
  return [
    `зависимостей объявлено ${объявлено.length}, не установлено ${нет.length}: ${нет.slice(0, 8).join(', ')}`
    + (нет.length > 8 ? ` … и ещё ${нет.length - 8}` : ''),
    '   → лечение: npm install в этом дереве (либо junction на node_modules главной копии)',
    '   → без него прогон даст ЛОЖНЫЕ КРАСНЫЕ: ERR_MODULE_NOT_FOUND читается как дефект предмета',
  ];
}

/* ── ВОПРОС 2: ИСТОРИЯ ──────────────────────────────────────────────────────────────────────
 * Порога здесь нет и быть не может: значение ровно одно — ОДИН коммит. Дерево с единственным
 * коммитом не отвечает «какие коммиты тронули файл» ни про один файл, и приборы, спрашивающие
 * git, зеленеют молча. Два коммита уже дают историю по файлам, поэтому граница не вкусовая.
 */
export function бедаИстории(коммитов) {
  if (коммитов === null) {
    return ['git в этом дереве не отвечает — приборы, спрашивающие историю, судить нельзя'];
  }
  if (коммитов > 1) return [];
  return [
    `коммитов в дереве: ${коммитов} — история СИНТЕТИЧЕСКАЯ`,
    '   → лечение: git remote add real <путь>/.git && git fetch real "refs/heads/*:refs/remotes/real/*"',
    '   → без него приборы, спрашивающие git, дадут ЛОЖНЫЙ ЗЕЛЁНЫЙ (EXP-0243): молчание об истории',
    '     неотличимо от «нарушений нет», и вывод переворачивается, а не шумит',
  ];
}

/* ── ВОПРОС 3: ЧИСТОТА ──────────────────────────────────────────────────────────────────────
 * Неотслеживаемый файл судьи — не безобидный мусор: `guards` краснеет на нём строкой «стражи
 * их НЕ судили», и красный принадлежит судье, а выглядит принадлежащим предмету.
 */
export function бедыДерева(строкиStatus) {
  const строки = (строкиStatus ?? []).filter((с) => с.trim());
  if (!строки.length) return [];
  const неотслеживаемых = строки.filter((с) => с.startsWith('??')).length;
  return [
    `дерево ГРЯЗНО: изменённых и неотслеживаемых файлов ${строки.length}`
    + (неотслеживаемых ? ` (из них вне индекса ${неотслеживаемых})` : ''),
    `   → ${строки.slice(0, 5).map((с) => с.trim()).join(' · ')}${строки.length > 5 ? ' …' : ''}`,
    '   → лечение: убрать своё, откатить мутации; числа из грязной копии говорят не о предмете суда',
  ];
}

/* ── ВОПРОС 4: ОТСТАВАНИЕ ───────────────────────────────────────────────────────────────────
 *
 * 🔴 ЭТОТ ВОПРОС ОПЛАЧЕН ПРОВАЛОМ САМОГО ЭТОГО ПРИБОРА, И ПОТОМУ СТОИТ ЗДЕСЬ.
 *
 * Смена 11, суд корзины: страж «неначатых» покраснел на `plans/79` и в дереве суда, и в моей
 * копии. Красный main по канону тушится прежде любой работы — я была в ОДНОМ ШАГЕ от объявления
 * пожара и остановки окна мержей. `main` была чиста, ворота 13/13.
 * Причина: копии отставали (на 11 и 19 коммитов), `plans/79` в них — СТАРОЙ редакции, а страж
 * спрашивает **git**, и `.git` у шести рабочих копий **ОБЩИЙ**. Он видел коммит, которого в
 * дереве не было. Красный был про СМЕСЬ ДВУХ МИРОВ.
 *
 * 🔑 И вот что делает этот вопрос обязательным: три вопроса выше на том дереве честно ответили
 * **«СТЕНД ГОДЕН»**. Дерево и было годным — негодной была ПОСЫЛКА, что прогон в нём говорит о
 * `main`. Прибор, написанный против ложных ответов стенда, промолчал о самом дорогом из них.
 *
 * ⛔ ПОЧЕМУ ЭТО НЕ БЕДА, А ОГОВОРКА, И ПОЧЕМУ ПЛОСКИЙ ОТКАЗ БЫЛ БЫ ХУЖЕ МОЛЧАНИЯ.
 * Судья ЗАКОННО судит старые головы — отставание для неё норма, а не поломка. Прибор, краснеющий
 * на норме, будет обходиться первым же прогоном и умрёт как `EXP-0194`. Поэтому вопрос 4 не
 * отказывает, а НАЗЫВАЕТ: сколько коммитов не видно дереву и СКОЛЬКО ПРИБОРОВ В ВОРОТАХ
 * спрашивают git — то есть чей именно вердикт здесь будет про смесь.
 *
 * 🔑 Форма взята у правила эстафеты, выведенного в тот же день Дизайнером: **условие называет
 * КОММИТ, а не имя** («проверка предком — команда, а не память»). Здесь то же: оговорка несёт
 * ЧИСЛО коммитов и ПОИМЁННЫЙ список приборов, а не совет «будь внимателен».
 */
export function оговоркаОтставания(позади, приборыСGit) {
  if (позади === null || позади === 0) return [];
  const имена = приборыСGit ?? [];
  return [
    `дерево отстало от «main» на ${позади} коммит(ов) — приборы, спрашивающие git, видят то, чего в дереве НЕТ`,
    имена.length
      ? `   → в воротах таких ${имена.length}: ${имена.join(' · ')}`
      : '   → приборов, спрашивающих git, в воротах не найдено — оговорка касается только ручных прогонов',
    '   → их красный/зелёный здесь — про СМЕСЬ двух миров, а не про предмет суда (оплачено сменой 11:',
    '     страж «неначатых» покраснел на plans/79 из чужого коммита, main была чиста 13/13)',
    '   → прежде чем звать такой красный находкой: git merge-base --is-ancestor <коммит> HEAD',
  ];
}

/** Насколько дерево позади `main`. `null` — ветки `main` нет или git не ответил. */
function позадиГлавной(корень) {
  try {
    return Number(execFileSync('git', ['rev-list', '--count', 'HEAD..main'], { cwd: корень, encoding: 'utf8' }).trim());
  } catch {
    return null;
  }
}

/**
 * Приборы СОСТАВА ВОРОТ, которые спрашивают git.
 *
 * Читается из `guards.mjs` — то есть из состава, а не из догадки по имени (`verify-tool-markers`
 * заводился ровно против такой догадки). Признак «спрашивает git» — упоминание запуска `git`
 * в исходнике прибора: грубо, но в НУЖНУЮ сторону — лишнее имя в оговорке дешевле пропущенного.
 */
function приборыСпрашивающиеGit(корень) {
  try {
    const состав = readFileSync(join(корень, 'tools', 'guards.mjs'), 'utf8');
    const имена = [...new Set([...состав.matchAll(/tools\/([a-z0-9-]+\.mjs)/giu)].map((m) => m[1]))];
    return имена.filter((имя) => {
      const путь = join(корень, 'tools', имя);
      return existsSync(путь) && /['"`]git['"`]/u.test(readFileSync(путь, 'utf8'));
    });
  } catch {
    return [];
  }
}

/** Имена зависимостей, объявленных манифестом, — обе секции разом. */
function объявленныеЗависимости(корень) {
  const p = JSON.parse(readFileSync(join(корень, 'package.json'), 'utf8'));
  return [...Object.keys(p.dependencies ?? {}), ...Object.keys(p.devDependencies ?? {})].sort();
}

/** Что реально лежит в `node_modules`, включая областные имена (`@scope/имя`). */
function установленныеЗависимости(корень) {
  const каталог = join(корень, 'node_modules');
  if (!existsSync(каталог)) return [];
  const имена = [];
  for (const запись of readdirSync(каталог, { withFileTypes: true })) {
    if (!запись.isDirectory() && !запись.isSymbolicLink()) continue;
    if (запись.name.startsWith('.')) continue;
    if (запись.name.startsWith('@')) {
      for (const внутри of readdirSync(join(каталог, запись.name))) имена.push(`${запись.name}/${внутри}`);
    } else имена.push(запись.name);
  }
  return имена;
}

/** Число коммитов дерева. `null` — git не ответил вовсе. */
function числоКоммитов(корень) {
  try {
    return Number(execFileSync('git', ['rev-list', '--count', 'HEAD'], { cwd: корень, encoding: 'utf8' }).trim());
  } catch {
    return null;
  }
}

/** Строки `git status --porcelain`. `null` — git не ответил. */
function состояниеДерева(корень) {
  try {
    return execFileSync('git', ['status', '--porcelain'], { cwd: корень, encoding: 'utf8' }).split(/\r?\n/u);
  } catch {
    return null;
  }
}

/** Все три вопроса разом. Возвращает список бед; пустой список — стенд годен. */
export function осмотретьСтенд(корень) {
  const состояние = состояниеДерева(корень);
  return [
    ...бедыЗависимостей(объявленныеЗависимости(корень), установленныеЗависимости(корень)),
    ...бедаИстории(числоКоммитов(корень)),
    ...(состояние === null ? ['git в этом дереве не отвечает — чистоту дерева проверить нечем'] : бедыДерева(состояние)),
  ];
}

/**
 * ОГОВОРКИ — то, что НЕ делает стенд негодным, но меняет ЧТЕНИЕ его прогонов.
 * Отделены от бед намеренно: беда чинится, оговорка держится в уме. Смешать их значило бы либо
 * краснеть на норме, либо промолчать о самом дорогом (разбор — у вопроса 4).
 */
export function осмотретьОговорки(корень) {
  return оговоркаОтставания(позадиГлавной(корень), приборыСпрашивающиеGit(корень));
}

