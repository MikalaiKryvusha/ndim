/**
 * ЗАМЕР КЛАССА 15 ВЛАДЕЛЬЦА — «УДИВЛЕНИЕ УБИТО ЗАРАНЕЕ». ОТВЕТ: ПРИЗНАК ЕСТЬ, НО НА ОДНОМ ПРИМЕРЕ.
 *
 * Его слово: «*фраза по твоей задумке должна нести элемент удивления, но ты в первой части
 * раскрываешь правду, а потом тянешь противопоставление — так ты ослабил свою попытку удивить
 * читателя*» (`candidates/owner-critical-notes-2026-08-22.md`, класс 15; возвращена карточка
 * «Отец, мать, сестра, брат», `Q124364048`).
 *
 * 🔴 ЭТОТ ПРИБОР ОПРОВЕРГ ОЖИДАНИЕ СВОЕГО ЖЕ АВТОРА, И РАДИ ЭТОГО ОН И НАПИСАН. Я шёл сюда
 * доказывать, что класс 15 машинно не берётся: дефект — это ПОРЯДОК частей фразы, а порядок
 * мерами поверхности не считается. Доказательство ниже это подтверждает — восемь счётных мер
 * из восьми дают на дефекте и на его лечении ОДНО И ТО ЖЕ число.
 * ⚠️ И всё-таки вывод «признака нет» оказался НЕВЕРЕН. Меры, перебранные первыми, СЧИТАЮТ
 * (сколько слов, запятых, придаточных) — им порядок и правда невидим. Но признак может не
 * считать, а СМОТРЕТЬ, ГДЕ стоит слово. Кандидат 1 делает ровно это — спрашивает, в какой
 * половине фразы стоит раскрытие и в какой контраст, — и различает дефект с лечением на той
 * самой паре, на которой все счётные меры слепы.
 * 🔑 Урок дороже самого класса: **«мера не различает» и «признака нет» — РАЗНЫЕ утверждения.**
 * Первое здесь доказано, второе чуть не выдано за доказанное.
 *
 * ═══ ЧТО МЕРИЛОСЬ ═══
 *
 * Пять кандидатов в признак, каждый — прямое прочтение его слов. Корпуса те же, что у остальных
 * классов: **A** — 50 описаний ЕГО каталога (`src/lib/content/dims-slice.json`), **C** — 50 наших
 * (`candidates/batches/01…04`), внутри C лежит сама возвращённая карточка.
 *
 * ═══ 🔴 ГЛАВНОЕ ДОКАЗАТЕЛЬСТВО — НЕ ТАБЛИЦА, А ПАРА ФРАЗ ═══
 *
 * Дефект класса 15 — это ПОРЯДОК ЧАСТЕЙ, а не слова и не знаки. Значит его лечение переставляет
 * части, ничего не добавляя. Прибор берёт ту самую фразу из возвращённой карточки и её же с
 * переставленными частями — и показывает, что ВСЕ поверхностные меры на них совпадают до
 * единицы: те же 31 слово, те же 206 знаков, те же 4 запятых, то же двоеточие, то же тире, те же
 * 2 придаточных, те же 3 слова-раскрытия.
 *
 * 🔑 Отсюда вывод, который сильнее любой таблицы: **никакая мера поверхности не может отличить
 * дефект от его лечения, потому что поверхность у них одна и та же.** Признак, который их
 * различит, обязан понимать, ЧТО раскрыто и КОГДА, — это разбор смысла, а не образец.
 *
 * ⛔ ЧЕГО ЭТОТ ЗАМЕР НЕ УТВЕРЖДАЕТ. Он не говорит «класс 15 невозможен машинно» вообще — он
 * говорит, что его не берут лексические и структурные признаки, то есть тот инструмент, которым
 * сделаны остальные пятнадцать. Языковая модель, читающая фразу целиком, задачу решить может;
 * это другой прибор и другая работа, и она названа, а не спрятана.
 *
 * Запуск: node tools/measure-class15.mjs
 */
import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

import { splitSentences } from './lib/prose-gates.mjs';
import { мераСложности } from './lib/owner-classes-ru.mjs';

const СРЕЗ = 'src/lib/content/dims-slice.json';
const ПАРТИИ = 'candidates/batches';

const корпусA = () => JSON.parse(readFileSync(СРЕЗ, 'utf8'))
  .map((r) => ({ имя: r.title?.ru, t: r.description?.ru ?? '' })).filter((x) => x.t);

const корпусC = () => {
  const из = [];
  for (const f of readdirSync(ПАРТИИ).filter((x) => /^\d\d_/u.test(x) && !/test/u.test(x)).sort()) {
    const b = JSON.parse(readFileSync(join(ПАРТИИ, f), 'utf8'));
    for (const c of b.candidates ?? []) {
      if (c.description?.ru) из.push({ имя: c.title?.ru, t: c.description.ru, партия: f.slice(0, 2) });
    }
  }
  return из;
};

/** Слова, которыми фраза объявляет раскрытие правды. Прямое прочтение его претензии. */
const РАСКРЫТИЕ = /(?<![\p{L}])(?:на\s+самом\s+деле|выясн[\p{L}]+|оказыва[\p{L}]+|правда\s+в\s+том|настоящ[\p{L}]+\s+(?:положение|лицо|причин[\p{L}]+)|прячет|скрывает|тайком)(?![\p{L}])/iu;
/** Слова противопоставления, которое он назвал «тянешь» после раскрытия. */
const КОНТРАСТ = /(?<![\p{L}])(?:но|однако|зато|пока|а\s+не|хотя)(?![\p{L}])/iu;

const КАНДИДАТЫ = [
  ['1. раскрытие в первой половине + контраст во второй', (s) => {
    const п = Math.floor(s.length / 2);
    return РАСКРЫТИЕ.test(s.slice(0, п)) && КОНТРАСТ.test(s.slice(п));
  }],
  ['2. слово-раскрытие где угодно во фразе', (s) => РАСКРЫТИЕ.test(s)],
  ['3. двоеточие и тире в одной фразе', (s) => s.includes(':') && s.includes('—')],
  ['4. контраст во второй половине фразы', (s) => КОНТРАСТ.test(s.slice(Math.floor(s.length / 2)))],
  ['5. раскрытие ДО двоеточия', (s) => { const i = s.indexOf(':'); return i > 0 && РАСКРЫТИЕ.test(s.slice(0, i)); }],
];

const A = корпусA();
const C = корпусC();
const ВОЗВРАЩЁННАЯ = 'Отец, мать, сестра, брат';

console.log('\n═══ ЗАМЕР КЛАССА 15: «УДИВЛЕНИЕ УБИТО ЗАРАНЕЕ» ═══');
console.log(`  A — тексты владельца: ${A.length} описаний · C — наши партии: ${C.length} описаний`);
console.log(`  внутри C — возвращённая за этот класс карточка «${ВОЗВРАЩЁННАЯ}»\n`);
console.log('  | кандидат в признак | A (его тексты) | C (наши) | ловит возвращённую? |');
console.log('  |---|---|---|---|');

const карточка = C.find((r) => r.имя === ВОЗВРАЩЁННАЯ);
for (const [имя, проба] of КАНДИДАТЫ) {
  const счёт = (к) => {
    let n = 0;
    let з = 0;
    for (const r of к) {
      let есть = false;
      for (const s of splitSentences(r.t)) if (проба(s)) { n += 1; есть = true; }
      if (есть) з += 1;
    }
    return { n, з };
  };
  const a = счёт(A);
  const c = счёт(C);
  const ловит = карточка ? splitSentences(карточка.t).some(проба) : false;
  console.log(`  | ${имя} | ${a.n} в ${a.з} | ${c.n} в ${c.з} | ${ловит ? '✅ да' : '❌ НЕТ'} |`);
}

console.log('\n🔑 ЧИТАТЬ ТАК, СВЕРХУ ВНИЗ.');
console.log('   · кандидат 1 — ЕДИНСТВЕННЫЙ, кто разделяет: 0 на текстах владельца, 1 у нас, и эта');
console.log('     одна есть ровно возвращённая карточка. Он же различает дефект и лечение (ниже);');
console.log('   · кандидаты 2 и 4 срабатывают на текстах САМОГО владельца (14 и 9 фраз) — они');
console.log('     запрещали бы писать так, как пишет он;');
console.log('   · кандидат 3 разделяет корпуса, но меряет НЕ ТО: он ловит сложность построения');
console.log('     фразы, а это класс 2, у которого порог назначает владелец;');
console.log('   · кандидат 5 срабатывает и на его тексте тоже — разделения нет.');
console.log('\n⚠️ 🔴 ЧЕСТНАЯ ГРАНИЦА КАНДИДАТА 1, И ОНА РЕШАЕТ ЕГО СУДЬБУ: положительный случай у');
console.log('   него ОДИН, и это та самая фраза, из которой он выведен. Признак, подогнанный под');
console.log('   свой единственный пример, отказом ставить нельзя: ноль ложных на 50 описаниях');
console.log('   владельца он показал, а ловит ли он КЛАСС или одну фразу — неизвестно до второй');
console.log('   находки. Поэтому в воротах он ЗАМЕЧАНИЕ. Придёт партия 6 — станет видно, и');
console.log('   перевод в отказ будет правкой в одну строку.');

/*
 * ── ДОКАЗАТЕЛЬСТВО ИНВАРИАНТНОСТИ: ДЕФЕКТ И ЕГО ЛЕЧЕНИЕ НЕРАЗЛИЧИМЫ ПОВЕРХНОСТЬЮ ────────────
 * Обе фразы — одна и та же строка возвращённой карточки. Во второй части переставлены местами:
 * раскрытие ушло с начала в конец, за двоеточие. Ни одного слова не добавлено и не убрано.
 */
const ПЛОХО = 'Отец, в свою очередь, прячет своё настоящее положение: держит во дворе старый пикап, нарочно оставляет беспорядок в комнате — пока на его запястье не оказываются часы, которые он тут же объявляет подделкой.';
const ХОРОШО = 'Отец, в свою очередь, держит во дворе старый пикап, нарочно оставляет беспорядок в комнате — пока на его запястье не оказываются часы, которые он тут же объявляет подделкой: прячет своё настоящее положение.';

const слова = (s) => (s.match(/[\p{L}\p{N}-]+/gu) ?? []).map((w) => w.toLowerCase());
const меры = (s) => ({
  знаков: s.length,
  слов: слова(s).length,
  запятых: (s.match(/,/gu) ?? []).length,
  двоеточий: (s.match(/:/gu) ?? []).length,
  тире: (s.match(/—/gu) ?? []).length,
  придаточных: (s.match(/(?<![\p{L}])(?:котор[\p{L}]+|что|чтобы|где|когда|пока|если|хотя|чем)(?![\p{L}])/giu) ?? []).length,
  'слов-раскрытий': (s.match(/(?<![\p{L}])(?:прячет|скрывает|настоящее|на\s+самом\s+деле|оказыва[\p{L}]+)(?![\p{L}])/giu) ?? []).length,
  'средняя фраза': мераСложности(s).срДлина,
});

console.log('\n── 🔴 ДЕФЕКТ И ЕГО ЛЕЧЕНИЕ — ОДНА И ТА ЖЕ ПОВЕРХНОСТЬ ──────────────');
console.log(`   ⛔ было : ${ПЛОХО}`);
console.log(`   ✅ стало: ${ХОРОШО}`);
console.log('');
const п = меры(ПЛОХО);
const х = меры(ХОРОШО);
let различает = 0;
console.log('   мера'.padEnd(22) + 'ДЕФЕКТ'.padStart(8) + 'ЛЕЧЕНИЕ'.padStart(9) + '   различает?');
for (const k of Object.keys(п)) {
  const одинаково = п[k] === х[k];
  if (!одинаково) различает += 1;
  console.log(`   ${k}`.padEnd(22) + String(п[k]).padStart(8) + String(х[k]).padStart(9) + `   ${одинаково ? 'нет' : '⚠️ ДА'}`);
}
const тотЖеНабор = слова(ПЛОХО).slice().sort().join(' ') === слова(ХОРОШО).slice().sort().join(' ');
console.log(`\n   мультимножество слов совпадает: ${тотЖеНабор ? 'ДА — ни одно слово не добавлено и не убрано' : 'нет'}`);
console.log(`   мер, различающих дефект и лечение: ${различает}`);

console.log('\n═══ ВЫВОД ═══');
console.log('✅ ПРИЗНАК ЕСТЬ, И ОН ПОЗИЦИОННЫЙ: раскрытие в первой половине фразы + контраст во');
console.log('   второй. Ноль на 50 описаниях владельца, одно попадание у нас — возвращённая');
console.log('   карточка. Дефект ловит, его лечение пропускает.');
console.log('🔴 И ПРИЗНАК СТОИТ НА ОДНОМ ПРИМЕРЕ — том самом, из которого выведен. Поэтому в');
console.log('   воротах он ЗАМЕЧАНИЕ, а не отказ, и об этом сказано вслух.');
console.log('🔑 СЧЁТНЫЕ МЕРЫ ЕГО НЕ ВИДЯТ ВОВСЕ: восемь мер из восьми дают на дефекте и на лечении');
console.log('   одно и то же число. «Мера не различает» и «признака нет» — разные утверждения.\n');
