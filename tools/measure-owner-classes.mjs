/**
 * ЗАМЕР КЛАССОВ ВЛАДЕЛЬЦА — русская сторона ворот прозы (`lib/owner-classes-ru.mjs`).
 *
 * Зачем прибор существует отдельно от юнитов: юнит доказывает, что признак ловит ТО САМОЕ на
 * поимённом случае; замер отвечает на другой вопрос — **сколько ложных он даёт на живом
 * материале**. Ноль на эталоне получают прогоном, а не уверенностью (`EXP-0192`). Все числа в
 * шапке `lib/owner-classes-ru.mjs` перевыводятся отсюда, и разойтись они не могут: там текст,
 * здесь прогон.
 *
 * КОРПУСА — только то, что лежит в git (боевая база роли не принадлежит):
 *   · **A** — `src/lib/content/dims-slice.json`, 50 русских описаний живого каталога. Это тексты
 *     САМОГО ВЛАДЕЛЬЦА: признак, краснеющий здесь, запрещал бы писать так, как пишет он;
 *   · **C** — `candidates/batches/01…04`, 50 наших русских описаний. Внутри — 10 из 12 карточек,
 *     возвращённых 2026-08-22, то есть настоящие дефекты классов, а не выдуманные.
 *
 * ⛔ ЧЕГО ЗАМЕР НЕ ДЕЛАЕТ. Он не ходит в реестр и потому не меряет класс 1 — у того свой прогон
 * (`node tools/check-candidate-release.mjs <партия>`), и число там другое по природе.
 *
 * Запуск: node tools/measure-owner-classes.mjs
 */
import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

import {
  противопоставление, полныйМетр, датыОбрубком, канцелярит, местоимениеВместоКороткойФормы,
  обрубкиФактов, мераСложности,
} from './lib/owner-classes-ru.mjs';

const СРЕЗ = 'src/lib/content/dims-slice.json';
const ПАРТИИ = 'candidates/batches';

const корпусA = () => JSON.parse(readFileSync(СРЕЗ, 'utf8'))
  .map((r) => ({ имя: r.title?.ru, t: r.description?.ru ?? '' }))
  .filter((x) => x.t);

const корпусC = () => {
  const из = [];
  /* `99_test_record.json` — служебная запись стенда, а не партия. Считать её в корпусе значило бы
   * мерить ложные отказы по тексту, который никто не сдавал владельцу. */
  const партии = readdirSync(ПАРТИИ).filter((x) => /^\d\d_/u.test(x) && !/test/u.test(x)).sort();
  for (const f of партии) {
    const b = JSON.parse(readFileSync(join(ПАРТИИ, f), 'utf8'));
    for (const c of b.candidates ?? []) {
      if (c.description?.ru) из.push({ имя: c.title?.ru, t: c.description.ru, партия: f.slice(0, 2) });
    }
  }
  return из;
};

/** Проверки замера. `сила` — то, чем находка становится в воротах. */
const ПРОВЕРКИ = [
  ['3 · противопоставление', 'замечание', (t) => противопоставление(t).map((h) => h.слово)],
  ['4 · «полный метр»', 'ОТКАЗ', (t) => полныйМетр(t)],
  ['5 · заголовок-обрубок про даты', 'ОТКАЗ', (t) => датыОбрубком(t)],
  ['6 · канцелярит «развёрнут»', 'ОТКАЗ', (t) => канцелярит(t).map((h) => h.форма)],
  ['7 · местоимение вместо короткой формы', 'ОТКАЗ', (t) => местоимениеВместоКороткойФормы(t).map((h) => h.оборот)],
  ['9 · факт брошен обрубком', 'замечание', (t) => обрубкиФактов(t).map((h) => h.обрубок)],
];

const A = корпусA();
const C = корпусC();

console.log('\n═══ ЗАМЕР КЛАССОВ ВЛАДЕЛЬЦА — РУССКАЯ СТОРОНА ═══');
console.log(`  A — тексты владельца (${СРЕЗ}): ${A.length} описаний`);
console.log(`  C — наши партии (${ПАРТИИ}/01…04): ${C.length} описаний\n`);
console.log('  | класс | сила | A: срабатываний / записей | C: срабатываний / записей |');
console.log('  |-------|------|---------------------------|---------------------------|');

const подробно = [];
for (const [имя, сила, проба] of ПРОВЕРКИ) {
  const счёт = (корпус) => {
    let n = 0;
    let з = 0;
    const где = [];
    for (const r of корпус) {
      const h = проба(r.t);
      if (!h.length) continue;
      n += h.length;
      з += 1;
      где.push(`${r.партия ? r.партия + ' ' : ''}${r.имя}: ${h.join(' · ')}`);
    }
    return { n, з, где };
  };
  const a = счёт(A);
  const c = счёт(C);
  console.log(`  | ${имя} | ${сила} | ${a.n} / ${a.з} | ${c.n} / ${c.з} |`);
  подробно.push([имя, a, c]);
}

console.log('\n── ЧТО ИМЕННО НАЙДЕНО ───────────────────────────────────────────');
for (const [имя, a, c] of подробно) {
  console.log(`\n${имя}`);
  if (!a.где.length && !c.где.length) { console.log('   (пусто в обоих корпусах)'); continue; }
  for (const x of a.где) console.log(`   🔴 A (текст ВЛАДЕЛЬЦА!) · ${x}`);
  for (const x of c.где) console.log(`   ·  C · ${x}`);
}

/*
 * КЛАСС 2 — отдельно и без порога. Печатаются те же числа, что стоят ориентиром в отчёте ворот;
 * если они здесь разойдутся с шапкой модуля, значит разошлись корпуса, а не мнения.
 */
const квантиль = (xs, q) => { const s = [...xs].sort((x, y) => x - y); return s[Math.min(s.length - 1, Math.floor(q * s.length))]; };
console.log('\n── КЛАСС 2: СЛОЖНОСТЬ ЯЗЫКА — МЕРА БЕЗ ПОРОГА ───────────────────');
for (const [имя, корпус] of [['A — владелец', A], ['C — наши партии', C]]) {
  const м = корпус.map((r) => мераСложности(r.t)).filter(Boolean);
  console.log(`  ${имя} (${м.length}):`);
  console.log(`     средняя длина фразы: медиана ${квантиль(м.map((x) => x.срДлина), 0.5)} · p90 ${квантиль(м.map((x) => x.срДлина), 0.9)}`);
  console.log(`     самая длинная фраза: медиана ${квантиль(м.map((x) => x.максДлина), 0.5)} · p90 ${квантиль(м.map((x) => x.максДлина), 0.9)}`);
  console.log(`     придаточных в самой сложной фразе: медиана ${квантиль(м.map((x) => x.максПридаточных), 0.5)} · p90 ${квантиль(м.map((x) => x.максПридаточных), 0.9)}`);
  console.log(`     запятых в самой насыщенной фразе: медиана ${квантиль(м.map((x) => x.максЗапятых), 0.5)} · p90 ${квантиль(м.map((x) => x.максЗапятых), 0.9)}`);
}
console.log('\n🔑 ЧИТАТЬ ТАК: наши фразы КОРОЧЕ его фраз. Порог по длине забраковал бы половину');
console.log('   каталога владельца и не поймал бы ни одной из карточек, возвращённых за класс 2.');
console.log('   Расходятся не длина, а ПЛОТНОСТЬ — придаточные и запятые на ту же фразу.');
console.log('   Порог здесь может назначить только владелец, и прибор его не назначает.\n');
