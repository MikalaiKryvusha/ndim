/**
 * ЮНИТ ДВЕРИ ВЫКАТА (`tools/deploy.mjs`) — `plans/79`, шаг 3.
 *
 * 🔴 ПОЧЕМУ У ДВЕРИ РАНЬШЕ НЕ БЫЛО ЮНИТА, И ПОЧЕМУ ЭТО НЕ ЛЕНЬ, А СЛЕДСТВИЕ ДЕФЕКТА.
 * До правки `plans/79` все 32 оператора двери стояли на верхнем уровне модуля. Значит юнит,
 * написанный для неё, при первом же `import` начал бы ВЫКАТ В БОЙ — сеть, сборка, `firebase
 * deploy`. Написать его было физически нельзя, и отсутствие юнита у самой опасной двери проекта
 * было не пробелом покрытия, а симптомом класса `ideas/43`.
 *
 * 🔑 ОТСЮДА ГЛАВНАЯ ПРОВЕРКА ЭТОГО ФАЙЛА — «ЗАВЕДОМО ЛОЖНОЕ УТВЕРЖДЕНИЕ ЧЕСТНО КРАСНОЕ».
 * Класс, пойманный вердиктом №16 на `team-status.mjs`, звучит так: прибор без предохранителя
 * ОТМЕНЯЕТ собственную проверяемость. Импорт исполняет CLI, тот зовёт `process.exit()`, тестовый
 * файл умирает ДО первого утверждения — и `node --test` засчитывает его пройденным:
 *
 *     тест с ЗАВЕДОМО ЛОЖНЫМ утверждением отчитывался «✔ tests 1 · pass 1 · fail 0»
 *
 * То есть зелёный такого набора не значит ничего. Проверка ниже ставит опыт наоборот: она
 * ТРЕБУЕТ, чтобы ложь была названа ложью. Пока эта проверка зелена, остальным можно верить.
 *
 * 🔴 ДВЕРЬ СПРАШИВАЕТСЯ ТОЛЬКО ДОЧЕРНИМ ПРОЦЕССОМ, хотя после правки её импорт безопасен.
 * Доктрина взята у соседа (`verify-import-safety.test.mjs`) и по той же причине: импортируй её
 * этот файл строкой `import`, и при ВОЗВРАТЕ дефекта набор умер бы молча и засчитался бы
 * пройденным — то есть проверка исчезла бы ровно в тот момент, ради которого написана.
 *
 * ⛔ ГРАНИЦА, НАЗВАННАЯ ЧЕСТНО: боевой путь двери здесь НЕ проверяется и проверяться не может —
 * он выкатывает. Судится ровно то, что судится без выката: контракт `targetFits`, код и вывод
 * `--selftest`, и безвредность импорта. Живой `--gate-only` — прогон руками, он в отчёте порции.
 *
 * Прогон: node --test tools/deploy.test.mjs   (или `npm run test:tools`)
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ЗДЕСЬ = dirname(fileURLToPath(import.meta.url));
const ДВЕРЬ = join(ЗДЕСЬ, 'deploy.mjs');
const ДВЕРЬ_URL = new URL('./deploy.mjs', import.meta.url).href;

const вНоде = (код, ...argv) => spawnSync(
	process.execPath,
	['--input-type=module', '-e', код, ...argv],
	{ encoding: 'utf8' },
);

/* ── Главное: импорт двери больше не отменяет проверяемость ──────────────────────────── */

test('🔴 ЗАВЕДОМО ЛОЖНОЕ утверждение при импортированной двери ЧЕСТНО КРАСНОЕ (класс вердикта №16)', () => {
	// Пока дверь работала на верхнем уровне, этот же набор отчитывался «pass 1 · fail 0»,
	// потому что процесс умирал раньше утверждения. Здесь мы требуем услышать «ложь».
	const r = вНоде(`
		import assert from 'node:assert/strict';
		import { test } from 'node:test';
		await import(${JSON.stringify(ДВЕРЬ_URL)});
		test('заведомо ложное', () => { assert.equal(1, 2); });
	`);
	const вывод = `${r.stdout}${r.stderr}`;
	assert.match(вывод, /fail 1/, 'ложное утверждение НЕ было названо ложным — дверь съела проверку');
	assert.notEqual(r.status, 0, 'набор с ложным утверждением вышел успехом');
});

test('🔴 ПОДКЛЮЧЁН: импорт двери не выкатывает, не ходит в сеть и не убивает чужой процесс', () => {
	/*
	 * 🔑 fetch подменяется ДО импорта и СЧИТАЕТ обращения — это замер, а не заявление.
	 * До правки на верхнем уровне стояли `await liveHash(...)` (сеть) и `await smokeGate(...)`
	 * (порты и дочерние процессы), то есть счётчик был бы ненулевым сразу.
	 */
	const r = вНоде(`
		let обращений = 0;
		globalThis.fetch = async (...а) => { обращений += 1; throw new Error('сеть запрещена в пробе: ' + а[0]); };
		await import(${JSON.stringify(ДВЕРЬ_URL)});
		console.log('ОБРАЩЕНИЙ-В-СЕТЬ:' + обращений);
		console.log('ЖИВ-ПОСЛЕ-ИМПОРТА');
	`);
	assert.match(r.stdout, /ОБРАЩЕНИЙ-В-СЕТЬ:0/, 'импорт двери сходил в сеть');
	assert.ok(r.stdout.includes('ЖИВ-ПОСЛЕ-ИМПОРТА'), 'импорт двери убил чужой процесс');
	assert.equal(r.status, 0);

	/*
	 * 🔑 ИНВАРИАНТ СИЛЬНЕЕ ПЕРЕЧНЯ СИМПТОМОВ: дверь при импорте НЕ ПРОИЗНОСИТ НИ СЛОВА.
	 *
	 * Первая редакция этой проверки перечисляла приметы выката («КОНТУР ВЫКАТА» в выводе, сеть,
	 * смерть процесса). Мутация показала дыру перечня: снятый предохранитель при argv с
	 * `--selftest` утекает ВЕТВЬЮ САМОТЕСТА — ни одной приметы из списка, а работа при импорте
	 * идёт. Перечень примет закрывает те входы, которые автор вспомнил; инвариант «молчит»
	 * закрывает все. Это тот же довод, по которому у `ideas/24` мера — доля незакрытой площади,
	 * а не «строки и колонки».
	 */
	const своё = ['ОБРАЩЕНИЙ-В-СЕТЬ:0', 'ЖИВ-ПОСЛЕ-ИМПОРТА'];
	const чужое = r.stdout.split('\n').map((s) => s.trim()).filter((s) => s && !своё.includes(s));
	assert.deepEqual(чужое, [], `дверь работала при импорте — она напечатала: ${чужое.join(' | ')}`);
	assert.equal(r.stderr.trim(), '', `дверь писала в stderr при импорте: ${r.stderr.trim()}`);
});

test('🔑 КОНТРОЛЬ ПРИБОРА: проба УМЕЕТ увидеть сеть — иначе её ноль ничего не значит', () => {
	// Без этого случая «обращений 0» зелено и при полностью сломанном счётчике (`EXP-0082`).
	const r = вНоде(`
		let обращений = 0;
		globalThis.fetch = async () => { обращений += 1; return new Response('x'); };
		await fetch('http://127.0.0.1:1/проба');
		console.log('ОБРАЩЕНИЙ-В-СЕТЬ:' + обращений);
	`);
	assert.match(r.stdout, /ОБРАЩЕНИЙ-В-СЕТЬ:1/, 'счётчик сети не считает — ноль в проверке выше бессодержателен');
});

/* ── CLI-путь: контракт не изменился ни на байт наблюдаемого ─────────────────────────── */

test('🔴 ЗАПУЩЕН: --selftest отвечает 8/8 и выходит нулём', () => {
	const r = spawnSync(process.execPath, [ДВЕРЬ, '--selftest'], { encoding: 'utf8' });
	assert.notEqual(r.stdout.trim(), '', 'самотест не ответил вовсе: предохранитель отключил дверь');
	assert.match(r.stdout, /проверок 8 · провалов 0/);
	assert.equal(r.status, 0);
});

test('🔑 самотест НЕ трогает контур: он отвечает раньше, чем дверь спросит `contourFromArgv`', () => {
	// Порядок внутри `main()` несущий: разбор контура читает argv и падает на чужом флаге.
	// Самотест обязан отвечать ДО него — иначе `--selftest` перестал бы быть безопасным.
	const r = spawnSync(process.execPath, [ДВЕРЬ, '--selftest'], { encoding: 'utf8' });
	assert.doesNotMatch(r.stdout, /КОНТУР ВЫКАТА/, 'самотест дошёл до объявления контура');
});
