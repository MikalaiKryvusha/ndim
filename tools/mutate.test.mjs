/**
 * ТЕСТ МЕХАНИЗМА МУТАЦИИ — и он стоит В ВОРОТАХ, а не флагом.
 *
 * 🔴 ПОВОД ДЛЯ ИМЕННО ТАКОГО РАЗМЕЩЕНИЯ. `npm run test:tools` берёт только `tools/*.test.mjs`.
 * Прибор, чья проверка живёт собственным `--selftest`, не позван НИКЕМ — класс «страж вне ворот»
 * (`EXP-0194`), пойманный за одну смену дважды и оба раза на одном исполнителе. Механизм, который
 * сторожит чужие доказательства, обязан сам стоять в воротах.
 *
 * Файлы мутируются ВРЕМЕННЫЕ, не рабочие: тест не имеет права зависеть от того, что в этот момент
 * лежит в дереве, и не имеет права портить дерево, если упадёт на середине.
 *
 * Прогон: node --test tools/mutate.test.mjs   (или `npm run test:tools`)
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { writeFileSync, readFileSync, rmSync, mkdtempSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';

import {
  подставить, сМутацией, совпавшиеОтветы, МутацияНеСостоялась,
} from './lib/mutate.mjs';

const ТЕКСТ = 'const a = 1;\nif (parts.length !== 2) { отказ(); }\nconst b = 2;\n';

/**
 * Временный файл на один случай — с гарантированной уборкой.
 *
 * ⚠️ УБОРКА РАЗВЕДЕНА ПО ВЕТКАМ ПО ТОЙ ЖЕ ПРИЧИНЕ, ЧТО И В САМОМ МЕХАНИЗМЕ, и первая редакция
 * помощника на этом и попалась: `finally` сносил каталог СИНХРОННО, едва работа вернула обещание,
 * и асинхронный случай падал с `ENOENT` вместо своей проверки. Тот же класс, что ловит модуль, —
 * пойман здесь на его собственном тесте.
 */
function вФайле(содержимое, работа) {
  const каталог = mkdtempSync(join(tmpdir(), 'ndim-mutate-'));
  const файл = join(каталог, 'прибор.mjs');
  writeFileSync(файл, содержимое, 'utf8');
  const убрать = () => rmSync(каталог, { recursive: true, force: true });
  try {
    const итог = работа(файл);
    if (итог && typeof итог.then === 'function') {
      return итог.then((з) => { убрать(); return з; }, (б) => { убрать(); throw б; });
    }
    убрать();
    return итог;
  } catch (беда) {
    убрать();
    throw беда;
  }
}

test('🔴 якоря нет — отказ ДО записи, файл не тронут', () => {
  вФайле(ТЕКСТ, (файл) => {
    assert.throws(
      () => подставить({ файл, якорь: 'такой строки здесь нет', мутант: 'что угодно' }),
      МутацияНеСостоялась,
    );
    assert.equal(readFileSync(файл, 'utf8'), ТЕКСТ, 'файл изменился при непопавшей мутации');
  });
});

/*
 * 🔑 ПАРА К СЛУЧАЮ ВЫШЕ, И ПООДИНОЧКЕ ОНИ БЕССМЫСЛЕННЫ. Без этого случая «отказ при нуле» была бы
 * зелёной и у механизма, который отказывает ВСЕГДА. Различает эти поведения только пара.
 */
test('якорь ровно один — подстановка проходит и подтверждается чтением', () => {
  вФайле(ТЕКСТ, (файл) => {
    const { восстановить } = подставить({
      файл, якорь: 'parts.length !== 2', мутант: 'parts.length < 2',
    });
    assert.match(readFileSync(файл, 'utf8'), /parts\.length < 2/u, 'мутант не лёг в файл');
    восстановить();
    assert.equal(readFileSync(файл, 'utf8'), ТЕКСТ);
  });
});

test('🔴 якорь встречается дважды — отказ: подстановка неоднозначна, а не «возьмём первый»', () => {
  вФайле('x = 1;\ny = 1;\n', (файл) => {
    assert.throws(
      () => подставить({ файл, якорь: '= 1;', мутант: '= 9;' }),
      (e) => e instanceof МутацияНеСостоялась && /2 раз/u.test(e.message),
    );
    assert.equal(readFileSync(файл, 'utf8'), 'x = 1;\ny = 1;\n', 'файл тронут при неоднозначной мутации');
  });
});

/*
 * 🔴 ЧЕТВЁРТЫЙ СЛОЙ «НЕ СПОСОБНА УПАСТЬ» — САМ МУТАНТ. Подстановка сама в себя проходит любой
 * контроль попадания ПО ФАКТУ: байты переписались, файл цел, `git diff` пуст. И поведение
 * тождественно исходнику — краснеть НЕ НА ЧЁМ.
 */
test('🔴 мутант тождествен якорю — отказ, иначе прогон пойдёт на неизменённом коде', () => {
  вФайле(ТЕКСТ, (файл) => {
    assert.throws(
      () => подставить({ файл, якорь: 'const a = 1;', мутант: 'const a = 1;' }),
      (e) => e instanceof МутацияНеСостоялась && /тождествен/u.test(e.message),
    );
  });
});

test('🔴 исходник возвращается, даже когда работа УПАЛА — ради падения мутация и ставится', () => {
  вФайле(ТЕКСТ, (файл) => {
    assert.throws(() => сМутацией(
      { файл, якорь: 'parts.length !== 2', мутант: 'parts.length < 2', молча: true },
      () => { throw new Error('набор упал, как и задумано'); },
    ), /набор упал/u);
    assert.equal(readFileSync(файл, 'utf8'), ТЕКСТ, 'исходник не вернулся после падения работы');
  });
});

test('исходник возвращается и при обычном возврате, а итог работы доходит до вызывающего', () => {
  вФайле(ТЕКСТ, (файл) => {
    const итог = сМутацией(
      { файл, якорь: 'parts.length !== 2', мутант: 'parts.length < 2', молча: true },
      () => readFileSync(файл, 'utf8'),
    );
    assert.match(итог, /parts\.length < 2/u, 'работа не увидела мутанта');
    assert.equal(readFileSync(файл, 'utf8'), ТЕКСТ);
  });
});

test('🔴 асинхронная работа дожидается ВНУТРИ мутации, а не после восстановления', async () => {
  await вФайле(ТЕКСТ, async (файл) => {
    const итог = await сМутацией(
      { файл, якорь: 'parts.length !== 2', мутант: 'parts.length < 2', молча: true },
      async () => {
        await new Promise((r) => { setTimeout(r, 5); });
        return readFileSync(файл, 'utf8');
      },
    );
    assert.match(итог, /parts\.length < 2/u, 'исходник вернулся раньше, чем работа прочитала мутанта');
    assert.equal(readFileSync(файл, 'utf8'), ТЕКСТ);
  });
});

test('асинхронное падение тоже возвращает исходник', async () => {
  await вФайле(ТЕКСТ, async (файл) => {
    await assert.rejects(() => сМутацией(
      { файл, якорь: 'parts.length !== 2', мутант: 'parts.length < 2', молча: true },
      async () => { throw new Error('упало асинхронно'); },
    ), /упало асинхронно/u);
    assert.equal(readFileSync(файл, 'utf8'), ТЕКСТ);
  });
});

/*
 * КОНТРОЛЬ ПО СМЫСЛУ — вторая половина класса (`EXP-0193`, заход 1: якорь ослаблен, а снятое
 * требование осталось на месте, байты при этом переписались честно).
 */
test('🔴 контроль по смыслу не сработал — работа НЕ запускается: её число ничего не значило бы', () => {
  вФайле(ТЕКСТ, (файл) => {
    let запускали = false;
    assert.throws(() => сМутацией(
      { файл, якорь: 'const a = 1;', мутант: 'const a = 7;', контроль: () => false },
      () => { запускали = true; },
    ), /контроль по смыслу не сработал/u);
    assert.equal(запускали, false, 'работа побежала при несработавшем контроле');
    assert.equal(readFileSync(файл, 'utf8'), ТЕКСТ, 'исходник не вернулся');
  });
});

test('контроль по смыслу сработал — работа идёт (пара к случаю выше)', () => {
  вФайле(ТЕКСТ, (файл) => {
    const итог = сМутацией(
      { файл, якорь: 'const a = 1;', мутант: 'const a = 7;', контроль: () => true },
      () => 'работа исполнилась',
    );
    assert.equal(итог, 'работа исполнилась');
  });
});

test('🔑 совпавшие ответы разных мутантов названы поимённо — вопроса не задали', () => {
  assert.deepEqual(совпавшиеОтветы([['м7', 'находок 4'], ['м8', 'находок 4']]), [['м7', 'м8']]);
  assert.deepEqual(совпавшиеОтветы([['м7', 'находок 2'], ['м8', 'находок 5']]), []);
});

test('отсутствие контроля по смыслу ПРОГОВАРИВАЕТСЯ, а не замалчивается', () => {
  вФайле(ТЕКСТ, (файл) => {
    const было = console.log;
    const сказано = [];
    console.log = (...а) => сказано.push(а.join(' '));
    try {
      сМутацией({ файл, якорь: 'const a = 1;', мутант: 'const a = 7;' }, () => null);
    } finally {
      console.log = было;
    }
    assert.match(сказано.join('\n'), /контроль ПО СМЫСЛУ не задан/u, 'половинчатый вердикт прошёл молча');
  });
});
