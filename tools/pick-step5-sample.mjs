/**
 * ВЫБОРКА ДЕСЯТИ СТРАНИЦ ДЛЯ ПРИЁМКИ ШАГА 5 (`plans/56`) — детерминированная.
 *
 * План требует «разные виды × три среза оценённости». Выбор берётся АЛФАВИТОМ внутри группы,
 * а не случайностью: прогон приёмки обязан повторяться, иначе «10 страниц проверено» описывает
 * один вечер, а не продукт, и следующая сессия не сможет пересмотреть те же кадры.
 *
 * Срезы оценённости — по числу голосов: 0 · 1–2 · 3 и больше. Границы взяты у самого продукта:
 * счётчик голосов на публичной странице показывается с ТРЁХ (интервью №022, одно правило внутри
 * и снаружи), значит «3+» и есть срез, где человек видит счётчик.
 *
 * Запуск: node tools/pick-step5-sample.mjs
 */
import { readFileSync } from 'node:fs';

const dims = JSON.parse(readFileSync('src/lib/content/dims-build.json', 'utf8'));
const срез = (d) => {
  const r = d.rates ?? 0;
  return r === 0 ? 'нет оценок' : r < 3 ? 'мало (1–2)' : 'есть (3+)';
};
const ЗАКАЗ = [
  ['Фильм', 'нет оценок'], ['Фильм', 'мало (1–2)'], ['Фильм', 'есть (3+)'],
  ['Видеоигра', 'нет оценок'], ['Видеоигра', 'мало (1–2)'], ['Видеоигра', 'есть (3+)'],
  ['Телесериал', 'нет оценок'], ['Телесериал', 'есть (3+)'],
  ['Роман', 'есть (3+)'],
  ['Музыкальный исполнитель', 'есть (3+)'],
];

const выбор = [];
for (const [вид, s] of ЗАКАЗ) {
  const группа = dims
    .filter((d) => (d.type?.ru ?? '') === вид && срез(d) === s)
    .filter((d) => (d.description?.ru ?? '').length > 0 && (d.description?.en ?? '').length > 0)
    .sort((a, b) => a.slug.localeCompare(b.slug));
  const d = группа[0];
  if (!d) {
    console.log(`⚠️ пусто: ${вид} · ${s} — в выборку не вошло, и это названо, а не замолчано`);
    continue;
  }
  выбор.push({ slug: d.slug, вид, срез: s, rates: d.rates ?? 0, rating: d.rating ?? null, title: d.title?.ru });
}

console.log(JSON.stringify(выбор, null, 1));
console.error(`\nвыбрано страниц: ${выбор.length} из ${ЗАКАЗ.length} заказанных`);
