import test from 'node:test';
import assert from 'node:assert/strict';
import { parseInterview, batchExitAfterDecision } from './review-core.mjs';

/** Собирает документ интервью с вариантом заданной длины. */
function документСВариантом(длина) {
	const хвост = 'ц'.repeat(Math.max(0, длина - 40));
	return [
		'# Интервью №999 — проверочное',
		'',
		'> **Статус:** 🔴 ЖДЁТ ОТВЕТА',
		'',
		'---',
		'',
		'### В1. Проверочный вопрос',
		'',
		`- **А) Длинный вариант.** Довод: ${хвост} **Цена:** ХВОСТ-МАРКЕР.`,
		'- **Б) Короткий вариант.** Довод: короткий.',
		'',
		'**Ответ:**',
		'',
	].join('\n');
}

test('текст варианта доезжает ЦЕЛИКОМ — предела длины нет', () => {
	const текст = документСВариантом(1200);
	const разбор = parseInterview('interviews/_проверочное.md', текст);
	const в1 = разбор.questions.find((q) => q.label === 'В1');
	assert.ok(в1, 'вопрос В1 не разобран — тест проверяет не то, что думает');

	const а = в1.options.find((o) => o.letter === 'А');
	assert.ok(а, 'вариант А не разобран');

	// Главное утверждение: хвост варианта — ЦЕНА — обязан быть на месте.
	assert.ok(
		а.label.includes('ХВОСТ-МАРКЕР'),
		`конец варианта потерян: длина ${а.label.length}, хвост «${а.label.slice(-40)}». ` +
			'Именно так выглядел дефект, найденный владельцем 2026-08-30: обрыв на полуслове, ' +
			'и вместе с ним — цена варианта.',
	);

	// И контроль от обратного: если бы предел вернулся, длина упёрлась бы ровно в него.
	assert.ok(
		а.label.length > 1000,
		`длина варианта ${а.label.length} — подозрительно близко к пределу; предел вернулся?`,
	);
});

test('КОНТРОЛЬ 0 — короткий вариант разбирается и не путается с длинным', () => {
	const разбор = parseInterview('interviews/_проверочное.md', документСВариантом(1200));
	const в1 = разбор.questions.find((q) => q.label === 'В1');
	const б = в1.options.find((o) => o.letter === 'Б');
	assert.ok(б, 'вариант Б не разобран — разбор видит не все варианты');
	assert.ok(б.label.length < 100, 'короткий вариант неожиданно длинный — варианты слиплись');
	assert.equal(в1.options.length, 2, 'вариантов должно быть ровно два');
});

test('пачка: сервер умирает ТОЛЬКО когда неотвеченных документов не осталось (bugs/NEW_review_batch_dies_after_first_answer)', () => {
	// Владелец 2026-09-05 ответил на первый документ пачки — сервер погас, второй и третий он писал в
	// мёртвую страницу. Решение о выходе теперь чистое и судится здесь, а не на живом владельце.
	assert.equal(batchExitAfterDecision([]), true, 'очередь пуста — пора закрываться');
	assert.equal(batchExitAfterDecision(['interviews/interview_061.md']), false, 'остался документ — жить');
	assert.equal(batchExitAfterDecision(['a.md', 'b.md']), false, 'осталось два — жить');
	assert.equal(batchExitAfterDecision(undefined), false, 'нет данных — не гадать, жить');
});
