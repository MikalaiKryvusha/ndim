/* ── КЛАСС 16: ПРОПУЩЕНО ТО, ЧТО ОН ЖДЁТ УВИДЕТЬ ─────────────────────────────────────────────
 * «*Ни слова о дате премьеры, об восприятии картины обществом =(*»
 *
 * ⚠️ 🔴 ЗАМЕР ГОВОРИТ, ЧТО ОТКАЗОМ ЭТО БЫТЬ НЕ МОЖЕТ, И ЦИФРА ЖЁСТКАЯ. В СОБСТВЕННОМ каталоге
 * владельца: описаний без полной даты — **47 из 50**, без единого слова о приёме — **29 из 50**.
 * То есть проверка, объявляющая это браком, забраковала бы почти весь его каталог. У нас без
 * приёма 27 из 50, без даты — 14.
 * 🔑 Отсюда форма: ЗАМЕЧАНИЕ-НАПОМИНАНИЕ, а не приговор. Оно говорит «этого в тексте нет», а не
 * «так нельзя», и решает человек. Шум назван вслух: на партии из 20 карточек это примерно
 * десяток строк.
 * ⏭ Скажет иначе на вычитке — правка в одну строку: список переезжает в `ownerClassProblems`.
 */
const ПОЛНАЯ_ДАТА = /(?<![\p{L}])\d{1,2}\s+(?:января|февраля|марта|апреля|мая|июня|июля|августа|сентября|октября|ноября|декабря)\s+\d{4}/iu;
const ПРИЁМ = /(?<![\p{L}])(?:критик|пресс[аы]|отзыв|приём|принят|оценк|рейтинг|награ|преми|номинац|фестивал|успех|сборы|касс)/iu;

/**
 * 16 — чего в описании нет. ЗАМЕЧАНИЕ-напоминание (разбор выше).
 *
 * 🔑 `датаВыхода` — то, что УЖЕ прочитано у реестра классом 1. Она попадает в замечание не для
 * красоты: без неё человек, увидев «нет даты премьеры», идёт её искать, а прибор эту дату в тот
 * же прогон уже узнал. Замечание, называющее недостающий факт, дешевле замечания, называющего
 * его отсутствие (правка по заказу Менеджера, смена 6: «одна правка формулировки экономит ей
 * поиск»).
 * ⚠️ Дата подставляется ТОЛЬКО как подсказка, откуда её взять, а не как готовая строка для
 * вставки в текст: владелец велел подавать дату СОБЫТИЕМ («вышла в прокат тогда-то»), а не
 * числом (класс 5).
 */
export function пропущенныйФакт(text, lang = 'ru', датаВыхода = null) {
  if (!русский(lang)) return [];
  const t = String(text ?? '');
  if (!t.trim()) return [];
  const нет = [];
  if (!ПОЛНАЯ_ДАТА.test(t)) нет.push(датаВыхода ? `даты премьеры (реестр знает: ${датаВыхода})` : 'даты премьеры');
  if (!ПРИЁМ.test(t)) нет.push('слов о приёме — награды, отзывы, сборы');
  return нет;
}

/* ── КЛАСС 15: УДИВЛЕНИЕ УБИТО ЗАРАНЕЕ ───────────────────────────────────────────────────────
 * «*фраза по твоей задумке должна нести элемент удивления, но ты в первой части раскрываешь
 * правду, а потом тянешь противопоставление — так ты ослабил свою попытку удивить читателя*».
 *
 * 🔴 ПРИЗНАК ПОЗИЦИОННЫЙ, А НЕ СЧЁТНЫЙ, И ЭТО ЕДИНСТВЕННОЕ, ЧТО ЗДЕСЬ РАБОТАЕТ. Дефект — это
 * ПОРЯДОК частей фразы. Лечение переставляет части, не трогая слов, и потому все счётные меры
 * на дефекте и на лечении дают ОДНО И ТО ЖЕ число: те же 31 слово, те же 206 знаков, те же
 * 4 запятые, то же двоеточие, те же 2 придаточных (доказательство — `tools/measure-class15.mjs`).
 * Различает их только вопрос «в какой ПОЛОВИНЕ фразы стоит раскрытие, а в какой контраст».
 *
 * 📐 Замер пяти кандидатов (A — 50 описаний владельца, C — 50 наших):
 *   · раскрытие в 1-й половине + контраст во 2-й — A **0**, C **1**, и эта одна есть ровно
 *     возвращённая карточка «Отец, мать, сестра, брат»;
 *   · слово-раскрытие где угодно — A 14, C 19: краснеет на его собственных текстах;
 *   · контраст во 2-й половине — A 9, C 17: то же самое;
 *   · двоеточие + тире — A 1, C 25: разделяет, но меряет сложность построения, то есть класс 2;
 *   · раскрытие до двоеточия — A 1, C 2: разделения нет.
 *
 * ⚠️ 🔴 ЧЕСТНАЯ ГРАНИЦА, И ОНА РЕШАЕТ СИЛУ ПРОВЕРКИ: положительный случай у признака ОДИН, и это
 * та самая фраза, из которой он выведен. Ноль ложных на 50 описаниях владельца показан прогоном,
 * а вот ловит признак КЛАСС или одну фразу — неизвестно до второй находки. Признак, подогнанный
 * под свой единственный пример, отказом ставить нельзя (`lib/gate-notes.mjs`), поэтому здесь
 * ЗАМЕЧАНИЕ.
 * ⏭ Придёт партия 6 — станет видно. Перевод в отказ будет правкой в одну строку.
 */
const РАСКРЫТИЕ_ПРАВДЫ = /(?<![\p{L}])(?:на\s+самом\s+деле|выясн[\p{L}]+|оказыва[\p{L}]+|правда\s+в\s+том|настоящ[\p{L}]+\s+(?:положение|лицо|причин[\p{L}]+)|прячет|скрывает|тайком)(?![\p{L}])/iu;
const КОНТРАСТ_ПОСЛЕ = /(?<![\p{L}])(?:но|однако|зато|пока|а\s+не|хотя)(?![\p{L}])/iu;

/** 15 — правда раскрыта до того, как сработало удивление. ЗАМЕЧАНИЕ (разбор выше). */
export function удивлениеУбито(text, lang = 'ru') {
  if (!русский(lang)) return [];
  const найдено = [];
  for (const s of splitSentences(text)) {
    const середина = Math.floor(s.length / 2);
    const раскрытие = s.slice(0, середина).match(РАСКРЫТИЕ_ПРАВДЫ);
    if (!раскрытие) continue;
    const контраст = s.slice(середина).match(КОНТРАСТ_ПОСЛЕ);
    if (!контраст) continue;
    найдено.push({ раскрытие: раскрытие[0], контраст: контраст[0], предложение: чисто(s) });
  }
  return найдено;
}

/* ── КЛАСС 2: СЛОЖНОСТЬ ЯЗЫКА — МЕРА, А НЕ ПРИГОВОР ──────────────────────────────────────────
 * «*очень сложным заковыристым тяжким в прочтении языком написано. Ошибка класса. Писать
 * проще*». Постановка Менеджера прямая: «*порогом НЕ суди. Меряй и предъявляй… порог тут может
 * назначить только владелец*».
 *
 * 🔴 И ЗАМЕР ГОВОРИТ, ЧТО ПОРОГ ПО ДЛИНЕ БЫЛ БЫ ПРОСТО НЕВЕРЕН. Наши фразы КОРОЧЕ его фраз:
 *
 *   | Мера (медиана по записи)          | A — владелец | C — наши партии |
 *   |-----------------------------------|-------------:|----------------:|
 *   | средняя длина фразы, знаков       | **154**      | 128             |
 *   | самая длинная фраза, знаков       | **223**      | 217             |
 *   | придаточных в самой сложной фразе | 1            | **2**           |
 *   | запятых в самой насыщенной фразе  | 4            | **5**           |
 *
 * А обе карточки, возвращённые ИМЕННО за класс 2, лежат внутри его же диапазона: «Простая
 * случайность» — средняя 131, самая длинная 259; «Невеста» — 135 и 209. Порог по длине не
 * поймал бы ни одну и забраковал бы половину каталога владельца.
 * 🔑 Расходятся не длина, а ПЛОТНОСТЬ: при более коротких фразах у нас больше придаточных и
 * запятых на ту же фразу. Поэтому мера отдаёт и то, и другое, и решение оставляет человеку.
 */
const ПОДЧИНИТЕЛЬНЫЙ = /(?<![\p{L}])(?:котор[\p{L}]+|что|чтобы|где|куда|когда|пока|если|хотя|поскольку|потому\s+что|так\s+как|чем|чей|чья|чьи|будто|словно|ибо)(?![\p{L}])/giu;

/**
 * МЕРА СЛОЖНОСТИ ОДНОГО ОПИСАНИЯ. Ничего не судит и ничего не запрещает — только считает.
 * Возвращает `null` для нерусского текста и для пустого: числа без материала были бы враньём.
 */
export function мераСложности(text, lang = 'ru') {
  if (!русский(lang)) return null;
  const ss = splitSentences(text);
  if (!ss.length) return null;
  const длины = ss.map((s) => s.length);
  const придаточные = ss.map((s) => (s.match(ПОДЧИНИТЕЛЬНЫЙ) ?? []).length);
  const запятые = ss.map((s) => (s.match(/,/gu) ?? []).length);
  const самая = ss[длины.indexOf(Math.max(...длины))];
  return {
    фраз: ss.length,
    срДлина: Math.round(длины.reduce((a, b) => a + b, 0) / ss.length),
    максДлина: Math.max(...длины),
    максПридаточных: Math.max(...придаточные),
    максЗапятых: Math.max(...запятые),
    самаяДлинная: чисто(самая),
  };
}

