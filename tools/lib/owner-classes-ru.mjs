import { splitSentences } from './prose-gates.mjs';
import { PRODUCTION_ACTIVE_WORDS } from './production-verbs.mjs';

const русский = (lang) => lang === 'ru';
const чисто = (s) => String(s ?? '').trim().replace(/\s+/gu, ' ');

/* ── КЛАСС 3: ПРОТИВОПОСТАВЛЕНИЕ ─────────────────────────────────────────────────────────────
 * «*зачем но и приём противопоставления? Я сто раз говорил… что я говорю не от
 * противопоставления. Я утверждаю факты*».
 * Замечание, а не отказ: у него самого «но» 22 раза на 50 описаний, «однако» — 10.
 * «Зато» держится в том же списке, хотя в корпусе A его нет: это ОДИН класс, и разводить его
 * слова по разной строгости значило бы объяснять человеку, почему одно слово останавливает
 * работу, а соседнее нет. Довод против отказа тут общий — корпус A мал (50 записей), и ноль в
 * нём не то же самое, что ноль в каталоге на 5121 запись.
 */
export const ПРОТИВОПОСТАВЛЕНИЕ = [
  [/(?<![\p{L}])но(?![\p{L}])/iu, 'но'],
  [/(?<![\p{L}])однако(?![\p{L}])/iu, 'однако'],
  [/(?<![\p{L}])зато(?![\p{L}])/iu, 'зато'],
];

/** Слова противопоставления с фразой, в которой они стоят. ЗАМЕЧАНИЕ: решает человек. */
export function противопоставление(text, lang = 'ru') {
  if (!русский(lang)) return [];
  const найдено = [];
  for (const s of splitSentences(text)) {
    for (const [образец, имя] of ПРОТИВОПОСТАВЛЕНИЕ) {
      /* Образцы объявлены БЕЗ флага `g` намеренно: `g` + `.test()` помнит позицию между
       * вызовами и через раз отвечает `false` на одном и том же входе. */
      if (образец.test(s)) найдено.push({ слово: имя, предложение: чисто(s) });
    }
  }
  return найдено;
}

/* ── КЛАСС 4: ЗАПРЕТ ТЕРМИНА «ПОЛНЫЙ МЕТР» ───────────────────────────────────────────────────
 * «*Запрет на термин "метр" в смысле типа полнометражного фильма. Это называется
 * Полнометражный*». Встретился ДВАЖДЫ в одной партии, а всего в партиях 1–4 — трижды.
 * Образец берёт только связку «полн… метр…»: голое «метр» — единица длины и часть слова
 * «метраж», запрещать его владелец не просил.
 */
const ПОЛНЫЙ_МЕТР = /(?<![\p{L}])полн[\p{L}]*\s+метр[\p{L}]*/giu;

/** Запрещённый термин. ОТКАЗ: ноль на текстах владельца. */
export function полныйМетр(text, lang = 'ru') {
  if (!русский(lang)) return [];
  return [...new Set((String(text ?? '').match(ПОЛНЫЙ_МЕТР) ?? []).map(чисто))];
}

/* ── КЛАСС 5: ЗАГОЛОВОК-ОБРУБОК ПРО ДАТЫ ─────────────────────────────────────────────────────
 * «*"Первые даты выхода" — некрасивая форма*» и, второй карточкой, «*"Даты выхода" — некрасиво
 * так писать. Ошибка класса*». Как надо — его словами: «*Картина вышла в прокат тогда-то.
 * Представлена на таком-то событии тогда-то. Вышла в свет тогда-то*».
 *
 * 🔴 РАЗДЕЛЯЮЩИЙ ПРИЗНАК — ТИРЕ, А НЕ САМИ СЛОВА, и это назначено замером, а не осторожностью.
 * Некрасива ФОРМА «заголовок — перечень», а не словосочетание «дата выхода». Живая строка
 * партии 2: «*Премьера прошла 25 декабря 2025 года в США, следующие даты выхода пришлись на
 * 22 января…*» — те же слова, полная фраза со сказуемым, претензии нет. Образец без условия
 * тире объявил бы её браком.
 * 📐 С условием: 8 срабатываний на партиях 1–4, 0 на текстах владельца, ложных 0.
 */
const ДАТЫ_ОБРУБКОМ = /(?<![\p{L}])(?:перв[\p{L}]+\s+)?дат[аы]\s+выхода\s*[—–-]/giu;

/** Заголовок-обрубок про даты. ОТКАЗ: ноль на текстах владельца. */
export function датыОбрубком(text, lang = 'ru') {
  if (!русский(lang)) return [];
  return [...new Set((String(text ?? '').match(ДАТЫ_ОБРУБКОМ) ?? []).map(чисто))];
}

/* ── КЛАСС 6: КАНЦЕЛЯРСКОЕ «ДЕЙСТВИЕ РАЗВЁРНУТО» ─────────────────────────────────────────────
 * «*"Действие развёрнуто" - действие разворачивается! Ошибка класса!*»
 * Менеджер заказал ловить «и его род», поэтому образец берёт все четыре короткие формы.
 * ⛔ Шире класса прибор не идёт: обобщать до «любого отглагольного канцелярита» нечем — замера
 * под такой список нет, а владелец назвал ровно это слово. Оккам.
 */
const РАЗВЁРНУТО = /(?<![\p{L}])развёрнут[аоы]?(?![\p{L}])/giu;

/** Короткая страдательная форма «развёрнут». ОТКАЗ: ноль на текстах владельца. */
export function канцелярит(text, lang = 'ru') {
  if (!русский(lang)) return [];
  const найдено = [];
  for (const s of splitSentences(text)) {
    const m = s.match(РАЗВЁРНУТО);
    if (m) найдено.push({ форма: чисто(m[0]), предложение: чисто(s) });
  }
  return найдено;
}

/* ── КЛАСС 7: ГЛАГОЛ ПРОИЗВОДСТВА С МЕСТОИМЕНИЕМ ВМЕСТО КОРОТКОЙ ФОРМЫ ───────────────────────
 * «*"поставила его" - поставлен*». Живые случаи партий: «*поставила его Мэгги Джилленхол*»
 * (возвращённая «Невеста») и «*Тоби Фокса, который написал её*» (Deltarune).
 *
 * ✅ Признак узкий по двум условиям сразу, и оба нужны:
 *   · глагол — из списка производства (`production-verbs.mjs`, откалиброван Дизайнером). Сюжетное
 *     «взял его», «нашёл её» под класс не попадает;
 *   · сразу за глаголом — местоимение-объект. Именно оно отодвигает короткую форму: «поставила
 *     его Мэгги» → «поставлен Мэгги».
 * 📐 Ноль на 50 описаниях владельца, 2 на наших.
 */
const МЕСТОИМЕНИЕ = ['его', 'её', 'ее', 'их'];
const ПРОИЗВОДСТВО_С_МЕСТОИМЕНИЕМ = new RegExp(
  `(?<![\\p{L}])(${PRODUCTION_ACTIVE_WORDS.ru.join('|')})\\s+(${МЕСТОИМЕНИЕ.join('|')})(?![\\p{L}])`,
  'giu',
);

/** Производственный глагол с местоимением. ОТКАЗ: ноль на текстах владельца. */
export function местоимениеВместоКороткойФормы(text, lang = 'ru') {
  if (!русский(lang)) return [];
  const найдено = [];
  for (const s of splitSentences(text)) {
    for (const m of s.matchAll(ПРОИЗВОДСТВО_С_МЕСТОИМЕНИЕМ)) {
      найдено.push({ оборот: чисто(m[0]), предложение: чисто(s) });
    }
  }
  return найдено;
}

/* ── КЛАСС 9: ФАКТ БРОШЕН ОБРУБКОМ ВМЕСТО ФРАЗЫ ──────────────────────────────────────────────
 * «*"музыка электронная" - брошено как между делом на отъебись. Я бы написал: Музыкальный ряд
 * игры выполнен в электронном стиле*». Заказ Менеджера: брать ЗАМЕРОМ-ПРЕДЪЯВЛЕНИЕМ, а не
 * отказом, — «*машинный признак тут легко переусердствует*».
 *
 * ═══ КАК ПРИЗНАК СУЖАЛСЯ, И ПОЧЕМУ ОБ ЭТОМ НАПИСАНО ═══
 *
 * Первая редакция звучала честно: «короткий хвост после запятой без глагола». Замер её убил —
 * **59 срабатываний на 50 описаниях владельца**: «*ставшего мишенью*», «*включая премию
 * "Грэмми"*», «*возглавляемую Сэл (Тильда Суинтон)*». Это причастные и предложные хвосты, они
 * законны и к делу не относятся.
 *
 * ✅ Разделило совсем другое — **ПОРЯДОК СЛОВ**. Обрубок владельца устроен как предикация без
 * связки: ИМЯ, потом ПРИЗНАК («музыка электронная»). Обычное словосочетание идёт наоборот
 * («электронная музыка») и обрубком не читается. Отсюда три условия:
 *   · ровно два слова, оба со строчной (заглавная — имя собственное, «Новая Зеландия»);
 *   · первое НЕ похоже на прилагательное или косвенную форму — то есть это имя в именительном;
 *   · второе — полное прилагательное.
 * 📐 Замер этой редакции: корпус владельца — **0**, наши партии 1–4 — **1**, и эта одна есть
 * ровно та строка, за которую он вернул карточку. Контроль стоит юнитом: его собственное
 * лечение («Музыкальный ряд игры выполнен в электронном стиле») обязано проходить молча.
 *
 * ⛔ ЧЕСТНАЯ ГРАНИЦА: морфологии у прибора нет, он судит по окончаниям. Обрубок из трёх слов и
 * обрубок с существительным на конце («жанр — хоррор») он не увидит. Это названо, а не спрятано
 * за зелёным прогоном.
 */
const ПРИЛАГАТЕЛЬНОЕ = /(?:ый|ий|ой|ая|яя|ое|ее|ые|ие)$/iu;
const КОСВЕННАЯ_ФОРМА = /(?:ым|им|ом|ем|ых|их|ому|ему|ую|юю|его|ого|ет|ёт|ут|ют|ит|ат|ят|ал|ял|ил|ел|ла|ло|ли|ся|сь|ть|чь)$/iu;
/** Служебные слова: с них обрубок не начинается — начинается придаточное или оборот. */
const СЛУЖЕБНОЕ = new Set(('в на с со к ко по из от до для при о об про за под над без через между а и но да или либо '
  + 'что чем как кто где когда чтобы если хотя пока же не ни то так там тут этот эта это эти его её их им ими '
  + 'который которая которое которые сам сама само сами вместе кроме вроде ради лишь только даже уже ещё').split(' '));

/** Обрубки «имя + прилагательное». ЗАМЕЧАНИЕ: предъявляется человеку и работу не останавливает. */
export function обрубкиФактов(text, lang = 'ru') {
  if (!русский(lang)) return [];
  const найдено = [];
  for (const s of splitSentences(text)) {
    const куски = [];
    const хвост = s.match(/,\s*([^,;:—–]{3,40})[.!?]\s*$/u);
    if (хвост) куски.push(хвост[1].trim());
    const целое = s.replace(/[.!?]+\s*$/u, '').trim();
    if (!/[,;:—–]/u.test(целое)) куски.push(целое);

    for (const кусок of куски) {
      const w = кусок.match(/[\p{L}-]+/gu) ?? [];
      if (w.length !== 2) continue;
      if (w.some((x) => /^\p{Lu}/u.test(x))) continue;
      if (СЛУЖЕБНОЕ.has(w[0].toLowerCase())) continue;
      if (ПРИЛАГАТЕЛЬНОЕ.test(w[0]) || КОСВЕННАЯ_ФОРМА.test(w[0])) continue;   // первое — ИМЯ
      if (!ПРИЛАГАТЕЛЬНОЕ.test(w[1])) continue;                                 // второе — ПРИЗНАК
      найдено.push({ обрубок: кусок, предложение: чисто(s) });
    }
  }
  return найдено;
}

/* ── КЛАСС 2: СЛОЖНОСТЬ ЯЗЫКА — МЕРА, А НЕ ПРИГОВОР ──────────────────────────────────────────
 * «*очень сложным заковыристым тяжким в прочтении языком написано. Ошибка класса. Писать
 * проще*». Постановка Менеджера прямая: «*порогом НЕ суди. Меряй и предъявляй… порог тут может
 * назначить только владелец*».
 *
 * 🔴 И ЗАМЕР ГОВОРИТ, ЧТО ПОРОГ ПО ДЛИНЕ БЫЛ БЫ ПРОСТО НЕВЕРЕН. Наши фразы КОРОЧЕ его фраз:
 *
 *   | Мера (медиана по записи)          | A — владелец | C — наши партии |
 *   |-----------------------------------|-------------:|----------------:|
 *   | средняя длина фразы, знаков       | **154**      | 128             |
 *   | самая длинная фраза, знаков       | **223**      | 217             |
 *   | придаточных в самой сложной фразе | 1            | **2**           |
 *   | запятых в самой насыщенной фразе  | 4            | **5**           |
 *
 * А обе карточки, возвращённые ИМЕННО за класс 2, лежат внутри его же диапазона: «Простая
 * случайность» — средняя 131, самая длинная 259; «Невеста» — 135 и 209. Порог по длине не
 * поймал бы ни одну и забраковал бы половину каталога владельца.
 * 🔑 Расходятся не длина, а ПЛОТНОСТЬ: при более коротких фразах у нас больше придаточных и
 * запятых на ту же фразу. Поэтому мера отдаёт и то, и другое, и решение оставляет человеку.
 */
const ПОДЧИНИТЕЛЬНЫЙ = /(?<![\p{L}])(?:котор[\p{L}]+|что|чтобы|где|куда|когда|пока|если|хотя|поскольку|потому\s+что|так\s+как|чем|чей|чья|чьи|будто|словно|ибо)(?![\p{L}])/giu;

/**
 * МЕРА СЛОЖНОСТИ ОДНОГО ОПИСАНИЯ. Ничего не судит и ничего не запрещает — только считает.
 * Возвращает `null` для нерусского текста и для пустого: числа без материала были бы враньём.
 */
export function мераСложности(text, lang = 'ru') {
  if (!русский(lang)) return null;
  const ss = splitSentences(text);
  if (!ss.length) return null;
  const длины = ss.map((s) => s.length);
  const придаточные = ss.map((s) => (s.match(ПОДЧИНИТЕЛЬНЫЙ) ?? []).length);
  const запятые = ss.map((s) => (s.match(/,/gu) ?? []).length);
  const самая = ss[длины.indexOf(Math.max(...длины))];
  return {
    фраз: ss.length,
    срДлина: Math.round(длины.reduce((a, b) => a + b, 0) / ss.length),
    максДлина: Math.max(...длины),
    максПридаточных: Math.max(...придаточные),
    максЗапятых: Math.max(...запятые),
    самаяДлинная: чисто(самая),
  };
}

