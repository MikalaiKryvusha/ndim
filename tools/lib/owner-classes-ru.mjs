    ...канцелярит(text, lang).map((h) => `класс 6, канцелярит: «${h.форма}» — действие разворачивается`),
    ...местоимениеВместоКороткойФормы(text, lang).map((h) => `класс 7, местоимение вместо короткой формы: «${h.оборот}»`),
    ...незакрытаяФраза(text, lang).map((h) => `класс 12, незакрытая фраза: «${h.оборот}» — ${h.признак}`),
