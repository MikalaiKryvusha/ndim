/**
 * КАНАЛ ПРЕДЪЯВЛЕНИЯ ЗАМЕЧАНИЙ — общий для всех ворот (постановка Менеджера, кусок 2, часть 2).
 *
 * ═══ ЗАЧЕМ ═══
 *
 * У ворот проекта было ровно одно слово — ОТКАЗ. Всё, что «стоит взглянуть, но запрещать нельзя»,
 * приходилось либо втискивать в отказ, либо молчать о нём. Оба выхода плохи, и оба уже оплачены:
 *
 *   · втиснуть в отказ — значит запретить писать так, как пишет владелец. Признак «be + причастие
 *     + by + названный деятель» дал **9 срабатываний на его собственных текстах** и был снят
 *     замером (`EXP-0192`); порог доли меты снят решением Менеджера по той же причине;
 *   · промолчать — значит спрятать находку за зелёным прогоном. Строчная латиница на замере
 *     56 карточек оказалась законной во всех живых случаях («screenlife» — термин, которым
 *     режиссёр сам называет свой приём), но НЕ показать её было бы умолчанием.
 *
 * Третьего слова у ворот не было, и каждая проверка изобретала его заново: доля меты печатает
 * предложения сама, артефактное подлежащее живёт отдельной функцией `proseNotes`, которую до
 * 2026-08-22 не звал НИКТО, а пятая проверка мастерской завела себе локальный массив `notes`,
 * которым пользовалась она одна. Три решения одной задачи в трёх местах — это пара, которая
 * молча разъедется (`AGENT_GUIDE.md` → «истина ↔ зеркало»).
 *
 * ═══ ЧТО ЭТО ЗА СЛОВО ═══
 *
 * **ЗАМЕЧАНИЕ — это находка, которую прибор ПРЕДЪЯВЛЯЕТ человеку и на которой НЕ настаивает.**
 * Оно печатается ВСЕГДА, в том числе при зелёном прогоне, и НИКОГДА не меняет код выхода.
 *
 * Когда находка обязана быть замечанием, а не отказом (правило выведено из уже принятых решений,
 * а не сочинено): **если признак краснеет хотя бы на одном тексте, который владелец написал или
 * одобрил, — он замечание.** Ноль на эталоне получают прогоном, а не уверенностью (`EXP-0192`).
 *
 * ⛔ ЧЕМ ЗАМЕЧАНИЕ НЕ ЯВЛЯЕТСЯ. Это не «мягкий отказ» и не способ протащить недоказанный признак
 * в ворота. Проверка, которая ДОЛЖНА запрещать (обязательные теги, объём, зачин с названия,
 * смешение алфавитов внутри слова), остаётся отказом: у неё ноль ложных на живом корпусе, и
 * прятать её в замечания значило бы разоружить ворота.
 *
 * ═══ УСТРОЙСТВО ═══
 *
 * Корзина, а не глобальный список: у каждого прогона своя, и два прибора в одном процессе не
 * смешивают вывод. Формат строки один на все ворота — `<адрес> · <проверка>: <сообщение>` —
 * потому что человек читает их подряд и не должен угадывать, кто из приборов это написал.
 *
 * 🟢 ФАЙЛ БЕЗОПАСЕН ДЛЯ ИМПОРТА: работы на верхнем уровне нет.
 *
 * Проверки: node --test tools/gate-notes.test.mjs   ·   npm run test:tools
 */

/** Заголовок блока — один на все ворота, чтобы человек узнавал его в любом отчёте. */
export const ЗАГОЛОВОК = '🟡 ПРЕДЪЯВЛЕНО ЧЕЛОВЕКУ (не отказ)';

/** Подпись под блоком: замечание не останавливает работу, и об этом сказано вслух. */
export const ПОДПИСЬ = 'Замечание не запрещает работу: прибор показал строку — решает человек.';

/**
 * Корзина замечаний одного прогона.
 *
 * `добавить` принимает `проверка` (кто нашёл), `адрес` (где — карточка, язык, правка) и
 * `сообщение`. Ни одно из трёх не факультативно: замечание без адреса человек не найдёт, а
 * без имени проверки не поймёт, кому верить.
 */
export function создатьКорзину() {
  const строки = [];
  return {
    добавить(проверка, адрес, сообщение) {
      if (!сообщение) return;
      строки.push({ проверка, адрес, сообщение });
    },
    /** Добавляет сразу список сообщений одной проверки. Пустой список — ничего не делает. */
    добавитьВсе(проверка, адрес, сообщения) {
      for (const с of сообщения ?? []) this.добавить(проверка, адрес, с);
    },
    список: () => [...строки],
    пусто: () => строки.length === 0,
    /** Готовые строки отчёта. Пустая корзина даёт пустой массив — заголовок не печатается. */
    строкиОтчёта() {
      if (!строки.length) return [];
      return [
        '',
        `${ЗАГОЛОВОК} — ${строки.length}:`,
        ...строки.map((з) => `   · ${з.адрес} · ${з.проверка}: ${з.сообщение}`),
        `   ${ПОДПИСЬ}`,
      ];
    },
    /** Печать блока. Вынесена сюда, чтобы формат не разъехался между воротами. */
    напечатать(вывод = console.log) {
      for (const с of this.строкиОтчёта()) вывод(с);
    },
  };
}
