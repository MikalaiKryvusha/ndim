/**
 * ПАРНЫЙ ЮНИТ САМОТЕСТА — общая половина восьми обёрток (эскалация QA смены 14).
 *
 * ═══ ЗАЧЕМ ПАРА ПРИБОРУ, У КОТОРОГО УЖЕ ЕСТЬ `--selftest` ═══
 *
 * **Самотест не способен поймать собственный незапуск.** Сломай стражу предохранитель наоборот —
 * и `--selftest` промолчит, напечатав ноль символов, а прогон отчитается успехом. Прибор в
 * воротах, чей самотест не зовут, стережёт ровно до первой правки, после которой молча перестаёт
 * стеречь: сам зелёный, ворота зелёные, красного не видит никто.
 * Формулировка принадлежит `tools/verify-import-safety.test.mjs`, и она же — довод эскалации:
 * замер по дереву дал **28 приборов с `--selftest`, у 17 пары нет, восемь из них стоят в воротах**.
 *
 * ═══ ПОЧЕМУ ОБЩИЙ МОДУЛЬ, А НЕ ШЕСТЬ КОПИЙ ЧЕТЫРЁХ УТВЕРЖДЕНИЙ ═══
 *
 * Форма обкатана проектом 11 раз, и все 11 раз она одна и та же. Шесть копий разъехались бы на
 * первой правке — и разъехались бы молча, потому что каждая копия остаётся зелёной сама по себе.
 * Здесь она живёт в одном месте, а КАЖДЫЙ вызов приносит СВОЙ образец итоговой строки: общая
 * механика, частный признак.
 *
 * 🔴 **ОБРАЗЕЦ ОБЯЗАН ЛОВИТЬ ЧИСЛО СЛУЧАЕВ, А НЕ ПРОСТО СЛОВО «чисто».** Самотест, не выполнивший
 * ни одного случая, печатает то же самое слово, что и выполнивший пятьдесят два, — и «зелено» на
 * нуле наблюдений неотличимо от здоровья (`TESTING_FRAMEWORK.md` правило 10, вопрос 3). Поэтому
 * помощник ТРЕБУЕТ группу-число и проверяет, что она больше нуля.
 * ⚠️ И образцы у приборов РАЗНЫЕ — их четыре вида на шесть приборов («самотест пройден: N
 * случаев» · «САМОТЕСТ: случаев N, провалов 0» · «САМОТЕСТ ЧИСТ: случаев N» · «проверок N ·
 * провалов 0»). Общей формы у самотестов проекта нет, и подгонять их под одну ЗДЕСЬ нельзя: это
 * правка восьми чужих приборов ради красоты пары. Поэтому образец приходит снаружи.
 *
 * ═══ ПОЧЕМУ ТОЛЬКО ДОЧЕРНИМ ПРОЦЕССОМ ═══
 *
 * Прибор спрашивается `spawnSync`, а не `import`. Сломанный предохранитель зовёт `process.exit()`,
 * и он убивает САМ ПРОГОН НАБОРА: вердикт читается как «тесты не запускались» вместо «предохранитель
 * снят», а `node --test` засчитывает такой файл пройденным. То есть страж исчез бы ровно в тот
 * момент, ради которого заведён (`EXP-0188` п.3, оплачено дважды).
 */

import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

/** Каталог `tools/` — от собственного файла, а не от `cwd`: юнит зовут из разных мест. */
const TOOLS = dirname(dirname(fileURLToPath(import.meta.url)));

/**
 * Спросить самотест прибора дочерним процессом.
 *
 * @param {string} прибор имя без `.mjs`
 * @param {string[]} [argv] дополнительные аргументы
 */
export function спроситьСамотест(прибор, argv = []) {
  const путь = join(TOOLS, `${прибор}.mjs`);
  const r = spawnSync(process.execPath, [путь, '--selftest', ...argv], { encoding: 'utf8' });
  return { stdout: r.stdout ?? '', stderr: r.stderr ?? '', status: r.status, путь };
}

/**
 * Спросить прибор В РАБОЧЕМ РЕЖИМЕ, без `--selftest`.
 *
 * 🔴 Нужно двум приборам воротной восьмёрки, у которых самотеста НЕТ ВОВСЕ
 * (`verify-sync-server-name`, `qa-journeys-lint`): звать нечего, а защищены они не лучше
 * остальных — хуже. Для них парная проверка судит другой предмет, и он назван в их файлах.
 */
export function спроситьПрогон(прибор, argv = []) {
  const путь = join(TOOLS, `${прибор}.mjs`);
  const r = spawnSync(process.execPath, [путь, ...argv], { encoding: 'utf8' });
  return { stdout: r.stdout ?? '', stderr: r.stderr ?? '', status: r.status, путь };
}

/**
 * Разобрать ответ самотеста по ОБРАЗЦУ ВЫЗЫВАЮЩЕГО.
 *
 * @param {string} stdout
 * @param {RegExp} образец обязан нести ровно одну группу — ЧИСЛО случаев
 * @returns {{ ответил: boolean, число: number|null }}
 */
export function разобратьОтвет(stdout, образец) {
  const m = stdout.match(образец);
  return { ответил: stdout.trim() !== '', число: m ? Number(m[1]) : null };
}

/**
 * Импорт прибора не смеет ни работать, ни убивать чужой процесс.
 *
 * Отдельная проба, а не проверка внутри самотеста: самотест исполняется ПОД ЗАПУСКОМ, то есть
 * ровно в том режиме, где предохранитель заведомо пропускает. Незапуск проверяется снаружи или
 * не проверяется вовсе.
 */
export function спроситьИмпорт(прибор) {
  const url = new URL(`../${прибор}.mjs`, import.meta.url).href;
  const r = spawnSync(
    process.execPath,
    ['--input-type=module', '-e', `await import(${JSON.stringify(url)}); console.log('ЖИВ-ПОСЛЕ-ИМПОРТА');`],
    { encoding: 'utf8' },
  );
  const stdout = r.stdout ?? '';
  return {
    жив: stdout.includes('ЖИВ-ПОСЛЕ-ИМПОРТА'),
    // Всё, кроме нашей метки, — это работа, которую импорт исполнять не имел права.
    лишнее: stdout.replace('ЖИВ-ПОСЛЕ-ИМПОРТА', '').trim(),
    status: r.status,
  };
}
