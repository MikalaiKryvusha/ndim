/** Порог длины, ниже которого хватает ОДНОГО производственного слова (правило контракта §4). */
export const SHORT_SENTENCE = 140;

const обр = (...основы) => основы.map((o) => new RegExp(String.raw`(?<![\p{L}])` + o, 'iu'));

/** Производственный лексикон — как объект СДЕЛАН: кто, где, когда, на чьи деньги. */
export const META_MARKERS = {
  ru: обр('продюс', 'сопродюс', 'студи[ияюей]', 'кинокомпани', 'производств', 'произв[ёе]л',
    'сн[ияи]ма[лн]', 'съ[её]мк', 'прокат', 'премьер', 'дистрибь', 'бюджет', 'монтаж',
    'оператор', 'композитор', 'сценари', 'выпуск', 'издател', 'разработчик', 'релиз', 'дубляж',
    'постановщик', 'дата выхода', 'вышел в прокат', 'экранизац'),
  en: обр('producer', 'produced', 'production', 'studio', 'filming', 'shooting', 'distribut',
    'premiere', 'budget', 'editing', 'cinematograph', 'composer', 'screenplay', 'release',
    'publisher', 'developer', 'score is by', 'directed by', 'written by'),
};

/**
 * Лексикон ПРИЁМА — как объект приняли. Слово владельца: такие строки он пишет сам и одобряет,
 * поэтому они выводят предложение из меты, а не добавляют к ней.
 * ⚠️ `преми[яюий]` и `премьер` разведены намеренно: премия — приём, премьера — выпуск.
 */
export const RECEPTION_MARKERS = {
  ru: обр('отзыв', 'критик', 'рецензи', 'принят', 'оценил', 'награ[дж]', 'преми[яюий]',
    'номинац', 'успех', 'успешн', 'провал', 'культов', 'признан', 'зрител', 'аудитори',
    'кассов', 'сборы', 'популярн'),
  en: обр('review', 'critic', 'reception', 'acclaim', 'award', 'nominat', 'success',
    'flop', 'cult', 'audience', 'praise', 'panned', 'box office', 'popular'),
};

const счёт = (s, образцы) => образцы.filter((re) => re.test(s)).length;

/**
 * КЛАСС ОДНОГО ПРЕДЛОЖЕНИЯ: `мета` · `приём` · `содержание`.
 * Приём проверяется ПЕРВЫМ и побеждает мету — это граница класса, названная владельцем.
 */
export function classifySentence(предложение, lang = 'ru') {
  const s = String(предложение ?? '');
  const мета = META_MARKERS[lang] ? счёт(s, META_MARKERS[lang]) : 0;
  const приём = RECEPTION_MARKERS[lang] ? счёт(s, RECEPTION_MARKERS[lang]) : 0;
  if (приём >= 1) return { класс: 'приём', мета, приём };
  const порог = s.length < SHORT_SENTENCE ? 1 : 2;
  return { класс: мета >= порог ? 'мета' : 'содержание', мета, приём };
}

/**
 * ДОЛЯ МЕТЫ ПО ОДНОМУ ОПИСАНИЮ. Возвращает и число, и САМИ предложения — прибор обязан
 * предъявлять, а не только считать. Разбивку на предложения берёт у ворот прозы: словарь
 * сокращений и правило инициала в проекте одни на всех, копий не заводим.
 */
export function metaShare(text, lang = 'ru', splitSentences) {
  const ss = splitSentences(text);
  const разобранные = ss.map((s) => ({ предложение: s, ...classifySentence(s, lang) }));
  const мета = разобранные.filter((x) => x.класс === 'мета');
  const приём = разобранные.filter((x) => x.класс === 'приём');
  return {
    всего: ss.length,
    мета: мета.length,
    приём: приём.length,
    доля: ss.length ? Math.round((100 * мета.length) / ss.length) : 0,
    предложенияМеты: мета,
    предложенияПриёма: приём,
  };
}

/** Незаполненное поле каталога несёт `-`; это и есть признак «нет», найденный в данных. */
const заполнено = (v) => {
  const s = String(v ?? '').trim();
  return s !== '' && s !== '-' && s !== '—';
};

/**
 * ДОПУСК В КОРПУС КАЛИБРОВКИ — есть автор И есть выпуск.
 * Проверяет ПРИБОР, а не память вызывающего: у практик обвязки нет по построению, и их ноль
 * в корпусе назначил бы норму нулевой.
 */
export function eligibleForCalibration(запись) {
  const автор = запись?.author;
  const имя = typeof автор === 'string' ? автор : (автор?.ru || автор?.en);
  return заполнено(имя) && заполнено(запись?.year);
}

/** Ряд «Матрицы» — единственный эталон, названный владельцем. Семь записей, и это мало. */
export const MATRIX_ROW = /матриц|matrix/iu;
export const MATRIX_ROW_SIZE = 7;

/**
 * Заголовок записи ОДНОЙ строкой, в какой бы форме он ни лежал.
 *
 * 🔴 Повод не теоретический: первая редакция отбора спрашивала `x.title.ru`, а прибор кормил её
 * записями, где `title` уже сведён к СТРОКЕ. Отбор дал **0 из 5125** там, где разведка находила
 * 7, — и вышло бы это не ошибкой, а пустым корпусом, о котором прибор бодро отчитался. Пара
 * «истина ↔ зеркало» между формой данных и формой отбора теперь снята: форму опознаёт функция.
 */
export const заголовокСтрокой = (запись) => {
  const t = запись?.title;
  if (!t) return '';
  return typeof t === 'string' ? t : `${t.ru ?? ''} ${t.en ?? ''}`;
};

/**
 * СБОРКА КОРПУСА КАЛИБРОВКИ. Непригодную запись НЕ пропускает и называет причину — расширять
 * эталон непригодным материалом нельзя, а молчаливый пропуск и есть способ его расширить.
 */
export function buildCalibrationCorpus(записи, отбор = (x) => MATRIX_ROW.test(заголовокСтрокой(x))) {
  const названные = (записи ?? []).filter(отбор);
  const принятые = названные.filter(eligibleForCalibration);
  const отклонённые = названные.filter((x) => !eligibleForCalibration(x))
    .map((x) => ({ имя: заголовокСтрокой(x) || x?.slug || '?', причина: 'нет автора или выпуска — в калибровку не идёт' }));
  return { принятые, отклонённые, названо: названные.length };
}
