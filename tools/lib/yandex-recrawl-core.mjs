/**
 * ЧИСТАЯ ЛОГИКА МАШИННОЙ ПОДАЧИ ПЕРЕОБХОДА — что отправлять, сколько и как понимать ответы.
 *
 * Сети здесь нет: всё, что можно решить до вызова, решается тут и покрывается юнитами.
 * Сетевая часть — `tools/yandex-recrawl.mjs`; читающая библиотека API (`lib/yandex-webmaster.mjs`)
 * остаётся ЧИТАЮЩЕЙ намеренно — её шапка объявляет это границей области, и пишущий вызов внутри
 * неё сделал бы объявление неправдой.
 *
 * Контракт API снят с первоисточника, а не по памяти — `researches/56` §3.5:
 *   · подача: `POST /v4/user/{uid}/hosts/{hid}/recrawl/queue`, тело `{"url": "…"}`,
 *     **один адрес за запрос** (150 адресов — это 150 вызовов);
 *   · ответ 202: `{task_id, quota_remainder}` — остаток приезжает С КАЖДЫМ ответом;
 *   · ошибки именованные: 400 INVALID_URL · 403 INVALID_USER_ID · 404 HOST_NOT_VERIFIED ·
 *     409 URL_ALREADY_ADDED · 429 QUOTA_EXCEEDED.
 */

/** Разобрать файл адресов: пустые строки и хвостовой перевод не считаются. */
export function parseAddresses(text) {
	return text
		.split(/\r?\n/)
		.map((line) => line.trim())
		.filter((line) => line.length > 0);
}

/**
 * Что осталось подать: очередь минус уже отправленное, порядок очереди сохраняется.
 *
 * 🔑 Порядок — не косметика: очередь построена «последние удалённые первыми» (`bugs/203`), и
 * пересортировка обесценила бы приоритет, выбранный при её сборке.
 */
export function remainingQueue(queue, alreadySent) {
	const sent = new Set(alreadySent);
	return queue.filter((url) => !sent.has(url));
}

/**
 * Сколько адресов подать сейчас — минимум из трёх границ.
 *
 * 🔴 МАШИНА УСТУПАЕТ ЧЕЛОВЕКУ. Квота общая у интерфейса и API (замерено, `bugs/203`), поэтому
 * владелец может слать руками в тот же день. Прибор берёт остаток квоты КАК ЕСТЬ и никогда не
 * пытается послать больше: спорить с человеком за общий ресурс — не его дело.
 */
export function planBatch({ remaining, quotaRemainder, cap = Infinity }) {
	const limits = [remaining.length, Math.max(0, quotaRemainder), Math.max(0, cap)];
	const size = Math.min(...limits);
	return {
		size,
		urls: remaining.slice(0, size),
		limitedBy:
			size === 0
				? remaining.length === 0
					? 'очередь пуста'
					: 'квота исчерпана'
				: size === remaining.length
					? 'очередь'
					: size === quotaRemainder
						? 'квота'
						: 'потолок порции',
	};
}

/** Именованные коды отказа Яндекса — из первоисточника, без нашего перевода. */
export const REFUSALS = {
	400: 'INVALID_URL — адрес не принят как валидный',
	403: 'INVALID_USER_ID — пользователь не тот',
	404: 'HOST_NOT_VERIFIED — права на хост не подтверждены',
	409: 'URL_ALREADY_ADDED — адрес уже в очереди переобхода',
	429: 'QUOTA_EXCEEDED — суточная квота исчерпана',
};

/**
 * Как понимать один ответ подачи.
 *
 * Три исхода, и путать их дорого:
 *   · `accepted` — адрес принят, квота потрачена;
 *   · `skipped` — адрес уже в очереди (409). Квота НЕ потрачена, и это не ошибка прогона;
 *   · `stop` — дальше слать бессмысленно (429 квота, 403/404 доступ): прогон останавливается,
 *     а не долбит API 149 раз подряд одним и тем же отказом.
 */
export function classifyResponse({ status, body }) {
	if (status === 202 || status === 200) {
		return {
			outcome: 'accepted',
			taskId: body?.task_id ?? null,
			quotaRemainder: typeof body?.quota_remainder === 'number' ? body.quota_remainder : null,
		};
	}
	if (status === 409) return { outcome: 'skipped', why: REFUSALS[409] };
	if (status === 429) return { outcome: 'stop', why: REFUSALS[429] };
	if (status === 403 || status === 404) return { outcome: 'stop', why: REFUSALS[status] };
	if (status === 400) return { outcome: 'failed', why: REFUSALS[400] };
	return { outcome: 'failed', why: `неизвестный код ${status}` };
}

/**
 * КАКОЙ ОСТАТОК КВОТЫ ПИСАТЬ В ЖУРНАЛ — ЗАМЕРЕННЫЙ, а не попутный.
 *
 * 🔴 Дефект первой живой подачи (2026-08-29, `bugs/NEW_ostatok-kvoty…`): прибор печатал остаток
 * из последнего 202-ответа, а Яндекс отдаёт `quota_remainder` ДО списания того самого вызова,
 * который отвечает. Наблюдение: напечатано «остаток квоты 1», немедленный опрос дал **0**.
 * Адрес не терялся — врал ОТЧЁТ о необратимом действии, а его читают, чтобы решить, слать ли ещё.
 *
 * 🔑 Класс — зеркало `bugs/215`: там снимок утверждал состояние числом, которого не проверил;
 * здесь строка утверждает состояние ПОСЛЕ действия числом, снятым ДО него. Общее одно: **отчёт о
 * необратимом действии построен на попутном числе, а не на замере.** Попутное дешевле — потому
 * его и берут.
 *
 * Замер может не приехать (сеть, 5xx). Тогда честнее назвать число попутным, чем выдать за замер.
 */
export function settleQuotaLeft({ measured, fromLastResponse }) {
	if (typeof measured === 'number') {
		return { value: measured, measured: true, why: 'остаток квоты замерен после подачи' };
	}
	return {
		value: fromLastResponse,
		measured: false,
		why: 'остаток квоты НЕ замерен (опрос не удался) — число из последнего ответа, оно может отставать на единицу',
	};
}

/**
 * Строка отчёта для `bugs/203` — числами, как предписал Менеджер: отправлено / остаток очереди /
 * остаток квоты. Строка собирается ЗДЕСЬ, чтобы её форма была одна и покрывалась юнитом.
 */
export function ledgerLine({ date, accepted, skipped, failed, queueLeft, quotaLeft }) {
	const parts = [
		`- **${date}** — отправлено **${accepted}**`,
		skipped > 0 ? `· уже в очереди ${skipped}` : null,
		failed > 0 ? `· отказов ${failed}` : null,
		`· остаток очереди **${queueLeft}**`,
		`· остаток квоты ${quotaLeft}`,
	];
	return parts.filter(Boolean).join(' ');
}

/**
 * НОМЕР ДОКУМЕНТА-ПЕРВОИСТОЧНИКА. Номер, а не имя: имя канон МЕНЯЕТ, номер — нет.
 *
 * `bugs/README.md`: «*Починен и проверен — `git mv NN_x.md NN_DONE_x.md`*». В дереве таких
 * переименованных документов уже 122, то есть операция рутинная.
 */
export const AUTH_DOC_NUMBER = '203';

/**
 * ОПОЗНАТЬ ДОКУМЕНТ-ПЕРВОИСТОЧНИК СРЕДИ ИМЁН `bugs/` — по НОМЕРУ, а не по полному имени.
 *
 * 🔴 Дефект 1 вердикта №10 QA, воспроизведённый судьёй живьём: прибор держал признаком полное
 * имя файла, судья закрыла `bugs/203` ровно так, как предписывает канон (`git mv` → `_DONE_`),
 * цитату владельца не тронула — и прибор отказал словами «нет документа разрешения», код 1.
 * Разрешение цело и не отозвано, а дверь заперта.
 *
 * 🔑 Почему это не совпадение и не редкость: очередь переобхода — 1201 адрес по 150 в сутки,
 * то есть ~9 дней; ровно в эти недели инцидент вылечится и документ уедет в `_DONE_`. Отказ
 * пришёлся бы на середину очереди.
 *
 * Признак выбран тот, что принадлежит документу и переживает канон: `203_…` и `203_DONE_…`
 * оба начинаются с номера. Неоднозначность (два документа с одним номером — класс, названный
 * в манифесте команды) — это ОТКАЗ, а не выбор наугад: для необратимого действия угадывать
 * первоисточник нельзя.
 */
export function findAuthDoc(fileNames, number = AUTH_DOC_NUMBER) {
	const startsWithNumber = new RegExp(`^${number}(?=_|\\.)`);
	const matches = [...fileNames]
		.filter((name) => name.endsWith('.md') && startsWithNumber.test(name))
		.sort();
	if (matches.length === 0) {
		return { file: null, why: `в bugs/ нет документа с номером ${number}` };
	}
	if (matches.length > 1) {
		return {
			file: null,
			why: `в bugs/ несколько документов с номером ${number} (${matches.join(', ')}) — первоисточник неоднозначен`,
		};
	}
	return { file: matches[0], why: `документ опознан по номеру ${number}` };
}

/**
 * ЧТЕНИЕ РАЗРЕШЕНИЯ ИЗ ПЕРВОИСТОЧНИКА — `bugs/203` § «Разрешение владельца».
 *
 * 🔴 Условие вердикта №7 QA, и оно сильнее, чем просто «сверять точно». Прежняя редакция держала
 * слово владельца в шапке САМОГО прибора — самоссылка: инструмент утверждал, что ему разрешено,
 * ссылаясь на собственный комментарий, и судье нечего было проверить. Теперь разрешение живёт в
 * версионируемом документе, а прибор его ЧИТАЕТ. Стёрли строку из документа — прибор не заведётся.
 *
 * 🔴 **Цитата берётся ПО ФОРМЕ ЗАПИСИ РАЗРЕШЕНИЯ, а не первой попавшейся «ёлочкой»** — замечание
 * З2 вердикта №10 QA, и оно про подмену, а не про аккуратность. Прежняя редакция брала первую
 * «ёлочку» в разделе; судья показала, что если стереть строку владельца, прибор молча примет за
 * разрешение соседнюю цитату — ВОПРОС МЕНЕДЖЕРА — и отрапортует «цитата прочитана из документа».
 * Абзац, вставленный выше строки владельца, тихо переназначил бы дверь на слова, которых владелец
 * не говорил.
 *
 * Форма, которую ищем (она же канон записи разрешений в багах) — ДВЕ строки, обе обязательны:
 *   ## Разрешение владельца …
 *   > **«<дословная цитата>»**
 *   > — владелец, <где и когда сказано>
 *
 * Подпись обязательна намеренно: она и есть то, что отличает СЛОВО ВЛАДЕЛЬЦА от любой другой
 * цитаты в том же разделе. Цитата без подписи — не разрешение, и прибор это называет.
 */
const PERMISSION_QUOTE = /^>\s*\*\*«([^»]+)»\*\*\s*$/;
const PERMISSION_ATTRIBUTION = /^>\s*—\s*владел/i;

export function readOwnerQuote(markdown) {
	const section = /^## +Разрешение владельца.*$/m.exec(markdown);
	if (!section) {
		return { quote: null, why: 'в документе нет раздела «## Разрешение владельца»' };
	}
	const tail = markdown.slice(section.index + section[0].length);
	const next = /^##\s/m.exec(tail);
	const lines = (next ? tail.slice(0, next.index) : tail).split(/\r?\n/);

	let sawQuote = false;
	for (let i = 0; i < lines.length; i += 1) {
		const quoted = PERMISSION_QUOTE.exec(lines[i]);
		if (!quoted) continue;
		sawQuote = true;
		// Подпись идёт следующей строкой цитаты; пустые строки внутри блока не мешают.
		for (let j = i + 1; j < lines.length; j += 1) {
			const line = lines[j].trim();
			if (line === '' || line === '>') continue;
			if (PERMISSION_ATTRIBUTION.test(line)) {
				return { quote: quoted[1].trim(), why: 'цитата прочитана из документа' };
			}
			break;
		}
	}
	if (sawQuote) {
		return {
			quote: null,
			why: 'цитата в разделе есть, но не подписана владельцем («— владелец, …») — это не разрешение',
		};
	}
	return {
		quote: null,
		why: 'в разделе разрешения нет цитаты, записанной по форме разрешения (> **«…»** + подпись владельца)',
	};
}

/**
 * Сверка слова, поданного оператором, с записанным в документе — ТОЧНЫМ совпадением.
 *
 * 🔴 Почему точным. Судья показал: предохранитель, требующий лишь непустую строку, пропускает
 * `--auth-owner "x"`. Для НЕОБРАТИМОГО действия это церемония, а не ворота: она проверяет, что
 * оператор что-то набрал, а не что владелец что-то разрешил.
 *
 * Единственная вольность — обрамляющие кавычки-ёлочки и внешние пробелы: оператор законно
 * копирует цитату вместе с ними. Ни регистр, ни внутренние слова не прощаются.
 */
export function authMatches(given, recorded) {
	const strip = (value) =>
		String(value ?? '')
			.trim()
			.replace(/^[«"]+/, '')
			.replace(/[»"]+$/, '')
			.trim();
	return strip(given) === strip(recorded);
}
