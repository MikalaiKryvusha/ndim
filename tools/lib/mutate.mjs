/**
 * МУТАЦИЯ ИСХОДНИКА С КОНТРОЛЕМ ПОПАДАНИЯ — общий механизм вместо трёх записей опыта.
 *
 * ═══ ЗАЧЕМ ЭТОТ ФАЙЛ СУЩЕСТВУЕТ ═══
 *
 * Мутация доказывает, что проверка СПОСОБНА покраснеть. Вердикт мутации — число падений, и он
 * действителен ровно тогда, когда подстановка ДЕЙСТВИТЕЛЬНО СОСТОЯЛАСЬ. Проект платил за это
 * трижды за сутки (`EXP-0180`, `EXP-0182`, `EXP-0189`, `EXP-0193`), и в последний раз — на авторе
 * самой записи, тем же вечером, тем же способом. **Урок, повторившийся после того, как он записан,
 * — урок, проваливший себя как текст** (`AGENT_GUIDE.md` → «Журнал опыта»), и лечится он
 * механизмом, а не четвёртой записью.
 *
 * ═══ 🔴 ГЛАВНОЕ: `.replace` — ТИХАЯ ФУНКЦИЯ, И В ЭТОМ ВЕСЬ КЛАСС ═══
 *
 * Не найдя образца, `String.prototype.replace` возвращает ИСХОДНИК и не жалуется. Файл
 * перезаписывается сам собой, `mtime` меняется, `git diff` пуст, прогон идёт как ни в чём не
 * бывало — и печатает число, полученное на НЕмутированном коде. Отсюда правило, ради которого
 * написан модуль: **контроль попадания обязан стоять ДО записи и ПАДАТЬ.** Всякая проверка,
 * стоящая после `.replace`, проверяет уже свершившийся факт и опоздала.
 *
 * ═══ 🔑 ВТОРОЙ КОНТРОЛЬ, ДЕШЁВЫЙ И ПОЧТИ НЕИЗВЕСТНЫЙ ═══
 *
 * Когда мутаций больше одной: **одинаковый ответ на разные вопросы есть признак, что вопроса не
 * задали.** Два РАЗНЫХ мутанта, давшие результат, совпавший до строчки, — это не совпадение, это
 * непроведённая подстановка. Именно так класс и был пойман в последний раз: не бдительностью, а
 * тем, что м7 и м8 напечатали тождественные таблицы.
 *
 * ═══ ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ, И ПОЧЕМУ ИМЕННО ЭТО ═══
 *
 * 1. **Образец встречается РОВНО ОДИН раз.** Не «хотя бы один»: два совпадения означают, что
 *    подстановка неоднозначна, и первое из них может оказаться не тем. Ноль — что мутации не будет
 *    вовсе. Оба случая — отказ ДО записи.
 * 2. **Мутант отличается от образца.** Подстановка «сама в себя» проходит любую проверку
 *    попадания по факту и не меняет ничего: набор прогонится, тесты исполнятся, покраснеть будет
 *    НЕ НА ЧЁМ (`AGENT_GUIDE.md` → лестница трёх вопросов, четвёртый слой «не способна упасть» —
 *    сам МУТАНТ).
 * 3. **Файл перечитывается ПОСЛЕ записи.** Диск мог не принять запись, редактор мог держать файл,
 *    перенос строк мог переписать содержимое (`EXP-0047`, `core.autocrlf`). Попадание по факту
 *    подтверждается чтением, а не верой в `writeFileSync`.
 * 4. **Восстановление в `finally`.** Падение работы — обычное дело: ради него мутация и ставится.
 *    Исходник обязан вернуться и при падении, и при исключении.
 *
 * ⚠️ **ЧЕСТНАЯ ГРАНИЦА, названная прямо:** `finally` не переживает `process.exit()` внутри работы,
 * убийство процесса и обрыв сессии. Восстановление гарантировано для исключений и обычного
 * возврата — не для смерти процесса. Страховка от неё одна и она снаружи: коммить ДО мутации
 * (`EXP-0190`), тогда `git checkout --` вернёт файл в любом случае.
 *
 * ⚠️ **КОНТРОЛЬ ПО СМЫСЛУ МОДУЛЬ НЕ ЗАМЕНЯЕТ.** Попадание по факту доказывает, что байты
 * переписались, и НЕ доказывает, что мутант ведёт себя иначе (`EXP-0193`, заход 1: якорь ослаблен,
 * а снятое требование осталось на месте). Поэтому у `сМутацией` есть довод `контроль` — строка или
 * проверка, которая ОБЯЗАНА сменить поведение. Он не обязателен, но его отсутствие модуль
 * ПРОГОВАРИВАЕТ: вердикт без него закрывает половину класса. Молчаливого половинчатого отчёта
 * здесь нет — приём взят у `tools/measure-rewrite-proportion.mjs`, который так же вслух говорит об
 * отсутствии второй меры.
 *
 * Применение:
 *   import { сМутацией } from './lib/mutate.mjs';
 *   const итог = сМутацией({
 *     файл: 'tools/прибор.mjs',
 *     якорь: 'if (parts.length !== 2) {',
 *     мутант: 'if (parts.length < 2) {',
 *     контроль: () => самотестКраснеет(),   // ОБЯЗАН вернуть true у мутанта
 *   }, () => прогнатьНабор());
 */
import { readFileSync, writeFileSync } from 'node:fs';

/** Ошибка мутации — отдельный тип, чтобы вызывающий отличал «мутация не состоялась» от падения работы. */
export class МутацияНеСостоялась extends Error {
  constructor(сообщение) {
    super(сообщение);
    this.name = 'МутацияНеСостоялась';
  }
}

/**
 * Подставить мутанта. Бросает ДО записи, если подстановка недействительна.
 *
 * @returns {{ восстановить: () => void, исходник: string }}
 */
export function подставить({ файл, якорь, мутант, читать = readFileSync, писать = writeFileSync }) {
  if (!файл) throw new МутацияНеСостоялась('не назван файл');
  if (typeof якорь !== 'string' || !якорь) throw new МутацияНеСостоялась('якорь пуст');
  if (typeof мутант !== 'string') throw new МутацияНеСостоялась('мутант не строка');

  // 🔴 Проверка 2 — раньше чтения файла: подстановка сама в себя мутацией не является.
  if (якорь === мутант) {
    throw new МутацияНеСостоялась('мутант тождествен якорю — подстановка ничего не изменит');
  }

  const исходник = читать(файл, 'utf8');

  // 🔴 Проверка 1 — РОВНО один, и она стоит ДО записи, потому что `.replace` молчит о промахе.
  const сколько = исходник.split(якорь).length - 1;
  if (сколько !== 1) {
    throw new МутацияНеСостоялась(
      сколько === 0
        ? `якорь не найден в ${файл} — мутации не будет, вердикт прогона недействителен`
        : `якорь найден в ${файл} ${сколько} раз(а), нужен ровно 1 — подстановка неоднозначна`,
    );
  }

  писать(файл, исходник.replace(якорь, мутант), 'utf8');

  // 🔴 Проверка 3 — попадание ПО ФАКТУ подтверждается ЧТЕНИЕМ, а не верой в запись.
  const после = читать(файл, 'utf8');
  if (!после.includes(мутант) || после.includes(якорь)) {
    писать(файл, исходник, 'utf8');
    throw new МутацияНеСостоялась(`запись в ${файл} не дала ожидаемого текста — исходник возвращён`);
  }

  let вернули = false;
  return {
    исходник,
    // Восстановление идемпотентно: `finally` может сработать после явного вызова.
    восстановить() {
      if (вернули) return;
      вернули = true;
      писать(файл, исходник, 'utf8');
    },
  };
}

/**
 * Мутация на время работы. Исходник возвращается ВСЕГДА — и при падении работы тоже, ради него
 * мутация и ставится.
 *
 * `контроль` — необязательная проверка «мутант ведёт себя иначе», исполняется ПОСЛЕ подстановки и
 * ДО работы. Вернула ложь — работа не запускается: её число ничего не значило бы.
 *
 * Работа может быть асинхронной: обещание дожидается ВНУТРИ мутации, иначе исходник вернулся бы
 * раньше, чем работа успела прочитать мутанта.
 */
export function сМутацией({ файл, якорь, мутант, контроль, молча = false }, работа) {
  const { восстановить } = подставить({ файл, якорь, мутант });
  if (!контроль && !молча) {
    console.log(`⚠️ ${файл}: контроль ПО СМЫСЛУ не задан — вердикт закрывает половину класса (EXP-0193)`);
  }
  /*
   * ⚠️ ЗДЕСЬ НЕЛЬЗЯ `finally`, И ЭТО ПОЙМАНО СОБСТВЕННЫМ ТЕСТОМ, А НЕ РАССУЖДЕНИЕМ.
   * `finally` исполняется СИНХРОННО — в тот момент, когда работа лишь ВЕРНУЛА обещание. Исходник
   * возвращался на диск раньше, чем асинхронная работа успевала прочитать мутанта, и прогон шёл
   * по неизменённому коду: ровно тот класс, против которого написан весь модуль, только изнутри.
   * Поэтому у синхронной и асинхронной ветки восстановление РАЗНОЕ: у первой — сразу, у второй —
   * на исходе обещания.
   */
  try {
    if (контроль && !контроль()) {
      throw new МутацияНеСостоялась(
        `контроль по смыслу не сработал: байты подставлены, поведение ${файл} не изменилось`,
      );
    }
    const итог = работа();
    if (итог && typeof итог.then === 'function') {
      return итог.then(
        (значение) => { восстановить(); return значение; },
        (беда) => { восстановить(); throw беда; },
      );
    }
    восстановить();
    return итог;
  } catch (беда) {
    восстановить();
    throw беда;
  }
}

/**
 * СОВПАВШИЕ ОТВЕТЫ РАЗНЫХ МУТАНТОВ — признак, что вопроса не задали.
 *
 * Дешёвый второй контроль для серии: разные мутации, давшие результат, совпавший до строчки,
 * почти всегда означают, что ни одна не состоялась. Именно так класс и был пойман в последний раз.
 *
 * @param итоги массив `[имяМутации, результат]`; результат сравнивается как строка.
 * @returns список пар имён, чьи результаты совпали
 */
export function совпавшиеОтветы(итоги) {
  const пары = [];
  for (let i = 0; i < итоги.length; i += 1) {
    for (let j = i + 1; j < итоги.length; j += 1) {
      if (String(итоги[i][1]) === String(итоги[j][1])) пары.push([итоги[i][0], итоги[j][0]]);
    }
  }
  return пары;
}
