import { basename } from 'node:path';

// Слот рабочего каталога спрашивается у ХОЗЯИНА парка, а не выводится здесь заново
// (довод — в шапке выше: вторая копия таблицы разъехалась бы молча). Ребро зависимости
// одно и стоит на виду: этот модуль читает `stand-slot.mjs`, обратного чтения нет.
import { slotOf } from './stand-slot.mjs';

/** Умолчания — слот 0. Менять их нельзя: на них стоит всё, что писалось до парка. */
const СЛОТ_0 = {
  app: 'http://localhost:5173',
  preview: 'http://localhost:4173',
  auth: '127.0.0.1:9099',
  firestore: '127.0.0.1:8181',
  storage: '127.0.0.1:9199',
  project: 'demo-ndim-dev',
};

const чисто = (v) => (typeof v === 'string' && v.trim() ? v.trim() : null);
/** `host:port` → `http://host:port`; уже готовый URL оставляется как есть. */
const какURL = (v) => (/^https?:\/\//.test(v) ? v : `http://${v}`).replace(/\/+$/, '');

/**
 * Адреса текущего стенда.
 * @returns {{app:string, preview:string, auth:string, firestore:string, storage:string,
 *            project:string, слот0:boolean}}
 */
export function standAddresses() {
  const app = какURL(чисто(process.env.PROBE_BASE) ?? СЛОТ_0.app);
  const preview = какURL(чисто(process.env.PROBE_PREVIEW_BASE) ?? СЛОТ_0.preview);
  const authHost = чисто(process.env.FIREBASE_AUTH_EMULATOR_HOST) ?? СЛОТ_0.auth;
  const fsHost = чисто(process.env.FIRESTORE_EMULATOR_HOST) ?? СЛОТ_0.firestore;
  const stHost = чисто(process.env.FIREBASE_STORAGE_EMULATOR_HOST) ?? СЛОТ_0.storage;
  // Имя проекта эмулятора у нас задаётся отдельно; `GCLOUD_PROJECT` — то, что ставит сам CLI.
  const project =
    чисто(process.env.NDIM_EMULATOR_PROJECT) ?? чисто(process.env.GCLOUD_PROJECT) ?? СЛОТ_0.project;

  const слот0 =
    app === СЛОТ_0.app && authHost === СЛОТ_0.auth && fsHost === СЛОТ_0.firestore;

  return {
    app,
    preview,
    auth: какURL(authHost),
    firestore: какURL(fsHost),
    storage: какURL(stHost),
    project,
    слот0,
  };
}

/**
 * Строка для шапки отчёта. Прибор ОБЯЗАН её печатать: кадры и числа, снятые не на том стенде,
 * ничем не отличаются от снятых на том — кроме этой строки.
 *
 * 🔴 И ОДНОЙ СТРОКИ ОКАЗАЛОСЬ МАЛО — ПОЛЕВОЙ ОЖОГ 2026-08-29 (Дизайнер).
 * Прибор `verify-test-card-face` был позван из ГОЛОЙ оболочки в копии роли (слот 1). Переменные
 * ставит потомкам `firebase emulators:exec`, в голой оболочке их нет — адреса честно упали на
 * умолчание, и прибор ушёл мерить стенд ГЛАВНОЙ копии (:5173). Четыре конфигурации вернули
 * зелёное с ЧУЖОГО дерева, пока в своём лежала наложенная мутация: «доказательство» показывало
 * ровно противоположное тому, что проверялось, и мутация «не краснела».
 * Строка адреса печаталась и была верна — но стояла первой, а глаз читающего идёт в вердикт.
 *
 * Поэтому умолчание, СОВПАВШЕЕ с чужим слотом, теперь кричит, а не шепчет: если рабочий каталог
 * принадлежит роли со слотом ≠ 0, а адреса взяты по умолчанию, это почти наверняка промах
 * вызова, и цена у него — ложное доказательство.
 * ⛔ Отказом это намеренно НЕ сделано: на слоте 0 стоит дверь выката, и её поведение обязано
 * остаться байт-в-байт прежним (тот же довод, что в шапке `stand-launch.mjs`).
 * ⛔ Таблица слотов сюда по-прежнему НЕ копируется — слот спрашивается у её хозяина.
 *
 * ⚠️ ЦЕНА ЭТОГО ПРЕДУПРЕЖДЕНИЯ, НАЗВАННАЯ ВСЛУХ: функция БОЛЬШЕ НЕ ЧИСТАЯ — она читает
 * `process.cwd()`. Раньше её ответ зависел только от аргумента, теперь ещё и от того, ОТКУДА
 * её позвали. Замечание ревью (Интегратор, 2026-08-29), и оно верное: её зовут три прибора,
 * и каждый вправе знать, что строка у них разойдётся при одном и том же `standAddresses()`,
 * если рабочие каталоги разные.
 * Чем это ограничено, чтобы не расползлось: `process.cwd()` читается ТОЛЬКО в ветке
 * «адреса по умолчанию» — то есть когда предупреждать не о чем, каталог вообще не спрашивается;
 * ответ по-прежнему детерминирован для пары (аргумент, каталог); ничего не пишется и не
 * кэшируется. Все три случая (промах кричит · окружение задано — молчит · каталог вне ролей —
 * молчит) стоят ЮНИТАМИ в `tools/stand-fleet.test.mjs`, на временных каталогах и подменой
 * `process.chdir()`; мутация «снять предупреждение» роняет ровно первый из трёх.
 * ⚠️ Прежняя редакция этой строки говорила «тестируется… так проверены все три случая», а
 * артефакта в дереве не имела — заявление о проверке, которое нельзя повторить (условие У3
 * суда №33). Формулировка заменена на адрес файла намеренно: проверить адрес дешевле, чем
 * поверить обещанию.
 * 🔑 Нечистой сделана РОВНО строка отчёта, а не `standAddresses()`: адреса обязаны остаться
 * функцией окружения и только его, иначе прибор начнёт вести себя по-разному в разных копиях —
 * а это тот самый класс, против которого предупреждение и написано.
 */
export function addressesLine(a = standAddresses()) {
  const строка = `стенд: приложение ${a.app} · auth ${a.auth} · firestore ${a.firestore} · проект ${a.project}`;
  if (!a.слот0) return `${строка} (адреса из окружения)`;
  const { slot, role } = slotOf(basename(process.cwd()));
  if (slot === 0) return `${строка} (слот 0, умолчание)`;
  return (
    `${строка} (слот 0, умолчание)
` +
    `🔴 ВНИМАНИЕ: рабочий каталог — место роли «${role}» (слот ${slot}), а адреса взяты ПО УМОЛЧАНИЮ. ` +
    `Значит прибор меряет стенд ЧУЖОЙ копии, а не твой: числа и кадры будут про другое дерево. ` +
    `Зови прибор под своим стендом — node tools/stand-launch.mjs --exec "<команда>" — либо задай ` +
    `PROBE_BASE и FIREBASE_*_EMULATOR_HOST руками.`
  );
}
