/**
 * ЯДРО СТРАЖА ВХОДНОГО ПРЕДОХРАНИТЕЛЯ: файл с экспортом не должен работать при импорте.
 * Класс и критерии приёмки — `ideas/43`; цена класса замерена в `EXPERIENCE.md`
 * (`EXP-0188` пункт 3 назвал и сосчитал класс; запись смены 10 измерила его цену В ВОРОТАХ:
 * прибор без предохранителя делает свой юнит зелёным, что бы в юните ни стояло).
 *
 * ═══ ЧТО ИМЕННО СУДИТСЯ ═══
 *
 * Красное = файл ОДНОВРЕМЕННО: (1) что-то экспортирует, (2) ведёт работу на верхнем уровне и
 * (3) эта работа НЕ закрыта предохранителем «запущен или подключён». Все три условия обязательны:
 * скрипту без экспорта предохранитель не нужен (работа на верхнем уровне и есть весь его смысл),
 * а чистой библиотеке нечего закрывать.
 *
 * ═══ 🔴 ПОЧЕМУ ПАРСЕР, А НЕ РЕГУЛЯРКА ═══
 *
 * `ideas/43` объявляет условием приёмки не отлов, а ОТСУТСТВИЕ ЛОЖНОГО КРАСНОГО: «страж, дающий
 * ложное красное, отключают целиком, и тогда он не защищает и от настоящего». Оплачено ДО его
 * написания — первая редакция зонда обвинила `tools/review.mjs`, у которого предохранитель ЕСТЬ,
 * просто написан другой формой. Регулярка по тексту спотыкается о комментарии, строки и шаблоны;
 * дерево разбора не спотыкается ни обо что.
 *
 * ═══ 🔑 ПРЕДОХРАНИТЕЛЬ ОПОЗНАЁТСЯ ПО СМЫСЛУ, А НЕ ПО НАПИСАНИЮ ═══
 *
 * Признак: сравнение (`===`, `!==`, …), у которого по одну сторону в поддереве есть `import.meta`,
 * а по другую — `process.argv[1]`. Обе известные проекту формы попадают под него ПО ПОСТРОЕНИЮ,
 * и третья, ещё не написанная, — тоже:
 *   · `import.meta.url === pathToFileURL(process.argv[1]).href`               (основная)
 *   · `resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))`  (`review.mjs`)
 * Это и есть критерий К2 `ideas/43`, исполненный устройством, а не перечнем форм.
 *
 * ═══ 🔴 МАЛО «ПРЕДОХРАНИТЕЛЬ ЕСТЬ» — ВАЖНО, ЧТО ОН ЗАКРЫВАЕТ РАБОТУ ═══
 *
 * Первый же полевой случай `ideas/43` был именно такой: у `rewrite-catalog-descriptions.mjs`
 * предохранитель БЫЛ, а самотест стоял СНАРУЖИ него — и `gate-rewrites --selftest` печатал
 * зелёный, ни разу не отработав. Поэтому судится не наличие сравнения где-нибудь в файле, а
 * КАЖДЫЙ верхнеуровневый оператор: он либо закрыт предохранителем, либо обвиняется поимённо,
 * со строкой.
 */
import { createRequire } from 'node:module';

const require_ = createRequire(import.meta.url);

/**
 * Разборщик берётся из `node_modules` проекта (его тянет SvelteKit). Прямой зависимостью он НЕ
 * объявлен намеренно: строка в `package.json` тянет за собой перетряску `package-lock.json` —
 * лишний конфликт мержа на ровном месте. Отсутствие парсера обязано быть ГРОМКИМ отказом с
 * названным лечением, а не тихим пропуском: страж, не сумевший разобрать файл, ничего о нём не
 * знает и не вправе говорить «зелено».
 */
export function загрузитьПарсер() {
  try {
    return require_('acorn');
  } catch {
    throw new Error('не найден разборщик acorn (его тянет SvelteKit) — выполни `npm ci` и повтори');
  }
}

/** Обход дерева: зовёт `посетить` на каждом узле. Узлы acorn — обычные объекты, обвязка не нужна. */
function обойти(узел, посетить) {
  if (!узел || typeof узел !== 'object') return;
  if (Array.isArray(узел)) { for (const э of узел) обойти(э, посетить); return; }
  if (typeof узел.type !== 'string') return;
  посетить(узел);
  for (const ключ of Object.keys(узел)) {
    if (ключ === 'type' || ключ === 'start' || ключ === 'end' || ключ === 'loc') continue;
    обойти(узел[ключ], посетить);
  }
}

const естьВПоддереве = (узел, признак) => {
  let нашёл = false;
  обойти(узел, (у) => { if (!нашёл && признак(у)) нашёл = true; });
  return нашёл;
};

const этоImportMeta = (у) => у.type === 'MetaProperty' && у.meta?.name === 'import' && у.property?.name === 'meta';

/** Именно ПЕРВЫЙ аргумент, а не любое обращение к `argv`: `process.argv[2]` — это уже команда. */
const этоArgv1 = (у) =>
  у.type === 'MemberExpression'
  && у.computed
  && у.property?.type === 'Literal' && у.property.value === 1
  && у.object?.type === 'MemberExpression'
  && у.object.property?.name === 'argv'
  && у.object.object?.name === 'process';

/**
 * Сравнение, которое и есть предохранитель: с одной стороны `import.meta`, с другой
 * `process.argv[1]`. Стороны не различаются — обе известные формы написаны в разном порядке.
 */
const этоСравнениеПредохранителя = (у) => {
  if (у.type !== 'BinaryExpression' || !['===', '==', '!==', '!='].includes(у.operator)) return false;
  const слева = { meta: естьВПоддереве(у.left, этоImportMeta), argv: естьВПоддереве(у.left, этоArgv1) };
  const справа = { meta: естьВПоддереве(у.right, этоImportMeta), argv: естьВПоддереве(у.right, этоArgv1) };
  return (слева.meta && справа.argv) || (слева.argv && справа.meta);
};

/** Операторы верхнего уровня, которые при подключении файла НЕ исполняются. */
const ИНЕРТНЫЕ = new Set([
  'ImportDeclaration', 'FunctionDeclaration', 'ClassDeclaration', 'EmptyStatement', 'VariableDeclaration',
]);

const ТЕЛА_ФУНКЦИЙ = new Set(['FunctionDeclaration', 'FunctionExpression', 'ArrowFunctionExpression']);

/**
 * `await`, исполняемый ПРИ ПОДКЛЮЧЕНИИ, — то есть на верхнем уровне выражения, а не в теле
 * функции, которую ещё надо позвать.
 *
 * 🔴 РАЗЛИЧАТЬ ОБЯЗАТЕЛЬНО, И ЭТО ОПЛАЧЕНО ПЕРВЫМ ЖЕ ПРОГОНОМ. Без спуска-исключения страж
 * обвинил `tools/review.mjs` за `export async function signal(…)`: `await` в ТЕЛЕ функции
 * исполнится, только когда функцию позовут, а импорт её лишь объявляет. Это ровно тот ложный
 * красный, о котором предупреждает `ideas/43` К2, — и он нашёлся на том же файле, что и в
 * прошлый раз, потому что проверка шла по известному случаю, а не по вере в свой признак.
 */
const естьВерхнийAwait = (узел) => {
  let нашёл = false;
  const идти = (у) => {
    if (нашёл || !у || typeof у !== 'object') return;
    if (Array.isArray(у)) { for (const э of у) идти(э); return; }
    if (typeof у.type !== 'string') return;
    if (ТЕЛА_ФУНКЦИЙ.has(у.type)) return; // тело функции — не верхний уровень
    if (у.type === 'AwaitExpression') { нашёл = true; return; }
    for (const ключ of Object.keys(у)) {
      if (ключ === 'type' || ключ === 'start' || ключ === 'end' || ключ === 'loc') continue;
      идти(у[ключ]);
    }
  };
  идти(узел);
  return нашёл;
};

/**
 * СУД НАД ИСХОДНИКОМ. Чистая функция: на входе текст, на выходе вердикт со строками.
 *
 * @param {string} исходник текст модуля.
 * @param {{parse?: Function}} [опции] разборщик (нужен проверкам); по умолчанию acorn проекта.
 * @returns {{экспорт: boolean, предохранитель: boolean, незакрытая: Array<{строка: number, вид: string}>}}
 */
export function судить(исходник, опции = {}) {
  const parse = опции.parse ?? загрузитьПарсер().parse;
  const дерево = parse(исходник, {
    ecmaVersion: 'latest',
    sourceType: 'module',
    allowAwaitOutsideFunction: true,
    locations: true,
  });

  let экспорт = false;
  let предохранитель = false;
  /** Имена констант, в которые записан предохранитель: `const ЗАПУЩЕН_НАПРЯМУЮ = <сравнение>`. */
  const именаПредохранителя = new Set();
  const незакрытая = [];

  for (const узел of дерево.body) {
    if (узел.type.startsWith('Export')) экспорт = true;

    if (естьВПоддереве(узел, этоСравнениеПредохранителя)) {
      предохранитель = true;
      if (узел.type === 'VariableDeclaration') {
        for (const д of узел.declarations) if (д.id?.type === 'Identifier') именаПредохранителя.add(д.id.name);
      }
    }

    /*
     * Объявление переменной инертно — даже с вызовом в правой части: `const ROOT = resolve(…)`
     * стоит в десятках приборов и работой не является. Считать его работой значило бы залить
     * проект ложным красным, то есть отключить стража (условие приёмки К2).
     * Исключение одно: `await` в правой части исполняется при подключении по-настоящему.
     */
    if (ИНЕРТНЫЕ.has(узел.type) && !(узел.type === 'VariableDeclaration' && естьВерхнийAwait(узел))) continue;

    // `export function f() {}` и `export const x = 1` — объявления, а не работа.
    if (узел.type.startsWith('Export') && узел.declaration && ИНЕРТНЫЕ.has(узел.declaration.type) && !естьВерхнийAwait(узел)) continue;
    if (узел.type.startsWith('Export') && !узел.declaration) continue;

    /*
     * Закрытая работа: `if (<предохранитель>) …` — сравнение прямо в условии либо константа, в
     * которую оно записано выше. Ветка `else` закрыта вместе с `if`: она исполняется ровно тогда,
     * когда предохранитель уже ответил.
     */
    if (узел.type === 'IfStatement') {
      const вУсловии = естьВПоддереве(узел.test, этоСравнениеПредохранителя)
        || естьВПоддереве(узел.test, (у) => у.type === 'Identifier' && именаПредохранителя.has(у.name));
      if (вУсловии) continue;
    }

    незакрытая.push({ строка: узел.loc.start.line, вид: узел.type });
  }

  return { экспорт, предохранитель, незакрытая };
}

/** Вердикт по одному файлу: красный ровно тогда, когда есть экспорт И есть незакрытая работа. */
export function красный(вердикт) {
  return вердикт.экспорт && вердикт.незакрытая.length > 0;
}

/* ── Реестр исключений и отсрочек ─────────────────────────────────────────────────────── */

/**
 * СУД НАД САМИМ РЕЕСТРОМ — и он существует потому, что реестр исключений гниёт быстрее кода.
 *
 * 🔴 ПРАВИЛО, РАДИ КОТОРОГО НАПИСАНА ЭТА ФУНКЦИЯ: **строка реестра обязана уметь покраснеть
 * сама.** Исключение, переживший свой повод, — это не «просто лишняя строка»: он молча
 * разрешает ровно тот дефект, ради запрета которого страж заведён, и разрешает НАВСЕГДА, потому
 * что снимать его некому и нечем. Требование поставлено Менеджером на `verify-role-env.mjs`
 * («строка сама краснеет, когда файл уйдёт из состава»); распространено на ВСЕ четыре строки,
 * потому что класс у них один, а не только у той.
 *
 * Отсюда четыре повода покраснеть у самой строки:
 *   · файла нет в дереве — повод исчез вместе с ним (это и есть случай `verify-role-env.mjs`
 *     после мержа порции А);
 *   · файл больше не красный — вылечили, а строку забыли снять;
 *   · причины нет — «маркер без причины сам является нарушением» (идиома проекта, живёт в
 *     `questions-guard.mjs` и `verify-role-env-scope.mjs`);
 *   · отсрочка без даты и условия снятия — это не отсрочка, а вечное разрешение под другим
 *     именем. У исключения срок не спрашивается: оно объявлено законным по существу.
 *
 * @param {{реестр: Array, красные: Set<string>, существующие: Set<string>}} вход
 * @returns {{покрытые: string[], непокрытые: string[], протухшие: Array<{файл: string, почему: string}>}}
 */
export function судитьРеестр({ реестр, красные, существующие }) {
  const покрытые = [];
  const протухшие = [];

  for (const строка of реестр) {
    const { файл, вид, причина, до, с } = строка;
    if (!причина || !String(причина).trim()) {
      протухшие.push({ файл, почему: 'строка без причины — причина обязательна' });
      continue;
    }
    if (вид === 'отсрочка' && (!до || !с)) {
      протухшие.push({ файл, почему: 'отсрочка без даты и условия снятия — это вечное разрешение под другим именем' });
      continue;
    }
    if (!существующие.has(файл)) {
      протухшие.push({ файл, почему: 'файла нет в дереве — повод исчез, строку снять' });
      continue;
    }
    if (!красные.has(файл)) {
      протухшие.push({ файл, почему: 'файл больше не красный — вылечен, строку снять' });
      continue;
    }
    покрытые.push(файл);
  }

  const покрыт = new Set(покрытые);
  return { покрытые, непокрытые: [...красные].filter((ф) => !покрыт.has(ф)), протухшие };
}
