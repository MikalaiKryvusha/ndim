/**
 * СОЕДИНИТЕЛЬ ПЕРЕЧИСЛЕНИЯ — то, что имеет право стоять между двумя именами одной роли.
 * Предлог соединителем НЕ является, и в этом вся сила правила: «*Играют A, B и C*» — одна
 * роль на троих, а «*после The Lost Daughter*» цепь обрывает.
 * ⚠️ Кавычки перечислены как ОДИНОЧНЫЕ знаки-разделители и НЕ парятся: признак, работающий на
 * парности, ломается на непарной кавычке (класс найден dev-1 в измерителе переписок 2026-08-22).
 */
const СОЕДИНИТЕЛЬ = new RegExp(
  String.raw`^[\s,;&"«»„“”()]*(?:` + [
    'и', 'а также', 'также', 'and', 'with', 'plus', 'вместе с', 'as well as',
  ].join('|') + String.raw`)?[\s,;&"«»„“”()]*$`,
  'iu',
);

/** Слово-имя: с заглавной, дальше буквы, апострофы, дефисы. Письменность любая. */
const СЛОВО = String.raw`\p{Lu}[\p{Ll}\p{Lu}'’-]*`;
/** Частицы внутри имени. Каждая с ГРАНИЦЕЙ: без неё `di` ловилось внутри `director`. */
const ЧАСТИЦЫ = ['де', 'дю', 'ван', 'фон', 'дель', 'of', 'the', 'de', 'van', 'von', 'du', 'di', 'da'];
const СВЯЗКА = new RegExp(
  СЛОВО + String.raw`(?:\s+(?:` + СЛОВО + '|(?:' + ЧАСТИЦЫ.join('|') + String.raw`)(?![\p{L}])))*`,
  'gu',
);

/**
 * НОРМАЛИЗАЦИЯ ИМЕНИ. Диакритика снимается: текст пишет «Gudnadottir», реестр держит
 * «Guðnadóttir» — это один человек, и без снятия он попадал в расхождения.
 * ⚠️ Снимается ТОЛЬКО для сверки. В самом тексте и в выводе имя остаётся как написано:
 * закон владельца о неприкосновенности названий старше любого нашего нормализатора.
 */
export function normalizeName(s) {
  return String(s ?? '')
    .normalize('NFD').replace(/[̀-ͯ]/gu, '')
    .toLowerCase()
    .replace(/ё/gu, 'е')
    .replace(/[đð]/gu, 'd').replace(/[øö]/gu, 'o').replace(/þ/gu, 'th').replace(/ß/gu, 'ss')
    .replace(/[’'`´]/gu, '')
    .replace(/[-–—.]/gu, ' ')
    .replace(/\s+/gu, ' ')
    .trim();
}

/**
 * СВЕРКА ДВУХ СЛОВ ПО ОБЩЕМУ НАЧАЛУ. Русская флексия меняет окончание, а не начало:
 * «Митчеллом» ≈ «Митчелл», «Элаем» ≈ «Элай», «Ривза» ≈ «Ривз».
 *
 * 🔴 ПОРОГ СЧИТАЕТСЯ ОТ КОРОТКОГО СЛОВА, А НЕ ОТ ДЛИННОГО, и это не мелочь. Первая редакция
 * резала основу по 70 % длины КАЖДОГО слова по отдельности, и на коротком русском имени рвалась:
 * «Элаем»/«Элай» дают общее начало «эла», а порог по длинному слову требовал четырёх букв —
 * живая карточка «Мороженщика» ушла в расхождения при исправном тексте. Порог от короткого:
 * общее начало ≥ 70 % его длины и не меньше трёх букв. Замер этой редакции — в шапке модуля.
 * ⚠️ Три буквы — низ, ниже опускать нельзя: «Иван»/«Игорь» дают одну общую букву и обязаны
 * расходиться, «Робин»/«Роберт» — три при пороге 3,5 и тоже обязаны.
 */
const общееНачало = (a, b) => {
  let i = 0;
  while (i < a.length && i < b.length && a[i] === b[i]) i += 1;
  return i;
};

/** Одиночная буква — инициал: «George P. Cosmatos» и «George Pan Cosmatos» один человек. */
const словоСошлось = (изТекста, изРеестра) => {
  if (изРеестра.length === 1 || изТекста.length === 1) return изТекста[0] === изРеестра[0];
  const короткое = Math.min(изТекста.length, изРеестра.length);
  /* Низ в три буквы НЕ ИМЕЕТ ПРАВА быть выше самого слова: «Ли Гарлингтон» из живой «Кобры»
   * при пороге 3 не сходился сам с собой — двухбуквенное имя короче собственного порога. */
  const порог = Math.max(Math.min(3, короткое), Math.ceil(короткое * 0.7));
  return общееНачало(изТекста, изРеестра) >= порог;
};

/**
 * Совпало ли имя из текста с реестровым: КАЖДОЕ слово реестрового имени нашлось в тексте.
 * Направление важно: связка из текста может нести лишний служебный кусок («Играют Киану Ривз»),
 * и требовать совпадения в обратную сторону значило бы ловить ложные расхождения.
 */
export function nameMatches(изТекста, изРеестра) {
  const a = normalizeName(изТекста).split(' ').filter(Boolean);
  const b = normalizeName(изРеестра).split(' ').filter(Boolean);
  if (!b.length || !a.length) return false;
  return b.every((w) => a.some((x) => словоСошлось(x, w)));
}

/**
 * ИМЕНА ОДНОЙ СУЩНОСТИ НА ЯЗЫКЕ — цепочка `bugs/159` плюс два разворота.
 * Возвращает ВСЕ пригодные написания: метку, мультиязычную метку и заголовок статьи, каждое —
 * с уточнением в скобках снятым и с инверсией «Фамилия, Имя» → «Имя Фамилия».
 */
export function entityLabels(entity, lang) {
  const источники = [
    entity?.labels?.[lang]?.value,
    entity?.labels?.mul?.value,
    entity?.sitelinks?.[`${lang}wiki`]?.title,
  ].filter(Boolean);
  const варианты = new Set();
  for (const исходное of источники) {
    const без = String(исходное).replace(/\s*\([^)]*\)\s*$/u, '').trim();
    if (без) варианты.add(без);
    const инверсия = без.match(/^([^,]+),\s*(.+)$/u);
    if (инверсия) варианты.add(`${инверсия[2]} ${инверсия[1]}`.trim());
  }
  return [...варианты];
}

/**
 * СОСТОЯНИЕ КАЖДОГО ИМЕННОГО СВОЙСТВА — здесь и рождается различение молчания и расхождения.
 * Вид: `нет-свойства` · `без-значения` · `без-метки` · `есть`.
 */
export function registryState(entity, referents, lang) {
  const по = {};
  for (const p of NAME_PROPS) {
    const утверждения = entity?.claims?.[p];
    if (!Array.isArray(утверждения) || !утверждения.length) { по[p] = { вид: 'нет-свойства', имена: [] }; continue; }
    const ссылки = утверждения
      .filter((s) => s?.mainsnak?.snaktype === 'value' && s.mainsnak.datavalue?.value?.id)
      .map((s) => s.mainsnak.datavalue.value.id);
    if (!ссылки.length) { по[p] = { вид: 'без-значения', имена: [] }; continue; }
    const имена = ссылки.flatMap((qid) => entityLabels(referents?.[qid], lang));
    по[p] = { вид: имена.length ? 'есть' : 'без-метки', имена: [...new Set(имена)] };
  }
  return по;
}

/** МОЛЧАНИЕ РЕЕСТРА ПО КАРТОЧКЕ — отдельный вывод: это НЕ ошибка карточки, и путать нельзя. */
export function registrySilence(состояние) {
  return NAME_PROPS
    .filter((p) => состояние[p] && состояние[p].вид !== 'есть')
    .map((p) => ({ свойство: p, роль: PROP_TITLES[p], вид: состояние[p].вид }));
}

/** Роль молчит, когда НИ ОДНО из её свойств не даёт имени на этом языке. */
const ролиМолчат = (виды) => виды.every((v) => v !== 'есть');

/** Разбивка на предложения. Роль не переходит границу предложения — это её естественный край. */
const предложения = (t) => String(t ?? '').split(/(?<=[.!?])\s+/u).filter((s) => s.trim());

/**
 * НАХОДКИ ПО ОДНОМУ ТЕКСТУ. Каждая несёт имя, роль, вердикт и то, ЧТО реестр даёт по этой роли, —
 * человеку нужен не ярлык, а строка, по которой он решит сам.
 *
 * Вердикты: `подтверждено` (в вывод не идёт) · `молчание` · `расхождение`.
 */
export function nameFindings(text, lang, состояние, свои = []) {
  const подтверждающие = NAME_PROPS.flatMap((p) => состояние?.[p]?.имена ?? []).concat(свои.filter(Boolean));
  const находки = [];
  let подтверждено = 0;
  let внеРоли = 0;

  for (const s of предложения(text)) {
    const метки = [];
    for (const r of РОЛИ) {
      const образец = r.образцы[lang];
      if (!образец) continue;
      for (const m of s.matchAll(образец)) метки.push({ конец: m.index + m[0].length, роль: r });
    }
    метки.sort((a, b) => a.конец - b.конец);

    let цепочка = null;   // роль, чьё перечисление идёт прямо сейчас
    let хвост = -1;       // конец последнего принятого куска

    for (const m of s.matchAll(СВЯЗКА)) {
      const фраза = m[0].replace(/[.,;:]+$/u, '').trim();
      if (фраза.split(/\s+/u).length < 2) continue;   // одиночное слово именем не считаем

      const маркер = метки.filter((x) => x.конец <= m.index).at(-1);
      let роль = null;
      if (маркер) {
        const приМаркере = (m.index - маркер.конец) <= ROLE_WINDOW;
        const продолжение = цепочка === маркер.роль && хвост >= 0 && СОЕДИНИТЕЛЬ.test(s.slice(хвост, m.index));
        if (приМаркере || продолжение) роль = маркер.роль;
      }

      if (подтверждающие.some((r) => nameMatches(фраза, r))) {
        подтверждено += 1;
        if (роль) { цепочка = роль; хвост = m.index + m[0].length; }
        continue;
      }
      if (!роль) { внеРоли += 1; continue; }
      цепочка = роль;
      хвост = m.index + m[0].length;

      const виды = роль.props.map((p) => состояние?.[p]?.вид ?? 'нет-свойства');
      const молчит = ролиМолчат(виды);
      находки.push({
        имя: фраза,
        роль: роль.роль,
        вердикт: молчит ? 'молчание' : 'расхождение',
        вид: молчит ? виды.find((v) => v !== 'есть') : 'есть',
        реестрДаёт: роль.props.flatMap((p) => состояние?.[p]?.имена ?? []),
        предложение: s,
      });
    }
  }
  return { находки, подтверждено, внеРоли };
}

/**
 * ОДНОЙ СТРОКОЙ КАЖДОЕ — то, что канал замечаний кладёт человеку на глаза.
 * Отказов здесь нет ни одного: прибор предъявляет, решает человек.
 */
export function nameNotes(text, lang, состояние, свои = []) {
  const { находки } = nameFindings(text, lang, состояние, свои);
  return находки.map((f) => (f.вердикт === 'молчание'
    ? `${f.роль}: «${f.имя}» — реестр молчит (${ПОЧЕМУ[f.вид] ?? f.вид}), сверить нечем`
    : `${f.роль}: «${f.имя}» — реестр даёт другое: ${f.реестрДаёт.slice(0, 4).join(', ')}`));
}

