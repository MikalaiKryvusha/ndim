import { readdirSync, statSync, existsSync } from 'node:fs';
import { join } from 'node:path';

/** Что в `src/` не считается исходником сборки: сюда сборка не смотрит. */
const ПРОПУСК = new Set(['node_modules', '.svelte-kit']);

/**
 * Самый свежий файл дерева: время и адрес. Адрес обязателен — «сборка устарела» без имени файла
 * заставляет человека искать причину руками, а имя отвечает на «почему» сразу.
 *
 * @returns {{ at: number, file: string, count: number } | null} `null` — дерева нет вовсе
 */
export function newestIn(dir) {
  if (!existsSync(dir)) return null;
  let at = 0;
  let file = '';
  let count = 0;
  /** @param {string} d */
  const обойти = (d) => {
    for (const e of readdirSync(d, { withFileTypes: true })) {
      if (ПРОПУСК.has(e.name)) continue;
      const p = join(d, e.name);
      if (e.isDirectory()) {
        обойти(p);
        continue;
      }
      count += 1;
      const m = statSync(p).mtimeMs;
      if (m > at) {
        at = m;
        file = p;
      }
    }
  };
  обойти(dir);
  return count === 0 ? null : { at, file, count };
}

/** Момент в виде, который читает человек, — локальное время, а не ISO в UTC. */
const когда = (ms) =>
  new Date(ms).toLocaleString('ru-RU', { dateStyle: 'short', timeStyle: 'medium' });

/**
 * Свежа ли сборка относительно исходников.
 *
 * @param {{ src?: string, build?: string }} [opts]
 * @returns {{ fresh: boolean, why: string, srcAt: number|null, buildAt: number|null,
 *             srcFile: string, buildFile: string, srcCount: number, buildCount: number }}
 */
export function buildFreshness({ src = 'src', build = 'build' } = {}) {
  const s = newestIn(src);
  const b = newestIn(build);

  // Порядок ответов важен: «сборки нет» и «сборка устарела» лечатся одинаково, но читаются
  // по-разному, и слить их в одну строку значило бы спрятать половину случаев.
  if (!b) {
    return {
      fresh: false,
      why: `каталога «${build}» нет или он пуст — сначала \`npm run build\``,
      srcAt: s?.at ?? null, buildAt: null,
      srcFile: s?.file ?? '', buildFile: '',
      srcCount: s?.count ?? 0, buildCount: 0,
    };
  }
  if (!s) {
    return {
      fresh: false,
      why: `каталога «${src}» нет или он пуст — мерить нечем, и это НЕ «свежо»`,
      srcAt: null, buildAt: b.at,
      srcFile: '', buildFile: b.file,
      srcCount: 0, buildCount: b.count,
    };
  }

  const fresh = b.at >= s.at;
  return {
    fresh,
    why: fresh
      ? `сборка не старше исходников: ${когда(b.at)} против ${когда(s.at)}`
      : `СБОРКА УСТАРЕЛА: ${когда(b.at)} против исходника ${когда(s.at)} · новее всех «${s.file}»`,
    srcAt: s.at, buildAt: b.at,
    srcFile: s.file, buildFile: b.file,
    srcCount: s.count, buildCount: b.count,
  };
}

/**
 * Строка для шапки отчёта. Прибор ОБЯЗАН её печатать, даже когда всё свежо: числа и кадры,
 * снятые с несвежего артефакта, ничем не отличаются от снятых со свежего — кроме этой строки.
 *
 * Дробь здесь не украшение (`TESTING_FRAMEWORK.md` правило 10, вопрос 3): «сборка свежа» при
 * нуле осмотренных файлов означало бы, что прибор не достал материал, а не что материал хорош.
 */
export function freshnessLine(f = buildFreshness()) {
  const знак = f.fresh ? '✅' : '🔴';
  return `${знак} свежесть сборки: ${f.why} · осмотрено src ${f.srcCount} · build ${f.buildCount}`;
}
