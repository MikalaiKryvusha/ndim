/**
 * КАК ГАСИТЬ СВОЙ СТЕНД — один рецепт на все приборы, и он привязан к ПОРТУ, а не к подстроке.
 *
 * Зачем модуль. Рецепт гашения жил дословной копией в двух съёмщиках кадров, и обе копии
 * советовали одно и то же: перебрать `node.exe` и убить всё, чья командная строка совпала с
 * маской `'vite'`. На машине одного агента это работало. В командном режиме
 * (`NDIM_WORKTREE_DEV_TEAM_MANIFEST.md`) — это выстрел по соседям: пять рабочих мест, у каждого
 * свой `node_modules/vite`, и маска `'vite'` накрывает preview другой роли ровно так же, как
 * свой. Роль при этом не узнает, что её сервер погас: она увидит «страница не отвечает» и пойдёт
 * искать дефект в продукте.
 *
 * 🔑 ПОЧЕМУ ПОРТ — ПРАВИЛЬНЫЙ ПРИЗНАК «МОЁ». Стенд занят по замку доски ОДНОЙ ролью, и порт —
 * это ровно та вещь, которую замок и выдаёт. Держатель порта единственный, находится по системной
 * таблице соединений и гасится по PID. Признак не зависит ни от формы командной строки, ни от
 * того, чем поднят сервер, и по построению не может задеть чужой процесс на другом порту.
 *
 * 🔴 ТРИ ОПЛАЧЕННЫХ ПОЛЕМ ПРИЧИНЫ НЕ ВОЗВРАЩАТЬ МАСКУ:
 *   · `EXP-0081` — поиск по подстроке НАХОДИТ САМ ПОИСК: команда убила собственный PowerShell,
 *     а паника расширила радиус и уронила чужие MCP-серверы;
 *   · `EXP-0131` — гашение по имени инструмента задело бы страницы ЧУЖОГО проекта на этой же
 *     машине; спасло только несовпадение имён файлов, то есть случайность;
 *   · 2026-08-21, `dev-2` — обратная сторона той же монеты: узкая маска `'vite preview'` не нашла
 *     НИ ОДНОГО процесса при живом сервере (настоящая командная строка —
 *     `"node" "…\vite\bin\vite.js" preview`), и «процессов 0» при отвечающем порте читается как
 *     «всё чисто». Осиротевший preview потом отдаёт СТАРУЮ сборку, а кадры с него врут
 *     (`EXP-0091`).
 *
 * Маска ошибается в обе стороны: слишком широкая бьёт по чужому, слишком узкая молчит о своём.
 * Порт не ошибается ни в одну.
 */

