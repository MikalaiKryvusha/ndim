/**
 * Готовая к вставке строка PowerShell: погасить держателя ИМЕННО ЭТОГО порта.
 *
 * `-ErrorAction SilentlyContinue` стоит сознательно: «порт никто не слушает» — это НОРМА, а не
 * ошибка, и краснеть на ней рецепт не должен.
 *
 * @param {number} port порт, чей держатель гасится
 */
export const killPortRecipe = (port) =>
  `Get-NetTCPConnection -LocalPort ${port} -State Listen -ErrorAction SilentlyContinue | ` +
  `ForEach-Object { Stop-Process -Id $_.OwningProcess -Force }`;

/**
 * Строка «кто держит порт» — для ЧТЕНИЯ ГЛАЗАМИ перед гашением (`EXP-0131`: сначала посмотри
 * командные строки, потом гаси).
 *
 * @param {number} port
 */
export const whoHoldsPortRecipe = (port) =>
  `Get-NetTCPConnection -LocalPort ${port} -State Listen -ErrorAction SilentlyContinue | ` +
  `ForEach-Object { Get-CimInstance Win32_Process -Filter "ProcessId=$($_.OwningProcess)" } | ` +
  `Select-Object ProcessId, CommandLine`;
