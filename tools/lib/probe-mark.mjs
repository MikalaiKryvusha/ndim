/**
 * МЕТКА СВОЕГО ПРОГОНА: прибор перестаёт считаться человеком в воронке.
 *
 * ═══ ПОВОД ═══
 *
 * Первое в истории проекта чтение `space/funnel/days` целиком (аудит 2026-08-28, `bugs/202`
 * дефект 2) дало `guest_start` = 77 за 25 дней. Четыре всплеска внутри — 10 (08-14) · 16
 * (08-15) · 11 (08-17) · 26 (08-22) — пришлись РОВНО на дни выкатов и боевых смоуков, а в
 * дни без выкатов гостей было 0–1.
 *
 * Причина в том, что наши приборы честно ходят настоящей дверью гостя (`/profile?guest=1`,
 * свежий контекст → `track('guest_start')`) и от живого человека НЕОТЛИЧИМЫ. То есть прибор
 * притока показывал владельцу нас самих, а вопрос «сколько пришло людей» оставался без
 * ответа именно в те дни, когда ответ был нужнее всего.
 *
 * ═══ ЧТО ДЕЛАЕТ ═══
 *
 * Ставит `sessionStorage['ndim-probe'] = '1'` **до первой навигации** — через
 * `addInitScript`, то есть скриптом, который исполняется в каждом документе контекста
 * РАНЬШЕ кода приложения. `track()` при этой метке молчит (`src/lib/data/funnel.ts`).
 *
 * 🔑 **Почему `addInitScript`, а не `page.evaluate` после `goto`.** Первый шаг воронки
 * считается на первом же кадре страницы: к моменту, когда прибор доберётся до `evaluate`,
 * `track('landing_view')` уже отработал и число уже испорчено. Метка обязана существовать
 * ДО того, как приложение получит управление, — другого места у неё нет.
 *
 * 🔑 **Метится КОНТЕКСТ, а не страница.** `sessionStorage` живёт на вкладку и на источник:
 * прибор, заводящий второй контекст (второй гость, вторая тема, второй размер экрана),
 * обязан пометить и его. Поэтому помощник принимает контекст, а не браузер, и поэтому же
 * `tools/verify-probe-mark.mjs` судит каждый вызов `newContext`.
 *
 * ═══ ГРАНИЦЫ, НАЗВАННЫЕ ЧЕСТНО ═══
 *
 * · Метка НИЧЕГО не отключает, кроме счётчиков воронки: продукт под ней работает ровно так
 *   же, и прибор судит то же самое, что судил вчера. Это не «режим тестирования» — таких
 *   режимов в продукте нет и заводить их нельзя (они красят зелёным непроверенное).
 * · Метка НЕ чистит прошлые числа. Ряд до дня выката остаётся загрязнённым, и разрыв
 *   помечается датой честно (`plans/74`: задним числом ничего не переписываем).
 * · Метка не защищает от накрутки посторонним — она о СВОИХ прогонах. Накрутка это App
 *   Check, отдельная работа и отдельный риск (шапка `funnel.ts`).
 * · Человеку эта метка достаться не может: её некому поставить. Обратное — единственный
 *   способ ошибиться в СТОРОНУ НЕДОСЧЁТА, и он требует, чтобы кто-то выполнил её руками
 *   в консоли своей вкладки.
 *
 * Применение (после каждого `newContext`, до первого `goto`):
 *
 *     import { markProbeContext } from './lib/probe-mark.mjs';
 *     const ctx = await browser.newContext({ ... });
 *     await markProbeContext(ctx);
 *
 * Родня: `plans/74` фаза 1 Ш3 · `bugs/202` · страж `tools/verify-probe-mark.mjs`.
 */

/**
 * Имя метки. ОДНА пара с `PROBE_MARK` в `src/lib/data/funnel.ts`, и пару сторожит
 * `tools/verify-probe-mark.mjs`: разъехавшиеся имена дали бы молчаливый недосмотр —
 * прибор считал бы себя помеченным, а продукт считал бы его человеком.
 */
export const PROBE_MARK = 'ndim-probe';

/**
 * Метит контекст браузера как наш прогон.
 *
 * Обращение к хранилищу защищено на СТОРОНЕ СТРАНИЦЫ: `sessionStorage` бросает в документах,
 * у которых нет источника (`about:blank`, песочница фрейма), а init-скрипт исполняется в
 * каждом из них. Непойманное исключение здесь роняло бы саму страницу прибора — то есть
 * метка сломала бы прогон, который пришла лечить.
 *
 * @param {import('@playwright/test').BrowserContext} context контекст ПОСЛЕ `newContext()`
 * @returns {Promise<void>}
 */
export async function markProbeContext(context) {
  await context.addInitScript((mark) => {
    try {
      sessionStorage.setItem(mark, '1');
    } catch {
      // Хранилища нет — метить нечего и ронять нечего.
    }
  }, PROBE_MARK);
}

/**
 * То же для приборов, которые заводят страницу напрямую (`browser.newPage()`): у такой
 * страницы контекст всё равно есть, он просто неявный.
 *
 * ⚠️ Звать СРАЗУ после `newPage()` и ДО первого `goto`. Init-скрипт применяется к
 * следующим навигациям, а не к уже загруженному документу: помеченная задним числом
 * страница успеет посчитать свой шаг.
 *
 * @param {import('@playwright/test').Page} page страница ПОСЛЕ `newPage()`, до `goto`
 * @returns {Promise<void>}
 */
export async function markProbePage(page) {
  await markProbeContext(page.context());
}
