/**
 * КЛЮЧИ СЕРВИСНЫХ АККАУНТОВ — единственное место, где прибор берёт доступ к контуру.
 *
 * 🔴 ПРАВИЛО ВЛАДЕЛЬЦА 2026-08-15: «*ключи нужно вынести в .env, никогда ключи в коде и других
 * файлах не храним*». Поэтому здесь НЕТ чтения файлов ключей — только `.env`.
 *
 * ПОЧЕМУ BASE64, А НЕ СЫРОЙ JSON В ЗНАЧЕНИИ. Ключ Google — это JSON, внутри которого `private_key`
 * несёт PEM. В JSON переводы строк уже экранированы, но само значение остаётся строкой с
 * фигурными скобками, запятыми и кавычками — а `.env` разбирают десятки разных парсеров
 * (Node `--env-file`, docker `--env-file`, оболочки), и каждый обращается с кавычками по-своему.
 * Base64 — ASCII без единого спецсимвола: одна строка, которую нельзя разобрать неправильно.
 *
 * ПОЧЕМУ КОНТУР — ЧАСТЬ ИМЕНИ ПЕРЕМЕННОЙ. Контуров два, ключи разные, и цена путаницы
 * несимметрична: боевым ключом можно перезаписать данные живых людей. Имя переменной называет
 * контур вслух, поэтому «взял не тот ключ» перестаёт быть молчаливой опечаткой.
 */
import { loadEnv } from './env.mjs';

/** Имя переменной окружения для контура. */
const VAR = { prod: 'NDIM_PROD_SA_B64', stage: 'NDIM_STAGE_SA_B64' };

/** Проект Firebase каждого контура — чтобы «ключ стейджа + боевой проект» было невыразимо. */
export const PROJECT_OF = { prod: 'ndim-space', stage: 'ndim-stage' };

/**
 * Ключ сервисного аккаунта контура как объект для `cert()`.
 *
 * Падает громко и с адресом лечения: молчаливый `undefined` ушёл бы в Admin SDK и вернулся
 * невнятной ошибкой авторизации через минуту работы.
 */
export function serviceAccount(contour) {
	loadEnv();
	const name = VAR[contour];
	if (!name) throw new Error(`неизвестный контур «${contour}»; ожидались: ${Object.keys(VAR).join(', ')}`);
	const raw = process.env[name];
	if (!raw) {
		throw new Error(
			`нет ключа контура «${contour}»: переменная ${name} пуста.\n` +
				`Заполните .env по образцу .env.example (значение — base64 от JSON ключа).`,
		);
	}
	let parsed;
	try {
		parsed = JSON.parse(Buffer.from(raw, 'base64').toString('utf8'));
	} catch (error) {
		throw new Error(`${name} не разбирается: ожидался base64 от JSON ключа (${error.message})`);
	}
	// Проверка «ключ того контура, за который себя выдаёт»: имя переменной и содержимое ключа
	// обязаны сойтись, иначе одна перепутанная строка в .env даёт запись не в тот проект.
	if (parsed.project_id !== PROJECT_OF[contour]) {
		throw new Error(
			`${name} содержит ключ проекта «${parsed.project_id}», а контур «${contour}» — это ` +
				`«${PROJECT_OF[contour]}». Проверьте .env.`,
		);
	}
	return parsed;
}
