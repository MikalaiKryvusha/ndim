/**
 * Завершение прибора, который ходит в сеть: код возврата ВЫСТАВЛЯЕТСЯ, а не выстреливается.
 *
 * ⚠️ ЦЕНА ЭТОГО МОДУЛЯ УПЛАЧЕНА ПРОГОНОМ 2026-08-28, и вот чем именно.
 *
 * `process.exit()` при живом сетевом соединении роняет процесс на Windows:
 * `Assertion failed: !(handle->flags & UV_HANDLE_CLOSING)` — и код возврата приезжает **127
 * вместо 1**. Прибор при этом печатает ПРАВИЛЬНЫЙ отказ, а вызывающий, судящий по коду, видит
 * бессмыслицу. Дренирования тела ответа не хватает: сокет держит пул соединений.
 * `process.exitCode` даёт циклу событий закрыться самому, и код доезжает честным.
 *
 * 🔑 ПОЧЕМУ ЭТО МОДУЛЬ, А НЕ ПРАВИЛО В ГОЛОВАХ. Пять сетевых приборов несли этот хвост копиями,
 * из них три — старой редакцией с `process.exit()`. Два уцелевших держались не устройством, а
 * тем, что их правили последними: судья QA назвал это «везением, а не устройством» (срез суда
 * №4 по «Зрение» Ф2, пункт 3 неотсуженного). Один общий хвост убирает класс по построению —
 * забыть его нельзя, потому что писать нечего.
 *
 * Держится проверкой `tools/exit-after-fetch.test.mjs` — она в воротах `npm run test:tools`,
 * а не рядом с ними.
 */

/**
 * Довести `main()` до кода возврата, не убивая процесс.
 *
 * @param {Promise<number>} promise — обещание `main()`, разрешающееся кодом возврата.
 * @returns {Promise<void>} завершается, когда код выставлен (нужно тестам, приборам — нет).
 */
export function settleExit(promise) {
	return promise.then(
		(code) => {
			process.exitCode = code;
		},
		(error) => {
			console.error(`🔴 ${error.message}`);
			process.exitCode = 1;
		},
	);
}
