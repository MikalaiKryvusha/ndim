/**
 * Глаголы производства в ДЕЙСТВИТЕЛЬНОМ залоге. Дословно из `genre-depth.mjs` Дизайнера
 * (`ndim_designer`, `e7f04a1`) — правка этого списка идёт через неё, а не здесь.
 */
/*
 * 🔑 СЛОВА ОБЪЯВЛЕНЫ СПИСКОМ, А ОБРАЗЕЦ СОБИРАЕТСЯ ИЗ НИХ (правка 2026-08-22). Слова остались
 * ДОСЛОВНО теми же — сменилась только форма объявления. Повод: класс 7 владельца
 * («*"поставила его" - поставлен*») судит те же самые глаголы, и ему нужен образец с другими
 * границами. Вторая копия списка разъехалась бы с этой на первом же добавленном глаголе —
 * ровно та пара «истина ↔ зеркало», за которую проект уже платил.
 */
export const PRODUCTION_ACTIVE_WORDS = {
  ru: ['снял', 'сняла', 'сняли', 'снимал', 'написал', 'написала', 'написали', 'поставил',
    'поставила', 'поставили', 'создал', 'создала', 'создали', 'произвёл', 'произвела',
    'произвели', 'выпустил', 'выпустила', 'выпустили', 'срежиссировал', 'спродюсировал',
    'экранизировал', 'издал', 'издала', 'разработал', 'разработала', 'сочинил', 'сочинила'],
  en: ['directed', 'wrote', 'writes', 'created', 'creates', 'produced', 'produces', 'adapted',
    'adapts', 'developed', 'develops', 'built', 'builds', 'published', 'publishes', 'filmed',
    'films', 'shot', 'scored', 'edited', 'helmed', 'made', 'directs', 'creates'],
};

export const PRODUCTION_ACTIVE = {
  ru: new RegExp(`^(${PRODUCTION_ACTIVE_WORDS.ru.join('|')})$`, 'iu'),
  en: new RegExp(`^(${PRODUCTION_ACTIVE_WORDS.en.join('|')})$`, 'iu'),
};

/**
 * Слова, которые пишутся с заглавной по грамматике, а не потому, что они имя. Без этого списка
 * «*Both are built…*» и «*The film made…*» читались бы как «деятель назван».
 * ⚠️ Список УЗКИЙ намеренно: он снимает начало предложения и служебные слова, а не решает,
 * имя перед нами или нет. Решать это машине нечем, и прибор здесь только предъявляет.
 */
const НЕ_ИМЯ = new Set([
  'the', 'a', 'an', 'this', 'that', 'these', 'those', 'both', 'some', 'each', 'every',
  'on', 'for', 'at', 'in', 'by', 'with', 'and', 'but', 'it', 'he', 'she', 'they', 'who',
  'и', 'в', 'на', 'он', 'она', 'они', 'оба', 'обе', 'это', 'эта', 'этот', 'тот', 'та', 'который',
]);

const слова = (s) => String(s ?? '').match(/[\p{L}\p{N}'’-]+/gu) ?? [];
const выглядитИменем = (w) => Boolean(w) && /^\p{Lu}/u.test(w) && !НЕ_ИМЯ.has(w.toLowerCase());

/**
 * ДЕЙСТВИТЕЛЬНЫЕ ПРОИЗВОДСТВЕННЫЕ ОБОРОТЫ С НАЗВАННЫМ ДЕЯТЕЛЕМ.
 * Возвращает найденные глаголы; пустой список означает «в этом предложении такого оборота нет».
 * Деятель считается названным, когда слово с заглавной стоит вплотную СЛЕВА или СПРАВА: по-русски
 * он чаще справа («*сценарий написал Дрю Годдард*»), по-английски слева («*Nolan directed*»).
 */
export function activeProductionHits(предложение, lang = 'ru') {
  const образец = PRODUCTION_ACTIVE[lang];
  if (!образец) return [];
  const сс = слова(предложение);
  const из = [];
  for (let i = 0; i < сс.length; i += 1) {
    if (!образец.test(сс[i])) continue;
    if (выглядитИменем(сс[i - 1]) || выглядитИменем(сс[i + 1])) из.push(сс[i]);
  }
  return из;
}
