/**
 * Слова первого предложения.
 * · Дефис внутри слова сохраняется: «научно-фантастический» — одно слово, и разрывать его значило
 *   бы сдвигать шкалу на ровном месте.
 * · ЧИСЛА СЧИТАЮТСЯ СЛОВАМИ. Шкала меряет, сколько слов читатель прочтёт до жанра, а год он
 *   читает наравне с остальным: «The 2002 American psychological thriller» — жанр на четвёртом
 *   слове, и выбрасывать «2002» из счёта значило бы врать в пользу текста. Поймано самотестом.
 */
export function words(предложение) {
  return String(предложение ?? '').match(/[\p{L}\p{N}][\p{L}\p{N}\p{M}-]*/gu) ?? [];
}

/**
 * ГЛУБИНА ЖАНРА в одном предложении.
 * @returns {{глубина: number|null, слово: string|null, всего: number}}
 */
export function genreDepthOfSentence(предложение, lang = 'ru') {
  const образцы = GENRE_WORDS[lang] ?? [];
  const сс = words(предложение);
  for (let i = 0; i < сс.length; i += 1) {
    if (образцы.some((re) => re.test(сс[i]))) {
      return { глубина: i + 1, слово: сс[i], всего: сс.length };
    }
  }
  return { глубина: null, слово: null, всего: сс.length };
}

/**
 * ГЛУБИНА ЖАНРА в описании: по ПЕРВОМУ предложению.
 * @param splitSentences разбиватель ворот (`tools/lib/prose-gates.mjs`) — свой не заводим.
 */
export function genreDepth(text, lang = 'ru', splitSentences) {
  const ss = splitSentences(text);
  if (!ss.length) return { глубина: null, слово: null, всего: 0, первое: '' };
  return { ...genreDepthOfSentence(ss[0], lang), первое: ss[0] };
}

/**
 * ═══ ЗАЧИН ДЕЙСТВИТЕЛЬНЫМ ПРОИЗВОДСТВЕННЫМ ОБОРОТОМ ═══
 *
 * 🔴 Заведено 2026-08-22 после того, как проба на 360 правках нашла СЛЕПОЕ ПЯТНО у доли меты.
 * Её лексикон держит страдательные обороты — «directed by», «written by», «produced», — а конвейер
 * правок переписал их действительными: «*Wilford Lloyd Baumes created this American series*»,
 * «*Devin Clark created this American animated sitcom*», «*снял её Ди Джей Карузо*». Ни один
 * страдательный образец на них не срабатывает, и прибор доли меты называет такое предложение
 * СОДЕРЖАНИЕМ.
 *
 * Замер слепого пятна на журналах правок: первое предложение открывается действительным
 * производственным оборотом у **56** описаний до правки и у **112** после — ровно вдвое больше;
 * из них доля меты не признала производством **30 из 56** и **81 из 112**.
 *
 * 🔑 Отсюда и смысл признака: имя человека, поставленное первым словом, — это ТО ЖЕ САМОЕ
 * производство впереди содержания, только в другом залоге. Замена залога дефекта не лечит, а
 * прячет — и прячет именно от прибора.
 *
 * ⚠️ 🔴 ОКНА У ПРИЗНАКА НЕТ, И ЭТО ВАЖНО. Первая редакция ловила производственный глагол в
 * первых шести словах — и красила исправный зачин «*The 2002 American psychological thriller
 * **directed** by Christopher Nolan*», где глагол стоит шестым, но ПОСЛЕ жанра. Поймано
 * самотестом. Правило переписано на сравнение ПОЗИЦИЙ: производство впереди тогда и только
 * тогда, когда производственный оборот стоит РАНЬШЕ жанрового слова. Окно осталось одно —
 * запасное, для предложений, где жанра нет вовсе.
 */
export const PRODUCTION_ACTIVE = {
  ru: /^(снял|сняла|сняли|снимал|написал|написала|написали|поставил|поставила|поставили|создал|создала|создали|произвёл|произвела|произвели|выпустил|выпустила|выпустили|срежиссировал|спродюсировал|экранизировал|издал|издала|разработал|разработала|сочинил|сочинила)$/iu,
  en: /^(directed|wrote|writes|created|creates|produced|produces|adapted|adapts|developed|develops|built|builds|published|publishes|filmed|films|shot|scored|edited|helmed|made|directs|creates)$/iu,
};

/** Запасное окно: применяется ТОЛЬКО когда жанрового слова в предложении нет вовсе. */
export const ЗАЧИН_СЛОВ = 6;

/**
 * Позиция первого действительного производственного оборота в предложении.
 * @returns {{есть: boolean, слово: string|null, место: number|null}}
 */
export function opensWithProduction(предложение, lang = 'ru') {
  const re = PRODUCTION_ACTIVE[lang];
  if (!re) return { есть: false, слово: null, место: null };
  const сс = words(предложение);
  for (let i = 0; i < сс.length; i += 1) {
    if (re.test(сс[i])) return { есть: true, слово: сс[i], место: i + 1 };
  }
  return { есть: false, слово: null, место: null };
}

/**
 * КЛАСС ЗАЧИНА — чем открывается первое предложение.
 * `производство` — производственный оборот стоит РАНЬШЕ жанрового слова (или жанра нет вовсе,
 *   а оборот стоит в первых `ЗАЧИН_СЛОВ` словах) · `жанр` — жанр назван раньше производства ·
 * `иное` — ни того, ни другого признака в предложении нет.
 */
export function openingClass(предложение, lang = 'ru') {
  const ж = genreDepthOfSentence(предложение, lang).глубина;
  const п = opensWithProduction(предложение, lang);
  if (п.есть && (ж === null ? п.место <= ЗАЧИН_СЛОВ : п.место < ж)) {
    return { класс: 'производство', жанр: ж, производство: п.место, слово: п.слово };
  }
  if (ж !== null) return { класс: 'жанр', жанр: ж, производство: п.место, слово: null };
  return { класс: 'иное', жанр: null, производство: п.место, слово: null };
}

/**
 * СДВИГ между «было» и «стало» — приговор одной правке.
 * `ухудшение` — жанр уехал вглубь · `улучшение` — вышел вперёд · `ровно` — не сдвинулся ·
 * `жанр пропал` и `жанр появился` — разряды, где сравнивать числа нечем.
 */
export function depthShift(было, стало) {
  const a = было?.глубина ?? null;
  const b = стало?.глубина ?? null;
  if (a === null && b === null) return { исход: 'жанра нет ни там ни там', сдвиг: null };
  if (a === null) return { исход: 'жанр появился', сдвиг: null };
  if (b === null) return { исход: 'жанр пропал', сдвиг: null };
  if (b > a) return { исход: 'ухудшение', сдвиг: b - a };
  if (b < a) return { исход: 'улучшение', сдвиг: b - a };
  return { исход: 'ровно', сдвиг: 0 };
}
