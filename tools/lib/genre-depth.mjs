/**
 * ГЛУБИНА ЖАНРА — на каком слове читатель узнаёт, ЧТО перед ним.
 *
 * Признак заведён 2026-08-22 Дизайнером (ревьювером) по `bugs/180`: владелец отказался вычитывать
 * 360 правок и потребовал урегулировать их ПРАВИЛАМИ. Признак превращает его слова в число.
 *
 * ═══ ЗАЧЕМ ОТДЕЛЬНЫЙ ПРИЗНАК, КОГДА ЕСТЬ ДОЛЯ МЕТЫ ═══
 *
 * Доля меты (`tools/lib/meta-share.mjs`, dev-3) отвечает на вопрос СКОЛЬКО в тексте производства.
 * Она НЕ отвечает на вопрос, что стоит ВПЕРЕДИ, — а сломалось у конвейера правок именно это.
 * Образец из `bugs/180`, английская «Бессонница»:
 *
 *   Было:  «The 2002 American psychological thriller directed by Christopher Nolan…»
 *   Стало: «Hillary Seitz wrote the screenplay and Christopher Nolan directed this 2002
 *           American psychological thriller…»
 *
 * Производственных слов столько же, предложений столько же — доля меты у обоих текстов ОДНА И ТА
 * ЖЕ. А правило владельца нарушено сильнее: раньше фраза открывалась жанром, теперь двумя
 * фамилиями. Слово владельца, по которому судим: «*много пишут про создание объекта культуры и
 * мало про его само содержание, сюжет — это важнее*» (2026-08-22).
 *
 * ═══ 🔴 ПОЧЕМУ ПРИЗНАК НЕ «МЕТА В ПЕРВОМ ПРЕДЛОЖЕНИИ» ═══
 *
 * Такой признак осудил бы текст САМОГО ВЛАДЕЛЬЦА. Его зачин о «Матрице», написанный его рукой:
 *
 *   «*Научно-фантастический боевик братьев Вачовски: они же написали сценарий, продюсировал
 *   Джоэл Сильвер.*»
 *
 * Производство стоит здесь в первом же предложении, и это НОРМА: канон мастерской ставит жанр с
 * авторством первой из пяти частей описания. Владелец пишет так сам. Разница между его зачином и
 * сломанной правкой одна — у него жанр стоит ВТОРЫМ СЛОВОМ, а производство идёт следом. Поэтому
 * меряется позиция ЖАНРА, а не наличие меты.
 *
 * ═══ ЧЕМ МЕРИТСЯ ═══
 *
 * Мера называется ДО числа (`EXP-0191`, `EXP-0195`): **порядковый номер слова в ПЕРВОМ
 * предложении, на котором впервые стоит слово вида или жанра.** 1 — текст открывается им,
 * 13 — читатель прочтёт двенадцать слов, прежде чем узнает, что перед ним.
 *
 * · Эталон владельца («Матрица»): «Научно-фантастический боевик…» → **2**.
 * · «Бессонница» до правки: «The 2002 American psychological thriller…» → **4**.
 * · «Бессонница» после правки: «Hillary Seitz wrote the screenplay…» → **13**.
 *
 * Сравнение правки идёт по СДВИГУ: глубина «стало» больше глубины «было» — ухудшение, меньше —
 * улучшение. Сравниваются два текста об одном объекте, поэтому разница словарей не мешает.
 *
 * ⚠️ ЧЕСТНЫЕ ГРАНИЦЫ, все четыре:
 * 1. Жанрового слова может не быть вовсе — тогда глубина `null`, и это ОТДЕЛЬНЫЙ разряд, а не
 *    большое число. «Жанр не назван» и «жанр назван поздно» — разные беды, и лечатся розно.
 * 2. Словарь видов и жанров конечен. Слово вне словаря читается как «жанра нет», поэтому словарь
 *    взят из СЛОВАРЯ КАТАЛОГА (соглашение о тегах и жанровые слова его же описаний), а не выдуман.
 * 3. Признак смотрит ТОЛЬКО первое предложение. О том, что дальше, отвечает доля меты; два
 *    признака работают в паре.
 * 4. Видовое слово внутри ИМЕНИ ПРЕДПРИЯТИЯ признак не отличает: «Warner Brothers **Games**
 *    published it» даёт глубину 3, хотя жанра там нет. Цена мала и направлена в безопасную
 *    сторону — такой текст выглядит ЛУЧШЕ, чем он есть, то есть признак скорее пропустит беду,
 *    чем оболжёт исправный текст. Случай стоит в самотесте и закреплён как известное поведение.
 * 5. Прибор ПРЕДЪЯВЛЯЕТ, а не судит — порога-приговора здесь нет, как и у доли меты. Он даёт
 *    число и сдвиг; решение о карточке принимает человек.
 *
 * 🔴 ЛОЖНЫЕ СРАБАТЫВАНИЯ ПОЙМАНЫ ДО ПРОГОНА, А НЕ ПОСЛЕ. Первая редакция словаря брала основы
 * «игр», «рассказ», «повест», «практик» — и красила «Играют Джейсон Стейтем…», «Рассказывают её
 * с начала…», «повествует о жизни Моисея…», «практически». Все четыре стоят в самотесте
 * контролями. Отсюда устройство словаря: рискованные слова живут ТОЧНЫМИ ФОРМАМИ, основы
 * оставлены только там, где хвост однозначен.
 *
 * 🔒 Самотест — `tools/genre-depth.test.mjs`, входы РУССКИЕ (`AGENT_GUIDE.md` → «САМОТЕСТ РУССКОЙ
 * ПРОВЕРКИ ИДЁТ НА РУССКОМ ОБРАЗЦЕ»): `\b` и `\w` в JavaScript определены через ASCII и на
 * кириллице молча дают ноль. Здесь границы держит не образец, а РАЗБОР НА СЛОВА по `\p{L}`.
 */

/** Основа: слово начинается с неё. Годится там, где хвост однозначен («боевик», «боевике»). */
const основа = (...осн) => osnToRe(осн, false);
/** Точная форма: слово равно ей целиком. Для слов, чья основа живёт и в чужих словах. */
const форма = (...сл) => osnToRe(сл, true);
const osnToRe = (список, точно) =>
  список.map((s) => new RegExp('^' + s + (точно ? '$' : ''), 'iu'));

