/**
 * КЛАСС 1 ВЛАДЕЛЬЦА — «НЕ ВЫШЕДШИЙ ОБЪЕКТ НЕ ПОДАЁТСЯ НА ВЫЧИТКУ».
 *
 * Его слово дословно (`candidates/owner-critical-notes-2026-08-22.md`, класс 1):
 * «*Если назначен, то какого хуя ты завёл его и даёшь мне на вычитку как то, чем якобы люди
 * будут формировать свой профиль NDim ID? Как ты себе это представляешь, если люди ещё не видели
 * этот фильм?*» и отдельно: «*То есть, ещё выйдет? В будущем? А сегодня какая дата, когда ты это
 * пишешь*».
 *
 * ═══ 🔴 ЗАМЕР ПЕРЕВЕРНУЛ ПОСТАНОВКУ, И ЭТО ГЛАВНОЕ, ЧТО ЗДЕСЬ НАПИСАНО ═══
 *
 * Постановка звучала так: «дата выхода в будущем относительно дня прогона = ОТКАЗ; дату брать
 * из реестра, а не из текста». Прибор написан ровно такой. Но прогон реестра по ВСЕМ 50
 * карточкам партий 1–4 (2026-08-22, свойство `P577`) дал:
 *
 *   · карточек с датой выхода В БУДУЩЕМ — **0**;
 *   · карточек без `P577` вовсе — **0**;
 *   · обе карточки, возвращённые владельцем ИМЕННО за класс 1, вышли в ПРОШЛОМ:
 *     Resident Evil Requiem (`Q124983920`) — 2026-02-27, «Вот это драма!» (`Q130590402`) — 2026-03-17.
 *
 * 🔑 Значит фильтр по реестру на СЕГОДНЯШНЕМ материале не поймал бы НИ ОДНОЙ из тех карточек,
 * за которые владелец рассердился. Это третий вопрос лестницы к зелёному прогону
 * (`AGENT_GUIDE.md`): проверка исполняется, признак верен, а материал дать ей упасть не может.
 * Объявить такой прогон зелёным и уйти — значит выдать «правило держится» за «проверка не
 * способна покраснеть».
 *
 * ✅ ЧТО ЖЕ ЕГО РАССЕРДИЛО НА САМОМ ДЕЛЕ — ВИДНО В ТЕКСТЕ ЭТИХ ДВУХ КАРТОЧЕК:
 *   · «*Выход назначен на 27 февраля 2026 года…*» (Resident Evil Requiem);
 *   · «*…выход которой назначен на 2026 год*», «*устройство сюжета пока не раскрывалось*»
 *     («Вот это драма!»).
 * Объект вышел полгода назад, а карточка написана в будущем времени. Он прочитал «назначен» и
 * сделал единственный возможный вывод: «ещё выйдет? в будущем? а сегодня какая дата». Ошибка
 * не в отборе — она в том, что описание СТАРЕЕТ и никто его не пересматривает.
 *
 * 📐 Замер разделяющего признака «текст говорит о выходе как о будущем»:
 *   | Корпус                                  | Срабатываний | Записей |
 *   |-----------------------------------------|-------------:|--------:|
 *   | каталог владельца, срез 50 (его тексты)  | **0**        | 0       |
 *   | наши партии 1–4 (50 карточек)            | 8            | 8 из 50 |
 * И среди этих восьми — ОБЕ возвращённые карточки класса 1. Ноль на его собственных текстах
 * против восьми на наших — это разделение, а не порог по вкусу.
 *
 * ═══ ОТСЮДА У КЛАССА 1 ДВЕ ПОЛОВИНЫ, И ОНИ ПРИКРЫВАЮТ ДРУГ ДРУГА ═══
 *
 *   **1а — ФИЛЬТР ОТБОРА.** Реестр говорит, что объект ещё не вышел → ОТКАЗ. На партиях 1–4
 *   срабатываний ноль; ценность его вся впереди — в новых 60 карточках, где отбор идёт заново.
 *   Доказан мутацией (`tools/release-date.test.mjs`), а не прогоном по материалу, на котором
 *   покраснеть не на чем.
 *
 *   **1б — СТАРЫЙ РЕГИСТР ТЕКСТА.** Реестр говорит, что объект УЖЕ вышел, а описание пишет о
 *   нём как о будущем → ОТКАЗ. Восемь срабатываний на партиях 1–4.
 *
 * 🔑 Ложного отказа не даёт ни одна: 1б краснеет ТОЛЬКО когда реестр подтвердил, что объект
 * вышел. Если объект и правда не вышел, слово «назначен» законно — и тогда карточку
 * останавливает 1а, по своей причине и своими словами.
 *
 * ⛔ ЧЕГО ЭТОТ МОДУЛЬ НЕ ДЕЛАЕТ. Он не судит, ВЕРНА ли дата в тексте описания: сверка текста с
 * реестром по числам — отдельная работа, и замера под неё нет. Он не знает даты, которой нет в
 * реестре: «нет `P577`» — утверждение о РЕЕСТРЕ, а не о мире (`EXP-0165`), и такая карточка
 * получает ЗАМЕЧАНИЕ, а не отказ и не зелёный.
 *
 * ⚠️ ГРУБАЯ ТОЧНОСТЬ РЕЕСТРА — ТРЕТИЙ ИСХОД, А НЕ ОКРУГЛЕНИЕ. У `P577` бывает точность «год»
 * (`precision 9`) и «месяц» (`10`). Запись «2026 год» в августе 2026-го не отвечает на вопрос
 * «вышел ли»: объект мог выйти в марте, а мог выйти в декабре. Поэтому ОТКАЗ ставится, только
 * когда в будущем лежит ПОЗДНЯЯ граница периода — то есть когда объект не вышел НИ ПРИ КАКОМ
 * прочтении записи. Иначе — замечание. Ложный отказ здесь дороже недосчёта: он снимает с
 * вычитки живой объект.
 * 📐 В партиях 1–4 грубых записей 4 из 50, и у всех четырёх рядом стоит точная дата в прошлом
 * (Deltarune `+2027-00-00` при выходе 2018-10-31), поэтому ни одна замечания не получила.
 *
 * 🟢 Работы на верхнем уровне нет — файл безопасен для импорта.
 *
 * Проверки: node --test tools/release-date.test.mjs   ·   npm run test:tools
 * Замер:    node tools/measure-owner-classes.mjs
 */

/** Свойство реестра «дата публикации». Одно место объявления — его же зовёт прибор отбора. */
export const СВОЙСТВО_ДАТЫ = 'P577';

const дней = (год, месяц) => new Date(Date.UTC(год, месяц, 0)).getUTCDate();
const дву = (n) => String(n).padStart(2, '0');

/**
 * ПЕРИОД, КОТОРЫЙ ОБОЗНАЧАЕТ ЗАПИСЬ РЕЕСТРА. Возвращает `{ рано, поздно }` в виде `YYYY-MM-DD`
 * либо `null`, если точность грубее десятилетия — такую запись машина не толкует вовсе.
 *
 * Формат реестра: `+2026-02-27T00:00:00Z`, где месяц и день бывают `00` при грубой точности.
 * Точность: 11 — день, 10 — месяц, 9 — год, 8 — десятилетие.
 */
export function периодЗаписи(time, precision) {
  const m = /^([+-])(\d{4,})-(\d{2})-(\d{2})T/u.exec(String(time ?? ''));
  if (!m || m[1] === '-') return null;           // до нашей эры карточек мастерской не бывает
  const год = Number(m[2]);
  const месяц = Number(m[3]);
  const день = Number(m[4]);
  const p = Number(precision);
  if (p >= 11 && месяц && день) return { рано: `${m[2]}-${дву(месяц)}-${дву(день)}`, поздно: `${m[2]}-${дву(месяц)}-${дву(день)}` };
  if (p === 10 && месяц) return { рано: `${m[2]}-${дву(месяц)}-01`, поздно: `${m[2]}-${дву(месяц)}-${дву(дней(год, месяц))}` };
  if (p === 9) return { рано: `${m[2]}-01-01`, поздно: `${m[2]}-12-31` };
  if (p === 8) return { рано: `${m[2]}-01-01`, поздно: `${год + 9}-12-31` };
  return null;
}

/**
 * СОСТОЯНИЕ ВЫХОДА ПО ВСЕМ ЗАПИСЯМ РЕЕСТРА. `периоды` — список `{ рано, поздно }`.
 *
 * 🔴 Считается по ВСЕМ записям, а не по самой ранней. Причина замерена: у Deltarune самая ранняя
 * запись по «рано» — грубый `+2027-00-00`, а рядом стоит точная 2018-10-31. Судить по одной
 * записи значило бы объявить вышедшую игру невышедшей.
 *
 * Три исхода:
 *   · `вышел` — хотя бы у одной записи ПОЗДНЯЯ граница уже в прошлом. Объект точно вышел;
 *   · `не вышел` — у ВСЕХ записей РАННЯЯ граница в будущем. Объект точно не вышел;
 *   · `грубо` — ни то, ни другое: реестр знает только год или месяц, и ответа в нём нет.
 */
export function состояниеВыхода(периоды, сегодня) {
  const п = (периоды ?? []).filter(Boolean);
  if (!п.length) return { вид: 'нет даты' };
  const вышедшие = п.filter((x) => x.поздно <= сегодня);
  if (вышедшие.length) {
    return { вид: 'вышел', дата: вышедшие.map((x) => x.рано).sort()[0] };
  }
  if (п.every((x) => x.рано > сегодня)) {
    return { вид: 'не вышел', дата: п.map((x) => x.рано).sort()[0] };
  }
  return { вид: 'грубо', дата: п.map((x) => x.рано).sort()[0], поздно: п.map((x) => x.поздно).sort().at(-1) };
}

/**
 * ДАТЫ ВЫХОДА ОБЪЕКТА ПО ИДЕНТИФИКАТОРУ РЕЕСТРА.
 *
 * Три ответа, и путать их нельзя — ровно как у `заголовокИзРеестра` по соседству:
 *   · `{ есть: true, периоды }` — реестр ответил и даты знает;
 *   · `{ есть: false }` — реестр ответил, а `P577` у записи НЕТ. Честное «не знаю»;
 *   · `null` — реестра СПРОСИТЬ НЕ УДАЛОСЬ (нет идентификатора, записи нет, сеть легла).
 *
 * `спросить` передаётся вызывающим: так развилка проверяется юнитами БЕЗ сети, и функция
 * физически не может сходить в сеть мимо кэша прибора.
 */
export async function датыИзРеестра(qid, спросить) {
  if (!qid) return null;
  const ответ = await спросить('wikidata', { action: 'wbgetentities', ids: qid, props: 'claims' });
  const запись = ответ?.entities?.[qid];
  if (!запись || запись.missing !== undefined) return null;
  const claims = запись.claims?.[СВОЙСТВО_ДАТЫ];
  if (!Array.isArray(claims) || !claims.length) return { есть: false };
  const периоды = claims
    .map((c) => c.mainsnak?.datavalue?.value)
    .filter(Boolean)
    .map((v) => периодЗаписи(v.time, v.precision))
    .filter(Boolean);
  return периоды.length ? { есть: true, периоды } : { есть: false };
}

/*
 * ── 1б: ТЕКСТ ГОВОРИТ О ВЫШЕДШЕМ ОБЪЕКТЕ КАК О БУДУЩЕМ ─────────────────────────────────────
 *
 * Список УЗКИЙ намеренно, и каждая строка в нём — замер, а не догадка (числа в шапке):
 *   · «выход/премьера/релиз … назначен» — 8 срабатываний на наших партиях, 0 у владельца;
 *   · «пока не раскрыт/раскрывалось» — 2 срабатывания, и обе карточки — те самые, что владелец
 *     вернул за класс 1. У владельца — 0.
 * Голое «назначен» без слова о выходе в список НЕ взято по двум причинам сразу: «назначен на
 * должность» — сюжет, а на восьми живых срабатываниях второй образец не добавлял НИ ОДНОГО
 * нового текста и лишь удваивал отказ на одном и том же обороте.
 *
 * ⚠️ ГРАНИЦЫ СЛОВА — ТОЛЬКО `(?<![\p{L}])…(?![\p{L}])`. В JavaScript `\b` и `\w` определены
 * через ASCII, и флаг `u` этого не чинит: рядом с кириллицей образец молча не срабатывает
 * никогда. Урок оплачен в этом же приборе (`AUTHORITY_PATTERNS`, правка 2026-08-22).
 * Стережёт `node tools/verify-cyrillic-word-boundary.mjs`.
 */
export const БУДУЩИЙ_РЕГИСТР = [
  [/(?<![\p{L}])(?:выход|премьера|релиз|показ|выпуск|издание)[^.;!?]{0,40}?назначен[аоы]?(?![\p{L}])/giu, 'выход назначен'],
  [/(?<![\p{L}])пока\s+не\s+раскры[\p{L}]*/giu, 'пока не раскрыто'],
];

/**
 * Обороты, которыми описание говорит о выходе объекта как о БУДУЩЕМ.
 * Судит только русский текст: английская половина — отдельная работа с отдельным замером,
 * а молчать честнее, чем краснеть невпопад.
 */
export function будущийРегистр(text, lang = 'ru') {
  if (lang !== 'ru') return [];
  const t = String(text ?? '');
  const найдено = [];
  for (const [образец, имя] of БУДУЩИЙ_РЕГИСТР) {
    const m = t.match(образец);
    if (m) найдено.push({ признак: имя, оборот: m[0].trim().replace(/\s+/gu, ' ') });
  }
  return найдено;
}

/**
 * ПРИГОВОР КЛАССА 1 ПО ОДНОЙ КАРТОЧКЕ — обе половины в одном месте, чтобы порядок между ними
 * был проверяем юнитом, а не жил в голове читающего.
 *
 * `ответ` — то, что вернули `датыИзРеестра`. Возвращает `{ отказы, замечания, состояние }`.
 */
export function приговорКласса1(ответ, текстRu, сегодня) {
  const отказы = [];
  const замечания = [];

  if (ответ === null) {
    замечания.push('реестр не ответил — вышел ли объект, машина не знает');
    return { отказы, замечания, состояние: { вид: 'не спросили' } };
  }
  if (ответ.есть === false) {
    замечания.push(`даты выхода нет в реестре (${СВОЙСТВО_ДАТЫ}) — вышел ли объект, машина не знает`);
    return { отказы, замечания, состояние: { вид: 'нет даты' } };
  }

  const состояние = состояниеВыхода(ответ.периоды, сегодня);
  if (состояние.вид === 'не вышел') {
    отказы.push(`объект ещё не вышел — реестр: ${состояние.дата}, сегодня ${сегодня}`);
    return { отказы, замечания, состояние };
  }
  if (состояние.вид === 'грубо') {
    замечания.push(`реестр знает дату грубо (${состояние.дата}…${состояние.поздно}) — вышел ли объект, машина не знает`);
    return { отказы, замечания, состояние };
  }

  /* Объект вышел. Теперь — и только теперь — законен спрос за старый регистр текста. */
  for (const h of будущийРегистр(текстRu, 'ru')) {
    отказы.push(`объект вышел ${состояние.дата}, а описание пишет о нём как о будущем — «${h.оборот}»`);
  }
  return { отказы, замечания, состояние };
}
