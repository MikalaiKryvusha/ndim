// ПРАВИЛО Н9 — ПУНКТУАЦИЯ ПОЯСНЕНИЯ: приложение, обрамлённое запятыми
// ═══════════════════════════════════════════════════════════════════════════════════════════
//
// Заказ владельца 2026-08-22, класс 10: «"Грэйс и Джексон, молодые супруги," - ты неправильно
// пользуешься знаками препинания… Когда вводится пояснение, оно обрамляется тире с двух сторон».
//
// 🔴 НОРМА ДОПУСКАЕТ ОБА ЗНАКА, И ЭТО СКАЗАНО ЗДЕСЬ, А НЕ ТОЛЬКО В ДОКУМЕНТЕ.
// Розенталь §19 п. 1 предписывает ЗАПЯТЫЕ, он же §19 п. 10.3 — ТИРЕ «для выделения (с двух
// сторон) приложения, носящего характер пояснения»; академический справочник §61 говорит прямо:
// «наряду с запятыми, распространенные приложения могут выделяться тире». Владелец выбрал тире —
// для наших текстов это закон, но запятая ошибкой русского языка не является. Поэтому Н9 —
// правило ГОЛОСА на грамматической площадке, и оно ПРЕДЪЯВЛЯЕТ, никогда не отказывает.
//
// 🔴 ТОЧНОСТЬ НИЖЕ, ЧЕМ У Н1/Н2, И ЭТО СВОЙСТВО ЗАДАЧИ, А НЕ НЕБРЕЖНОСТЬ. Отличить приложение
// («Муж, капитан судна, звонит») от однородного ряда («очереди, расписание, всеобщая спешка»)
// можно только по смыслу. Замер руками:
// 12 настоящих из 29 предъявленных, 2 из 6 в срезе живого каталога — ~41 %.
// Число названо в отчёте прибора и в правиле Н9 документа, а не спрятано.

/** Слова, после которых оборот — не приложение. */
const ПРЕДЛОГИ_ЛЮБЫЕ = new Set(['в', 'во', 'на', 'за', 'под', 'над', 'при', 'по', 'о', 'об', 'из',
  'с', 'со', 'к', 'ко', 'от', 'до', 'для', 'без', 'через', 'между', 'среди', 'после', 'перед',
  'около', 'вокруг', 'у', 'про', 'ради', 'сквозь']);
const СЛУЖЕБНЫЕ = new Set(['и', 'а', 'но', 'или', 'что', 'чтобы', 'как', 'когда', 'если', 'хотя',
  'потому', 'так', 'то', 'же', 'ли', 'да', 'зато', 'однако', 'чем', 'пока', 'едва', 'будто',
  'словно', 'точно', 'ведь', 'ни', 'не', 'только', 'уже', 'ещё', 'даже', 'вот', 'здесь', 'там',
  'тут', 'теперь', 'например', 'впрочем', 'конечно', 'кстати', 'наконец', 'возможно', 'вероятно',
  'кажется', 'разумеется', 'напротив', 'скорее', 'правда', 'словом', 'наоборот', 'значит', 'итак',
  'кроме', 'помимо', 'вместо', 'включая', 'судя', 'причём', 'многократно', 'постепенно', 'начиная']);
const ОТНОСИТЕЛЬНЫЕ = /^котор|^чей$|^чья$|^чьё$|^где$|^куда$|^откуда$|^почему$|^зачем$|^кто$|^чем$/iu;

/** Служебные частицы в составе имён: «фон Сюдов», «ван Дамм» — часть имени, а не строчное слово. */
const ЧАСТИЦЫ_ИМЁН = new Set(['фон', 'ван', 'де', 'дель', 'да', 'ла', 'ле', 'аль', 'бен', 'ди', 'дю']);

const ОКОНЧАНИЯ_ПРИЛ = '(?:ая|яя|ое|ее|ый|ий|ой|ые|ие|ую|юю|ым|им|ом|ем|ей|ого|его|ому|ему|ых|их|ыми|ими)';
const ПРИЧАСТИЕ_ПОЛНОЕ = new RegExp(`(?:нн|т|вш|ш|ущ|ющ|ащ|ящ|ем|им|енн|анн|янн)${ОКОНЧАНИЯ_ПРИЛ}$`, 'iu');
const ДЕЕПРИЧАСТИЕ = /(?:[аяуюеи]я|ав|ив|ев|ыв|вши|ши)$/iu;
const ЛИЧНАЯ_ФОРМА = /(?:[аеиочяу]ет|[аеиочяу]ют|[аеиочяу]ит|[аеиочяу]ат|[аеиочяу]ят|[аеиоуяы]л|[аеиоуяы]ла|[аеиоуяы]ли|[аеиоуяы]ло|тся|ться|ется|ются|ится|ятся)$/iu;
const СЛОВО_RE = new RegExp(`[${БУКВА}\u0301-]+`, 'gu');

/** 🔴 Возвратный постфикс снимается ДО разбора: «оставшейся», «отбиваясь», «добивающийся». */
const безВозвратного = (с) => с.toLowerCase().replace(/(?:ся|сь)$/u, '');
const заглавное = (с) => /^[\p{Lu}]/u.test(с) || /^[A-Z0-9]/u.test(с) || ЧАСТИЦЫ_ИМЁН.has(с.toLowerCase());
const причастие = (с) => ПРИЧАСТИЕ_ПОЛНОЕ.test(безВозвратного(с));
const деепричастие = (с) => ДЕЕПРИЧАСТИЕ.test(безВозвратного(с)) && !причастие(с);
const личнаяФорма = (с) => ЛИЧНАЯ_ФОРМА.test(с) && !причастие(с) && !деепричастие(с);

/**
 * Находит обороты вида «X, ГРУППА,» и отделяет похожие на приложение от заведомо не приложений.
 *
 * @returns {{подозрения: Array<{правило: string, цитата: string, почему: string}>,
 *            оборотов: number, отсев: Record<string, number>}}
 */
export function пунктуацияПояснения(текст) {
  const подозрения = [];
  const отсев = {};
  let оборотов = 0;

  for (const предложение of текст.split(/(?<=[.!?])\s+/u)) {
    const re = new RegExp(`(?<!${БУКВА})(${БУКВА}[${БУКВА}-]*)\s*,\s*([^,;:—–()«»"]{2,60}?)\s*,`, 'gu');
    let m;
    while ((m = re.exec(предложение))) {
      const голова = m[1];
      const группа = m[2].trim();
      const слова = группа.match(СЛОВО_RE) ?? [];
      if (слова.length === 0 || слова.length > 4) continue;
      оборотов += 1;

      const первое = слова[0].toLowerCase();
      const хвост = предложение.slice(m.index + m[0].length);
      const словаХвоста = хвост.match(СЛОВО_RE) ?? [];

      let причина = null;
      if (ПРЕДЛОГИ_ЛЮБЫЕ.has(первое)) причина = 'начинается предлогом — обстоятельство';
      else if (СЛУЖЕБНЫЕ.has(первое)) причина = 'начинается служебным словом или наречием';
      else if (ОТНОСИТЕЛЬНЫЕ.test(первое)) причина = 'придаточное';
      else if (причастие(слова[0])) причина = 'причастный оборот — определение, а не приложение';
      else if (деепричастие(слова[0])) причина = 'деепричастный оборот';
      else if (слова.some(личнаяФорма)) причина = 'внутри личная форма глагола — оборот со сказуемым';
      else if (личнаяФорма(голова)) причина = 'голова — глагол; приложения к глаголу не бывает';
      else if (слова.every(заглавное)) причина = 'группа целиком из имён собственных — перечисление';
      else if (слова.some((с) => ['и', 'или', 'да', 'ни'].includes(с.toLowerCase()))) причина = 'сочинительный союз внутри — перечисление';
      // 🔑 ГЛАВНЫЙ РАЗЛИЧИТЕЛЬ, найденный замером: у приложения сказуемое стоит ПОСЛЕ оборота
      // («…молодые супруги, УЕЗЖАЮТ»), у перечисления его нет или оно стоит до
      // («Играют Колин Ферт, Ив Хьюсон, Колман Доминго.»). Снимает 23 оборота из 276.
      else if (!словаХвоста.some(личнаяФорма)) причина = 'после оборота нет сказуемого — перечисление, а не вставка';

      if (причина) { отсев[причина] = (отсев[причина] ?? 0) + 1; continue; }

      подозрения.push({
        правило: 'Н9',
        цитата: `${голова}, ${группа},`,
        почему: 'похоже на пояснение при подлежащем — владелец требует тире с двух сторон;'
          + ' норма допускает и запятые, поэтому решает человек',
      });
    }
  }
  return { подозрения, оборотов, отсев };
}
