/**
 * Словоформы единственного числа по типу склонения.
 * Множественное число сюда НЕ входит намеренно — см. «границы» в шапке.
 * Одна форма может нести несколько падежей (`режиссёра` — родительный и винительный); поэтому
 * значение всегда МНОЖЕСТВО, а не один падеж.
 */
function формыЕдинственного(лемма, склонение) {
  const без_ь = лемма.replace(/ь$/u, '');
  switch (склонение) {
    case 'м-твёрдый':
      return { [лемма]: ['им'], [лемма + 'а']: ['род', 'вин'], [лемма + 'у']: ['дат'], [лемма + 'ом']: ['твор'], [лемма + 'е']: ['предл'] };
    case 'м-мягкий':
      return { [лемма]: ['им'], [без_ь + 'я']: ['род', 'вин'], [без_ь + 'ю']: ['дат'], [без_ь + 'ем']: ['твор'], [без_ь + 'е']: ['предл'] };
    case 'м-на-й': {
      const о = лемма.slice(0, -1);
      return { [лемма]: ['им'], [о + 'я']: ['род', 'вин'], [о + 'ю']: ['дат'], [о + 'ем']: ['твор'], [о + 'е']: ['предл'] };
    }
    case 'м-на-ий': {
      const о = лемма.slice(0, -1);
      // предложный на «-ии», а не на «-ие»: о сценарии, в сценарии
      return { [лемма]: ['им'], [о + 'я']: ['род', 'вин'], [о + 'ю']: ['дат'], [о + 'ем']: ['твор'], [о + 'и']: ['предл'] };
    }
    case 'ж-на-а': {
      const о = лемма.slice(0, -1);
      // после шипящих, «г/к/х» и мягкой основы родительный на «и», а не на «ы»
      const род = /[жшчщгкхий]$/u.test(о) ? о + 'и' : о + 'ы';
      const предл = /и$/u.test(о) ? о + 'и' : о + 'е';
      // творительный на «-ей» после мягкой основы и шипящих: студиЕЙ, писательницЕЙ
      const твор = /[жшчщцийь]$/u.test(о) ? о + 'ей' : о + 'ой';
      return { [лемма]: ['им'], [род]: ['род'], [предл]: ['дат', 'предл'], [о + 'у']: ['вин'], [твор]: ['твор'] };
    }
    case 'ж-на-ь':
      return { [лемма]: ['им', 'вин'], [без_ь + 'и']: ['род', 'дат', 'предл'], [без_ь + 'ью']: ['твор'] };
    default:
      throw new Error(`неизвестный тип склонения: ${склонение}`);
  }
}

/** Форма существительного → { род, падежи, лемма, роль }. Собирается один раз. */
export const ФОРМЫ = (() => {
  const карта = new Map();
  for (const запись of ЛЕКСИКОН) {
    for (const [форма, падежи] of Object.entries(формыЕдинственного(запись.лемма, запись.склонение))) {
      const ключ = форма.toLowerCase();
      const прежнее = карта.get(ключ);
      // Коллизия форм разных лемм («критика» — и родительный от «критик», и другое слово):
      // складываем чтения, а не затираем. Больше чтений — больше поводов промолчать.
      if (прежнее) {
        карта.set(ключ, {
          род: прежнее.род === запись.род ? прежнее.род : 'спорный',
          падежи: [...new Set([...прежнее.падежи, ...падежи])],
          леммы: [...new Set([...прежнее.леммы, запись.лемма])],
          роль: прежнее.роль || Boolean(запись.роль),
        });
      } else {
        карта.set(ключ, { род: запись.род, падежи, леммы: [запись.лемма], роль: Boolean(запись.роль) });
      }
    }
  }
  return карта;
})();

