/** Пара «слово + слово» с позицией: нужен предшествующий токен для ловушки 3. */
const ТОКЕНЫ = new RegExp(`(?<!${БУКВА})[${БУКВА}\\u0301-]+(?!${БУКВА})`, 'giu');

/**
 * Имя правила по характеру расхождения. Разведка §0: у возврата владельца нарушены ОБА яруса,
 * и назвать надо тот, который он назвал, — род.
 *   падеж сходится, род нет  → Н1 (то самое «тунисской режиссёром»)
 *   род сходится, падеж нет  → Н2
 *   не сходится ничего       → Н1+Н2
 */
function имяПравила(чтения, родСущ, падежиСущ) {
  // 🔑 ЯКОРЬ — ПАДЕЖ СУЩЕСТВИТЕЛЬНОГО, и порядок вопросов здесь важнее их формулировки.
  // Падеж существительного в закрытом лексиконе известен точно, а род прилагательного —
  // только набором чтений. Поэтому сначала спрашиваем «падеж-то сошёлся?»: если да, значит
  // писавший поставил нужный падеж НЕ В ТОМ РОДЕ — и это ровно то, что назвал владелец
  // («Режиссёр - Он Мой, мужской род»), а не абстрактное «форма не согласована».
  if (чтения.some((ч) => падежиСущ.includes(ч.split(':')[1]))) return 'Н1';
  if (чтения.some((ч) => ч.split(':')[0] === родСущ)) return 'Н2';
  return 'Н1+Н2';
}

/**
 * Разбирает текст и возвращает подозрения и покрытие.
 *
 * @returns {{
 *   подозрения: Array<{правило: string, цитата: string, определение: string,
 *                      существительное: string, чтения: string[], требуется: string, почему: string}>,
 *   снятоН3: Array<{цитата: string}>,
 *   снятоОмонимией: Array<{цитата: string, вид: string}>,
 *   пар: number, известных: number, неизвестных: number, множественных: number
 * }}
 */
export function проверить(текст) {
  const подозрения = [];
  const снятоН3 = [];
  const снятоОмонимией = [];
  let пар = 0, известных = 0, неизвестных = 0, множественных = 0;

  const токены = [...текст.matchAll(ТОКЕНЫ)].map((m) => ({ слово: m[0], индекс: m.index }));

  for (let i = 1; i < токены.length; i += 1) {
    const левое = токены[i - 1];
    const правое = токены[i];

    // 🔴 ПАРА НЕ ПЕРЕШАГИВАЕТ ЗНАК ПРЕПИНАНИЯ. Между определением и его существительным стоит
    // только пробел. Точка, запятая, тире, скобка — это уже другая синтаксическая группа, и
    // соседство через них не значит ничего: «…не столичной, а обыкновенной. Картина выпущена…»
    // давало подозрение на паре «обыкновенной Картина», которой в тексте нет.
    // Найдено прогоном прибора по корпусам N и K: четыре ложных из семи были именно этим.
    const промежуток = текст.slice(левое.индекс + левое.слово.length, правое.индекс);
    // Неразрывный пробел записан ЯВНЫМ escape, а не символом: в исходнике он невидим,
    // и подстановка мутации о него уже спотыкалась — «не нашлось» вместо честного падения.
    if (!/^[\s\u00A0]+$/u.test(промежуток)) continue;

    const разбор = разборПрилагательного(левое.слово);
    if (!разбор) continue;

    пар += 1;
    const сущ = ФОРМЫ.get(правое.слово.toLowerCase());
    if (!сущ) { неизвестных += 1; continue; }
    известных += 1;

    // Множественное число не судится (граница в шапке), но считается вслух.
    if (разбор.множественное) { множественных += 1; continue; }

    // Ловушка 3: предложные формы прилагательного неотличимы от творительных форм
    // существительного («окном» ≡ «новом»). Два условия сразу, и оба обязательны:
    //   1. пара стоит после предлога, управляющего предложным падежом;
    //   2. существительное САМО может быть предложным.
    // Без второго условия «…и в этом игра стоит ближе…» даёт подозрение на «этом игра», где
    // «в этом» — законченная предложная группа, а «игра» — подлежащее следующего оборота.
    if (['ом', 'ем'].includes(разбор.окончание)) {
      const предыдущий = токены[i - 2]?.слово.toLowerCase();
      if (!ПРЕДЛОГИ_ПРЕДЛОЖНОГО.has(предыдущий)) continue;
      if (!сущ.падежи.includes('предл')) continue;
    }

    if (сущ.род === 'спорный') continue;

    const цитата = `${левое.слово} ${правое.слово}`;

    // ОМОНИМИЯ СРАВНИТЕЛЬНОЙ СТЕПЕНИ. Форма на «-ее» — это и средний род прилагательного
    // («позднее время»), и сравнительная степень («позднее игра вышла на Xbox»), а сравнительная
    // НЕИЗМЕНЯЕМА и не согласуется ни с чем. Различить их здесь нечем, поэтому судим такую форму
    // только при существительном СРЕДНЕГО рода, где сравнительное чтение отпадает.
    // Найдено прогоном по корпусу N: «позднее игра» было последним ложным срабатыванием.
    if (разбор.окончание === 'ее' && сущ.род !== 'с') { снятоОмонимией.push({ цитата, вид: 'сравнительная степень' }); continue; }

    if (причастиеУправляет(разбор, сущ.падежи)) { снятоН3.push({ цитата }); continue; }

    const согласовано = разбор.чтения.some((ч) => {
      const [род, падеж] = ч.split(':');
      return род === сущ.род && сущ.падежи.includes(падеж);
    });
    if (согласовано) continue;

    подозрения.push({
      правило: имяПравила(разбор.чтения, сущ.род, сущ.падежи),
      цитата,
      определение: левое.слово,
      существительное: правое.слово,
      чтения: разбор.чтения,
      требуется: `${сущ.род}:${сущ.падежи.join('|')}`,
      почему: `«${левое.слово}» читается как ${разбор.чтения.join(', ')}; «${правое.слово}» —`
        + ` ${сущ.род === 'м' ? 'мужской' : сущ.род === 'ж' ? 'женский' : 'средний'} род,`
        + ` ${сущ.падежи.join(' или ')} падеж`,
    });
  }

  return { подозрения, снятоН3, снятоОмонимией, пар, известных, неизвестных, множественных };
}

