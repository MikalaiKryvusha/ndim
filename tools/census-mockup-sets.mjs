import { readdirSync, readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

/** Корень дерева, из которого запущен прибор, — от собственного файла (класс `EXP-0269`). */
const КОРЕНЬ = new URL('../', import.meta.url);

/**
 * 🔴 ХРАПОВИК: наборы, которые съёмщик сегодня не берёт. Список — ДОЛГ, а не норма.
 *
 * Заведён 2026-08-30 (`bugs/NEW_shooter_sees_13_of_23_mockup_sets`). Все десять написаны до того,
 * как `#stage[data-w]` стал домом стиля.
 *
 * Правила обращения:
 *   · починил набор — УБЕРИ его отсюда тем же коммитом (страж иначе покраснеет и скажет об этом);
 *   · добавляешь набор — он обязан быть снимаемым; дописывать сюда новые имена НЕЛЬЗЯ, кроме
 *     случая, когда это осознанное решение с разбором в коммите.
 */
const ХРАПОВИК = [
  'catalog-door-mockups.html',
  'desktop-layout-mockups.html',
  'guest-flow-mockups.html',
  'landing-mockups.html',
  'light-theme-mockups.html',
  'login-mockups.html',
  'menu-mockups.html',
  'onboarding-demo-mockups.html',
  'space-mockups.html',
  'widget-layout-mockups.html',
];

/**
 * Крючки, которые дёргает `tools/shoot-mockups.mjs`. Кавычки в образцах обязательны: без них
 * `id=width` совпал бы и с `id=width-mid`, и перепись врала бы в удобную сторону.
 */
const КРЮЧКИ = {
  варианты: /<button[^>]*\bdata-v\s*=/i,
  stage: /\bid=(["'])stage\1/i,
  width: /\bid=(["'])width\1/i,
  theme: /\bid=(["'])theme\1/i,
};
const КРЮЧОК_MID = /\bid=(["'])width-mid\1/i;

/** Набор дома стиля — тот, у которого есть кнопки вариантов. Прочие html в `design/` не наборы. */
export function этоНабор(html) {
  return КРЮЧКИ.варианты.test(html);
}

/** Чего набору не хватает, чтобы съёмщик его взял. Пустой список — снимаем. */
export function чегоНеХватает(html) {
  return Object.entries(КРЮЧКИ)
    .filter(([, образец]) => !образец.test(html))
    .map(([имя]) => имя);
}

/**
 * Перепись каталога макетов. Чистая функция от ПУТИ — поэтому её можно позвать на поддельном
 * дереве, что юниты и делают.
 */
export function перепись(каталогМакетов) {
  const файлы = readdirSync(каталогМакетов)
    .filter((f) => f.endsWith('.html'))
    .sort();

  const наборы = [];
  for (const файл of файлы) {
    const html = readFileSync(resolve(каталогМакетов, файл), 'utf8');
    if (!этоНабор(html)) continue;
    const нехватка = чегоНеХватает(html);
    наборы.push({ файл, снимаем: нехватка.length === 0, нехватка, mid: КРЮЧОК_MID.test(html) });
  }

  const долг = наборы.filter((н) => !н.снимаем);
  return {
    всего: наборы.length,
    снимаемых: наборы.length - долг.length,
    сСреднейШириной: наборы.filter((н) => н.снимаем && н.mid).length,
    долг,
    наборы,
  };
}

/** Приговор храповика: долг вырос — красный; долг уменьшился — тоже красный, но с другим лечением. */
export function судХраповика(долгИмена, храповик = ХРАПОВИК) {
  const сейчас = new Set(долгИмена);
  const было = new Set(храповик);
  const появились = [...сейчас].filter((и) => !было.has(и)).sort();
  const ушли = [...было].filter((и) => !сейчас.has(и)).sort();
  return { появились, ушли, чисто: появились.length === 0 && ушли.length === 0 };
}

function печать(итог) {
  console.log(
    `Наборы макетов дома стиля: ${итог.всего} · снимаемых съёмщиком: ${итог.снимаемых} · ` +
      `не снимаемых: ${итог.долг.length} · со средней шириной 1024: ${итог.сСреднейШириной}`,
  );
  if (итог.долг.length) {
    console.log('\nНе снимаются (чего не хватает):');
    for (const н of итог.долг) console.log(`  · ${н.файл.padEnd(32)} нет: ${н.нехватка.join(', ')}`);
  }

  const { появились, ушли, чисто } = судХраповика(итог.долг.map((н) => н.файл));
  if (чисто) {
    console.log(`\n✅ Долг совпал с храповиком (${ХРАПОВИК.length}). Новых неснимаемых наборов нет.`);
    return 0;
  }
  console.log('');
  if (появились.length) {
    console.log('🔴 ДОЛГ ВЫРОС — эти наборы съёмщик не возьмёт, а в храповике их нет:');
    for (const и of появились) console.log(`     ${и}`);
    console.log('   Лечение: привести набор к дому стиля (#stage[data-w] · #width · #theme),');
    console.log('   а не дописывать его имя в ХРАПОВИК — храповик существует, чтобы долг не рос.');
  }
  if (ушли.length) {
    console.log('🔴 ХРАПОВИК ПРОТУХ — эти имена в нём есть, а в долге их больше нет:');
    for (const и of ушли) console.log(`     ${и}`);
    console.log('   Лечение: убрать их из ХРАПОВИК тем же коммитом, которым набор починен или');
    console.log('   переименован. Иначе список внутри стража сам станет протухшим числом.');
  }
  return 1;
}

/* ── Самотест: доказывает, что перепись СЧИТАЕТ, а не повторяет заученное ─────────────── */

export function selftest() {
  let провалов = 0;
  const скажи = (ок, что, деталь) => {
    if (!ок) провалов += 1;
    console.log(`${ок ? '✅' : '🔴'} ${что}${деталь ? ` · ${деталь}` : ''}`);
  };

  const целый = `<div class="picker"><button data-v="1">V1</button><button id="width-mid">1024</button>
    <button id="width">390</button><button id="theme">тема</button></div><div id="stage" data-w="1440"></div>`;
  скажи(этоНабор(целый) && чегоНеХватает(целый).length === 0, 'полный набор признан снимаемым');

  const безStage = целый.replace('<div id="stage" data-w="1440"></div>', '');
  скажи(
    чегоНеХватает(безStage).join() === 'stage',
    'набор без #stage назван неснимаемым, и назван ИМЕННО из-за stage',
    `не хватает: ${чегоНеХватает(безStage).join(', ')}`,
  );

  const безТемы = целый.replace('<button id="theme">тема</button>', '');
  скажи(
    чегоНеХватает(безТемы).join() === 'theme',
    'признак ПО СУЩЕСТВУ: набор с #stage, но без #theme, тоже неснимаем',
    'проверка «есть ли #stage» пропустила бы его',
  );

  скажи(!этоНабор('<html><body>просто страница</body></html>'), 'страница без кнопок вариантов набором не считается');

  // Кавычки в образце: `id="width-mid"` не должен сойти за `id="width"`.
  const толькоMid = `<div class="picker"><button data-v="1">V</button><button id="width-mid">1024</button>
    <button id="theme">т</button></div><div id="stage" data-w="390"></div>`;
  скажи(
    чегоНеХватает(толькоMid).join() === 'width',
    'id="width-mid" НЕ засчитывается за id="width"',
    `не хватает: ${чегоНеХватает(толькоMid).join(', ')}`,
  );

  скажи(судХраповика(['a'], ['a']).чисто, 'храповик: долг совпал — чисто');
  скажи(
    судХраповика(['a', 'b'], ['a']).появились.join() === 'b',
    'храповик КРАСНЕЕТ на выросшем долге и называет новичка',
  );
  скажи(
    судХраповика(['a'], ['a', 'b']).ушли.join() === 'b',
    'храповик КРАСНЕЕТ на уменьшившемся долге — иначе список сам протухнет',
  );

  console.log(провалов ? `\n🔴 САМОТЕСТ КРАСНЫЙ: провалов ${провалов}` : '\n✅ САМОТЕСТ ЧИСТ');
  return провалов ? 1 : 0;
}

/* ── Точка входа. Работа только под ЗАПУСКОМ, не под импортом (класс EXP-0188). ────────── */

const ЗАПУЩЕН_НАПРЯМУЮ = Boolean(process.argv[1]) && import.meta.url === pathToFileURL(process.argv[1]).href;

if (ЗАПУЩЕН_НАПРЯМУЮ) {
  process.exitCode = process.argv.includes('--selftest')
    ? selftest()
    : печать(перепись(fileURLToPath(new URL('design', КОРЕНЬ))));
}
