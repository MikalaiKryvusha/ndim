const RU_LITERAL = /(['"`])([^'"`\n]*[А-яЁё][^'"`\n]*)\1/gu;

/**
 * ДВЕРЬ — блок `signedOut: { … }` и ключи, начинающиеся с `signin`. Зона ищется ПО ЯКОРЮ, а не по
 * номерам строк: номера разъезжаются молча, якорь — громко (самотест ниже это и проверяет).
 */
export function doorLines(src) {
	const lines = src.split('\n');
	const door = new Set();
	for (let i = 0; i < lines.length; i++) {
		if (!/^\s*(?:signedOut\s*:\s*\{|signin[A-Za-z]*\s*:\s*\{)/u.test(lines[i])) continue;
		let depth = 0;
		for (let j = i; j < lines.length; j++) {
			depth += (lines[j].match(/\{/gu) || []).length;
			depth -= (lines[j].match(/\}/gu) || []).length;
			door.add(j + 1);
			if (depth <= 0 && j > i) break;
		}
	}
	return door;
}

function walk(dir, out = []) {
	let entries;
	try { entries = readdirSync(dir); } catch { return out; }
	for (const e of entries) {
		const p = join(dir, e);
		if (statSync(p).isDirectory()) walk(p, out);
		else if (/\.(ts|js|svelte)$/u.test(e) && !SKIP.test(e) && !OUT_OF_ZONE.test(p)) out.push(p);
	}
	return out;
}

/** Судит один текст. Возвращает улики ПОИМЁННО — сводного числа намеренно нет. */
export function judge(text) {
	const hits = [];
	for (const rule of RULES) {
		for (const m of text.matchAll(rule.re)) hits.push({ rule: rule.id, why: rule.why, found: m[0] });
	}
	return hits;
}

/**
 * Выбить из HTML то, что человек НЕ читает: стили, скрипты, комментарии. Номера строк обязаны
 * пережить операцию — иначе красный покажет не на ту строку, и следующий будет искать вслепую.
 * Поэтому вырезанное заменяется тем же числом переводов строки, а не пустотой.
 */
export function stripInvisible(src) {
	const пусто = (m) => '\n'.repeat((m.match(/\n/gu) || []).length);
	return src
		.replace(/<style\b[\s\S]*?<\/style>/giu, пусто)
		.replace(/<script\b[\s\S]*?<\/script>/giu, пусто)
		.replace(/<!--[\s\S]*?-->/gu, пусто);
}

/**
 * Разложить макет на строки видимого текста, пометив каждую: она внутри симулированной
 * ПОВЕРХНОСТИ продукта или в пояснении агента. Глубина считается по `<div>`: макеты мастерской
 * написаны руками, один блок — своя строка, и счётчик глубины здесь честнее, чем регулярка
 * «от класса до закрывающего тега».
 */
export function mockupLines(src) {
	const out = [];
	let depth = 0;
	let surfaceAt = null;
	stripInvisible(src).split('\n').forEach((line, i) => {
		const opensSurface = /<div[^>]*class="[^"]*"/u.test(line)
			&& MOCKUP_SURFACE.test((line.match(/<div[^>]*class="([^"]*)"/u) ?? ['', ''])[1]);
		if (opensSurface && surfaceAt === null) surfaceAt = depth;
		const текст = line.replace(/<[^>]*>/gu, ' ').replace(/&[a-z]+;|&#\d+;/giu, ' ').replace(/\s+/gu, ' ').trim();
		if (текст) out.push({ line: i + 1, text: текст, onDoor: surfaceAt !== null });
		depth += (line.match(/<div\b/gu) || []).length;
		depth -= (line.match(/<\/div>/gu) || []).length;
		if (surfaceAt !== null && depth <= surfaceAt) surfaceAt = null;
	});
	return out;
}

/** Обойти макеты второй зоны и судить их тем же оценщиком, что и продукт. */
function scanMockups() {
	const found = [];
	for (const zone of MOCKUP_ZONES) {
		const files = [];
		walkHtml(join(ROOT, zone), files);
		for (const f of files) {
			const src = readFileSync(f, 'utf8');
			for (const { line, text, onDoor } of mockupLines(src)) {
				for (const hit of judge(text)) {
					found.push({
						file: relative(ROOT, f).split(String.fromCharCode(92)).join('/'),
						line, onDoor, str: text, ...hit,
					});
				}
			}
		}
	}
	return found;
}

function walkHtml(dir, out = []) {
	let entries;
	try { entries = readdirSync(dir); } catch { return out; }
	for (const e of entries) {
		const p = join(dir, e);
		if (statSync(p).isDirectory()) walkHtml(p, out);
		else if (/\.html$/u.test(e)) out.push(p);
	}
	return out;
}

function scan() {
	const found = [];
	for (const f of ZONES.flatMap((z) => walk(join(ROOT, z)))) {
		const src = readFileSync(f, 'utf8');
		const door = doorLines(src);
		src.split('\n').forEach((line, i) => {
			const t = line.trim();
			if (t.startsWith('*') || t.startsWith('//') || t.startsWith('/*')) return;
			for (const m of line.matchAll(RU_LITERAL)) {
				const str = m[2];
				if (SCALE_1X.test(str)) return;
				for (const hit of judge(str)) {
					found.push({
						file: relative(ROOT, f).split(String.fromCharCode(92)).join('/'),
						line: i + 1,
						onDoor: door.has(i + 1),
						str,
						...hit,
					});
				}
			}
		});
	}
	return found;
}

