/**
 * РАЗВЕДКА КУЛЬТОВОЙ КЛАССИКИ — что знает весь мир, а каталога NDim у нас нет.
 *
 * Заказ владельца 2026-08-23, дословно: «*а есть популярные культовые объекты культуры, а не
 * только какое-то современное? не обязательно дрочить 2026 год, можно за все времена разведку
 * сделать и найти то, чего в NDim ещё нет, но оно суппер культовое*».
 *
 * ═══ ЧЕМ ЭТОТ ПРИБОР ОТЛИЧАЕТСЯ ОТ СОСЕДА ═══
 *
 * `scout-wikidata-candidates.mjs` ищет НОВИНКИ и заперт на год: у него `FILTER(YEAR(?d) = 2026)`,
 * и «Крёстный отец» через него не пройдёт никогда. Здесь года нет вовсе, а отбор идёт по одной
 * мере — сколько языковых разделов Википедии написали об объекте. Классика тем и отличается от
 * новинки, что её успели описать на десятках языков.
 *
 * 🔑 ПОЧЕМУ ЭТО ЧЕСТНАЯ МЕРА ИМЕННО ДЛЯ КЛАССИКИ — и нечестная для новинки. Википедия догоняет
 * медленно: свежий фильм может собирать залы и иметь пять разделов. У объекта сорокалетней
 * давности этот довод не работает — мир успел написать о нём всё, что хотел. Поэтому у соседа
 * порог стоит низкий (8) и служит грубым ситом, а здесь он высокий и служит определением
 * культовости.
 *
 * ⛔ ЧЕГО ПРИБОР НЕ ДЕЛАЕТ: не пишет в каталог ни одной записи. Инвариант мастерской (В3 = А):
 * измерение рождается только нажатием владельца.
 *
 * ═══ ДЕДУПЛИКАЦИЯ — ЧИСЛОМ, А НЕ НА ГЛАЗ ═══
 *
 * Название нормализуется ТЕМ ЖЕ нормализатором, что у поиска в продукте (`model/feed.ts` →
 * `normalizeForSearch`), и сверяется с ОБЕИМИ половинами названий всех измерений каталога.
 * Вторая копия правил нормализации разъехалась бы с первой на первом же дефисе.
 *
 * ⚠️ ЧЕСТНАЯ ГРАНИЦА ДЕДУПЛИКАЦИИ, названная вслух: сверка идёт ПО НАЗВАНИЮ. Объект, который у
 * нас записан под другим прокатным именем, прибор объявит отсутствующим. Это недобор точности, а
 * не выдумка: лишняя строка в списке стоит одной проверки глазами, пропущенная классика стоит
 * дороже.
 *
 * Запуск:
 *   node tools/scout-cult-classics.mjs                          # все виды, пороги по умолчанию
 *   node tools/scout-cult-classics.mjs --kind Фильм --min 100   # один вид и свой порог
 *   node tools/scout-cult-classics.mjs --limit 600 --out <путь>
 */
import { writeFileSync } from 'node:fs';
import { readFileSync } from 'node:fs';

import { normalizeForSearch } from '../src/lib/model/feed.ts';

const arg = (имя, поумолчанию = null) => {
	const i = process.argv.indexOf(имя);
	return i >= 0 && process.argv[i + 1] && !process.argv[i + 1].startsWith('--') ? process.argv[i + 1] : поумолчанию;
};

/**
 * Виды и ПОРОГИ КУЛЬТОВОСТИ. Пороги разные, и это не вкус: у видов разная плотность внимания
 * Википедии. О фильмах пишут на всех языках, о видеоиграх — заметно реже, о романах реже ещё.
 * Один порог на всех дал бы список из одних фильмов.
 */
const ВИДЫ = [
	{ qid: 'Q11424', ru: 'Фильм', en: 'Film', порог: 70 },
	{ qid: 'Q5398426', ru: 'Телесериал', en: 'TV Series', порог: 45 },
	{ qid: 'Q7889', ru: 'Видеоигра', en: 'Video game', порог: 35 },
	{ qid: 'Q8261', ru: 'Роман', en: 'Novel', порог: 45 },
	{ qid: 'Q7725634', ru: 'Книга', en: 'Book', порог: 45 },
];

const ENDPOINT = 'https://query.wikidata.org/sparql';
const UA = 'NDimSpace-catalog-scout/1.0 (https://ndimspace.app; agent of NDim Space 2.0)';
const ПАУЗА = Number(arg('--pause', '2000'));
const ПОПЫТОК = Number(arg('--retries', '3'));
const ПРЕДЕЛ = Number(arg('--limit', '400'));
const подождать = (мс) => new Promise((r) => { setTimeout(r, мс); });

async function спросить(query, чтоЭто) {
	let последняя = 'неизвестно';
	for (let попытка = 1; попытка <= ПОПЫТОК; попытка += 1) {
		await подождать(ПАУЗА * попытка);
		try {
			const ответ = await fetch(`${ENDPOINT}?format=json&query=${encodeURIComponent(query)}`, {
				headers: { 'User-Agent': UA, Accept: 'application/sparql-results+json' },
			});
			if (ответ.ok) return (await ответ.json()).results.bindings;
			последняя = `HTTP ${ответ.status}`;
		} catch (e) {
			последняя = `обрыв ${e?.cause?.code ?? e?.message ?? 'неизвестно'}`;
		}
		if (попытка < ПОПЫТОК) console.error(`  ↻ ${чтоЭто}: ${последняя} — попытка ${попытка + 1} из ${ПОПЫТОК}`);
	}
	console.error(`  ⚠️ ${чтоЭто}: ${последняя} — вид ПРОПУЩЕН, и это названо, а не скрыто`);
	return null;
}

/**
 * СУЖЕНИЕ без меток и без сортировки. `ORDER BY` по большому набору упирается в потолок сервиса;
 * порядок делается кодом после того, как строки приехали, — там он бесплатен.
 */
const сужение = (qid, порог) => `
SELECT ?item ?sitelinks WHERE {
  ?item wdt:P31 wd:${qid} ; wikibase:sitelinks ?sitelinks .
  FILTER(?sitelinks >= ${порог})
}
LIMIT ${ПРЕДЕЛ}`;

/*
 * 🔴 ДОБОР МЕТОК ИДЁТ НЕ ЧЕРЕЗ SPARQL, И ЭТО ОПЛАЧЕНО ПЕРВЫМ ЖЕ ПРОГОНОМ (2026-08-23).
 *
 * Первая редакция добирала метки и год одним запросом `VALUES … OPTIONAL{label} GROUP BY`.
 * На фильмах и сериалах он работал, а на ВИДЕОИГРАХ возвращал ПУСТЫЕ метки: у игры десятки дат
 * выпуска (по платформе и региону), перекрёстное произведение внутри группы разрастается, и
 * необязательное соединение с меткой отваливается молча. Тот же QID отдельным запросом метку
 * отдавал исправно.
 *
 * 🔑 Цена молчания была не косметической: сверка с каталогом идёт ПО НАЗВАНИЮ, а у записи без
 * названия сверять нечего — все игры разом объявились отсутствующими, включая те, что в каталоге
 * стоят годами. Пустое поле прошло бы как «новинка», и разведка соврала бы числом.
 *
 * Лечение простое (Оккам): метки и год берутся `wbgetentities` — прямым чтением сущностей по
 * пятьдесят штук. Ответ там детерминирован и от числа дат не зависит.
 */
async function метки(qids) {
	const выход = new Map();
	for (let i = 0; i < qids.length; i += 50) {
		const порция = qids.slice(i, i + 50);
		await подождать(500);
		const url =
			'https://www.wikidata.org/w/api.php?action=wbgetentities&format=json&props=labels|claims' +
			`&languages=ru|en|mul&ids=${порция.join('|')}`;
		let ответ;
		try {
			const res = await fetch(url, { headers: { 'User-Agent': UA } });
			ответ = await res.json();
		} catch (e) {
			console.error(`  ⚠️ метки ${i + 1}…${i + порция.length}: ${e?.message ?? 'обрыв'} — порция пропущена`);
			continue;
		}
		for (const [qid, e] of Object.entries(ответ.entities ?? {})) {
			const даты = [];
			for (const c of e.claims?.P577 ?? []) {
				const v = c.mainsnak?.datavalue?.value;
				if (v?.time) даты.push(v.time.slice(1, 11));
			}
			/*
			 * 🔴 ЗАПАСНАЯ МЕТКА `mul` — не мелочь, а условие видимости половины видеоигр.
			 * Wikidata переносит названия, ОДИНАКОВЫЕ во всех языках, в общую метку `mul`, и
			 * тогда языковых меток у записи нет вовсе: у Super Mario 64 нет ни ru, ни en.
			 * Без запасной метки такая запись приезжает безымянной, сверять её с каталогом
			 * нечем, и разведка врёт числом. Тот же добор уже стоит в годовой разведке.
			 */
			const общая = e.labels?.mul?.value ?? '';
			выход.set(qid, {
				ru: e.labels?.ru?.value ?? общая,
				en: e.labels?.en?.value ?? общая,
				год: даты.sort()[0]?.slice(0, 4) ?? '',
			});
		}
	}
	return выход;
}

// ── Каталог: что у нас уже есть ─────────────────────────────────────────────────────────────
const снимок = JSON.parse(readFileSync('src/lib/content/dims-build.json', 'utf8'));
const измерения = Array.isArray(снимок) ? снимок : Object.values(снимок);
const наши = new Set();
for (const d of измерения) {
	for (const имя of [d.title?.ru, d.title?.en]) {
		const н = имя ? normalizeForSearch(имя) : '';
		if (н) наши.add(н);
	}
}
console.log(`наш каталог: ${измерения.length} измерений · нормализованных названий ${наши.size}`);

const выбранный = arg('--kind');
const виды = выбранный ? ВИДЫ.filter((k) => k.ru === выбранный) : ВИДЫ;
if (!виды.length) {
	console.error(`неизвестный вид «${выбранный}»; есть: ${ВИДЫ.map((k) => k.ru).join(', ')}`);
	process.exit(2);
}
const порогФлагом = arg('--min') ? Number(arg('--min')) : null;

const найдено = [];
const наши_же = [];
/** Записи, у которых имя не добылось: сверять их с каталогом НЕЧЕМ, и они считаются отдельно. */
const безымянные = [];
for (const вид of виды) {
	const порог = порогФлагом ?? вид.порог;
	console.log(`\n▶ ${вид.ru}: языковых разделов ≥ ${порог}, предел ${ПРЕДЕЛ}`);
	const узкие = await спросить(сужение(вид.qid, порог), `сужение ${вид.ru}`);
	if (!узкие) continue;
	const qids = [...new Set(узкие.map((r) => String(r.item.value).split('/').pop()))];
	const вес = new Map(узкие.map((r) => [String(r.item.value).split('/').pop(), Number(r.sitelinks.value)]));
	console.log(`  найдено в реестре: ${qids.length}`);

	const подписи = await метки(qids);
	for (const qid of qids) {
		const м = подписи.get(qid);
		if (!м) {
			// Имя не добыто — запись НЕ объявляется отсутствующей: сверять нечем, и молчание
			// об этом было бы той же ложью, что пустая метка в первой редакции.
			безымянные.push({ qid, вид: вид.ru, sitelinks: вес.get(qid) ?? 0 });
			continue;
		}
		const есть = [м.ru, м.en].some((имя) => имя && наши.has(normalizeForSearch(имя)));
		const запись = { qid, вид: вид.ru, видEn: вид.en, ru: м.ru, en: м.en, год: м.год, sitelinks: вес.get(qid) ?? 0 };
		(есть ? наши_же : найдено).push(запись);
	}
	console.log(`  из них нет у нас: ${найдено.filter((x) => x.вид === вид.ru).length}`);
}

найдено.sort((a, b) => b.sitelinks - a.sitelinks);

console.log('\n════ ИТОГ РАЗВЕДКИ КЛАССИКИ ════');
console.log(`  всего осмотрено: ${найдено.length + наши_же.length}`);
console.log(`  уже в каталоге:  ${наши_же.length}`);
console.log(`  🆕 НЕТ у нас:     ${найдено.length}`);
if (безымянные.length) console.log(`  ⏭ имя не добыто, НЕ СВЕРЕНЫ: ${безымянные.length}`);
console.log('\n  верхние тридцать по известности:');
for (const x of найдено.slice(0, 30)) {
	console.log(`  ${String(x.sitelinks).padStart(3)}  ${x.вид.padEnd(11)} ${x.год.padEnd(5)} ${x.ru || '—'} | ${x.en || '—'} | ${x.qid}`);
}

const путьJson = arg('--out-json', 'test-results/scout-cult-classics.json');
writeFileSync(путьJson, JSON.stringify({ порогФлагом, предел: ПРЕДЕЛ, найдено, наши_же, безымянные }, null, 1), 'utf8');
console.log(`\nданные для следующего шага: ${путьJson}`);
console.log(
	'\n⚠️ ЧЕСТНАЯ ГРАНИЦА: сверка с каталогом идёт ПО НАЗВАНИЮ. Объект, записанный у нас под другим\n' +
		'   прокатным именем, попадёт в список как отсутствующий — это проверяется глазами за минуту.',
);
