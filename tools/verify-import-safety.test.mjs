/**
 * ТЕСТ СТРАЖА ВХОДНОГО ПРЕДОХРАНИТЕЛЯ (`tools/verify-import-safety.mjs` + ядро
 * `tools/lib/import-safety.mjs`).
 *
 * 🔴 ПОЧЕМУ У СТРАЖА, У КОТОРОГО ЕСТЬ `--selftest`, ЕЩЁ И ЮНИТ. Самотест не способен поймать
 * собственный незапуск: сломай стражу предохранитель наоборот — и `--selftest` промолчит,
 * напечатав ноль символов, а прогон отчитается успехом. Это замерено мутацией на доске команды
 * смены 10 и стоило класса `EXP-0227`. Поэтому здесь самотест ЗОВУТ СНАРУЖИ и требуют, чтобы он
 * ответил, а не просто «не упал».
 *
 * 🔴 ЯДРО ИМПОРТИРУЕТСЯ, СТРАЖ — НЕТ. `lib/import-safety.mjs` чист (одни объявления), его импорт
 * безопасен. Сам страж спрашивается ТОЛЬКО дочерним процессом: импортируй его этот файл строкой
 * `import`, и при возврате дефекта набор умер бы молча и засчитался бы пройденным — то есть
 * страж исчез бы ровно в тот момент, ради которого заведён.
 *
 * Прогон: node --test tools/verify-import-safety.test.mjs   (или `npm run test:tools`)
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

import {
  судить, красный, судитьРеестр, строкаКорпуса, охватНазван,
} from './lib/import-safety.mjs';

const ЗДЕСЬ = dirname(fileURLToPath(import.meta.url));
const СТРАЖ = join(ЗДЕСЬ, 'verify-import-safety.mjs');
const СТРАЖ_URL = new URL('./verify-import-safety.mjs', import.meta.url).href;
const прогон = (...argv) => spawnSync(process.execPath, [СТРАЖ, ...argv], { encoding: 'utf8' });

/* ── Ядро: договор функции суда ──────────────────────────────────────────────────────── */

test('вердикт несёт строку и вид оператора — по нему чинят не думая', () => {
  const в = судить('export const a = 1;\nmain();\nfunction main() {}\n');
  assert.equal(красный(в), true);
  assert.deepEqual(в.незакрытая, [{ строка: 2, вид: 'ExpressionStatement' }]);
});

test('без экспорта работа на верхнем уровне не судится вовсе', () => {
  const в = судить('main();\nfunction main() {}\n');
  assert.equal(в.экспорт, false);
  assert.equal(красный(в), false);
});

test('🔑 предохранитель опознан по СМЫСЛУ: стороны сравнения можно поменять местами', () => {
  // Обе известные проекту формы написаны в разном порядке — признак обязан быть симметричным.
  const прямо = 'import { pathToFileURL } from "node:url";\nexport const a = 1;\n'
    + 'if (import.meta.url === pathToFileURL(process.argv[1]).href) main();\nfunction main() {}\n';
  const наоборот = 'import { resolve } from "node:path";\nimport { fileURLToPath } from "node:url";\nexport const a = 1;\n'
    + 'if (resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) main();\nfunction main() {}\n';
  assert.equal(судить(прямо).предохранитель, true);
  assert.equal(судить(наоборот).предохранитель, true);
  assert.equal(красный(судить(прямо)), false);
  assert.equal(красный(судить(наоборот)), false);
});

test('🔴 предохранитель есть, а работа снаружи — красный (случай rewrite-catalog-descriptions)', () => {
  const в = судить(
    'import { pathToFileURL } from "node:url";\nexport const a = 1;\n'
    + 'const З = Boolean(process.argv[1]) && import.meta.url === pathToFileURL(process.argv[1]).href;\n'
    + 'if (process.argv.includes("--selftest")) selftest();\n'
    + 'if (З) main();\nfunction main() {}\nfunction selftest() {}\n',
  );
  assert.equal(в.предохранитель, true, 'предохранитель в файле есть');
  assert.equal(красный(в), true, 'и всё равно красный: самотест стоит снаружи него');
});

test('неразобранный исходник — не зелёный, а исключение', () => {
  // Страж, не сумевший разобрать файл, ничего о нём не знает и не вправе говорить «зелено».
  assert.throws(() => судить('export const = ;'));
});

/* ── Страж целиком: только дочерним процессом ────────────────────────────────────────── */

test('🔴 ЗАПУЩЕН: --selftest ОТВЕТИЛ и зелен', () => {
  const r = прогон('--selftest');
  assert.notEqual(r.stdout.trim(), '', 'самотест не ответил вовсе: предохранитель отключил стража');
  assert.match(r.stdout, /✅ самопроверка чиста: (\d+)\/\1/);
  assert.equal(r.status, 0);
});

test('🔑 К2 ideas/43: контрольные случаи неосновных форм стоят в самотесте и зелены', () => {
  // Без них собственный зелёный стража ничего не значит — это условие приёмки, а не украшение.
  const { stdout } = прогон('--selftest');
  assert.match(stdout, /^✅ 🔑 К2: вторая форма /m);
  assert.match(stdout, /^✅ 🔑 К2: третья форма /m);
});

test('🔴 ПОДКЛЮЧЁН: импорт стража не исполняет обход и не убивает чужой процесс', () => {
  const r = spawnSync(process.execPath, [
    '--input-type=module',
    '-e', `await import(${JSON.stringify(СТРАЖ_URL)}); console.log('ЖИВ-ПОСЛЕ-ИМПОРТА');`,
  ], { encoding: 'utf8' });
  assert.ok(r.stdout.includes('ЖИВ-ПОСЛЕ-ИМПОРТА'), 'импорт убил чужой процесс');
  assert.ok(!r.stdout.includes('осмотрено файлов'), 'импорт запустил обход дерева');
  assert.equal(r.status, 0);
});

test('К4: суд не вакуумен — печатает, сколько наблюдений сделал', () => {
  const { stdout } = прогон();
  assert.match(stdout, /осмотрено файлов \.mjs: \d+/);
  assert.match(stdout, /из них с экспортом: \d+ · с предохранителем: \d+/);
});

/* ── Охват в строке корпуса: замечание З1 суда №20 ───────────────────────────────────── */

test('🔴 З1 суда №20: живая строка корпуса называет ОХВАТ, а не только число', () => {
  // В тех же воротах стоит перепись приборов, считающая корпус по одному `tools/`. Два размера
  // корпуса в одном прогоне без подписи читаются как противоречие — оба числа при этом верны.
  // Каталоги здесь названы ЛИТЕРАЛОМ намеренно: сменят корпус стража — этот тест обязан
  // покраснеть и потребовать осознанного решения, а не подстроиться молча.
  const { stdout } = прогон();
  assert.match(stdout, /^осмотрено файлов \.mjs: \d+ · охват: tools\/ и sync-server\/$/m);
});

test('🔴 судья охвата УМЕЕТ сказать «нет» — иначе зелёный первого случая ничего не значит', () => {
  const каталоги = ['tools', 'sync-server'];
  assert.equal(охватНазван(строкаКорпуса(292, каталоги), каталоги), true);
  assert.equal(охватНазван('осмотрено файлов .mjs: 292', каталоги), false, 'голое число прошло');
  assert.equal(
    охватНазван('осмотрено файлов .mjs: 292 (tools, sync-server)', каталоги), false,
    'попутная скобка засчитана за названный охват',
  );
  assert.equal(
    охватНазван('осмотрено файлов .mjs: 292 · охват: tools/', каталоги), false,
    'половина охвата засчитана за весь',
  );
});

test('🔑 КОНТРОЛЬ: судья охвата не привязан к двум каталогам и не красит исправное', () => {
  // Ложное красное отключают целиком — и тогда правило не защищает вовсе (`ideas/43`, К1).
  assert.equal(охватНазван(строкаКорпуса(273, ['tools']), ['tools']), true);
  assert.equal(охватНазван(строкаКорпуса(1, ['a', 'b', 'c']), ['a', 'b', 'c']), true);
});

test('🔑 случаи охвата СТОЯТ в самотесте и отвечают зелёным', () => {
  // Без этого их снятие прошло бы незаметно: страж остался бы зелёным, потеряв проверку.
  const { stdout } = прогон('--selftest');
  assert.match(stdout, /^✅ 🔑 строка корпуса несёт и число, и охват целиком$/m);
  assert.match(stdout, /^✅ 🔴 голое число без охвата — не проходит/m);
});

/* ── Реестр исключений: строка обязана уметь покраснеть сама ─────────────────────────── */

test('🔴 реестр протухает ПЯТЬЮ способами, и каждый называет себя', () => {
  // Исключение, пережившее свой повод, молча разрешает ровно тот дефект, ради которого страж
  // заведён, — и разрешает навсегда. Поэтому у реестра свой суд, и вот его пять поводов.
  const красные = new Set(['tools/a.mjs']);
  const существующие = new Set(['tools/a.mjs', 'tools/c.mjs']);
  const суд = (строка) => судитьРеестр({ реестр: [строка], красные, существующие });

  assert.match(суд({ файл: 'tools/нет.mjs', вид: 'исключение', причина: 'разобрано в ideas/43' })
    .протухшие[0].почему, /нет в дереве/);
  assert.match(суд({ файл: 'tools/c.mjs', вид: 'исключение', причина: 'разобрано в ideas/43' })
    .протухшие[0].почему, /больше не красный/);
  assert.match(суд({ файл: 'tools/a.mjs', вид: 'исключение', причина: '   ' })
    .протухшие[0].почему, /без причины/);
  assert.match(суд({ файл: 'tools/a.mjs', вид: 'исключение', причина: 'так надо' })
    .протухшие[0].почему, /ни на что не указывает/);
  assert.match(суд({ файл: 'tools/a.mjs', вид: 'отсрочка', причина: 'чинится порцией по plans/78' })
    .протухшие[0].почему, /без даты и условия/);
});

test('исправная строка покрывает красное и не считается протухшей', () => {
  const r = судитьРеестр({
    реестр: [{ файл: 'tools/a.mjs', вид: 'исключение', причина: 'несущая работа, разобрана в bugs/94' }],
    красные: new Set(['tools/a.mjs', 'tools/b.mjs']),
    существующие: new Set(['tools/a.mjs', 'tools/b.mjs']),
  });
  assert.deepEqual(r.покрытые, ['tools/a.mjs']);
  assert.deepEqual(r.непокрытые, ['tools/b.mjs']);
  assert.deepEqual(r.протухшие, []);
});

test('🔑 покрытое печатается ПОИМЁННО: молчаливое исключение неотличимо от забытого', () => {
  const { stdout } = прогон();
  assert.match(stdout, /реестр: исключений и отсрочек \d+, из них в силе \d+/);
  assert.match(stdout, /⏸️ .+ — (исключение|отсрочка)/);
  assert.match(stdout, /^ {6}причина: .+/m, 'причина обязана быть видна в выводе, а не только в коде');
});

test('🔴 отписка вместо причины глушила настоящего красного — теперь красное (суд №18)', () => {
  // Живой обход судьи: { вид: 'исключение', причина: 'так надо' } давала стражу код 0.
  const вход = {
    красные: new Set(['tools/a.mjs']),
    существующие: new Set(['tools/a.mjs']),
  };
  for (const отписка of ['так надо', 'потом', 'сложно', 'ок']) {
    const r = судитьРеестр({ реестр: [{ файл: 'tools/a.mjs', вид: 'исключение', причина: отписка }], ...вход });
    assert.equal(r.покрытые.length, 0, `отписка «${отписка}» всё ещё покрывает красное`);
    assert.match(r.протухшие[0].почему, /ни на что не указывает/);
  }
});

test('🔑 КОНТРОЛЬ: признак содержательности не красит исправные причины', () => {
  // Страж, дающий ложное красное, отключают целиком — и тогда он не защищает и от настоящего.
  const вход = {
    красные: new Set(['tools/a.mjs']),
    существующие: new Set(['tools/a.mjs']),
  };
  for (const годная of [
    'несущий инвариант, разобран в bugs/94',
    'читает src/lib/firebase.ts на импорте — в этом весь смысл',
    'слово владельца 2026-08-22',
    'вердикт QA №18 назвал порядок',
    'класс описан в EXP-0188',
  ]) {
    const r = судитьРеестр({ реестр: [{ файл: 'tools/a.mjs', вид: 'исключение', причина: годная }], ...вход });
    assert.deepEqual(r.протухшие, [], `исправная причина покрашена красным: «${годная}»`);
    assert.deepEqual(r.покрытые, ['tools/a.mjs']);
  }
});
