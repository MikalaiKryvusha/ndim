test('🔴 класс 5 судит ФОРМУ, а не слова: полная фраза с теми же словами проходит', () => {
  /* Живая строка партии 2, к которой у владельца претензий нет. Образец без условия тире
   * объявил бы её браком — это и есть та граница, ради которой условие поставлено. */
  const живая = 'Премьера прошла 25 декабря 2025 года в США, следующие даты выхода пришлись на 22 января.';
  assert.deepEqual(датыОбрубком(живая), []);
});

test('класс 5: его собственная форма подачи даты проходит молча', () => {
  assert.deepEqual(датыОбрубком('Картина вышла в прокат 7 мая 2026 года. Представлена на фестивале 8 мая.'), []);
});

