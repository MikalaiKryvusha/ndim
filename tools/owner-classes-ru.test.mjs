// ── КЛАСС 15: удивление убито заранее — ЗАМЕЧАНИЕ ────────────────────────────────────────────

test('МУТАЦИЯ класс 15: признак ПОЗИЦИОННЫЙ — перестановка частей его гасит', () => {
  /* 🔴 Обе фразы состоят из ОДНИХ И ТЕХ ЖЕ 31 слова и 206 знаков, с теми же 4 запятыми, тем же
   * двоеточием и тем же тире. Ни одно слово не добавлено и не убрано — переставлены части.
   * Значит любая СЧЁТНАЯ мера на этой паре слепа, и тест сторожит ровно то, что признак
   * смотрит на ПОЗИЦИЮ, а не считает. Подмена его счётным образцом обязана уронить этот тест. */
  const дефект = 'Отец, в свою очередь, прячет своё настоящее положение: держит во дворе старый пикап, нарочно оставляет беспорядок в комнате — пока на его запястье не оказываются часы, которые он тут же объявляет подделкой.';
  const лечение = 'Отец, в свою очередь, держит во дворе старый пикап, нарочно оставляет беспорядок в комнате — пока на его запястье не оказываются часы, которые он тут же объявляет подделкой: прячет своё настоящее положение.';
  assert.equal(дефект.length, лечение.length, 'контроль пары: длина одна — счётная мера их не различит');
  assert.equal(удивлениеУбито(дефект).length, 1, 'правда раскрыта до противопоставления — предъявляем');
  assert.deepEqual(удивлениеУбито(лечение), [], 'правда ушла в конец — прибор обязан замолчать');
});

