test('класс 9 идёт в ЗАМЕЧАНИЯ: заказ Менеджера — предъявлять, а не отказывать', () => {
  const t = 'Облик города собран по образцу застройки, музыка электронная.';
  assert.deepEqual(ownerClassProblems(t), []);
  assert.equal(ownerClassNotes(t).length, 1);
});

// ── КЛАСС 2: мера сложности — числа, а не приговор ───────────────────────────────────────────

test('класс 2 МЕРЯЕТ и ничего не запрещает', () => {
  const t = 'Первая фраза короткая. Вторая фраза длиннее, и в ней есть придаточное, которое можно снять.';
  const м = мераСложности(t);
  assert.equal(м.фраз, 2);
  assert.equal(м.максПридаточных, 1, '«которое» — придаточное; «и» — сочинение, не считается');
  assert.ok(м.максДлина > м.срДлина);
  assert.deepEqual(ownerClassProblems(t), [], 'порог назначает владелец, а не прибор');
  assert.deepEqual(ownerClassNotes(t), [], 'мера идёт отдельным блоком, а не замечанием на каждую карточку');
});

test('класс 2 называет САМУЮ ДЛИННУЮ фразу — предъявить человеку надо строку, а не только число', () => {
  const м = мераСложности('Коротко. Здесь заметно длиннее, и эту строку человек должен увидеть целиком.');
  assert.match(м.самаяДлинная, /человек должен увидеть/u);
});

test('мера отказывается считать там, где материала нет, вместо того чтобы врать нулями', () => {
  assert.equal(мераСложности(''), null);
  assert.equal(мераСложности('Any English text here.', 'en'), null);
});

// ── Английская сторона: русский список ей не судья ───────────────────────────────────────────

test('английский текст не судится НИ ОДНОЙ из русских проверок', () => {
  const en = 'But the score was composed by another author, and the release is scheduled.';
  assert.deepEqual(ownerClassProblems(en, 'en'), []);
  assert.deepEqual(ownerClassNotes(en, 'en'), []);
});

// ── Общий выход: отказы и замечания не перепутаны местами ────────────────────────────────────

test('🔴 отказы и замечания разведены по каналам, и каждый класс назван по номеру', () => {
  const t = 'Для Баркера это первый полный метр. Но зрителю этого мало. Первая дата выхода — 5 сентября 2025 года.';
  const отказы = ownerClassProblems(t);
  const замечания = ownerClassNotes(t);
  assert.equal(отказы.length, 2, 'классы 4 и 5 останавливают работу');
  assert.ok(отказы.every((о) => /^класс \d/u.test(о)), 'человек читает номер класса, а не догадывается');
  assert.equal(замечания.length, 1, 'класс 3 предъявляется');
  assert.match(замечания[0], /^класс 3/u);
});
