#!/usr/bin/env node
/**
 * СТРАЖ ОБЩЕГО МОДУЛЯ ЯЗЫКА — ворота шага 1 плана `plans/39` (фаза 6 эпика `plans/24`).
 *
 * Судит ИСХОДНИКИ, а не собранный сайт, и это здесь правильно: охраняемое свойство —
 * «язык читается из ОДНОГО места», то есть свойство самого дерева кода. По собранному сайту
 * его не увидеть вовсе — бандлер склеит четырнадцать копий в одну строку, и страж был бы
 * зелёным на любом коде.
 *
 * Что охраняется и почему (замер до работы: 14 прямых чтений в 12 файлах):
 *
 *   1. Ни одного `ndim-lang` вне модуля. Пока язык переключался в одном месте, копии сходили
 *      с рук; с приходом ЯЗЫКОВЫХ АДРЕСОВ они разойдутся обязательно — адрес говорит одно,
 *      память браузера другое, и побеждает тот, кто прочитал позже.
 *   2. Ни одной своей копии состояния (`let lang = $state<…>`). Это дословно устройство,
 *      за которое проект уже заплатил дефектом `bugs/53` на теме: владелец переключал тему в
 *      «Меню», а шапка показывала прежнюю.
 *   3. Ни одной третьей копии типа `Lang`.
 *   4. 🔴 ИНЛАЙН-СКРИПТ `app.html` ПОВТОРЯЕТ ПОРЯДОК МОДУЛЯ. Это ЕДИНСТВЕННАЯ копия правила,
 *      которую нельзя убрать в модуль: скрипт исполняется до всякого JS приложения, ради
 *      первого кадра без мигания. Значит это и единственное место, где правило может
 *      разойтись молча, — и именно поэтому оно проверяется отдельно, а не «на глаз».
 *
 * ⚠️ КОНТРОЛЬ ПРИБОРА (EXP-0082) стоит ПЕРВЫМ и он здесь не украшение. Все проверки ниже —
 * отрицательные («ничего не нашлось»), а отрицательная проверка красится зелёным от чего
 * угодно: переименовали ключ, переехал файл, опечатка в шаблоне пути. Поэтому сперва
 * доказываем, что искать ЕСТЬ ГДЕ и что охраняемые строки на месте.
 *
 * Запуск:  node tools/verify-lang-module.mjs
 * Выход:   0 — чисто; 1 — есть провалы.
 */
import { readFileSync, existsSync, readdirSync, statSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const SRC = 'src';
/** Модуль состояния языка — ЕДИНСТВЕННОЕ место, где ключу хранилища место. */
const LANG_MODULE = join('src', 'lib', 'ui', 'lang.svelte.ts');
/** Оболочка документа: инлайн-скрипт до гидратации, импортировать модуль физически не может. */
const APP_HTML = join('src', 'app.html');
/** Где типу `Lang` жить разрешено. */
const TYPE_HOMES = [join('src', 'lib', 'ui', 'format.ts'), join('src', 'lib', 'content', 'langs.ts')];

let failed = 0;
let passed = 0;
const check = (name, ok, detail = '') => {
  if (ok) passed += 1;
  else failed += 1;
  console.log(`  ${ok ? '✅' : '❌'} ${name}${detail ? ` — ${detail}` : ''}`);
};

/**
 * Только КОД: комментарии выкидываются.
 *
 * 🔴 Первая редакция стража этого не делала — и покраснела на собственных комментариях,
 * объясняющих, чего делать нельзя. Документ, который ЦИТИРУЕТ запрещённую строку, чтобы
 * назвать её запрещённой, — не нарушение, а объяснение; страж, не умеющий их различать,
 * учит будущие сессии не писать объяснений. `//` внутри `https://` сохраняется: перед ним
 * стоит двоеточие.
 */
const code = (s) =>
  s
    .replace(/<!--[\s\S]*?-->/g, ' ')
    .replace(/\/\*[\s\S]*?\*\//g, ' ')
    .replace(/(^|[^:'"\w])\/\/[^\n]*/g, '$1 ');

/** Все файлы дерева исходников. */
function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...walk(full));
    else out.push(full);
  }
  return out;
}

if (!existsSync(SRC)) {
  console.error('❌ нет каталога src/ — страж запускается из корня проекта');
  process.exit(1);
}

const files = walk(SRC).filter((f) => /\.(svelte|ts|html)$/.test(f));
const text = new Map(files.map((f) => [f, readFileSync(f, 'utf8')]));

// ── КОНТРОЛЬ ПРИБОРА: искать есть где и охраняемое на месте ──────────────────
console.log('\n— контроль прибора —');
check('дерево исходников прочитано', files.length > 50, `${files.length} файлов`);
check('модуль языка существует', text.has(LANG_MODULE), LANG_MODULE);
check('оболочка документа существует', text.has(APP_HTML), APP_HTML);
check(
  'ключ хранилища ЖИВ в модуле (иначе весь страж — зелёная пустышка)',
  (text.get(LANG_MODULE) ?? '').includes("'ndim-lang'"),
);
check(
  'инлайн-скрипт вообще занимается языком',
  (text.get(APP_HTML) ?? '').includes("setAttribute('lang'"),
);

// ── 1. Ключ хранилища — только в модуле и в инлайн-скрипте ───────────────────
console.log('\n— ключ `ndim-lang` живёт в ОДНОМ месте —');
{
  const ALLOWED = new Set([LANG_MODULE, APP_HTML]);
  const strays = [];
  for (const [file, body] of text) {
    if (ALLOWED.has(file)) continue;
    // Ищем ОБРАЩЕНИЕ к хранилищу, а не упоминание строки: слово `ndim-lang` в комментарии
    // документа — не дефект, а объяснение. Дефект — это чтение или запись мимо модуля.
    const hit = /localStorage\s*\.\s*(get|set)Item\s*\(\s*['"]ndim-lang['"]/.exec(code(body));
    if (hit) strays.push(`${relative(SRC, file)}: ${hit[0]}`);
  }
  check('прямых обращений к памяти языка вне модуля нет', strays.length === 0,
    strays.length === 0 ? 'было 14 в 12 файлах' : strays.join(' · '));
}

// ── 2. Своей копии состояния языка ни у кого нет ─────────────────────────────
console.log('\n— своей копии состояния языка ни у кого нет —');
{
  const strays = [];
  for (const [file, body] of text) {
    if (file === LANG_MODULE) continue;
    if (/\blet\s+lang\s*=\s*\$state\b/.test(body)) strays.push(relative(SRC, file));
  }
  check('ни один экран не держит свой `let lang = $state`', strays.length === 0,
    strays.length === 0 ? 'было 10' : strays.join(' · '));
}

// ── 3. Компоненты не объявляют свой тип `Lang` ───────────────────────────────
// ⚠️ ГРАНИЦА ПРОВЕРКИ, названная честно. Судятся только КОМПОНЕНТЫ (`.svelte`): там локальный
// `type Lang` — всегда копия-вставка общего типа. У модулей всё иначе: `format.ts` (слой
// интерфейса), `schema.ts` (слой данных Firestore) и `langs.ts` (публичные адреса) объявляют
// его каждый у себя, и слой данных не обязан импортировать из слоя интерфейса. Свести их в
// одно — отдельная работа про слои, а не про язык; расширять сюда её молча было бы дрейфом
// охвата. Замер на сегодня: три объявления в модулях, ноль в компонентах.
console.log('\n— компоненты не объявляют свой тип `Lang` —');
{
  const strays = [];
  for (const [file, body] of text) {
    if (!file.endsWith('.svelte')) continue;
    if (/\btype\s+Lang\s*=\s*'(ru|en)'\s*\|/.test(code(body))) strays.push(relative(SRC, file));
  }
  check('локальных объявлений `type Lang` в компонентах нет', strays.length === 0,
    strays.length === 0 ? 'было 3 (лендинг, «Профиль», демо похожести)' : strays.join(' · '));
}

// ── 4. Шапка берёт язык из модуля, а не пропсом ──────────────────────────────
console.log('\n— шапка берёт язык из модуля, а не пропсом —');
{
  const strays = [];
  for (const [file, body] of text) {
    // Ищем ПРИМЕНЕНИЕ (атрибут, объявление пропса, вызов), а не слово: комментарий,
    // объясняющий, почему колбэка больше нет, — не нарушение.
    if (/\bonLang\s*[=(:,]/.test(code(body))) strays.push(relative(SRC, file));
  }
  check('колбэка `onLang` в проекте не осталось', strays.length === 0,
    strays.length === 0 ? 'было 7 одинаковых копий' : strays.join(' · '));
  const bar = text.get(join('src', 'lib', 'ui', 'AppBar.svelte')) ?? '';
  check('шапка импортирует общий модуль языка', /from\s+'\$lib\/ui\/lang\.svelte'/.test(bar));
}

// ── 5. 🔴 ИНЛАЙН-СКРИПТ ПОВТОРЯЕТ ПОРЯДОК МОДУЛЯ ─────────────────────────────
// Копия правила здесь неустранима, значит она обязана быть ДОКАЗАННО одинаковой.
console.log('\n— инлайн-скрипт повторяет порядок модуля: адрес → память → браузер —');
{
  const html = text.get(APP_HTML) ?? '';
  // Комментарии выкидываем ДО поиска: сам скрипт объясняет, какая строка стояла здесь
  // раньше, и цитата прежнего дефекта не должна читаться как дефект.
  const script = code(/<script>([\s\S]*?)<\/script>/.exec(html)?.[1] ?? '');

  const atPath = script.search(/location\s*\.\s*pathname/);
  const atMemory = script.search(/getItem\s*\(\s*['"]ndim-lang['"]/);
  const atBrowser = script.search(/navigator\s*\.\s*language/);

  check('скрипт смотрит на АДРЕС', atPath >= 0);
  check('скрипт смотрит в ПАМЯТЬ', atMemory >= 0);
  check('скрипт спрашивает БРАУЗЕР (интервью №024, В1 = А)', atBrowser >= 0);
  // Порядок — это и есть всё правило. `/en/…` у человека с `ru` в памяти ломался ровно
  // потому, что память читалась раньше адреса.
  check('АДРЕС читается РАНЬШЕ памяти', atPath >= 0 && atMemory >= 0 && atPath < atMemory,
    `адрес @${atPath} · память @${atMemory}`);
  check('память читается РАНЬШЕ браузера', atMemory >= 0 && atBrowser >= 0 && atMemory < atBrowser,
    `память @${atMemory} · браузер @${atBrowser}`);

  // Список языков обязан совпадать с `$lib/content/langs.ts`: инлайн-скрипт знает его наизусть,
  // и добавленный третий язык должен уронить страж, а не тихо не заработать на первом кадре.
  const langs = [...((text.get(join('src', 'lib', 'content', 'langs.ts')) ?? '')
    .match(/export const LANGS\s*=\s*\[([^\]]*)\]/)?.[1] ?? '')
    .matchAll(/'([a-z-]+)'/g)].map((m) => m[1]);
  check('список языков модуля прочитан', langs.length >= 2, langs.join(', '));
  const missing = langs.filter((code) => !new RegExp(`['"]${code}['"]`).test(script));
  check('инлайн-скрипт знает КАЖДЫЙ язык модуля', missing.length === 0,
    missing.length === 0 ? langs.join(', ') : `не знает: ${missing.join(', ')}`);
}

// ── Итог ─────────────────────────────────────────────────────────────────────
console.log(`\n${failed === 0 ? '✅' : '❌'} проверок ${passed + failed} · провалов ${failed}\n`);
process.exit(failed === 0 ? 0 : 1);
