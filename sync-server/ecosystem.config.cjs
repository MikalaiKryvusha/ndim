/**
 * СЛУЖБА СЕРВЕРА СИНХРОНИЗАЦИИ ПОД PM2 — замена контейнеру (слово владельца 2026-09-08:
 * «переделывай сервер синхронизации на PM2»).
 *
 * ПОЧЕМУ .cjs, А НЕ .js: в корне проекта `"type": "module"`, а PM2 читает конфиг через `require`.
 * Расширение `.cjs` называет это вслух и снимает вопрос.
 *
 * 🔴 В ЭТОМ ФАЙЛЕ НЕТ И НЕ БУДЕТ НИ ОДНОГО СЕКРЕТА. Здесь только команда; ключ читает из `.env`
 * сам прибор запуска, в память процесса. Причина конкретная: `pm2 save` кладёт окружение
 * процессов в свой файл дампа (`~/.pm2/dump.pm2`), и боевой ключ, попав сюда, оказался бы на
 * диске. Правило владельца 2026-08-15: «никогда ключи в коде и других файлах не храним».
 *
 * 🔒 ВХОД — ЗАМОРОЖЕННАЯ КОПИЯ, А НЕ РАБОЧЕЕ ДЕРЕВО. Образ был снимком; рабочее дерево снимком не
 * является, и правка `index.mjs` уехала бы в бой при ближайшем перезапуске. Бой живёт в отдельной
 * рабочей копии, прибитой к коммиту:
 *     git worktree add --detach ../ndim-server-prod <коммит>
 *     cd ../ndim-server-prod/sync-server && npm install --omit=dev
 * Что сейчас в бою — отвечает `git -C ../ndim-server-prod rev-parse --short HEAD`.
 *
 * Команды:
 *   pm2 start sync-server/ecosystem.config.cjs   # поднять
 *   pm2 logs ndim-server-prod                    # смотреть лог
 *   pm2 restart ndim-server-prod                 # перезапустить
 *   pm2 save                                     # запомнить состав служб на перезагрузку
 *   node tools/read-server-pulse.mjs --contour prod   # жив ли он на самом деле
 */
const { existsSync } = require('node:fs');
const { resolve } = require('node:path');

const КОРЕНЬ = resolve(__dirname, '..');

/**
 * Node, которым поднимать службу. Не `'node'` и не `process.execPath`: первое возьмёт Node самого
 * PM2 (под nvm он старый), второе — тот же PM2-шный. Нужен установленный в систему.
 */
const NODE = [
	resolve(process.env.ProgramFiles ?? 'C:/Program Files', 'nodejs', 'node.exe'),
	resolve(process.env['ProgramFiles(x86)'] ?? 'C:/Program Files (x86)', 'nodejs', 'node.exe'),
].find((путь) => existsSync(путь)) ?? 'node';

module.exports = {
	apps: [
		{
			/**
			 * СЛУЖБА СТЕЙДЖА — не «копия боевой на всякий случай», а место, где ДОКАЗЫВАЕТСЯ дверь
			 * выката (`plans/85`). Главный путь двери (выкат → пульс → откат) нельзя проверить,
			 * не выкатив хоть куда-то, а выкат в бой требует отдельного слова владельца.
			 * Заодно закрывается хвост `plans/83` — «стейдж под PM2 не поднят».
			 *
			 * ⛔ Ключ здесь тоже не живёт: контур назван доводом, ключ читает прибор запуска из `.env`.
			 */
			name: 'ndim-server-stage',
			cwd: КОРЕНЬ,
			script: 'tools/run-sync-server.mjs',
			interpreter: NODE,
			args: ['--contour', 'stage', '--entry', resolve(КОРЕНЬ, '..', 'ndim-server-stage', 'sync-server', 'index.mjs')],
			watch: false,
			autorestart: true,
			exp_backoff_restart_delay: 5000,
			min_uptime: 60_000,
			max_restarts: 10,
			max_memory_restart: '450M',
			time: true,
			merge_logs: true,
		},
		{
			// Имя то же, что у контейнера, — чтобы в документах и привычках ничего не разъехалось.
			name: 'ndim-server-prod',
			cwd: КОРЕНЬ,
			script: 'tools/run-sync-server.mjs',

			// 🔴 ВЕРСИЯ NODE НАЗВАНА ЯВНО, А НЕ ВЗЯТА ИЗ PATH. PM2 на этой машине стоит под nvm и
			// запускает СВОИМ Node — замер 2026-09-08: v22.6.0, тогда как сервер синхронизации
			// требует ≥ 23.6 и импортирует ядро похожести исходником `.ts`. Со старым Node служба
			// упала бы на первом импорте. Второй предохранитель — в самом приборе запуска: он
			// сверяет версию с `engines` и отказывается стартовать.
			interpreter: NODE,
			args: ['--contour', 'prod', '--entry', resolve(КОРЕНЬ, '..', 'ndim-server-prod', 'sync-server', 'index.mjs')],

			// 🔴 НАБЛЮДЕНИЕ ЗА ФАЙЛАМИ ВЫКЛЮЧЕНО НАМЕРЕННО. С ним любая правка в дереве
			// перезапускала бы БОЕВУЮ службу — ровно то свойство контейнера-снимка, ради
			// которого заведена замороженная копия.
			watch: false,

			// Замена `restart: unless-stopped` у контейнера.
			autorestart: true,
			// Падение на старте (нет ключа, нет входа, отказ Firestore) не должно превращаться в
			// петлю: задержка растёт, а `min_uptime` отличает «поднялся и работает» от «упал сразу».
			exp_backoff_restart_delay: 5000,
			min_uptime: 60_000,
			max_restarts: 10,

			// Потолок памяти — предохранитель от утечки, а не рабочая норма.
			// ЗАМЕР живого процесса 2026-09-08 (прогретый кэш, 348 точек Пространства):
			//   рабочий набор 98,8 МБ · частная память 94,7 МБ
			//   процессор за 60 с — 0,03 с, то есть 0,05 % одного ядра и 0,003 % машины (16 потоков)
			// Потолок взят с запасом ×4,5 от замера.
			max_memory_restart: '450M',

			// Время в каждой строке лога: без него «когда он замолчал» приходится выводить.
			time: true,
			merge_logs: true,
		},
	],
};
