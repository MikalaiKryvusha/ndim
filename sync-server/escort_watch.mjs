// Подписка эскорта новичка (эпик 60, фаза 2, шаг 2 — `plans/62`).
//
// ЗАЧЕМ. Слово владельца (интервью №040 В1): «*Новичок ставит оценку — попадает в очередь
// приоритетного пересчёта… но оно не делает холостых записей и чтений*». Узнавать о событии
// БЕЗ опроса умеет только подписка — и это позиция самого поставщика (`researches/43` §3.1:
// «one-shot queries re-read data that may not have changed»). Здесь живёт ТОЛЬКО слух:
// подписка слышит событие и отдаёт его наружу. Кто и когда считает — дело пульса (шаг 3),
// окна и потолок — шаги 4–5.
//
// ФОРМА ВЫБОРКИ — `dirty == true`, отбор эскорта фильтром процесса. Почему не уже:
//   · «первые оценки новичка» — ГЛАВНОЕ событие подписки — полем запроса невыразимы:
//     девственная точка отличается ОТСУТСТВИЕМ `firstSeen`/`escortRuns`, а Firestore не
//     умеет условия «поля нет»; дать клиенту писать маркер нельзя — белый список полей
//     точки (`bugs/153`) закрыт, и открывать его ради запроса значило бы вернуть подделку;
//   · `escortRuns < 3` поймал бы ТОЛЬКО середину эскорта (2-й и 3-й пересчёты) и был бы
//     глух к первому событию — то есть ровно к тому, ради чего подписка ставится.
// Цена формы в СЕГОДНЯШНЕЙ архитектуре — единицы: минутный цикл вычищает `dirty` за
// такт-другой, поэтому стоячий набор подписки почти всегда пуст, а переподключение стоит
// «единицы чтений» — это посчитано разведкой для ЭТОЙ ЖЕ выборки (`researches/43` §3.2).
// 🔴 Обязанность фазы 3, названная вслух: замедлив старожилов до часа, она расширит пул
// `dirty` до часового — и обязана ПЕРЕРЕШИТЬ ширину выборки (принять цену переподключений
// пулом либо развести представление «ждёт часа» и «ждёт эскорта»). Молча унаследовать
// эту форму фаза 3 не имеет права.
//
// ОБРЫВ — ГЛАВНЫЙ РИСК ПОДПИСКИ, и лечится он снимком переподъёма. В серверном SDK нет
// офлайн-персистентности, поэтому каждый обрыв тарифицируется как новый запрос
// (`researches/43` §3.2) — но он же и СПАСАЕТ: первый снимок после переподъёма отдаёт ВСЁ,
// что сейчас в выборке, то есть события, случившиеся во время обрыва, приходят догоном.
// Молчаливый обрыв — потерянные новички, поэтому каждый обрыв и каждый переподъём — строка
// в логе (требование шага 2 дословно).
//
// ⛔ Подписка — УСКОРЕНИЕ, а не единственная дорога: в фазе 2 обновлённые NDim ID подбирает
// живой минутный цикл, в целевой архитектуре — часовой такт. Смерть подписки замедляет
// новичка, но не теряет его.

/**
 * Событие эскорта: точка внутри эскорта получила обновлённый NDim ID.
 * @typedef {{ uid: string, at: number }} EscortEvent
 */

/**
 * Создаёт подписку эскорта. Ничего не подключает до `start()`.
 *
 * @param {object} deps
 * @param {import('firebase-admin/firestore').Firestore} deps.db
 * @param {(line: string) => void} deps.log
 * @param {(event: EscortEvent) => void} deps.onEscortEvent — слушатель событий; дедупликация
 *        и расписание пересчётов — его сторона (шаг 3), подписка отдаёт сырой факт.
 * @param {(data: Record<string, unknown>) => boolean} deps.isEscorting — правило «эта точка
 *        в эскорте» (в бою — `escortActive` из index.mjs; внедряется, чтобы модуль не тянул
 *        весь сервер и был проверяем в одиночку).
 * @param {() => number} [deps.now]
 * @param {number} [deps.retryBaseMs] — первая пауза переподъёма (дальше ×2 до потолка).
 * @param {number} [deps.retryMaxMs]
 */
export function createEscortWatch({
  db,
  log,
  onEscortEvent,
  isEscorting,
  now = Date.now,
  retryBaseMs = 5_000,
  retryMaxMs = 60_000,
}) {
  /** Отписка живого слушателя; null = подписки нет (не поднята или оборвана). */
  let unsubscribe = null;
  let retryTimer = null;
  let retryDelayMs = retryBaseMs;
  /** Первый снимок после (пере)подъёма — догон: считаем его отдельно ради честного лога. */
  let catchingUp = false;

  function handleSnapshot(snapshot) {
    let caught = 0;
    for (const change of snapshot.docChanges()) {
      // 'removed' — точка вышла из выборки (dirty снят), событие уже потреблено циклом.
      if (change.type !== 'added' && change.type !== 'modified') continue;
      const data = change.doc.data();
      // Старожил — не наша дорога: его подберёт общий ритм. Фильтр стоит ЗДЕСЬ, а не в
      // запросе, — разбор в шапке модуля.
      if (!isEscorting(data)) continue;
      caught += 1;
      onEscortEvent({ uid: change.doc.id, at: now() });
    }
    if (catchingUp) {
      catchingUp = false;
      retryDelayMs = retryBaseMs; // связь живая — следующий обрыв снова начнёт с малой паузы
      if (caught > 0) log(`подписка эскорта: догнано из снимка переподъёма — ${caught}`);
    }
  }

  function handleError(error) {
    // Слушатель после ошибки мёртв (SDK его не воскрешает) — молчание здесь было бы
    // потерянными новичками. Переподъём планируем сами, с растущей паузой.
    unsubscribe = null;
    log(
      `подписка эскорта оборвалась: ${error.message} — переподъём через ${Math.round(retryDelayMs / 1000)} с`,
    );
    retryTimer = setTimeout(() => {
      retryTimer = null;
      attach('поднята заново');
      retryDelayMs = Math.min(retryDelayMs * 2, retryMaxMs);
    }, retryDelayMs);
    // Служба живёт по setInterval цикла; висящий таймер переподъёма не должен держать
    // процесс, когда всё остальное уже отпущено (--once, тесты).
    if (typeof retryTimer.unref === 'function') retryTimer.unref();
  }

  function attach(word) {
    catchingUp = true;
    unsubscribe = db
      .collection('points')
      .where('dirty', '==', true)
      .onSnapshot(handleSnapshot, handleError);
    log(`подписка эскорта ${word}: выборка dirty, отбор эскорта — в процессе`);
  }

  return {
    start() {
      if (unsubscribe !== null || retryTimer !== null) return; // вторая подписка = двойные события
      attach('поднята');
    },

    stop() {
      if (retryTimer !== null) {
        clearTimeout(retryTimer);
        retryTimer = null;
      }
      if (unsubscribe !== null) {
        unsubscribe();
        unsubscribe = null;
      }
    },

    /** Жива ли подписка прямо сейчас (для деградации пульса на общий ритм, шаг 3). */
    isAlive() {
      return unsubscribe !== null;
    },

    /**
     * Дверь для теста обрыва: рвёт подписку ТЕМ ЖЕ путём, каким её рвёт настоящая ошибка
     * (через handleError, с переподъёмом и логом), — тест доказывает боевую дорогу
     * восстановления, а не свою собственную. В бою не зовётся.
     */
    _testBreak(reason = 'тестовый обрыв') {
      if (unsubscribe !== null) {
        unsubscribe();
        handleError(new Error(reason));
      }
    },
  };
}
