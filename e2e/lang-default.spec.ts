import { expect, test } from '@playwright/test';

/*
 * ЯЗЫК: КТО ПОБЕЖДАЕТ КОГО — сценарий ворот шага 1 плана `plans/39` (фаза 6 эпика `plans/24`).
 *
 * Правило одно и у него ЖЁСТКИЙ порядок (`$lib/ui/lang.svelte.ts` → `readInitial()`):
 *
 *     АДРЕС  →  ПАМЯТЬ БРАУЗЕРА  →  ЯЗЫК БРАУЗЕРА
 *
 * 🔴 Почему это отдельный файл, а не строки в `landing.spec.ts`. Здесь каждая проверка обязана
 * ОБЪЯВИТЬ язык машины (`test.use({ locale })`), потому что именно он и есть предмет спора.
 * Остальные сценарии проекта судят русского человека и объявляют это один раз в
 * `playwright.config.ts`; смешивать два разных предположения в одном файле — верный способ
 * получить проверку, которая зелена по случайности настроек.
 *
 * 🔑 КОНТРОЛЬ ПРИБОРА (EXP-0082) встроен парами. Каждое «побеждает» проверяется в ОБЕ стороны:
 * если бы страница просто отдавала жёстко зашитый язык, односторонняя проверка была бы зелёной
 * на сломанном коде. Пара «`/en/…` даёт en И `/ru/…` даёт ru» этого не позволяет.
 *
 * Решения, которые здесь исполняются:
 *   · интервью №024, В1 = А — пустая память спрашивает БРАУЗЕР («просит русский — даём русский,
 *     иначе английский»); так «EN основной» (интервью №009, В8) работает для всего мира и не
 *     подсовывает чужой язык русскоязычному человеку, а таких сегодня все 331;
 *   · интервью №010, Р5 = В — у каждого языка свой префикс адреса.
 */

/** Любая настоящая страница каталога — они собраны на обоих языках (`plans/36`). */
const DIM_SLUG = '10-cloverfield-lane-js0baimt';

/** Положить выбор языка в память ДО загрузки страницы — как у вернувшегося человека. */
const remember = (value: string) => `try { localStorage.setItem('ndim-lang', ${JSON.stringify(value)}); } catch {}`;

// ─────────────────────────────────────────────────────────────────────────────
// 1. Пустая память — спрашиваем браузер (интервью №024, В1 = А)
// ─────────────────────────────────────────────────────────────────────────────

test.describe('пустая память: язык берётся у браузера', () => {
	test.describe('браузер просит русский', () => {
		test.use({ locale: 'ru-RU' });

		test('русскоязычный человек без памяти получает РУССКИЙ', async ({ page }) => {
			await page.goto('/');
			await expect(page.locator('html')).toHaveAttribute('lang', 'ru');
		});
	});

	test.describe('браузер просит английский', () => {
		test.use({ locale: 'en-US' });

		test('англоязычный человек без памяти получает АНГЛИЙСКИЙ', async ({ page }) => {
			await page.goto('/');
			await expect(page.locator('html')).toHaveAttribute('lang', 'en');
		});
	});

	test.describe('браузер просит язык, которого у нас нет', () => {
		test.use({ locale: 'de-DE' });

		test('немецкоязычный человек получает АНГЛИЙСКИЙ, а не пустоту', async ({ page }) => {
			// «Иначе английский» — вторая половина ответа В1 = А. Проверка существует потому,
			// что третий язык здесь легко было бы не обработать вовсе.
			await page.goto('/');
			await expect(page.locator('html')).toHaveAttribute('lang', 'en');
		});
	});
});

// ─────────────────────────────────────────────────────────────────────────────
// 2. Память побеждает браузер (человек уже выбрал — его выбор уважают)
// ─────────────────────────────────────────────────────────────────────────────

test.describe('память побеждает язык браузера', () => {
	test.use({ locale: 'en-US' });

	test('английский браузер + выбранный РУССКИЙ = русский', async ({ page }) => {
		await page.addInitScript(remember('ru'));
		await page.goto('/');
		await expect(page.locator('html')).toHaveAttribute('lang', 'ru');
	});

	test('контроль прибора: тот же браузер БЕЗ памяти даёт английский', async ({ page }) => {
		// Без этой пары проверка выше была бы зелёной и на коде, который всегда отдаёт «ru».
		await page.goto('/');
		await expect(page.locator('html')).toHaveAttribute('lang', 'en');
	});
});

// ─────────────────────────────────────────────────────────────────────────────
// 3. 🔴 АДРЕС ПОБЕЖДАЕТ ПАМЯТЬ — главное правило эпика
// ─────────────────────────────────────────────────────────────────────────────

test.describe('адрес побеждает память браузера', () => {
	test.use({ locale: 'ru-RU' });

	test('человек с «ru» в памяти на /en/… ОСТАЁТСЯ на английском', async ({ page }) => {
		/*
		 * Это ровно тот дефект, который `hooks.server.ts` до сегодня называл прямым текстом как
		 * НЕпочиненный: «у робота работало, у человека ломалось». Инлайн-скрипт `app.html`
		 * слепо переписывал `lang` из памяти поверх значения, поставленного из адреса, — и
		 * английская страница объявлялась русской.
		 */
		await page.addInitScript(remember('ru'));
		await page.goto(`/en/dimension/${DIM_SLUG}`);
		await expect(page.locator('html')).toHaveAttribute('lang', 'en');
	});

	test('контроль прибора: тот же человек на /ru/… остаётся на русском', async ({ page }) => {
		// Обратное плечо: без него проверку выше прошёл бы код, жёстко пишущий «en».
		await page.addInitScript(remember('ru'));
		await page.goto(`/ru/dimension/${DIM_SLUG}`);
		await expect(page.locator('html')).toHaveAttribute('lang', 'ru');
	});

	test('и наоборот: человек с «en» в памяти на /ru/… видит РУССКИЙ', async ({ page }) => {
		await page.addInitScript(remember('en'));
		await page.goto(`/ru/dimension/${DIM_SLUG}`);
		await expect(page.locator('html')).toHaveAttribute('lang', 'ru');
	});
});

// ─────────────────────────────────────────────────────────────────────────────
// 4. Личные экраны языковых адресов НЕ получили и берут язык из памяти
// ─────────────────────────────────────────────────────────────────────────────

test.describe('за стеной входа адрес язык не задаёт', () => {
	test.use({ locale: 'en-US' });

	test('личный экран уважает выбор человека, а не язык машины', async ({ page }) => {
		// Языковых адресов за стеной входа нет и не будет (`plans/39` шаг 2): там источник
		// истины — память. Здесь же проверяется, что мост «адрес → память» не сломал этот путь.
		await page.addInitScript(remember('ru'));
		await page.goto('/menu');
		await expect(page.locator('html')).toHaveAttribute('lang', 'ru');
	});
});
