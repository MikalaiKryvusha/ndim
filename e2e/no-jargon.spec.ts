/**
 * На лице продукта не бывает жаргона разработчика.
 *
 * ЗАЧЕМ ЭТОТ ТЕСТ СУЩЕСТВУЕТ. 2026-07-12, боевой прод, экран «Связи» встречал живого человека
 * такой фразой:
 *
 *     «Связей пока нет: вычислитель ещё не считал. На стенде: node calculator/index.mjs --once»
 *
 * Два нарушения канона разом: запрещённое слово «вычислитель» (в интерфейсе — только «Сервер
 * синхронизации») и КОМАНДА РАЗРАБОТЧИКА, показанная человеку. То же самое висело на экране
 * «Пространство». Прожило это до самого запуска, потому что **ни один тест не смотрел на слова,
 * которые видит человек** — все проверяли поведение.
 *
 * Механизм ошибки известен и записан в STATUS: агент пишет интерфейс тем же языком, каким
 * описывает себе код. Поймано трижды. Значит, ловить это должна машина, а не память.
 *
 * Проверяем СОБРАННЫЙ артефакт — то, что реально уедет к людям, а не исходники: комментарии в
 * коде на этом языке писать можно и нужно, а в бандл они не попадают.
 */
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';

import { expect, test } from '@playwright/test';

/**
 * Слова и обрывки, которых на лице продукта быть не может ни при каких обстоятельствах.
 *
 * Здесь только то, что ОДНОЗНАЧНО является жаргоном: имя нашей внутренней папки, команды
 * запуска, запрещённое словарём слово. Общие слова («стенд», «localhost») не берём — они
 * законно встречаются в коде (`isStand()` сравнивает хост со строкой 'localhost'), и тест
 * на них давал бы ложную тревогу, а ложная тревога убивает доверие к тесту.
 */
const FORBIDDEN = [
  'вычислитель', // словарь продукта: только «Сервер синхронизации» (AGENT_GUIDE)
  'вычислител', // на случай других падежей: «вычислителя», «вычислителем»
  'node calculator',
  'calculator/index.mjs',
  '--once',
  'npm run',
];

/**
 * Описание объекта каталога — НЕ наш текст, и судить его словарём продукта нельзя.
 *
 * 🔴 Полевой случай, ради которого это появилось (2026-08-03, фаза 5 эпика `ideas/30`): страж
 * покраснел на страницах фильмов **«Скрытые фигуры»** и **«Игра в имитацию»**. Оба про людей,
 * которые считали вручную, — слово «вычислитель» стоит там по делу, в описании произведения.
 * Запрет же существует для СЛОВАРЯ ПРОДУКТА: внутреннее имя папки `calculator/` не должно
 * выходить на лицо приложения вместо «Сервера синхронизации».
 *
 * Вырезаем ровно блок описания, а не всю страницу: обвязка страницы каталога — наш текст, и
 * жаргон в ней страж обязан ловить по-прежнему. Ослабить проверку целиком было бы дешевле и
 * неправильно.
 */
const stripCatalogDescription = (html: string) =>
	html.replace(/<div class="desc[^"]*">[\s\S]*?<\/div>/g, ' ');

/**
 * 🔴 ВЫРЕЗАЕТСЯ РОВНО ОПИСАНИЕ И НИЧЕГО БОЛЬШЕ.
 *
 * Первая редакция вырезала заодно все `<script>` — «там сериализованная нагрузка пререндера с
 * теми же чужими описаниями». Судейский проход это отмёл: исключение было ШИРЕ своего
 * обоснования, а жаргон разработчика в инлайн-скрипте — ровно то, что страж обязан ловить.
 * Замер по собранному сайту: без вырезания скриптов находок **ноль**, то есть оно не нужно и
 * сегодня (после `csr = false` полезной нагрузки в скриптах страниц каталога больше нет вовсе).
 * **Ослабление, которое ничего не даёт, — просто ослабление.**
 */
const ourTextOnly = (html: string) => stripCatalogDescription(html);

/** Все файлы собранного сайта — именно они уезжают к людям. */
function filesOf(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? filesOf(path) : [path];
  });
}

test('в собранном сайте нет жаргона разработчика и команд запуска', () => {
  const files = filesOf('build').filter((f) => /\.(html|js|css|txt|xml)$/.test(f));
  expect(files.length, 'сборка пуста — проверять нечего').toBeGreaterThan(0);

  const found: string[] = [];
  for (const file of files) {
    const text = ourTextOnly(readFileSync(file, 'utf8'));
    for (const word of FORBIDDEN) {
      if (text.includes(word)) found.push(`${file} → «${word}»`);
    }
  }

  expect(found, 'жаргон разработчика уехал бы к живым людям').toEqual([]);
});
