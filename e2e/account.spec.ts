/**
 * Смоук экрана «Управлять аккаунтом» (/account) на продакшен-сборке БЕЗ эмуляторов.
 *
 * Полный сценарий (виджет «Мой аккаунт», гость, не вошедший, обе темы и ширины) гоняется
 * стражем `tools/verify-account.mjs` на живом стенде — он требует Java и эмуляторов и в общий
 * прогон не входит. Здесь проверяется то, что обязано работать ВСЕГДА, даже когда базы нет:
 *   1) шелл экрана пререндерен и закрыт от индексации;
 *   2) без сессии экран честно предлагает войти, а не виснет и не показывает пустоту;
 *   3) на лице приложения нет наших внутренних команд.
 *
 * Экран заведён фазой 4 эпика `plans/15` (план `plans/18`), форма утверждена владельцем
 * 2026-08-01 (макет V2 + виджеты, `plans/17`).
 */
import { expect, test } from '@playwright/test';

test('аккаунт: шелл пререндерен и закрыт от индексации', async ({ request }) => {
  const response = await request.get('/account');
  expect(response.ok()).toBeTruthy();
  const html = (await response.text()).replace(/ |&nbsp;/g, ' ');

  // Имя экрана — инфинитив, канон 1.x (кадр app-14, researches/24 §2.1). «Управление
  // аккаунтом» — это имя ДВЕРИ в «Профиле», а не заголовок экрана.
  expect(html).toContain('Управлять аккаунтом');
  // Приватный экран не индексируется (researches/08, чеклист п. 14).
  expect(html).toContain('noindex');
  // Здесь живут почта и дата создания — ПДн; в пререндеренном HTML их быть не может
  // по построению (сессии на этапе сборки нет), и эта проверка стережёт построение.
  // ⚠️ Ищем адрес ПО ФОРМЕ, а не по символу «@»: он есть в любом CSS (`@media`), и первая
  // редакция этой проверки краснела на исправной сборке.
  expect(html).not.toMatch(/[\w.+-]+@[\w-]+\.[a-z]{2,}/i);
});

test('аккаунт: без данных — честная ошибка человеческим языком, без жаргона', async ({ page }) => {
  /*
   * ⚠️ ЗДЕСЬ ОЖИДАЕТСЯ НЕ «войдите», а «не удалось прочитать», и это не оплошность.
   * Прогон идёт по адресу localhost, а для продукта localhost — это СТЕНД: он пытается
   * войти пользователем стенда, эмулятора рядом нет, и экран честно сообщает о сбое.
   * Ровно так же устроен смоук «Профиля». Ветку «Войдите…» проверяет страж
   * `tools/verify-account.mjs` на живом стенде дверью `?as=none`.
   */
  await page.goto('/account');
  await expect(page.getByText('Не удалось прочитать', { exact: false })).toBeVisible({ timeout: 20000 });
  // Тот же экран работает в бою — внутренних команд на нём быть не должно.
  await expect(page.getByText('npm run stand')).toHaveCount(0);
});
